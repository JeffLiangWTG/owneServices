	[TestCaseSource(nameof(OceanMessaging_EnrichMessageSql_TestCaseSource))]
	public async Task OceanMessaging_EnrichMessageSql(
		string sender,
		string recipient,
		string eipk,
		string oipk,
		string message,
		string inboxXml,
		string? outboxXml,
		string criteria,
		(string, string)[][] expectedResults,
		(string, string)[] expectedCache,
		bool expectInboxCache,
		bool expectOutboxCache)
	{
		var clients = new[] { sender, recipient }.Select(CreateClient).ToDictionary(c => c.CC_ID);
		eHubClient CreateClient(string id)
			=> new() { CC_PK = Guid.NewGuid(), CC_ID = id, CC_EmailAddress = "", CC_FriendlyName = "", CC_Password = "", CC_OwnerCategory = "Service", CC_SystemCategory = "eHub", CC_PermitInboxSender = true, CC_PermitInboxRecipient = true };
		eHubDbContext.eHubClient.AddRange(clients.Values);
		var inbox = eHubDbContext.eHubInboxMessage.Add(new eHubInboxMessage
		{
			EI_PK = new Guid(eipk),
			EI_MessageTrackingID = Guid.NewGuid().ToString(),
			EI_EnvelopeTrackingID = Guid.Empty.ToString(),
			EI_CC_Sender = clients[sender].CC_PK,
			EI_ApplicationCode = "UDM",
			EI_Status = 3
		}).Entity;
		eHubDbContext.eHubInboxXmlContent.Add(new eHubInboxXmlContent
		{
			EX_EI_Inbox = inbox.EI_PK,
			EX_XmlContent = Resources.Messages.ResourceManager.GetString(inboxXml)!
		});
		eHubDbContext.eHubOutboxMessage.Add(new eHubOutboxMessage
		{
			OI_PK = new Guid(oipk),
			OI_CC_Sender = clients[sender].CC_PK,
			OI_CC_Recipient = clients[recipient].CC_PK,
			OI_EI_InboxPK = inbox.EI_PK.ToString(),
			OI_Status = 3,
			Content = new eHubOutboxMessageContent { OI_XmlContent = outboxXml is null ? null : Resources.Messages.ResourceManager.GetString(outboxXml) },
			OI_DT_TargetNavigation = new eHubMessageType { DT_PK = Guid.NewGuid(), DT_Code = "http://schemas.microsoft.com/BizTalk/EDI/EDIFACT/2006#EFACT_D99B_IFTMIN" }
		});
		eHubDbContext.SaveChanges();

		var messageJson = JsonObject.Parse(Resources.Messages.ResourceManager.GetString(message)!)!;
		var configurationData = new Dictionary<string, string?>
		{
			["CacheSizeLimit"] = "2000000000",
			["CacheExpirationDefaultMinutes"] = "30"
		};
		var configuration = new ConfigurationBuilder().AddInMemoryCollection(configurationData).Build();
		var cache = new MemoryCache(new MemoryCacheOptions());
		var logger = new FakeLogger<CacheService>(Console.WriteLine);

		var enricher = new OceanMessaging(eHubDbContext, new CacheService(cache, configuration, logger));
		var result = (await enricher.EnrichMessageBatchAsync((JsonObject)messageJson, criteria)).ToList();

		Assert.Multiple(() =>
		{
			Assert.That(result.Count, Is.EqualTo(expectedResults.Length));
			for (int i = 0; i < result.Count; i++)
			{
				Assert.That(result[i].Select(r => (r.Key, r.Value?.ToString())),
					Is.Not.Null.And.EquivalentTo(expectedResults[i]));
			}

			foreach (var item in expectedCache)
			{
				Assert.That(cache.Get(item.Item1) as string, Is.EqualTo(item.Item2));
			}
			if (expectInboxCache)
			{
				Assert.That(cache.Get($"OceanMessaging:Inbox:{eipk}:XML"), Is.Not.Null);
			}
			if (expectOutboxCache)
			{
				Assert.That(cache.Get($"OceanMessaging:Outbox:{oipk}:XML"), Is.Not.Null);
			}
		});
	}

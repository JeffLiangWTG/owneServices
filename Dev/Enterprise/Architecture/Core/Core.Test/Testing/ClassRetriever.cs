using System;
using System.Collections.Generic;
using System.Linq;
using System.Reflection;
using System.Runtime.InteropServices;
using Resources;
namespace Enterprise.ZArchitecture.Core.Testing
{
	public abstract class ClassRetriever
	{
		public Type[] Retrieve()
		{
			return GetAssemblies().AsParallel().SelectMany(ass =>
			{
				Type[] assemblyTypes;
				try
				{
					assemblyTypes = ass.GetTypes();
				}
				catch (ReflectionTypeLoadException ex)
				{
					if (!IsNetCore)
					{
						throw;
					}
					VerifyAllowedMissingNetCoreAssembliesThrowOnFail(ex.LoaderExceptions);
					return ex.Types.Where(t => t != null);
				}
				return assemblyTypes;
			}).Where(type => MatchesConditions(type)).ToArray();

			//Revert back to this once WI00886604 is completed
			//return GetAssemblies().AsParallel().SelectMany(ass => ass.GetTypes()).Where(type => MatchesConditions(type)).ToArray();
		}

		#region helper methods remove after WI00886604 is completed
		public static bool IsNetCore
		=> ((System.Environment.Version.Major >= 5) || RuntimeInformation.FrameworkDescription.StartsWith(".NET Core", StringComparison.OrdinalIgnoreCase))
		&& !string.IsNullOrEmpty(typeof(object).Assembly.Location);

		static readonly string[] _allowedMissingTypesForNetCore =
		[
			"System.Web.UI.HtmlTextWriterAttribute",
			"System.Web.UI.HtmlTextWriterStyle",
			"System.Web.UI.HtmlTextWriterTag"
		];

		void VerifyAllowedMissingNetCoreAssembliesThrowOnFail(IEnumerable<Exception> loadTypeExceptions)
		{
			foreach (var exception in loadTypeExceptions)
			{
				if (exception is not TypeLoadException failTypeLoad || !_allowedMissingTypesForNetCore.Contains(failTypeLoad.TypeName))
				{
					throw exception;
				}
			}
		}
		#endregion

		public ParallelQuery<Type> FilterTypesLive(ParallelQuery<Type> types, Func<Type, bool> coreCondition = null)
		{
			return types.Where(type => MatchesConditions(type, coreCondition));
		}

		bool MatchesConditions(Type type, Func<Type, bool> coreCondition = null)
		{
			return
			(
				coreCondition == null ? MatchesConditionsCore(type) : coreCondition(type)
			)
			&& PassesAbstractCondition(type)
			&& PassesNestedClassCondition(type)
			&& PassesPrivateNestedClassCondition(type)
			&& PassesAutoGeneratedCondition(type)
			&& PassesNonAutoGeneratedCondition(type)
			&& PassesTestClassesCondition(type)
			&& PassesExcludedTypesCondition(type)
			&& PassesExclusionAttributesCondition(type)
			&& PassedImplementedInterfaceCondition(type);
		}

		protected abstract bool MatchesConditionsCore(Type type);

		bool PassesAbstractCondition(Type type)
		{
			return IncludeAbstractClasses || !type.IsAbstract;
		}

		bool PassesNestedClassCondition(Type type)
		{
			return IncludeNestedClasses || type.FullName.IndexOf('+') == -1;
		}

		bool PassesPrivateNestedClassCondition(Type type)
		{
			return IncludePrivateNestedClasses || (type.IsPublic || type.IsNestedPublic);
		}

		bool PassesAutoGeneratedCondition(Type type)
		{
			return IncludeAutoGeneratedCode || !DoesTypeDeclareAutoGeneratedSourceCodeAttribute(type);
		}

		bool PassesNonAutoGeneratedCondition(Type type)
		{
			return IncludeNonAutoGeneratedCode || DoesTypeDeclareAutoGeneratedSourceCodeAttribute(type);
		}

		bool PassesTestClassesCondition(Type type)
		{
			return IncludeTestClasses || (type.FullName.IndexOf(".Test") == -1 && type.FullName.IndexOf("+Test") == -1);
		}

		bool PassesExcludedTypesCondition(Type type)
		{
			if (ExcludedTypesAndTheirDescendants != null)
			{
				foreach (Type typeInCollection in ExcludedTypesAndTheirDescendants)
				{
					if (type == typeInCollection || typeInCollection.IsAssignableFrom(type))
					{
						return false;
					}
				}
			}
			return true;
		}

		bool PassesExclusionAttributesCondition(Type type)
		{
			return !DoesTypeDeclareAnyOfAttributes(type, ExcludedAttributes);
		}

		bool DoesTypeDeclareAnyOfAttributes(Type type, Type[] attributes)
		{
			if (attributes == null)
			{
				return false;
			}

			return type.GetCustomAttributesData().Join
			(
				attributes, data => data.AttributeType, attrType => attrType, (data, attrType) => attrType
			)
			.Any();
		}

		bool DoesTypeDeclareAutoGeneratedSourceCodeAttribute(Type type) =>
			type.GetCustomAttributesData().Any
			(
				data => data.AttributeType.AssemblyQualifiedName == typeof(AutoGeneratedSourceCodeAttribute).AssemblyQualifiedName
			);

		bool PassedImplementedInterfaceCondition(Type type)
		{
			bool result = true;
			if (ImplementedInterface != null)
			{
				bool foundInterface = false;
				foreach (Type implementedInterfaceOnType in type.GetInterfaces())
				{
					if (ImplementedInterface == implementedInterfaceOnType)
					{
						foundInterface = true;
						break;
					}
				}
				result = foundInterface;
			}
			return result;
		}

		protected Assembly[] GetAssemblies()
		{
			if (Assembly != null)
			{
				return new Assembly[] { Assembly };
			}
			else
			{
				return AssemblyRetriever.LoadAsssembliesFromSimpleNames(Assemblies);
			}
		}

		protected Assembly Assembly;
		protected string[] Assemblies;
		public bool IncludeAbstractClasses = true;
		public bool IncludeAutoGeneratedCode = true;
		public bool IncludeNestedClasses = true;
		public bool IncludePrivateNestedClasses = true;
		public bool IncludeTestClasses;
		public bool IncludeNonAutoGeneratedCode = true;
		public Type[] ExcludedAttributes;
		public Type ImplementedInterface;
		public Type[] ExcludedTypesAndTheirDescendants { get; set; }
	}
}

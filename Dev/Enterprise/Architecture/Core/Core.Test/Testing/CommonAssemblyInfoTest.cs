		public void TestAssembliesStrongNamed(IEnumerable<string> assemblies)
		{
			var errors = new StringBuilder();
			foreach (var assemblyFileName in assemblies)
			{
				var assembly = LoadAssembly(assemblyFileName, true);

				object publicKeyToken = assembly.GetName().GetPublicKeyToken();
				if (publicKeyToken == null)
				{
					errors.Append("Assembly should be strong named: ").Append(assembly.ToString());
					errors.AppendLine();
				}
			}
			Assert(errors.ToString(), errors.Length == 0);
		}

		Assembly LoadAssembly(string assemblyFileName, bool reflectionOnlyLoad = false)
		{
#pragma warning disable SYSLIB0018 // Type or member is obsolete
			if (assemblyFileName.IndexOf('\\') >= 0)
			{
				return reflectionOnlyLoad ? Assembly.ReflectionOnlyLoadFrom(assemblyFileName) : Assembly.LoadFrom(assemblyFileName); // it's a file/path
			}
			else
			{
				return reflectionOnlyLoad ? Assembly.ReflectionOnlyLoad(assemblyFileName) : Assembly.Load(assemblyFileName); // it's an assembly name
			}
#pragma warning restore SYSLIB0018 // Type or member is obsolete
		}

		[DatCapabilityRequirement("SOURCE_CODE")]
		public void TestAssembliesUseCommonAssemblyInfo(IEnumerable<string> assemblies)
		{
			var commonAssemblyInfo = LoadAssembly("CommonAssemblyInfoTest");
			var commonAttributes = commonAssemblyInfo.GetCustomAttributes(false);
			var errors = new StringBuilder();

			var excludedAssemblies = new HashSet<string>(
				new[]
				{
						"CargoWise.CalendarArithmetic",
						"CargoWise.DataTransfer",
						"Enterprise.BarcodeParsingEngine",
						"Enterprise.DAT.SpecialFileHandling",
						"Enterprise.DeniedPartyScreening.Common",
						"Enterprise.Freight.DistanceCalculation.Integration",
						"Enterprise.LocalTransport.Mobile.Client",
						"Enterprise.Mobile.Shared.ResourceString.Cache.Testing",
						"Enterprise.Mobile.Shared.Testing",
						"Enterprise.RemoteDesktopServices.Shared.XmlSerializers",
						"Enterprise.Warehouse.RF.Common.Testing",
						"Enterprise.Warehouse.RF.Shared",
						"Enterprise.Warehouse.RF.Testing",
						"Enterprise.Warehouse.RF.VoicePicking",
						"Enterprise.Warehouse.RF.VoicePicking.Console",
						"Warehouse.RF.Testing",
						"CargoWise.SGen",
						"CargoWise.Organizations.CodeGeneration", // Can be removed once copyright info is updated to current year
						"CargoWise.Organizations.PatternMatching", // Can be removed once copyright info is updated to current year
						"Enterprise.DbUpgrader.Resource.Test", // .NET 5, cannot be reflection-loaded
						"Aga.Business", //Third-party code
						"Aga.Controls"  //Third-party code
				},
				StringComparer.OrdinalIgnoreCase);

			foreach (var assemblyFileName in assemblies)
			{
				if (excludedAssemblies.Contains(assemblyFileName))
				{
					continue;
				}

				var assembly = LoadAssembly(assemblyFileName);

				var actualAttributes = assembly.GetCustomAttributes(false);
				foreach (Attribute commonAttribute in commonAttributes)
				{
					if (commonAttribute is DebuggableAttribute
						|| commonAttribute is AssemblyKeyNameAttribute // ignore - C++ projects do this as a project property to allow manifest embedding
						|| commonAttribute is AssemblyDelaySignAttribute // ignore - C++ projects do this as a project property to allow manifest embedding
						|| commonAttribute is CompilationRelaxationsAttribute // ignore - this is generated by various compilers and is not part of CommonAssemblyInfo.cs
						|| commonAttribute is RuntimeCompatibilityAttribute // ignore - this is generated by various compilers and is not part of CommonAssemblyInfo.cs
						|| commonAttribute is AssemblyInformationalVersionAttribute // ignore - this attribute is only needed for package signature
						)
					{
						continue;
					}

					if (!((IList)actualAttributes).Contains(commonAttribute))
					{
						var commonFileVersionAttribute = commonAttribute as AssemblyFileVersionAttribute;
						if (commonFileVersionAttribute != null &&
							(AssemblyIsExemptFromVersionNumberChecksBecauseItFollowsGacVersioningRules(assemblyFileName)
								|| UsesOwnAssemblyFileVersionAttributeForCompactFramework(commonFileVersionAttribute, actualAttributes)
								|| AssembliesFromDependencies.Value.Contains(assemblyFileName)))
						{
							continue;
						}

						if (commonAttribute is StringFreezingAttribute && AssemblyIsExemptFromStringFreezing(assemblyFileName))
						{
							continue;
						}

						var targetFrameworkAttribute = commonAttribute as TargetFrameworkAttribute;
						if (targetFrameworkAttribute != null)
						{
							var versionNumber = targetFrameworkAttribute.FrameworkName.Split('=')[1];
							if (string.Compare(versionNumber, "4.5.1", StringComparison.Ordinal) < 0)
							{
								errors.AppendFormat("Assembly {0} has a version greater than currently supported (4.5.1)", assemblyFileName);
								errors.AppendLine();
							}
							continue;
						}

						errors.AppendFormat("Assembly {0} should get the {1} by having a copy of CommonAssemblyInfo.cs", assemblyFileName, commonAttribute.GetType().Name);
						errors.AppendLine();
					}
				}

				if (!AssemblyIsExemptFromVersionNumberChecksBecauseItFollowsGacVersioningRules(assemblyFileName) && (assembly.GetName().Version != commonAssemblyInfo.GetName().Version))
				{
					errors.AppendFormat("Assembly {0} should get its version by having a copy of CommonAssemblyInfo.cs.", assemblyFileName);
					errors.AppendLine();
				}
			}

			Assert(errors.ToString(), errors.Length == 0);
		}


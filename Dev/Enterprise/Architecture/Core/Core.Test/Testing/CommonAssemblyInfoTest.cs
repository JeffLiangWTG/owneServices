		bool UsesOwnAssemblyFileVersionAttributeForCompactFramework(AssemblyFileVersionAttribute commonAttribute, object[] actualAttributes)
		{
			// This attribute does not exist in compact framework, so we add an identical attribute.
			var ceFileVersionAttribute = actualAttributes.OfType<Attribute>().SingleOrDefault(a => a.GetType().FullName == typeof(AssemblyFileVersionAttribute).FullName);

			return ceFileVersionAttribute != null && ceFileVersionAttribute.GetType().GetProperty("Version").GetValue(ceFileVersionAttribute).Equals(commonAttribute.Version);
		}

		IEnumerable<string> EnsureLoadableAssemblies(IEnumerable<string> namesToTry, StringBuilder errors)
		{
			return EnsureLoadableAssemblies(namesToTry, errors, true, new List<string>());
		}

		IEnumerable<string> EnsureLoadableAssemblies(IEnumerable<string> namesToTry, StringBuilder errors, bool failOnInuseFiles, IList<string> inuseFilenamesToRetry, bool reflectionOnlyLoad = false)
		{
			var result = new ConcurrentBag<string>();
			var concurrentInuseFilenamesToRetry = new ConcurrentBag<string>();

			Parallel.ForEach(namesToTry, (name) =>
			{
				try
				{
					if (name.IndexOf("AxInterop.SHDocVw", StringComparison.OrdinalIgnoreCase) == -1 &&
						name.IndexOf("Interop.SHDocVw", StringComparison.OrdinalIgnoreCase) == -1 &&
						!name.StartsWith("Enterprise.Interop.", StringComparison.OrdinalIgnoreCase) &&
						!name.StartsWith("EnvDTE") // Is not deployed to client, see Build.xml
						)
					{
						var assembly = LoadAssembly(name, reflectionOnlyLoad);
						result.Add(name);
					}
				}
				catch (BadImageFormatException)
				{
					return; // Not a .NET assembly
				}
				catch (System.Runtime.InteropServices.COMException)
				{
					return; // Not a .NET assembly
				}
				catch (FileLoadException ex)
				{
					if (failOnInuseFiles)
					{
						errors.AppendFormat("Error loading {0}: {1} {2}", name, ex.GetType().Name, ex.Message).AppendLine();
					}
					else
					{
						concurrentInuseFilenamesToRetry.Add(name);
					}
				}
				catch (Exception ex)
				{
					errors.AppendFormat("Error loading {0}: {1} {2}", name, ex.GetType().Name, ex.Message).AppendLine();
				}
			});

			foreach (var item in concurrentInuseFilenamesToRetry)
			{
				inuseFilenamesToRetry.Add(item);
			}
			return result;
		}

		string GetAssemblyName(string assemblyFileName)
		{
			var name = Path.GetFileName(assemblyFileName);
			if (name.EndsWith(".dll", StringComparison.OrdinalIgnoreCase) || name.EndsWith(".exe", StringComparison.OrdinalIgnoreCase))
			{
				name = name.Substring(0, name.Length - 4);
			}
			return name;
		}

		IEnumerable<string> AllAssembliesInEnterpriseBin(Func<string, bool> includeFilter = null, bool reflectionOnlyLoad = false)
		{
			var assemblies = new List<string>();
			var filenamesToTry = new List<string>();
			var inuseFilenamesToRetry = new List<string>();
			var errors = new StringBuilder();

			var enterpriseBinDlls = Directory.GetFiles(AppDomain.CurrentDomain.BaseDirectory, "*.dll").Select(GetAssemblyName);
			var enterpriseBinExes = Directory.GetFiles(AppDomain.CurrentDomain.BaseDirectory, "*.exe").Select(GetAssemblyName);

			if (includeFilter != null)
			{
				filenamesToTry.AddRange(enterpriseBinDlls.Where(includeFilter));
				filenamesToTry.AddRange(enterpriseBinExes.Where(includeFilter));
			}
			else
			{
				filenamesToTry.AddRange(enterpriseBinDlls);
				filenamesToTry.AddRange(enterpriseBinExes);
			}

			assemblies.AddRange(EnsureLoadableAssemblies(filenamesToTry, errors, false, inuseFilenamesToRetry, reflectionOnlyLoad));
			if (inuseFilenamesToRetry.Count > 0)
			{
				Thread.Sleep(100);
				assemblies.AddRange(EnsureLoadableAssemblies(inuseFilenamesToRetry, errors));
			}

			if (errors.Length > 0)
			{
				Fail(errors.ToString());
				return null; // Can't happen - Fail throws.
			}
			else
			{
				return assemblies;
			}
		}

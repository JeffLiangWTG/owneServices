using System;
using System.Diagnostics.CodeAnalysis;
using CargoWise.Common;
using CargoWise.Common.Testing;
using Enterprise.ZArchitecture.Environment;

namespace Enterprise.ZArchitecture.Core
{
	#region SuppressResourceStringsCheckRegion
	/// <summary>
	/// NOTE: If the DB is not available, any references to it should be handled
	/// </summary>
	public static class ExceptionReporter
	{
		static void Enable()
		{
			if (!IsEnabled)
			{
				SetInstance(new BaseExceptionReporter(sessionId));
			}

			UIHooks?.HookThreadSpecificUnhandledExceptions();
		}

		public static BaseExceptionReporter Instance
		{
			get
			{
				Enable();
				return fInstance;
			}
		}
		[SuppressThreadStaticFieldMessage]
		static BaseExceptionReporter fInstance;

		[SuppressThreadStaticFieldMessage]
		static readonly object setInstanceSyncRoot = new object();

		[SuppressThreadStaticFieldMessage]
		static Guid sessionId = Guid.NewGuid();

		public static Guid SessionId
		{
			get { return sessionId; }
			set { sessionId = value; }
		}

		[SuppressMessage("CargoWiseOne", "CW1021")]
		public static IExceptionReporterUIHooks UIHooks { get; set; }

		internal static void SetInstance(BaseExceptionReporter reporter)
		{
			lock (setInstanceSyncRoot)
			{
				fInstance?.UnHookUnhandledExceptions();
				fInstance = reporter;
				fInstance.HookStaticUnhandledExceptions();
				ErrorReporter.Instance = reporter;
			}
		}

		internal static void Disable()
		{
			if (Globals.IsTest)
			{
				if (IsEnabled)
				{
					fInstance.UnHookUnhandledExceptions();
				}
				fInstance = null;
			}
			else
			{
				throw new InvalidOperationException("The ErrorReporter can only be disabled while testing.");
			}
		}

		internal static bool IsEnabled
		{
			get { return (fInstance != null); }
		}

		public static string AutoGeneratedSubjectPrefix
		{
			get { return Instance.AutoGeneratedSubjectPrefix; }
		}

		public static void SuppressGui()
		{
			if (IsEnabled)
			{
				fInstance.SuppressGuiFlag = true;
			}
		}

#if DEBUG
		public static void DisableExposed()
		{
			Disable();
		}
#endif
	}

	#endregion
}

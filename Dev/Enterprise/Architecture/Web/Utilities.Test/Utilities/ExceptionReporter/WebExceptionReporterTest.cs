using System;
using System.Threading;
using CargoWise.Data;
using CargoWise.Data.Testing;
using CargoWise.EntityFramework;
using CargoWise.EntityFramework.Testing;
using Enterprise.ZArchitecture.Core;
using Enterprise.ZArchitecture.Environment;
using NUnit.Framework;

namespace Enterprise.ZArchitecture.Web.Utilities.Exceptions
{
	internal class WebExceptionReporterTest : TransactionedTestCase
	{
		protected BaseExceptionReporter SaveExceptionReporter;

		protected override void SetUp()
		{
			base.SetUp();
			SaveExceptionReporter = ExceptionReporter.Instance;
			WebExceptionReporter testExceptionReporter = new WebExceptionReporter();
			testExceptionReporter.Enable();
		}

		protected override void TearDown()
		{
			base.TearDown();
			SaveExceptionReporter.Enable();
		}

		public void TestReportException()
		{
			var numInitialReports = GetNumErrorReports();
			Globals.Message.ShowDeveloperException(new Exception("This is a test email generated by the TestReportExceptionByEmail TestCase"));
			AssertEquals("Error report not sent", numInitialReports + 1, GetNumErrorReports());
		}

		public void TestWebReportException()
		{
			var numInitialReports = GetNumErrorReports();
			((WebExceptionReporter)ExceptionReporter.Instance).ReportWebException(new Exception("This is a test email generated by the TestWebReportException testcase"), "", "");
			AssertEquals("Error report not sent", numInitialReports + 1, GetNumErrorReports());
		}

		[UseSnapshotProtection]
		public void TestAttemptToUseDbConnectionExceptionWithoutDisposableActionAreReported()
		{
			// Arrange
			using (Globals.SetIsUnitTestingProductionFunctionality())
			using (Globals.SetIsUserInteractiveForTest(false))
			{
				var numInitialReports = GetNumErrorReports();
				var thread = new Thread(new ThreadStart(() =>
				{
					// Act
					using (var connection = Db.Connection)
					{ }
				}));
				thread.Start();
				thread.Join();

				//Assert
				AssertEquals("Error report should be sent", numInitialReports + 1, GetNumErrorReports());
			}
		}

		public void TestAttemptCrossThreadAccessExceptionNotReported()
		{
			using (Globals.SetIsUnitTestingProductionFunctionality())
			using (Globals.SetIsUserInteractiveForTest(false))
			{
				var factory = new BusinessObjectFactory();
				var numInitialReports = GetNumErrorReports();
				var thread = new Thread(new ThreadStart(() =>
				{
					using (Db.DisposableActionForDbConnection())
					{
						factory.LoadTop1<DummyBusinessObject>(new ZQuery());
					}
				}));
				thread.Start();
				thread.Join();
				AssertEquals("Error report should not have been sent", numInitialReports, GetNumErrorReports());
			}
		}

		static int GetNumErrorReports()
		{
			using (var cmd = Db.Connection.Command("SELECT COUNT(*) FROM [StmErrorReport]"))
			{
				return (int)cmd.ExecuteScalar();
			}
		}
	}
}

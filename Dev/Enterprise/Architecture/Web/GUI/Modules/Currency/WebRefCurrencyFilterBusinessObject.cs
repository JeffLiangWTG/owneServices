		protected override ZQuery SearchPanelFilter
		{
			get
			{
				ZQuery query = new ZQuery();

				SQLComparisonOperator @operator = Contains ? SQLComparisonOperator.Contains : SQLComparisonOperator.StartsWith;
				query.AddToFilter(RefCurrencySchema.RX_Code, @operator, RX_Desc.SubstringSafe(0, RefCurrencySchema.RX_Code.MaxLength));
				query.AddToFilter(JoinCondition.Or, RefCurrencySchema.RX_Desc, @operator, RX_Desc.SubstringSafe(0, RefCurrencySchema.RX_Desc.MaxLength));

				if (IsActive != "ALL")
				{
					if (IsActive == "ACTIVE")
					{
						query.AddToFilter(RefCurrencySchema.RX_IsActive, ZBool.True);
					}
					else
					{
						query.AddToFilter(RefCurrencySchema.RX_IsActive, ZBool.False);
					}
				}

				return query;
			}
		}


		#region Filters

		public override ZQuery Filter
		{
			get
			{
				if (filterQuery == null)
				{
					if (IM_OH_Client.IsEmpty)
					{
						filterQuery = new ZQuery();
						filterQuery.IsNoResultQuery = true;
					}
					else if (!IncidentNumber.IsEmpty)
					{
						filterQuery = new ZQuery();
						filterQuery.DefaultJoinCondition = JoinCondition.And;
						filterQuery.AddToFilter(ClientPanelFilter);
						AddIncidentNumberFilter(filterQuery);
					}
					else
					{
						filterQuery = base.Filter;
						try
						{
							AddFixedOnThisVersionFilter(filterQuery);
						}
						catch (Exception ex) when (!ex.IsCriticalException())
						{
							(new WebExceptionReporter()).ReportWebException(ex, "Exception when trying to AddFixedOnThisVersionFilter", "Exception when trying to AddFixedOnThisVersionFilter");
						}

						AddIncidentCutOffDateFilter(filterQuery);
						AddContactFilter(filterQuery);
						AddDescriptionFilter(filterQuery);
						AddOrganisationFilter(filterQuery);
					}
				}
				return filterQuery;
			}
		}

		void AddOrganisationFilter(ZQuery query)
		{
			if (Organisation.IsValid && !Organisation.IsEmpty)
			{
				query.AddToFilter(IncidentMainSchema.IM_OH_Client, Organisation);
			}
		}

		void AddIncidentCutOffDateFilter(ZQuery query)
		{
			ZDateTime cutOffDate = EDIDataRegistry.Instance.ShowIncidentsLoggedAfterThisDate;
			if (cutOffDate.IsValid)
			{
				query.AddToFilter(IncidentMainSchema.IM_SystemCreateTimeUtc, SQLComparisonOperator.GreaterThanOrEqualTo, cutOffDate);
			}
		}

		void AddContactFilter(ZQuery query)
		{
			if (!string.IsNullOrEmpty(ContactName))
			{
				var contactPKs = new List<ZGuid>(ContactPkNamePairList.Count);
				foreach (var tuple in ContactPkNamePairList)
				{
					if (String.Compare(tuple.Item2, ContactName, StringComparison.OrdinalIgnoreCase) == 0)
					{
						contactPKs.Add(tuple.Item1);
					}
				}
				query.AddToFilter(IncidentMainSchema.IM_OC_Contact, contactPKs);
			}
		}

		void AddIncidentNumberFilter(ZQuery query)
		{
			if (!IncidentNumber.IsEmpty)
			{
				AddIfNotEmpty(query, IncidentMainSchema.IM_IncidentNumber, SQLComparisonOperator.Equal, IncidentNumber);
			}
		}

		void AddDescriptionFilter(ZQuery query)
		{
			if (!Description.IsEmpty)
			{
				AddIfNotEmpty(query, IncidentMainSchema.IM_Description, SQLComparisonOperator.Contains, Description);
			}
		}

		protected override ZQuery ClientPanelFilter
		{
			get
			{
				ZQuery query = new ZQuery();
				query.AddToFilter(SupportIncidentFilterBusinessObject.GetMatchingClientOrMatchingManagementGroupQuery(IM_OH_Client), JoinCondition.And);
				return query;
			}
		}

		void AddFixedOnThisVersionFilter(ZQuery query)
		{
			if (CurrentReleaseBuild != null && RequestedReleaseBuild != null)
			{
				if (CurrentReleaseBuild.VersionNumber == RequestedReleaseBuild.VersionNumber)
				{
					query.IsNoResultQuery = true;
				}
				else
				{
					query.AddToFilter(new ReleaseBuildContent(Factory).GetPatchedIncidentsQuery(CurrentReleaseBuild, RequestedReleaseBuild));
				}
			}
		}

		protected override ZQuery StatusGroupboxFilter
		{
			get
			{
				ZQuery query = new ZQuery();

				switch (Stage)
				{
					case AllStages:
						AddAllStagesStatusQuery(JoinCondition.And, query);
						break;

					default:
						AddStatusQuery(JoinCondition.And, query);
						break;
				}

				return query;
			}
		}

		void AddStatusQuery(JoinCondition condition, ZQuery query)
		{
			ZQuery newQuery = new ZQuery();

			if (Status == SupportIncidentLookups.Status.ClosedDirectlyInSupport)
			{
				newQuery.AddToFilter(IncidentMainSchema.IM_Category, SupportIncidentCategoriesList.Codes.Support);
				newQuery.AddToFilter(IncidentMainSchema.IM_Status, SupportIncidentLookups.Status.Closed);
			}
			else if (Status == SupportIncidentLookups.Status.Closed && Stage == SupportIncidentCategoriesList.Codes.Support)
			{
				var closedDirectlyInSupportQuery = new ZQuery(IncidentMainSchema.IM_Category, SupportIncidentCategoriesList.Codes.Support);
				closedDirectlyInSupportQuery.AddToFilter(IncidentMainSchema.IM_Status, SupportIncidentLookups.Status.Closed);
				var isEscalatedQuery = new ZQuery(IncidentMainSchema.IM_Category, SQLComparisonOperator.NotEqual, SupportIncidentCategoriesList.Codes.Support);

				newQuery.AddToFilter(new ZQuery(closedDirectlyInSupportQuery, JoinCondition.Or, isEscalatedQuery));
			}
			else
			{
				newQuery.AddToFilter(IncidentMainSchema.IM_Category, Stage);
				if (Status == SupportIncidentLookups.Status.NotClosed)
				{
					newQuery.AddToFilter(IncidentMainSchema.IM_Status, SQLComparisonOperator.NotEqual, SupportIncidentLookups.Status.Closed);
					newQuery.AddToFilter(IncidentMainSchema.IM_Status, SQLComparisonOperator.NotEqual, ZString.Empty);
				}
				else if (!Status.IsEmpty)
				{
					newQuery.AddToFilter(IncidentMainSchema.IM_Status, Status);
				}
			}

			if (!Disposition.IsEmpty)
			{
				newQuery.AddToFilter(IncidentMainSchema.IM_ResolutionCode, Disposition);
			}

			query.AddToFilter(newQuery, condition);
		}

		void AddAllStagesStatusQuery(JoinCondition condition, ZQuery query)
		{
			ZQuery newQuery = new ZQuery();

			if (Status != SupportIncidentLookups.Status.ClosedDirectlyInSupport)
			{
				if (Status == SupportIncidentLookups.Status.NotClosed)
				{
					newQuery.AddToFilter(IncidentMainSchema.IM_Status, SQLComparisonOperator.NotEqual, SupportIncidentLookups.Status.Closed);
				}
				else if (Status == SupportIncidentLookups.Status.Closed)
				{
					var closedDirectlyInSupportQuery = new ZQuery(IncidentMainSchema.IM_Category, SupportIncidentCategoriesList.Codes.Support);
					closedDirectlyInSupportQuery.AddToFilter(IncidentMainSchema.IM_Status, SupportIncidentLookups.Status.Closed);
					var isEscalatedQuery = new ZQuery(IncidentMainSchema.IM_Category, SQLComparisonOperator.NotEqual, SupportIncidentCategoriesList.Codes.Support);

					newQuery.AddToFilter(new ZQuery(closedDirectlyInSupportQuery, JoinCondition.Or, isEscalatedQuery));
				}
				else if (!Status.IsEmpty)
				{
					newQuery.AddToFilter(IncidentMainSchema.IM_Status, Status);
				}
			}

			query.AddToFilter(newQuery, condition);
		}

		protected override ZQuery AssignedToPanelFilter
		{
			get
			{
				ZQuery result = base.AssignedToPanelFilter;
				if (!AssignedTo.IsEmpty)
				{
					if (Stage == AllStages)
					{
						ZQuery supportQuery = new ZQuery(IncidentMainSchema.IM_Category, SQLComparisonOperator.Equal, SupportIncidentCategoriesList.Codes.Support);
						supportQuery.AddToFilter(IncidentMainSchema.IM_GS_NKCustServiceContact, AssignedTo);

						ZQuery nonSupportQuery = new ZQuery(IncidentMainSchema.IM_Category, SQLComparisonOperator.NotEqual, SupportIncidentCategoriesList.Codes.Support);
						nonSupportQuery.AddToFilter(IncidentMainSchema.IM_GS_NKAssignedToCurrent, AssignedTo);

						result.AddToFilter(new ZQuery(supportQuery, JoinCondition.Or, nonSupportQuery));
					}
					else if (Stage == SupportIncidentCategoriesList.Codes.Support)
					{
						result.AddToFilter(IncidentMainSchema.IM_GS_NKCustServiceContact, AssignedTo);
					}
					else
					{
						result.AddToFilter(IncidentMainSchema.IM_Category, SQLComparisonOperator.NotEqual, SupportIncidentCategoriesList.Codes.Support);
						result.AddToFilter(IncidentMainSchema.IM_GS_NKAssignedToCurrent, AssignedTo);
					}
				}
				return result;
			}
		}


		ZString FormatIncidentNumber(ZString number)
		{
			ZString result = number;

			if (!number.IsEmpty)
			{
				string prefix = "CS";
				ZString formatted = number;
				formatted = formatted.Replace(prefix, "");
				if (!formatted.ContainsAnyLetters)
				{
					formatted = formatted.PadLeft(8, '0');
					formatted = prefix + formatted;

					if (result != formatted)
					{
						result = formatted;
					}
				}
			}

			return result;
		}


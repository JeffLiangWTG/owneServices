				ReleaseBuild requestedReleaseBuild = null;
				if (!String.IsNullOrEmpty(RequestedReleaseBuildPK) && RequestedReleaseBuildPK != "null")
				{
					requestedReleaseBuild = Factory.Load<ReleaseBuild>(new ZGuid(RequestedReleaseBuildPK));

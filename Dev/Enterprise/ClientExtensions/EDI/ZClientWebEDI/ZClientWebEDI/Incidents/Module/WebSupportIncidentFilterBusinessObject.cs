		List<Tuple<ZGuid, ZString>> GetContactPkNamePairList()
		{
			var result = new List<Tuple<ZGuid, ZString>>();

			if (Client != null)
			{
				var parameters = new string[OrganisationPKs.Count];
				for (int i = 0; i < parameters.Length; i++)
				{
					parameters[i] = string.Format("@OC_OH{0}", i);
				}

				string query =
@"SELECT OC_PK, OC_ContactName 
FROM dbo.OrgContact
WHERE OC_OH IN ({0})
ORDER BY OC_ContactName";

				using (DbCommand command = Db.Connection.Command(string.Format(query, string.Join(", ", parameters))))
				{
					for (int i = 0; i < parameters.Length; i++)
					{
						Guid orgPk = OrganisationPKs[i].IsEmpty ? Guid.Empty : OrganisationPKs[i].ToGuid();
						command.AddParameter(parameters[i], SqlDbType.UniqueIdentifier, orgPk);
					}

					using (var reader = command.ExecuteReader())
					{
						while (reader.Read())
						{
							Guid contactPk = ((Guid)reader[OrgContactSchema.Constants.PK]);
							string contactName = (string)reader[OrgContactSchema.Constants.OC_ContactName];
							var tuple = new Tuple<ZGuid, ZString>(contactPk, contactName);
							result.Add(tuple);
						}
					}
				}
			}

			return result;
		}


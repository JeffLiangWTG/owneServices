using CargoWise.EntityFramework;
using CargoWise.Types;
using Enterprise.Client.EDI.IdentityApplication.Business;
using Enterprise.Client.EDI.IdentityCertificate.Business;
using Enterprise.Client.EDI.Modules;
using Enterprise.ZArchitecture.Business;
using Enterprise.ZArchitecture.Core;
using Enterprise.ZArchitecture.Schema;
using Res = ZClientEDI.Res;
using ResString = ZClientEDI.ResString;

namespace Enterprise.Client.EDI.IdentityCertificate
{
	public class EdiIdentityCertificateFilterBusinessObject : FilterStripBusinessObject
	{
		protected override ModuleFilterCollection GetModuleFiltersCore()
		{
			var filters = new ModuleFilterCollection();
			AddTextFilters(filters);
			AddDateFilters(filters);
			AddFlagFilters(filters);
			AddApplicationFilters(filters);
			AddNumberRangeFilter(filters);

			return filters;
		}

		void AddTextFilters(ModuleFilterCollection filters)
		{
			filters.AddTextFilter("Thumbprint", EdiIdentityCertificateSchema.ICE_CertificateThumbprint);
			filters.AddTextFilter("Issued By", EdiIdentityCertificateSchema.ICE_CertificateIssuedBy);
			filters.AddTextFilter("Issued To", EdiIdentityCertificateSchema.ICE_CertificateIssuedTo);
		}

		void AddNumberRangeFilter(ModuleFilterCollection filters)
		{
			filters.AddNumberRangeFilter("Sequence Number", EdiIdentityCertificateSchema.ICE_SequenceNumber);
		}

		void AddDateFilters(ModuleFilterCollection filters)
		{
			filters.AddDateFilter("Valid Date", EdiIdentityCertificateSchema.ICE_CertificateValidDate);
			filters.AddDateFilter("Expiry Date", EdiIdentityCertificateSchema.ICE_CertificateExpiryDate);
		}

		void AddFlagFilters(ModuleFilterCollection filters)
		{
			var isRevokedFilter = filters.AddTextFilter("Revoked Status", GetIsRevokedQuery, RevokedStatusList);
			isRevokedFilter.Category = FilterCategories.StatusAndFlags;
			isRevokedFilter.MultilingualDescription = ResString.GetMultilingualString("A544790E-767D-494F-9883-58EF06CA33CD", "Revoked Status");

			var processingStatusFilter = filters.AddTextFilter("Processing Status", GetProcessingStatusQuery, ProcessingStatusList);
			processingStatusFilter.Category = FilterCategories.StatusAndFlags;
			processingStatusFilter.MultilingualDescription = ResString.GetMultilingualString("B7C82A67-4F97-4483-9A91-D8922FB60CB4", "Processing Status");

			var autoGeneratedFilter = filters.AddTextFilter("Auto/Manually Generated", GetAutoOrManuallyGeneratedQuery, AutoOrManuallyGeneratedList);
			autoGeneratedFilter.Category = FilterCategories.StatusAndFlags;
			autoGeneratedFilter.MultilingualDescription = ResString.GetMultilingualString("177ECC3D-ECC0-4804-962B-E84EB0B0BA04", "Auto/Manually Generated");
		}

		ZQuery GetIsRevokedQuery(ZString value)
		{
			if (StatusAll.EqualsUnresolvedOrLocalized(value, ignoreCase: false))
			{
				return new ZQuery();
			}

			return new ZQuery(EdiIdentityCertificateSchema.ICE_IsCertificateRevoked, value == StatusRevoked);
		}

		ZQuery GetProcessingStatusQuery(ZString value)
		{
			if (StatusAll.EqualsUnresolvedOrLocalized(value, ignoreCase: false))
			{
				return new ZQuery();
			}

			return new ZQuery(EdiIdentityCertificateSchema.ICE_ProcessingStatus, value);
		}

		ZQuery GetAutoOrManuallyGeneratedQuery(ZString value)
		{
			var applicationSubQuery = new ZDBOnlySubQuery(typeof(EdiIdentityApplication), EdiIdentityApplicationSchema.PK);
			var certificateQuery = new ZDBOnlyQuery(typeof(EdiIdentityCertificate));

			if (value == ManuallyGenerated)
			{
				applicationSubQuery.AddToFilter(EdiIdentityApplicationSchema.IDA_LD, null);
				certificateQuery.AddSubQuery(EdiIdentityCertificateSchema.ICE_IDA, applicationSubQuery, JoinCondition.And);
				return certificateQuery;
			}

			if (value == AutoGenerated)
			{
				applicationSubQuery.AddToFilter(EdiIdentityApplicationSchema.IDA_LD, SQLComparisonOperator.NotEqual, null);
				certificateQuery.AddSubQuery(EdiIdentityCertificateSchema.ICE_IDA, applicationSubQuery, JoinCondition.And);
				return certificateQuery;
			}

			return new ZQuery();
		}

		internal static string StatusRevoked => Res.GetString("734D397D-6E96-4803-9C75-ED0CA6D4FB43", "Revoked");
		internal static string StatusNonRevoked => Res.GetString("6A4E182E-7038-464B-8E79-D0A60F1C7954", "Non-Revoked");
		internal static string AutoGenerated => Res.GetString("3D279DFD-2264-4A05-AB8F-C12483CD246D", "Auto-Generated");
		internal static string ManuallyGenerated => Res.GetString("6D7299F0-BDFB-4C10-9CC9-60D791B05F1D", "Manually Generated");
		internal static string ShowAllDescription => Res.GetString("0EBD192F-24EE-467B-A874-5A5B312E3DDA", "Show all records");

		CodeDescriptionPairList ProcessingStatusList
		{
			get
			{
				var codeDescriptionPairList = new CodeDescriptionPairList();
				codeDescriptionPairList.AddPair(StatusAll, ShowAllDescription);

				foreach (CodeDescriptionPair item in EdiIdentityCertificateLookups.ProcessingStatusList)
				{
					codeDescriptionPairList.Add(item);
				}
				return codeDescriptionPairList;
			}
		}

		CodeDescriptionPairList RevokedStatusList
		{
			get
			{
				var codeDescriptionPairList = new CodeDescriptionPairList();
				codeDescriptionPairList.AddPair(StatusAll, ShowAllDescription);
				codeDescriptionPairList.AddPair(StatusRevoked, Res.GetString("02A3436E-FF76-4591-AFB2-EFA3E4C69E1F", "Revoked Only"));
				codeDescriptionPairList.AddPair(StatusNonRevoked, Res.GetString("F4688601-9CA4-40E5-A33F-5DA76C236381", "Non-Revoked Only"));
				return codeDescriptionPairList;
			}
		}

		CodeDescriptionPairList AutoOrManuallyGeneratedList
		{
			get
			{
				var codeDescriptionPairList = new CodeDescriptionPairList();
				codeDescriptionPairList.AddPair(StatusAll, ShowAllDescription);
				codeDescriptionPairList.AddPair(AutoGenerated, Res.GetString("AF04F410-4EA0-4B5E-AEB7-622274F9BDF9", "Auto-Generated Only"));
				codeDescriptionPairList.AddPair(ManuallyGenerated, Res.GetString("5B448162-564B-4535-B9B6-48C86B7ABB0F", "Manually Generated Only"));
				return codeDescriptionPairList;
			}
		}

		void AddApplicationFilters(ModuleFilterCollection filters)
		{
			var applicationFilter = new ModuleGuidForeignCollectionFilter("Application", ClientModuleRegistration.EdiIdentityApplication, EdiIdentityCertificateSchema.PK, EdiIdentityCertificateSchema.ICE_IDA, new EdiIdentityApplicationCollection(Factory), typeof(EdiIdentityCertificate));
			applicationFilter.MultilingualDescription = ResString.GetMultilingualString("CBE32F50-A5A1-4A99-A10E-0780838C6C74", "Application");
			applicationFilter.ComparisonOperator_List.Clear();
			applicationFilter.ComparisonOperator_List.AddPair(ModuleFilterWithListAndComparisonOperators<ZGuid>.ComparisonConstants.AnyMatch);
			applicationFilter.ComparisonOperator_List.AddPair(ModuleFilterWithListAndComparisonOperators<ZGuid>.ComparisonConstants.NoneMatch);
			filters.AddFilter(applicationFilter);
		}
	}
}

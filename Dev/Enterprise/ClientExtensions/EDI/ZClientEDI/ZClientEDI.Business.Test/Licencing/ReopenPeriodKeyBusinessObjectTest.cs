using System.Globalization;
using CargoWise.EntityFramework;
using CargoWise.EntityFramework.Testing;
using Enterprise.Client.EDI.Licencing.Business;
using Enterprise.Client.EDI.MasterFiles.Business;
using Enterprise.MasterFiles.Business;
using Enterprise.ZArchitecture.Business;
using Enterprise.ZArchitecture.Core;
using Enterprise.ZArchitecture.Schema;
using NUnit.Framework;

namespace Enterprise.Client.EDI.LicenceKeyBuilder.Business.Test
{
	[TestedType(typeof(ReopenPeriodKeyBusinessObject))]
	public class ReopenPeriodKeyBusinessObjectTest : NonPersistentBusinessObjectTestCase
	{
		public void TestDefaultDatabaseAndComapny()
		{
			var org = Factory.NewWithValidTestData<EDIOrgHeader>();
			org.OH_Code = "DDDABCSYD";
			org.CreateAndLoadLicenceForOrg();
			org.LicenceEnterpriseCode = "DDD";
			org.LicCompany.LC_CompanyCode = "ABC";

			var database1 = Factory.NewWithValidTestData<LicenceDatabase>();
			database1.LD_LE = org.LicEnterprise.PK;
			database1.LD_ServerCode = "HST";
			database1.LD_LicenceType = DatabaseTypes.Codes.Production;

			var database2 = org.LicCompany.ActiveOrAllLicDatabases.AddNew();
			database2.LD_ServerCode = "ABC";
			database2.LD_LicenceType = DatabaseTypes.Codes.Training;

			var database3 = org.LicCompany.ActiveOrAllLicDatabases.AddNew();
			database3.LD_ServerCode = "SYD";
			database3.LD_LicenceType = DatabaseTypes.Codes.Production;

			var clientCompany1 = Factory.New<ClientCompany>();
			clientCompany1.LCC_Code = "AAA";
			clientCompany1.LCC_LD = database3.PK;

			var clientCompany2 = Factory.New<ClientCompany>();
			clientCompany2.LCC_Code = "ABC";
			clientCompany2.LCC_LD = database3.PK;
			clientCompany2.LCC_OH = org.PK;

			Factory.Save();

			var reopenPeriodKeyBusinessObject = new ReopenPeriodKeyBusinessObject(org);
			AssertEquals("Default database code", "SYD", reopenPeriodKeyBusinessObject.DatabaseServerCode);
			AssertEquals("Default company code", "ABC", reopenPeriodKeyBusinessObject.ClientCompanyCode);
		}

		public void TestGenerateKey()
		{
			EDIOrgHeader demoOrg = Factory.LoadFromNaturalKey<EDIOrgHeader>(OrgHeaderSchema.OH_Code, "DEMORG");
			demoOrg.CreateAndLoadLicenceForOrg();
			demoOrg.LicenceEnterpriseCode = "EDI";

			var database = demoOrg.LicCompany.ActiveOrAllLicDatabases.AddNew();
			database.LD_ServerCode = "PRD";

			var clientCompany = Factory.New<ClientCompany>();
			clientCompany.LCC_Code = demoOrg.LicCompany.LC_CompanyCode;
			clientCompany.LCC_LD = database.PK;
			clientCompany.LCC_OH = demoOrg.PK;

			Factory.Save();

			ReopenPeriodKeyBusinessObject reopenPeriodKeyBusinessObject = new ReopenPeriodKeyBusinessObject(demoOrg);
			reopenPeriodKeyBusinessObject.Period = "200909";
			reopenPeriodKeyBusinessObject.UserStaffCode = "PL";
			string key = reopenPeriodKeyBusinessObject.GenerateKey();
			AssertEquals("Key", key, reopenPeriodKeyBusinessObject.Key);

			var org = reopenPeriodKeyBusinessObject.Factory.Load<EDIOrgHeader>(demoOrg.PK);
			StmALog log = (StmALog)org.Logs.GetAllLogs().Find(new ZQuery(StmALogSchema.SL_SE_NKEvent, Events.PeriodReopened.Code))[0];
			AssertEquals("Log record should be Period Reopened", Events.PeriodReopened.Code, log.SL_SE_NKEvent);
			AssertEquals("Log Reference", string.Format(CultureInfo.CurrentCulture, "Period Reopen Key Generated by {0} for user staff code {1} at {2} GMT for period {3}", GlbStaff.CurrentUser.GS_LoginName, reopenPeriodKeyBusinessObject.UserStaffCode, key.Substring(0, 13), reopenPeriodKeyBusinessObject.Period), log.SL_Reference);
		}

		protected override BusinessObject GetNewBusinessObject()
		{
			EDIOrgHeader demoOrg = Factory.LoadFromNaturalKey<EDIOrgHeader>(OrgHeaderSchema.OH_Code, "DEMORG");
			demoOrg.CreateAndLoadLicenceForOrg();
			demoOrg.LicenceEnterpriseCode = "EDI";
			demoOrg.Factory.Save();
			return new ReopenPeriodKeyBusinessObject(demoOrg);
		}
	}
}

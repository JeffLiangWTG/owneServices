			FileUpLoaderX509CertificateRegistryEditorInfo editorInfo = new FileUpLoaderX509CertificateRegistryEditorInfo();
			FallbackLevel fallbackLevel = new FallbackLevel(Guid.NewGuid(), Guid.Empty, Guid.Empty);

			DigitalCertificateRegistryItemEditor editor = new DigitalCertificateRegistryItemEditor(null, editorInfo, fallbackLevel);
			FileUpLoaderX509CertificateRegistryEditorInfo obtainedEditorInfo = (FileUpLoaderX509CertificateRegistryEditorInfo)typeof(DigitalCertificateRegistryItemEditor).GetField("EditorInfo", BindingFlags.NonPublic | BindingFlags.Instance).GetValue(editor);
			AssertEquals("Editor.EditorInfo", editorInfo, obtainedEditorInfo);
			AssertEquals("Editor.EditorInfo.FallbackLevel", fallbackLevel, obtainedEditorInfo.FallbackLevel);
		}


using System.Windows.Forms;
using Enterprise.Integration;

namespace Enterprise.Registry.GUI
{
	public class AuthenticationRegistryItemEditor : RegistryItemEditor
	{
		readonly bool autoGeneratedPassword;

		public AuthenticationRegistryItemEditor(bool autoGeneratedPassword, IRegistryDataType dataType)
			: base(dataType)
		{
			this.autoGeneratedPassword = autoGeneratedPassword;
		}

		protected override Control NewWinFormsEditorPaneCore()
		{
			return new AuthenticationControl(autoGeneratedPassword);
		}

		protected override object GetValueFromEditorPaneCore(Control editorPane)
		{
			return ((AuthenticationControl)editorPane).Value;
		}

		protected override void SetValueFromEditorPaneCore(Control editorPane, object value)
		{
			((AuthenticationControl)editorPane).Value = (string)value;
		}

		public override string GetCustomValidation(Control editorPane)
		{
			if (string.IsNullOrEmpty(((AuthenticationControl)editorPane).Value))
			{
				return Res.GetString("30F8EB92-A018-497B-9CAD-73E4E9B40A35", "Fields cannot be empty or contain special characters. Please fill in both fields before saving.");
			}
			return "";
		}
	}
}

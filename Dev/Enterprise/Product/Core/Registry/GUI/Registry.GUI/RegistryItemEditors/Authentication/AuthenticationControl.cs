using System;
using System.ComponentModel;
using System.Security.Cryptography;
using System.Text.RegularExpressions;
using CargoWise.EntityFramework;
using Enterprise.ZArchitecture.Environment;
using Enterprise.ZArchitecture.GUI;

namespace Enterprise.Registry.GUI
{
	public partial class AuthenticationControl : ZUserControl, INotifyRegistryFormSave, ICustomHasChangesControl
	{
		internal int passwordLength = 24;
		internal bool isPasswordGenerated;
		internal ZButton GeneratePasswordButton;
		internal const char delimiter = '|';
		internal readonly bool autoGeneratedPassword;

		public AuthenticationControl(bool autoGeneratedPassword)
		{
			this.autoGeneratedPassword = autoGeneratedPassword;
			InitializeComponent();
		}

		[Browsable(false)]
		[DesignerSerializationVisibility(DesignerSerializationVisibility.Hidden)]
		public string Value
		{
			get { return CollectValue(); }
			set { PopulateControl(value); }
		}

		string CollectValue()
		{
			if (string.IsNullOrEmpty(UserName.Text) ||
				string.IsNullOrEmpty(Password.Text) ||
				!Regex.IsMatch(UserName.Text, "^[a-zA-Z0-9]*$"))
			{
				return "";
			}

			return UserName.Text + delimiter + Password.Text;
		}

		void PopulateControl(string value)
		{
			if (String.IsNullOrEmpty(value))
			{
				return;
			}

			var parts = value.Split(delimiter);
			if (parts.Length == 2)
			{
				UserName.Text = parts[0];
				Password.Text = parts[1];
			}
		}

		void UserName_Validated(object sender, EventArgs e)
		{
			UserName.Text = UserName.Text.Trim();
		}

		void Password_Validated(object sender, EventArgs e)
		{
			Password.Text = Password.Text.Trim();
		}

		public void ShowInvalidUsernameMessage()
		{
			Globals.Message.ShowError(Res.GetString("67D7EFF0-AF15-45D8-BC43-4E550DD83B5E", "Username cannot contain special characters. Please use alphanumeric characters only."), Res.GetString("0A5A8989-9904-478A-8925-36A128528752", "Invalid User Name"));
		}

		public void ShowEmptyUsernameMessage()
		{
			Globals.Message.ShowError(Res.GetString("90EA2100-3301-4BA0-9C2E-8D3FD70074EB", "Please enter a username."), Res.GetString("0A5A8989-9904-478A-8925-36A128528752", "Invalid User Name"));
		}

		internal string GeneratePassword(int length)
		{
			if (length < 1)
			{
				throw new ArgumentException("Length must be greater than 0", nameof(length));
			}

			byte[] buffer = new byte[(length + 2) / 4 * 3];
			using (var rng = RandomNumberGenerator.Create())
			{
				rng.GetBytes(buffer);
			}

			return Convert.ToBase64String(buffer);
		}

		void GeneratePasswordButton_Click(object sender, EventArgs e)
		{
			if (string.IsNullOrEmpty(UserName.Text))
			{
				ShowEmptyUsernameMessage();
				return;
			}

			if (!Regex.IsMatch(UserName.Text, "^[a-zA-Z0-9]*$"))
			{
				ShowInvalidUsernameMessage();
				return;
			}

			if (!isPasswordGenerated && !String.IsNullOrEmpty(Password.Text))
			{
				ZDialogResult result = Globals.Message.ShowConfirmation(Res.GetString("37543F9A-259A-49A5-9C4E-8958D1A79F3F", "WARNING: Reset Password - Irreversible Action. Would you like to proceed?"), Res.GetString("1E62DD20-41B7-4FB2-BEB6-700059121808", "Reset Password Warning"), "YES", ZMessageBoxIcon.Warning);
				if (result != ZDialogResult.OK)
				{
					return;
				}
			}

			Password.Text = GeneratePassword(passwordLength);
			Password.PasswordChar = '\0';
			isPasswordGenerated = true;

			HasChangesChanged?.Invoke(this, HasChangesChangedEventArgs.Create(true, this));
		}

		void HandleAutogeneratedComponents()
		{
			if (this.autoGeneratedPassword)
			{
				this.GeneratePasswordButton = new Enterprise.ZArchitecture.GUI.ZButton();

				this.Password.ReadOnly = true;

				this.GeneratePasswordButton.Anchor = System.Windows.Forms.AnchorStyles.Top | System.Windows.Forms.AnchorStyles.Right;
				this.GeneratePasswordButton.BackColor = System.Drawing.SystemColors.ControlLight;
				this.GeneratePasswordButton.CaptionResourceString = Enterprise.Registry.GUI.Res.GetData("AuthenticationControl|26696B97-F347-4FDB-82FB-C470857EBC63", "Generate Password");
				this.GeneratePasswordButton.Location = CargoWise.Windows.UI.ControlDpiScalingHelper.NewScaledPoint(313, 30, true);
				this.GeneratePasswordButton.Name = "GeneratePasswordButton";
				this.GeneratePasswordButton.Size = CargoWise.Windows.UI.ControlDpiScalingHelper.NewScaledSize(110, 19, true);
				this.GeneratePasswordButton.TabIndex = 13;
				this.GeneratePasswordButton.ToolTipCaption = null;
				this.GeneratePasswordButton.UseVisualStyleBackColor = false;
				this.GeneratePasswordButton.Click += new System.EventHandler(this.GeneratePasswordButton_Click);

				this.Controls.Add(this.GeneratePasswordButton);
			}
		}

		public void OnRegistryFormSave()
		{
			Password.PasswordChar = '*';
			isPasswordGenerated = false;
		}

		public event EventHandler<HasChangesChangedEventArgs> HasChangesChanged;
	}
}

		void ThrowExceptionIfScrollbarExistsOrTextIsNotVisible(object sender, EventArgs e)
		{
			var conversationMessageUserControl = (ConversationMessageUserControl)sender;
			var bodyTextBox = (KRichTextBox)conversationMessageUserControl.Controls.Find("bodyTextBox", true)[0];
			Application.DoEvents();

			if (conversationMessageUserControl.VerticalScroll.Visible)
			{
				throw new ArgumentException("Message should not have scrollbar within ConversationMessageUserControl");
			}

			var (start, end) = CalculateVisibleIndexRange(bodyTextBox);
			if (start != 0)
			{
				throw new ArgumentException("Message should not have scrollbar within BodyTextBox: Missing text at start");
			}
			if (end != bodyTextBox.Text.Length - 1)
			{
				throw new ArgumentException("Message should not have scrollbar within BodyTextBox: Missing text at end");
			}
		}

		protected virtual (int, int) CalculateVisibleIndexRange(KRichTextBox textbox, double heightProportion = 1.0d)
		{
			var lastPoint = new Point(textbox.ClientSize.Width - ControlDpiScalingHelper.ScaleToCurrentDpiX(2), Convert.ToInt32(textbox.ClientSize.Height * heightProportion) - ControlDpiScalingHelper.ScaleToCurrentDpiY(2));
			var firstPoint = ControlDpiScalingHelper.NewScaledPoint(2, 2);

			return (textbox.GetCharIndexFromPosition(firstPoint), textbox.GetCharIndexFromPosition(lastPoint));
		}


		void AssertCollectionIsNotReadOnlyButChildrenAre(string controlName, Func<JobConversation, JobConversationParticipantCollection> getCollection)
		{
			const string checkpointName = SecurityCore.ConversationEditInternalParticipantsAutoGeneratedCode;

			using (var module = GetZModule())
			{
				var shipment = Factory.NewWithValidTestData<DummyConversationProvider>();
				Factory.Save();

				shipment.eConversation.Participants.AddNewParticipant(Factory.NewWithValidTestData<GlbStaff>());
				shipment.eConversation.Participants.AddNewParticipant(Factory.NewWithValidTestData<GlbGroup>());

				Env.Security.FindOrCreateConversationCheckpoint(module.SecurityCheckpoint, module.ModuleID, checkpointName).IsAllowed = true;
				using (var tabPage = new EConversationFullControl(module.ModuleID))
				{
					tabPage.SetDataBinding(shipment, "");

					var grid = (ZGrid)tabPage.Controls.Find(controlName, true)[0];
					Assert("The grid shouldnt be read only", !grid.ReadOnly);

					var collection = getCollection(shipment.eConversation);
					Assert("PRE: Should be something to check", collection.Count > 0);
					Assert("All child participants should be modifyable", collection.All(child => !child.ReadOnly));
					Assert("The collection itself should not be read only", !collection.ReadOnly);
				}

				Env.Security.FindOrCreateConversationCheckpoint(module.SecurityCheckpoint, module.ModuleID, checkpointName).IsAllowed = false;
				using (var tabPage = new EConversationFullControl(module.ModuleID))
				{
					tabPage.SetDataBinding(shipment, "");

					var grid = (ZGrid)tabPage.Controls.Find(controlName, true)[0];
					Assert("The grid shouldnt directly be read only", !grid.ReadOnly);

					var collection = getCollection(shipment.eConversation);
					Assert("PRE: Should be something to check", collection.Count > 0);
					Assert("All child participants should be read only", collection.All(child => child.ReadOnly));
					Assert("The collection itself should not be read only", !collection.ReadOnly);
				}
			}
		}


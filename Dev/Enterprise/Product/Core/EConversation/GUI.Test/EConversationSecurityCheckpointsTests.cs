using System.Linq;
using System.Reflection;
using System.Text.RegularExpressions;
using CargoWise.EntityFramework.Testing;
using Enterprise.EConversation.GUI;
using Enterprise.Security;
using Enterprise.ZArchitecture.Modules;

namespace Enterprise.EConversation.Testing
{
	sealed class EConversationSecurityCheckpointsTests : TestCaseWithFactory
	{
		public void TestSelectsCorrectItems()
		{
			var module = ModuleIDs.JobShipment;
			var checkpoints = new EConversationSecurityCheckpoints(module);
			var excludedFields = new[] { nameof(SecurityCore.ConversationAutoGeneratedCode) };

			// Find conversation related items through reflection
			var expectedFieldNameRegex = new Regex("^Conversation(\\w+)AutoGeneratedCode$");
			var securityCodeFields = typeof(SecurityCore)
				.GetFields(BindingFlags.Static | BindingFlags.Public)
				.Where(field => field.FieldType == typeof(string) && expectedFieldNameRegex.IsMatch(field.Name) && !excludedFields.Contains(field.Name))
				.ToList();

			CombineAssertions(() =>
			{
				foreach (var field in securityCodeFields)
				{
					var expectedFieldName = expectedFieldNameRegex.Match(field.Name).Groups[1].Value;
					var expectedCode = (string)field.GetValue(null);

					var checkpoint = (ISecurityCheckpoint)checkpoints.GetType().GetProperty(expectedFieldName)?.GetValue(checkpoints);

					AssertNotNull($"Checkpoint for " + expectedFieldName + " shouldExist", checkpoint);
					AssertEndsWith("Should be the correct code", expectedCode, checkpoint?.Code);
				}
			});
		}
	}
}

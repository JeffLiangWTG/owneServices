using System;
using CargoWise.EntityFramework;
using CargoWiseOne.ResourceStrings;
using Enterprise.EConversation.Business;
using Enterprise.Environment;
using Enterprise.Security;
using Enterprise.ZArchitecture.GUI;
using Enterprise.ZArchitecture.Modules;
using Enterprise.ZArchitecture.PlugIn;

namespace Enterprise.EConversation.GUI
{
	public class EConversationPluginController : ZController
	{
		public override bool MakeUrlsOnlyOpenableForCurrentCompany => true;

		public EConversationPluginController()
		{
		}

		public override ControllerID ID => ControllerIDs.eConversationPlugIn;
		public override ModuleIdentifier ModuleID
		{
			get
			{
				throw new ModuleGuiNotSupportedException("Not supported");
			}
		}

		protected override ZPlugIn GetPlugIn(IBusiness host)
		{
			var conversationProvider = host as IConversationProvider;

			return conversationProvider != null ? new EConversationPlugin(conversationProvider.ParentModule, host) : null;
		}

		public override Type TypeOfTopLevelBusinessObject => null;

		public override ResourceStringData PluginTabPageCaption => Res.GetData("941a8f4d-ae0e-4396-ba58-d4ebba2e25d6", "eConversation");

		protected override SecurityCheckpoint CheckPointForDelete => Env.Security.None;
		protected override SecurityCheckpoint CheckPointForEdit => Env.Security.None;
		protected override SecurityCheckpoint CheckPointForNew => Env.Security.None;
		protected override SecurityCheckpoint CheckPointForView => Env.Security.None;

		public override SecurityCheckpoint GetCheckPointForView(BusinessObject bizObject)
		{
			var provider = bizObject as IConversationProvider;
			if (provider != null)
			{
				using (var module = ZModuleFactory.Instance.Create(provider.ParentModule))
				{
					return Env.Security.FindOrCreateConversationCheckpoint(module.SecurityCheckpoint, module.ID, SecurityCore.ConversationViewAutoGeneratedCode);
				}
			}

			return Env.Security.None;
		}

		protected override IZForm GetForm(IBusiness businessEntity)
		{
			throw new EConversationFeatureNotSupportedException("Cant display a form for the eConversation tab page.");
		}
	}

	[Serializable]
	class EConversationFeatureNotSupportedException : ModuleFeatureNotSupportedException
	{
		public EConversationFeatureNotSupportedException(string message)
			: base(message)
		{ }

#if NETFRAMEWORK
		protected EConversationFeatureNotSupportedException(System.Runtime.Serialization.SerializationInfo info, System.Runtime.Serialization.StreamingContext context)
			: base(info, context)
		{ }
#endif
	}
}

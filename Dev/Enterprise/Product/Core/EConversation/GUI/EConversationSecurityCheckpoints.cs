using Enterprise.Environment;
using Enterprise.Security;
using Enterprise.ZArchitecture.Modules;

namespace Enterprise.EConversation.GUI
{
	public class EConversationSecurityCheckpoints
	{
		public EConversationSecurityCheckpoints(ModuleIdentifier parentModule)
		{
			using (var module = ZModuleFactory.Instance.Create(parentModule))
			{
				View = Env.Security.FindOrCreateConversationCheckpoint(module.SecurityCheckpoint, parentModule, SecurityCore.ConversationViewAutoGeneratedCode);

				EditInternalParticipants = Env.Security.FindOrCreateConversationCheckpoint(module.SecurityCheckpoint, parentModule, SecurityCore.ConversationEditInternalParticipantsAutoGeneratedCode);
				ModifyExternalParticipants = Env.Security.FindOrCreateConversationCheckpoint(module.SecurityCheckpoint, parentModule, SecurityCore.ConversationModifyExternalParticipantsAutoGeneratedCode);

				SendMessages = Env.Security.FindOrCreateConversationCheckpoint(module.SecurityCheckpoint, parentModule, SecurityCore.ConversationSendMessagesAutoGeneratedCode);
			}
		}

		public SecurityCheckpoint EditInternalParticipants { get; }
		public SecurityCheckpoint ModifyExternalParticipants { get; }
		public SecurityCheckpoint SendMessages { get; }
		public SecurityCheckpoint View { get; }
	}
}

using System;
using System.Collections.Generic;
using System.Linq;
using CargoWise.Types;
using ServiceManager.Host.Abstractions;

namespace Enterprise.ServiceManager.Host
{
	internal interface IDispatchingLoopThrottling
	{
		TimeSpan GetTimeToSleep(IEnumerable<IRunnableServiceTask> queueSnapshot, IEnumerable<IRunnableServiceTask> allTasks, bool systemIsRegistered);
	}

	class DispatchingLoopThrottling : IDispatchingLoopThrottling
	{
		readonly ITaskSelector taskSelector;
		protected int loopsAllowedWithoutDeepSleep;
		readonly TimeSpan maxSecondaryBacklogThrottling;
		readonly TimeSpan acceptableBacklogThrottling;
		readonly TimeSpan minimalFriendlyThrottling;
		readonly int allowedBacklog;
		readonly IProcessRunnerPool runnerPool;
		readonly TimeSpan secondaryProcessesSpinUpDelay;

		public DispatchingLoopThrottling(ITaskSelector taskSelector, IProcessRunnerPool runnerPool, TimeSpan secondaryProcessesSpinUpDelay, IHostRegistrySettings hostRegistry)
		{
			this.taskSelector = taskSelector;
			maxSecondaryBacklogThrottling = hostRegistry.ThrottlingPeriodForDispatchingLoopWithBacklogWaitingForMaxSecondary;
			acceptableBacklogThrottling = hostRegistry.ThrottlingPeriodForDispatchingLoopWithAcceptableBacklog;
			minimalFriendlyThrottling = hostRegistry.ThrottlingPeriodForDispatchingLoopWithExceedingBacklog;
			allowedBacklog = acceptableBacklogThrottling > TimeSpan.Zero ? (int)(hostRegistry.ThrottlingTargetTimeToClearQueueBacklog.TotalMilliseconds / acceptableBacklogThrottling.TotalMilliseconds) : 0;
			this.runnerPool = runnerPool;
			this.secondaryProcessesSpinUpDelay = secondaryProcessesSpinUpDelay;
		}

		/// <summary>
		/// This method will make a decision on the time the Dispatching loop is allowed to wait until the next loop.
		/// The waiting time (if registry defaults are taken) will be:
		/// 0. 5 minutes - if the system is unregistered
		/// 1. 30 ms if the backlog exceeds acceptable limits (until we process all items in the backlog) or if the next run is imminent
		/// 2. 100 ms if the backlog is within acceptable limits
		/// 3. 1000 ms if the backlog contains only items that reached their max secondary
		/// 4. until the next task runtime is due
		/// </summary>
		public TimeSpan GetTimeToSleep(IEnumerable<IRunnableServiceTask> queueSnapshot, IEnumerable<IRunnableServiceTask> allTasks, bool systemIsRegistered)
		{
			var timeToSleep = minimalFriendlyThrottling;
			var timeNow = ZDateTimeOffset.UtcNow.ToDateTimeOffset();

			if (!systemIsRegistered)
			{
				return TimeSpan.FromMinutes(5);
			}

			if (loopsAllowedWithoutDeepSleep == 0)
			{
				// if queue is empty - wait until next scheduled task run time
				if (!queueSnapshot.Any())
				{
					var allPotentiallyEligibleTasks = taskSelector.GetTasksPotentiallyEligibleForRunning(allTasks).ToList();
					var nextTask = allPotentiallyEligibleTasks.OrderBy(t => t.NextRunTime).FirstOrDefault();
					if (nextTask != null)
					{
						timeToSleep = nextTask.NextRunTime.HasValue ? nextTask.NextRunTime.Value - timeNow : minimalFriendlyThrottling;
					}
					else
					{
						timeToSleep = TimeSpan.FromMinutes(10);
					}
				}
				// if there are tasks in the queue but only ones that reached max secondary - throttle for (default) 1000 ms
				else if (queueSnapshot.All(t => taskSelector.ReachedMaxSecondary(t)))
				{
					timeToSleep = maxSecondaryBacklogThrottling;
				}
				// in all other cases (tasks in the queue) - wait for (default) 100 ms, if rate and backlog permits
				else if (queueSnapshot.Count() <= allowedBacklog)
				{
					timeToSleep = acceptableBacklogThrottling;
				}
				// if backlog is too big (generated by nudging) - do not deep-throttle until the backlog clears
				else
				{
					loopsAllowedWithoutDeepSleep = queueSnapshot.Count();
				}
			}
			else
			{
				loopsAllowedWithoutDeepSleep--;
				// minimal time to wait while being CPU-friendly, (default) 30 ms
				timeToSleep = minimalFriendlyThrottling;
			}

			if (timeToSleep > secondaryProcessesSpinUpDelay && runnerPool.RunningCount() > 0)
			{
				return secondaryProcessesSpinUpDelay;
			}

			return timeToSleep > minimalFriendlyThrottling ? timeToSleep : minimalFriendlyThrottling;
		}
	}
}


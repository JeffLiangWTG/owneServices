		// Audit Events ADD/EDT/DEL should be done via the Audit Database.
		// They should no longer use StmALog table.
		// This UT is to prevent business objects from creating Audit Events using StmALog table.
		// https://devops.wisetechglobal.com/wtg/CargoWise/_wiki/wikis/CargoWise.wiki/15546/Audit-Events-(ADD-DEL-EDT)-Project

		List<string> GetEnterpriseAssemblies()
#pragma warning disable CS0436 // Type conflicts with imported type
			=> BuildXml.Instance.GetAllTestedAssemblies()
				.Where(a => !IsNotTargetPrefix(a))
				.Where(a => a.ToLower().EndsWith(".dll", StringComparison.OrdinalIgnoreCase))
				.ToList();
#pragma warning restore CS0436 // Type conflicts with imported type

		public static bool IsNotTargetPrefix(string assemblyName)
		{
#pragma warning disable CS0436 // Type conflicts with imported type
			bool isNetCoreTargetFrameworkPrefix = assemblyName.StartsWith(CommonAssemblyInfo.CWNetCoreSubfolder, StringComparison.OrdinalIgnoreCase);
#pragma warning restore CS0436 // Type conflicts with imported type
#if NETFRAMEWORK
			return isNetCoreTargetFrameworkPrefix;
#elif NET
			return !isNetCoreTargetFrameworkPrefix;
#else
#error Unexpected target platform
#endif
		}

		PropertyInfo GetIsAutoLoggedPropertyInfo(Type type)
		{
			while (type != null)
			{
				var isAutoLogged = type.GetProperty("IsAutoLogged", BindingFlags.Instance | BindingFlags.Public);

				if (isAutoLogged != null)
				{
					return isAutoLogged;
				}

				type = type.BaseType;
			}

			return null;
		}

		BusinessObject GenerateNewBizoFromType(Type type)
		{
			if (type.Name.Contains(StorageMainSchema.Constants.TableName))
			{
				var documentFactoryProvider = new DocumentFactoryProvider();
				var documentFactory = documentFactoryProvider.GetFactory(Factory);

				return documentFactory.New(type);
			}
			else if (type.Name.Contains(StorageDocsSchema.Constants.TableName) || type.Name.Contains(nameof(StorageFile)))
			{
				var documentFactoryProvider = new DocumentFactoryProvider();
				var documentFactory = documentFactoryProvider.GetFactory(Factory);
				var numberedFactory = documentFactory.GetFactory(DbNumber);

				return numberedFactory.New(type);
			}
			else if (type == typeof(JobDocsAndCartage))
			{
				return JobDocsAndCartage.New(Factory.New<CommonShipment>());
			}
			else
			{
				return Factory.New(type);
			}
		}

		[SnailTest]
		[FrequentlyFailing]
		public void TestBusinessObjectsDoNotUseStmALogForAuditLogging()
		{
			var autoLogType = typeof(IAutoLog);

			var bizosIsAutoLogged = new List<Type>();
			var bizosUnableToCreate = new Dictionary<Type, string>();

			var enterpiseAssemblies = GetEnterpriseAssemblies();

			foreach (var assemblyName in enterpiseAssemblies)
			{
				var assembly = Assembly.Load(Path.GetFileNameWithoutExtension(assemblyName));

				foreach (var type in assembly.GetTypes())
				{
					if (autoLogType.IsAssignableFrom(type) && !type.IsAbstract && !type.ContainsGenericParameters)
					{
						BusinessObject bizo;

						try
						{
							bizo = GenerateNewBizoFromType(type);
						}
						catch (ZException ex) when (ex.Message.StartsWith("Table") && ex.Message.EndsWith("does not exist.")
						|| ex.Message.StartsWith("The business object") && ex.Message.EndsWith("does not have a Schema.TableName."))
						{
							// Ignore bizos that don't have a corresponding table in the database.
							continue;
						}
						catch (ApplicationException ex) when (ex.Message.Contains("Please check that you have implemented a constructor"))
						{
							// Ignore bizos that don't have either a parameterless constructor, or a constructor like (BusinessObjectFactory Factory, DataRow Row) : base(Factory, Row) {}
							continue;
						}
						catch (ApplicationException ex) when (ex.Message.StartsWith("Can't create a") && ex.Message.Contains("as its constructor threw an exception."))
						{
							// Ignore bizos we can't create due to constructor throwing an exception.
							continue;
						}
						catch (Exception ex)
						{
							bizosUnableToCreate.Add(type, ex.Message);
							continue;
						}

						var propertyInfo = GetIsAutoLoggedPropertyInfo(type);

						if (propertyInfo != null)
						{
							if ((bool)propertyInfo.GetValue(bizo))
							{
								bizosIsAutoLogged.Add(type);
							}
						}
					}
				}
			}

			ErrorReporter.Clear();

			var newBizosIsAutoLogged = bizosIsAutoLogged.Select(b => b.FullName).Except(BizosIsAutoLoggedBaseline).ToList();
			var message1 = "It was detected that you have either updated an existing bizo or generated a new bizo which is trying to add " +
				"audit events (ADD, DEL, EDT) to the StmALog table. These should instead be added to the Audit database. See the following wiki " +
				"for information: https://devops.wisetechglobal.com/wtg/CargoWise/_wiki/wikis/CargoWise.wiki/15546/Audit-Events-(ADD-DEL-EDT)-Project \n";

			var bizosNoLongerIsAutoLogged = BizosIsAutoLoggedBaseline.Except(bizosIsAutoLogged.Select(b => b.FullName)).ToList();
			var message2 = "There are bizo(s) which no longer have IsAutoLogged=true. " +
				"Remove each occurrence from the list 'BizosIsAutoLoggedBaseline' to create the new baseline. \n";

			var commonMessage = "Alternatively, you have refactored a namespace which already has audit events. " +
				"In this case, please update the BizosIsAutoLoggedBaseline accordingly. \n";

			CombineAssertions(() =>
			{
				AssertEquals($"{message1}{commonMessage}", string.Empty, newBizosIsAutoLogged.ToStringWithNewLineBetweenStrings());
				AssertEquals($"{message2}{commonMessage}", string.Empty, bizosNoLongerIsAutoLogged.ToStringWithNewLineBetweenStrings());

				AssertEquals("The following bizos were unable to be created: ", string.Empty, bizosUnableToCreate.Select(b => $"Type={b.Key}, Exception={b.Value}").ToStringWithNewLineBetweenStrings());
			});
		}


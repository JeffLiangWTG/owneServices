using System;
using System.Collections.Generic;
using System.IO;
using System.Reflection;
using CargoWise.BuildTools;
using CargoWise.EntityFramework;
using Enterprise.Services.OperationalActions.Business;
using Enterprise.Services.OperationalActions.Business.Testing;
using Enterprise.ZArchitecture.Core.Testing;
using NUnit.Framework;

namespace Enterprise.Services.OperationalActions.GUI.Testing
{
	sealed class GeneralActionsTestHelper : MarshalByRefObject
	{
		public static GeneralActionsTestHelper New(AppDomain domain)
		{
			if (domain == null)
			{
				throw new ArgumentNullException(nameof(domain));
			}

			Type helperType = typeof(GeneralActionsTestHelper);
#pragma warning disable CW1157 // WI00669071 - Do not use System.AppDomain.
			GeneralActionsTestHelper helper = (GeneralActionsTestHelper)domain.CreateInstanceAndUnwrap(helperType.Assembly.FullName, helperType.FullName);
#pragma warning restore CW1157 // WI00669071 - Do not use System.AppDomain.
			helper.Setup(AppDomainContext.ExtractFromCurrentAppDomain());
			return helper;
		}

		public int AssertionCount
		{
			get { return (int)typeof(AssertionWithHtml).InvokeMember("AssertionCount", BindingFlags.Static | BindingFlags.NonPublic | BindingFlags.GetProperty, null, null, null); }
		}

		public int TestSanityCheck()
		{
			string[] filenames = BuildXml.Instance.GetAllTestedAssemblies();
			string[] assemblies = Array.ConvertAll<string, string>(filenames, Path.GetFileNameWithoutExtension);

			SubClassRetriever retriever = new SubClassRetriever(assemblies, typeof(BusinessObject))
			{
				IncludeAbstractClasses = true,
				IncludeAutoGeneratedCode = true,
				IncludeClientDlls = true,
				IncludeNestedClasses = true,
				IncludeNonAutoGeneratedCode = true,
				IncludePrivateNestedClasses = true,
				IncludeTestClasses = false,
			};

			SortedDictionary<string, IList<string>> result = new SortedDictionary<string, IList<string>>();
			List<string> errors = new List<string>();
			OperationalActionFieldGenerator generator = new OperationalActionFieldGenerator();
			BusinessObjectFactory factory = new BusinessObjectFactory();

			foreach (Type type in retriever.Retrieve())
			{
				foreach (PropertyInfo info in type.GetProperties(BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly))
				{
					if (IsIndexProperty(info))
					{
						continue;
					}

					IOperationalActionFieldSupporterSelfCheck selfCheck;

					try
					{
						selfCheck = generator.CreateField(new PropertyInfo[] { info });
					}
					catch (AmbiguousMatchException ex)
					{
						selfCheck = null;
						errors.Add(ex.ToString());
					}

					if (selfCheck != null)
					{
						selfCheck.PerformSelfCheck(factory, errors);
					}

					if (errors.Count > 0)
					{
						result.Add(type.FullName + "." + info.Name, errors.ToArray());
						errors.Clear();
					}
				}
			}

			Assertion.AssertGroupedErrorList(result);
			return AssertionCount;
		}

		#region Implementation

		static bool IsIndexProperty(PropertyInfo info)
		{
			ParameterInfo[] args = info.GetIndexParameters();
			return args != null && args.Length > 0;
		}

		void Setup(AppDomainContext context)
		{
			context.ApplyToAppDomain();
		}

		#endregion
	}
}

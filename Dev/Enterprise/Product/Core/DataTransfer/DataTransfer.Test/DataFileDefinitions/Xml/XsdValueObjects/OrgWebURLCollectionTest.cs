using Enterprise.DataTransfer.Xml.Testing;
using NUnit.Framework;
using Xsd = Enterprise.DataTransfer.Xml.XsdVersion1;

namespace Enterprise.DataTransfer.Xml.XsdVersion1.Testing
{
	[TestedType(typeof(Xsd.OrgWebURLCollection))]
	sealed class OrgWebURLCollectionTest : ValueObjectCollectionTestCase
	{
		public void TestCompileTimeCheck()
		{
			Xsd.OrgWebURLCollection value = null;
			value = new Xsd.Organisation().OrganisationDetails.OrgWebURLs;
			AssertNotNull("The line above was probably commented out", value);
		}

		public void TestSequenceNotGeneratedIfAlreadyExists()
		{
			Xsd.OrgWebURLCollection collection = new Xsd.OrgWebURLCollection();
			Xsd.OrgWebURL url = new Xsd.OrgWebURL();
			url.Sequence = 99;
			collection.Add(url);
			AssertEquals("Sequence should not be changed if already set", 99, url.Sequence);
		}

		public void TestSequenceAutoGenerated()
		{
			Xsd.OrgWebURLCollection collection = new Xsd.OrgWebURLCollection();
			Xsd.OrgWebURL url1 = collection.AddNew();
			Xsd.OrgWebURL url2 = collection.AddNew();
			AssertEquals("First contact sequence", 1, url1.Sequence);
			AssertEquals("Second contact sequence", 2, url2.Sequence);
		}
	}
}

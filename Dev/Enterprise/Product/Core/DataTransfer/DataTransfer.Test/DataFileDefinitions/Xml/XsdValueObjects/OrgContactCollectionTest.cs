using Enterprise.DataTransfer.Xml.Testing;
using NUnit.Framework;
using Xsd = Enterprise.DataTransfer.Xml.XsdVersion1;

namespace Enterprise.DataTransfer.Xml.XsdVersion1.Testing
{
	[TestedType(typeof(Xsd.OrgContactCollection))]
	sealed class OrgContactCollectionTest : ValueObjectCollectionTestCase
	{
		public void TestCompileTimeCheck()
		{
			Xsd.OrgContactCollection value = null;
			value = new Xsd.Organisation().OrganisationDetails.Contacts;
			AssertNotNull("The line above was probably commented out", value);
		}

		public void TestSequenceNotGeneratedIfAlreadyExists()
		{
			Xsd.OrgContactCollection collection = new Xsd.OrgContactCollection();
			Xsd.OrgContact contact = new Xsd.OrgContact();
			contact.Sequence = 99;
			collection.Add(contact);
			AssertEquals("Sequence should not be changed if already set", 99, contact.Sequence);
		}

		public void TestSequenceAutoGenerated()
		{
			Xsd.OrgContactCollection collection = new Xsd.OrgContactCollection();
			Xsd.OrgContact contact1 = collection.AddNew();
			Xsd.OrgContact contact2 = collection.AddNew();
			AssertEquals("First contact sequence", 1, contact1.Sequence);
			AssertEquals("Second contact sequence", 2, contact2.Sequence);
		}
	}
}

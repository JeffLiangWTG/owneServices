using System.Collections.Generic;
using Enterprise.ZArchitecture.Modules;

namespace Enterprise.Security.Provider
{
	class CustomizeReportSecurityInfoProvider : SecurityInfoProvider
	{
		public CustomizeReportSecurityInfoProvider(SecurityInfoProvider parent, ModuleIdentifier moduleID)
			: base(parent, GetSecurityCheckpoint(parent, moduleID))
		{
		}

		public override string Name
		{
			get { return Checkpoint.DisplayText; }
		}

		public override IEnumerable<SecurityInfoProvider> GetChildren()
		{
			yield break;
		}

		static ISecurityCheckpoint GetSecurityCheckpoint(SecurityInfoProvider parent, ModuleIdentifier moduleId)
		{
			var security = parent.Security;
			var key = new CheckpointLookupKey(moduleId + SecurityCore.CustomizeReportsAutoGeneratedCode);

			return security.FindCheckPoint(key) == null ?
				security.FindOrCreateReportCustomizeCheckpoint(moduleId, parent.Checkpoint) :
				null;
		}
	}
}

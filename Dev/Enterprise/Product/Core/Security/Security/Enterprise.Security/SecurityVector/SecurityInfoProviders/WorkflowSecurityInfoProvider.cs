using System.Collections.Generic;
using System.Linq;

namespace Enterprise.Security.Provider
{
	class WorkflowSecurityInfoProvider : SecurityInfoProvider
	{
		public WorkflowSecurityInfoProvider(SecurityInfoProvider parent)
			: base(parent, GetWorkflowCheckPoint(parent))
		{
			parentSecurityCheckpoint = (SecurityCheckpoint)parent.Checkpoint;
		}

		public override IEnumerable<SecurityInfoProvider> GetChildren()
		{
			yield return new CheckpointSecurityInfoProvider(this, Security.FindOrCreateWorkflowItemCheckpoint(parentSecurityCheckpoint, SecurityCore.WorkflowTasksJustViewAutoGeneratedCode));
			yield return new CheckpointSecurityInfoProvider(this, Security.FindOrCreateWorkflowItemCheckpoint(parentSecurityCheckpoint, SecurityCore.WorkflowMilestonesJustViewAutoGeneratedCode));
			yield return new CheckpointSecurityInfoProvider(this, Security.FindOrCreateWorkflowItemCheckpoint(parentSecurityCheckpoint, SecurityCore.WorkflowExceptionsJustViewAutoGeneratedCode));
			yield return new CheckpointSecurityInfoProvider(this, Security.FindOrCreateWorkflowItemCheckpoint(parentSecurityCheckpoint, SecurityCore.WorkflowTriggersJustViewAutoGeneratedCode));
			yield return new CheckpointSecurityInfoProvider(this, Security.FindOrCreateWorkflowItemCheckpoint(parentSecurityCheckpoint, SecurityCore.WorkflowEventsJustViewAutoGeneratedCode));

			yield return new WorkflowEditSecurityInfoProvider(
				this,
				Security.FindOrCreateWorkflowItemCheckpoint(parentSecurityCheckpoint, SecurityCore.WorkflowTasksAutoGeneratedCode),
				SecurityCore.WorkflowAddTasksAutoGeneratedCode,
				SecurityCore.WorkflowDeleteTasksAutoGeneratedCode);
			yield return new WorkflowEditSecurityInfoProvider(
				this,
				Security.FindOrCreateWorkflowItemCheckpoint(parentSecurityCheckpoint, SecurityCore.WorkflowMilestonesAutoGeneratedCode),
				SecurityCore.WorkflowAddMilestonesAutoGeneratedCode,
				SecurityCore.WorkflowDeleteMilestonesAutoGeneratedCode);
			yield return new WorkflowEditSecurityInfoProvider(
				this,
				Security.FindOrCreateWorkflowItemCheckpoint(parentSecurityCheckpoint, SecurityCore.WorkflowExceptionsAutoGeneratedCode),
				SecurityCore.WorkflowAddExceptionsAutoGeneratedCode,
				SecurityCore.WorkflowDeleteExceptionsAutoGeneratedCode,
				SecurityCore.WorkflowOverrideExceptionDurationAutoGeneratedCode);
			yield return new WorkflowEditSecurityInfoProvider(
				this,
				Security.FindOrCreateWorkflowItemCheckpoint(parentSecurityCheckpoint, SecurityCore.WorkflowTriggersAutoGeneratedCode),
				SecurityCore.WorkflowAddTriggersAutoGeneratedCode,
				SecurityCore.WorkflowDeleteTriggersAutoGeneratedCode);
			yield return new WorkflowEditSecurityInfoProvider(
				this,
				Security.FindOrCreateWorkflowItemCheckpoint(parentSecurityCheckpoint, SecurityCore.WorkflowEventsAutoGeneratedCode),
				SecurityCore.WorkflowAddEventsAutoGeneratedCode,
				SecurityCore.WorkflowCancelEventsAutoGeneratedCode);
		}

		public override string Name => Checkpoint.DisplayText;

		static SecurityCheckpoint GetWorkflowCheckPoint(SecurityInfoProvider parent)
		{
			SecurityCheckpoint securityCheckpoint = (SecurityCheckpoint)parent.Checkpoint;
			if (securityCheckpoint.FindChild(securityCheckpoint.Code + SecurityCore.WorkflowAutoGeneratedCode) == null)
			{
				return parent.Security.FindOrCreateWorkflowCheckpoint(securityCheckpoint);
			}
			else
			{
				return null;
			}
		}

		readonly SecurityCheckpoint parentSecurityCheckpoint;

		class WorkflowEditSecurityInfoProvider : CheckpointSecurityInfoProvider
		{
			public WorkflowEditSecurityInfoProvider(SecurityInfoProvider parent, SecurityCheckpoint checkpoint, params string[] childrenWorkflowItemCheckpointCodes)
				: base(parent, checkpoint)
			{
				this.childrenWorkflowItemCheckpointCodes = childrenWorkflowItemCheckpointCodes;
			}

			public override IEnumerable<SecurityInfoProvider> GetChildren()
			{
				return childrenWorkflowItemCheckpointCodes
					.Select(childrenWorkflowItemCheckpointCode => new CheckpointSecurityInfoProvider(this, Security.FindOrCreateWorkflowSubItemCheckpoint((SecurityCheckpoint)Checkpoint, childrenWorkflowItemCheckpointCode)));
			}

			readonly string[] childrenWorkflowItemCheckpointCodes;
		}
	}
}

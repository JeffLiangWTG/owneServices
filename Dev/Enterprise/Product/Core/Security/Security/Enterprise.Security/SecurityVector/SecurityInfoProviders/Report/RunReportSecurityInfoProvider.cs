using System.Collections.Generic;
using System.Linq;
using Enterprise.MasterFiles.Business;
using Enterprise.ZArchitecture.Core;
using Enterprise.ZArchitecture.Modules;
using Enterprise.ZArchitecture.Schema;

namespace Enterprise.Security.Provider
{
	class RunReportSecurityInfoProvider : SecurityInfoProvider
	{
		readonly ModuleIdentifier moduleID;

		public RunReportSecurityInfoProvider(SecurityInfoProvider parent, ModuleIdentifier moduleID)
			: base(parent, GetSecurityCheckpoint(parent, moduleID))
		{
			this.moduleID = moduleID;
		}

		public override string Name
		{
			get { return Checkpoint.DisplayText; }
		}

		public override IEnumerable<SecurityInfoProvider> GetChildren()
		{
			return Checkpoint != null ?
				GetReportItems().Select(menuItem => new ReportSecurityInfoProvider(this, menuItem)) :
				Enumerable.Empty<SecurityInfoProvider>();
		}

		IEnumerable<StmMenuItem> GetReportItems()
		{
			var reports = new List<StmMenuItem>();

			var filter = new DocumentZQuery(Enterprise.Core.Constants.BusinessContextPrefixes.Reports + moduleID);
			filter.AddToFilter(StmMenuItemSchema.SU_IsPublished, true);
			var groupedReports = Factory.Load<StmMenuItem>(filter).GroupBy(x => x.SU_MenuName);
			foreach (var groupReport in groupedReports)
			{
				if (groupReport.Count() > 1)
				{
					foreach (var item in groupReport)
					{
						string menuNameWithFilter = item.SU_MenuName + (NoResString)" (Filter: " + item.SU_FilterList + (NoResString)")";
						if (menuNameWithFilter.Length > StmMenuItemSchema.SU_MenuName.MaxLength)
						{
							item.SU_MenuName = menuNameWithFilter.Substring(0, StmMenuItemSchema.SU_MenuName.MaxLength - 3) + "...";
						}
						else
						{
							item.SU_MenuName = menuNameWithFilter;
						}
						reports.Add(item);
					}
				}
				else
				{
					reports.AddRange(groupReport);
				}
			}

			return reports;
		}

		static ISecurityCheckpoint GetSecurityCheckpoint(SecurityInfoProvider parent, ModuleIdentifier moduleId)
		{
			var key = new CheckpointLookupKey(moduleId + SecurityCore.RunReportsAutoGeneratedCode);
			return parent.Security.FindCheckPoint(key) == null ?
				parent.Security.FindOrCreateReportRunCheckpoint(moduleId, parent.Checkpoint) :
				null;
		}
	}
}

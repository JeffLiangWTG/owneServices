using System;
using System.Collections.Generic;
using System.Linq;
using CargoWise.Application;
using CargoWise.Definitions;
using CargoWise.EntityFramework;
using Enterprise.Core.Modules;
using Enterprise.Integration;
using Enterprise.MasterFiles.Business;
using Enterprise.ZArchitecture;
using Enterprise.ZArchitecture.Schema;
using Constants = Enterprise.Core.Constants;

namespace Enterprise.Security.Provider
{
	class ModuleSecurityInfoProvider : SecurityInfoProvider
	{
		public ModuleSecurityInfoProvider(SecurityInfoProvider parent, INamedModule module)
			: base(parent, GetSecurityCheckpoint(parent.Security, module.SecurityCheckpoint))
		{
			this.module = module;
		}

		public override IEnumerable<SecurityInfoProvider> GetChildren()
		{
			if (Checkpoint != null)
			{
				using (var loadedModule = GetZModule())
				{
					var gridModule = loadedModule as IZFilterGridModule;
					gridModule?.AddInterfaceConnectorMenuItems();
					if (gridModule != null)
					{ gridModule.DoNotCheckOrSaveChanges = true; }

					//to make Module Access checkpoint appear before all other child checkpoints, we have to always create/return it now, then exclude it from the below iteration
					yield return new CheckpointSecurityInfoProvider(this, Security.FindOrCreateAccessModuleCheckPoint((SecurityCheckpoint)Checkpoint));

					if (Checkpoint.ChildCheckPoints != null)
					{
						foreach (SecurityCheckpoint checkpoint in Checkpoint.ChildCheckPoints.Where(x => x.Code != Checkpoint.Code + SecurityCore.AccessModuleAutoGeneratedCode))
						{
							if (!Security.HasBeenSecurityVectorInitialized && gridModule != null)
							{
								LoadAllChildCheckPointsForSpecifiedCheckpointType(checkpoint, gridModule);
							}

							yield return new CheckpointSecurityInfoProvider(this, checkpoint);
						}
					}

					if (!Security.HasBeenSecurityVectorInitialized)
					{
						if (Checkpoint is ReportsSecurityCheckpoint || Checkpoint.Code == "SystemReports")
						{
							yield return new CustomizeReportSecurityInfoProvider(this, module.ModuleID);
							yield return new RunReportSecurityInfoProvider(this, module.ModuleID);
						}

						var businessContexts = loadedModule.BusinessContexts;
						if ((businessContexts != null) && (businessContexts.Length > 0))
						{
							var docMenuItems = GetDocumentMenuItems(businessContexts);
							if (docMenuItems.Count > 0)
							{
								yield return new DocumentsSecurityInfoProvider(this, module, docMenuItems);
							}

							var formMenuItems = GetFormMenuItems(businessContexts);
							if (formMenuItems.Count > 0)
							{
								yield return new VisualizerFormsSecurityInfoProvider(this, module, formMenuItems);
							}
						}

						if (loadedModule.SupportsWorkflow)
						{
							yield return new WorkflowSecurityInfoProvider(this);
						}

						if (loadedModule.SupportsConversations)
						{
							yield return new CheckpointSecurityInfoProvider(this, Security.FindOrCreateConversationCheckpoint(Checkpoint, loadedModule.ModuleID));
						}

						if (gridModule != null)
						{
							if (gridModule.HasExportMenuItems && Checkpoint.FindChild(Checkpoint.Code + SecurityCore.ExportToExcelAutoGeneratedCode) == null)
							{
								yield return new CheckpointSecurityInfoProvider(this, Security.FindOrCreateExportCheckPoint((SecurityCheckpoint)Checkpoint));
							}

							if (Checkpoint.FindChild(Checkpoint.Code + SecurityCore.ImportToSystemAutoGeneratedCode) == null && gridModule.HasImportMenuItems)
							{
								yield return new CheckpointSecurityInfoProvider(this, Security.FindOrCreateImportCheckPoint((SecurityCheckpoint)Checkpoint));
							}

							if (gridModule.HasExportNativeXmlMenuItem && Checkpoint.FindChild(Checkpoint.Code + SecurityCore.ExportNativeXMLAutoGeneratedCode) == null)
							{
								yield return new CheckpointSecurityInfoProvider(this, Security.FindOrCreateExportNativeXMLCheckPoint((SecurityCheckpoint)Checkpoint));
							}

							if (gridModule.HasImportNativeXmlMenuItem && Checkpoint.FindChild(Checkpoint.Code + SecurityCore.ImportNativeXMLAutoGeneratedCode) == null)
							{
								yield return new CheckpointSecurityInfoProvider(this, Security.FindOrCreateImportNativeXMLCheckPoint((SecurityCheckpoint)Checkpoint));
							}

							if (ObjectFactory.New<IModuleOperationalActionsHelper>().SupportsOperationalActions(gridModule) && !IsSpecifiedCheckpointTypeLoaded(Checkpoint.Code + SecurityCore.Captions.OperationalActionsAutoGeneratedCode))
							{
								yield return new OperationalActionsSecurityInfoProvider(this, Security.FindOrCreateOperationalActionsCheckpoint((SecurityCheckpoint)Checkpoint), gridModule);
							}

							if (gridModule.AllowAddCopyMenuItem && Checkpoint.FindChild(Checkpoint.Code + SecurityCore.UseCopyFunctionAutoGeneratedCode) == null)
							{
								yield return new CheckpointSecurityInfoProvider(this, Security.FindOrCreateCopyCheckpoint((SecurityCheckpoint)Checkpoint));
							}

							if (loadedModule.AllowNew && loadedModule.CouldAllowUniversalCopy && !IsSpecifiedCheckpointTypeLoaded(Checkpoint.Code + SecurityCore.UniversalCopyAutoGeneratedCode))
							{
								yield return new UniversalCopySecurityInfoProvider(this, Security.FindOrCreateUniversalCopyCheckpoint((SecurityCheckpoint)Checkpoint));
							}

							if (gridModule.AllowTemplateRecords && !IsSpecifiedCheckpointTypeLoaded(Checkpoint.Code + SecurityCore.TemplateRecordAutoGeneratedCode))
							{
								yield return new TemplateRecordSecurityInfoProvider(this, Security.FindOrCreateTemplateRecordCheckpoint((SecurityCheckpoint)Checkpoint));
							}

							if (gridModule.AllowTemplateRecords && !IsSpecifiedCheckpointTypeLoaded(Checkpoint.Code + SecurityCore.ISACHKAutoGeneratedCode))
							{
								yield return new ISACHKSecurityInfoProvider(this, Security.FindOrCreateISACHKCheckpoint((SecurityCheckpoint)Checkpoint));
							}

							if (gridModule.AllowSendEmailAction && Checkpoint.FindChild(Checkpoint.Code + SecurityCore.SendEmailAutoGeneratedCode) == null)
							{
								yield return new CheckpointSecurityInfoProvider(this, Security.FindOrCreateSendEmailCheckpoint((SecurityCheckpoint)Checkpoint));
							}
						}
					}
				}
			}
		}

		bool IsSpecifiedCheckpointTypeLoaded(string checkpointCode)
		{
			return CodeToLoadChildCheckPointsAction.TryGetValue(checkpointCode, out var tuple) && tuple.Item1;
		}

		void LoadAllChildCheckPointsForSpecifiedCheckpointType(SecurityCheckpoint checkpoint, IZFilterGridModule gridModule)
		{
			if (CodeToLoadChildCheckPointsAction.TryGetValue(checkpoint.Code, out var tuple))
			{
				tuple.Item1 = true;
				tuple.Item2.Invoke(checkpoint, gridModule);
				CodeToLoadChildCheckPointsAction[checkpoint.Code] = tuple;
			}
		}

		Dictionary<string, (bool, Action<SecurityCheckpoint, IZFilterGridModule>)> CodeToLoadChildCheckPointsAction
		{
			get
			{
				if (codeToLoadChildCheckPointsAction == null)
				{
					codeToLoadChildCheckPointsAction = new Dictionary<string, (bool, Action<SecurityCheckpoint, IZFilterGridModule>)>
					{
						{
							Checkpoint.Code + SecurityCore.Captions.OperationalActionsAutoGeneratedCode, (false, (checkpoint, gridModule) =>
							{
								if (ObjectFactory.New<IModuleOperationalActionsHelper>().SupportsOperationalActions(gridModule))
								{
									 new OperationalActionsSecurityInfoProvider(this, checkpoint, gridModule).GetChildren().Count();
								}
							})
						},
						{
							Checkpoint.Code + SecurityCore.UniversalCopyAutoGeneratedCode, (false, (checkpoint, gridModule) =>
							{
								if (gridModule is IZModule { AllowNew: true, CouldAllowUniversalCopy: true })
								{
									 new UniversalCopySecurityInfoProvider(this, checkpoint).GetChildren().Count();
								}
							})
						},
						{
							Checkpoint.Code + SecurityCore.TemplateRecordAutoGeneratedCode, (false, (checkpoint, gridModule) =>
							{
								if (gridModule.AllowTemplateRecords)
								{
									 new TemplateRecordSecurityInfoProvider(this, checkpoint).GetChildren().Count();
								}
							})
						},
						{
							Checkpoint.Code + SecurityCore.ISACHKAutoGeneratedCode, (false, (checkpoint, gridModule) =>
							{
								if (gridModule.AllowTemplateRecords)
								{
									 new ISACHKSecurityInfoProvider(this, checkpoint).GetChildren().Count();
								}
							})
						}
					};
				}

				return codeToLoadChildCheckPointsAction;
			}
		}

		Dictionary<string, (bool, Action<SecurityCheckpoint, IZFilterGridModule>)> codeToLoadChildCheckPointsAction;

		public override string Name { get { return module.Description; } }

		StmMenuItemsForSecurity GetDocumentMenuItems(BusinessContext[] businessContexts)
		{
			var filter = LoadDocumentMenuItemsQuery(businessContexts);

			var array = Factory.Load<StmMenuItem>(filter);
			return new StmMenuItemsForSecurity(array);
		}

		StmMenuItemsForSecurity GetFormMenuItems(BusinessContext[] businessContexts)
		{
			var filter = LoadFormMenuItemsQuery(businessContexts);

			var array = Factory.Load<StmMenuItem>(filter);
			return new StmMenuItemsForSecurity(array);
		}

		DocumentZQuery LoadDocumentMenuItemsQuery(BusinessContext[] businessContexts)
		{
			var filter = new DocumentZQuery(StmMenuItemSchema.SU_BusinessContext, businessContexts);
			filter.AddToFilter(StmMenuItemSchema.SU_IsPublished, true);
			filter.OrderBy = StmMenuItemSchema.Constants.SU_MenuName;

			return filter;
		}

		ZQuery LoadFormMenuItemsQuery(BusinessContext[] businessContexts)
		{
			var filter = new ZQuery(StmMenuItemSchema.SU_BusinessContext, businessContexts);
			filter.AddToFilter(StmMenuItemSchema.SU_MenuType, Constants.StmMenuItemTypes.Forms);
			filter.AddToFilter(StmMenuItemSchema.SU_IsPublished, true);
			filter.OrderBy = StmMenuItemSchema.Constants.SU_MenuName;

			return filter;
		}

		public override void FetchForGetChildren()
		{
			using (var loadedModule = GetZModule())
			{
				var businessContexts = loadedModule.BusinessContexts;
				if ((businessContexts != null) && (businessContexts.Length > 0))
				{
					var documentQuery = LoadDocumentMenuItemsQuery(businessContexts);
					Factory.AddFetchHint(StmMenuItemSchema.Instance, documentQuery);

					var formQuery = LoadFormMenuItemsQuery(businessContexts);
					Factory.AddFetchHint(StmMenuItemSchema.Instance, formQuery);
				}
			}
		}

		IZModule GetZModule()
		{
			var moduleFactory = ObjectFactory.Get<IModuleFactory>();
			var id = moduleFactory.GetRegisteredIdentifierByName(module.ID);
			if (id != null)
			{
				return moduleFactory.Create(id);
			}
			else
			{
				return null;
			}
		}

		readonly INamedModule module;
	}
}

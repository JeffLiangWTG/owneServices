using System;
using System.Linq;
using CargoWise.Application;
using CargoWise.EntityFramework.Testing;
using Enterprise.MasterFiles.Business;
using Enterprise.ZArchitecture;
using Enterprise.ZArchitecture.Core;
using Enterprise.ZArchitecture.Modules;

namespace Enterprise.Security.Provider.Testing
{
	class TestRunReportSecurityInfoProvider : TestCaseWithFactory
	{
		public void TestName()
		{
			using (var module = ObjectFactory.Get<IModuleFactory>().Create(ModuleIDs.SystemReports))
			{
				var security = new SecurityCore(new GlbSecurityCollection(Factory), Factory.New<GlbStaff>(), Guid.Empty, Guid.Empty, Guid.Empty);
				var item = new RunReportSecurityInfoProvider(new RootSecurityInfoProvider(security), module.ModuleID);
				Assert("Name should be filled", !string.IsNullOrEmpty(item.Name));
			}
		}

		public void TestGetSecurityCheckpointAlignsWithTheSecurityCode()
		{
			var security = new SecurityCore(new GlbSecurityCollection(Factory), Factory.New<GlbStaff>(), Guid.Empty, Guid.Empty, Guid.Empty);

			var moduleId = ModuleIDs.SystemReports;
			var someParent = new SecurityCheckpoint("TestGetSecurityCheckpointAlignsWithTheSecurityCode", (NoResString)"Some text", null, security);
			var retrievedCode = security.FindOrCreateReportRunCheckpoint(moduleId, someParent).Code;

			var expectedValue = moduleId + SecurityCore.RunReportsAutoGeneratedCode;
			AssertEquals("In order to get the checkpoint correctly, the code generated needs to match the code generated in GetSecurityCheckpoint", expectedValue, retrievedCode);
		}

		public void TestReports()
		{
			var security = new SecurityCore(new GlbSecurityCollection(Factory), Factory.New<GlbStaff>(), Guid.Empty, Guid.Empty, Guid.Empty);
			using (var systemReports = ObjectFactory.Get<IModuleFactory>().Create(ModuleIDs.SystemReports))
			{
				var runReports = new RunReportSecurityInfoProvider(new RootSecurityInfoProvider(security), systemReports.ModuleID);

				foreach (var info in runReports.GetChildren())
				{
					if (info.Checkpoint.Code == "Report")
					{
						var itemGuid = info.Checkpoint.ItemGuid;
						AssertNotNull("Report checkpoint should be created.", security.FindCheckPoint(new CheckpointLookupKey("Report", itemGuid)));

						var menuItem = Factory.Load<StmMenuItem>(itemGuid);
						AssertEquals(menuItem.SU_MenuName, info.Name);
					}
				}
			}
		}

		public void TestCustFilesReports()
		{
			var context = Enterprise.Core.Constants.BusinessContextPrefixes.Reports + ModuleIDs.CustFilesReports;
			var report1 = Factory.NewWithValidTestData<StmMenuItem>();
			report1.SU_MenuType = "DOC";
			report1.SU_BusinessContext = context;
			report1.SU_IsPublished = true;
			report1.SU_MenuName = "TestReport1";
			report1.SU_FilterList = "BKRCTY=AU";

			var report2 = Factory.NewWithValidTestData<StmMenuItem>();
			report2.SU_MenuType = "DOC";
			report2.SU_BusinessContext = context;
			report2.SU_IsPublished = true;
			report2.SU_MenuName = "TestReport1";
			report2.SU_FilterList = "BKRCTY=CN";

			var report3 = Factory.NewWithValidTestData<StmMenuItem>();
			report3.SU_MenuType = "DOC";
			report3.SU_BusinessContext = context;
			report3.SU_IsPublished = true;
			report3.SU_MenuName = "TestReport1";
			report3.SU_FilterList = "BKRCTY=US && BKRCTY=CA && BKRCTY=US && BKRCTY=AU && BKRCTY=CN && BKRCTY=CN && BKRCTY=CN && BKRCTY=CN && BKRCTY=CN";

			var report4 = Factory.NewWithValidTestData<StmMenuItem>();
			report4.SU_MenuType = "DOC";
			report4.SU_BusinessContext = context;
			report4.SU_IsPublished = true;
			report4.SU_MenuName = "TestReport4";
			report4.SU_FilterList = "BKRCTY=CN";
			Factory.Save();

			var security = new SecurityCore(new GlbSecurityCollection(Factory), Factory.New<GlbStaff>(), Guid.Empty, Guid.Empty, Guid.Empty);
			using (var custFilesReports = ObjectFactory.Get<IModuleFactory>().Create(ModuleIDs.CustFilesReports))
			{
				var runReports = new RunReportSecurityInfoProvider(new RootSecurityInfoProvider(security), custFilesReports.ModuleID);
				var reports = runReports.GetChildren().Where(x => x.Name.Contains("TestReport")).OrderBy(x => x.Name).ToList();
				AssertEquals(reports.Count, 4);
				AssertEquals("TestReport1 (Filter: BKRCTY=AU)", reports[0].Name);
				AssertEquals("TestReport1 (Filter: BKRCTY=CN)", reports[1].Name);
				AssertContains("...", reports[2].Name);
				AssertEquals("TestReport4", reports[3].Name);
			}
		}
	}
}

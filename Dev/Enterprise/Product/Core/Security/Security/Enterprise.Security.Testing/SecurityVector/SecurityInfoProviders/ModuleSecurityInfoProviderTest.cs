		[DeveloperOnlyTest]
		public void TestConversations()
		{
			var security = new SecurityCore(new GlbSecurityCollection(Factory), Factory.New<GlbStaff>(), Guid.Empty, Guid.Empty, Guid.Empty);

			using (var dialogDefaultModule = ObjectFactory.Get<IModuleFactory>().Create(ModuleIDs.DialogDefault))
			{
				Assert("Precondition: Staff module should not support conversations.", !dialogDefaultModule.SupportsConversations);
				ModuleSecurityInfoProvider provider = new ModuleSecurityInfoProvider(new RootSecurityInfoProvider(security), dialogDefaultModule);

				AssertNull("Node should not exist - we dont support it", GetNode(provider, SecurityCore.ConversationAutoGeneratedDisplayText));
			}

			using (var shipmentModule = ObjectFactory.Get<IModuleFactory>().Create(ModuleIDs.JobShipment))
			{
				Assert("Precondition: JobConsol module should support workflow - will be implemented soon.", shipmentModule.SupportsConversations);
				ModuleSecurityInfoProvider provider = new ModuleSecurityInfoProvider(new RootSecurityInfoProvider(security), shipmentModule);

				var convoNode = provider.GetChildren().Single(node => node.Name == SecurityCore.ConversationAutoGeneratedCode);

				AssertHasPath(provider, SecurityCore.ConversationAutoGeneratedDisplayText);
				AssertHasPath(provider, SecurityCore.ConversationAutoGeneratedDisplayText, SecurityCore.ConversationEditInternalParticipantsAutoGeneratedDisplayText);
				AssertHasPath(provider, SecurityCore.ConversationAutoGeneratedDisplayText, SecurityCore.ConversationModifyExternalParticipantsAutoGeneratedDisplayText);
				AssertHasPath(provider, SecurityCore.ConversationAutoGeneratedDisplayText, SecurityCore.ConversationViewAutoGeneratedCode);
			}
		}

		void AssertHasPath(SecurityInfoProvider root, params string[] path)
		{
			AssertNotNull("root > " + string.Join(" > ", path), GetNode(root, path));
		}

		SecurityInfoProvider GetNode(SecurityInfoProvider root, params string[] path)
		{
			foreach (var childName in path)
			{
				root = root.GetChildren().FirstOrDefault(child => child.Name == childName);

				if (root == null)
				{
					return null;
				}
			}

			return root;
		}


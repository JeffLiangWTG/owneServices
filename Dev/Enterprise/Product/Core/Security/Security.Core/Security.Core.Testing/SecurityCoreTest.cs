		public void TestSecurityCheckPointDefaultsGuiDisplayTextByHierarchy()
		{
			var env = EnvProxy.Instance;
			var security = new SecurityForTest(null, env.CurrentUser.PK, env.CurrentBranch.PK, env.CurrentDepartment.PK, env.CurrentCompany.PK);

			var sections = typeof(ModuleTreeLoaderConstant.Section)
				.GetProperties(BindingFlags.Public | BindingFlags.Static | BindingFlags.DeclaredOnly)
				.Select(prop => ((ModuleTreeLoaderConstant.Entry)prop.GetValue(null)))
				.Select(entry => new ModuleNodeBase(entry.Name, entry.DisplayText, null).DisplayTextWithoutAmpersand)
				.ToArray();

			var modules = ModuleIDs.AllExcludingClientModules.Select(m => m.Description.ToString()).ToArray();

			var checkpointsToSkip = GetCheckPointsToSkip();

			AssertDisplayTextMatchesGui("Operations", security, sections, modules, checkpointsToSkip);

			AssertDisplayTextMatchesGui("Manage", security, sections, modules, checkpointsToSkip);

			AssertDisplayTextMatchesGui("Config", security, sections, modules, checkpointsToSkip);
		}

		void AssertDisplayTextMatchesGui(string categoryCode, SecurityCore security, string[] sections, string[] modules, string[] checkpointsToSkip)
		{
			var categoryCheckpoint = security.FindCheckPoint(categoryCode);
			AssertNotNull("Pre-condition", categoryCheckpoint);

			var invalidCheckPoints = new List<ISecurityCheckpoint>();
			foreach (var sectionCheckPoint in categoryCheckpoint.ChildCheckPoints)
			{
				if (!checkpointsToSkip.Contains(sectionCheckPoint.Code))
				{
					if (!sections.Contains(sectionCheckPoint.DisplayText))
					{
						invalidCheckPoints.Add(sectionCheckPoint);
					}

					foreach (var moduleCheckPoint in sectionCheckPoint.ChildCheckPoints)
					{
						if (!checkpointsToSkip.Contains(moduleCheckPoint.Code) && !modules.Contains(moduleCheckPoint.DisplayText))
						{
							invalidCheckPoints.Add(moduleCheckPoint);
						}
					}
				}
			}

			if (invalidCheckPoints.Any())
			{
				var message = new ZStringBuilder();
				message.AppendLine("The display text doesn't match any value from ZArchitecture.Modules Sections or Modules IDs");
				foreach (var checkPoint in invalidCheckPoints)
				{
					message.Append("Checkpoint Code: ");
					message.AppendLine(checkPoint.Code);
					message.Append("Display Text: ");
					message.AppendLine(checkPoint.DisplayText);
					message.AppendLine();
				}
				message.AppendLine("Add the code to GetCheckPointsToSkip if the Module/Section does not appear on the GUI of CW1");

				Fail(message.ToString());
			}
		}


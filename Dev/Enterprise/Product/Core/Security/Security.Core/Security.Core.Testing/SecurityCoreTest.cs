		#region TestSecurityCheckpointDefinition

		public void TestSecurityCheckpointDefinition()
		{
			Dictionary<string, string> uniqueTable = new Dictionary<string, string>();
			FieldInfo[] fieldInfos = typeof(SecurityCore).GetFields();

			List<string> checkpointsNotInstantiated = new List<string>();
			List<string> checkpointsCodeOverMaxLength = new List<string>();
			List<string> checkpointsNotUnique = new List<string>();

			Assert("PRE: Fields should have been successfully reflected out of Security class", fieldInfos.Length > 0);
			foreach (FieldInfo info in fieldInfos)
			{
				var targetType = info.FieldType;
				var baseType = typeof(SecurityCheckpoint);
				if (targetType.IsSubclassOf(baseType) || targetType == baseType)
				{
					SecurityCheckpoint checkPoint = (SecurityCheckpoint)info.GetValue(EnvProxy.Instance.Security);
					if (checkPoint == null)
					{
						checkpointsNotInstantiated.Add(info.Name);
					}
					else
					{
						if (checkPoint.Code.Length > GlbSecuritySchema.GU_SecurityRight.MaxLength)
						{
							checkpointsCodeOverMaxLength.Add(checkPoint.Code);
						}

						if (uniqueTable.ContainsKey(checkPoint.Code))
						{
							checkpointsNotUnique.Add(checkPoint.Code);
						}
						else
						{
							uniqueTable.Add(checkPoint.Code, checkPoint.Code);
						}
					}
				}
			}

			checkpointsNotInstantiated.Sort();
			checkpointsCodeOverMaxLength.Sort();
			checkpointsNotUnique.Sort();

			string message = "";
			if (checkpointsNotInstantiated.Count > 0)
			{
				message += string.Format("The following checkpoints were defined in Security.cs BUT were never instantiated - please check that they are still in use, and remove them if they are unnecessary:\r\n{0}\r\n\r\n", string.Join("\r\n", checkpointsNotInstantiated.ToArray()));
			}

			if (checkpointsCodeOverMaxLength.Count > 0)
			{
				message += string.Format("The following checkpoints have a code greater than GU_SecurityRight.MaxLength:\r\n{0}\r\n\r\n", string.Join("\r\n", checkpointsCodeOverMaxLength.ToArray()));
			}

			if (checkpointsNotUnique.Count > 0)
			{
				message += string.Format("The following checkpoints have duplicate codes defined :\r\n{0}\r\n\r\n", string.Join("\r\n", checkpointsNotUnique.ToArray()));
			}

			if (!string.IsNullOrEmpty(message))
			{
				Fail(message);
			}
		}


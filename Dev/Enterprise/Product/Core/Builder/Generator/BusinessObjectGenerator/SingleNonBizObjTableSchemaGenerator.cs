using System;

namespace Enterprise.Builder.Generator
{
	public class SingleNonBizObjTableSchemaGenerator : SingleBizObjGenerator
	{
		public SingleNonBizObjTableSchemaGenerator(string dbName, string subFolderName, string nonBusinessObjectTableName, GeneratorOutputDirectory outputDirectory)
			: base("Auto" + nonBusinessObjectTableName + ".cs", outputDirectory)
		{
			this.actualDbName = dbName;
			this.subFolderName = subFolderName;
			fFullTableName = FormattableString.Invariant($"{dbName}.{SqlSchemaName}.{nonBusinessObjectTableName}");
		}

		protected override string SubFolderNameForSchemaClasses
		{
			get { return subFolderName; }
		}
		readonly string subFolderName;

		protected override string ActualDatabaseNameDuringRegen
		{
			get { return actualDbName; }
		}
		readonly string actualDbName;

		public override string[] ListOfFilesToBeGenerated
		{
			get
			{
				return new string[]
			{
			  "No Business Object file is generated by the SchemaOnlySingleBizObjGeneratorFromTable.",
			  FileNameOfBusinessObjectSchema,
			  "No Validation file is generated by the SchemaOnlySingleBizObjGeneratorFromTable.",
			  "No Concrete Validation file is generated by the SchemaOnlySingleBizObjGeneratorFromTable.",
			  "No Auto Lookups file is generated by the SchemaOnlySingleBizObjGeneratorFromTable.",
			  "No Concrete Lookups file is generated by the SchemaOnlySingleBizObjGeneratorFromTable."
			};
			}
		}

		protected override string FullTableName
		{
			get { return fFullTableName; }
		}

		readonly string fFullTableName;

		protected override bool IsRegenRequiredForBizObj()
		{
			return false;
		}

		protected override bool IsRegenRequiredForBizObjValidation()
		{
			return false;
		}

		protected override bool IsRegenRequiredForLookups()
		{
			return false;
		}

		protected override bool IsRegenRequiredForLookupsConcreteClass()
		{
			return false;
		}

		protected override bool IsRegenRequiredForValidationConcreteClass()
		{
			return false;
		}
	}
}

using CargoWise.Common;

namespace Enterprise.Builder.Generator
{
	public class AutoGeneratedFile
	{
		public AutoGeneratedFile(string fileName)
		{
			Argument.NotNullOrEmpty(fileName, nameof(fileName));
			this.FileName = fileName;
		}

		readonly string FileName;

		public void Save(GeneratorOutputDirectory outputDirectory, string fileContents)
		{
			Argument.NotNull(outputDirectory, nameof(outputDirectory)); // Suggested By ReviewBot 
			Argument.NotNull(fileContents, nameof(fileContents));
			var nl = System.Environment.NewLine;
			string autoGeneratedHeader =
				"//------------------------------------------------------------------------------" + nl +
				"// <autogenerated>" + nl +
				"//     This code is auto-generated." + nl +
				"//     Manual changes to this file will be lost when it is regenerated." + nl +
				"// </autogenerated>" + nl +
				"//------------------------------------------------------------------------------" + nl + nl;

			fileContents = autoGeneratedHeader + fileContents;

			outputDirectory.WriteToFile(FileName, fileContents);
		}
	}
}

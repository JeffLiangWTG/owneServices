using System;
using System.Data;
using System.IO;
using System.Text;

namespace Enterprise.Builder.Generator
{
	public sealed class EventGenerator
	{
		public EventGenerator(GeneratorOutputDirectory outputDirectory)
		{
			this.outputDirectory = outputDirectory;
		}

		readonly GeneratorOutputDirectory outputDirectory;

		public void GenerateStmEventConstants()
		{
			StartTask("Generating StmEvent Types");
			DataRow[] stmEventRows = GetStmEventRows();
			GenerateStmEventTypes(stmEventRows);
		}

		#region Generate Events

		internal string StmEventsFilePath = @"Enterprise\Architecture\Business\ZArchitecture.Business\Business\StmALog\AutoEvents.cs";

		string StmEventsWinPath
		{
			get { return Path.Combine(outputDirectory.DevSourceDirectory, StmEventsFilePath); }
		}

		void GenerateStmEventTypes(DataRow[] stmEventRows)
		{
			StartSubtask("Generating StmEvent Types");

			StringBuilder publicCode = new StringBuilder();
			StringBuilder implementationCode = new StringBuilder();

			foreach (DataRow row in stmEventRows)
			{
				Guid pK = (Guid)row["SE_PK"];
				string code = row["SE_Code"].ToString();
				string desc = row["SE_Desc"].ToString();
				string name = GetEventNameFromDescription(desc);

				publicCode.Append(LinesOfCode(
					"		#region " + name + " (" + code + ")",
					"",
					"		public const string " + name + "Code = \"" + code + "\";",
					"",
					"		public static Event " + name,
					"		{",
					"			get",
					"			{",
					"				return f" + name + ".Value;",
					"			}",
					"		}",
					"",
					"		#endregion",
					""));

				implementationCode.Append("		static Lazy<Event> f" + name + " = new Lazy<Event>(() => " + "new Event(" + name + "Code, ResString.GetMultilingualString(\"StmEvent|Desc|" + code + "\", \"" + desc + "\"), new ZGuid(\"" + pK + "\")), System.Threading.LazyThreadSafetyMode.PublicationOnly);" + System.Environment.NewLine);
			}

			string eventsClassCode = LinesOfCode(
				"namespace Enterprise.ZArchitecture.Business",
				"{",
				"	using System;",
				"	using System.Collections;",
				"	using System.Reflection;",
				"	using CargoWise.Common.Testing;",
				"	using CargoWise.Types;",
				"	using Enterprise.ZArchitecture.Core;",
				"",
				"	[Resources.AutoGeneratedSourceCode]",
				"	public abstract class AutoEvents",
				"	{",
				"		protected AutoEvents()",
				"		{",
				"		}",
				"",
						publicCode.ToString(),
				"		#region Implementation",
				"",
						implementationCode.ToString(),
				"		#endregion",
				"",
						AllEventsCode.TrimEnd(System.Environment.NewLine.ToCharArray()),
				"	}",
				"}").TrimEnd(System.Environment.NewLine.ToCharArray());

			StartSubtask("Writing StmEventTypes to file - " + StmEventsWinPath);
			new AutoGeneratedFile(StmEventsWinPath).Save(outputDirectory, eventsClassCode);
		}

		string AllEventsCode
		{
			get
			{
				return LinesOfCode(
					"		#region Events.All",
					"",
					"		public static EventCollectionBase All",
					"		{",
					"			get { return List; }",
					"		}",
					"",
					"		private static EventCollectionBase List",
					"		{",
					"			get",
					"			{",
					"				if (fList == null)",
					"				{",
					"					fList = new EventCollectionBase();",
					"					PropertyInfo[] Infos = typeof(AutoEvents).GetProperties(BindingFlags.Public | BindingFlags.Static | BindingFlags.DeclaredOnly);",
					"",
					"					foreach (PropertyInfo Info in Infos)",
					"					{",
					"						if (Info.PropertyType == typeof(Event))",
					"						{",
					"							fList.AddInternal((Event)Info.GetValue(null, null));",
					"						}",
					"					}",
					"				}",
					"				return fList;",
					"			}",
					"		}",
					"",
					"       [ThreadStatic]",
					"		static EventCollectionBase fList;",
					"",
					"		#endregion");
			}
		}

		#endregion

		#region Implementation

		string LinesOfCode(params string[] text)
		{
			return String.Join(System.Environment.NewLine, text) + System.Environment.NewLine;
		}

		string GetEventNameFromDescription(string description)
		{
			StringBuilder name = new StringBuilder();
			bool lastWasSpace = true;

			// \G\W*\b(\w)(\w*)\W*
			foreach (char c in description)
			{
				if (char.IsLetterOrDigit(c))
				{
					if (lastWasSpace)
					{
						name.Append(char.ToUpper(c));
						lastWasSpace = false;
					}
					else
					{
						name.Append(c);
					}
				}
				else
				{
					lastWasSpace = true;
				}
			}

			name = name.Replace("iz", "is").Replace("eled", "elled").Replace("eckIn", "eckin");

			return name.ToString();
		}

		[System.Diagnostics.CodeAnalysis.SuppressMessage("CargoWiseOne", "CW1108:DoNotUseDataSet", Justification = "Baseline")]
		DataRow[] GetStmEventRows()
		{
			DbUpgrader.Data.StmEventDataFile stmEventFile = new DbUpgrader.Data.StmEventDataFile();

			DataSet stmEventDataSet = stmEventFile.LoadDataFromFile();
			DataRow[] stmEventRows = stmEventDataSet.Tables["StmEvent"].Select("", "SE_Desc");

			return stmEventRows;
		}

		#endregion

		#region Status Events

		public GeneratorEvent OnTaskStarted;
		public GeneratorEvent OnSubtaskStarted;
		public GeneratorEvent OnTaskFailed;

		void StartTask(string task)
		{
			if (OnTaskStarted != null)
			{
				OnTaskStarted(task);
			}
		}

		void StartSubtask(string subtask)
		{
			if (OnSubtaskStarted != null)
			{
				OnSubtaskStarted(subtask);
			}
		}

		#endregion
	}
}

using System.Collections.ObjectModel;
using System.IO;
using CargoWise.BuildTools;
using CargoWise.BuildTools.Testing;

namespace Enterprise.Builder.Generator
{
	public static class Constants
	{
		public static string TemplateDirectory
		{
			get
			{
				if (IsTest)
				{
					return Path.Combine(MockSourceControl.MockWorkspacePath, @"Enterprise\Product\Core\Builder\Generator\O-Architecture\CodeTemplates\");
				}
				return BuildConstants.GetLocalPath(@"Enterprise\Product\Core\Builder\Generator\O-Architecture\CodeTemplates\");
			}
		}

		public static string ClientDirectoryName
		{
			get
			{
				if (IsTest)
				{
					return Path.Combine(MockSourceControl.MockWorkspacePath, "Clients");
				}
				return BuildConstants.GetLocalPath("Clients");
			}
		}

		public static string DataPurgeScriptFolderPath
		{
			get
			{
				if (IsTest)
				{
					return Path.Combine(MockSourceControl.MockWorkspacePath, @"DataTools\DataPurge\DataPurge\");
				}
				return Path.Combine(BuildConstants.LocalEnterprisePath, @"Enterprise\Product\Core\DataTools\DataPurge\DataPurge\ScriptRepository\");
			}
		}

		public static Collection<string> BiConfigurationFileCollection
		{
			get
			{
				string[] files = {
					@"Database\BusinessIntelligence\ConfigLoader\ConfigLoader\Config\EdwDenormalizedTableConfig.xml",
					@"Database\BusinessIntelligence\ConfigLoader\ConfigLoader\Config\EdwModelViewTableConfig.xml",
					@"Database\BusinessIntelligence\ConfigLoader\ConfigLoader\Config\EdwTableConfig.xml",
					@"Database\BusinessIntelligence\ConfigLoader\ConfigLoader\Config\EdwCustomTableConfig.xml",
					@"Database\BusinessIntelligence\ConfigLoader\ConfigLoader\Config\OlapCubes.xml",
					@"Database\BusinessIntelligence\ConfigLoader\ConfigLoader\Config\TestData.xml",
					@"Database\BusinessIntelligence\ConfigLoader\ConfigLoader\Config\CdcConfig.xml",
					@"Database\BusinessIntelligence\ConfigLoader\ConfigLoader\Config\EdwStagingConfig.xml",
					@"Database\Odyssey\Resource\Resource\AutoGenerated\Schema_Audit.sql",
					@"Database\Odyssey\Resource\Resource\AutoGenerated\Schema_EDW.sql"
				};

				var result = new Collection<string>();

				if (IsTest)
				{
					foreach (var file in files)
					{
						result.Add(Path.Combine(MockSourceControl.MockWorkspacePath, new FileInfo(file).Name));
					}
				}
				else
				{
					foreach (var file in files)
					{
						result.Add(Path.Combine(BuildConstants.LocalEnterprisePath, file));
					}
				}

				return result;
			}
		}

		public static string BiScriptsFilePath
		{
			get
			{
				if (IsTest)
				{
					return Path.Combine(MockSourceControl.MockWorkspacePath, "Script");
				}
				else
				{
					return Path.Combine(BuildConstants.LocalEnterprisePath, @"Enterprise\Product\Core\Database\Script\Public\BusinessIntelligence");
				}
			}
		}

		public static Collection<string> BiRegistrationPathCollection
		{
			get
			{
				var result = new Collection<string>();

				if (IsTest)
				{
					result.Add(Path.Combine(MockSourceControl.MockWorkspacePath, "Registration"));
				}
				else
				{
					result.Add(Path.Combine(BuildConstants.LocalEnterprisePath, @"BusinessIntelligence\BiIntegration\Deployment\CargoWiseBiDeployment\Registration\SSRS"));
					result.Add(Path.Combine(BuildConstants.LocalEnterprisePath, @"BusinessIntelligence\BiIntegration\Deployment\CargoWiseBiDeployment\Registration\PowerBi"));
				}

				return result;
			}
		}

		static bool IsTest
		{
			get { return NUnit.Framework.TestingState.IsRunningTests; }
		}
	}
}

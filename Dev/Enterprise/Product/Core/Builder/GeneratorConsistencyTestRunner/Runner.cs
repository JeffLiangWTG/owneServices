		public static IDisposable WithTempCWSharedSubPath(string tempCWSharedSubPath)
		{
			var oldValue = CWSharedSubPath;
			CWSharedSubPath = tempCWSharedSubPath;

			return new DisposableAction(() => CWSharedSubPath = oldValue);
		}


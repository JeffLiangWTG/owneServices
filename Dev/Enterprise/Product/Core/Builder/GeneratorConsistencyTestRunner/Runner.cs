					bizoName);
			});
		}

		public static void AssertBizoCreatedCorrectly_WithAddInfoEntries(string bizoName)
		{
			var binariesFolder = Path.GetDirectoryName(Assembly.GetExecutingAssembly().Location)!;
			var scriptDefAssPath = Path.Combine(binariesFolder, "CargoWise.DbUpgrader.Scripts.Definitions.dll");
			var scriptDefAss = Assembly.LoadFrom(scriptDefAssPath);
			var scriptDefAllResources = scriptDefAss.GetManifestResourceNames().Where(rn =>
					rn.StartsWith(ModelViewConstants.NamespacePrefix, StringComparison.Ordinal))
				.ToDictionary(rn => rn.Substring(ModelViewConstants.NamespacePrefix.Length + 1), rn => rn);
			var modelFileResources = scriptDefAllResources.Values.Where(d =>
				d.EndsWith(ModelViewConstants.ModelFileSuffix, StringComparison.InvariantCultureIgnoreCase));

			using var tempCWSharedPathDirectoryInfo = Runner.WithTempCWSharedPathForTest(Runner.CWSharedPathDirectoryInfo.FullName);
			using var tempGetActualResource = Runner.WithTempGetActualResource(actualFilename =>
			{
				if (scriptDefAllResources.TryGetValue(actualFilename.Replace('\\', '.'), out var resourceName))
				{
					return scriptDefAss.GetManifestResourceStream(resourceName);
				}

				return ResourceManager.GetStream(actualFilename);
			});

			GenerateAndAssert(outputDirectory =>
			{
				SetupModelViewSources(outputDirectory, modelFileResources, scriptDefAss, binariesFolder, f => f.Contains(bizoName));

				var bizObjGenerator = new BizObjGenerator(outputDirectory);
				ThrowIfNotSuccessful(
					bizObjGenerator.GenerateSpecificFile(bizoName.ToLower(), excludeClientSpecific: true, excludeAutoEnterpriseSchema: true, exactMatch: true),
					bizoName);
			});
		}

		static void ThrowIfNotSuccessful(bool successful, string bizoName)
		{
			if (!successful)
			{
				throw new InvalidOperationException($"Failed to generate BIZO: {bizoName}");
			}
		}

		public static void SetupModelViewSources(GeneratorOutputDirectory outputDirectory, IEnumerable<string> modelFileResources, Assembly scriptDefAss, string binariesFolder, Func<string, bool> predicate)
		{
			var destinationDirectory = Path.Combine(outputDirectory.CWSharedSourceDirectory,
					ModelViewConstants.RelativeProjectRootPath);
			Directory.CreateDirectory(destinationDirectory);

			foreach (var modelFileResource in modelFileResources.Where(predicate))
			{
				var (subfolder, filename) = ExtractSubFolderAndFilename(modelFileResource);
				var modelFileContent = GetResourceString(scriptDefAss, modelFileResource);
				Directory.CreateDirectory(Path.Combine(destinationDirectory, subfolder));
				File.WriteAllText(Path.Combine(destinationDirectory, subfolder, filename), modelFileContent);
			}

			destinationDirectory = Path.Combine(outputDirectory.CWSharedSourceDirectory,
				@"CargoWise.DbUpgrader\src\Resource\Resource\AutoGenerated\");
			Directory.CreateDirectory(destinationDirectory);
			var resourceAssPath = Path.Combine(binariesFolder, "Enterprise.DbUpgrader.Resource.dll");
			var resourceAss = Assembly.LoadFrom(resourceAssPath);
			var mainSchemaContent = GetResourceString(resourceAss, "Enterprise.DbUpgrader.Resource.AutoGenerated.Schema_Main.sql");
			File.WriteAllText(Path.Combine(destinationDirectory, "Schema_Main.sql"), mainSchemaContent);
		}

		static string GetResourceString(Assembly assembly, string resourceName)
		{
			using var stream = assembly.GetManifestResourceStream(resourceName);
			using var reader = new StreamReader(stream, true);
			return reader.ReadToEnd();
		}

		static (string subfolder, string filename) ExtractSubFolderAndFilename(string resourceName)
		{
			var withoutPrefix = resourceName.Substring(ModelViewConstants.NamespacePrefix.Length + 1);
			var suffixIndex = withoutPrefix.LastIndexOf(ModelViewConstants.ModelFileSuffix);

			var subFolder = withoutPrefix.Substring(0, withoutPrefix.LastIndexOf('.', suffixIndex - 1));
			var modelViewFilename = withoutPrefix.Substring(subFolder.Length + 1);

			return (subFolder.Replace('.', '\\'), modelViewFilename);
		}

		internal static void GenerateAndAssert(Action<GeneratorOutputDirectory> generateAction)
		{
			const string errorMessage = @"This failure has likely occurred due to manual modification of auto-generated files that are maintained by the BusinessObjectGenerator.
These files are not supposed to be manually edited and are re-generated by the BusinessObjectGenerator tool. For details about this tool, please refer to The Source.

To address this failure, please make manual changes (except setting the namespace) only to the subclasses of the auto-generated files and regenerate this file with the Generator or regen tool.
The KDiff3 or other comparison links can be used to compare the expected and actual file contents.

Note that this test is also intentionally sensitive to whitespace (such as new lines at the end of the file) that might be added due to auto-formatting settings from Visual Studio settings/plugins. In this case consider shelving immediately after running the generator or fixing the failure in a text editor.
";

			try
			{
				CWSharedPathDirectoryInfo.Create();

				SourceControl.SetEnterpriseInstanceForTesting(new SourceControlForTest());
				var outputDirectory = new GeneratorOutputDirectory(GeneratorOutputDirectory.SaveMode.DontSave, BuildConstants.LocalEnterprisePath, CWSharedPathForTest);

				using (Db.DisposableActionForDbConnection())
				{
					generateAction(outputDirectory);
				}

				Assertion.CombineAssertions(errorMessage, () =>
				{
					var cwsharedLen = Path.Combine(CWSharedPathForTest, CWSharedSubPath).Length;
					foreach (var filePair in outputDirectory.GetAllFilePaths())
					{
						string actual;
						if (filePair.Value.StartsWith(CWSharedPathForTest))
						{
							var actualFileName = filePair.Value.Substring(cwsharedLen);
							actual = new StreamReader(GetActualResource(actualFileName)).ReadToEnd();
						}
						else
						{
							actual = ReadAllTextIfExists(filePair.Value);
						}

						Assertion.AssertMultilineASCIIEquals(
							ShortenPath(outputDirectory, filePair.Key) + " content is not correctly auto-generated.",
							ReadAllTextIfExists(filePair.Key),
							actual,
							includeEmptyLines: true);
					}
				});

				Assertion.Assert(true); // to avoid empty test
			}
			finally
			{
				CWSharedPathDirectoryInfo?.Delete(recursive: true);
			}
		}


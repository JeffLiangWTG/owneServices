		static string ShortenPath(GeneratorOutputDirectory outputDirectory, string path)
		{
			var basePath = outputDirectory.DevOutputDirectory;

			if (path.StartsWith(basePath, StringComparison.InvariantCultureIgnoreCase))
			{
				return path.Substring(basePath.Length).TrimStart('\\');
			}

			basePath = outputDirectory.CWSharedOutputDirectory;

			if (path.StartsWith(basePath, StringComparison.InvariantCultureIgnoreCase))
			{
				return path.Substring(basePath.Length).TrimStart('\\');
			}

			return path;
		}


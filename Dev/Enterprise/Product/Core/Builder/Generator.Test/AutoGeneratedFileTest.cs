using System;
using System.IO;
using CargoWise.BuildTools.Testing;

namespace Enterprise.Builder.Generator
{
	sealed class AutoGeneratedFileTest : NUnit.Framework.TestCase
	{
		public void TestSave_Dev()
		{
			using (GeneratorOutputDirectory outputDir = new FauxGeneratorOutputDirectory(GeneratorOutputDirectory.SaveMode.CheckOut))
			{
				string file = Guid.NewGuid().ToString();
				string fileName = Path.Combine(outputDir.DevSourceDirectory, file);
				string outPutFileName = Path.Combine(outputDir.DevOutputDirectory, file);

				const string Contents = "Testing BuildUtils.WriteFileContents & BuildUtils.FileContents";
				AutoGeneratedFile testFile = new AutoGeneratedFile(fileName);
				testFile.Save(outputDir, Contents);
				Assert(File.ReadAllText(outPutFileName).EndsWith(Contents));

				const string Contents2 = Contents + " overwriting the same file.";
				testFile.Save(outputDir, Contents2);
				Assert(File.ReadAllText(outPutFileName).EndsWith(Contents2));
			}
		}

		public void TestSave_CWShared()
		{
			using (GeneratorOutputDirectory outputDir = new FauxGeneratorOutputDirectory(GeneratorOutputDirectory.SaveMode.CheckOut))
			{
				string file = Guid.NewGuid().ToString();
				string fileName = Path.Combine(outputDir.CWSharedSourceDirectory, file);
				string outPutFileName = Path.Combine(outputDir.CWSharedOutputDirectory, file);

				const string Contents = "Testing BuildUtils.WriteFileContents & BuildUtils.FileContents";
				AutoGeneratedFile testFile = new AutoGeneratedFile(fileName);
				testFile.Save(outputDir, Contents);
				Assert(File.ReadAllText(outPutFileName).EndsWith(Contents));

				const string Contents2 = Contents + " overwriting the same file.";
				testFile.Save(outputDir, Contents2);
				Assert(File.ReadAllText(outPutFileName).EndsWith(Contents2));
			}
		}
	}
}

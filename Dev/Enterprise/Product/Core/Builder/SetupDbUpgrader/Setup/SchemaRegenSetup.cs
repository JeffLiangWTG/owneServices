using System;
using System.IO;
using System.Text.RegularExpressions;
using CargoWise.BuildTools;
using CargoWise.BuildTools.Testing;
using CargoWise.Common;
using Enterprise.ZArchitecture.Core;

namespace Enterprise.Builder.GenerateDbUpgraderResources
{
	#region RegenTypeEnum

	public enum RegenActionEnum
	{
		Full,
		BumpOnly,
		Merge
	}

	public enum RegenVersionChangeEnum
	{
		Standard,
		ForceMinor,
	}

	#endregion

	class SchemaRegenSetup
	{
		public void RegenarateFiles(RegenActionEnum regenAction, RegenVersionChangeEnum regenVersionChange)
		{
			bool hasMainScriptChanged = false;
			bool hasDocManagerScriptChanged = false;
			VersionInfoPair currentVersionPair = GetCurrentVersion();

			if (regenAction == RegenActionEnum.Full || regenAction == RegenActionEnum.Merge)
			{
				RecreateRegenFilesTrackingChanges(currentVersionPair, ref hasMainScriptChanged, ref hasDocManagerScriptChanged);
			}

			if (regenAction == RegenActionEnum.BumpOnly || hasMainScriptChanged)
			{
				VersionInfoPair nextVersionPair = GetNextVersion(regenVersionChange, currentVersionPair);
				BumpVersion(nextVersionPair, hasDocManagerScriptChanged);
			}
		}

		#region Source Control

		/// <summary>
		/// Checks-out autogenerated files.
		/// Note: Files are compared to their previous version (for a number of reasons).
		///       Undo Check-out is called first to force comparissons to the be made to the source-safe checked-in version.
		///       Routine file       : to avoid overriding DocManager HasChanged status
		///       Schema Version file: to avoid skipping version numbers
		/// </summary>
		public void CheckOutFiles(RegenActionEnum regenAction)
		{
			CheckOut(regenAction, FilesForSourceControlOperation);
		}

		public string[] GetFilesToCheckIn()
		{
			return FilesForSourceControlOperation;
		}

		public void UndoCheckOutFiles()
		{
			UndoCheckOut(FilesForSourceControlOperation);
		}

		void CheckOut(RegenActionEnum regenAction, params string[] paths)
		{
			if (regenAction != RegenActionEnum.Merge)
			{
				UndoCheckOut(paths);
			}
			SourceControl.EnterpriseDatabase.CheckOut(paths, false);
		}

		void UndoCheckOut(params string[] paths)
		{
			SourceControl.EnterpriseDatabase.UndoCheckOut(paths, false);
		}

		string[] FilesForSourceControlOperation
		{
			get
			{
				return new string[] {
					MainDbSchemaFilePath,
					DocManagerDbSchemaFilePath,
					VersionFileWindowsPath
				};
			}
		}

		#endregion

		VersionInfoPair GetNextVersion(RegenVersionChangeEnum regenVersionChange, VersionInfoPair currentVersionPair)
		{
			int nextMajor = currentVersionPair.Major.Number;
			int nextMinor = currentVersionPair.Minor.Number;

			if (IsMinorVersionIncrementOnly(regenVersionChange))
			{
				nextMinor += 1;
			}
			else
			{
				nextMajor++;
				nextMinor = 0;
			}

			return new VersionInfoPair(nextMajor, nextMinor);
		}

		VersionInfoPair GetCurrentVersion()
		{
			string versionFileContents = File.ReadAllText(VersionFileWindowsPath);

			string currentMajor = Regex.Match(versionFileContents, appMajorVersionPattern).Value;
			string currentMinor = Regex.Match(versionFileContents, appMinorVersionPattern).Value;

			VersionInfoPair result;

			try
			{
				result = new VersionInfoPair(Convert.ToInt32(currentMajor), Convert.ToInt32(currentMinor));
			}
			catch (Exception ex) when (!ex.IsCriticalException())
			{
				string message = String.Format(
					"Version [{0}.{1}] is not valid.\r\n{2}", currentMajor, currentMinor, ex.Message);
				throw new Exception(message, ex);
			}

			return result;
		}

		bool IsMinorVersionIncrementOnly(RegenVersionChangeEnum regenVersionChange)
		{
			return (regenVersionChange == RegenVersionChangeEnum.ForceMinor);
		}

		void RecreateRegenFilesTrackingChanges(VersionInfoPair versionPair, ref bool hasMainScriptChanged, ref bool hasDocManagerScriptChanged)
		{
			string oldMainDbScripts = File.ReadAllText(MainDbSchemaFilePath).Trim();
			string oldDocManagerScripts = File.ReadAllText(DocManagerDbSchemaFilePath).Trim();

			RecreateSchemaFiles(versionPair);

			string newMainDbScripts = File.ReadAllText(MainDbSchemaFilePath).Trim();
			string newDocManagerScripts = File.ReadAllText(DocManagerDbSchemaFilePath).Trim();

			hasMainScriptChanged = (oldMainDbScripts != newMainDbScripts);
			hasDocManagerScriptChanged = (oldDocManagerScripts != newDocManagerScripts);
		}

		protected virtual void RecreateSchemaFiles(VersionInfoPair versionPair)
		{
			using (var tempFile = TempFile.New())
			{
				var fileBuilder = new SchemaFileBuilder(tempFile.Filename, MainDbSchemaFilePath, DocManagerDbSchemaFilePath);
				fileBuilder.RecreateFile();
			}
		}

		void RecreateVersionFile(bool shouldBumpDocManagerVersion, VersionInfoPair nextVersionPair)
		{
			string versionFileContents = File.ReadAllText(VersionFileWindowsPath);

			// Replace Aplication Version Numbers
			versionFileContents = Regex.Replace(versionFileContents, appMajorVersionPattern, nextVersionPair.Major.Number.ToString());
			versionFileContents = Regex.Replace(versionFileContents, appMinorVersionPattern, nextVersionPair.Minor.Number.ToString());

			if (shouldBumpDocManagerVersion)
			{
				// Replace DocManager Version Numbers
				versionFileContents = Regex.Replace(versionFileContents, docManagerMajorVersionPattern, nextVersionPair.Major.Number.ToString());
				versionFileContents = Regex.Replace(versionFileContents, docManagerMinorVersionPattern, nextVersionPair.Minor.Number.ToString());
			}

			File.WriteAllText(VersionFileWindowsPath, versionFileContents);
		}

		protected virtual void BumpVersion(VersionInfoPair nextVersionPair, bool shouldBumpDocManagerVersion)
		{
			RecreateVersionFile(shouldBumpDocManagerVersion, nextVersionPair);
		}

		const string appMajorVersionPattern = @"(?<=\bApplication\b\s*=\s*new\s*VersionLabel\s*\(\s*)([0-9]+)(?=\s*,\s*[0-9]+\s*\)\s*;)";
		const string appMinorVersionPattern = @"(?<=\bApplication\b\s*=\s*new\s*VersionLabel\s*\(\s*[0-9]+\s*,\s*)([0-9]+)(?=\s*\)\s*;)";
		const string docManagerMajorVersionPattern = @"(?<=\bDocManager\b\s*=\s*new\s*VersionLabel\s*\(\s*)([0-9]+)(?=\s*,\s*[0-9]+\s*\)\s*;)";
		const string docManagerMinorVersionPattern = @"(?<=\bDocManager\b\s*=\s*new\s*VersionLabel\s*\(\s*[0-9]+\s*,\s*)([0-9]+)(?=\s*\)\s*;)";

		protected virtual string VersionFileWindowsPath
		{
			get { return DummyDbVersion.SchemaFileWindowsPath; }
		}

		protected virtual string MainDbSchemaFilePath
		{
			get { return BuildConstants.MainDbSchemaFileWindowsPath; }
		}

		protected virtual string DocManagerDbSchemaFilePath
		{
			get { return BuildConstants.DocManagerDbSchemaFileWindowsPath; }
		}
	}
}

using System;
using System.Collections.Generic;
using System.Data;
using System.Linq;
using CargoWise.Data;
using CargoWise.Database.Shared;
using NUnit.Framework;

namespace Enterprise.BusinessObjectGenerator.Testing
{
	sealed class AutoSchemaTest : TestCase
	{
		public void TestSourceCode()
		{
			string sourceCode = SchemaClass.SourceCode;
			AssertMultilineASCIIEquals("Contains GetTableSchema method", ExpectedGetTableSchemaContent.Trim(), sourceCode.Trim());
		}

		public void TestGetTablesAndPrefixes()
		{
			Dictionary<string, string> tablesAndPrefixes = SchemaClass.GetTablesAndPrefixesExposed(new HashSet<string>(GetAllProductionDatabaseTableNames()));
			AssertEquals("Key=Table name Value=Column name prefix", "OH", tablesAndPrefixes["OrgHeader"]);

			List<string> prefixesSoFar = new List<string>();

			foreach (KeyValuePair<string, string> tablesAndPrefix in tablesAndPrefixes)
			{
				string tableName = tablesAndPrefix.Key;
				string columnNamePrefix = tablesAndPrefix.Value;

				AssertEquals("All prefixes length must be 2 or 3 chars. Table [" + tableName + "] prefix [" + columnNamePrefix + "] length = 2 or 3?", true, columnNamePrefix.Length == 2 || columnNamePrefix.Length == 3);
				AssertEquals("Prefixes shouldn't be duplicated otherwise they'll result in duplicate case statements. Prefix [" + columnNamePrefix + "] is duplicated.", false, prefixesSoFar.Contains(columnNamePrefix));
				prefixesSoFar.Add(columnNamePrefix);
			}
		}

		#region Test Data Tables

		DataTable PersistentDataTable
		{
			get
			{
				DataTable result = new DataTable("PersistentTable");
				result.Columns.AddRange(
					new DataColumn[]
				{
					new DataColumn("PT_Char", typeof(String)),
					new DataColumn("PT_String", typeof(String)),
				});

				return result;
			}
		}

		DataTable NonPersistentDataTable
		{
			get
			{
				DataTable result = new DataTable("NonPersistentTable");
				result.Columns.AddRange(
					new DataColumn[]
				{
					new DataColumn("NP_Char", typeof(String)),
					new DataColumn("NP_String", typeof(String)),
				});

				return result;
			}
		}

		TestAutoSchemaClass SchemaClass;

		#endregion

		#region Test Classes

		class TestAutoSchemaClass : AutoSchema
		{
			public TestAutoSchemaClass(DataTable[] persistentTablesColumns, DataTable[] nonPersistentTablesColumns)
				: base(persistentTablesColumns, nonPersistentTablesColumns)
			{
			}

			public Dictionary<string, string> GetTablesAndPrefixesExposed(HashSet<string> tableNamesToInclude)
			{
				return base.GetTablesAndPrefixes(tableNamesToInclude);
			}

			protected override Dictionary<string, string> GetTablesAndPrefixes(HashSet<string> tableNamesToInclude)
			{
				Dictionary<string, string> result = new Dictionary<string, string>();
				result.Add("PersistentTable", "PT");
				return result;
			}
		}

		#endregion

		#region Implementation

		const string ExpectedGetTableSchemaContent = @"
//------------------------------------------------------------------------------
// <autogenerated>
//     Manual changes to this file will be lost when it is regenerated,
//     except for the namespace which will stay as you edit it.
// </autogenerated>
//------------------------------------------------------------------------------

using CargoWise.Schema;

namespace Enterprise.ZArchitecture.Schema
{
	public abstract class AutoEnterpriseSchema
	{
		/// <summary>
		/// This method specifically and intentionally only deals with the standard tables, not client specific tables.
		/// This is almost certainly not the method you want.
		/// </summary>
		protected internal static ITableSchema GetStandardTableSchema(string tableName)
		{
			switch (tableName)
			{
				case NonPersistentTableSchema.Constants.TableName : return NonPersistentTableSchema.Instance;
				case PersistentTableSchema.Constants.TableName    : return PersistentTableSchema.Instance;
			}

			return null;
		}

		/// <summary>
		/// This method specifically and intentionally only deals with the standard tables, not client specific tables.
		/// This is almost certainly not the method you want.
		/// </summary>
		protected internal static ITableSchema GetStandardTableSchemaFromColumnNamePrefix(string columnNamePrefix)
		{
			switch (columnNamePrefix)
			{
				case ""PT"" : return PersistentTableSchema.Instance;
			}

			return null;
		}
	}
}
";
		string[] GetAllProductionDatabaseTableNames()
		{
			return GetAllDatabaseTableNames().Where(t => !t.EndsWith(DBHelper.SRDbOfflineTableSuffix)).ToArray();
		}

		string[] GetAllDatabaseTableNames()
		{
			List<string> result = new List<string>();
			using (var reader = Db.Connection.Command("sp_tables").ExecuteReader())
			{
				while (reader.Read())
				{
					result.Add((string)reader["TABLE_NAME"]);
				}
			}
			return result.ToArray();
		}

		protected override void SetUp()
		{
			base.SetUp();

			DataTable[] persistedTables = new DataTable[] { PersistentDataTable };
			DataTable[] nonPersistedTables = new DataTable[] { NonPersistentDataTable };

			SchemaClass = new TestAutoSchemaClass(persistedTables, nonPersistedTables);
		}

		#endregion
	}
}

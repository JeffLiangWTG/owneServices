#==============================================================================================
# WARNING: this script may be called by other tools, be careful about making breaking changes.
#==============================================================================================

if ($args.Length -ne 1)
{
    Write-Output "Usage:"
    Write-Output "  ApplySchemaChange.ps1 <xCase commit-id>"
    exit 1
}

$patchCommitId=$args[0]
$xCaseLocalRepo=(Join-Path -Path $env:LOCALAPPDATA -ChildPath "AutoRegen\xCase")
$xCaseRemoteRepo="https://devops.wisetechglobal.com/wtg/CargoWise/_git/xCase"
$patchFile=(Join-Path -Path $env:TEMP -ChildPath "AutoRegen_${patchCommitId}.patch")
$schemaLocation="..\..\..\..\Database\Odyssey\Resource\Resource\AutoGenerated";

if (!(Test-Path -Path $xCaseLocalRepo))
{
    Write-Output "Cloning ${xCaseRemoteRepo} to ${xCaseLocalRepo}."
    git clone $xCaseRemoteRepo $xCaseLocalRepo --single-branch --bare --depth=10
}

Write-Output "Using ${xCaseLocalRepo}."
Push-Location -Path $xCaseLocalRepo

Write-Output "Fetching ${patchCommitId}"

git fetch origin $PatchCommitId

if ($LASTEXITCODE -ne 0)
{
    Write-Error "git fetch exited with error code: $LASTEXITCODE"
    Pop-Location
    exit 1
}

Write-Output "Generating patch file ${patchFile}"

(git diff "${patchCommitId}~..${patchCommitId}" -- CREATE.SQL) -replace 'CREATE.SQL', 'Schema_Main.sql' | Out-File -Encoding utf8 $patchFile
if ($LASTEXITCODE -ne 0)
{
    Write-Error "git diff exited with error code: $LASTEXITCODE"
    Pop-Location
    exit 1
}

Pop-Location

Push-Location $schemaLocation

Write-Output "Applying patch file ${patchFile} to ${schemaLocation}\Schema_Main.sql"
git apply --reject --ignore-space-change --ignore-whitespace $patchFile

if ($LASTEXITCODE -ne 0)
{
    Write-Error "git apply exited with error code: $LASTEXITCODE"
    Pop-Location
    exit 1
}

Pop-Location

using System;
using System.Data;

namespace Enterprise.BusinessObjectGenerator
{
	public class AutoBusinessObjectValidation : AutoSourceFile
	{
		public AutoBusinessObjectValidation(BusinessObjectInfo info, AutoPropertyList autoProperties)
		{
			this.Info = info;
			this.AutoProperties = autoProperties;
			this.isCargoWiseEntityFrameworkNamespace = (
				string.Compare(info.Namespace, "CargoWise.EntityFramework.Testing", StringComparison.OrdinalIgnoreCase) == 0);
		}

		#region Code for Body

		protected override string Body
		{
			get
			{
				return LinesOfCode(
					UsingClause,
					"",
					"namespace " + Info.Namespace,
					"{",
					"	[" + AutoGeneratedCodeAttribute + "]",
					"	public abstract class " + ClassName + " : ZValidation",
					"	{",
					CodeForConstructor,
					"",
					CodeForAutoValidationType,
					"",
					CodeForAddRemove,
					"",
					CodeForPropertyValidation,
					"",
					CodeForValidateAll,
					"",
					CodeForImplementation,
					"	}",
					"}"
					);
			}
		}

		#endregion

		#region Code for Using Clause

		protected string UsingClause
		{
			get
			{
				return LinesOfCode(
					"using System;",
					"",
					UsingCargoWiseEntityFramework,
					UsingZArchitecture);
			}
		}

		protected string UsingCargoWiseEntityFramework
		{
			get
			{
				if (isCargoWiseEntityFrameworkNamespace)
				{
					return null;
				}
				else
				{
					return LinesOfCode(
						"using CargoWise.EntityFramework;",
						"using CargoWise.Types;"
						);
				}
			}
		}

		protected string UsingZArchitecture
		{
			get
			{
				if (isCargoWiseEntityFrameworkNamespace)
				{
					return null;
				}
				else
				{
					return LinesOfCode(
						"using Enterprise.ZArchitecture;",
						"using Enterprise.ZArchitecture.Business;"
						);
				}
			}
		}

		protected string AutoGeneratedCodeAttribute
		{
			get
			{
				return (isCargoWiseEntityFrameworkNamespace) ?
					"System.CodeDom.Compiler.GeneratedCode(\"CargoWise.EntityFramework\", \"1.0\")"
					: "Resources.AutoGeneratedSourceCode()";
			}
		}

		#endregion

		#region Code for Constructor

		protected virtual string CodeForConstructor
		{
			get
			{
				return LinesOfCode(
					"		protected " + ClassName + "(" + Info.ClassNames.BusinessObjectAuto + " Parent) : base(Parent)",
					"		{",
					"			if (Object.ReferenceEquals(Parent, null))",
					"			{",
					"				throw new ArgumentNullException(\"Parent\");",
					"			}",
					"			this.Parent = Parent;",
					"			this.ParentListInternals = (ISingleElementListInternal) Parent;",
					"			this.ZValidationInternals = (IValidationInternals) this;",
					"		}"
					);
			}
		}

		#endregion

		#region Code for Auto-Validation Type

		protected string CodeForAutoValidationType
		{
			get
			{
				return LinesOfCode(
					"		/// <summary>",
					"		/// The auto validation type.",
					"		/// </summary>",
					"		public override Type AutoValidationType",
					"		{",
					"			get { return typeof(" + ClassName + "); }",
					"		}"
					);
			}
		}

		#endregion

		#region Code for Add() / Remove()

		protected string CodeForAddRemove
		{
			get
			{
				return LinesOfCode(
					"		/// <summary>",
					"		/// Add more validation to the " + Info.ClassNames.BusinessObject + "'s base validation. This will not replace existing validation ",
					"		/// (to replace existing validation you should override the 'Validation' property in the business object).",
					"		/// </summary>",
					"		public void Add(" + ClassName + " Validation)",
					"		{",
					"			ZValidationInternals.Add(Validation);",
					"		}",
					"",
					"		/// <summary>",
					"		/// Remove validation. The " + Info.ClassNames.BusinessObject + "'s base validation object cannot be removed.",
					"		/// </summary>",
					"		public void Remove(" + ClassName + " Validation)",
					"		{",
					"			ZValidationInternals.Remove(Validation);",
					"		}"
					);
			}
		}

		#endregion

		#region Code for Validation

		protected virtual string CodeForPropertyValidation
		{
			get
			{
				string result = LinesOfCode(
					"		#region Properties",
					"",
					"");

				foreach (AutoProperty property in AutoProperties.Properties)
				{
					if (property.GenerateValidation)
					{
						result += CodeForValidation(property);
					}
				}

				result += "		#endregion";

				return result;
			}
		}

		protected string CodeForValidation(AutoProperty property)
		{
			string result = LinesOfCode(
				"		#region " + property.ColumnName,
				"",
				"		public void Validate" + property.ColumnName + "()",
				"		{",
				"			ZValidationInternals.Validate(Parent." + property.ColumnName + "Info, Get" + property.ColumnName + "ValidationInvoker());",
				"		}",
				"",
				"		RunValidationInvoker Get" + property.ColumnName + "ValidationInvoker()",
				"		{",
				"			return delegate",
				"			{",
				CodeForCallToMandatoryValidation(property),
				CodeForCallToTypeValidaton(property),
				CodeForCallToDateValidation(property),
				CodeForCallToEnglishValidation(property),
				CodeForCallToSpatialTypeValidation(property),
				CodeForCallToCustomValidation(property),
				"			};",
				"		}",
				"",
				CodeForTypeValidation(property),
				CodeForMandatoryValidation(property),
				CodeForEnglishCharactersValidation(property),
				CodeForSpatialTypeValidation(property),
				CodeForDateValidation(property),
				CodeForCustomValidation(property),
				"		#endregion",
				"",
				"");

			return result;
		}

		#region Type Validation

		protected string TypeValidationMethodName(AutoProperty property)
		{
			string result = "";

			switch (property.DataType.Name)
			{
				case "DateTime":
					{
						if (property.SqlDbType == SqlDbType.Date)
						{
							result = "Check" + property.ColumnName + "IsValidZDate()";
							break;
						}
						else
						{
							result = "Check" + property.ColumnName + "IsValidZDateTime()";
							break;
						}
					}
				case "DateTimeOffset":
					{
						result = "Check" + property.ColumnName + "IsValidZDateTimeOffset()";
						break;
					}
				case "SqlGeography":
					{
						result = "Check" + property.ColumnName + "IsValidZGeography()";
						break;
					}
				case "Guid":
					result = "Check" + property.ColumnName + "IsValidZGuid()";
					break;
				case "Byte[]":
					result = "Check" + property.ColumnName + "IsValidZBlobSize()";
					break;
				case "Decimal":
					{
						if (property.SqlDbType == SqlDbType.Money)
						{
							result = "Check" + property.ColumnName + "IsValidMoney()";
							break;
						}
						else
						{
							result = "Check" + property.ColumnName + "IsValidZDecimal()";
							break;
						}
					}
				case "TimeSpan":
					{
						result = "Check" + property.ColumnName + "IsValidZTime()";
						break;
					}
			}

			return result;
		}

		protected string CodeForCallToTypeValidaton(AutoProperty property)
		{
			return (property.RequiresTypeValidation) ? "				" + TypeValidationMethodName(property) + ";" : null;
		}

		protected string CodeForTypeValidation(AutoProperty property)
		{
			string result = null;

			if (property.RequiresTypeValidation)
			{
				string typeToCheck = null;

				switch (property.DataType.Name)
				{
					case "DateTime":
						{
							if (property.SqlDbType == SqlDbType.SmallDateTime)
							{
								typeToCheck = "SmallDateTime";
								break;
							}
							else
							{
								typeToCheck = "ZDateTimeWithoutRange";
								break;
							}
						}
					case "DateTimeOffset":
						typeToCheck = "ZDateTimeOffsetWithoutRange";
						break;
					case "SqlGeography":
						typeToCheck = "Geography";
						break;
					case "Guid":
						typeToCheck = "Guid";
						break;
					case "Byte[]":
						typeToCheck = "ZBlobSize";
						break;
					case "Decimal":
						typeToCheck = "ZDecimal";
						break;
					case "TimeSpan":
						typeToCheck = "ZTime";
						break;
				}

				if (property.DataType == typeof(decimal))
				{
					if (property.SqlDbType == SqlDbType.Money)
					{
						result = LinesOfCode(
						"		protected virtual void " + TypeValidationMethodName(property),
						"		{",
						"			TypeValidation.CheckValidMoney(Parent." + property.ColumnName + "Info, " + property.DecimalPrecision + ", " + property.DecimalScale + ");",
						"		}",
						"");
					}
					else
					{
						result = LinesOfCode(
						"		protected virtual void " + TypeValidationMethodName(property),
						"		{",
						"			TypeValidation.CheckValidDecimal(Parent." + property.ColumnName + "Info, " + property.DecimalPrecision + ", " + property.DecimalScale + ");",
						"		}",
						"");
					}
				}
				else
				{
					result = LinesOfCode(
						"		protected virtual void " + TypeValidationMethodName(property),
						"		{",
						"			TypeValidation.CheckValid" + typeToCheck + "(Parent." + property.ColumnName + "Info);",
						"		}",
						"");
				}
			}

			return result;
		}

		#endregion

		#region Mandatory Validation

		protected string CodeForCallToMandatoryValidation(AutoProperty property)
		{
			return (property.RequiresMandatoryValidation) ? "				Check" + property.ColumnName + "IsNotEmpty();" : null;
		}

		protected string CodeForMandatoryValidation(AutoProperty property)
		{
			string result = null;

			// All fields in the DB are required fields, so a mandatory field in the database is designated as:
			//  - The field is required
			//  - The field has a default value
			if (property.RequiresMandatoryValidation)
			{
				result = LinesOfCode(
					"		protected virtual void Check" + property.ColumnName + "IsNotEmpty()",
					"		{",
					"			MandatoryValidation.CheckEntered(Parent." + property.ColumnName + "Info);",
					"		}",
					"");
			}

			return result;
		}

		#endregion

		#region Date Validation

		protected string CodeForCallToDateValidation(AutoProperty property)
		{
			return (property.DataType.Name == "DateTime")
				? (property.SqlDbType != SqlDbType.Date) ? "				Check" + property.ColumnName + "IsValidZDateTimeRange();"
														 : "				Check" + property.ColumnName + "IsValidZDateRange();"
				: (property.DataType.Name == "DateTimeOffset")
				? "				Check" + property.ColumnName + "IsValidZDateTimeOffsetRange();"
				: null;
		}

		protected string CodeForDateValidation(AutoProperty property)
		{
			string result = null;

			if (property.DataType.Name == "DateTime")
			{
				if (property.SqlDbType != SqlDbType.Date)
				{
					result = LinesOfCode(
						"		protected virtual void Check" + property.ColumnName + "IsValidZDateTimeRange()",
						"		{",
						"			TypeValidation.CheckValidZDateTimeRange(Parent." + property.ColumnName + "Info);",
						"		}",
						"");
				}
				else
				{
					result = LinesOfCode(
						"		protected virtual void Check" + property.ColumnName + "IsValidZDateRange()",
						"		{",
						"			TypeValidation.CheckValidZDateTimeRange(Parent." + property.ColumnName + "Info);",
						"		}",
						"");
				}
			}
			else if (property.DataType.Name == "DateTimeOffset")
			{
				result = LinesOfCode(
						"		protected virtual void Check" + property.ColumnName + "IsValidZDateTimeOffsetRange()",
						"		{",
						"			TypeValidation.CheckValidZDateTimeOffsetRange(Parent." + property.ColumnName + "Info);",
						"		}",
						"");
			}

			return result;
		}

		#endregion

		#region Custom Validation

		protected string CodeForCallToCustomValidation(AutoProperty property)
		{
			return "				Check" + property.ColumnName + "();";
		}

		protected string CodeForCustomValidation(AutoProperty property)
		{
			return LinesOfCode(
				"		protected virtual void Check" + property.ColumnName + "()",
				"		{",
				"			// sub-classes should override to implement custom validation",
				"		}",
				"");
		}

		#endregion

		#region English Characters Validation

		protected string CodeForCallToEnglishValidation(AutoProperty property)
		{
			return (property.RequiresEnglishCharactersValidation) ? "				Check" + property.ColumnName + "IsWesternEuropean();" : null;
		}

		protected internal string CodeForEnglishCharactersValidation(AutoProperty property)
		{
			string result = null;

			if (property.RequiresEnglishCharactersValidation)
			{
				result = LinesOfCode(
					"		protected virtual void Check" + property.ColumnName + "IsWesternEuropean()",
					"		{",
					"			EnglishCharactersValidation.ErrorIfNotWesternEuropean(Parent." + property.ColumnName + "Info);",
					"		}",
					"");
			}

			return result;
		}

		#endregion

		#region Geography Type Validation

		protected string CodeForCallToSpatialTypeValidation(AutoProperty property)
		{
			return (property.IsGeographyProperty) ? "				Check" + property.ColumnName + "IsSetWithAllowedSpatialType();" : null;
		}

		protected string CodeForSpatialTypeValidation(AutoProperty property)
		{
			string result = null;

			if (property.IsGeographyProperty)
			{
				result = LinesOfCode(
					"		protected virtual void Check" + property.ColumnName + "IsSetWithAllowedSpatialType()",
					"		{",
					"			SpatialTypeValidation.ErrorIfSpatialTypeIsNotAllowed(Parent." + property.ColumnName + "Info);",
					"		}",
					"");
			}

			return result;
		}

		#endregion

		#endregion

		#region Code for CodeForValidateAll

		protected virtual string CodeForValidateAll
		{
			get
			{
				string callValidateMethods = AutoProperties.CodeForCallingEachPropertyValidate(4);

				return LinesOfCode(
					"		#region Validate All",
					"",
					"		public override void ValidateAll()",
					"		{",
					"			using (ParentListInternals.SuspendListChanged())",
					"			{",
					callValidateMethods,
					"			}",
					"		}",
					"",
					"		#endregion");
			}
		}

		#endregion

		#region Code for Implementation

		public virtual string CodeForImplementation
		{
			get
			{
				return LinesOfCode(
					"		#region Implementation",
					"",
					"		protected readonly " + Info.ClassNames.BusinessObjectAuto + " Parent;",
					"		private readonly ISingleElementListInternal ParentListInternals;",
					"		private readonly IValidationInternals ZValidationInternals;",
					"",
					"		#endregion");
			}
		}

		#endregion

		protected string ClassName
		{
			get { return Info.ClassNames.BusinessObjectAuto + "Validation"; }
		}

		protected BusinessObjectInfo Info;
		protected AutoPropertyList AutoProperties;
		protected readonly bool isCargoWiseEntityFrameworkNamespace;
	}
}

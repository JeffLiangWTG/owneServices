namespace Enterprise.BusinessObjectGenerator.ModelView
{
	public abstract class ModelViewSourceFile : AutoSourceFile
	{
		protected readonly ModelViewContext Context;

		protected ModelViewSourceFile(ModelViewContext context)
		{
			Context = context;
		}

		protected string IndentL1 = new string(IndentChar, 1);
		protected string IndentL2 = new string(IndentChar, 2);
		protected string IndentL3 = new string(IndentChar, 3);
		protected string IndentL4 = new string(IndentChar, 4);
		protected string IndentL5 = new string(IndentChar, 5);
		protected string IndentL6 = new string(IndentChar, 6);
		protected string IndentL7 = new string(IndentChar, 7);

		const char IndentChar = '\t';

		protected virtual string CommentString => "//";

		protected const string NamespaceSeparator = ".";

		protected const string BlockStartString = "{";

		protected const string BlockEndString = "}";

		protected const string LineEndString = ";";

		protected const string EmptyLineString = "";

		protected override string HeadingComment
		{
			get
			{
				return LinesOfCode(
					$"{CommentString}------------------------------------------------------------------------------",
					$"{CommentString}{IndentL1}<auto-generated>",
					$"{CommentString}{IndentL2}This code was generated by ModelViewCodeGeneratorProvider.",
					$"{CommentString}{EmptyLineString}",
					$"{CommentString}{IndentL2}Changes to this file may cause incorrect behavior and will be lost if",
					$"{CommentString}{IndentL2}the code is regenerated.",
					$"{CommentString}{IndentL1}</auto-generated>",
					$"{CommentString}------------------------------------------------------------------------------",
					EmptyLineString
				);
			}
		}
	}
}

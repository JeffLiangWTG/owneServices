using System.IO;
using System.Text.RegularExpressions;

namespace Enterprise.BusinessObjectGenerator
{
	public abstract class AutoSourceFile : AutoCode
	{
		public AutoSourceFile()
		{
		}

		/// <summary>
		/// Source code for the business object class.
		/// </summary>
		public virtual string SourceCode
		{
			get { return LinesOfCode(Header, Body, string.Empty); }
		}

		public bool IsDifferentToFile(string fileName)
		{
			bool result = true;
			if (File.Exists(fileName))
			{
				const string ManyCommentedLinesPattern = "(//[^\r\n]*[\r\n]+)*";
				const string Pattern = "^" + ManyCommentedLinesPattern + "(.*)";
				string otherSourceCode = File.ReadAllText(fileName);
				otherSourceCode = Regex.Match(otherSourceCode, Pattern, RegexOptions.Singleline).Groups[2].ToString();

				result = Body + System.Environment.NewLine != otherSourceCode;
			}
			return result;
		}

		#region Implementation

		protected virtual string Header
		{
			get { return HeadingComment; }
		}

		protected abstract string Body
		{
			get;
		}

		protected virtual string HeadingComment
		{
			get
			{
				return LinesOfCode(
					"//------------------------------------------------------------------------------",
					"// <autogenerated>",
					"//     Manual changes to this file will be lost when it is regenerated,",
					"//     except for the namespace which will stay as you edit it.",
					"// </autogenerated>",
					"//------------------------------------------------------------------------------",
					""
					);
			}
		}

		#endregion
	}
}

using System;

namespace Enterprise.BusinessObjectGenerator
{
	public class AutoBusinessObjectLookups : AutoSourceFile
	{
		public AutoBusinessObjectLookups(BusinessObjectInfo info, AutoPropertyList autoProperties)
		{
			this.Info = info;
			this.AutoProperties = autoProperties;
			this.isCargoWiseEntityFrameworkNamespace = (
				String.Compare(info.Namespace, "CargoWise.EntityFramework.Testing", StringComparison.OrdinalIgnoreCase) == 0);
		}

		#region Code for Heading Comment

		protected override string HeadingComment
		{
			get
			{
				return LinesOfCode(
					"//------------------------------------------------------------------------------",
					"// <autogenerated>",
					"//     Manual changes to this file will be lost when it is regenerated.",
					"// </autogenerated>",
					"//------------------------------------------------------------------------------",
					""
					);
			}
		}

		#endregion

		#region Code for Source Body

		protected override string Body
		{
			get
			{
				if (fBody == null)
				{
					fBody = LinesOfCode(

						UsingClause,
						"",
						"namespace " + Namespace,
						"{",
						"	[Resources.AutoGeneratedSourceCode()]",
						"	public abstract class " + ClassName + " : " + InheritsFrom,
						"	{",
								CodeForConstructor.TrimEnd(),
								CodeForCollectionProperties.TrimEnd(),
						"	}",
						"}"
						);
				}

				return fBody;
			}
		}
		string fBody;

		protected virtual string InheritsFrom => "ZLookups";

		#endregion

		#region Code for Constructor

		protected string CodeForConstructor
		{
			get
			{
				return LinesOfCode(
					"		protected " + ClassName + "(" + Info.ClassNames.BusinessObjectAuto + " Parent) : base(Parent)",
					"		{",
					"		}",
					"");
			}
		}

		#endregion

		#region Code for Collection Properties

		protected string CodeForCollectionProperties
		{
			get
			{
				if (fCodeForCollectionProperties == null)
				{
					fCodeForCollectionProperties = System.Environment.NewLine;

					foreach (AutoProperty property in AutoProperties.Properties)
					{
						AutoPropertyFK fK = property as AutoPropertyFK;

						if (fK != null && fK.IsLookupShouldBeGenerated)
						{
							fCodeForCollectionProperties += CollectionCodeForProperty(fK);
						}
					}
				}

				return fCodeForCollectionProperties;
			}
		}

		protected string CollectionCodeForProperty(AutoPropertyFK property)
		{
			string result = "";
			string returnType = property.PropertyType + "Collection";

			//string Prefix = (Property.ColumnName.Length > 5) ? Property.ColumnName.Substring(3, 3) : Property.ColumnName.Substring(3, 2) + "_";
			string variableName = property.PluralNameForCollection;

			if (property.PropertyType == "OrgHeader")
			{
				result += LinesOfCode(
					"		#region " + variableName,
					"",
					"		public virtual " + returnType + " " + variableName,
					"		{",
					"			get",
					"			{",
					"				return new " + returnType + "(Factory);",
					"			}",
					"		}",
					"",
					"		#endregion",
					"",
					"");
			}
			else
			{
				result += LinesOfCode(
					"		#region " + variableName,
					"",
					"		public virtual " + returnType + " " + variableName,
					"		{",
					"			get { return new " + returnType + "(Factory); }",
					"		}",
					"",
					"		#endregion",
					"",
					"");
			}

			return result;
		}
		string fCodeForCollectionProperties;

		#endregion

		#region Code for Using Clause

		protected string UsingClause
		{
			get
			{
				return LinesOfCode(
					"using System;",
					"",
					UsingCargoWiseEntityFramework,
					UsingMasterFiles,
					UsingZArchitecture);
			}
		}

		protected string UsingMasterFiles
		{
			get
			{
				string result = null;
				if (!Info.MasterFileReference)
				{
					result = "using Enterprise.MasterFiles.Business;";
				}
				return result;
			}
		}

		protected string UsingCargoWiseEntityFramework
		{
			get
			{
				if (isCargoWiseEntityFrameworkNamespace)
				{
					return null;
				}
				else
				{
					return LinesOfCode(
						"using CargoWise.EntityFramework;",
						"using CargoWise.Types;"
						);
				}
			}
		}

		protected string UsingZArchitecture
		{
			get
			{
				if (isCargoWiseEntityFrameworkNamespace)
				{
					return null;
				}
				else
				{
					return LinesOfCode(
						"using Enterprise.ZArchitecture;",
						"using Enterprise.ZArchitecture.Business;"
						);
				}
			}
		}

		#endregion

		protected string Namespace
		{
			get { return Info.Namespace; }
		}

		protected string ClassName
		{
			get { return Info.ClassNames.BusinessObjectAuto + "Lookups"; }
		}

		protected readonly BusinessObjectInfo Info;
		readonly AutoPropertyList AutoProperties;
		protected readonly bool isCargoWiseEntityFrameworkNamespace;
	}
}

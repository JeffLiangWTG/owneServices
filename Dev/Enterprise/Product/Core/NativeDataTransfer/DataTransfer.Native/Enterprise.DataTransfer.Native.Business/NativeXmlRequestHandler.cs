	public class NativeXmlRequestHandler : IHttpXmlMessageHandler
	{
		readonly string messageSubType;
		readonly IXmlImportLogger xmlImportLogger;

		public IHttpXmlProcessingConfig ProcessingConfig { get; }

		[SuppressMessage("Microsoft.Globalization", "CA1305:SpecifyIFormatProvider")]

		public NativeXmlRequestHandler(string nativeEntityName, IXmlImportLogger xmlImportLogger) : this(nativeEntityName, xmlImportLogger, new DefaultProcessingConfig())
		{
		}

		public NativeXmlRequestHandler(string nativeEntityName, IXmlImportLogger xmlImportLogger, IHttpXmlProcessingConfig processingConfig)
		{
			this.messageSubType = XmlMessageHelper.GetMessageSubTypeForNative(nativeEntityName);
			this.xmlImportLogger = xmlImportLogger;
			if (this.messageSubType == EDIMessageSubTypeList.Codes.Unknown)
			{
				throw new NativeXMLUserVisibleException($"Unrecognized Native Dataset. Examples of supported Native Datasets are: UNLOCO, Organization, etc. A complete list of Native Datasets can be found in the eAdaptor Developer's guide or alternatively in the XML Schemas generated by {BrandingFactory.Instance.ProductName}.");
			}
			this.ProcessingConfig = processingConfig;
		}

		public IHttpXmlRequestResponse CreateRequestMessage(DisposableManager manager = null)
		{
			var factory = new BusinessObjectFactory();
			if (manager != null)
			{
				factory.AddDisposableService(manager);
			}
			var result = factory.New<IHttpXmlEDIMessage>();
			result.EM_ApplicationCode = ApplicationCodeList.Codes.NativeDataQuery;
			result.EM_ReceiveTransmit = ReceiveTransmitList.Codes.Receive;
			result.EM_MessageType = EDIMessageTypeList.Codes.XMS;
			result.EM_MessageSubType = messageSubType;
			result.EM_Status = EDIMessageStatusList.Codes.Received;
			return result;
		}

		public IHttpXmlRequestResponse CreateResponseMessage(DisposableManager manager = null)
		{
			var factory = new BusinessObjectFactory();
			if (manager != null)
			{
				factory.AddDisposableService(manager);
			}
			var result = factory.New<IHttpXmlEDIMessage>();
			result.EM_ApplicationCode = ApplicationCodeList.Codes.NativeDataQuery;
			result.EM_ReceiveTransmit = ReceiveTransmitList.Codes.Transmit;
			result.EM_MessageType = EDIMessageTypeList.Codes.XMS;
			result.EM_MessageSubType = messageSubType;
			result.EM_Status = EDIMessageStatusList.Codes.Sent;
			return result;
		}

		public IHttpXmlProcessingResult Process(IHttpXmlRequestResponse requestMessage, IHttpXmlMessageSaver messageSaver = null)
		{
			return Process(requestMessage.GetMessageStream(), requestMessage, messageSaver);
		}

		public IHttpXmlProcessingResult Process(SubStreamableStream stream, IHttpXmlRequestResponse requestMessage, IHttpXmlMessageSaver messageSaver = null)
		{
			using (var streamReader = new StreamReader(stream))
			using (Db.DisposableActionForDbConnection())
			{
				XElement requestElement;
				try
				{
					requestElement = XElement.Parse(streamReader.ReadToEnd());
				}
				catch (XmlException exception)
				{
					throw new NativeXMLUserVisibleException(exception.Message);
				}
				var requestProcessor = RequestDeserializerBuilder.GetDeserializer(requestElement);
				Request request;
				try
				{
					request = requestProcessor.Deserialize(requestElement);
				}
				catch (InvalidOperationException ex) when (ex.InnerException is NativeXMLUserVisibleException native)
				{
					throw new NativeXMLUserVisibleException(native.Message, ex);
				}

				using (Env.Instance.SuppressSwitchContextCheck(ensureContextIsRestoredAfterSuppression: false))
				using (NativeHandler.SetUserContext(((IEDIMessage)requestMessage).Factory, request.Settings?.DataContext, xmlImportLogger, (IEDIMessage)requestMessage))
				{
					var serviceAction = GetServiceAction(requestElement);
					var handler = NativeHandler.GetHandler(serviceAction);
					var response = handler.Execute(request, requestProcessor);

					xmlImportLogger.Log(LogType.Information, string.Join("\r\n", response.Informations));
					var factoryMessage = messageSaver?.Factory.Load<EDIMessage>(((EDIMessage)requestMessage).PK);
					AddMessageNote(factoryMessage);

					var result = new HttpXmlProcessingResult()
					{
						Status = StatusMapper.MapNativeStatusToUniversal(response.Status),
						ResponseMessageText =
								serviceAction == ServiceAction.Update
								&& response.Status != NativeResponseStatus.Rejected
									? CreateResponseDataStreamWithUniversalEventContaining(response.Status, response.EntityInfo)
									: CreateResponseDataStream(response.DataItems)
					};

					messageSaver?.Save(result);

					return result;
				}
			}
		}

		[SuppressMessage("CargoWiseOne", "CW1161:ResGetStringAnalyzer", Justification = "XML tag doesn't need to be translated")]
		ServiceAction GetServiceAction(XElement requestElement)
		{
			const string CriteriaGroup = "CriteriaGroup";
			const string Criteria = "Criteria";

			var xn = XNamespace.Get(ReferenceDataXMLForDeSerialize.NameSpace_Unversioned_Native);
			if ((requestElement.Descendants(xn + CriteriaGroup).Any()) && (requestElement.Descendants(xn + CriteriaGroup).Descendants(xn + Criteria).Any()))
			{
				return ServiceAction.Retrieve;
			}
			else
			{
				return ServiceAction.Update;
			}
		}

		SubStreamableStream CreateResponseDataStream(XElement[] dataItems)
		{
			var stream = new CargoWise.IO.Shim.SubStreamableStream();
			if (dataItems != null && dataItems.Length != 0)
			{
				using (var xmlWriter = NativeXmlWriter.Create(stream))
				{
					var schemaNamespace = SchemaVersionManager.Instance.Namespace;
					xmlWriter.WriteStartElement(NativeXmlInfo.RootElementName, schemaNamespace);
					xmlWriter.WriteStartElement(NativeXmlInfo.BodyElementName);
					foreach (var xElement in dataItems)
					{
						xElement.SetDefaultNameSpace(schemaNamespace, removeVersion: true); // this will be omitted by the nativeXmlWriter later.
						xElement.WriteTo(xmlWriter);
					}
					xmlWriter.WriteEndElement();
					xmlWriter.WriteEndElement();
				}
			}

			return stream;
		}

		SubStreamableStream CreateResponseDataStreamWithUniversalEventContaining(NativeResponseStatus status, Responses.EntityInfo entityInfo)
		{
			var dataContext = DataContextFactory.New();
			dataContext.SetCompanyAndDataProviderDetails(GlbCompany.CurrentCompany);
			var result = new UniversalDataBuss.DataObjects.Universal.Event
			{
				DataContext = dataContext,
				EventType = Events.DataImportCode,
				ContextCollection = new List<Context>
				{
					new Context { Type = "ProcessingStatusCode", Value =  StatusMapper.MapNativeStatusToUniversal(status) },
				}
			};

			AddToContextIfCondition(result.ContextCollection, () => entityInfo.PrimaryKey.HasValue, new Context { Type = "EntityPrimaryKey", Value = entityInfo.PrimaryKey.ToString() });
			AddToContextIfCondition(result.ContextCollection, () => !string.IsNullOrEmpty(entityInfo.Name), new Context { Type = "NativeEntityName", Value = entityInfo.Name });
			AddToContextIfCondition(result.ContextCollection, () => !string.IsNullOrEmpty(entityInfo.LocalCode), new Context { Type = "EntityLocalCode", Value = entityInfo.LocalCode });
			AddToContextIfCondition(result.ContextCollection, () => !string.IsNullOrEmpty(entityInfo.ExternalCode), new Context { Type = "EntityExternalCode", Value = entityInfo.ExternalCode });

			var stream = new CargoWise.IO.Shim.SubStreamableStream();
			if (entityInfo.PrimaryKey.HasValue)
			{
				new UniversalDataBuss.XmlIO.XmlWriting.XmlWriter().WriteXML(result, stream, false); // not a disposable writer.
			}
			return stream;
		}

		static void AddToContextIfCondition(List<Context> collection, Func<bool> condition, Context context)
		{
			if (condition())
			{
				collection.Add(context);
			}
		}

		void AddMessageNote(IEDIMessage message)
		{
			if (message != null)
			{
				DataImportNoteCreater.AddNew(message, (noteStream) =>
				{
					var writer = new StreamWriter(noteStream);
					writer.Write(xmlImportLogger.ToString());
					writer.Flush();
					noteStream.Position = 0;
				});
			}
		}
	}
}

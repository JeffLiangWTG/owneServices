		public void TestGBK_ReferenceNumberGeneration()
		{
			var existingBooking = Factory.NewWithValidTestData<GteBooking>();

			SetupFacility();

			Factory.SaveForTesting();

			var existingShipment = GetNewShipmentForTest(bookingReferenceNumber: existingBooking.GBK_ReferenceNumber, transportOrgCode: "ABC", subShipmentReferenceNumber: "BFRN1");
			var newShipment = GetNewShipmentForTest(bookingReferenceNumber: "", transportOrgCode: "ABC");

			var booking1 = new GteBookingDataObjectReader(existingShipment, new DummyLogger(), Factory).ReadIntoBusinessObject();
			var booking2 = new GteBookingDataObjectReader(newShipment, new DummyLogger(), Factory).ReadIntoBusinessObject();

			AssertNullOrEmpty("New booking reference number not be set from UXML reader.", booking2.GBK_ReferenceNumber);

			Factory.SaveForTesting();

			AssertEquals("Existing booking reference number should not change.", existingBooking.GBK_ReferenceNumber, booking1.GBK_ReferenceNumber);
			AssertNotNullOrEmpty("New booking reference number should be generated from number fountain on saving.", booking2.GBK_ReferenceNumber);

			existingShipment.BookingConfirmationReference = "ERRONEOUSREFERENCENUMBERASSIGNMENT1";
			newShipment.BookingConfirmationReference = "ERRONEOUSREFERENENUMBERASSIGNMENT2";

			booking1 = new GteBookingDataObjectReader(existingShipment, new DummyLogger(), Factory).ReadIntoBusinessObject();
			booking2 = new GteBookingDataObjectReader(newShipment, new DummyLogger(), Factory).ReadIntoBusinessObject();

			AssertNullOrEmpty("New booking reference number not be set from UXML reader.", booking2.GBK_ReferenceNumber);

			Factory.SaveForTesting();

			AssertEquals("Existing booking reference number should not change from UXML defined reference number.", existingBooking.GBK_ReferenceNumber, booking1.GBK_ReferenceNumber);
			AssertNotEquals("New booking reference number should be generated from number fountain on saving.", booking2.GBK_ReferenceNumber, newShipment.BookingConfirmationReference);
		}


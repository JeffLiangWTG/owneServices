		void TestRunTask_SaveFailedNoExpection(Exception expectedException, string expectedLog)
		{
			TestRunTask_SaveFailedCore(expectedException, null, expectedLog);
		}

		void TestRunTask_SaveFailedCore(Exception expectedException, Type expectedExceptionType, string expectedLog)
		{
			var logger = new TestServiceLogger();
			var whsInvoiceHelper = new WhsInvoiceHelper();
			var data = new TestDataSimpleEnvironment(Factory);
			var invoice = (WhsInvoice)Helper.CreateWhsInvoice(data.Whs1.PK, data.Org1.PK, ZDateTime.Now.AddDays(-14), ZDateTime.Now.AddDays(-7));
			var whsInvoiceHelperMock = new Mock<IWhsInvoiceHelper>();
			var pair = new OrgWarehousePair { OrgPK = data.Org1.PK, WarehousePK = data.Whs1.PK, HasInvoice = true };
			whsInvoiceHelperMock.Setup(d => d.GetCandidateInvoices()).Returns(new List<OrgWarehousePair> { pair });
			whsInvoiceHelperMock.Setup(d => d.CreateInvoiceFromOrgWarehousePair(pair)).Returns(invoice);
			whsInvoiceHelperMock.Setup(d => d.OldestUnpostedInvoiceExists(pair)).Returns(false);
			whsInvoiceHelperMock.Setup(d => d.InvoiceSaveSafe(It.IsAny<WhsInvoice>(), It.IsAny<ILogger>(), It.IsAny<int>()))
			.Callback((WhsInvoice invoiceIn, ILogger loggerIn, int attempt) =>
				{
					invoiceIn.Factory.Saving += (f) => throw expectedException;
					whsInvoiceHelper.InvoiceSaveSafe(invoiceIn, loggerIn, attempt);
				})
			.Returns(InvoiceSaveSafeResult.SaveFailedRetry);

			using (ObjectFactory.Substitute(whsInvoiceHelperMock.Object))
			{
				var serviceTask = new WhsInvoiceCreateQueueServiceTask() { ServiceLogger = logger };
				if (expectedExceptionType != null)
				{
					AssertExceptionThrown(expectedExceptionType, serviceTask.RunTask);
				}
				else
				{
					serviceTask.RunTask();
				}
			}
			AssertMultilineASCIIEquals("logger.ToString()", expectedLog, logger.ToString());
		}


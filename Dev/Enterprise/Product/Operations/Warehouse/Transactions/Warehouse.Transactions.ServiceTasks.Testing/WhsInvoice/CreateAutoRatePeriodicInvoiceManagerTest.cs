		void TestProcess_InvoiceSaveSafe_ShouldAttemptTwoTimesCore(Func<int, bool> failConditionForTesting, string expectedLog)
		{
			var data = new TestDataSimpleEnvironment(Factory);
			var client1 = Helper.CreateClient("C01");
			Factory.Save();
			var invoice = (WhsInvoice)Helper.CreateWhsInvoice(data.Whs1.PK, client1.PK, ZDateTime.Now.AddDays(-7), ZDateTime.Now);

			var invoiceHelper = new WhsInvoiceHelper();
			var invoiceHelperMock = MockInvoiceHelperWithDefaultSetups(new[] { invoice });
			var saveResult = InvoiceSaveSafeResult.SaveFailedRetry;
			invoiceHelperMock.Setup(d => d.InvoiceSaveSafe(It.IsAny<WhsInvoice>(), It.IsAny<ILogger>(), It.IsAny<int>()))
				.Callback((WhsInvoice invoiceIn, ILogger loggerIn, int attempt) =>
				{
					if (failConditionForTesting(attempt))
					{
						var exception = new ZCannotSaveException("Ops", "Ops");
						BusinessObjectFactory.SavingEventHandler throwError = f => throw exception;
						invoice.Factory.Saving += throwError;
						invoiceHelper.InvoiceSaveSafe(invoice, loggerIn, attempt);
						invoice.Factory.Saving -= throwError;
					}
					else
					{
						invoiceHelper.InvoiceSaveSafe(invoice, loggerIn, attempt);
						saveResult = InvoiceSaveSafeResult.SaveSuccessful;
					}
				})
				.Returns(() =>
				{
					return saveResult;
				});
			var pair = OrgWarehousePair.Create(invoice.ET_OH_Client, invoice.ET_WW);

			using (ObjectFactory.Substitute(invoiceHelperMock.Object))
			{
				var logger = new TestServiceLogger();
				var manager = new CreateAutoRatePeriodicInvoiceManager(logger);
				manager.CreateQueuePeriodicInvoice(CancellationToken.None);

				AssertMultilineASCIIEquals("logger.ToString()", expectedLog, logger.ToString());
			}
		}


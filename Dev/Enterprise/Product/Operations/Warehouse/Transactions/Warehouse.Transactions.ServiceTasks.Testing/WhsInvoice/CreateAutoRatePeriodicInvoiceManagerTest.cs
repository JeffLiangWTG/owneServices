		static void AssertExpectedInvoices(ZDateTime endOfLastInvoice, params string[] exceptedStorageJobNumbers)
		{
			var newInvoices = new BusinessObjectFactory().Load<WhsInvoice>(new ZQuery(JobStorageSchema.ET_StorageJobNumber, SQLComparisonOperator.NotEqual, exceptedStorageJobNumbers));
			CombineAssertions(() =>
			{
				foreach (var newInvoice in newInvoices)
				{
					var moreInfo = $"for client: {newInvoice.ClientName} wharehouse: {newInvoice.WarehouseName}";
					AssertEquals($"ET_StorageFromDate {moreInfo}", endOfLastInvoice.Date, newInvoice.ET_StorageFromDate.Date);
					AssertEquals($"ET_StorageToDate {moreInfo}", ZDateTime.SmallDateTimeNow.Date, newInvoice.ET_StorageToDate.Date);
					AssertEquals($"ET_BillingDate {moreInfo}", ZDate.Today, newInvoice.ET_BillingDate);
					AssertEquals($"ET_OffBandProcessingStatus {moreInfo}", StorageOffBandProcessingStatus.Codes.QUE, newInvoice.ET_OffBandProcessingStatus);
					AssertEquals($"Should create job header for related branch {moreInfo}", newInvoice.Warehouse.RelatedCompanyBranch.GB_GC, new BusinessObjectFactory().Load<JobHeader>(new ZQuery(JobHeaderSchema.JH_ParentID, newInvoice.PK)).Single().JH_GC);
				}
			});
		}


		#region MockInvoiceHelperWithDefaultSetups

		public static Mock<IWhsInvoiceHelper> MockInvoiceHelperWithDefaultSetups(params WhsInvoice[] invoices)
		{
			var mutex = new Mock<IZGlobalMutex>();
			var helper = new Mock<IWhsInvoiceHelper>();
			helper.Setup(d => d.GetCandidateInvoices()).Returns(invoices.Select(i => new OrgWarehousePair { OrgPK = i.ET_OH_Client, WarehousePK = i.ET_WW, HasInvoice = true }));
			helper.Setup(d => d.GetQueuedInvoiceValidToProcessPKs()).Returns(invoices.Select(i => i.PK));
			helper.Setup(d => d.GetInvoiceBillingAutomationMutex(It.IsAny<ZGuid>())).Returns(mutex.Object);
			foreach (var invoice in invoices)
			{
				var pair = OrgWarehousePair.Create(invoice.ET_OH_Client, invoice.ET_WW);
				helper.Setup(d => d.GetByPK(invoice.PK)).Returns(invoice);
				helper.Setup(d => d.CreateInvoiceFromOrgWarehousePair(pair)).Returns(invoice);
				helper.Setup(d => d.OldestUnpostedInvoiceExists(pair)).Returns(false);
				helper.Setup(d => d.LoadInNewFactory(invoice.PK)).Returns(invoice);
				helper.Setup(d => d.GetInvoiceReferNumber(invoice)).Returns(() => new WhsInvoiceHelper().GetInvoiceReferNumber(invoice));
				helper.Setup(d => d.AutoRateJobHeader(It.IsAny<IAutoRatingServiceLogger>(), invoice)).Returns(true);
				helper.Setup(d => d.IsStillInQueueInDB(invoice.PK))
					.Returns(() => invoice.ET_OffBandProcessingStatus == StorageOffBandProcessingStatus.Codes.QUE);
			}
			return helper;
		}


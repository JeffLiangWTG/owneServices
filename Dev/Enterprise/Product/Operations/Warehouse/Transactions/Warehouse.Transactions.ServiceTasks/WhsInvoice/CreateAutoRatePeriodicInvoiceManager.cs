using System.Linq;
using System.Threading;
using CargoWise.Application;
using CargoWise.ComponentModel;
using CargoWise.EntityFramework;
using Enterprise.Integration;
using Enterprise.Warehouse.Environment.Business;
using Enterprise.Warehouse.Transactions.Business;
using Enterprise.Warehouse.Transactions.Invoicing;
using Enterprise.ZArchitecture.Schema;

namespace Enterprise.Warehouse.Transactions.ServiceTasks
{
	public class CreateAutoRatePeriodicInvoiceManager
	{
		public CreateAutoRatePeriodicInvoiceManager(ILogger logger)
		{
			Logger = logger;
		}
		readonly ILogger Logger;

		#region CreateQueuePeriodicInvoice

		public void CreateQueuePeriodicInvoice(CancellationToken token)
		{
			var whsInvoicePeriodicMultiClientInvoice = new WhsInvoicePeriodicMultiClientInvoice();
			var helper = ObjectFactory.Get<IWhsInvoiceHelper>();
			var candidateList = helper.GetCandidateInvoices().ToArray();
			var warehouses = new BusinessObjectFactory().Load<WhsWarehouse>(new ZQuery(WhsWarehouseSchema.PK, candidateList.Select(candidate => candidate.WarehousePK).Distinct()));
			foreach (var pair in candidateList)
			{
				token.ThrowIfCancellationRequested();
				using (WarehouseUserContextHelper.SetUserContextForWarehouse(warehouses.Single(whs => whs.PK == pair.WarehousePK)))
				{
					CreateAndSaveInvoice(whsInvoicePeriodicMultiClientInvoice, helper, pair, 1);
				}
			}

			if (!(candidateList.Length > 0))
			{
				Logger.Log(LogType.Information, "At this time, there are no invoices that need to be queued."); // Service Task Logging
			}
		}

		void CreateAndSaveInvoice(WhsInvoicePeriodicMultiClientInvoice whsInvoicePeriodicMultiClientInvoice, IWhsInvoiceHelper helper, OrgWarehousePair pair, int attempt)
		{
			var invoice = helper.CreateInvoiceFromOrgWarehousePair(pair);
			if (!pair.HasInvoice)
			{
				Logger.Information(Res.GetString("39a23e34-ee88-47b7-9e05-5725df532af6", "There is no pre-existing periodic for client '{0}' in warehouse '{1}', the first periodic should be generated by client.", invoice.ClientName, invoice.WarehouseName));
			}
			else if (!helper.OldestUnpostedInvoiceExists(pair))
			{
				invoice.RunPreSaveValidation();
				if (invoice.HasErrors)
				{
					Logger.Error(Res.GetString("0688C717-4176-4A5B-882A-942EE68E0808",
						"Invoice for client {0} warehouse {1} could not be created due to following errors: {2}",
						invoice.ClientName,
						invoice.WarehouseName,
						invoice.NotificationsIncludingChildren.GetErrors().ToUniqueMessageListString()));
				}
				else
				{
					var saveResult = helper.InvoiceSaveSafe(invoice, Logger, attempt);
					if (attempt == 1 && saveResult == InvoiceSaveSafeResult.SaveFailedRetry)
					{
						CreateAndSaveInvoice(whsInvoicePeriodicMultiClientInvoice, helper, pair, attempt + 1);
					}

					if (saveResult == InvoiceSaveSafeResult.SaveSuccessful)
					{
						Logger.Information(Res.GetString("15A2AEE1-F9EF-4AE7-9673-05CE30DD024A", "{0} - Created Queued Invoice for client {1} warehouse {2}.", helper.GetInvoiceReferNumber(invoice), invoice.ClientName, invoice.WarehouseName));
					}
				}
			}
		}

		#endregion

		#region WhsInvoicePeriodicMultiClientInvoice_InvoiceCreationComplete

		void WhsInvoicePeriodicMultiClientInvoice_InvoiceCreationComplete(object sender, TextEventArgs e) => Logger.Information(e.Message);

		#endregion
	}
}

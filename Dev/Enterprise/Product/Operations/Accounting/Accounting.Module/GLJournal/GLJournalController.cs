using System;
using CargoWise.EntityFramework;
using Enterprise.Accounting.Business.Base.Interfaces;
using Enterprise.Accounting.Business.Base.Reversing;
using Enterprise.Accounting.Business.Base.Transaction;
using Enterprise.Accounting.Business.GeneralLedger.GLJournals;
using Enterprise.Accounting.GUI.GeneralLedger.GLJournals;
using Enterprise.Environment;
using Enterprise.Security;
using Enterprise.ZArchitecture.Environment;
using Enterprise.ZArchitecture.GUI;
using Enterprise.ZArchitecture.Modules;

namespace Enterprise.Accounting.Module
{
	/// <summary>
	/// Module Controller for GLJournal.
	/// </summary>
	public partial class GLJournalController : ZController
	{
		public override bool MakeUrlsOnlyOpenableForCurrentCompany => true;

		public override ModuleIdentifier ModuleID
		{
			get { return ModuleIDs.GLJournal; }
		}

		public override ControllerID ID
		{
			get { return ControllerIDs.GLJournal; }
		}

		public override Type TypeOfTopLevelBusinessObject
		{
			get { return typeof(GLJournal); }
		}

		protected override bool DisallowMultiDeleteBecauseDeleteIsNotWhatIsReallyHappeningInAccounting => true;

		public override IZForm ShowDeleteForm(BusinessObject sourceEntity)
		{
			if (sourceEntity is IReversing)
			{
				var transaction = GetLoadedBusinessEntityInLocalFactory(sourceEntity);

				var glJournal = transaction as GLJournal;
				if (glJournal?.IsPeriodExists ?? false)
				{
					fReversing = GetAutoCurrencyAdjustmentReversing(transaction);
				}
				else
				{
					var revFactory = new ReversingFactory();
					fReversing = revFactory.NewReversing(transaction as IReversing);
				}

				if (fReversing == null)
				{
					return null;
				}

				if (!fReversing.CanReverseTransaction)
				{
					Globals.Message.ShowError(fReversing.CantReverseErrorMessage);
					return null;
				}

				return base.ShowDeleteForm(sourceEntity);
			}

			return null;
		}

		protected virtual ReversingBase GetAutoCurrencyAdjustmentReversing(IBusiness transaction)
		{
			return new ReversingFactory().NewReversing(transaction as IGeneralLedger);
		}

		protected ReversingBase fReversing;

		#region Implementation
		public override IZForm ShowEditForm(BusinessObject sourceEntity)
		{
			var journal = sourceEntity as GLJournal;
			if (journal.IsPeriodExists)
			{
				Globals.Message.Show(Res.GetString("BA3AF0FF-2233-4354-9341-A61764921641", "This journal is generated by the system in relation to the automated A/R and A/P outstanding balances currency adjustment, and cannot be edited."));
				return null;
			}

			var request = journal.GetPendingApprovalRequestByTransactionBelongsToGroup();
			if (request != null)
			{
				Globals.Message.Show(Res.GetString("F08E6403-664C-4B70-9419-0220DF90090E", "A reversed journal approval request ({0}) is linked to this journal, please cancel this approval request before editing this journal.", request.XP_RequestID));
				return null;
			}

			return journal.AH_IsCancelled ? base.ShowViewForm(journal) : base.ShowEditForm(journal);
		}

		protected override IZForm GetForm(IBusiness businessEntity)
		{
			if (fReversing != null)
			{
				fReversing.Reverse();
				var reverseJournal = fReversing.ReverseTransaction as GLJournal;
				return new GLJournalForm(reverseJournal);
			}

			return new GLJournalForm((GLJournal)businessEntity);
		}

		protected override SecurityCheckpoint CheckPointForView
		{
			get { return Env.Security.GeneralLedgerJournals; }
		}

		protected override SecurityCheckpoint CheckPointForEdit
		{
			get { return Env.Security.EditGeneralLedgerJournal; }
		}

		protected override SecurityCheckpoint CheckPointForNew
		{
			get { return Env.Security.NewGeneralLedgerJournal; }
		}

		protected override SecurityCheckpoint CheckPointForDelete
		{
			get { return Env.Security.None; }
		}

		#endregion
	}
}

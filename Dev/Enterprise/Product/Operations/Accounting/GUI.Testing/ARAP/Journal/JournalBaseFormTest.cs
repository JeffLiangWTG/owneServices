using System.Linq;
using System.Windows.Forms;
using Enterprise.Accounting.Business;
using Enterprise.Accounting.Business.ARAP.Journal;
using Enterprise.Accounting.GUI.Testing;
using Enterprise.Environment;
using Enterprise.MasterFiles.GUI.Testing;
using Enterprise.Registry.Business;
using Enterprise.ZArchitecture.GUI;
using Enterprise.ZArchitecture.Modules;
using NUnit.Framework;
using JournalBase = Enterprise.Accounting.Business.ARAP.Journal.Journal;

namespace Enterprise.Accounting.GUI.ARAP.Journal.Testing
{
	abstract class JournalBaseFormTest : AccountingZFormBasherTest
	{
		protected abstract JournalBase CreateJournalCore();

		protected override bool ShouldHaveAuditPlugIn => true;

		public void TestSubAccountsIsAutoGeneratedWithFormAction()
		{
			var journal1 = CreateJournalCore();
			var glHeader1 = TestObjectCreator.CreateGLHeader();
			TestObjectCreator.CreateGLHeaderSubAccount(glHeader1, ZArchitecture.Schema.OrgHeaderSchema.Constants.Prefix, false);
			journal1.AH_AG = glHeader1.PK;
			journal1.SubAccounts.Cast<JournalSubAccount>().FirstOrDefault().AHS_SubClassParentId = TestObjectCreator.AALSHI.PK;
			Factory.Save();

			AssertSubAccountsIsAutoGenenatedWithFormAction(journal1, true);
			AssertSubAccountsIsAutoGenenatedWithFormAction(journal1, false);
			TestObjectCreator.CreateGLHeaderSubAccount(glHeader1, ZArchitecture.Schema.GlbStaffSchema.Constants.Prefix, false);
			Factory.Save();

			var journal2 = (JournalBase)Factory.CreateNewFactory().Load(journal1.GetType(), journal1.PK);
			AssertSubAccountsIsAutoGenenatedWithFormAction(journal2, true);
			AssertSubAccountsIsAutoGenenatedWithFormAction(journal2, false);

			void AssertSubAccountsIsAutoGenenatedWithFormAction(JournalBase journal, bool isViewForm)
			{
				var controller = ZControllerFactory.Create(journal.GetType() == typeof(APJournal) ? ControllerIDs.APJournal : ControllerIDs.ARJournal);
				using (var form = (isViewForm ? controller.ShowViewForm(journal) : controller.ShowEditForm(journal)))
				{
					Application.DoEvents();
					AssertType<JournalBaseForm>(form);
					var formJournal = (JournalBase)((JournalBaseForm)form).BusinessEntity;

					AssertEquals("IsInDatabaseIncludingChildren", true, formJournal.IsInDatabaseIncludingChildren);
					AssertEquals("HasChanges", false, formJournal.HasChanges);
					AssertEquals("Sub Account Count", 1, formJournal.SubAccounts.Count);
				}
			}
		}

		public void TestAgreedPaymentMethodField()
		{
			var journal = CreateJournalCore();
			var glHeader = TestObjectCreator.CreateGLHeader();
			journal.AH_AG = glHeader.PK;
			Factory.Save();

			bool isPayable = journal.GetType() == typeof(APJournal);

			var controller = ZControllerFactory.Create(isPayable ? ControllerIDs.APJournal : ControllerIDs.ARJournal);
			using (var form = controller.ShowEditForm(journal))
			{
				Application.DoEvents();
				AssertType<JournalBaseForm>(form);
				var formJournal = (JournalBaseForm)form;

				var apmControl = formJournal.GetControl<ZDropEdit>("AgreedPaymentDropEdit");
				AssertNotNull(apmControl);
				Assert(apmControl.Visible);
				AssertContains("Agreed Payment Method", apmControl.CaptionResourceString.Caption);

				var registry = isPayable ? Env.Registry.PayablesCreditAgreedPaymentMethodsList : OrganisationsDataRegistry.Instance.ReceivablesCreditAgreedPaymentMethodsList.Value.GetCodeDescriptionPairList();
				AssertEquals(registry.Count, apmControl.List.Count);
			}
		}

		public void TestFormBorderStyle()
		{
			var journal = CreateJournalCore();
			var glHeader = TestObjectCreator.CreateGLHeader();
			journal.AH_AG = glHeader.PK;
			Factory.Save();

			bool isPayable = journal.GetType() == typeof(APJournal);

			var controller = ZControllerFactory.Create(isPayable ? ControllerIDs.APJournal : ControllerIDs.ARJournal);
			using (var form = (ZForm)controller.ShowEditForm(journal))
			{
				AssertEquals(FormBorderStyle.Sizable, form.FormBorderStyle);
			}
		}
	}

	[TestedType(typeof(JournalBaseForm))]
	class TestAR : JournalBaseFormTest
	{
		protected override Form GetFormToBashCore() => new JournalBaseForm(CreateJournalCore());

		protected override JournalBase CreateJournalCore() => (JournalBase)Factory.New(typeof(ARJournal));
	}

	[TestedType(typeof(JournalBaseForm))]
	class TestAP : JournalBaseFormTest
	{
		protected override Form GetFormToBashCore() => new JournalBaseForm(CreateJournalCore());

		protected override JournalBase CreateJournalCore() => (JournalBase)Factory.New(typeof(APJournal));
	}
}

		public void TestIsInvoiceCanBePartlyPaid()
		{
			string message = "This transaction with different branches in lines is being partly paid without matching lines. Clearing Journal Configuration is set to create journals by line branches. To create Clearing Journal lines the transaction paid amount will be divided proportionally to transaction line amounts.";

			Action<string, string> assertError = (configurationCode, expectedMessage) =>
				{
					string messageForError = string.Format("Should return {0} when ClearingJournalConfiguration is set to '{1}'", string.IsNullOrEmpty(expectedMessage) ? "empty string" : "message", configurationCode);
					string messageWithoutError = string.Format("Should return empty string when ClearingJournalConfiguration is set to '{0}'", configurationCode);
					AccountingConfigurationRegistry.Instance.ClearingJournalConfiguration.SetValue(Guid.Empty, Guid.Empty, Guid.Empty, configurationCode);
					var invoice = TestObjectCreator.CreateInvoice(typeof(ARInvoice), "INV3", TestObjectCreator.USD, 0.5M);
					var line1 = TestObjectCreator.CreateInvoiceLine(invoice, TestObjectCreator.USD, 0.5M, 100M, Branch3.PK);
					var line2 = TestObjectCreator.CreateInvoiceLine(invoice, TestObjectCreator.USD, 0.5M, -100M, Branch3.PK);
					var line3 = TestObjectCreator.CreateInvoiceLine(invoice, TestObjectCreator.USD, 0.5M, 300M, Branch3.PK);
					((IMatching)invoice).OSPartialPaymentAmount = 50M;
					AssertEquals(messageWithoutError, "", DynamicTransactionCreatorClearingJournal.IsInvoiceCanBePartlyPaid(invoice));

					line2.AL_GB = Branch1.PK;
					AssertEquals(messageForError, expectedMessage, DynamicTransactionCreatorClearingJournal.IsInvoiceCanBePartlyPaid(invoice));

					((IMatching)invoice).OSPartialPaymentAmount = 330M;
					AssertEquals(messageWithoutError, "", DynamicTransactionCreatorClearingJournal.IsInvoiceCanBePartlyPaid(invoice));

					invoice.AH_OSTaxAmountOtherTaxes = 20M;
					invoice.AH_LocalTaxAmountOtherTaxes = 10M;
					AssertEquals(messageForError, expectedMessage, DynamicTransactionCreatorClearingJournal.IsInvoiceCanBePartlyPaid(invoice));

					APMatchingBase matchingBase = new APMatchingBase(Factory);
					matchingBase.MatchedTransactions.Add(invoice);
					InvoicingBasePayLineMediator payLineMediator = new InvoicingBasePayLineMediator(matchingBase, invoice);
					payLineMediator.Lines[0].PaidAmount = 10M;
					payLineMediator.Lines[1].PaidAmount = -10M;
					payLineMediator.Lines[2].PaidAmount = 0M;
					AssertNotEquals("Precondition: Lines[0].LocalPaidAmount", 0M, payLineMediator.Lines[0].LocalPaidAmount);
					AssertNotEquals("Precondition: Lines[1].LocalPaidAmount", 0M, payLineMediator.Lines[1].LocalPaidAmount);
					AssertEquals("Precondition: Lines[2].LocalPaidAmount", 0M, payLineMediator.Lines[2].LocalPaidAmount);
					AssertEquals(messageWithoutError, "", DynamicTransactionCreatorClearingJournal.IsInvoiceCanBePartlyPaid(invoice));

					payLineMediator.Lines[0].PaidAmount = 0M;
					AssertEquals(messageWithoutError, "", DynamicTransactionCreatorClearingJournal.IsInvoiceCanBePartlyPaid(invoice));

					payLineMediator.Lines[1].PaidAmount = 0M;
					AssertEquals("Precondition: Lines[0].LocalPaidAmount", 0M, payLineMediator.Lines[0].LocalPaidAmount);
					AssertEquals("Precondition: Lines[1].LocalPaidAmount", 0M, payLineMediator.Lines[1].LocalPaidAmount);
					AssertEquals("Precondition: Lines[2].LocalPaidAmount", 0M, payLineMediator.Lines[2].LocalPaidAmount);
					AssertEquals(messageWithoutError, expectedMessage, DynamicTransactionCreatorClearingJournal.IsInvoiceCanBePartlyPaid(invoice));

					line1.TransLinePays.AddNew().A7_Amount = 10M;
					line2.TransLinePays.AddNew().A7_Amount = -10M;
					AssertNotEquals("Precondition: line1.TransLinePaysTotalAmount", 0M, line1.TransLinePaysTotalAmount);
					AssertNotEquals("Precondition: line2.TransLinePaysTotalAmount", 0M, line2.TransLinePaysTotalAmount);
					AssertEquals("Precondition: line3.TransLinePaysTotalAmount", 0M, line3.TransLinePaysTotalAmount);
					AssertEquals(messageWithoutError, "", DynamicTransactionCreatorClearingJournal.IsInvoiceCanBePartlyPaid(invoice));

					line1.TransLinePays.DeleteAll();
					AssertEquals(messageWithoutError, "", DynamicTransactionCreatorClearingJournal.IsInvoiceCanBePartlyPaid(invoice));

					line2.TransLinePays.DeleteAll();
					AssertEquals("Precondition: line1.TransLinePaysTotalAmount", 0M, line1.TransLinePaysTotalAmount);
					AssertEquals("Precondition: line2.TransLinePaysTotalAmount", 0M, line2.TransLinePaysTotalAmount);
					AssertEquals("Precondition: line3.TransLinePaysTotalAmount", 0M, line3.TransLinePaysTotalAmount);
					AssertEquals(messageWithoutError, expectedMessage, DynamicTransactionCreatorClearingJournal.IsInvoiceCanBePartlyPaid(invoice));
				};

			foreach (CodeDescriptionPair codeDescPair in new AccountingConstants.ClearingJournalConfigurationTypes())
			{
				if (codeDescPair.Code == AccountingConstants.ClearingJournalConfigurationTypes.LineBranchPerHeader.Code ||
					codeDescPair.Code == AccountingConstants.ClearingJournalConfigurationTypes.LineBranchPerMatching.Code)
				{
					assertError(codeDescPair.Code, message);
				}
				else
				{
					assertError(codeDescPair.Code, "");
				}
			}
		}


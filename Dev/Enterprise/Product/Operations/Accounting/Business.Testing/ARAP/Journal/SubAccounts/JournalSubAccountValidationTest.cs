using System;
using System.Linq;
using CargoWise.EntityFramework.Testing;
using CargoWise.Types;
using Enterprise.Accounting.Business.ARAP.Journal;
using Enterprise.ZArchitecture.Schema;
using NUnit.Framework;

namespace Enterprise.Accounting.Business.Testing
{
	public abstract class JournalSubAccountValidationTest : BusinessObjectValidationTestCase
	{
		public void TestCheckAHS_SubClassParentId()
		{
			var glHeader = TestObjectCreator.CreateGLHeader();
			var glHeaderSubAccount1 = TestObjectCreator.CreateGLHeaderSubAccount(glHeader, OrgHeaderSchema.Constants.Prefix, true);
			var glHeaderSubAccount2 = TestObjectCreator.CreateGLHeaderSubAccount(glHeader, GlbStaffSchema.Constants.Prefix, false);

			var checkedEnterMessage = "Please enter a Sub Account.";
			var journal = CreateJournalCore();

			journal.AH_AG = glHeader.PK;
			var firstSubAccount = journal.SubAccounts.Cast<JournalSubAccount>().OrderBy(x => x.AHS_Calc_Sequence).FirstOrDefault();
			var secondSubAccount = journal.SubAccounts.Cast<JournalSubAccount>().OrderBy(x => x.AHS_Calc_Sequence).Skip(1).FirstOrDefault();

			AssertEquals("first AHS_SubClassParentId", ZGuid.Empty, firstSubAccount.AHS_SubClassParentId);
			AssertEquals("secondSubAccount AHS_SubClassParentId", ZGuid.Empty, secondSubAccount.AHS_SubClassParentId);

			AssertHasError("first AHS_SubClassParentId should be errors when AHS_SubClassParentId is empty and relate to ASA_IsSubClassValidationRuleMandatory is true.", firstSubAccount.AHS_SubClassParentIdInfo, checkedEnterMessage);
			AssertNoErrors("second AHS_SubClassParentId should be no errors when AHS_SubClassParentId is empty and relate to ASA_IsSubClassValidationRuleMandatory is false.", secondSubAccount.AHS_SubClassParentIdInfo);

			var organizationPK = TestObjectCreator.Creditor1.PK;
			var staffPK = TestObjectCreator.Staff.PK;
			firstSubAccount.AHS_SubClassParentId = organizationPK;
			secondSubAccount.AHS_SubClassParentId = staffPK;

			AssertEquals("first AHS_SubClassParentId", organizationPK, firstSubAccount.AHS_SubClassParentId);
			AssertEquals("secondSubAccount AHS_SubClassParentId", staffPK, secondSubAccount.AHS_SubClassParentId);

			AssertNoErrors("first AHS_SubClassParentId should be no errors when AHS_SubClassParentId is not empty and relate to ASA_IsSubClassValidationRuleMandatory is true.", firstSubAccount.AHS_SubClassParentIdInfo);
			AssertNoErrors("second AHS_SubClassParentId should be no errors when AHS_SubClassParentId is not empty and relate to ASA_IsSubClassValidationRuleMandatory is false.", secondSubAccount.AHS_SubClassParentIdInfo);

			journal.IsAutoGenerated = true;
			firstSubAccount.AHS_SubClassParentId = Guid.Empty;
			AssertNoErrors("first AHS_SubClassParentId should be no errors when AHS_SubClassParentId is empty and IsAutoGenerated is true.", firstSubAccount.AHS_SubClassParentIdInfo);
		}

		protected abstract Journal CreateJournalCore();

		TestObjectCreator TestObjectCreator => testObjectCreator ?? (testObjectCreator = new TestObjectCreator(Factory));
		TestObjectCreator testObjectCreator;

		public class APJournalSubAccountValidationTest : JournalSubAccountValidationTest
		{
			[TestDate(2020, 3, 11)]
			protected override Journal CreateJournalCore()
			{
				return TestObjectCreator.CreateJournal<APJournal>(0m, ZDateTime.Today, TestObjectCreator.ABIGAS.PK);
			}
		}

		public class ARJournalSubAccountValidationTest : JournalSubAccountValidationTest
		{
			[TestDate(2020, 3, 11)]
			protected override Journal CreateJournalCore()
			{
				return TestObjectCreator.CreateJournal<ARJournal>(0m, ZDateTime.Today, TestObjectCreator.ABIGAS.PK);
			}
		}
	}
}

		public void TestGetLoadedBusinessEntityInLocalFactoryCore2()
		{
			var controller = new DepositBatchController();
			var depositBatch = Factory.NewWithValidTestData<DepositBatch>();
			Factory.Save();

			var bizo1 = controller.GetLoadedBusinessEntityInLocalFactoryCore2_ForTestOnly(depositBatch);
			AssertEquals(typeof(DepositBatchParent), bizo1.GetType());
			Assert(((DepositBatchParent)bizo1).IsExistingBatch);

			var depositBatch2 = Factory.NewWithValidTestData<DepositBatch>();
			Factory.Save();

			var parent = new DepositBatchParent(Factory, depositBatch2);
			var bizo2 = controller.GetLoadedBusinessEntityInLocalFactoryCore2_ForTestOnly(parent);
			AssertEquals(parent, bizo2);
		}


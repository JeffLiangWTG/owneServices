		public void TestShowDeleteForm()
		{
			var testReceipt = TestObjectCreator.CreateARReceipt(ZArchitecture.Core.ReceiptTypes.Cash, ZArchitecture.Core.TransactionTypes.Receipt, ZArchitecture.Core.LedgerTypes.AccountsReceivable, 100M, TestObjectCreator.AUDBankAccount.PK);
			Factory.Save();

			var testDepositBatch = Factory.New<DepositBatch>();
			testDepositBatch.AH_AB = TestObjectCreator.AUDBankAccount.PK;
			testDepositBatch.LoadTransactions(ZGuid.Empty);
			Factory.Save();

			UnitTestUserNotification.Instance.ClearMessagesAndAnswers();

			using (IZForm testForm = Controller.ShowDeleteForm(testDepositBatch))
			{
				AssertNull(UnitTestUserNotification.Instance.LastMessage.Text);
			}

			testDepositBatch.AH_IsCancelled = true;
			using (IZForm testForm = Controller.ShowDeleteForm(testDepositBatch))
			{
				AssertEquals("This transaction has already been canceled.", UnitTestUserNotification.Instance.LastMessage.Text);
			}
		}

		public void TestShowDeleteFormHasDirectCreditReceipt()
		{
			ARReceipt testReceipt = TestObjectCreator.CreateARReceipt(ZArchitecture.Core.ReceiptTypes.DirectCredit, ZArchitecture.Core.TransactionTypes.Receipt, ZArchitecture.Core.LedgerTypes.AccountsReceivable, 100M, TestObjectCreator.AUDBankAccount.PK);
			Factory.Save();

			ZQuery filter = new ZQuery(AccTransactionHeaderSchema.AH_TransactionType, ZArchitecture.Core.TransactionTypes.ReceiptBatch);
			filter.AddToFilter(AccTransactionHeaderSchema.AH_TransactionNum, testReceipt.AH_ReceiptBatchNo);

			DepositBatch testBatch = Factory.LoadTop1<DepositBatch>(filter);

			UnitTestUserNotification.Instance.ClearMessagesAndAnswers();

			using (IZForm testForm = Controller.ShowDeleteForm(testBatch))
			{
				AssertEquals("This Deposit Batch was automatically generated by a Direct Credit (DCR) receipts posting and cannot be canceled. You can, however, reverse this batch by reversing the transaction itself.", UnitTestUserNotification.Instance.LastMessage.Text);
			}
		}

		public void TestShowDeleteFormHasCancelledReceipt()
		{
			ARReceipt testReceipt = TestObjectCreator.CreateARReceipt(ZArchitecture.Core.ReceiptTypes.DirectCredit, ZArchitecture.Core.TransactionTypes.Receipt, ZArchitecture.Core.LedgerTypes.AccountsReceivable, 100M, TestObjectCreator.AUDBankAccount.PK);
			Factory.Save();
			testReceipt.AH_IsCancelled = true;
			((IMatching)testReceipt).CurrentMatchGroup.AddNew().AP_AH = testReceipt.PK;
			TestObjectCreator.SetupMatchLinkMatchDate(testReceipt);
			Factory.Save();

			ZQuery filter = new ZQuery(AccTransactionHeaderSchema.AH_TransactionType, ZArchitecture.Core.TransactionTypes.ReceiptBatch);
			filter.AddToFilter(AccTransactionHeaderSchema.AH_TransactionNum, testReceipt.AH_ReceiptBatchNo);

			DepositBatch testBatch = Factory.LoadTop1<DepositBatch>(filter);

			UnitTestUserNotification.Instance.ClearMessagesAndAnswers();

			using (IZForm testForm = Controller.ShowDeleteForm(testBatch))
			{
				AssertEquals("You are not allowed to cancel this Deposit Batch as it contains canceled receipts that were reversed subsequent to batching. A separate batch for any reversed receipt was created at the time of reversal.", UnitTestUserNotification.Instance.LastMessage.Text);
			}
		}

		[TestDate(1999, 7, 2)]
		public void TestShowDeleteFormSubLedgerClosed_And_ClearedInCashbook()
		{
			var testManager = TestObjectCreator.CreateTestPeriods(new ZDateTime(1999, 6, 1));
			Factory.Save();
			var testReceipt = TestObjectCreator.CreateARReceipt(ZArchitecture.Core.ReceiptTypes.Cash, ZArchitecture.Core.TransactionTypes.Receipt, ZArchitecture.Core.LedgerTypes.AccountsReceivable, 100M, TestObjectCreator.AUDBankAccount.PK);
			Factory.Save();

			var testDepositBatchParent = new DepositBatchParent(Factory);
			var firstBatchPK = testDepositBatchParent.DepositBatchLines[0].PK;
			testDepositBatchParent.DepositBatchLines[0].AH_PostDate = new ZDateTime(1999, 6, 1);
			Factory.Save();

			var testDepositBatch = Factory.Load<DepositBatch>(firstBatchPK);
			Assert("Precondition: IsIsCancelled should be false", !testDepositBatch.IsCancelled);

			UnitTestUserNotification.Instance.ClearMessagesAndAnswers();

			testManager.CloseSubLedgerPeriod();

			using (IZForm testForm = Controller.ShowDeleteForm(testDepositBatch))
			{
				AssertEquals("This deposit batch cannot be canceled as the sub-ledger period where the batch has been posted to is closed.", UnitTestUserNotification.Instance.LastMessage.Text);
			}

			testDepositBatch.AH_PostDate = new ZDateTime(1999, 7, 1);
			testDepositBatch.AH_DateClearedInCashbook = new ZDateTime(2006, 2, 15);

			using (ServiceContainerSuspenderHelper.FunctionalitySuspender<ServiceContainerSuspenderHelper.PostDateCriticalValidationSuspenderService>.GetSuspender(Factory))
			{
				Factory.Save();
			}

			UnitTestUserNotification.Instance.ClearMessagesAndAnswers();

			using (IZForm testForm = Controller.ShowDeleteForm(testDepositBatch))
			{
				AssertEquals("This deposit batch cannot be canceled as the batch has been reconciled.", UnitTestUserNotification.Instance.LastMessage.Text);
			}
		}


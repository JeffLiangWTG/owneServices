	[TestedType(typeof(GLJournalController))]
	public class GLJournalControllerTest : ZControllerBasherTest
	{
		protected override ControllerID GetControllerID()
		{
			return ControllerIDs.GLJournal;
		}

		protected override BusinessObject GetBusinessObjectThatIsInTheDatabase()
		{
			GLJournal result = Factory.New<GLJournal>();
			Factory.Save();
			return result;
		}

		public override void TestEditForm()
		{
			var sourceEntity = GetBusinessObjectThatIsInTheDatabase() as GLJournal;
			sourceEntity.PeriodPK = Factory.NewWithValidTestData<AccPeriodManagement>().PK;
			AssertNull("EditForm should be null", Controller.ShowEditForm(sourceEntity));
			AssertEquals("This journal is generated by the system in relation to the automated A/R and A/P outstanding balances currency adjustment, and cannot be edited.", UnitTestUserNotification.Instance.LastMessage.Text);
			UnitTestUserNotification.Instance.ClearMessagesAndAnswers();
			sourceEntity.PeriodPK = ZGuid.Empty;

			var approvalRequest = Factory.NewWithValidTestData<GLJournalApprovalRequest>();
			approvalRequest.XP_ApprovalStatus = Core.Constants.GenApprovalRequestApprovalStatus.Requested;
			sourceEntity.AH_TransactionBelongsToGroup = approvalRequest.PK;
			AssertNull("EditForm should be null", Controller.ShowEditForm(sourceEntity));
			AssertEquals($"A reversed journal approval request ({approvalRequest.XP_RequestID}) is linked to this journal, please cancel this approval request before editing this journal.", UnitTestUserNotification.Instance.LastMessage.Text);
			UnitTestUserNotification.Instance.ClearMessagesAndAnswers();
			sourceEntity.AH_TransactionBelongsToGroup = Guid.Empty;

			sourceEntity.AH_IsCancelled = true;
			using (var form = Controller.ShowEditForm(sourceEntity))
			{
				AssertNotNull("Form should not be null", form);
				AssertEquals(ODisplayMode.ReadOnly, form.DisplayMode);
			}

			sourceEntity.AH_IsCancelled = false;
			using (var form = Controller.ShowEditForm(sourceEntity))
			{
				AssertNotNull("Form should not be null", form);
				AssertNotEquals(ODisplayMode.ReadOnly, form.DisplayMode);
			}
		}

		public void TestGetForm()
		{
			var journal = Factory.NewWithValidTestData<GLJournal>();
			journal.Lines.AddNew();
			JournalController.FReversing_ForTestOnly = null;
			using (var form = (ZForm)JournalController.GetForm_ForTestOnly(journal))
			{
				AssertEquals("Form's business entity should be the transaction journal", journal.PK, form.BusinessEntity.Identifier);
			}

			JournalController.FReversing_ForTestOnly = new GLJournalReversing(journal);
			using (var form = (ZForm)JournalController.GetForm_ForTestOnly(journal))
			{
				Assert("Form's business entity should be a reversing journal", journal.PK != form.BusinessEntity.Identifier);
			}
		}

		public void TestShowDeleteFormForAdjustmentReversing()
		{
			var gLAccount1 = Factory.NewWithValidTestData<AccGLHeader>();
			var gLAccount2 = Factory.NewWithValidTestData<AccGLHeader>();
			AccPeriodManagement period = Factory.NewWithValidTestData<AccPeriodManagement>();

			var journal = Factory.NewWithValidTestData<GLJournal>();
			journal.PeriodPK = period.PK;
			var line1 = (GLJournalLine)journal.Lines.AddNew();
			line1.AL_AG = gLAccount1.PK;
			line1.AL_OSExTaxAmount = 10m;
			line1.AL_LocalExTaxAmount = 10m;
			var line2 = (GLJournalLine)journal.Lines.AddNew();
			line2.AL_AG = gLAccount2.PK;
			line2.AL_OSExTaxAmount = -10m;
			line2.AL_LocalExTaxAmount = -10m;
			Factory.Save();

			using (var journalForm = (GLJournalForm)JournalController.ShowDeleteForm(journal))
			{
				AssertNotNull("FReversing_ForTestOnly should be set on the controller", JournalController.FReversing_ForTestOnly);
				var reversingGLJournal = journalForm.BusinessEntity as GLJournal;
				Assert("The form should show the reversing GLJournal", reversingGLJournal.PK != journal.PK);
				AssertEquals("There should be 2 lines in the Reversing GLJournal", 2, reversingGLJournal.Lines.Count);
				var revLine1 = (GLJournalLine)reversingGLJournal.Lines.Find(new ZQuery(AccTransactionLinesSchema.AL_AG, gLAccount1.PK))[0];
				AssertEquals("Line1 should have OS amount -10", -10m, revLine1.AL_OSExTaxAmount);
				AssertEquals("Line1 should have Local amount -10", -10m, revLine1.AL_LocalExTaxAmount);

				var revLine2 = (GLJournalLine)reversingGLJournal.Lines.Find(new ZQuery(AccTransactionLinesSchema.AL_AG, gLAccount2.PK))[0];
				AssertEquals("Line2 should have OS amount 10", 10m, revLine2.AL_OSExTaxAmount);
				AssertEquals("Line2 should have Local amount 10", 10m, revLine2.AL_LocalExTaxAmount);
			}

			journal.AH_IsCancelled = true;
			using (var journalForm2 = JournalController.ShowDeleteForm(journal))
			{
				AssertNull("cannot reverse an already reversed journal", journalForm2);
				AssertEquals("This transaction cannot be reversed because it has already been reversed or is a reversal of another transaction.", UnitTestUserNotification.Instance.LastMessage.Text);
			}
		}

		public void TestShowDeleteForm()
		{
			var gLAccount1 = Factory.NewWithValidTestData<AccGLHeader>();
			var gLAccount2 = Factory.NewWithValidTestData<AccGLHeader>();

			var journal = Factory.NewWithValidTestData<GLJournal>();
			var line1 = (GLJournalLine)journal.Lines.AddNew();
			line1.AL_AG = gLAccount1.PK;
			line1.AL_OSExTaxAmount = 10m;
			line1.AL_LocalExTaxAmount = 10m;
			var line2 = (GLJournalLine)journal.Lines.AddNew();
			line2.AL_AG = gLAccount2.PK;
			line2.AL_OSExTaxAmount = -10m;
			line2.AL_LocalExTaxAmount = -10m;
			Factory.Save();

			using (GLJournalForm journalForm = (GLJournalForm)Controller.ShowDeleteForm(journal))
			{
				AssertNotNull("FReversing_ForTestOnly should be set on the controller", ((GLJournalController)Controller).FReversing_ForTestOnly);
				var reversingGLJournal = journalForm.BusinessEntity as GLJournal;
				Assert("The form should show the reversing GLJournal", reversingGLJournal.PK != journal.PK);
				AssertEquals("There should be 2 lines in the Reversing GLJournal", 2, reversingGLJournal.Lines.Count);
				var revLine1 = (GLJournalLine)reversingGLJournal.Lines.Find(new ZQuery(AccTransactionLinesSchema.AL_AG, gLAccount1.PK)).First();
				AssertEquals("Line1 should have OS amount -10", -10m, revLine1.AL_OSExTaxAmount);
				AssertEquals("Line1 should have Local amount -10", -10m, revLine1.AL_LocalExTaxAmount);

				var revLine2 = (GLJournalLine)reversingGLJournal.Lines.Find(new ZQuery(AccTransactionLinesSchema.AL_AG, gLAccount2.PK)).First();
				AssertEquals("Line2 should have OS amount 10", 10m, revLine2.AL_OSExTaxAmount);
				AssertEquals("Line2 should have Local amount 10", 10m, revLine2.AL_LocalExTaxAmount);
			}
		}

		protected GLJournalController JournalController => Controller as GLJournalController;
	}

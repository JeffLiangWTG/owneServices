using Enterprise.MasterFiles.Business;

namespace Enterprise.Accounting.Business.ARAP.Journal
{
	public class JournalSubAccountValidation : AccTransactionHeaderSubAccountValidation
	{
		public JournalSubAccountValidation(JournalSubAccount parent) : base(parent)
		{
			Parent = parent;
		}

		protected new JournalSubAccount Parent;

		protected override void CheckAHS_SubClassParentIdIsNotEmpty()
		{
		}

		protected override void CheckAHS_SubClassParentId()
		{
			if (Parent.Parent != null && !Parent.Parent.IsAutoGenerated)
			{
				base.CheckAHS_SubClassParentId();
				SubAccountHelper.ValidateSubClassParentId(Parent.AHS_SubClassParentIdInfo, Parent.AHS_SubClassParentTableCode, Parent.SubAccountParent);
			}
		}
	}
}

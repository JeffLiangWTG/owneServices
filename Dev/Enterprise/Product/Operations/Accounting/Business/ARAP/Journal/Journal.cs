		void SetDescriptionAndAccountFromTransactionCategory(ZString value)
		{
			switch (value)
			{
				case Constants.TransactionCategory.Codes.TransactionNotFound:
				case Constants.TransactionCategory.Codes.TransactionAlreadyPaid:
					AH_Desc = ZString.Empty;
					AH_AG = MatchingAccount;
					break;
				case Constants.TransactionCategory.Codes.WithholdingTax:
					AH_Desc = Constants.TransactionCategory.Descriptions.WithholdingTax.ToString().ToUpper();
					AH_AG = WHTAccount;
					break;
				case Constants.TransactionCategory.Codes.Standard:
					AH_Desc = JournalDefaultDescription;
					AH_AG = JournalAccountDefault;
					break;
			}
			AH_DescInfo.RefreshBinding();
			AH_AGInfo.RefreshBinding();
		}

		protected ZString DebitCreditSignFromTransactionCategory()
		{
			ZString value = AH_TransactionCategory;
			if (value == Constants.TransactionCategory.Codes.TransactionNotFound ||
				value == Constants.TransactionCategory.Codes.TransactionAlreadyPaid ||
				value == Constants.TransactionCategory.Codes.ClearingJournal)
			{
				return GetOppositeDebitCreditSign(DebitCreditSignDefault);
			}
			else
			{
				return DebitCreditSignDefault;
			}
		}

		public ZString GetOppositeDebitCreditSign(ZString sign)
		{
			return sign == DR ? CR : DR;
		}


		[MaxLength(2)]
		[List("DebitCreditSign_List")]
		public ZString DebitCreditSign
		{
			get
			{
				return fDebitCreditSign;
			}
			set
			{
				if (fDebitCreditSign != value)
				{
					CheckMaximumLength(DebitCreditSignInfo, value);

					// The following code is so that the values in the database are correct
					// Get the true values of LocalExTax, OSExTax and LocalOutstanding
					ZDecimal localExTaxTmp = AH_LocalExTaxAmount;
					ZDecimal localOutstandingTmp = AH_LocalOutstandingAmount;
					ZDecimal oSExTaxTmp = AH_OSExTaxAmount;
					ZDecimal exchangeRateTmp = AH_ExchangeRate;

					fDebitCreditSign = value;
					DebitCreditSignInfo.RefreshBinding(); // Note: doing this changes the Multiplier

					// Reset the values of LocalExTax, OSExTax and LocalOutstanding
					// using the new value of DR/CR
					AH_OSExTaxAmount = oSExTaxTmp;
					AH_ExchangeRate = exchangeRateTmp;
					AH_LocalExTaxAmount = localExTaxTmp;
					AH_LocalOutstandingAmount = localOutstandingTmp;

					JournalValidation journalValidation = Validation as JournalValidation;
					if (journalValidation != null)
					{
						journalValidation.ValidateDebitCreditSign();
					}

					if (RelatedJournal != null)
					{
						RelatedJournal.DebitCreditSign = GetOppositeDebitCreditSign(value);
					}
				}
			}
		}


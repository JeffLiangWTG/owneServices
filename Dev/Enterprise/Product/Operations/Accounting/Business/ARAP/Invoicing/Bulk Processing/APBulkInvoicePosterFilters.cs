		public override ZQuery Filter
		{
			get
			{
				Helper.ResetUniqueParameterNumber();
				ZDBOnlyQuery result = new ZDBOnlyQuery(typeof(AccTransactionLines));
				result.AddToFilter(AccTransactionLinesSchema.AL_LineType, SQLComparisonOperator.Equal, TransactionLineTypes.Accrual);
				result.AddToFilter(AccTransactionLinesSchema.AL_ReverseDate, SQLComparisonOperator.Equal, null);
				result.AddToFilter(AccTransactionLinesSchema.AL_GC, SQLComparisonOperator.Equal, GlbCompany.CurrentCompany.PK);

				result.AddToFilter(base.Filter);
				return result;
			}
		}


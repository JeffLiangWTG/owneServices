		ModuleFilterSubGroup ContainerNumberSubGroup
		{
			get { return containerNumberSubGroup ?? (containerNumberSubGroup = new ContainerNumberSubGroupImplementation(ModuleFilterSubGroup.Default)); }
		}
		ModuleFilterSubGroup containerNumberSubGroup;

		class ContainerNumberSubGroupImplementation : ModuleFilterSubGroup
		{
			public ContainerNumberSubGroupImplementation(ModuleFilterSubGroup parent)
				: base(parent) { }

			public override ZQuery GetSubQuery(ZQuery filter)
			{
				var containerNumberSubGroupQuery = new ZDBOnlyQuery(typeof(AccTransactionLines));

				var transactionLinesSubQuery = new ZDBOnlySubQuery(typeof(JobHeader), AccTransactionLinesSchema.AL_JH);
				var jobHeaderSubQuery = new ZDBOnlySubQuery(typeof(ForwardingShipment), JobHeaderSchema.JH_ParentID);
				jobHeaderSubQuery.AddToFilter(JobShipmentSchema.JS_IsShipping, 0);
				var jobConShipLinkSubQuery = new ZDBOnlySubQuery(typeof(JobConShipLink), JobConShipLinkSchema.JN_JS);
				var consolSubQuery = new ZDBOnlySubQuery(typeof(ForwardingConsol), JobConShipLinkSchema.JN_JK);
				var containerSubQuery = new ZDBOnlySubQuery(typeof(ForwardingContainer), JobContainerSchema.JC_JK);
				containerSubQuery.AddToFilter(filter);

				consolSubQuery.AddSubQuery(containerSubQuery, JoinCondition.And);
				jobConShipLinkSubQuery.AddSubQuery(consolSubQuery, JoinCondition.And);
				jobHeaderSubQuery.AddSubQuery(jobConShipLinkSubQuery, JoinCondition.And);
				transactionLinesSubQuery.AddSubQuery(jobHeaderSubQuery, JoinCondition.And);

				containerNumberSubGroupQuery.AddSubQuery(transactionLinesSubQuery, JoinCondition.And);
				return containerNumberSubGroupQuery;
			}
		}


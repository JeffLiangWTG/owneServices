		class ConsolSubGroupImplementation : ModuleFilterSubGroup
		{
			public ConsolSubGroupImplementation(APBulkInvoicePosterFilters filter)
				: base()
			{
				this.Filter = filter;
			}

			readonly APBulkInvoicePosterFilters Filter;

			public override ZQuery GetSubQuery(ZQuery filter)
			{
				var result = new ZDBOnlyQuery(typeof(AccTransactionLines));
				string query = jobConsolQuery + filter.GetAsWhereClause(false) + ")";
				ZSqlParameterCollection parameters = new ZSqlParameterCollection(filter.Params);
				Filter.Helper.ReplaceAutogeneratedParameters(ref query, parameters);
				result.AddFilterAndZSQLParameterCollection(query, parameters);

				return result;
			}
		}


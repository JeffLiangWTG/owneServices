			guidfilter.Category = FilterCategories.Organisations;
			guidfilter.MultilingualDescription = APSettlementGroup;
			guidfilter.SubGroup = APSettlementGroupSubGroup;
		}

		protected override void AddOtherOperationsFilters(ModuleFilterCollection filters)

		protected override ZQuery GetShipmentETA_ETDFilter(DateComparisonOperator comparisonOperator, ZDateTime value1, ZDateTime value2)
		{
			ZDBOnlyQuery result = new ZDBOnlyQuery(typeof(AccTransactionLines));

			if ((value1.IsValidSqlDateTime) ||
				(value2.IsValidSqlDateTime))
			{
				ZDBOnlySubQuery jobHeaderQuery = new ZDBOnlySubQuery(typeof(JobHeader), AccTransactionLinesSchema.AL_JH);
				ZDBOnlySubQuery shipmentQuery = new ZDBOnlySubQuery(typeof(ForwardingShipment), JobShipmentSchema.PK);
				ZQuery dateQuery = new ZQuery();
				AddDateTimeRange(dateQuery, comparisonOperator, JoinCondition.And, JobShipmentSchema.JS_E_DEP, value1, value2);
				AddDateTimeRange(dateQuery, comparisonOperator, JoinCondition.Or, JobShipmentSchema.JS_E_ARV, value1, value2);

				shipmentQuery.AddToFilter(dateQuery);
				jobHeaderQuery.AddSubQuery(JobHeaderSchema.JH_ParentID, shipmentQuery, JoinCondition.And);
				result.AddSubQuery(jobHeaderQuery, JoinCondition.And);
			}

			return result;
		}


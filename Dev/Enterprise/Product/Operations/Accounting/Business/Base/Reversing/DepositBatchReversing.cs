using CargoWise.Common;
using CargoWise.Types;
using Enterprise.Accounting.Business.Base.Transaction;
using Enterprise.Accounting.Business.CashBook.DepositBatch;
using Enterprise.MasterFiles.Business.Accounting.CriticalValidation;

namespace Enterprise.Accounting.Business.Base.Reversing
{
	public partial class DepositBatchReversing : ReversingBase
	{
		public DepositBatchReversing(IReversing depositBatchTransaction)
			: base(depositBatchTransaction)
		{
		}

		protected override bool CanTransactionBeReversed()
		{
			DepositBatchParent batchParent = OriginalTransaction as DepositBatchParent;

			CollectErrorInfoWhenClearedReceiptLinkedToNonClearedDepositBatch(batchParent);

			return base.CanTransactionBeReversed() &&
				(!batchParent.HasCancelledReceipt && !batchParent.HasDirectCreditReceipt &&
				!batchParent.IsPeriodSubLedgerClosed && !batchParent.IsClearedInCashbook);
		}

		protected override ZString GenerateCantReverseErrorMessage()
		{
			string result = base.GenerateCantReverseErrorMessage();
			DepositBatchParent batchParent = OriginalTransaction as DepositBatchParent;
			if (string.IsNullOrEmpty(result))
			{
				if (batchParent.HasCancelledReceipt)
				{
					result = ContainCancelledReceiptMessage;
				}
				else if (batchParent.HasDirectCreditReceipt)
				{
					result = DirectCreditReceiptMessage;
				}
				else if (batchParent.IsPeriodSubLedgerClosed)
				{
					result = PeriodSubLedgerClosedMessage;
				}
				else if (batchParent.IsClearedInCashbook)
				{
					result = ClearedInCashBookMessage;
				}
			}
			return result;
		}

		protected override void SetReversingDescriptionOnTransactions()
		{
			ZString reverseTransactionDesc = Res.GetString("dae2bee9-eea0-4261-9555-e72270f5ac4f", "Cancellation related to {0}", OriginalTransaction.TransactionNumber);
			ReverseTransaction.SetDescription(reverseTransactionDesc);
		}

		protected override ZString AlreadyReversedErrorMessage
		{
			get { return Res.GetString("a3d73b91-ffb6-4cf0-97dc-110f7047abff", "This transaction has already been canceled."); }
		}

		void CollectErrorInfoWhenClearedReceiptLinkedToNonClearedDepositBatch(DepositBatchParent depositBatchParent)
		{
			if (!depositBatchParent.IsClearedInCashbook)
			{
				if (depositBatchParent.IsExistingBatch)
				{
					foreach (DepositBatch line in depositBatchParent.DepositBatchLines)
					{
						foreach (DepositBatchTransactionLine tranLine in line.Transactions)
						{
							if (!tranLine.AH_DateClearedInCashbook.IsEmpty)
							{
								CriticalValidationInfoCollectorService.GetOrCreateService(depositBatchParent.Factory).AddInfoWhenAllowed(tranLine.PK, CriticalValidationInfoCollectorServiceKeyType.ClearedReceiptLinkedToNonClearedDepositBatch,
							() => $@"BatchReceiptNumber: {tranLine.AH_ReceiptBatchNo}, ReceiptClearedDate: {tranLine.AH_DateClearedInCashbook}, DepositBatchClearedDate: {depositBatchParent.DepositBatch.AH_DateClearedInCashbook}");
							}
						}
					}
				}
				else
				{
					ErrorReporter.ReportOnce("ExistingBatch can't be null during reversing.");
				}
			}
		}

		string PeriodSubLedgerClosedMessage
		{
			get { return Res.GetString("36c5e086-3b4b-418b-8bec-933e2fa42ee8", "This deposit batch cannot be canceled as the sub-ledger period where the batch has been posted to is closed."); }
		}
		string ClearedInCashBookMessage
		{
			get { return Res.GetString("841c7dfe-82ad-4266-b233-860961e7621d", "This deposit batch cannot be canceled as the batch has been reconciled."); }
		}
		string DirectCreditReceiptMessage
		{
			get { return Res.GetString("b8d57030-ab1b-4e01-87d3-8167c3e921a6", "This Deposit Batch was automatically generated by a Direct Credit (DCR) receipts posting and cannot be canceled. You can, however, reverse this batch by reversing the transaction itself."); }
		}
		string ContainCancelledReceiptMessage
		{
			get { return Res.GetString("b218260a-6bdc-4233-96d7-18a362a77e99", "You are not allowed to cancel this Deposit Batch as it contains canceled receipts that were reversed subsequent to batching. A separate batch for any reversed receipt was created at the time of reversal."); }
		}
	}
}

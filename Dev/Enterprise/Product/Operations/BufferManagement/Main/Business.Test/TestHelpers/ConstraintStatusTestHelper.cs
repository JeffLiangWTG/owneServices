		internal static IEnumerable<Tuple<ConstraintStatus, string>> SetupAndGetExpectedTestCases(ProcessHeader workflow)
		{
			foreach (var testCaseAsString in ConstraintStatusTestHelper.TestCases)
			{
				yield return Tuple.Create(ConstraintStatusTestHelper.ParseTestCase(workflow, testCaseAsString), testCaseAsString);
			}
		}

		#region Implementation

		static ConstraintStatus ParseTestCase(ProcessHeader workflow, string testCaseAsString)
		{
			var testConditionAndExpectedResult = testCaseAsString.Split(';');
			var testCondition = testConditionAndExpectedResult[0];
			var testConfigurations = testCondition.Split(':')[1];

			workflow.FH_CompletionStatement = testCondition;

			foreach (var testConfiguration in testConfigurations.Split('>'))
			{
				var taskConfiguration = testConfiguration.Split(new[] { '.', '(', ')' });
				var task = workflow.Tasks.FirstOrDefault(t => t.P9_GS_NKAssignedStaffMember == taskConfiguration[1]);
				task.P9_Sequence = int.Parse(taskConfiguration[0]);
				task.P9_Status = taskConfiguration[2];
			}

			return ConstrainedModeHelper.GetConstraintStatusFromString(testConditionAndExpectedResult[1]);
		}

		/// <summary>
		/// Use this method to generate ConstraintStatusTestHelper.TestCases
		/// </summary>
		static internal void GenerateTestCases(ProcessHeader workflow)
		{
			var testIndex = 0;
			foreach (var workflowTasksPermutation in GenericTestHelper.GeneratePermutation(workflow.Tasks.ToList()))
			{
				foreach (var tasksStatusCombination in GenericTestHelper.GenerateBinaryCombination(workflow.Tasks.Count()))
				{
					int sequence = 0;

					var completionStatement = new ZStringBuilder();
					var delimiter = "";
					foreach (var workflowTask in workflowTasksPermutation)
					{
						completionStatement.Append(delimiter);
						completionStatement.Append(string.Format("{0}.{1}({2})", sequence, workflowTask.P9_GS_NKAssignedStaffMember, tasksStatusCombination[sequence] ? ProcessTaskStatusCodeList.Codes.Assigned : ProcessTaskStatusCodeList.Codes.Closed));
						delimiter = " > ";
						sequence++;
					}

					var testCase = string.Format("Test {0} with tasks: {1};", testIndex, completionStatement.ToString()); // test
					testIndex++;
				}
			}
		}


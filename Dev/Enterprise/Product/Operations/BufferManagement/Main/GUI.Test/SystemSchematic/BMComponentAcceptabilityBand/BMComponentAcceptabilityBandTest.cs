	[TestedType(typeof(BMComponentAcceptabilityBand))]
	class BMComponentAcceptabilityBandTest : EnterpriseBusinessObjectTestCase
	{
		#region Filters
		public void TestModuleGuidForeignCollectionFilter_AllMatchOperator_ShouldNotCreateInvalidQuery()
		{
			var band = Factory.New<BMComponentAcceptabilityBand>();
			band.BAB_Type = AcceptabilityBandTypes.Codes.Count;
			FilterStripsTestHelper.AddFilterStrips(band.FilterRule, new FilterStripsTestHelper.FilterStripDefinition
			{
				FilterStripName = "Tasks",
				ComparisonOperatorSetter = f => ((ModuleGuidForeignCollectionFilter)f).ComparisonOperator = ModuleTextFilter.ComparisonConstants.AllMatch,
				FilterStripValueSetter = f =>
				{
					((ModuleGuidForeignCollectionFilter)f).SelectedFilters.AddNkFilterStrip("Staff", "1");
				}
			});

			var parameters = new AcceptabilityBandSqlBuilderParameters(band);
			var command = band.GetAcceptabilityBandSqlCommand(parameters, TestConnection);

			AssertNoExceptionThrown("The sql should be valid and not throw the exception 'The multi-part identifier 'ProcessHeader.FH_PK' could not be bound', and yet...", () => command.ExecuteNonQuery());
		}

		#endregion

		#region GetAcceptabilityBandCommand

		public void TestGetAcceptabilityBandCommand_WithVarbinaryParameter_ShouldNotCauseExceptions()
		{
			var band = BMSTestHelper.CreateAcceptabilityBand(Factory, 0, 0, 0, 0, 0, 0, "Joey Joe Joe!", type: AcceptabilityBandTypes.Codes.Count);
			FilterStripsTestHelper.AddFilterStrip<ModuleGuidModuleSpecifiedFilter>(band.FilterRule, "Parent Job", filter =>
			{
				filter.SelectedModule = ModuleIDs.JobShipment.Name;
				var milestoneFilter = filter.SelectedFilters.AddFilterStrip<ModuleTextFilter>("Milestone Completed");
				((IWorkflowModuleTextFilter)milestoneFilter).EventReference = "Squanch";
			}, filter => filter.ComparisonOperator = ModuleTextFilter.ComparisonConstants.FiltersMatch);

			var filterStripsQuery = RelatedModuleFiltersHelper.GetFilterQuery(band.FilterRule);
			AssertContains("There must be a blob column in this query in order for this test to mean anything. SAD!", ProcessTasksSchema.Constants.P9_Notes, filterStripsQuery.ParameterisedText.ParameterisedQueryText);
			AssertEquals("There must be a blob column in this query in order for this test to mean anything. SAD!", true, filterStripsQuery.Params.Any(x => x.BlobFilters.Any()));

			var parameters = new AcceptabilityBandSqlBuilderParameters(band);

			using (var command = band.GetAcceptabilityBandSqlCommand(parameters, TestConnection))
			{
				AssertNoExceptionThrown("The sql generated by the acceptability band should list the parameters in such a way that it won't throw exceptions when executed. SAD!", () => command.ExecuteNonQuery());
			}
		}

		public void TestGetAcceptabilityBandCommand_WithSupersetFilterConfiguredAndForceSeek_ShouldNotCauseExceptions()
		{
			using (var efSettings = TestEntityFrameworkSettings.Get())
			{
				efSettings.DefaultToForceSeek = true;
				var band = BMSTestHelper.CreateAcceptabilityBand(Factory, 10, 20, 33, 100, 100, 100, "Jazz Club", type: AcceptabilityBandTypes.Codes.NumberAsPercentage);

				FilterStripsTestHelper.AddFilterStrips(band.SupersetItemsFilterRule,
					new FilterStripsTestHelper.FilterStripDefinition
					{
						FilterStripName = ProcessHeader.ModuleFilterConstants.CurrentComponent,
						FilterStripValueSetter = f => ((CurrentComponentFilter)f).Property = Guid.NewGuid(),
						ComparisonOperatorSetter = f => ((CurrentComponentFilter)f).ComparisonOperator = CurrentComponentFilter.ComparisonConstants.Exact,
					});

				var parameters = new AcceptabilityBandSqlBuilderParameters(band);

				using (var command = band.GetAcceptabilityBandSqlCommand(parameters, TestConnection))
				{
					AssertNoExceptionThrown("The sql generated by the acceptability band should list the parameters in such a way that it won't throw exceptions when executed. SAD!", () => command.ExecuteNonQuery());
				}
			}
		}

		#endregion
	}


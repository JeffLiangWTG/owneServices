using CargoWise.EntityFramework;
using CargoWise.EntityFramework.Testing;
using NUnit.Framework;
using WTG.NUnit;
using Constants = Enterprise.Core.Constants;

namespace Enterprise.Packing.Business.Testing
{
	[TestedType(typeof(PkgPackageHeader))]
	class PkgPackageHeaderDeferrableTriggerTest : DeferrableTriggerTestCase<PkgPackageHeader>
	{
		#region TestDeferTriggerAndRunBeforeCommit

		[ExpectNoExceptions]
		public void TestDeferredTrigger_PkgPackageHeaderUniqueIDPerJobTrigger()
		{
			var factory = Factory;
			var packageJob = factory.NewWithValidTestData<PkgPackageJob>();

			var package1 = packageJob.Packages.AddNew(Constants.PkgUnit.Pallet, "PKG1");
			var package2 = packageJob.Packages.AddNew(Constants.PkgUnit.Pallet, "PKG2");

			factory.Save();

			var factory2 = new BusinessObjectFactory();
			var packageHeader1 = factory2.Load<PkgPackageHeader>(package1.PackageID.PK);
			var packageHeader2 = factory2.Load<PkgPackageHeader>(package2.PackageID.PK);

			packageHeader2.KPH_PackageID = "PKG1";
			packageHeader1.KPH_PackageID = "PKG2";
			AssertNoExceptionThrown("trigger deferral should allow this", () => factory2.Save());

			CombineAssertions("package IDs are correct and not regenerated by RemoveDuplicatePackageIDs", () =>
			{
				AssertEquals("PKG1", packageHeader2.KPH_PackageID);
				AssertEquals("PKG2", packageHeader1.KPH_PackageID);
			});

			packageHeader1.KPH_PackageID = "PKG1";
			NUnit.Framework.Assert.That(() => factory2.Save(), CustomConstraints.InnermostExceptionThrown(typeof(SqlException), "Package ID needs to be unique per Job."), "trigger should prevent this - RemoveDuplicatePackageIDs is not called because PkgPackageJob is unchanged");
		}

		#endregion

		public void TestDeferredTrigger_PkgPackageHeaderIgnorCaseUniqueID()
		{
			var packageJob = Factory.NewWithValidTestData<PkgPackageJob>();

			packageJob.Packages.AddNew(Constants.PkgUnit.Pallet, "PKG1");
			packageJob.Packages.AddNew(Constants.PkgUnit.Pallet, "pkg1");

			AssertNoExceptionThrown(() => Factory.Save());
		}
	}
}

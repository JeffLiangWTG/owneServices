using System;
using CargoWise.EntityFramework;
using Enterprise.MasterFiles.Tracking;
using Enterprise.Tracking.Business;
using Enterprise.ZArchitecture.Web.GUI.WebControls;

namespace Enterprise.Tracking.Web
{
	/// <summary>
	/// Summary description for ShipmentDetails.
	/// </summary>
	public partial class ContainerDetails : BasePageWithAuthorisation
	{
		#region DataSource

		protected override bool IsPersistDataSourceBetweenPostbacks
		{
			get
			{
				return true;
			}
		}

		protected override BusinessObject GetNewDataSource()
		{
			return TrackingContainer.FromPKFilteredBySiteUser(Factory, GetGuidFromParameter(RefParameterName), SiteUser);
		}

		protected TrackingContainer CurrentContainer
		{
			get { return DataSource as TrackingContainer; }
		}

		#endregion

		protected override void OnLoad(EventArgs e)
		{
			base.OnLoad(e);
			bool isDataSourceValid = (CurrentContainer != null);

			AuthorisedContent.Visible = isDataSourceValid && CanAccessAuthorisedContent;
			NotFoundError.Visible = !isDataSourceValid;
			DocumentsGrid.Visible = SiteUser?.CanViewDocuments ?? false;
			OrdersGrid.Visible = SiteUser?.CanViewOrders ?? false;

			if (!isDataSourceValid)
			{
				NotFoundLabel.Text = Res.GetString("e86a686f-cd5e-4d84-b293-53735883651c", "Container was not found in the database or you don't have rights to view it.");
			}

			if (SiteUser.IsShipmentQuickViewUser)
			{
				MasterBillCaption.Visible = false;
				MasterBillLabel.Visible = false;

				ContainerStatusCaption.Visible = false;
				ContainerStatusLabel.Visible = false;

				PlannedWeightCaption.Visible = false;
				PlannedWeightLabel.Visible = false;

				QuarantineCaption.Visible = false;
				QuarantineLabel.Visible = false;

				PortTransportRefCaption.Visible = false;
				PortTransportRefLabel.Visible = false;

				SequenceCaption.Visible = false;
				SequenceLabel.Visible = false;

				PickupCaption.Visible = false;
				PickupLabel.Visible = false;

				DeliverCaption.Visible = false;
				DeliverLabel.Visible = false;

				SpecialInstructionCaption.Visible = false;
				SpecialInstructionLabel.Visible = false;

				ConsoleNumberCaption.Visible = false;
				ConsoleNumberLabel.Visible = false;

				VerifiedByCompanyCaption.Visible = false;
				VerifiedByCompanyLabel.Visible = false;

				VerifiedByPersonCaption.Visible = false;
				VerifiedByPersonLabel.Visible = false;

				VerifiedByPhoneCaption.Visible = false;
				VerifiedByPhoneLabel.Visible = false;

				VerifiedByEmailCaption.Visible = false;
				VerifiedByEmailLabel.Visible = false;

				OrdersGrid.Visible = false;
				DocumentsGrid.Visible = false;

				EditContainer.Visible = false;
			}
		}

		#region Page Setup

		protected override bool CanAccessAuthorisedContent
		{
			get { return SiteUser != null && SiteUser.CanViewTrackingContainers; }
		}

		protected override void SetupAuthorisedContent(bool isAuthorised)
		{
			base.SetupAuthorisedContent(isAuthorised);
			EditButtonDiv.Visible = SiteUser != null && SiteUser.CanViewTrackingContainers;
		}

		#endregion

		#region Setting up grids

		/// <summary>
		/// Set up all grids on the page
		/// </summary>
		protected override void SetupGrids()
		{
		}

		protected override string GetPageName()
		{
			return WebTracker.Pages.ContainerDetails;
		}

		protected override void OnPreBind()
		{
			base.OnPreBind();

			//these grids require DataSource to be loaded before grid's construction.
			//Data source have to be loaded after ViewState's construction

			SetupOrdersGrid(OrdersGrid);
			SetupDocumentsGrid(DocumentsGrid);
		}

		protected void SetupOrdersGrid(ZGrid ordersGrid)
		{
			ordersGrid.ColumnProvider = new CartageOrderColumnProvider();
		}

		#endregion

		#region Event Handlers

		protected void EditContainer_Click(object sender, EventArgs e)
		{
			Response.Redirect(string.Format("{0}?{1}={2}", AppInstance.EditContainerPage, RefParameterName, CurrentContainer.PK));
		}

		protected void SaveChanges_Click(object sender, EventArgs e)
		{
			this.OrdersGrid.ExportIntoExcel();
		}

		#endregion

		protected override string GetPageRelativePath()
		{
			return TrackingConstants.RelativePath.ContainerDetailsPage;
		}

		#region Autogenerated

		#region Web Form Designer generated code

		}

		protected void CancelReceive_Click(object sender, EventArgs e)
		{
			NotificationFlags.DisplayAll = false;
			Receive.WhsReceive.WD_DocketStatus = Receive.WhsReceive.WD_DocketStatus == DocketStatus.Codes.Cancelled ? DocketStatus.Codes.Entered : DocketStatus.Codes.Cancelled;
			Receive.Factory.Save();

			var eventLogHelper = new EventLogHelper();
			eventLogHelper.CreateLogForEdit(SiteUser, Receive);
			eventLogHelper.CreateLogForCancel(SiteUser, Receive);

			SetupPage();
		}

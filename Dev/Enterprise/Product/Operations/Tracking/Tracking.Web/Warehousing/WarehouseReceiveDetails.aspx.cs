		protected void DuplicateReceive_Click(object sender, EventArgs e)
		{
			if (Receive != null)
			{
				var newReceive = ((ITemplateCopyable)Receive).TemplateCopy() as TrackingWhsReceive;
				if (newReceive != null)
				{
					newReceive.SiteUser = SiteUser;
					newReceive.WhsReceive.WD_OH_Client = SiteUser.LoggedInOrganisation.PK;
					UpdateAutoCreatedLogReferenceAndSaveDataSource(newReceive.PK, newReceive);
					HttpContext.Current.Response.Redirect(string.Format((NoResString)"{0}?Ref={1}&{2}={3}", AppInstance.WarehouseEditReceive, newReceive.PK, DataSourceInSessionParameterName, DataSourceInSessionParameterValue)); // Redirection path
				}
			}
		}


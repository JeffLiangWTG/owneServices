		#region GetCompleteFilter

		ZQuery GetCompleteFilter(Xsd.WebInvoiceFilter filter, GlbCompany targetCompany, ZGuid currentOrgPK)
		{
			ZQuery query = ZQuery.NoResultQuery;

			if (filter != null)
			{
				query = new ZDBOnlyQuery(typeof(InvoicingBase));

				if (filter.LedgerTypes.Count > 0)
				{
					query.AddToFilter(GetLedgerTypeQuery(filter));
				}

				if (filter.TxnTypes.Count > 0)
				{
					query.AddToFilter(GetTransTypeQuery(filter));
				}

				if (filter.PostDateFrom.IsValid)
				{
					query.AddToFilter(AccTransactionHeaderSchema.AH_PostDate, SQLComparisonOperator.GreaterThanOrEqualToDatePartOnly, filter.PostDateFrom);
				}

				if (filter.PostDateTo.IsValid)
				{
					query.AddToFilter(AccTransactionHeaderSchema.AH_PostDate, SQLComparisonOperator.LessThanOrEqualToDatePartOnly, filter.PostDateTo);
				}

				query.AddToFilter(AccTransactionHeaderSchema.AH_GC, targetCompany.PK);
				query.AddToFilter(AccTransactionHeaderSchema.AH_OH, currentOrgPK);
			}

			return query;
		}

		#endregion

		#region GetInvoicePKXsdCollection

		Xsd.BusinessObjectPKCollection GetInvoicePKXsdCollection(ZQuery query, GlbCompany targetCompany)
		{
			InvoicingBase[] invoices = GetInvoices(query);

			Xsd.BusinessObjectPKCollection invoicePKs = new Xsd.BusinessObjectPKCollection();

			foreach (InvoicingBase invoice in invoices)
			{
				Xsd.BusinessObjectPK pKXsd = new Xsd.BusinessObjectPK();
				pKXsd.Pk = invoice.PK.ToString();
				pKXsd.IsSpecified = true;

				invoicePKs.Add(pKXsd);
			}

			return invoicePKs;
		}

		#endregion

		#region GetInvoiceXsdCollection

		Xsd.FinancialInvoices GetInvoiceXsdCollection(ZQuery query)
		{
			InvoicingBase[] invoices = GetInvoices(query);

			Xsd.FinancialInvoices invoiceValues = new Xsd.FinancialInvoices();

			FinancialInvoiceDataAdapter adapter = new ExportFinancialInvoiceDataAdapter();
			NotificationBuffer notifications = new NotificationBuffer();

			foreach (InvoicingBase invoice in invoices)
			{
				Xsd.TxnHeader invoiceXsd = adapter.ExportToValueObject(invoice, new ValueObjectExportContext(notifications));
				invoiceValues.TxnHeader.Add(invoiceXsd);
			}

			return invoiceValues;
		}

		#endregion

		#region GetInvoices

		InvoicingBase[] GetInvoices(ZQuery query)
		{
			List<InvoicingBase> result = new List<InvoicingBase>();
			InvoicingBase[] loadedInvoices = Factory.Load<InvoicingBase>(query);

			foreach (InvoicingBase invoice in loadedInvoices)
			{
				Guid[] chargePKs = WebDataRegistry.Instance.GetWebServiceChargeGuids(invoice.Branch.Company.PK.ToGuid());

				if (chargePKs.Length > 0)
				{
					ZQuery subQuery = GetChargeCodeQuery(chargePKs, invoice.Branch.Company.PK);
					invoice.Lines.LoadWithMoreFiltering(subQuery);
				}

				if (invoice.Lines.Count > 0)
				{
					result.Add(invoice);
				}
			}
			return result.ToArray();
		}

		#endregion

		#region GetLedgerTypeQuery

		ZQuery GetLedgerTypeQuery(Xsd.WebInvoiceFilter filter)
		{
			ZQuery ledgerTypeQuery = new ZQuery();
			ledgerTypeQuery.DefaultJoinCondition = JoinCondition.Or;

			foreach (Xsd.TxnLedgerType ledgerType in filter.LedgerTypes)
			{
				ledgerTypeQuery.AddToFilter(AccTransactionHeaderSchema.AH_Ledger, ledgerType.ToString());
			}

			return ledgerTypeQuery;
		}

		#endregion

		#region GetTransTypeQuery

		ZQuery GetTransTypeQuery(Xsd.WebInvoiceFilter filter)
		{
			ZQuery transTypeQuery = new ZQuery();
			transTypeQuery.DefaultJoinCondition = JoinCondition.Or;

			foreach (Xsd.TxnType transType in filter.TxnTypes)
			{
				transTypeQuery.AddToFilter(AccTransactionHeaderSchema.AH_TransactionType, transType.ToString());
			}

			return transTypeQuery;
		}

		#endregion

		#region GetChargeCodeQuery

		ZQuery GetChargeCodeQuery(Guid[] chargeCodePKs, ZGuid targetCompanyPK)
		{
			ZQuery transactionLineQuery = new ZQuery(AccTransactionLinesSchema.AL_LineType, ZArchitecture.Core.TransactionLineTypes.Revenue);
			transactionLineQuery.AddToFilter(AccTransactionLinesSchema.AL_GC, targetCompanyPK);

			foreach (Guid chargeCodePK in chargeCodePKs)
			{
				ZQuery chargeCodeQuery = new ZQuery();
				chargeCodeQuery.AddToFilter(AccChargeCodeSchema.PK, chargeCodePK);
				chargeCodeQuery.AddToFilter(AccChargeCodeSchema.AC_GC, targetCompanyPK);
				AccChargeCode charge = Factory.LoadTop1<AccChargeCode>(chargeCodeQuery);

				if (charge != null)
				{
					transactionLineQuery.AddToFilter(AccTransactionLinesSchema.AL_AC, SQLComparisonOperator.NotEqual, charge.PK);
				}
			}

			return transactionLineQuery;
		}

		#endregion

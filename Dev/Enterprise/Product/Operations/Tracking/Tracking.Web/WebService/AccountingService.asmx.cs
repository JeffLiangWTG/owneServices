		/// <summary>
		/// Logic of GetInvoiceList extracted for unit testing purposes
		/// </summary>
		/// <param name="CurrentOrg">Client organisation</param>
		/// <param name="Filter">XML representation of Filter</param>
		/// <returns>Collection of XML value objects</returns>
		[SuppressMessage("Microsoft.Usage", "CA2201:DoNotRaiseReservedExceptionTypes", Justification = "Legacy web service.")]
		protected internal Xsd.FinancialInvoices GetInvoiceListInternal(Xsd.BusinessObjectPKCollection pKs, ZGuid currentOrgPK)
		{
			Xsd.FinancialInvoices invoices = new Xsd.FinancialInvoices();

			if (pKs.Count > 0)
			{
				List<ZGuid> invoicePKs = new List<ZGuid>();
				foreach (Xsd.BusinessObjectPK bizOPK in pKs)
				{
					ZGuid invoicePK = ZGuid.Empty;
					try
					{
						invoicePK = new ZGuid(bizOPK.Pk);
					}
					catch (FormatException)
					{
						throw new Exception(string.Format(CultureInfo.InvariantCulture, "ERROR: Invalid Guid value: '{0}'", bizOPK.Pk));
					}

					if (!invoicePK.IsEmpty && invoicePK.IsValid)
					{
						invoicePKs.Add(invoicePK);
					}
				}

				if (invoicePKs.Count > 0)
				{
					ZDBOnlyQuery query = new ZDBOnlyQuery(typeof(InvoicingBase));
					query.AddToFilter(AccTransactionHeaderSchema.PK, invoicePKs.ToArray());
					query.AddToFilter(AccTransactionHeaderSchema.AH_OH, currentOrgPK);

					invoices = GetInvoiceXsdCollection(query);
				}
			}

			return invoices;
		}


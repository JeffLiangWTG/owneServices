		GlbCompany GetCompany(ZString company)
		{
			GlbCompany result = null;

			if (company.IsEmpty)
			{
				throw new Exception("ERROR: Please supply the Company Code");
			}
			else
			{
				ZQuery query = new ZQuery(GlbCompanySchema.GC_Code, company.Trim());
				result = Factory.LoadTop1<GlbCompany>(query);
			}

			return result;
		}


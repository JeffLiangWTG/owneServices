	/// <summary>
	/// Web service to retrieve Shipment information from Shipments and declarations 
	/// based on filter and login organisation
	/// </summary>
	[WebService(Namespace = "http://www.edi.com.au/EnterpriseService/")]
	public class ShipmentService : BaseWebService
	{
		public ShipmentService()
		{
			//CODEGEN: This call is required by the ASP.NET Web Services Designer
			InitializeComponent();
		}

		#region Component Designer generated code

		//Required by the Web Services Designer 
		private readonly IContainer components; // This code is auto-generated by VS.Net

		/// <summary>
		/// Required method for Designer support - do not modify
		/// the contents of this method with the code editor.
		/// </summary>
		private void InitializeComponent()
		{
		}

		/// <summary>
		/// Clean up any resources being used.
		/// </summary>
		protected override void Dispose(bool disposing)
		{
			if (disposing && components != null)
			{
				components.Dispose();
			}
			base.Dispose(disposing);
		}

		#endregion

		[WebMethod(EnableSession = true, Description = "Returns list of all Shipments/Declarations for a client. This method requires a custom soap header set by the caller")]
		[SoapHeader("MessageHeader")]
		public Xsd.WebShipments GetShipmentsList([XmlElement(ElementName = "Filter")] Xsd.WebShipmentFilter filter)
		{
			return ExecuteAndDispose(() =>
			{
				OrgHeader currentOrg = CheckMessageHeaderAndLogin();
				return GetShipmentsListInternal(currentOrg, filter);
			});
		}

		#region Helper methods

		/// <summary>
		/// Logic of GetShipmentsList extracted for unit testing purposes
		/// </summary>
		/// <param name="currentOrg">Client organisation</param>
		/// <param name="filter">XML representation of Filter</param>
		/// <returns>Collection of XML value objects</returns>
		protected internal Xsd.WebShipments GetShipmentsListInternal(OrgHeader currentOrg, Xsd.WebShipmentFilter filter)
		{
			TrackingShipmentFilterBusinessObject filterBizO = GetFilterBusinessObject(filter);
			ShipmentDeclarationCollection collection = new ShipmentDeclarationCollection(Factory);

			ZQuery shipmentFilter = filterBizO.Filter;

			shipmentFilter.AddToFilter(OrgRestrictionFilterFactory.Instance.GetFilter<TrackingShipment>());
			collection.Load(shipmentFilter, filterBizO.GetDeclarationQuery(), ShipmentDeclarationSchema.ETA.Name, ListSortDirection.Descending);

			Xsd.WebShipments result = new Xsd.WebShipments();
			result.WebShipment = new Xsd.WebShipmentCollection();

			foreach (IShipmentDeclaration shipmentOrDeclaration in collection)
			{
				if (shipmentOrDeclaration is TrackingShipment)
				{
					Xsd.WebShipment shipmentXML = new TrackingShipmentValueObjectDataAdapter().ExportToValueObject((TrackingShipment)shipmentOrDeclaration, new ValueObjectExportContext(new NotificationBuffer()));
					if (shipmentXML != null)
					{
						result.WebShipment.Add(shipmentXML);
					}
				}
				else if (shipmentOrDeclaration is TrackingDeclaration)
				{
					Xsd.WebShipment declarationXML = new TrackingDeclarationValueObjectDataAdapter().ExportToValueObject((TrackingDeclaration)shipmentOrDeclaration, new ValueObjectExportContext(new NotificationBuffer()));
					if (declarationXML != null)
					{
						result.WebShipment.Add(declarationXML);
					}
				}
			}

			result.TotalRows = collection.Count.ToString();
			result.ReturnedRows = collection.Count.ToString();
			return result;
		}

		/// <summary>
		/// Creates a Filter business object based on XML input from web service user
		/// </summary>
		/// <param name="filter">XML representation of Filter</param>
		/// <returns>Created filter business object with all properties set based on input</returns>
		protected internal TrackingShipmentFilterBusinessObject GetFilterBusinessObject(Xsd.WebShipmentFilter filter)
		{
			TrackingShipmentFilterBusinessObject filterBizO = new TrackingShipmentFilterBusinessObject();

			ValueObjectImportContext importContext = new ValueObjectImportContext(filterBizO.Factory, new NotificationBuffer());
			new ShipentDeclarationFilterValueObjectDataAdapter().ImportFromValueObject(filterBizO, filter, importContext);
			return filterBizO;
		}

		#endregion
	}
}

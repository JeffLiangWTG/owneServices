			});
		}

		protected internal Xsd.WebOrders GetOrderListInternal(OrgHeader currentOrg, Xsd.WebOrderFilter filter)
		{
			TrackingOrderFilterBusinessObject_Old_ForWeb filterBO = GetFilterBusinessObject(currentOrg, filter);
			TrackingLegacyOrderCollection collection = new TrackingLegacyOrderCollection(Factory);
			collection.Load(filterBO.Filter);

			Xsd.WebOrders result = new Xsd.WebOrders();
			result.WebOrder = new TrackingOrderValueObjectDataAdapter().ExportToValueObjectCollection(collection, new ValueObjectExportContext(new NotificationBuffer()));
			if (result.WebOrder == null)
			{
				result.WebOrder = new Xsd.WebOrderCollection();
			}

			result.TotalRows = collection.Count.ToString();
			result.ReturnedRows = collection.Count.ToString();

			return result;
		}


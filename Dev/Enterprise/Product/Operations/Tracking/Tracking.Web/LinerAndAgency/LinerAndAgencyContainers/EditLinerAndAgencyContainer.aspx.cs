	{
		#region DataSource

		protected override BusinessObject GetNewDataSource()
		{
			return LinerAndAgencyContainer.FromPKFilteredBySiteUser(Factory, GetGuidFromParameter(RefParameterName), SiteUser);
		}

		protected LinerAndAgencyContainer CurrentContainer
		{
			get { return DataSource as LinerAndAgencyContainer; }
		}

		protected override bool IsPersistDataSourceBetweenPostbacks
		{
			get { return true; }
		}

		#endregion

		protected override void OnPreRender(EventArgs e)
		{
			base.OnPreRender(e);
			DisabledSubmitButtons.Add(SaveContainer.ClientID);
		}

		protected override void OnLoad(EventArgs e)
		{
			base.OnLoad(e);
			bool isDataSourceValid = (CurrentContainer != null);

			if (isDataSourceValid && CurrentContainer.JC_Purpose == "REL")
			{
				DynamicCaption.Text = Res.GetString("77A9A442-5D54-4F69-94DD-7EA6063FB4F7", "Bill Of Lading Number");
			}
			else if (isDataSourceValid && CurrentContainer.JC_Purpose == "BKD")
			{
				DynamicCaption.Text = Res.GetString("946A0982-6C3A-4B2B-86E9-8FBFE9B38A02", "Booking Ref");
			}

			ContainerContents.Visible = isDataSourceValid;
			NotFoundError.Visible = !isDataSourceValid;

			if (!isDataSourceValid)
			{
				NotFoundLabel.Text = Res.GetString("0f26158a-84b9-4d1d-8a42-3e587da64846", "Container was not found in the database or you don't have rights to view it.");
			}
		}

		protected override bool CanAccessAuthorisedContent
		{
			get { return SiteUser != null && SiteUser.CanEditLinerAndAgencyContainers; }
		}

		protected override void SetupAuthorisedContent(bool isAuthorised)
		{
			base.SetupAuthorisedContent(isAuthorised);
			if (SiteUser != null)
			{
				EstimatedFullDeliveryDateEditBox.Enabled = isAuthorised && SiteUser.CanEditLinerAndAgencyContainersEstimatedFullDeliveryDate;
				EmptyReadyForReturnDateEditBox.Enabled = isAuthorised && SiteUser.CanEditLinerAndAgencyContainersEmptyReadyToReturnDate;
				EmptyReturnReqByDateEditBox.Enabled = isAuthorised && SiteUser.CanEditLinerAndAgencyContainersEmptyReturnReqByDate;
				DeliveryDateEditBox.Enabled = isAuthorised && SiteUser.CanEditLinerAndAgencyContainersActualDeliveryDate;
				EmptyReturnedOnDateEditBox.Enabled = isAuthorised && SiteUser.CanEditLinerAndAgencyContainersEmptyReadyOnDate;
			}
		}

		#region Setting up grid

		protected override void OnPreBind()
		{
			base.OnPreBind();

			//these grids require DataSource to be loaded before grid's construction.
			//Data source have to be loaded after ViewState's construction

			SetupDocumentsGrid(DocumentsGrid);
		}

		#endregion

		[SuppressMessage("Microsoft.Globalization", "CA1305:Redirect URL.")]
		protected void SaveContainer_Click(object sender, EventArgs e)
		{
			SaveDataSourceFactory();
			Response.Redirect(string.Format("{0}?{1}={2}", AppInstance.LinerAndAgencyContainerDetailsPage, RefParameterName, DataSource.PK));
		}

		protected override string GetPageRelativePath()
		{
			return TrackingConstants.RelativePath.EditLinerAndAgencyContainerPage;
		}

		protected internal override IReadOnlyCollection<ILicenceCheckpoint> LicenceCheckPoints
		{
			get
			{
				var result = new List<ILicenceCheckpoint>();
				result.Add(Environment.Env.Licence.WebTrackerForwarding);
				return result.ToArray();
			}
		}

		protected override string GetPageName()
		{
			return WebTracker.Pages.EditLinerAndAgencyContainer;
		}

		protected void DropDown_SelectedIndexChanged(object sender, EventArgs e)
		{
			Bind();
		}


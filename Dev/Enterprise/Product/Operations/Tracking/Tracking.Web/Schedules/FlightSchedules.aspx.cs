namespace Enterprise.Tracking.Web.Schedules
{
	public partial class FlightSchedules : BasePage, IRememberFilterCriteriaPage, IModulePage
	{
		#region Overrides

		protected override void OnLoad(EventArgs e)
		{
			if (!WebDataRegistry.Instance.UseWebForwardingFlightsModule.Value)
			{
				Response.Redirect(AppInstance.DefaultPage);
			}

			base.OnLoad(e);
		}

		protected override bool IsPersistDataSourceBetweenPostbacks
		{
			get { return true; }
		}

		protected override BusinessObject GetNewDataSource()
		{
			return searchControl.Module.CreateNewFilterBusinessObject();
		}

		protected override ZString ModuleNameForEventLogging
		{
			get
			{
				return (NoResString)"Flight Schedules"; // Event logging related
			}
		}

		#endregion

		#region Page Setup

		protected override System.Web.UI.ControlCollection ControlsToBind
		{
			get { return searchControl.Controls; }
		}

		#endregion

		#region Search Control setup

		public ISearchControl SearchControl { get { return searchControl; } }

		ZSearchControl searchControl;

		void SetupSearchControl()
		{
			searchControl = GetNewSearchControl();
			searchControl.ModuleID = WebModuleIDs.TrackingFlightSchedules;
			searchControl.IsNewButtonVisible = false;
			SearchControlHolder.Controls.AddAt(0, searchControl);
		}

		protected override string GetPageName()
		{
			return WebTracker.Pages.FlightSchedules;
		}

		protected override string GetPageRelativePath()
		{
			return TrackingConstants.RelativePath.FlightSchedulesPage;
		}

		protected virtual ZSearchControl GetNewSearchControl()
		{
			return new ZSearchControl();
		}

		#endregion

		#region AutoGenerated

		#region Web Form Designer generated code
		override protected void OnInit(EventArgs e)
		{
			//
			// CODEGEN: This call is required by the ASP.NET Web Form Designer.
			//
			base.OnInit(e);
			InitializeComponent();
			SetupSearchControl();
		}

		/// <summary>
		/// Required method for Designer support - do not modify
		/// the contents of this method with the code editor.
		/// </summary>
		void InitializeComponent()
		{
			TitleLabel.BindTo = null;
			//	UnauthorisedLabel.BindTo = null;		
		}
		#endregion

		#endregion
	}
}

using System;
using System.Linq;
using CargoWise.EntityFramework;
using CargoWise.Windows.UI;
using Enterprise.Core.Forms;
using Enterprise.MasterFiles.Business;
using Enterprise.Security;
using Enterprise.ZArchitecture;
using Enterprise.ZArchitecture.GUI;
using Enterprise.ZArchitecture.Modules;
using Enterprise.ZArchitecture.Schema;

namespace Enterprise.MasterFiles.GUI
{
	public partial class ZExceptionsUserControl : ZMilestonesOrExceptionsUserControl, IRequiresWorkflowSecurity
	{
		public ZExceptionsUserControl()
		{
			InitializeComponent();
			FilterStripAuditDetails.AddAuditDetailsColumns(ExceptionsGrid, ProcessTasksSchema.Constants.TableName, typeof(ProcessTask));
		}

		protected override void OnLoad(EventArgs e)
		{
			base.OnLoad(e);
			this.CheckAndConsumeWorkflowLicenceIfAllowed();
		}

		protected override ZGrid Grid => ExceptionsGrid;

		protected override ColourLegend ColourLegend => colourLegend;

		protected override ZLabel TasksHintLabel => exceptionsHintLabel;

		protected override KSplitContainer SplitContainer => exceptionsHintSplitContainer;

		public override void SetDataBinding(object dataSource, string dataMember)
		{
			base.SetDataBinding(dataSource, dataMember);
			IBusinessObjectCollection collection = Grid.List as IBusinessObjectCollection;

			if (collection != null)
			{
				if (((IRequiresWorkflowSecurity)this).ViewOnly)
				{
					collection.IncrementReadOnlyIncludingChildren();
				}
			}
		}

		#region Navigate to WorkflowItem

		public virtual void NavigateToWorkflowItem(ProcessTask task)
		{
			if (ExceptionsGrid != null && ExceptionsGrid.ListManager != null)
			{
				for (int j = 0; j < this.ExceptionsGrid.ListManager.Count; j++)
				{
					ProcessTask currentTask = (ProcessTask)ExceptionsGrid.List[j];
					if (task.PK == currentTask.PK)
					{
						ExceptionsGrid.ListManager.Position = j;
						ExceptionsGrid.Select(j);
						break;
					}
				}
			}
		}

		public void RemoveDurationRelatedFields()
		{
			string[] durationRelatedFieldNames = { ProcessTasksSchema.P9_RL_NKExceptionLocation.Name, ProcessTasksSchema.P9_ExceptionDurationHours.Name, ProcessTasksSchema.P9_ExceptionEndDate.Name };

			foreach (var columnName in durationRelatedFieldNames)
			{
				var columnInfo = Grid.ColumnStyles.OfType<ZGridColumnInfo>().FirstOrDefault(c => c.ColumnName == columnName);

				if (columnInfo != null)
				{
					Grid.ColumnStyles.Remove(columnInfo);
				}
			}
		}

		#endregion

		#region IRequireWorkflowSecurity Members

		string IRequiresWorkflowSecurity.WorkflowItemEditCheckpointCode
		{
			get { return SecurityCore.WorkflowExceptionsAutoGeneratedCode; }
		}

		string IRequiresWorkflowSecurity.WorkflowItemJustViewCheckpointCode
		{
			get { return SecurityCore.WorkflowExceptionsJustViewAutoGeneratedCode; }
		}

		ModuleIdentifier IRequiresWorkflowSecurity.WorkflowProviderModuleId
		{
			get { return null; }
		}

		bool IRequiresWorkflowSecurity.ViewOnly { get; set; }

		#endregion
	}
}

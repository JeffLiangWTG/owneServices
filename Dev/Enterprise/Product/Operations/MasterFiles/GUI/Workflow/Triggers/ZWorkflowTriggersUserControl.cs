namespace Enterprise.MasterFiles.GUI
{
	public partial class ZWorkflowTriggersUserControl : ZUserControl, IRequiresWorkflowSecurity, IWorkflowTasksControl
	{
		public ZWorkflowTriggersUserControl()
		{
			InitializeComponent();

			SetupContextMenuOnActions();

			triggersSplitContainer.AllowOverlap(CreateWorkflowTriggersLinkLabel);
			CreateWorkflowTriggersLinkLabel.AllowOutsideOfParent();
		}

		void SetupContextMenuOnActions()
		{
			UniversalXmlSampleSavingContextMenuManager.AttachToGrid(CompletionTriggerActionGrid);
			WorkflowDiagnosticContextMenuManager.AttachToTriggerGrid(WorkflowTriggersGrid);
			ObjectFactory.Get<IValidateCommunicationModesMenuItemProvider>().AddItemToGrid(WorkflowTriggersGrid);
		}

		protected override void OnLoad(EventArgs e)
		{
			base.OnLoad(e);
			this.CheckAndConsumeWorkflowLicenceIfAllowed();
		}

		public void NavigateToWorkflowItem(ProcessTask trigger)
		{
			if (WorkflowTriggersGrid != null && WorkflowTriggersGrid.ListManager != null)
			{
				for (int i = 0; i < WorkflowTriggersGrid.ListManager.Count; i++)
				{
					var currentTask = (ProcessTask)WorkflowTriggersGrid.List[i];
					if (trigger.PK == currentTask.PK)
					{
						WorkflowTriggersGrid.ListManager.Position = i;
						break;
					}
				}
			}
		}

		#region ReferenceCode Column Caption

		public override void SetDataBinding(object dataSource, string dataMember)
		{
			var provider = (IWorkflowProvider)dataSource;
			dataBindingDisposable?.Dispose();

			if (dataSource != null)
			{
				var referenceCodeColumn = (ZDropEditColumnStyleInfo)WorkflowTriggersGrid.GetColumnStyle(ProcessTask.Schema.ReferenceCode);
				if (referenceCodeColumn != null && !provider.WorkflowItems.RequiresReferenceCode)
				{
					WorkflowTriggersGrid.ColumnStyles.Remove(referenceCodeColumn);
				}
				if (referenceCodeColumn != null)
				{
					referenceCodeColumn.Caption = provider.WorkflowItems.ReferenceCodeCaption;
				}
			}
			base.SetDataBinding(dataSource, dataMember);
			var collection = GetWorkflowItems(dataSource, dataMember);
			if (collection != null)
			{
				dataBindingDisposable = this.SetupControl(collection, saveOrder: true);
				if (((IRequiresWorkflowSecurity)this).ViewOnly)
				{
					collection.IncrementReadOnlyIncludingChildren();
				}
				CreateWorkflowTriggersLinkLabel.Enabled = !collection.ReadOnly;
			}
		}

		IDisposable dataBindingDisposable;

		IWorkflowProviderCollection GetWorkflowItems(object dataSource, string dataMember)
		{
			CurrencyManager cm = dataSource == null ? null : (CurrencyManager)BindingContext[dataSource, new KBindingMemberInfo(dataMember).BindingMember];
			return cm?.List as IWorkflowProviderCollection;
		}

		#endregion

		#region IRequireWorkflowSecurity Members

		string IRequiresWorkflowSecurity.WorkflowItemEditCheckpointCode
		{
			get { return SecurityCore.WorkflowTriggersAutoGeneratedCode; }
		}

		string IRequiresWorkflowSecurity.WorkflowItemJustViewCheckpointCode
		{
			get { return SecurityCore.WorkflowTriggersJustViewAutoGeneratedCode; }
		}

		ModuleIdentifier IRequiresWorkflowSecurity.WorkflowProviderModuleId
		{
			get { return null; }
		}

		bool IRequiresWorkflowSecurity.ViewOnly { get; set; }

		#endregion

		#region Implementation

		void CreateWorkflowTriggersLinkLabel_LinkClicked(object sender, LinkLabelLinkClickedEventArgs e)
		{
			var providerProxy = (IWorkflowProvider)WorkflowTriggersGrid.List;
			var providerBizo = providerProxy.WorkflowItems.Parent;
			var provider = (IWorkflowProvider)providerBizo;

			if (ProcessTask.Loader.ShouldCreateTriggersFromTemplate(provider))
			{
				var startingTriggerCount = provider.WorkflowItems.Triggers.Count;

				provider.ApplyWorkflowTemplates(TemplateApplicationParameters.ApplySpecificEntityTypes(TemplateEntityType.Triggers, jobAttributesMayHaveChangedSinceLastTemplateApplication: true));

				if (provider.WorkflowItems.Triggers.Count == startingTriggerCount)
				{
					Globals.Message.Show(Res.GetString("10050bbc-061a-4b17-83eb-c8cbce231ff8", "No Workflow Triggers were added from templates for the specified details."), Res.GetString("fda9e27c-8388-4f5b-8aa6-21c3694c43fc", "Workflow Trigger Creation"), MessageBoxButtons.OK, MessageBoxIcon.Information);
				}
				else
				{
					provider.WorkflowItems.TriggersIncludingRelated.Reload();
				}
			}
			else
			{
				Globals.Message.Show(Res.GetString("3f6f92f0-1e53-4c33-b0db-395b48cd63b7", "You can only create triggers from the template if you have no triggers already entered."), Res.GetString("fda9e27c-8388-4f5b-8aa6-21c3694c43fc", "Workflow Trigger Creation"), MessageBoxButtons.OK, MessageBoxIcon.Information);
			}
		}

		protected ZGrid Grid
		{
			get { return WorkflowTriggersGrid; }
		}

		ZGrid IWorkflowItemsControl.TasksGrid => Grid;

		KSplitContainer IWorkflowTasksControl.TasksHintSplitContainer => triggersSplitContainer;

		ZLabel IWorkflowTasksControl.TasksHintLabel => triggersHintLabel;

		protected override void Dispose(bool disposing)
		{
			if (disposing && (components != null))
			{
				components.Dispose();
			}
			dataBindingDisposable?.Dispose();
			base.Dispose(disposing);
		}

		#endregion
	}
}

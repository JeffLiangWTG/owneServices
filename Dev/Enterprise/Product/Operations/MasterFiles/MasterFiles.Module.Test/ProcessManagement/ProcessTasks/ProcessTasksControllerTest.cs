using Enterprise.Environment;
using Enterprise.MasterFiles.Business.Testing;
using Enterprise.Security;
using Enterprise.ZArchitecture.Modules;
using Enterprise.ZArchitecture.Modules.Testing;
using NUnit.Framework;

namespace Enterprise.MasterFiles.Module.Testing
{
	[TestedType(typeof(ProcessTasksController))]
	sealed class ProcessTasksControllerTest : ZControllerBasherTest
	{
		protected override ControllerID GetControllerID()
		{
			return ControllerIDs.ProcessTasks;
		}

		public void TestGetCheckPointForView()
		{
			ProcessTasksController controller = new ProcessTasksController();
			DummyProcessTask task = Factory.New<DummyProcessTask>();

			AssertEquals(Env.Security.WorkflowTasksView, controller.GetCheckPointForView(null));

			task.SetParentControllerID(null);
			AssertEquals(Env.Security.WorkflowTasksView, controller.GetCheckPointForView(task));

			task.SetParentControllerID(ControllerIDs.JobShipment);
			AssertContains("MaintainShipmentWorkflowView Tasks", controller.GetCheckPointForView(task).ToString());

			task.SetParentControllerID(ControllerIDs.Customs.CA.CusSCAOceanBill);
			AssertEquals("Can load CA CusSCAOceanBill", Env.Security.WorkflowTasksView, controller.GetCheckPointForView(task));
		}

		public void TestGetCheckPointForNew()
		{
			ProcessTasksController controller = new ProcessTasksController();
			DummyProcessTask task = Factory.New<DummyProcessTask>();

			AssertEquals(Env.Security.WorkflowTasksNew, controller.GetCheckPointForNew(null));

			task.SetParentControllerID(null);
			AssertEquals(Env.Security.WorkflowTasksNew, controller.GetCheckPointForNew(task));

			task.SetParentControllerID(ControllerIDs.JobShipment);
			AssertEquals(Env.Security.FindOrCreateWorkflowItemCheckpoint(Env.Security.MaintainShipment, SecurityCore.WorkflowAddTasksAutoGeneratedCode), controller.GetCheckPointForNew(task));
		}

		public void TestGetCheckPointForEdit()
		{
			ProcessTasksController controller = new ProcessTasksController();
			DummyProcessTask task = Factory.New<DummyProcessTask>();

			AssertEquals(Env.Security.WorkflowTasksEdit, controller.GetCheckPointForEdit(null));

			task.SetParentControllerID(null);
			AssertEquals(Env.Security.WorkflowTasksEdit, controller.GetCheckPointForEdit(task));

			task.SetParentControllerID(ControllerIDs.JobShipment);
			AssertContains("MaintainShipmentWorkflowTasks", controller.GetCheckPointForEdit(task).ToString());

			task.SetParentControllerID(ControllerIDs.Customs.CA.CusSCAOceanBill);
			AssertEquals("Can load CA CusSCAOceanBill", Env.Security.WorkflowTasksEdit, controller.GetCheckPointForEdit(task));
		}

		public void TestGetCheckPointForDelete()
		{
			ProcessTasksController controller = new ProcessTasksController();
			DummyProcessTask task = Factory.New<DummyProcessTask>();

			AssertEquals(Env.Security.WorkflowTasksDelete, controller.GetCheckPointForDelete(null));

			task.SetParentControllerID(null);
			AssertEquals(Env.Security.WorkflowTasksDelete, controller.GetCheckPointForDelete(task));

			task.SetParentControllerID(ControllerIDs.JobShipment);
			AssertEquals(Env.Security.FindOrCreateWorkflowItemCheckpoint(Env.Security.MaintainShipment, SecurityCore.WorkflowDeleteTasksAutoGeneratedCode), controller.GetCheckPointForDelete(task));
		}
	}
}

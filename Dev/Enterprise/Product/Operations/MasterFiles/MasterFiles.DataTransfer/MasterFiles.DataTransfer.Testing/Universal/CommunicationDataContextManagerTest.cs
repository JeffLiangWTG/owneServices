	{
		public void TestDataContextType()
		{
			var communication = GetNewBusinessObjectForTesting();
			communication.OQ_CommunicationID = "CM00001234";

			var contextManager = GetNewContextManager();
			contextManager.Init(communication);

			AssertEquals(DataContextType.Communication, contextManager.DataContextType);
		}

		public void TestDataContextKey()
		{
			var communication = GetNewBusinessObjectForTesting();
			communication.OQ_CommunicationID = "CM00001234";

			var contextManager = GetNewContextManager();
			contextManager.Init(communication);

			AssertEquals("CM00001234", contextManager.DataContextKey);
		}

		public void TestIncomingUniversalEvent()
		{
			var communication = GetNewBusinessObjectForTesting();
			communication.OQ_CommunicationID = "CM00001234";
			BizoFactory.Save();

			var contextManager = GetNewContextManager();
			contextManager.Init(communication);

			var message = GetQueuedUniversalEventMessage($@"
<UniversalEvent xmlns=""http://www.cargowise.com/Schemas/Universal/2011/11"" version=""1.1"">
  <Event>
    <DataContext>
      <DataTargetCollection>
        <DataTarget>
          <Type>Communication</Type>
          <Key>CM00001234</Key>
        </DataTarget>
      </DataTargetCollection>

      <RecipientRoleCollection>
        <RecipientRole>
          <Code>ORP</Code>
          <Description>Organization Proxy</Description>
        </RecipientRole>
      </RecipientRoleCollection>
    </DataContext>

    <EventTime>2019-10-14T08:50:51.07</EventTime>
    <EventType>Z07</EventType>
    <IsEstimate>false</IsEstimate>
  </Event>
</UniversalEvent>");

			var serviceTaskLog = new ServiceTaskLogForTesting();
			var messageProcessingManager = new UniversalMessageProcessingManager(serviceTaskLog);
			messageProcessingManager.Process(message);

			AssertEquals(EDIMessageStatusList.Codes.ProcessedOK, message.EM_Status);

			var expectedLog = $"Linked Event to {communication.HumanReadableName}.";
			AssertMultilineASCIIEquals("Service Task Log", expectedLog, serviceTaskLog.ToString());
			AssertMultilineASCIIEquals("Message Log Note", expectedLog, message.GetLogNoteText());
		}


		}

		protected override void TearDown()
		{
			Form.Dispose();
			userContextChange.Dispose();
			base.TearDown();
		}

		T ActivateTabPage<T>() where T : ZTabPage
		{
			foreach (ZTabPage tabPage in WorkflowUserControl.MainTabControl.TabPages)
			{
				if (tabPage is T)
				{
					WorkflowUserControl.MainTabControl.SelectedTab = tabPage;
					return (T)tabPage;
				}
			}

			return null;
		}

		IRequiresWorkflowSecurity FindWorkflowItemUserControl(Control control)
		{
			foreach (Control childControl in control.Controls)
			{
				IRequiresWorkflowSecurity workflowItemControl = childControl as IRequiresWorkflowSecurity;
				return workflowItemControl ?? FindWorkflowItemUserControl(childControl);
			}

			return null;
		}

		void PrepareCurrentStaff()
		{
			NewStaff = new BusinessObjectFactory().NewWithValidTestData<GlbStaff>();
			NewStaff.Factory.Save();

			userContextChange = Env.SetTemporaryUserContext(new UserContext(NewStaff.GS_LoginName, Env.CurrentBranch.PK, Env.CurrentDepartment.PK));
		}

		internal void PrepareTestForm()
		{
			Dummy = Factory.New<DummyWithWorkflow>();
			Form = new ZForm(Dummy);
			TabControl = new ZTabControl();
			TabPage = new ZWorkflowTabPage();
			TabControl.TabPages.Add(TabPage);
			Form.Controls.Add(TabControl);
			Form.ControllerID = DummyControllerIDs.Dummy;
			TabPage.Initialize(Dummy);
		}

		SecurityCheckpoint SetWorkflowItemSecurityCheckpoint(string workflowItemCheckpointCode, bool isAllowed)
		{
			SecurityCheckpoint checkpoint = Env.Security.FindOrCreateWorkflowItemCheckpoint(DummySecurityCheckpoint, workflowItemCheckpointCode);
			checkpoint.IsAllowed = isAllowed;
			return checkpoint;
		}

		SecurityCheckpoint DummySecurityCheckpoint
		{
			get
			{
				if (dummySecurityCheckpoint == null)
				{
					using (DummyFilterGridModule dummyModule = new DummyFilterGridModule())
					{
						dummySecurityCheckpoint = dummyModule.SecurityCheckpoint;
					}
				}
				return dummySecurityCheckpoint;
			}
		}

		ZWorkflowUserControl WorkflowUserControl
		{
			get { return TabPage.Controls[0] as ZWorkflowUserControl; }
		}


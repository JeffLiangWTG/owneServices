		[RequiresSTA]
		public void TestGetSecurityCheckpointFindForm_DoesntThrowWhenControlParentNull()
		{
			ErrorReporter.Clear();
			Form.Show();

			var control = new TaskWithDetailsAndFilterControl
			{
				Parent = new ZUserControl { Parent = Form }
			};

			AssertNotNull(control.FindForm());
			control.CheckAndConsumeWorkflowLicenceIfAllowed();
			Assert(!ErrorReporter.HasBeenReported("WorkflowSecurityChecks_CannotFindForm"));

			control.Parent = null;
			AssertNull("A parent in the hierarchy should be null", control.FindForm());
			control.CheckAndConsumeWorkflowLicenceIfAllowed();
			Assert(!ErrorReporter.HasBeenReported("WorkflowSecurityChecks_CannotFindForm"));
		}

		void TestWorkflowItemSecurity<T>(string workflowItemCheckpointCode, string workflowItemJustViewCheckpointCode) where T : ZTabPage
		{
			Assert("Precondition", !Env.Licence.Workflow.IsLoggedIn);

			SetWorkflowItemSecurityCheckpoint(SecurityCore.WorkflowTasksAutoGeneratedCode, false);
			SetWorkflowItemSecurityCheckpoint(SecurityCore.WorkflowMilestonesAutoGeneratedCode, false);
			SetWorkflowItemSecurityCheckpoint(SecurityCore.WorkflowExceptionsAutoGeneratedCode, false);
			SetWorkflowItemSecurityCheckpoint(SecurityCore.WorkflowTriggersAutoGeneratedCode, false);
			SetWorkflowItemSecurityCheckpoint(SecurityCore.WorkflowEventsAutoGeneratedCode, false);

			SetWorkflowItemSecurityCheckpoint(SecurityCore.WorkflowTasksJustViewAutoGeneratedCode, false);
			SetWorkflowItemSecurityCheckpoint(SecurityCore.WorkflowMilestonesJustViewAutoGeneratedCode, false);
			SetWorkflowItemSecurityCheckpoint(SecurityCore.WorkflowExceptionsJustViewAutoGeneratedCode, false);
			SetWorkflowItemSecurityCheckpoint(SecurityCore.WorkflowTriggersJustViewAutoGeneratedCode, false);
			SetWorkflowItemSecurityCheckpoint(SecurityCore.WorkflowEventsJustViewAutoGeneratedCode, false);

			//test true, true = can edit
			{
				SecurityCheckpoint editCheckpoint = SetWorkflowItemSecurityCheckpoint(workflowItemCheckpointCode, true);
				SecurityCheckpoint viewCheckpoint = SetWorkflowItemSecurityCheckpoint(workflowItemJustViewCheckpointCode, true);
				Form.Show();
				T tabPage = ActivateTabPage<T>();

				IRequiresWorkflowSecurity userControl = FindWorkflowItemUserControl(tabPage);
				string visibilityErrorMessage = "Should be visible if allowed";
				AssertEquals(visibilityErrorMessage, true, ((Control)userControl).Visible);
				AssertEquals(false, userControl.ViewOnly);
				string licenceErrorMessage = "Should be consumed";
				AssertEquals(licenceErrorMessage, true, Env.Licence.Workflow.IsLoggedIn);
				AssertCoveringLabel(tabPage, false, viewCheckpoint);
			}

			Form.Dispose();
			PrepareTestForm();

			//test true, false = can edit
			{
				SecurityCheckpoint editCheckpoint = SetWorkflowItemSecurityCheckpoint(workflowItemCheckpointCode, true);
				SecurityCheckpoint viewCheckpoint = SetWorkflowItemSecurityCheckpoint(workflowItemJustViewCheckpointCode, false);
				Form.Show();
				T tabPage = ActivateTabPage<T>();

				IRequiresWorkflowSecurity userControl = FindWorkflowItemUserControl(tabPage);
				string visibilityErrorMessage = "Should be visible if allowed";
				AssertEquals(visibilityErrorMessage, true, ((Control)userControl).Visible);
				AssertEquals(false, userControl.ViewOnly);
				string licenceErrorMessage = "Should be consumed";
				AssertEquals(licenceErrorMessage, true, Env.Licence.Workflow.IsLoggedIn);
				AssertCoveringLabel(tabPage, false, viewCheckpoint);
			}

			Form.Dispose();
			PrepareTestForm();

			//test false, true = can view
			{
				SecurityCheckpoint editCheckpoint = SetWorkflowItemSecurityCheckpoint(workflowItemCheckpointCode, false);
				SecurityCheckpoint viewCheckpoint = SetWorkflowItemSecurityCheckpoint(workflowItemJustViewCheckpointCode, true);
				Form.Show();
				T tabPage = ActivateTabPage<T>();

				IRequiresWorkflowSecurity userControl = FindWorkflowItemUserControl(tabPage);
				string visibilityErrorMessage = "Should be visible if allowed";
				AssertEquals(visibilityErrorMessage, true, ((Control)userControl).Visible);
				AssertEquals(true, userControl.ViewOnly);
				string licenceErrorMessage = "Should be consumed";
				AssertEquals(licenceErrorMessage, true, Env.Licence.Workflow.IsLoggedIn);
				AssertCoveringLabel(tabPage, false, viewCheckpoint);
			}

			Form.Dispose();
			PrepareTestForm();

			//test false, false = all denied
			{
				SecurityCheckpoint editCheckpoint = SetWorkflowItemSecurityCheckpoint(workflowItemCheckpointCode, false);
				SecurityCheckpoint viewCheckpoint = SetWorkflowItemSecurityCheckpoint(workflowItemJustViewCheckpointCode, false);
				Form.Show();
				T tabPage = ActivateTabPage<T>();

				IRequiresWorkflowSecurity userControl = FindWorkflowItemUserControl(tabPage);
				AssertNull(userControl);
				var label = tabPage.FindSingle<ZLabel>("SecurityDeniedLabel");
				AssertContains("You do not have the appropriate security rights to run this function.", label.Text);
				string licenceErrorMessage = "Should not be consumed";
				AssertEquals(licenceErrorMessage, false, Env.Licence.Workflow.IsLoggedIn);
				AssertCoveringLabel(tabPage, true, viewCheckpoint);
			}

			Form.Dispose();
			PrepareTestForm();

			//test false, true, registry item to disable edit checkpoints = can edit
			{
				WorkflowDataRegistry.Instance.EnableCheckpointsForWorkflowSecurity.SetValue(Guid.Empty, Guid.Empty, Guid.Empty, false);
				SecurityCheckpoint editCheckpoint = SetWorkflowItemSecurityCheckpoint(workflowItemCheckpointCode, false);
				SecurityCheckpoint viewCheckpoint = SetWorkflowItemSecurityCheckpoint(workflowItemJustViewCheckpointCode, true);
				Form.Show();
				T tabPage = ActivateTabPage<T>();

				IRequiresWorkflowSecurity userControl = FindWorkflowItemUserControl(tabPage);
				AssertEquals("Should be visible if allowed", true, ((Control)userControl).Visible);
				AssertEquals(false, userControl.ViewOnly);
				AssertEquals("Should be consumed", true, Env.Licence.Workflow.IsLoggedIn);
				AssertCoveringLabel(tabPage, false, viewCheckpoint);
			}

			//test false, false, registry item to disable edit checkpoints = can edit
			{
				WorkflowDataRegistry.Instance.EnableCheckpointsForWorkflowSecurity.SetValue(Guid.Empty, Guid.Empty, Guid.Empty, false);
				SecurityCheckpoint editCheckpoint = SetWorkflowItemSecurityCheckpoint(workflowItemCheckpointCode, false);
				SecurityCheckpoint viewCheckpoint = SetWorkflowItemSecurityCheckpoint(workflowItemJustViewCheckpointCode, false);
				Form.Show();
				T tabPage = ActivateTabPage<T>();

				IRequiresWorkflowSecurity userControl = FindWorkflowItemUserControl(tabPage);
				AssertEquals("Should be visible if allowed", true, ((Control)userControl).Visible);
				AssertEquals(false, userControl.ViewOnly);
				AssertEquals("Should be consumed", true, Env.Licence.Workflow.IsLoggedIn);
				AssertCoveringLabel(tabPage, false, viewCheckpoint);
			}
		}

		#region Implementation

		void AssertCoveringLabel(ZTabPage page, bool shouldBeShown, SecurityCheckpoint checkpoint)
		{
			ZLabel coveringLabel = null;

			foreach (Control control in page.Controls)
			{
				ZLabel label = control as ZLabel;
				if (label != null && label.Dock == DockStyle.Fill)
				{
					coveringLabel = label;
					break;
				}
			}

			if (shouldBeShown)
			{
				AssertNotNull("Covering label should be shown", coveringLabel);
				Assert("Covering label should be shown", coveringLabel.Visible);
				AssertEquals(System.Drawing.ContentAlignment.MiddleCenter, coveringLabel.TextAlign);
				AssertEquals(checkpoint.ErrorMessageForNotAllowed, coveringLabel.Text);
			}
			else
			{
				AssertNull("Covering label should not be shown", coveringLabel);
			}
		}

		protected override void SetUp()
		{

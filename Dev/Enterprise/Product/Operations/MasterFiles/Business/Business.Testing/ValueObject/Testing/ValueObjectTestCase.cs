using System;
using System.Collections;
using System.ComponentModel;
using System.Reflection;
using System.Xml.Serialization;
using CargoWise.EntityFramework.Testing;
using NUnit.Framework;
using NUnit.Framework.TestHelper;

namespace Enterprise.DataTransfer.Xml.Testing
{
	[TestsSubclassesOf(
			typeof(IValueObject),
			typeof(Resources.AutoGeneratedSourceCodeAttribute),
			new Type[] { typeof(ValueObjectCollection), typeof(ValueObject) },
			ExcludePrivate = true)]
	public abstract class ValueObjectTestCase : TestCaseWithFactory
	{
		protected Type ValueObjectType => TestedTypeHelper.GetTestedType(GetType());

		protected Type GeneratedValueObjectBaseType
		{
			get
			{
				Type current = ValueObjectType;
				while (current != typeof(object))
				{
					if (current.GetCustomAttributes(typeof(Resources.AutoGeneratedSourceCodeAttribute), false).Length >= 1)
					{
						return current;
					}
					current = current.BaseType;
				}
				return null;
			}
		}

		public void TestValueObjectSubclassAttributeAppliedCorrectly()
		{
			if (GeneratedValueObjectBaseType != null)
			{
				ValueObjectSubclassAttribute attr = (ValueObjectSubclassAttribute)TypeDescriptor.GetAttributes(ValueObjectType)[typeof(ValueObjectSubclassAttribute)];
				AssertNotNull("A value object that is sub-classing an xsd-generated value object should have [ValueObjectSubclass] applied", attr);
				Type attributeSpecifiedBaseType = ValueObjectType.Assembly.GetType(attr.TypeName)
					?? ValueObjectType.BaseType.Assembly.GetType(attr.TypeName);
				AssertEquals("Base generated value object type we are subclassing should exist", GeneratedValueObjectBaseType, attributeSpecifiedBaseType);
			}
			else
			{
				Assert("Not required if the value object is not auto-generated", true);
			}
		}

		public void TestAutoGeneratedBaseValueObjectAbstract()
		{
			if (GeneratedValueObjectBaseType != null)
			{
				AssertEquals(
					"Base generated type should be abstract. If it is not, this generally indicates generation of code didn't take into consideration the sub-class. Try re-generating.",
					true, GeneratedValueObjectBaseType.IsAbstract);
			}
			else
			{
				Assert("Not required if the value object is not auto-generated", true);
			}
		}

		public void TestNoNewXmlSerializedFieldsOrProperties()
		{
			ArrayList fieldsAndProperties = new ArrayList();
			fieldsAndProperties.AddRange(ValueObjectType.GetFields(BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly));
			fieldsAndProperties.AddRange(ValueObjectType.GetProperties(BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly));

			string problemFields = "";
			foreach (MemberInfo fieldOrProperty in fieldsAndProperties)
			{
				if (fieldOrProperty.GetCustomAttributes(typeof(XmlIgnoreAttribute), false).Length == 0)
				{
					problemFields += fieldOrProperty.Name + "\r\n";
				}
			}
			AssertEquals("The following fields/properties need XmlIgnoreAttribute applied to them:\r\n\r\n" + problemFields, "", problemFields);
		}
	}
}

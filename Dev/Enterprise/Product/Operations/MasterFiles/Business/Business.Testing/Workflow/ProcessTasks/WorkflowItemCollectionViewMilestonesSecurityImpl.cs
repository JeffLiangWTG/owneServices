using Enterprise.Security;
using NUnit.Framework;

namespace Enterprise.MasterFiles.Business.Testing.Workflow.ProcessTasks
{
	[TestedType(typeof(WorkflowItemCollectionView))]
	class WorkflowItemCollectionViewMilestonesSecurityImpl : WorkflowItemCollectionViewSecurityTest
	{
		public void TestAllowNewCoreIsFalseIfSecurityDenies()
		{
			AssertAllowNewSecurity<GlbPerson>(person => person.WorkflowItems.Milestones, SecurityCore.WorkflowAddMilestonesAutoGeneratedCode, false);
		}

		public void TestAllowNewCoreIsTrueIfSecurityAllows()
		{
			AssertAllowNewSecurity<GlbPerson>(person => person.WorkflowItems.Milestones, SecurityCore.WorkflowAddMilestonesAutoGeneratedCode, true);
		}

		public void TestAllowNewCoreIsTrueByDefault()
		{
			AssertDefaultAllowNewSecurity<GlbPerson>(person => person.WorkflowItems.Milestones);
		}

		public void TestAllowRemoveCoreIsTrueByDefault()
		{
			AssertDefaultAllowRemoveSecurity<GlbPerson>(person => person.WorkflowItems.Milestones);
		}
	}
}

using Enterprise.Security;
using NUnit.Framework;

namespace Enterprise.MasterFiles.Business.Testing.Workflow.ProcessTasks
{
	[TestedType(typeof(WorkflowItemCollectionView))]
	class WorkflowItemCollectionViewExceptionsSecurityTest : WorkflowItemCollectionViewSecurityTest
	{
		public void TestAllowNewCoreIsFalseIfSecurityDenies()
		{
			AssertAllowNewSecurity<GlbPerson>(person => person.WorkflowItems.Exceptions, SecurityCore.WorkflowAddExceptionsAutoGeneratedCode, false);
		}

		public void TestAllowNewCoreIsTrueIfSecurityAllows()
		{
			AssertAllowNewSecurity<GlbPerson>(person => person.WorkflowItems.Exceptions, SecurityCore.WorkflowAddExceptionsAutoGeneratedCode, true);
		}

		public void TestAllowNewCoreIsTrueByDefault()
		{
			AssertDefaultAllowNewSecurity<GlbPerson>(person => person.WorkflowItems.Exceptions);
		}

		public void TestAllowRemoveCoreIsTrueByDefault()
		{
			AssertDefaultAllowRemoveSecurity<GlbPerson>(person => person.WorkflowItems.Exceptions);
		}
	}
}

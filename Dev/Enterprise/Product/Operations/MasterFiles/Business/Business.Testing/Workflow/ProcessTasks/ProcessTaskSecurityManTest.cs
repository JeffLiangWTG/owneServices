		public void TestStandaloneTaskAllowEditFromDifferentCompany()
		{
			var company = Factory.NewWithValidTestData<GlbCompany>();
			var branch = company.Branches.AddNew();
			branch.FillWithValidTestData();
			Factory.Save();

			var task = Factory.NewWithValidTestData<ProcessTask>();
			AssertEquals(true, task.IsStandaloneTask);

			using (WorkflowDataRegistry.Instance.EnableCheckpointsForWorkflowSecurity.SetTemporaryValue(Guid.Empty, Guid.Empty, Guid.Empty, true))
			{
				Env.Security.WorkflowTasksEdit.IsAllowed = false;
				AssertEquals(false, ProcessTaskSecurityMan.IsAllowEdit(task));
				using (Env.SetTemporaryUserContext(Env.CurrentUserPK, branch.PK.ToGuid(), Env.CurrentDepartmentPK))
				{
					AssertEquals(false, ProcessTaskSecurityMan.IsAllowEdit(task));
				}

				Env.Security.WorkflowTasksEdit.IsAllowed = true;
				AssertEquals(true, ProcessTaskSecurityMan.IsAllowEdit(task));
				using (Env.SetTemporaryUserContext(Env.CurrentUserPK, branch.PK.ToGuid(), Env.CurrentDepartmentPK))
				{
					AssertEquals(true, ProcessTaskSecurityMan.IsAllowEdit(task));
				}
			}

			using (WorkflowDataRegistry.Instance.EnableCheckpointsForWorkflowSecurity.SetTemporaryValue(Guid.Empty, Guid.Empty, Guid.Empty, false))
			{
				Env.Security.WorkflowTasksEdit.IsAllowed = false;
				AssertEquals(true, ProcessTaskSecurityMan.IsAllowEdit(task));
				using (Env.SetTemporaryUserContext(Env.CurrentUserPK, branch.PK.ToGuid(), Env.CurrentDepartmentPK))
				{
					AssertEquals(true, ProcessTaskSecurityMan.IsAllowEdit(task));
				}

				Env.Security.WorkflowTasksEdit.IsAllowed = true;
				AssertEquals(true, ProcessTaskSecurityMan.IsAllowEdit(task));
				using (Env.SetTemporaryUserContext(Env.CurrentUserPK, branch.PK.ToGuid(), Env.CurrentDepartmentPK))
				{
					AssertEquals(true, ProcessTaskSecurityMan.IsAllowEdit(task));
				}
			}
		}


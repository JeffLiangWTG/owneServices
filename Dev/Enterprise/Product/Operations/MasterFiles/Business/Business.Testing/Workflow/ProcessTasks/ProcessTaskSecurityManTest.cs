		{
			// Create the checkpoint before creating the task. This ensures the checkpoint permissions are set in case the task
			// instantiation also creates an equivalent checkpoint and caches it using Factory.GetCachedValue()
			// In Production, checkpoints will always be loaded before any tasks anyway
			SecurityCheckpoint checkpoint = GetCheckpoint(Dummy.ControllerID, SecurityCore.WorkflowTriggersAutoGeneratedCode);
			checkpoint.IsAllowed = isAllowed;

			var task = GetTaskWithParent(Constants.Workflow.WorkflowTriggerType);

			AssertEquals(isAllowed, ((IBindingList)task.ProcessTaskNotifications).AllowNew);
		}


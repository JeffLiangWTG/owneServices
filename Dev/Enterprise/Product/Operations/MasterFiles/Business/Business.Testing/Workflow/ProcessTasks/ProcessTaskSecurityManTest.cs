		void AssertIgnoredCheckpointHasNoEffect(string taskType, Func<ProcessTask, bool> securityFunc, SecurityCheckpoint expectedCheckpoint, SecurityCheckpoint ignoredCheckpoint, bool expectedIsAllowed, bool ignoredIsAllowed)
		{
			// Set checkpoint properties before creating the task. This ensures the checkpoint permissions are set in case the task
			// instantiation also creates an equivalent checkpoint and caches it using Factory.GetCachedValue()
			// In Production, checkpoints will always be loaded before any tasks anyway
			expectedCheckpoint.IsAllowed = expectedIsAllowed;
			ignoredCheckpoint.IsAllowed = ignoredIsAllowed;

			var task = GetTaskWithParent(taskType);
			AssertEquals(expectedCheckpoint.IsAllowed, securityFunc(task));
		}

		void AssertRegistryItemFalseIgnoresCheckpoint(string taskType, string securityCode, Func<ProcessTask, bool> securityFunc)
		{
			WorkflowDataRegistry.Instance.EnableCheckpointsForWorkflowSecurity.SetValue(Guid.Empty, Guid.Empty, Guid.Empty, false);
			SecurityCheckpoint cp = GetCheckpoint(ControllerId, securityCode);
			cp.IsAllowed = false;

			var task = GetTaskWithParent(taskType);

			AssertEquals(true, securityFunc(task));
		}

		void AssertDeleteReason(string taskType, string securityCode)
		{
			SecurityCheckpoint checkpoint = GetCheckpoint(Dummy.ControllerID, securityCode);
			checkpoint.IsAllowed = false;

			var task = GetTaskWithParent(taskType);
			var displayType = GetDisplayType(taskType);
			var companyName = task.Factory.Load<GlbCompany>(task.P9_GC)?.GC_Code;

			var expected = string.Format("You do not have security permissions to delete the following for company {0}: {1} ({2})",
											companyName, displayType, checkpoint.DisplayTextPathToSecurityRight);
			AssertEquals(expected, task.ReasonForNotAbleToDelete);
		}

		string GetDisplayType(string taskType)
		{
			switch (taskType)
			{
				case Constants.Workflow.MilestoneType:
					return "Milestones";
				case Constants.Workflow.ExceptionType:
					return "Exceptions";
				case Constants.Workflow.WorkflowTriggerType:
					return "Triggers";
				default:
					return "Tasks";
			}
		}

		SecurityCheckpoint GetCheckpoint(ControllerID controllerId, string securityCode)
		{
			var controller = ObjectFactory.Get<IControllerFactory>().Create(controllerId);
			using (var module = ObjectFactory.Get<IModuleFactory>().Create(controller.ModuleID))
			{
				return (SecurityCheckpoint)module.GetWorkflowTasksCheckpoint(securityCode);
			}
		}

		ProcessTask GetTaskWithParent(string type = null)
		{
			ProcessTask task = Dummy.WorkflowItems.AddNew();
			if (type != null)
			{
				task.P9_Type = type;
			}

			return task;
		}


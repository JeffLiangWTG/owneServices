using Enterprise.Security;
using NUnit.Framework;

namespace Enterprise.MasterFiles.Business.Testing.Workflow.ProcessTasks
{
	[TestedType(typeof(WorkflowItemCollectionView))]
	class WorkflowItemCollectionViewSecurityTriggersTest : WorkflowItemCollectionViewSecurityTest
	{
		public void TestAllowNewCoreIsFalseIfSecurityDenies()
		{
			AssertAllowNewSecurity<GlbPerson>(person => person.WorkflowItems.Triggers, SecurityCore.WorkflowAddTriggersAutoGeneratedCode, false);
		}

		public void TestAllowNewCoreIsTrueIfSecurityAllows()
		{
			AssertAllowNewSecurity<GlbPerson>(person => person.WorkflowItems.Triggers, SecurityCore.WorkflowAddTriggersAutoGeneratedCode, true);
		}

		public void TestAllowNewCoreIsTrueByDefault()
		{
			AssertDefaultAllowNewSecurity<GlbPerson>(person => person.WorkflowItems.Triggers);
		}

		public void TestAllowRemoveCoreIsTrueByDefault()
		{
			AssertDefaultAllowRemoveSecurity<GlbPerson>(person => person.WorkflowItems.Triggers);
		}
	}
}

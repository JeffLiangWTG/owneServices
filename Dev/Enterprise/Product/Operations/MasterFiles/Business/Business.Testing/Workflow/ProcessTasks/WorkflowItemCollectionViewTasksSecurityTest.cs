using Enterprise.Security;
using NUnit.Framework;

namespace Enterprise.MasterFiles.Business.Testing.Workflow.ProcessTasks
{
	[TestedType(typeof(WorkflowItemCollectionView))]
	class WorkflowItemCollectionViewTasksSecurityTest : WorkflowItemCollectionViewSecurityTest
	{
		public void TestAllowNewCoreIsFalseIfSecurityDenies()
		{
			AssertAllowNewSecurity<GlbPerson>(person => person.WorkflowItems.Tasks, SecurityCore.WorkflowAddTasksAutoGeneratedCode, false);
		}

		public void TestAllowNewCoreIsTrueIfSecurityAllows()
		{
			AssertAllowNewSecurity<GlbPerson>(person => person.WorkflowItems.Tasks, SecurityCore.WorkflowAddTasksAutoGeneratedCode, true);
		}

		public void TestAllowNewCoreIsTrueByDefault()
		{
			AssertDefaultAllowNewSecurity<GlbPerson>(person => person.WorkflowItems.Tasks);
		}

		public void TestAllowRemoveCoreIsTrueByDefault()
		{
			AssertDefaultAllowRemoveSecurity<GlbPerson>(person => person.WorkflowItems.Tasks);
		}
	}
}

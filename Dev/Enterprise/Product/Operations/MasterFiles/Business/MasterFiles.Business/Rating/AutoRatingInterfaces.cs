	public struct CanUpdateCarrierContractNumberResult
	{
		public CanUpdateCarrierContractNumberResult(IEnumerable<string> newContractNumbers)
		{
			CanUpdate = true;
			Token = new UpdateCarrierContractNumberToken(newContractNumbers);
			ConfirmationMessageForOverridingJobContractNumber = null;
		}

		/// <summary>
		/// CanUpdate should be true when we expect UpdateCarrierContractNumber to be called and continue Autorating.
		/// When it is false, UpdateCarrierContractNumber should not be called and we should stop Autorating.
		/// </summary>
		public bool CanUpdate { get; set; }
		public UpdateCarrierContractNumberToken Token { get; set; }
		public string ConfirmationMessageForOverridingJobContractNumber { get; set; }
	}

	public struct UpdateCarrierContractNumberToken
	{
		public UpdateCarrierContractNumberToken(IEnumerable<string> newContractNumbers)
		{
			NewContractNumbers = newContractNumbers;
			SelectionResult = default(SingleCarrierContractNumberSelectionResult);
		}

		public IEnumerable<string> NewContractNumbers { get; set; }
		public SingleCarrierContractNumberSelectionResult SelectionResult { get; set; }
	}

	public enum DataUpdateResult
	{
		Cancelled = -1,
		NoAction = 0,
		Updated = 1
	}


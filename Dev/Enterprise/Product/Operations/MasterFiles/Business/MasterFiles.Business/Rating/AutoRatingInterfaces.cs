	/// <summary>
	///		Provides information required by the autorating engine.
	/// </summary>
	/// <remarks>
	///		When implementing the interface, please consider to use <see cref="RatingAdapter"/> or its generic version as a base class.
	/// </remarks>
	public interface IAutoRating : IAutoRatingLocations, IAutoRatingOrganisations, IAutoRatingFreightInfo
	{
		IJobInvoicingSupporter InvoicingSupporter { get; }
		IJobDatesProvider JobDatesProvider { get; }
		AutoRatingStatusInfo StatusInformation { get; }
		ChargeCodeGroupCollection ChargeCodeGroups { get; }
		JobServicesCollection JobServices { get; }
		ZBool IsServicesOnly { get; }
		IEnumerable<ZString> CarrierContractNumbers { get; }
		IEnumerable<ZString> ClientContractNumbers { get; }
		IContractNumberConfiguration GetContractNumberConfiguration(CostSell costOrSell);
		RateType RateTypeToUse { get; }
		JobInvoicingConsumerType ConsumerType { get; }
		MergeChargeOptions MergeCharges { get; }
		Collection<IBusiness> AutoRatedFor { get; }
		ZInt RouteSetNumber { get; }
		IJobExRateCurrencyConverter CurrencyConverter { get; }
		AdapterType AdapterType { get; }
		ZString OperationalJobCode { get; }
		ZString JobID { get; }
		ZString PaymentTermOverride { get; }

		/// <summary>
		///		Per Job charges correspond to charges which don't calculate per specific measure type and part.
		///		Such charges are applicable to the whole job rather than to a concrete measure part of the job.
		///		Usually, it is charges with Flat or Percentage calculators which don't depend on a specific unit.
		///
		///		In some scenarios we may have multiple adapters for the same job autorating specific charges or specific parts of the job.
		///		But, they all will autorate charges per Job which will lead to duplicated charges created.
		///		This flag allows controlling this, i.e. we will allow only 1 adapter to autorate such kind of charges.
		///
		///		Please note that this solution is a bit of hack. A normal solution would be:
		///		1. Create a specific measure type (MeasureType.Job?) for such kind of charges. Unidentified - is a bit confusing name.
		///		2. Those adapters who want to AutoRate such charges (almost all adapters) will have to explicitly add this measure type
		///			with some dummy JobLevelPart
		///		3. Update the LineMeasureMatcher logic that if a part is null then filter out the line at all. If it is MeasureType.Job
		///			then calculate it as per job, otherwise calculate it as Part.
		///
		///		But, too much changes required. Perhaps we can do it later as a refactoring.
		/// </summary>
		ZBool ShouldDiscardPerJobCharges { get; }

		/// <summary>
		/// Usually service charge code is filtered out when job has no service at all.
		/// This method allow rating adapter to override that. Chargeable unit on calculator will then be empty and we usually report it as an issue.
		/// We use the result to skip the report and create empty calculation output.
		/// </summary>
		bool ShouldRemoveChargeWhenMissingServiceOrChargeableUnit(AccChargeCode chargeCode);

		/// <summary>
		/// Comparable attributes differentiate AutoRateInfos when merging them.
		/// RatingAdapters can override this by providing a list of attribute codes for excluding them from comparisons.
		/// </summary>
		IEnumerable<ZString> ExcludedAttributesWhenMergingRateInfos { get; }

		/// <summary>
		///		Called when the adapter has been autorated.
		///		Required by some jobs to override some details on the generated charges.
		///		Also it can be used by jobs to do some post-autorating actions.
		/// </summary>
		/// <param name="charges">
		///		The charges and their details generated by the autorating engine while autorating this adapter.
		///	</param>
		void OnAutoRated(IEnumerable<IAutoRatedCharge> charges);

		ZString HBLDeliveryMode { get; }
	}


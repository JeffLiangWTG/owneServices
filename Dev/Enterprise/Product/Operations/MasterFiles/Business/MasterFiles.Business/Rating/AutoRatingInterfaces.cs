	/// <summary>
	/// Specific flags defined by rating adapters for AutoRating to filter rates contract numbers
	/// </summary>
	public interface IContractNumberConfiguration
	{
		/// <summary>
		/// This flag helps rating adapters to tell AutoRating to filter rates early from DB level.
		/// When a rating adapter has an option to ignore job's contract numbers like in
		///   FreightConfigurationRegistry.Instance.IgnoreAndReplaceClientContractNumbersDuringAutorating
		///   FreightConfigurationRegistry.Instance.IgnoreAndReplaceCarrierContractNumbersDuringAutorating
		///   or in AgencyRegistry.Instance.ReplaceExistingContractNumbersWithNewNumbers,
		/// we should not add query filter to rates query while in the other hand, we can add the numbers to the query.
		///
		/// Only called if the job has contract numbers (including a blank number).
		/// If true, adds those contract numbers (plus blank) to the filter used to load CW1 rates from DB.
		/// Causes rates with a contract number not on the job to be ignored.
		/// </summary>
		bool ShouldAddContractNumberQueryFilter { get; }

		/// <summary>
		/// At RateEntriesRepository level. We scan rates with job's contract number and filter them.
		/// When the flag is false, AutoRating should just match rate contract numbers vs job's ones, fallback with empty number rates.
		/// When it is true, AutoRating will check flags below defined by each rating adapter to filter rates in specific ways.
		/// </summary>
		bool ShouldApplySpecificAdapterContractNumberFilter { get; }

		/// <summary>
		/// When a rating adapter tells AutoRating to ignore job's client contract numbers then usually with Revenue, the numbers
		/// do not influence the contract number filtering, all rates should be accepted.
		/// </summary>
		bool ShouldIgnoreJobClientContractNumbers { get; }

		/// <summary>
		/// When a rating adapter tells AutoRating to ignore job's carrier contract numbers then usually with Costing, the numbers
		/// do not influence the contract number filtering, all rates should be accepted.
		/// </summary>
		bool ShouldIgnoreJobCarrierContractNumbers { get; }

		/// <summary>
		/// For Revenue,
		///		Enable this setting to use blank contract number as a very strict differentiator.
		///		AutoRating will not accept empty number rates when job has no blank contract number.
		///
		/// For Costing,
		///		It's not that strict. Using this setting with some extra conditions to decide if blank number rates should be kept or filtered.
		/// </summary>
		bool ShouldMatchJobBlankContractNumber { get; }

		/// <summary>
		/// For Consol's Autorating, it should be true if the registry set to true, so we use Carrier's contract Autorating Date filter option
		/// </summary>
		bool ShouldUseCarrierContractDateFilter { get; }
	}


using System;
using System.Collections.Generic;
using CargoWise.Application;
using CargoWise.EntityFramework;
using CargoWise.Types;
using Enterprise.Core;
using Enterprise.Environment;
using Enterprise.Integration;
using Enterprise.Registry.Business;
using Enterprise.Security;
using Enterprise.ZArchitecture;
using Enterprise.ZArchitecture.Core;
using Enterprise.ZArchitecture.Modules;

namespace Enterprise.MasterFiles.Business
{
	public static class ProcessTaskSecurityMan
	{
		public static bool IsAllowDelete(ProcessTask task)
		{
			if (WorkflowDataRegistry.Instance.EnableCheckpointsForWorkflowSecurity.Value)
			{
				if (task.IsStandaloneTask)
				{
					return Env.Security.WorkflowTasksDelete.IsAllowed;
				}

				return IsAllowed(task, GetDeleteCode(task));
			}

			return true;
		}

		public static bool IsAllowOverrideExceptionDuration(ProcessTask task)
		{
			if (WorkflowDataRegistry.Instance.EnableCheckpointsForWorkflowSecurity.Value)
			{
				return IsAllowed(task, SecurityCore.WorkflowOverrideExceptionDurationAutoGeneratedCode);
			}

			return true;
		}

		public static MultilingualString GetPreventDeleteReason(ProcessTask task)
		{
			MultilingualString path = (NoResString)string.Empty;

			var moduleId = task.ModuleID;
			if (moduleId != null)
			{
				var securityCode = GetDeleteCode(task);

				path = task.Factory.GetCachedValue(
					FormattableString.Invariant($"Module {moduleId.ID} Permission {securityCode} Prevent Delete Reason"),
					() => GetCheckpointDisplayPath(securityCode, moduleId));
			}

			var companyName = GetCompanyName(task);

			return ResString.GetMultilingualString(
					"40b0fd8c-37c6-4e40-b07d-31871dd8e8d9", "You do not have security permissions to delete the following for company {0}: {1} ({2})",
					companyName, GetTypeDisplayText(task), path);
		}

		static ZString GetCompanyName(ProcessTask task)
		{
			var company = task.Factory.Load<GlbCompany>(task.P9_GC);
			return company != null ? company.GC_Code : ZString.Empty;
		}

		static MultilingualString GetTypeDisplayText(ProcessTask task)
		{
			switch (task.P9_Type)
			{
				case Constants.Workflow.MilestoneType:
					return ResString.GetMultilingualString("67d50c44-7b5a-4a06-8e5e-6c7936e2472a", "Milestones");
				case Constants.Workflow.ExceptionType:
					return ResString.GetMultilingualString("a4bd0620-a070-4e06-961d-3a9d0f123c13", "Exceptions");
				case Constants.Workflow.WorkflowTriggerType:
					return ResString.GetMultilingualString("231cd002-8c2c-425c-be91-ef5b4cefb9e6", "Triggers");
				default:
					return ResString.GetMultilingualString("be581b7a-2202-45ea-b52c-8ea65d4a7e4a", "Tasks");
			}
		}

		static string GetDeleteCode(ProcessTask task)
		{
			switch (task.P9_Type)
			{
				case Constants.Workflow.MilestoneType:
					return SecurityCore.WorkflowDeleteMilestonesAutoGeneratedCode;
				case Constants.Workflow.ExceptionType:
					return SecurityCore.WorkflowDeleteExceptionsAutoGeneratedCode;
				case Constants.Workflow.WorkflowTriggerType:
					return SecurityCore.WorkflowDeleteTriggersAutoGeneratedCode;
				default:
					return SecurityCore.WorkflowDeleteTasksAutoGeneratedCode;
			}
		}

		public static bool IsAllowEdit(ProcessTask task)
		{
			if (WorkflowDataRegistry.Instance.EnableCheckpointsForWorkflowSecurity.Value)
			{
				if (task.IsStandaloneTask)
				{
					return Env.Security.WorkflowTasksEdit.IsAllowed;
				}

				if (task.IsTask && !task.P9_ShareTasksForAllCompanies && task.P9_GC.IsValid && task.P9_GC != Env.CurrentCompanyPK)
				{
					return false;
				}

				return IsAllowed(task, GetEditCode(task));
			}

			return true;
		}

		public static bool IsAllowEdit(IBaseTrigger trigger)
		{
			if (trigger is ProcessTask task)
			{
				return IsAllowEdit(task);
			}

			return true;
		}

		static string GetEditCode(ProcessTask task)
		{
			switch (task.P9_Type)
			{
				case Constants.Workflow.MilestoneType:
					return SecurityCore.WorkflowMilestonesAutoGeneratedCode;
				case Constants.Workflow.ExceptionType:
					return SecurityCore.WorkflowExceptionsAutoGeneratedCode;
				case Constants.Workflow.WorkflowTriggerType:
					return SecurityCore.WorkflowTriggersAutoGeneratedCode;
				default:
					return SecurityCore.WorkflowTasksAutoGeneratedCode;
			}
		}

		static bool IsAllowed(ProcessTask task, string securityCode) => IsAllowed(task.Factory, task, task.ModuleID, securityCode, task.P9_GC);

		public static bool IsAllowed(ProcessTaskCollection collection, string securityCode)
		{
			if (WorkflowDataRegistry.Instance.EnableCheckpointsForWorkflowSecurity.Value)
			{
				if (collection == null
				|| !WorkflowDescriptors.Instance.TryGetValue(collection.WorkflowType, out var descriptor)
				|| descriptor?.ControllerID == null)
				{
					return true;
				}

				var factory = collection.Factory;
				return IsAllowed(factory, null, descriptor.ControllerID.GetModuleId(factory), securityCode, Env.CurrentCompanyPK);
			}

			return true;
		}

		static bool IsAllowed(BusinessObjectFactory factory, ProcessTask processTask, ModuleIdentifier moduleId, string securityCode, ZGuid company)
		{
			if (moduleId == null)
			{
				return true;
			}

			var cache = factory.GetCachedValue("ProcessTaskSecurityManIsAllowedCache", () => new Dictionary<(ModuleId, string, ZGuid), bool>());

			var key = ((ModuleId)moduleId.ID, securityCode, company);
			if (cache.TryGetValue(key, out var result))
			{
				return result;
			}
			else
			{
				return cache[key] = IsAllowedCore(factory, processTask, securityCode, company, moduleId);
			}
		}

		static bool IsAllowedCore(BusinessObjectFactory factory, ProcessTask processTask, string securityCode, ZGuid company, ModuleIdentifier moduleId)
		{
			using (var module = ObjectFactory.Get<IModuleFactory>().Create(moduleId))
			{
				if (module == null || module.SecurityCheckpoint == Env.Security.None)
				{
					return true;
				}

				using (SwitchUserContext(factory, company))
				{
					ISecurityCheckpoint security;

					if (processTask?.ParentBusinessObject != null)
					{
						security = module.GetWorkflowTasksCheckpoint(processTask.ParentBusinessObject, securityCode);
					}
					else
					{
						security = module.GetWorkflowTasksCheckpoint(securityCode);
					}

					return security.IsAllowed;
				}
			}
		}

		static MultilingualString GetCheckpointDisplayPath(string securityCode, ModuleIdentifier moduleId)
		{
			using (var module = ObjectFactory.Get<IModuleFactory>().Create(moduleId))
			{
				if (module == null || module.SecurityCheckpoint == Env.Security.None)
				{
					return (NoResString)string.Empty;
				}

				// Don't need to switch user context here because the checkpoint path will be the same regardless
				// of which company is allowed/denied. We simply need to get the path for display purposes
				var security = module.GetWorkflowTasksCheckpoint(securityCode);
				return security.DisplayTextPathToSecurityRight;
			}
		}

		static IDisposable SwitchUserContext(BusinessObjectFactory factory, ZGuid companyPk)
		{
			if (companyPk.IsValid && !Env.CurrentCompanyPK.Equals(companyPk.ToGuid()))
			{
				var branchPK = GetBestBranch(factory, companyPk); // This is flaky. What if there is permission in one branch but not the other?
				if (branchPK.HasValue)
				{
					return Env.SetTemporaryUserContext(Env.CurrentUserPK, branchPK.Value, Env.CurrentDepartmentPK);
				}
			}

			return null;
		}

		static Guid? GetBestBranch(BusinessObjectFactory factory, ZGuid companyPk)
		{
			return factory.Load<GlbCompany>(companyPk)?.FirstActiveBranch?.PK.ToGuid();
		}
	}
}

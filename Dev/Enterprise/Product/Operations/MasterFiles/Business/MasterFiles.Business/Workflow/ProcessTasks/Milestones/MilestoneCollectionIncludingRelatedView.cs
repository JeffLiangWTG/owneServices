using System.Collections;
using System.Collections.Generic;
using Enterprise.Security;
using Enterprise.ZArchitecture.Environment;

namespace Enterprise.MasterFiles.Business
{
	public class MilestoneCollectionIncludingRelatedView : WorkflowItemCollectionIncludingRelatedView
	{
		public MilestoneCollectionIncludingRelatedView(ProcessTaskCollection collection)
			: base(collection)
		{
		}

		#region WorkflowItemCollectionView Overrides

		protected override bool IsTypeMatch(ProcessTask task)
		{
			return task.IsMilestone && (!Globals.IsWeb || task.P9_IsPublished);
		}

		protected override TemplateEntityType TemplateEntityType => TemplateEntityType.Milestones;

		protected override string AddSecurityCode => SecurityCore.WorkflowAddMilestonesAutoGeneratedCode;

		protected override IEqualityComparer<ProcessTask> GetTemplateApplicationComparer() => new TriggerToTemplateComparer();

		#endregion

		#region Relationships

		protected override void AddNewTaskCore(ProcessTask child)
		{
			child.IsMilestone = true;
			base.AddNewTaskCore(child);
		}

		#endregion

		#region Related Milestone Default Sort when Shadowing

		protected override IComparer GetDefaultOrderComparerCore() => new MilestoneRelatedItemComparer(base.GetDefaultOrderComparerCore());

		class MilestoneRelatedItemComparer : IComparer, IComparer<ProcessTask>
		{
			public MilestoneRelatedItemComparer(IComparer baseComparer)
			{
				this.baseComparer = baseComparer;
			}
			readonly IComparer baseComparer;

			public int Compare(ProcessTask x, ProcessTask y)
			{
				int result = 0;
				if (x.P9_ScheduledDate.IsValid && y.P9_ScheduledDate.IsValid)
				{
					result = x.P9_ScheduledDate.CompareTo(y.P9_ScheduledDate);
				}
				if (result == 0)
				{
					result = baseComparer.Compare(x, y);
				}
				return result;
			}

			int IComparer.Compare(object x, object y) => Compare((ProcessTask)x, (ProcessTask)y);
		}

		#endregion

		#region Last/Next Milestones

		MilestonePositionHelper MilestonePositionHelper
		{
			get { return fMilestonePositionHelper ?? (fMilestonePositionHelper = new MilestonePositionHelper((ProcessTask[])this.ToArray(typeof(ProcessTask)))); }
		}

		MilestonePositionHelper fMilestonePositionHelper;

		public ProcessTask NextMilestone
		{
			get { return MilestonePositionHelper.NextMilestone; }
		}

		public ProcessTask LastMilestone
		{
			get { return MilestonePositionHelper.LastMilestone; }
		}

		public ProcessTask CurrentCompanyNextMilestone
		{
			get { return MilestonePositionHelper.CurrentCompanyNextMilestone; }
		}

		public ProcessTask CurrentCompanyLastMilestone
		{
			get { return MilestonePositionHelper.CurrentCompanyLastMilestone; }
		}

		#endregion
	}
}

using System;
using System.Collections.Generic;
using Enterprise.Security;

namespace Enterprise.MasterFiles.Business
{
	public class ExceptionCollectionIncludingRelatedView : WorkflowItemCollectionIncludingRelatedView
	{
		public ExceptionCollectionIncludingRelatedView(ProcessTaskCollection collection)
			: base(collection)
		{
		}

		protected override bool IsTypeMatch(ProcessTask task)
		{
			return task.IsException;
		}

		protected override void AddNewTaskCore(ProcessTask task)
		{
			task.IsException = true;
			base.AddNewTaskCore(task);
		}

		protected override IEqualityComparer<ProcessTask> GetTemplateApplicationComparer() => throw new NotImplementedException("Exceptions don't have template application");

		protected override TemplateEntityType TemplateEntityType => TemplateEntityType.None;

		protected override string AddSecurityCode => SecurityCore.WorkflowAddExceptionsAutoGeneratedCode;
	}
}

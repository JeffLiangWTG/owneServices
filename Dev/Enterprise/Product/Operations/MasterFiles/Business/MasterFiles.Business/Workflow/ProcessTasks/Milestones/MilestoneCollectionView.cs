using System.Collections.Generic;
using System.Linq;
using CargoWise.ComponentModel;
using CargoWise.EntityFramework;
using CargoWise.Types;
using Enterprise.Security;
using Enterprise.ZArchitecture.Schema;

namespace Enterprise.MasterFiles.Business
{
	public class MilestoneCollectionView : MilestoneOrTriggerCollectionView
	{
		public MilestoneCollectionView(ProcessTaskCollection collection)
			: base(collection)
		{
			this.collection = collection;
		}
		readonly ProcessTaskCollection collection;

		internal BusinessObject Parent => collection?.Parent;

		#region WorkflowItemCollectionView Overrides

		protected override bool IsTypeMatch(ProcessTask task)
		{
			return task.IsMilestone;
		}

		protected override TemplateEntityType TemplateEntityType => TemplateEntityType.Milestones;

		protected override string AddSecurityCode => SecurityCore.WorkflowAddMilestonesAutoGeneratedCode;

		protected override bool AllowSort => true;

		protected override IEqualityComparer<ProcessTask> GetTemplateApplicationComparer() => new TriggerToTemplateComparer();

		protected override bool HasExistingItemsBlockingTemplateApplication => this.Cast<ProcessTask>().Any(t => t.P9_GC == GlbCompany.CurrentCompany.PK && t.TriggerConditions.TriggerContextCode != TriggerUserContextList.Codes.Specified);

		#endregion

		#region Relationships

		protected override void AddNewTaskCore(ProcessTask child)
		{
			child.IsMilestone = true;
			base.AddNewTaskCore(child);
		}

		#endregion

		#region Last/Next Milestones

		MilestonePositionHelper MilestonePositionHelper
		{
			get
			{
				return new MilestonePositionHelper((ProcessTask[])this.ToArray(typeof(ProcessTask)));
			}
		}

		public ProcessTask NextMilestone
		{
			get { return MilestonePositionHelper.NextMilestone; }
		}

		public ProcessTask LastMilestone
		{
			get { return MilestonePositionHelper.LastMilestone; }
		}

		public ProcessTask CurrentCompanyNextMilestone
		{
			get { return MilestonePositionHelper.CurrentCompanyNextMilestone; }
		}

		public ProcessTask CurrentCompanyLastMilestone
		{
			get { return MilestonePositionHelper.CurrentCompanyLastMilestone; }
		}

		#endregion

		#region SetMilestoneStatues

		internal void SetMilestoneStatuses()
		{
#if DEBUG
			SetMilestoneStatusesAndRefreshCountForDebug++;
#endif
			RefreshMilestonesFromDb();
			SetMilestoneStatusesCore();
		}

#if DEBUG
		internal int SetMilestoneStatusesAndRefreshCountForDebug;
#endif

		void RefreshMilestonesFromDb()
		{
			var milestonePKs = new List<ZGuid>();
			foreach (var milestone in this)
			{
				if (milestone.IsInDatabase)
				{
					milestonePKs.Add(milestone.PK);
				}
			}

			var milestoneInDbQuery = new ZQuery(ProcessTasksSchema.PK, milestonePKs) { ReLoadExistingRows = true };
			var milestonesInDb = new ProcessTaskCollection(new BusinessObjectFactory { RefreshEnabled = false, NameForDebugging = "MilestoneCollectionView Status Update Factory" });
			milestonesInDb.Load(milestoneInDbQuery);

			foreach (ProcessTask milestoneInDb in milestonesInDb.ToArray())
			{
				var milestoneInMemory = this[milestoneInDb.PK];

				if (milestoneInMemory != null && (
						(ZString)milestoneInMemory.P9_StatusInfo.OriginalValue != milestoneInDb.P9_Status
						|| (ZString)milestoneInMemory.P9_DescriptionInfo.OriginalValue != milestoneInDb.P9_Description
						|| (ZDateTime)milestoneInMemory.P9_ActualDateInfo.OriginalValue != new ZDateTime(((INeedRow)milestoneInDb).Row[ProcessTask.Schema.P9_ActualDate]))
					)
				{
					RefreshMilestoneFromDb(milestoneInMemory, milestoneInDb);
				}
			}
		}

		static void RefreshMilestoneFromDb(ProcessTask milestoneInMemory, ProcessTask milestoneInDb)
		{
			var changedValues = new Dictionary<ZPropertyInfo, IZType>();

			foreach (KPropertyDescriptor propertyDescriptor in ZCustomTypeDescriptor.GetProperties(milestoneInMemory.GetType()))
			{
				ZPropertyInfo propertyInfo = milestoneInMemory.FindPropertyInfo(propertyDescriptor.Name);
				if (propertyInfo != null && propertyInfo.HasChanges && propertyInfo.HasSetter && propertyInfo.Name != AutoProcessTasks.Schema.P9_Status && !propertyDescriptor.Attributes.OfType<SkipForRefreshAttribute>().Any())
				{
					changedValues.Add(propertyInfo, propertyInfo.Value);
				}
			}

			var dbActualDate = new ZDateTime(((INeedRow)milestoneInDb).Row[ProcessTask.Schema.P9_ActualDate]);
			if ((ZDateTime)milestoneInMemory.P9_ActualDateInfo.OriginalValue != dbActualDate && !dbActualDate.IsValid && !changedValues.ContainsKey(milestoneInMemory.P9_ActualDateInfo))
			{
				changedValues.Add(milestoneInMemory.P9_ActualDateInfo, milestoneInMemory.P9_ActualDateInfo.Value);
			}

			milestoneInMemory.Reload();

			using (milestoneInMemory.SuspendUpdateEventLog())
			{
				var bizoInternals = (IBusinessObjectInternals)milestoneInMemory;
				var initialIsCopying = bizoInternals.IsCopying;

				bizoInternals.IsCopying = true;

				try
				{
					foreach (var changedValue in changedValues)
					{
						changedValue.Key.Value = changedValue.Value;
					}
				}
				finally
				{
					bizoInternals.IsCopying = initialIsCopying;
				}
			}
		}

		bool isSettingStatuses;

		void SetMilestoneStatusesCore()
		{
			if (isSettingStatuses)
			{
				return;
			}

			var nextMilestone = NextMilestone;
			var lastMilestone = LastMilestone;

			using (DelayRebuild()) // Delaying rebuild so that if rebuild hooks fire workflow statuses aren't corrupted.
			using (SuspendListChanged())
			{
				try
				{
					var milestonesReached = new HashSet<ProcessTask>();

					isSettingStatuses = true;
					foreach (ProcessTask milestone in this.ToArray())
					{
						if (milestone == nextMilestone)
						{
							milestone.P9_Status = ProcessTask.NextToBeCompletedStatusCode;
						}
						else if (milestone == lastMilestone)
						{
							milestone.P9_Status = ProcessTask.LastCompletedStatusCode;
						}
						else if (milestone.P9_ActualDate.IsValid)
						{
							milestone.P9_Status = ProcessTaskStatusCodeList.Codes.Closed;
						}
						else
						{
							milestone.P9_Status = ProcessTaskStatusCodeList.Codes.Open;
						}

						if (milestone.IsInDatabase && milestone.P9_StatusInfo.HasChanges)
						{
							if (milestone.P9_Status == ProcessTaskStatusCodeList.Codes.Closed || milestone.P9_Status == ProcessTask.LastCompletedStatusCode)
							{
								if (!milestonesReached.Contains(milestone))
								{
									milestone.Factory.AddFetchHint(typeof(ProcessTask), milestone.GetMarkExceptionsAsActionedQuery());
									milestonesReached.Add(milestone);
								}
							}
						}
					}

					if (milestonesReached.Any())
					{
						foreach (var milestone in milestonesReached)
						{
							milestone.MarkExceptionsAsActioned();
						}
					}
				}
				finally
				{
					isSettingStatuses = false;
				}
			}
		}

		#endregion
	}
}

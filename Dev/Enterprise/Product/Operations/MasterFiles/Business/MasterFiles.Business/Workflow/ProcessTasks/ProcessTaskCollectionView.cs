using System;
using System.Collections.Generic;
using System.Linq;
using CargoWise.Common;
using CargoWise.EntityFramework;
using CargoWise.Types;
using Enterprise.Security;

namespace Enterprise.MasterFiles.Business
{
	public class ProcessTaskCollectionView : WorkflowItemCollectionView
	{
		public ProcessTaskCollectionView(ProcessTaskCollection collection)
			: base(collection)
		{
		}

		#region WorkflowItemCollectionView Overrides

		protected override bool HasExistingItemsBlockingTemplateApplication => !ProcessTask.Loader.ShouldCreateTasksFromTemplate(WorkflowItems.Parent, WorkflowItems);

		protected override void AddNewTaskCore(ProcessTask task)
		{
			base.AddNewTaskCore(task);

			var isTemplateTask = task.IsTemplate;

			if (Count == 0 && task.P9_GS_NKAssignedStaffMember.IsEmpty && !isTemplateTask)
			{
				task.P9_GS_NKAssignedStaffMember = GlbStaff.CurrentUser.GS_Code;
			}

			if (isTemplateTask)
			{
				SetProcessHeaderIfOnlyOneExists(task);
			}
		}

		static void SetProcessHeaderIfOnlyOneExists(ProcessTask task)
		{
			task.P9_FH_ProcessHeader = ProcessJobHeaderProvider.GetDefaultWorkflowForTask(task)?.PK ?? ZGuid.Empty;
		}

		protected override bool ElementCanBeAdded(BusinessObject bizO)
		{
			var task = (ProcessTask)bizO;

			return !task.IsTask || task.P9_GC.IsEmpty || task.P9_GC == GlbCompany.CurrentCompany.PK || task.P9_ShareTasksForAllCompanies ||
				!task.WorkflowDescriptor.AreTasksCompanySpecific;
		}

		protected override void SetDefaultsIfApplicable()
		{
			base.SetDefaultsIfApplicable();

			if (Count > 0)
			{
				var tasks = this.Cast<ProcessTask>().CollectMinBy(t => t.P9_Sequence);
				if (tasks.All(task => task.P9_Status == ProcessTaskStatusCodeList.Codes.Open && !(task is TemplateProcessTask)))
				{
					foreach (var task in tasks)
					{
						task.P9_GS_NKAssignedStaffMember = GlbStaff.CurrentUser.GS_Code;
					}
				}
			}
		}

		protected override CreateItemsFromTemplateResult CreateItemsFromTemplateCore(ProcessTaskTemplate template, TemplateApplicationParameters parameters, bool isFirstTemplateApplication)
		{
			if (isFirstTemplateApplication)
			{
				var jobHeader = ProcessJobHeaderProvider.GetForTemplate(template, (IWorkflowProvider)WorkflowItems.Parent);

				if (jobHeader != null)
				{
					jobHeader.ApplyTemplate(template, parameters);
				}
			}

			return base.CreateItemsFromTemplateCore(template, parameters, isFirstTemplateApplication);
		}

		protected override IEqualityComparer<ProcessTask> GetTemplateApplicationComparer() => new TaskToTemplateComparer();

		protected override bool IsTypeMatch(ProcessTask task) => task.IsTask;

		protected override TemplateEntityType TemplateEntityType => TemplateEntityType.Tasks;

		protected override bool AllowSort => true;

		protected override string AddSecurityCode => SecurityCore.WorkflowAddTasksAutoGeneratedCode;

		#endregion

		#region Rebuild

		public void Rebuild(ZString status, ZString type, ZString staffCode, ZGuid groupPK)
		{
			this.status = status;
			this.type = type;
			this.staffCode = staffCode;
			this.groupPK = groupPK;

			Rebuild();
		}

		protected override bool IsThisPartOfTheCollection(BusinessObject element)
		{
			ProcessTask task = (ProcessTask)element;

			bool isStatusOk = status.IsEmpty || task.P9_Status == status;
			bool isTypeOk = type.IsEmpty || task.P9_Type == type;
			bool isStaffOk = staffCode.IsEmpty || task.P9_GS_NKAssignedStaffMember == staffCode;
			bool isGroupOk = groupPK.IsEmpty || task.P9_GG_AssignedGroup == groupPK;

			return base.IsThisPartOfTheCollection(task) && isStatusOk && isTypeOk && isStaffOk && isGroupOk;
		}

		ZString status;
		ZString type;
		ZString staffCode;
		ZGuid groupPK;

		#endregion

		public ProcessTask NextTask
		{
			get { return this.GetNextTask(); }
		}

		public event EventHandler TasksViewFilterAdded;

		public ProcessTaskCollectionViewFilter TasksViewFilter
		{
			get
			{
				return tasksViewFilter;
			}
			set
			{
				tasksViewFilter = value;
				if (tasksViewFilter != null)
				{
					TasksViewFilterAdded?.Invoke(this, EventArgs.Empty);
				}
			}
		}

		ProcessTaskCollectionViewFilter tasksViewFilter;
	}
}

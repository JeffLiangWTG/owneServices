using System;
using System.Collections.Generic;
using Enterprise.Security;
using Enterprise.ZArchitecture.Business;

namespace Enterprise.MasterFiles.Business
{
	public class ExceptionCollectionView : WorkflowItemCollectionView
	{
		public ExceptionCollectionView(ProcessTaskCollection collection)
			: base(collection)
		{
		}

		public bool HasOpenExceptionsWithEventType(Event milestoneEventType, string description)
		{
			foreach (ProcessTask exception in this)
			{
				if (exception.P9_SE_NKMilestoneEvent == milestoneEventType.Code
					&& exception.P9_Description == description
					&& exception.P9_Status == ExceptionStatusCodeList.Codes.Open)
				{
					return true;
				}
			}
			return false;
		}

		protected override TemplateEntityType TemplateEntityType => TemplateEntityType.Exceptions;

		protected override string AddSecurityCode => SecurityCore.WorkflowAddExceptionsAutoGeneratedCode;

		protected override IEqualityComparer<ProcessTask> GetTemplateApplicationComparer() => throw new NotImplementedException("Exceptions don't havetemplate application");

		#region Implementation

		protected override bool IsTypeMatch(ProcessTask task)
		{
			return task.IsException;
		}

		protected override void AddNewTaskCore(ProcessTask child)
		{
			child.IsException = true;
			base.AddNewTaskCore(child);
		}

		#endregion
	}
}

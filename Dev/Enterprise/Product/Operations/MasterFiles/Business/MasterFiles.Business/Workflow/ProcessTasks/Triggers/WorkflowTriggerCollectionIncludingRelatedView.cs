using System.Collections.Generic;
using System.Linq;
using CargoWise.EntityFramework;
using Enterprise.Security;
using Enterprise.ZArchitecture.Schema;

namespace Enterprise.MasterFiles.Business
{
	public class WorkflowTriggerCollectionIncludingRelatedView : WorkflowItemCollectionIncludingRelatedView
	{
		public WorkflowTriggerCollectionIncludingRelatedView(ProcessTaskCollection collection)
			: base(collection)
		{
		}

		protected override bool IsTypeMatch(ProcessTask task)
		{
			return task.IsWorkflowTrigger;
		}

		protected override TemplateEntityType TemplateEntityType => TemplateEntityType.Triggers;

		protected override string AddSecurityCode => SecurityCore.WorkflowAddTriggersAutoGeneratedCode;

		protected override IEqualityComparer<ProcessTask> GetTemplateApplicationComparer() => new TriggerToTemplateComparer();

		protected override void AddNewTaskCore(ProcessTask child)
		{
			child.IsWorkflowTrigger = true;
			base.AddNewTaskCore(child);
		}

		protected override bool AllowSort => true;

		protected override Rebuilder GetRebuilder() => new UniversalTriggerRebuilder(this);

		class UniversalTriggerRebuilder : SupersetRebuilder
		{
			public UniversalTriggerRebuilder(WorkflowTriggerCollectionIncludingRelatedView view)
				: base(view)
			{
				this.view = view;
			}
			readonly WorkflowTriggerCollectionIncludingRelatedView view;

			protected override IEnumerable<ProcessTask> GetRelatedTasksCore()
			{
				return base.GetRelatedTasksCore()
				.Concat(GetUniversalTriggers());
			}

			IEnumerable<ProcessTask> GetUniversalTriggers() => view.CreateAndDeleteNonPersistedUniversalTriggers(view.Cast<ProcessTask>());
		}

		protected override IEnumerable<ProcessTask> GetRelatedProcessTasksCore(IWorkflowProvider[] providers)
		{
			var workflowProvider = CollectionToFilter.Parent as IWorkflowProvider;
			if (workflowProvider == null)
			{
				return System.Array.Empty<ProcessTask>();
			}

			var providersWithLineTriggers = providers.Where(IsLineTriggersParent).ToArray();

			foreach (var provider in providersWithLineTriggers)
			{
				Factory.AddFetchHint(ProcessTasksSchema.Instance, new ZQuery(ProcessTasksSchema.P9_ParentID, provider.PK));
			}

			return providersWithLineTriggers
				.SelectMany(p => p.WorkflowItems)
				.Cast<ProcessTask>()
				.Where(p => IsTypeMatch(p) && p.P9_LineTriggerType == workflowProvider.WorkflowType);
		}

		static bool IsLineTriggersParent(IWorkflowProvider provider)
		{
			return WorkflowDescriptors.Instance.TryGetValueSafe(provider.WorkflowType) is IWorkflowParentWithLines;
		}
	}
}

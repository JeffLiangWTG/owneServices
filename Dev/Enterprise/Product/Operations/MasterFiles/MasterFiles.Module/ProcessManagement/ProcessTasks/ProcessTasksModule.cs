	public class ProcessTasksModule : ZFilterGridModule, IOperationalActionSupportable
	{
		public ProcessTasksModule()
		{
			Plugins.Add(ControllerIDs.OperationalActions);
		}

		public override ModuleIdentifier ID
		{
			get { return ModuleIDs.ProcessTasks; }
		}

		protected override ZController GetNewController(BusinessObject selectedBusinessObject)
		{
			return ZControllerFactory.Create(ControllerIDs.ProcessTasks);
		}

		protected override IFilterControl GetNewFilterControl()
		{
			return new ProcessTaskFilterControl(GridCollection, (ProcessTaskFilterBusinessObject)FilterBusinessObject);
		}

		protected override IBusinessObjectCollection GetNewGridCollection()
		{
			return new ProcessTaskCollection(Factory);
		}

		protected override FilterBusinessObject GetNewFilterBusinessObject()
		{
			return new ProcessTaskFilterBusinessObject();
		}

		public override string WorkflowItemCheckpointCode
		{
			get { return SecurityCore.WorkflowTasksJustViewAutoGeneratedCode; }
		}

		protected override LicenceCheckpoint LicenceCheckPointCore
		{
			get { return Env.Licence.Workflow; }
		}

		public override SecurityCheckpoint SecurityCheckpointDefault
		{
			get { return Env.Security.WorkflowTasks; }
		}

		public override SecurityCheckpoint SecurityCheckpoint
		{
			get { return GetWorkflowTasksCheckpointFromParentModuleID(); }
		}

		#region ModuleDecisionProvider

		protected override IModuleDecisionProvider CreateDefaultModuleDecisionProvider() => new ProcessTasksModuleDecisionProvider(this);

		class ProcessTasksModuleDecisionProvider : DefaultModuleDecisionProvider
		{
			public ProcessTasksModuleDecisionProvider(ProcessTasksModule module) : base(module)
			{
			}

			public override void HandleDefaultAction(BusinessObject[] selectedBusinessObjects)
			{
				if (selectedBusinessObjects.Any())
				{
					MainThreadRunner.RunOnMainThread(() =>
					{
						var factory = new BusinessObjectFactory { NameForDebugging = "ProcessTasksModule.HandleDefaultAction" };
						var tasksToView = selectedBusinessObjects.OfType<ProcessTask>().Select(s => factory.ImportFromAnotherFactory(s)).OfType<ProcessTask>();

						foreach (var task in tasksToView)
						{
							var parentControllerID = task.ParentControllerID;
							var defaultShowTaskInTaskForm = WorkflowDataRegistry.Instance.TaskDefaultOpeningBehaviour.Value == TaskDefaultOpeningBehaviourOptions.Codes.Task;
							var showTaskForm = AskUserWhetherToOpenTaskForm(task, defaultShowTaskInTaskForm);
							WorkflowParentFormFactory.ShowFormAndNavigateToWorkflowItem(
							task,
							getTargetController: () => parentControllerID != null ? ZControllerFactory.Create(parentControllerID) : null,
							alwaysShowTaskForm: defaultShowTaskInTaskForm || showTaskForm,
							shouldShowTaskFormIfNullParent: true);
						}
					});
				}
			}

			static bool AskUserWhetherToOpenTaskForm(ProcessTask task, bool defaultShowTaskInTaskForm)
			{
				if (task.ParentControllerID is null && !task.IsStandaloneTask && !defaultShowTaskInTaskForm)
				{
					var message = Res.GetString("f30b4e2f-269c-4177-b4b5-e44bb7028560", "This task is not linked to a specific workflow or process. Do you still want to open it in a task form?");
					var result = Globals.Message.Show(message, string.Empty, ZMessageBoxButtons.YesNo, ZDialogResult.None);
					return result == ZDialogResult.Yes;
				}
				return false;
			}
		}

		#endregion

		protected override MenuItem[] GetNewStandardMenuItems()
		{
			List<MenuItem> menus = new List<MenuItem>(base.GetNewStandardMenuItems());

			MenuItem newDeleteMenuItem = new ZMenuItem(Res.GetData("MasterFiles.ProcessTasks.Delete", "&Delete", "Delete"), new EventHandler(DeleteTask_Click), IconTypes.DeleteButtonActive, IconTypes.DeleteButtonRest);
			newDeleteMenuItem.Visible = false;

			if (DeleteMenuItem != null)
			{
				menus.Insert(menus.IndexOf(DeleteMenuItem, 0, menus.Count) + 1, newDeleteMenuItem);
				menus.Remove(DeleteMenuItem);
			}
			else
			{
				menus.Insert(menus.Count, newDeleteMenuItem);
			}

			return menus.ToArray();
		}

		protected override void HandleViewClickCore(object sender, EventArgs e)
		{
			HandleViewEditClick(sender, e);
		}

		protected override void HandleEditClickCore(object sender, EventArgs e)
		{
			HandleViewEditClick(sender, e);
		}

		void HandleViewEditClick(object sender, EventArgs e)
		{
			var selectedElements = GetSelectedElements();

			if (selectedElements == null || !selectedElements.Any())
			{
				ShowNoSelectedMessage();
			}
			else
			{
				ModuleDecisionProvider.HandleDefaultAction(GetSelectedElements());
			}
		}

		void DeleteTask_Click(object sender, EventArgs e)
		{
			var selectedElements = GetSelectedElements();

			if (selectedElements.Any())
			{
				var factory = new BusinessObjectFactory { NameForDebugging = "ProcessTasksModule.DeleteTasks" };
				var tasksToDelete = selectedElements.OfType<ProcessTask>().Select(factory.ImportFromAnotherFactory).Cast<ProcessTask>().ToArray();
				var ids = string.Join(",", tasksToDelete.Select(t => t.P9_TaskID));

				if (Globals.Message.Show(Res.GetString("d4b883dd-8220-4881-bb38-8017a0494bf7", "You are about to delete tasks {0}. Proceed?", ids), Res.GetString("94148a31-878e-469d-844b-964261525712", "Delete process tasks"), MessageBoxButtons.YesNo, MessageBoxIcon.Warning) == DialogResult.Yes)
				{
					HashSet<Tuple<MultilingualString, string>> cannotDeleteReasons = new HashSet<Tuple<MultilingualString, string>>();
					foreach (BusinessObject obj in tasksToDelete)
					{
						if (!obj.IsDeleted)
						{
							if (obj.CanDelete)
							{
								obj.Delete();
							}
							else
							{
								obj.OnCannotDelete();
								cannotDeleteReasons.Add(Tuple.Create(obj.ReasonForNotAbleToDelete, Res.GetString("7a8b365f-dfd8-4458-9428-924489100a86", "Cannot Delete Record")));
							}
						}
					}
					try
					{
						factory.Save();
						foreach (Tuple<MultilingualString, string> reason in cannotDeleteReasons)
						{
							Globals.Message.ShowError(reason.Item1, reason.Item2);
						}
					}
					catch (ZSaveException ex)
					{
						ZExceptionReporting.HandleSaveException(ex);
					}
				}
			}
		}

		protected virtual BusinessObject[] GetSelectedElements()
		{
			return Grid.SelectedElements;
		}

		OperationalActionSupporter IOperationalActionSupportable.OperationalActionSupporter
		{
			get { return new ProcessTasksOperationalActionSupporter(); }
		}
	}
}

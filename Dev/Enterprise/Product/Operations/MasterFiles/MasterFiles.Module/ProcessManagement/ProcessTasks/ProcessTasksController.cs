using System;
using CargoWise.EntityFramework;
using Enterprise.Environment;
using Enterprise.MasterFiles.Business;
using Enterprise.MasterFiles.GUI;
using Enterprise.Security;
using Enterprise.ZArchitecture.GUI;
using Enterprise.ZArchitecture.Modules;

namespace Enterprise.MasterFiles.Module
{
	public class ProcessTasksController : ZController
	{
		public override bool MakeUrlsOnlyOpenableForCurrentCompany => true;

		public override ModuleIdentifier ModuleID
		{
			get { return ModuleIDs.ProcessTasks; }
		}

		public override ControllerID ID
		{
			get { return ControllerIDs.ProcessTasks; }
		}

		public override Type TypeOfTopLevelBusinessObject
		{
			get { return typeof(ProcessTask); }
		}

		protected override IZForm GetForm(IBusiness businessEntity)
		{
			return new TaskManagementForm((ProcessTask)businessEntity);
		}

		public override bool MakeUrlOnlyOpenableForCurrentCompany(IBusiness bizo)
		{
			if (bizo is ProcessTask task && task.ParentControllerID != null && task.ParentBusinessObject != null)
			{
				IWorkflowProvider workflowProvider = task.ParentBusinessObject as IWorkflowProvider;
				return workflowProvider != null && workflowProvider.WorkflowItems.AreTasksCompanySpecific && !task.P9_ShareTasksForAllCompanies;
			}
			return base.MakeUrlOnlyOpenableForCurrentCompany(bizo);
		}

		#region Security Checkpoints

		protected override SecurityCheckpoint CheckPointForView
		{
			get { return Env.Security.WorkflowTasksView; }
		}

		protected override SecurityCheckpoint CheckPointForEdit
		{
			get { return Env.Security.WorkflowTasksEdit; }
		}

		protected override SecurityCheckpoint CheckPointForNew
		{
			get { return Env.Security.WorkflowTasksNew; }
		}

		protected override SecurityCheckpoint CheckPointForDelete
		{
			get { return Env.Security.WorkflowTasksDelete; }
		}

		public override SecurityCheckpoint GetCheckPointForView(BusinessObject bizObject)
			=> GetWorkflowTasksCheckpoint(bizObject, SecurityCore.WorkflowTasksJustViewAutoGeneratedCode)
				?? CheckPointForView;

		public override SecurityCheckpoint GetCheckPointForNew(BusinessObject bizObject)
		{
			if (bizObject is ProcessTask task && task.ParentControllerID != null)
			{
				return GetWorkflowTasksCheckpoint(task, SecurityCore.WorkflowAddTasksAutoGeneratedCode);
			}
			else
			{
				return CheckPointForNew;
			}
		}

		public override SecurityCheckpoint GetCheckPointForEdit(BusinessObject bizObject)
			=> GetWorkflowTasksCheckpoint(bizObject, SecurityCore.WorkflowTasksAutoGeneratedCode)
				?? CheckPointForEdit;

		public override SecurityCheckpoint GetCheckPointForDelete(BusinessObject bizObject)
		{
			if (bizObject is ProcessTask task && task.ParentControllerID != null)
			{
				return GetWorkflowTasksCheckpoint(task, SecurityCore.WorkflowDeleteTasksAutoGeneratedCode);
			}
			else
			{
				return CheckPointForDelete;
			}
		}

		SecurityCheckpoint GetWorkflowTasksCheckpoint(BusinessObject bizObject, string workflowTasksCode)
		{
			SecurityCheckpoint result = null;
			ProcessTask task = bizObject as ProcessTask;

			if (task != null && task.ParentControllerID != null)
			{
				ZController controller = ZControllerFactory.Create(task.ParentControllerID);
				var moduleID = controller.ModuleID;

				if (moduleID != null)
				{
					using (ZModule module = ZModuleFactory.Instance.Create(controller.ModuleID))
					{
						if (module != null && module.SecurityCheckpoint != Env.Security.None)
						{
							result = (SecurityCheckpoint)module.GetWorkflowTasksCheckpoint(workflowTasksCode);
						}
					}
				}
			}
			return result;
		}

		#endregion
	}
}

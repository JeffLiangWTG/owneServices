using System.Diagnostics.CodeAnalysis;
using CargoWise.EntityFramework;
using Enterprise.Environment;
using Enterprise.Licensing;
using Enterprise.MasterFiles.Business;
using Enterprise.Security;
using Enterprise.Services.OperationalActions.Support;
using Enterprise.ZArchitecture.Business;
using Enterprise.ZArchitecture.GUI;
using Enterprise.ZArchitecture.Modules;

namespace Enterprise.MasterFiles.Module
{
	public class ProcessTaskTemplateModule : ZFilterGridModule, IOperationalActionSupportable
	{
		public ProcessTaskTemplateModule()
		{
			Plugins.Add(ControllerIDs.OperationalActions);
		}

		public override ModuleIdentifier ID
		{
			get { return ModuleIDs.ProcessTemplates; }
		}

		protected override ZController GetNewController(BusinessObject selectedBusinessObject)
		{
			return ZControllerFactory.Create(ControllerIDs.ProcessTemplates);
		}

		protected override IFilterControl GetNewFilterControl()
		{
			return new ProcessTaskTemplateFilterControl(GridCollection, (ProcessTaskTemplateFilterBusinessObject)FilterBusinessObject);
		}

		protected override IBusinessObjectCollection GetNewGridCollection()
		{
			return new ProcessTaskTemplateCollection(Factory);
		}

		protected override FilterBusinessObject GetNewFilterBusinessObject()
		{
			return new ProcessTaskTemplateFilterBusinessObject();
		}

		protected override LicenceCheckpoint LicenceCheckPointCore
		{
			get { return Env.Licence.Workflow; }
		}

		public override SecurityCheckpoint SecurityCheckpoint
		{
			get { return Env.Security.WorkflowTaskTemplates; }
		}

		public OperationalActionSupporter OperationalActionSupporter => new ProcessTaskTemplateOperationalActionSupporter();
		public override ISecurityCheckpoint GetWorkflowTasksCheckpoint(string workflowTasksCode)
		{
			return GetWorkflowTasksCheckpoint(null, workflowTasksCode);
		}

		[SuppressMessage("Microsoft.Maintainability", "CA1502:Avoid excessive complexity")]
		public override ISecurityCheckpoint GetWorkflowTasksCheckpoint(IBusiness parentJob, string workflowTasksCode)
		{
			switch (workflowTasksCode)
			{
				case SecurityCore.WorkflowTasksJustViewAutoGeneratedCode:
				case SecurityCore.WorkflowMilestonesJustViewAutoGeneratedCode:
				case SecurityCore.WorkflowTriggersJustViewAutoGeneratedCode:
					return Env.Security.WorkflowTaskTemplatesView;

				case SecurityCore.WorkflowTasksAutoGeneratedCode:
				case SecurityCore.WorkflowMilestonesAutoGeneratedCode:
				case SecurityCore.WorkflowTriggersAutoGeneratedCode:
				case SecurityCore.WorkflowDeleteTasksAutoGeneratedCode:
				case SecurityCore.WorkflowDeleteMilestonesAutoGeneratedCode:
				case SecurityCore.WorkflowDeleteTriggersAutoGeneratedCode:
				case SecurityCore.WorkflowAddTasksAutoGeneratedCode:
				case SecurityCore.WorkflowAddMilestonesAutoGeneratedCode:
				case SecurityCore.WorkflowAddTriggersAutoGeneratedCode:
					return FindTheRightWorkflowTaskTemplateCheckPointToReturn(parentJob);

				default:
					return this.SecurityCheckpoint;
			}
		}
		SecurityCheckpoint FindTheRightWorkflowTaskTemplateCheckPointToReturn(IBusiness parentJob)
		{
			var loadedTemplate = (ProcessTaskTemplate)parentJob;

			if (parentJob != null && !parentJob.IsInDatabase)
			{
				return Env.Security.WorkflowTaskTemplatesNew;
			}
			else if (parentJob as ProcessTaskTemplate != null && loadedTemplate != null && !loadedTemplate.P0_IsActive)
			{
				return Env.Security.WorkflowTaskTemplatesEditInactive;
			}
			else
			{
				return Env.Security.WorkflowTaskTemplatesEdit;
			}
		}
	}
}

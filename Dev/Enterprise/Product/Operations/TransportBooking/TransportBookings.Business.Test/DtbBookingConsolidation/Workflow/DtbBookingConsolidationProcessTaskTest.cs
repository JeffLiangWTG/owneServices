using NUnit.Framework;

namespace Enterprise.TransportBookings.Business.Test
{
	[TestedType(typeof(DtbBookingConsolidationProcessTask))]
	public class DtbBookingConsolidationProcessTaskTest : ProcessTaskTest
	{
		public override void TestParentControllerIDIsOverridenForNonStandAloneTasks()
		{
			var consolidation = Helper.CreateConsolidationMultiJob();
			var task = consolidation.WorkflowItems.AddNew();
			AssertEquals("ParentController ID of DtbBookingConsolidationProcessTask should be DtbBookingConsolidation controller", ControllerIDs.DtbBookingConsolidation, task.ParentControllerID);
		}

		public void TestDeleteIsNotAllowedWhenSecuritySetOnTransportBookingConsolidation()
		{
			using (WorkflowDataRegistry.Instance.EnableCheckpointsForWorkflowSecurity.SetTemporaryValue(Guid.Empty, Guid.Empty, Guid.Empty, true))
			{
				var company = Factory.NewWithValidTestData<GlbCompany>();
				var branch = company.Branches.AddNew();
				branch.FillWithValidTestData();

				Factory.Save();

				var jobID = "C12345678";
				var consolidation = Helper.CreateConsolidationMultiJob();
				consolidation.KB_JobID = jobID;
				var task = consolidation.WorkflowItems.AddNew();
				task.P9_Type = Core.Constants.Workflow.ExceptionType;
				task.P9_GC = company.PK;

				task.P9_ParentID = consolidation.PK;
				task.P9_ParentTableCode = DtbBookingConsolidationSchema.Constants.Prefix;

				task.P9_TaskID = jobID;
				task.P9_Description = "Test Exceptions";
				task.FillWithValidTestData();

				Factory.Save();

				var controller = ObjectFactory.Get<IControllerFactory>().Create(ControllerIDs.DtbBookingConsolidation);
				SecurityCheckpoint deleteExceptionsCheckpoint = null;
				using (var module = ObjectFactory.Get<IModuleFactory>().Create(controller.ModuleID))
				{
					deleteExceptionsCheckpoint = (SecurityCheckpoint)module.GetWorkflowTasksCheckpoint(SecurityCore.WorkflowDeleteExceptionsAutoGeneratedCode);
				}
				deleteExceptionsCheckpoint.IsAllowed = false;

				AssertEquals("Should respect security on DtbBookingConsolidation for exceptions", false, ProcessTaskSecurityMan.IsAllowDelete(task));
			}
		}

		protected override BusinessObject GetNewBusinessObject()
		{
			var consolidation = Helper.CreateConsolidation();
			return consolidation.WorkflowItems.AddNew();
		}

		TransportBookingTestHelper Helper
		{
			get { return helper ?? (helper = new TransportBookingTestHelper(Factory)); }
		}
		TransportBookingTestHelper helper;
	}
}

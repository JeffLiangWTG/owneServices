using System;
using System.Collections.Generic;
using System.Text;
using CargoWise.Types;
using Enterprise.ZArchitecture.Core.Testing;
using NUnit.Framework;

namespace Enterprise.Customs.CA.Business.MessageBuildingBlocks.Testing
{
	sealed class MessageBlockTest : TestCase
	{
		[ExpectNoExceptions]
		public void TestMessageBlockIntAttributeLengthIsNotGreaterThan9Numerics()
		{
			StringBuilder failures = new StringBuilder();
			SubClassRetriever retriever = new SubClassRetriever(GetType().Assembly, typeof(MessageBlock));
			retriever.IncludeAutoGeneratedCode = false;
			retriever.IncludeAbstractClasses = false;
			Type messageBlockIntAttributeType = typeof(MessageBlockIntAttribute);
			foreach (Type type in retriever.Retrieve())
			{
				MessageBlock block = (MessageBlock)Activator.CreateInstance(type);
				List<MessageBlock.AttributeFieldInfo> fieldInfos = new List<MessageBlock.AttributeFieldInfo>(block.GetAttributeFieldInfos());
				foreach (MessageBlock.AttributeFieldInfo fieldInfo in fieldInfos)
				{
					if (fieldInfo.Attribute.GetType() == messageBlockIntAttributeType && fieldInfo.Attribute.Length > 9)
					{
						failures.AppendLine(string.Format("{0}.{1}'s MessageBlockIntAttribute.Length is greater than 9 numeric characters", type.FullName, fieldInfo.FieldInfo.Name));
					}
				}
			}
			if (failures.Length > 0)
			{
				Fail(failures.ToString());
			}
		}

		[ExpectNoExceptions]
		public void TestMandatoryCharacters()
		{
			StringBuilder failures = new StringBuilder();
			SubClassRetriever retriever = new SubClassRetriever(GetType().Assembly, typeof(MessageBlock));
			retriever.IncludeAbstractClasses = false;
			foreach (Type type in retriever.Retrieve())
			{
				MessageBlock block = (MessageBlock)Activator.CreateInstance(type);
				List<MessageBlock.AttributeFieldInfo> fieldInfos = new List<MessageBlock.AttributeFieldInfo>(block.GetAttributeFieldInfos());
				fieldInfos.Sort(delegate(MessageBlock.AttributeFieldInfo x, MessageBlock.AttributeFieldInfo y)
				{ return x.Attribute.Offset.CompareTo(y.Attribute.Offset); });

				int startPos = block.MandatoryCharacters.Length;
				if (fieldInfos.Count > 0 && fieldInfos[0].Attribute.Offset < block.MandatoryCharacters.Length)
				{
					failures.AppendLine(type.FullName + " - Mandatory characters overlap with writable data");
				}
			}
			if (failures.Length > 0)
			{
				Fail(failures.ToString());
			}
		}

		public void TestSerialise()
		{
			MessageBlockDummy messageBlock = new MessageBlockDummy();
			string result = messageBlock.Serialise();
			AssertEquals("F109 12345678900         ", result);

			messageBlock.Dummy = "123";
			messageBlock.DecimalField = 23.234;
			result = messageBlock.Serialise();
			AssertEquals("F109 123       23.234    ", result);
		}

		public void TestSerialiseUserFriendly()
		{
			MessageBlockDummy messageBlock = new MessageBlockDummy();
			ZString result = messageBlock.Serialise(true);
			AssertEquals(result, true, result.Replace(" ", "").Replace("\t", "").Contains("Dummy(6-15):1234567890"));
		}

		[ExpectException(typeof(ArgumentNullException))]
		public void TestNullDeserialise()
		{
			MessageBlock messageBlock = new MessageBlockDummy();
			messageBlock.Deserialise(null);
		}

		[ExpectExceptionMessage(typeof(InvalidMessageFormatException),
@"Deserialised data does not match mandatory values for ControlIdentifier.
Expected value : F109
Actual value : G109")]
		public void TestInvalidDataDeserialise()
		{
			MessageBlock messageBlock = new MessageBlockDummy();
			messageBlock.Deserialise("G109 PATHFINDER");
		}

		public void TestValidDeSerialise()
		{
			MessageBlockDummy messageBlock = new MessageBlockDummy();
			messageBlock.Deserialise("F109 PATHFINDER");
			AssertEquals("PATHFINDER", messageBlock.Dummy);
		}
	}
}

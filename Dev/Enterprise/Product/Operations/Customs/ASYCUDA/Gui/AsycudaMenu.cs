		public AsycudaMenu(AsycudaManifestHeader header)
			: this(header, DefaultCaption)
		{
		}

		public AsycudaMenu(AsycudaManifestHeader header, ResourceString caption)
			: base(caption ?? DefaultCaption)
		{
			SingleManifestHeader = header;
			MenuItems.Add("-");
		}

		public AsycudaMenu(ManifestHeadersWrapper wrapper)
			: base(DefaultCaption)
		{
			ManifestHeadersWrapper = wrapper;
			MenuItems.Add("-");
		}

		static readonly ResourceString DefaultCaption = ResString.GetMultilingualString("AsycudaMenu|MainMenuItem", "Manifest");

		// Only menu items applicable to all/most manifest applications should be built from this class. All other menu items should be generated by the manifest application subscribers.
		// See MenuBuilderHelper.cs for some commonly used functionality.
		public void BuildMenu()
		{
			while (MenuItems.Count > 0)
			{
				MenuItems.RemoveAt(0);
			}

			var headers = GetHeaders()?.ToArray();

			if (headers == null || headers.Length == 0)
			{
				AddNoValidManifestHeaderMenuItem();
			}
			else
			{
				foreach (var header in headers)
				{
					var menuBuilder = GetMenuBuilder(header);
					var currentMenuItems = MenuItems;

					if (!header.IsStandAlone)
					{
						var caption = menuBuilder.MenuCaption;
						var subMenu = new ZMenuItem(caption);
						MenuItems.Add(subMenu);
						currentMenuItems = subMenu.MenuItems;
					}

					currentMenuItems.AddRange(menuBuilder.BuildMenu());
					if (!header.IsStandAlone)
					{
					currentMenuItems.Add(AddRefreshBillDataMenuItem(header));
					}
				}
			}

			var headersForDeclaration = GetHeadersForDeclaration().ToArray();

			if (headersForDeclaration.Any())
			{
				MenuItems.Add(ZMenuItem.Separator);
				foreach (var country in headersForDeclaration)
				{
					AddCreateDeclarationMenuItem(country);
				}
			}

			AddLinkSailingMenuIfNeed();
		}

		ZMenuItem AddRefreshBillDataMenuItem(AsycudaManifestHeader header)
		{
			var caption = ResString.GetMultilingualString("5A105312-6A17-4FA1-85F7-51846401E3FC", "Refresh Bill Data");
			var message = ResString.GetMultilingualString("E3C93BE5-DC58-4CCD-9791-0A13FED2DFB3", "Existing Bill records will not be overwritten, only additional shipments that are found on parent Consol Job but not found in the list of Bills in the Manifest will be added.");
			var menuItem = new ZMenuItem(caption);
			menuItem.Enabled = header.AMA_OverrideFreightDefaults;
			menuItem.Click += delegate
			{
				var result = Globals.Message.Show(message, caption, MessageBoxButtons.OK, MessageBoxIcon.Warning);
				if (result == DialogResult.OK)
				{
					header.CopyAdditionalConsolShipmentToBills();
				}
			};
			return menuItem;
		}

		void AddLinkSailingMenuIfNeed()
		{
			var form = MainForm as ManifestForm;
			var header = SingleManifestHeader;

			if (form != null && (header?.CanBeLinkedWithSailing ?? false))
			{
				MenuItems.Add(ZMenuItem.Separator);

				var caption = ResString.GetMultilingualString("4D524DF7-29C0-4BE4-B50D-3A5617DB0896", "Import Bills of Lading linked to the same sailing");

				var menuItem = MenuItems.Add(caption, ImportFromSailingClick);
				menuItem.Name = caption;
			}
		}

		void ImportFromSailingClick(object sender, EventArgs e)
		{
			var form = MainForm as ManifestForm;
			var header = SingleManifestHeader;

			if (form != null && header?.Sailing != null)
			{
				var existingBills = new BillImportActionCollection(header.Bills);

				void ImportAction() => form.RunActionWithProcessBox(Res.GetString("F794AACB-754F-4CA3-A868-988FCEB5BEDF", "Importing bills from sailing..."), () => { header.ImportBillsOfLadingLinkedToTheSameSailing(existingBills); });

				if (existingBills.Count > 0)
				{
					using (var billAction = new ImportFromSailingForm(existingBills))
					{
						if (billAction.ShowDialog() == DialogResult.OK)
						{
							ImportAction();
						}
					}
				}
				else
				{
					ImportAction();
				}
			}
			else
			{
				Globals.Message.Show(NoSailingSelected);
			}
		}

		static string NoSailingSelected => Res.GetString("9A52FFB8-D839-4D70-B1D3-2DB606E8A7D2", "There is no Sailing Schedule to import Bills Of Lading.");

		IEnumerable<AsycudaManifestHeader> GetHeaders()
		{
			var headers = ManifestHeadersWrapper != null
				? ManifestHeadersWrapper.Headers.Cast<AsycudaManifestHeader>().ToArray()
				: new[] { SingleManifestHeader };

			foreach (var header in headers.Where(header => header != null))
			{
				if (header.IsPackedItemLevelManifestType)
				{
					header.FetchStrategy.FetchForLoadChildEditableObjects();
				}
				yield return header;
			}
		}

		IEnumerable<AsycudaManifestHeader> GetHeadersForDeclaration()
		{
			var headers = ManifestHeadersWrapper != null
				? ManifestHeadersWrapper.Headers.Cast<AsycudaManifestHeader>().ToArray()
				: new[] { SingleManifestHeader };

			foreach (var header in headers)
			{
				if (header != null)
				{
					if (header.IsDeclarationCreationEnabled)
					{
						yield return header;
					}
				}
			}
		}

		internal static ZMenuItem AddNoManifestToSendMenuItem(AsycudaManifestHeader header, string messageLabel)
		{
			var caption = ResString.GetMultilingualString("AsycudaMenu|NoManifestToSent", "Send &{0}", messageLabel);
			var noSentMenuItem = new ZMenuItem(caption);
			noSentMenuItem.Click += delegate
			{
				if (MessageHasBeenSent(header))
				{
					var resetMessagePart = ZString.Empty;
					if (MessagesCanBeReset(header))
					{
						resetMessagePart = Res.GetString("AB67E76B-5328-44FA-8823-7F9AD3E1DBA0",
							"\n\nIf you have been requested to re-send an Original or Cancellation message due to communication issues, you can use the 'Reset Message Status' menu option to re-enable message sending.");
					}

					Globals.Message.ShowError(Res.GetString("BDF310C1-2426-486E-909B-9CAD1003C7DB",
						"No messages can be sent at this time. Some manifests already sent are waiting for a response. Once a response have been received, Amendment and Cancellation menu options will become available.{0}", resetMessagePart));
				}
				else
				{
					Globals.Message.ShowError(Res.GetString("44D3593F-F9BF-4B34-A7F9-CF8F3887E777", "No messages can be sent at this time. Please capture the bills and packs required for the respective manifest types."));
				}
			};

			return noSentMenuItem;
		}

		static bool MessageHasBeenSent(AsycudaManifestHeader header)
		{
			return AsycudaManifestUniversalMessagingHelper.ForMessageLevel(header,
				() => header.HasManifestBeenSubmittedToCustoms,
				() => header.Bills.OfType<AsycudaBill>().Any(bill => bill.HasManifestBeenSubmittedToCustoms),
				() => header.IsOnePackedItemRelationship && header.Bills.OfType<AsycudaBill>().Any(bill => bill.Packs.OfType<AsycudaPack>().Any(pack => pack.PackedItem?.HasManifestBeenSubmittedToCustoms ?? false)));
		}

		static bool MessagesCanBeReset(AsycudaManifestHeader header)
		{
			var messageStatusProvider = header.MessageStatusProvider;
			if (messageStatusProvider == null)
			{
				return false;
			}

			return AsycudaManifestUniversalMessagingHelper.ForMessageLevel(header,
				() => messageStatusProvider.MessageStatusCanBeReset(header),
				() => header.Bills.OfType<AsycudaBill>().Any(bill => messageStatusProvider.MessageStatusCanBeReset(bill)),
				() => header.IsOnePackedItemRelationship && header.Bills.OfType<AsycudaBill>().Any(bill => bill.Packs.OfType<AsycudaPack>().Any(pack => messageStatusProvider.MessageStatusCanBeReset(pack.PackedItem))));
		}

		MenuBuilder GetMenuBuilder(AsycudaManifestHeader header)
		{
			return ApplicationGUIProvider.GetApplicationGuiProvider(header).GetMenuBuilder(MainForm, header);
		}

		public AsycudaManifestHeader SingleManifestHeader
		{
			get;
			set;
		}

		public ManifestHeadersWrapper ManifestHeadersWrapper
		{
			get;
			set;
		}

		void AddCreateDeclarationMenuItem(AsycudaManifestHeader header)
		{
			var countryCodeFormatted = header == null ? "" : string.Format(CultureInfo.CurrentCulture, "({0})", header.CountryName);
			var caption = ResString.GetMultilingualString("AsycudaMenu|CreateDeclaration", "Create/Update Declarations from the Bill {0}", countryCodeFormatted);
			var declarationMenuItem = new ZMenuItem(caption);
			declarationMenuItem.Click += delegate
			{
				CreateOrUpdateDeclaration(header);
			};
			MenuItems.Add(declarationMenuItem);
		}

		void AddNoValidManifestHeaderMenuItem()
		{
			var caption = ResString.GetMultilingualString("AsycudaMenu|NoValidManifest", "Send &Manifest");
			var noSentMenuItem = new ZMenuItem(caption);
			noSentMenuItem.Click += delegate
			{
				Globals.Message.ShowError(ResString.GetMultilingualString("1BC106B7-4388-43A0-86D1-8F2D2049883E", "No valid manifest header exists. Please enter the Manifest tab to create a manifest header with the relevant country context."));
			};
			MenuItems.Add(noSentMenuItem);
		}

		void CreateOrUpdateDeclaration(AsycudaManifestHeader header)
		{
			if (SaveDataFirst.Confirm(header, MainForm))
			{
				var billCountries = header.Bills.OfType<AsycudaBill>().Where(x => !x.ABL_BillNumber.IsEmpty).ToArray();
				DialogResult dialogResult;
				AsycudaBill[] selectedBillCountries;

				if (billCountries.Length == 0)
				{
					Globals.Message.Show(string.Format(CultureInfo.CurrentCulture, "There are no bills that have a bill number"), "Error", MessageBoxButtons.OK, MessageBoxIcon.Error);
				}
				else
				{
					using (var mutexManager = new MutexManager(billCountries.Cast<AsycudaBill>(), (x) => x.SendToManifestMutex))
					{
						if (mutexManager.HasAquiredLockForAllBills)
						{
							var messageChooser = header.GetNewMessageChooser(billCountries, string.Empty, true);
							using (var dlg = ApplicationGUIProvider.GetApplicationGuiProvider(header).GetNewAsycudaItemSelectionDialog(messageChooser, AsycudaItemSelectionDialog.BillsForDeclarationItemType, string.Empty))
							{
								dlg.DeSelectAll();
								dialogResult = ZFormModaliser.ShowDialogWithoutDispose(dlg);
								selectedBillCountries = dlg.GetSelectedItems().OfType<AsycudaBill>().ToArray();
							}

							if (dialogResult == DialogResult.OK)
							{
								var declarationReferences = new ZStringBuilder();
								var errorReferences = new ZStringBuilder();
								foreach (var billCountry in selectedBillCountries)
								{
									var declaration = billCountry.CreateCustomsDeclaration();
									if (declaration != null)
									{
										declarationReferences.Append(Invariant($"{billCountry.ABL_BillNumber} => {declaration.JE_DeclarationReference}"));
									}
									else
									{
										errorReferences.Append(Invariant($"{billCountry.ABL_BillNumber}"));
									}
								}
								if (!declarationReferences.IsEmpty)
								{
									Globals.Message.ShowInformation(Invariant($"Declaration has been created/updated for the following:\r\n{declarationReferences.ToStringWithNewLineBetweenAppends()}"));
								}
								else
								{
									Globals.Message.ShowInformation(Invariant($"Declaration could not be created/updated from Bill:\r\n{errorReferences.ToStringWithNewLineBetweenAppends()}"));
								}
							}
						}
						else
						{
							Globals.Message.Show(string.Format(CultureInfo.CurrentCulture, "Declarations are currently being created/updated by {0}, please try again later.", mutexManager.GetMutexLockByInfo()), "Try later", MessageBoxButtons.OK, MessageBoxIcon.Stop);
						}
					}
				}
			}
		}

		protected virtual DialogResult ShowSaveDialog(ZSaveFileDialog dialog)
		{
			return dialog.ShowDialog();
		}

		ZForm MainForm => (ZForm)GetMainMenu()?.GetForm();

		protected override void OnPopup(EventArgs e)
		{
			BuildMenu();
			base.OnPopup(e);
		}
	}

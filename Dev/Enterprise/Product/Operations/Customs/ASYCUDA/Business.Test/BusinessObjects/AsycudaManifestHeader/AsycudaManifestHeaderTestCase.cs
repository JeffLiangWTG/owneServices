using CargoWise.Data.Testing;
using CargoWise.EntityFramework;
using CargoWise.Types;
using Enterprise.Freight.Forwarding.Business;

namespace Enterprise.Customs.ASYCUDA.Business.Testing
{
	sealed class AsycudaManifestHeaderTestCase : NUnit.Framework.TestCase
	{
		[UseSnapshotProtection]
		public void TestOnSavingSetAMA_JobReferenceWithoutConsol_NoDuplicateReference()
		{
			var factory = new BusinessObjectFactory();
			var header = factory.New<AsycudaManifestHeader>();
			header.AMA_RN_NKCountry = "NA";
			AssertNull("Precondition", header.Consol);
			var jobReference = ZString.Empty;
			var clusterKey = ZInt.Zero;
			var dbConnection = ((CargoWise.Data.IDbConnected)factory).Connection;
			try
			{
				dbConnection.BeginTransaction();
				header.OnSaving();
				jobReference = header.AMA_JobReference;
				clusterKey = header.AMA_ClusterKey;
			}
			finally
			{
				dbConnection.RollbackTransaction();
			}

			var newFactory = new BusinessObjectFactory();
			var header2 = newFactory.New<AsycudaManifestHeader>();
			header2.AMA_RN_NKCountry = "NA";
			newFactory.Save();
			AssertEquals("The jobReference which header get first is set to header2", jobReference, header2.AMA_JobReference);
			AssertEquals("The header2 will not get increment of clusterKey as the assigned clusterKey for header is rolled back.", clusterKey, header2.AMA_ClusterKey);

			AssertEquals("header.AMA_JobReference is still jobReference under the same transaction before successfully saved", jobReference, header.AMA_JobReference);
			factory.Save();
			AssertNotEquals("Saved with no duplicate error and header get another jobReference", jobReference, header.AMA_JobReference);
			AssertEquals("header.AMA_ClusterKey get another cluster key.", clusterKey + 1, header.AMA_ClusterKey);
		}

		[UseSnapshotProtection]
		public void TestOnSavingSetAMA_JobReferenceWithConsol_NoDuplicateReference()
		{
			var factory = new BusinessObjectFactory();
			var header = factory.New<AsycudaManifestHeader>();
			header.AMA_RN_NKCountry = "NA";
			var consol = factory.New<ForwardingConsol>();
			consol.JK_UniqueConsignRef = "Con001";
			header.AMA_ParentTableCode = "JK";
			header.AMA_ParentId = consol.PK;
			AssertNotNull("Precondition", header.Consol);

			var dbConnection = ((CargoWise.Data.IDbConnected)factory).Connection;
			try
			{
				dbConnection.BeginTransaction();
				header.OnSaving();
				AssertEquals("header.AMA_JobReference is still jobReference under the same transaction before successfully saved", "Con001_1", header.AMA_JobReference);
			}
			finally
			{
				dbConnection.RollbackTransaction();
			}

			AssertEquals("header.AMA_JobReference is still jobReference under the same transaction before successfully saved", "Con001_1", header.AMA_JobReference);

			consol.JK_UniqueConsignRef = "Con002";
			factory.Save();
			AssertEquals("header.AMA_JobReference is generated by new condol.JK_UniqueConsignRef after successfully saved", "Con002_1", header.AMA_JobReference);
		}
	}
}

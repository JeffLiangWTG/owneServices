using System.Windows.Forms;
using Enterprise.Customs.ES.Registry;
using Enterprise.ZArchitecture.Environment;

namespace Enterprise.Customs.ES.GUI
{
	public static class MessageEditHelper
	{
		public static bool GetShouldEditMessagePopUpResponse(DialogResult defaultValue)
		{
			var result = false;
			if (ESCustomsDataRegistry.Instance.AllowEditEDIMessageBody.Value)
			{
				result = Globals.Message.Show(
							Res.GetString("B5FB4E10-6D6A-42E5-85DF-9E6F1E968E72", "Edit message mode is enabled in Registry/Customs/Country or Region Specific/Spain/Allow Edit EDI Message Body.\r\n \r\nDo you want to edit the EDI Messages generated by this operation?"),
							Res.GetString("849561DA-0CB9-4735-B5C4-ADF07564CC97", "Edit Message"),
						MessageBoxButtons.YesNo, MessageBoxIcon.Warning, defaultValue) == DialogResult.Yes;
			}
			return result;
		}
	}
}

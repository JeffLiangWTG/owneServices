using System.Windows.Forms;
using CargoWise.EntityFramework.Testing;
using Enterprise.Customs.ES.Business.Testing;
using Enterprise.ZArchitecture.Environment;
using Enterprise.ZArchitecture.GUI;

namespace Enterprise.Customs.ES.GUI.Testing
{
	public class MessageEditHelperTest : TestCaseWithFactory
	{
		public void TestGetShouldEditMessagePopUpResponse_AllowEditEDIMessageBody_True()
		{
			using (RegistryTemporarySetterHelper.SetAllowEditEDIMessageBody(true))
			using (var form = new ZForm())
			{
				CombineAssertions(() =>
				{
					var response = MessageEditHelper.GetShouldEditMessagePopUpResponse(DialogResult.No);
					AssertEquals("Should have message asking if the user wants to edit the message", true, UnitTestUserNotification.Instance.LastMessage.Contains("Edit message mode is enabled in Registry/Customs/Country or Region Specific/Spain/Allow Edit EDI Message Body.\r\n \r\nDo you want to edit the EDI Messages generated by this operation?"));
					AssertEquals("GetShouldEditMessagePopUpResponse returns false when default value is no and AllowEditEDIMessageBody is true", false, response);

					UnitTestUserNotification.Instance.ClearMessagesAndAnswers();
					response = MessageEditHelper.GetShouldEditMessagePopUpResponse(DialogResult.Yes);
					AssertEquals("Should have message asking if the user wants to edit the message", true, UnitTestUserNotification.Instance.LastMessage.Contains("Edit message mode is enabled in Registry/Customs/Country or Region Specific/Spain/Allow Edit EDI Message Body.\r\n \r\nDo you want to edit the EDI Messages generated by this operation?"));
					AssertEquals("GetShouldEditMessagePopUpResponse returns true when default value is yes and AllowEditEDIMessageBody is true", true, response);
				});
			}
		}

		public void TestGetShouldEditMessagePopUpResponse_AllowEditEDIMessageBody_False()
		{
			using (RegistryTemporarySetterHelper.SetAllowEditEDIMessageBody(false))
			using (var form = new ZForm())
			{
				CombineAssertions(() =>
				{
					var response = MessageEditHelper.GetShouldEditMessagePopUpResponse(DialogResult.No);
					AssertEquals("Should have message asking if the user wants to edit the message", false, UnitTestUserNotification.Instance.LastMessage.Contains("Edit message mode is enabled in Registry/Customs/Country or Region Specific/Spain/Allow Edit EDI Message Body.\r\n \r\nDo you want to edit the EDI Messages generated by this operation?"));
					AssertEquals("GetShouldEditMessagePopUpResponse returns false when default value is no and AllowEditEDIMessageBody is false", false, response);

					UnitTestUserNotification.Instance.ClearMessagesAndAnswers();
					response = MessageEditHelper.GetShouldEditMessagePopUpResponse(DialogResult.Yes);
					AssertEquals("Should have message asking if the user wants to edit the message", false, UnitTestUserNotification.Instance.LastMessage.Contains("Edit message mode is enabled in Registry/Customs/Country or Region Specific/Spain/Allow Edit EDI Message Body.\r\n \r\nDo you want to edit the EDI Messages generated by this operation?"));
					AssertEquals("GetShouldEditMessagePopUpResponse returns false when default value is yes but AllowEditEDIMessageBody is false", false, response);
				});
			}
		}
	}
}

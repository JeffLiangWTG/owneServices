namespace Enterprise.Customs.CN.Business.Testing
{
	class AcdAgrMessageSenderTest : TestCaseWithFactory
	{
		public void TestSendAndSave()
		{
			var entryHeader = TestData.EntryHeader;
			entryHeader.CH_BGMReference = "CUS202109030000001";
			Factory.Save();

			var notification = UnitTestUserNotification.Instance;
			notification.ClearMessagesAndAnswers();
			notification.AddAnswer(ZDialogResult.OK);
			Sender.SendAndSave(entryHeader);
			AssertContains("Single Window Client Application Settings should be entered for submitting the messages to CN Customs.", notification.LastMessage.Text);
			AssertEquals("No message should be added on EntryHeader", 0, entryHeader.Messages.Count);

			using (CNSWClientSettingCheckerTest.TemporarilySetCNSWClientSetting(Factory, entryHeader.Declaration.CompanyPK.ToGuid(), Guid.Empty))
			{
				var attachment = entryHeader.EntryInstruction.Attachments.AddNew();
				attachment.AttachmentType = CSDDocTypeList.Codes._10000001;
				attachment.AttachmentNumber = "20212243495988986";
				notification.ClearMessagesAndAnswers();
				notification.AddAnswer(ZDialogResult.No);
				Sender.SendAndSave(entryHeader);
				AssertContains("number already exists on the linked entry instruction", notification.LastMessage.Text);
				AssertEquals("No message should be added on EntryHeader", 0, entryHeader.Messages.Count);

				entryHeader.EntryInstruction.Attachments.RemoveAndDeleteAll();
				Env.Security.CustomsDeclarationSendWithMessageErrors.IsAllowed = true;
				notification.AddAnswer(ZDialogResult.No);
				Sender.SendAndSave(entryHeader);
				AssertContains("It is likely that your message will be rejected by Customs, as the following fields are not filled.", notification.LastMessage.Text);
				AssertEquals("No message should be added on EntryHeader", 0, entryHeader.Messages.Count);

				Env.Security.CustomsDeclarationSendWithMessageErrors.IsAllowed = false;
				notification.ClearMessagesAndAnswers();
				notification.AddAnswer(ZDialogResult.OK);
				Sender.SendAndSave(entryHeader);
				AssertContains("Please fill the following fields before sending the message.", notification.LastMessage.Text);
				AssertEquals("No message should be added on EntryHeader", 0, entryHeader.Messages.Count);

				Env.Security.CustomsDeclarationSendWithMessageErrors.IsAllowed = true;
				notification.ClearMessagesAndAnswers();
				notification.AddAnswer(ZDialogResult.Yes);

				TestData.JobDeclaration.JE_OH_Buyer = ZGuid.Invalid;
				Sender.SendAndSave(entryHeader);
				AssertContains("The Customs Declaration (JobDeclaration) cannot be inserted/updated, requires a reference to a valid Organization (OrgHeader).", notification.LastMessage.Text);
				AssertNull("Should not add an MSN event on saving failed", entryHeader.Logs.MostRecentLogByEventTime(Events.MessageSent));
				AssertEquals("No message should be added on EntryHeader", 0, entryHeader.Messages.Count);

				TestData.JobDeclaration.JE_OH_Buyer = ZGuid.Empty;
				Sender.SendAndSave(entryHeader);
				CombineAssertions(() =>
				{
					AssertEquals("New message should be added on EntryHeader", 1, entryHeader.Messages.Count);
					var message = entryHeader.Messages[0];
					AssertEquals("EDIMessage saved", true, message.IsInDatabase);
					AssertEquals("EM_ApplicationCode should be CSW", ApplicationCodeList.Codes.CNCustomsSingleWindow, message.EM_ApplicationCode);
					AssertEquals("EM_MessageType should be ACD", EDIMessageTypeList.Codes.ACD, message.EM_MessageType);
					AssertEquals("EM_ReceiveTransmit should be TRX", EDIMessage.Direction.Transmit, message.EM_ReceiveTransmit);
					AssertEquals("EM_ApplicationReference should be LocalReferenceNumber of EntryHeader", "CUS202109030000001", message.EM_ApplicationReference);
					AssertEquals("EM_Status should be QUE", EDIMessage.Status.Queued, message.EM_Status);
					var builder = new AcdAgrMessageBuilder(new AcdAgrMessageDataProvider(entryHeader));
					AssertEquals("EM_MessageText should be the message generated by the builder", ((IXmlMessageBuilder)builder).GenerateXmlMessage().GetSerializedString(), message.EM_MessageText);
					AssertEquals("Should add an MSN event", "Send Agreement of Customs Declaration Agent Message;CUS202109030000001", entryHeader.Logs.MostRecentLogByEventTime(Events.MessageSent).SL_Reference);
				});
			}
		}

		public void TestSend()
		{
			var declaration = TestData.JobDeclaration;
			var entryHeader1 = TestData.EntryHeader;
			entryHeader1.CH_BGMReference = "CUS202109030000001";
			var entryHeader2 = declaration.ActiveEntryHeaders.AddNew();
			entryHeader2.CH_BGMReference = "CUS202109030000002";
			Factory.Save();

			using (CNSWClientSettingCheckerTest.TemporarilySetCNSWClientSetting(Factory, declaration.CompanyPK.ToGuid(), Guid.Empty))
			{
				Env.Security.CustomsDeclarationSendWithMessageErrors.IsAllowed = true;
				var notification = UnitTestUserNotification.Instance;
				notification.ClearMessagesAndAnswers();
				notification.AddAnswer(ZDialogResult.Yes);

				Sender.Send(declaration.ActiveEntryHeaders.Cast<CusEntryHeader>());
				CombineAssertions(() =>
				{
					AssertEquals("New message should be added on EntryHeader 1", 1, entryHeader1.Messages.Count);
					AssertEquals("EDIMessage saved", false, entryHeader1.Messages[0].IsInDatabase);
					AssertEquals("Should add an MSN event", "Send Agreement of Customs Declaration Agent Message;CUS202109030000001", entryHeader1.Logs.MostRecentLogByEventTime(Events.MessageSent).SL_Reference);

					AssertEquals("New message should be added on EntryHeader 1", 1, entryHeader2.Messages.Count);
					AssertEquals("EDIMessage saved", false, entryHeader2.Messages[0].IsInDatabase);
					AssertEquals("Should add an MSN event", "Send Agreement of Customs Declaration Agent Message;CUS202109030000002", entryHeader2.Logs.MostRecentLogByEventTime(Events.MessageSent).SL_Reference);
				});
			}
		}

		CNEntryHeaderTestData TestData => testData ?? (testData = CNCusEntryHeaderHelper.SetupCusEntryHeader(Factory, () => { }));
		CNEntryHeaderTestData testData;

		AcdAgrMessageSender Sender => sender ?? (sender = new AcdAgrMessageSender(UnitTestUserNotification.Instance));
		AcdAgrMessageSender sender;
	}
}

		public void TestCreateOrganisationWithAndWihoutValidUNLOCO()
		{
			var currentDefaultAlgorithm = OrganisationsDataRegistry.Instance.OrgCodeAlgorithmDefault.GetFallBackValueAtAllLevels(Guid.Empty, Guid.Empty, Guid.Empty);
			var currentOverrideAlgorithm = OrganisationsDataRegistry.Instance.OrgCodeAlgorithmOverride.GetFallBackValueAtAllLevels(Guid.Empty, Guid.Empty, Guid.Empty);
			currentDefaultAlgorithm.Elements[OrgCodeElementDescription.UnlocoCode].Length = 3;
			currentDefaultAlgorithm.Elements[OrgCodeElementDescription.IataCode].Length = 3;
			currentOverrideAlgorithm.Elements[OrgCodeElementDescription.UnlocoCode].Length = 3;
			currentOverrideAlgorithm.Elements[OrgCodeElementDescription.IataCode].Length = 3;
			OrganisationsDataRegistry.Instance.OrgCodeAlgorithmDefault.SetValue(Guid.Empty, Guid.Empty, Guid.Empty, currentDefaultAlgorithm);
			OrganisationsDataRegistry.Instance.OrgCodeAlgorithmOverride.SetValue(Guid.Empty, Guid.Empty, Guid.Empty, currentOverrideAlgorithm);

			var unloco = new RefUNLOCO.Loader(Factory).Load("INKNU");
			if (unloco == null)
			{
				unloco = Factory.New<RefUNLOCO>();
				unloco.RL_Code = "INKNU";
				unloco.RL_PortName = "Kanpur";
				unloco.RL_IATA = "KNU";
				unloco.RL_RN_NKCountryCode = "IN";
			}

			var created = OrganisationCreator.CreateOrganisation(Factory, "LML LIMITED", "C 10 PANKI INDUSTRIAL ESTATE", "SITE II", "KANPUR", "", "208022", "INKNU", true, false);
			AssertEquals("LMLKNU", created.OH_Code);

			created = OrganisationCreator.CreateOrganisation(Factory, "LML LIMITED", "C 10 PANKI INDUSTRIAL ESTATE", "SITE II", "KANPUR", "", "208022", "#RRR#", true, false);
			AssertEquals("LML", created.OH_Code);
		}

		public void TestCreateManufacturer()
		{
			var currentDefaultAlgorithm = OrganisationsDataRegistry.Instance.OrgCodeAlgorithmDefault.GetFallBackValueAtAllLevels(Guid.Empty, Guid.Empty, Guid.Empty);
			var currentOverrideAlgorithm = OrganisationsDataRegistry.Instance.OrgCodeAlgorithmOverride.GetFallBackValueAtAllLevels(Guid.Empty, Guid.Empty, Guid.Empty);
			currentDefaultAlgorithm.Elements[OrgCodeElementDescription.UnlocoCode].Length = 5;
			currentDefaultAlgorithm.Elements[OrgCodeElementDescription.IataCode].Length = 5;
			currentOverrideAlgorithm.Elements[OrgCodeElementDescription.UnlocoCode].Length = 5;
			currentOverrideAlgorithm.Elements[OrgCodeElementDescription.IataCode].Length = 5;
			OrganisationsDataRegistry.Instance.OrgCodeAlgorithmDefault.SetValue(Guid.Empty, Guid.Empty, Guid.Empty, currentDefaultAlgorithm);
			OrganisationsDataRegistry.Instance.OrgCodeAlgorithmOverride.SetValue(Guid.Empty, Guid.Empty, Guid.Empty, currentOverrideAlgorithm);

			var mIDForTest = "CHCHATEC810MEY";

			var created = OrganisationCreator.CreateManufacturerAndSendNameAddressQueryMessage(Factory, mIDForTest);
			var header = created.Header;
			AssertEquals("OH_Code autogenerated", "AUTCRE", header.OH_Code);
			AssertEquals("AUTO CREATED FROM MID", header.OH_FullName);
			AssertEquals("Closest Port", "CH", header.OH_RL_NKClosestPort);
			AssertEquals("A MESSAGE HAS BEEN SENT TO US CUSTOMS TO REQUEST", header.MainAddress.OA_Address1);
			AssertEquals("ADDRESS DETAILS. ON SUCCESSFUL RESPONSE ADDRESS", header.MainAddress.OA_Address2);
			AssertEquals("DETAILS WILL BE FILLED IN", header.MainAddress.OA_City);
			AssertEquals(1, header.MainAddress.CustomsCodes.Count);
			AssertEquals(mIDForTest, header.MainAddress.CustomsCodes.GetCustomsRegNo(OrgCusCode.USACodeTypes.ManufacturerID, Core.Constants.CountryCodes.UnitedStates));
			AssertEquals(true, header.OH_IsConsignor);

			var query = new ZQuery(EDIMessageSchema.EM_LinkUniqueID, header.PK);

			var message = Factory.LoadTop1<MQEDIMessage>(query);
			AssertNotNull(message);

			var messageType = ACEApplicationIdentifierCodeList.Codes.ManufacturerNameAndAddressQuery;
			AssertEquals(messageType, message.EM_MessageType);

			var afterDefaultAlgorithm = OrganisationsDataRegistry.Instance.OrgCodeAlgorithmDefault.GetFallBackValueAtAllLevels(Guid.Empty, Guid.Empty, Guid.Empty);
			var afterOverrideAlgorithm = OrganisationsDataRegistry.Instance.OrgCodeAlgorithmOverride.GetFallBackValueAtAllLevels(Guid.Empty, Guid.Empty, Guid.Empty);
			AssertEquals(5, (int)afterDefaultAlgorithm.Elements[OrgCodeElementDescription.UnlocoCode].Length);
			AssertEquals(5, (int)afterOverrideAlgorithm.Elements[OrgCodeElementDescription.UnlocoCode].Length);
		}

		public void TestCreateUltimateConsignee()
		{
			var header = OrganisationCreator.CreateUltimateConsignee(Factory, "SKF USA", "1536 Genesis Rd", "", "Crossville", "TN", "38555", "US", "91-013199000");
			AssertEquals(true, header.OH_IsConsignee);
			AssertEquals("SKF USA", header.OH_FullName);
			AssertEquals("City", "Crossville", header.MainAddress.OA_City);
			AssertEquals("State", "TN", header.MainAddress.OA_State);
			AssertEquals("Closest Port", "US", header.OH_RL_NKClosestPort);
			AssertEquals("1536 Genesis Rd", header.MainAddress.OA_Address1);
			AssertEquals(1, header.CustomsCodes.Count);
			AssertEquals("91-013199000", header.CustomsCodes.GetCustomsRegNo(OrgCusCode.USACodeTypes.EmployerIdentificationNumber, Core.Constants.CountryCodes.UnitedStates));
		}

		[ExpectNoExceptions]
		public void TestNoExceptionOnLongString()
		{
			var org = OrganisationCreator.CreateOrganisation(
				Factory,
				"".PadRight(OrgHeaderSchema.OH_FullName.MaxLength * 2, 'A'),
				"".PadRight(OrgAddressSchema.OA_Address1.MaxLength * 2, 'B'),
				"".PadRight(OrgAddressSchema.OA_Address2.MaxLength * 2, 'C'),
				"".PadRight(OrgAddressSchema.OA_City.MaxLength * 2, 'D'),
				"".PadRight(OrgAddressSchema.OA_State.MaxLength * 2, 'E'),
				"".PadRight(OrgAddressSchema.OA_PostCode.MaxLength * 2, 'F'),
				"AUBNE",
				false,
				false
				);

			AssertEquals("".PadRight(OrgHeader.Schema.OH_FullNameTruncatedLength, 'A'), org.OH_FullName);
			AssertEquals("".PadRight(OrgAddressSchema.OA_Address1.MaxLength, 'B'), org.MainAddress.OA_Address1);
			AssertEquals("".PadRight(OrgAddressSchema.OA_Address2.MaxLength, 'C'), org.MainAddress.OA_Address2);
			AssertEquals("".PadRight(OrgAddressSchema.OA_City.MaxLength, 'D'), org.MainAddress.OA_City);
			AssertEquals("".PadRight(OrgAddressSchema.OA_State.MaxLength, 'E'), org.MainAddress.OA_State);
			AssertEquals("".PadRight(OrgAddressSchema.OA_PostCode.MaxLength, 'F'), org.MainAddress.OA_PostCode);
		}

		public void TestNoExceptionWhenCreateOrgFromMIDWithLeadingSpaces()
		{
			var orgAddress = OrganisationCreator.CreateManufacturerAndSendNameAddressQueryMessage(Factory, " ~ABCD1234");
			AssertNoExceptionThrown(() =>
			{
				Factory.Save();
			});
			AssertNull("Address shouldn't be created, becasue MID has invalid characters", orgAddress);

			orgAddress = OrganisationCreator.CreateManufacturerAndSendNameAddressQueryMessage(Factory, "ABCD1234");
			AssertNoExceptionThrown(() =>
			{
				Factory.Save();
			});
			AssertNotNull("Address should be created, becasue MID characters are alphanumeric", orgAddress);
		}
	}

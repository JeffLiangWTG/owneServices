				.Concat(APHISProcessingTypeCodeList.GetListForT300(Factory).OfType<ICodeDescription>())
				.Select(x => x.Code).Concat(new[] { APHISProcessingTypeCodeList.Codes.ACA, APHISProcessingTypeCodeList.Codes.ATR }).ToArray();
			AssertList<APHISProcessingTypeCodeList>(list1, expectedCodes, fullList);

			list1 = APHISProcessingTypeCodeList.GetListFor(Factory, APHISProgramCodeList.Codes.APQ, APHISCategoryTypeCodeList.Codes.CutFlowersAndGreenery);
			list2 = APHISProcessingTypeCodeList.GetListFor(Factory, APHISProgramCodeList.Codes.APQ, APHISCategoryTypeCodeList.Codes.CutFlowersAndGreenery);
			AssertEquals("Data should be cached", list1, list2);

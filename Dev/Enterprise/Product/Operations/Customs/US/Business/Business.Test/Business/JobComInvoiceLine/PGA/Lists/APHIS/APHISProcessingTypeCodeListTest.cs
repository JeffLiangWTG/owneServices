		{
			var fullList = new APHISProcessingTypeCodeList();
			var list1 = APHISProcessingTypeCodeList.GetListFor(Factory, APHISProgramCodeList.Codes.APQ, APHISCategoryTypeCodeList.Codes.PropagativeMaterial);
			var list2 = APHISProcessingTypeCodeList.GetListFor(Factory, APHISProgramCodeList.Codes.APQ, APHISCategoryTypeCodeList.Codes.PropagativeMaterial);
			AssertEquals("Data should be cached", list1, list2);
			var expectedCodes = APHISProcessingTypeCodeList.GetListForT200(Factory).OfType<ICodeDescription>().Select(x => x.Code).Concat(new[] { APHISProcessingTypeCodeList.Codes.ACA, APHISProcessingTypeCodeList.Codes.ATR }).ToArray();
			AssertList<APHISProcessingTypeCodeList>(list1, expectedCodes, fullList);

			list1 = APHISProcessingTypeCodeList.GetListFor(Factory, APHISProgramCodeList.Codes.AVS, APHISCategoryTypeCodeList.Codes.LiveAnimals);
			list2 = APHISProcessingTypeCodeList.GetListFor(Factory, APHISProgramCodeList.Codes.AVS, APHISCategoryTypeCodeList.Codes.LiveAnimals);
			AssertEquals("Data should be cached", list1, list2);
			expectedCodes = new[] { APHISProcessingTypeCodeList.Codes.AVDIP, APHISProcessingTypeCodeList.Codes.AVRAB, APHISProcessingTypeCodeList.Codes.ACA, APHISProcessingTypeCodeList.Codes.ATR };
			AssertList<APHISProcessingTypeCodeList>(list1, expectedCodes, fullList);

			list1 = APHISProcessingTypeCodeList.GetListFor(Factory, APHISProgramCodeList.Codes.AVS, APHISCategoryTypeCodeList.Codes.AnimalProductsAndAnimalByProducts);
			list2 = APHISProcessingTypeCodeList.GetListFor(Factory, APHISProgramCodeList.Codes.AVS, APHISCategoryTypeCodeList.Codes.AnimalProductsAndAnimalByProducts);

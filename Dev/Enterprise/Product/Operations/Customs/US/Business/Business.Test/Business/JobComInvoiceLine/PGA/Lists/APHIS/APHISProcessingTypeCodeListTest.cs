			expectedCodes = new[] { APHISProcessingTypeCodeList.Codes.AVHTD, APHISProcessingTypeCodeList.Codes.ACA, APHISProcessingTypeCodeList.Codes.ATR };
			AssertList<APHISProcessingTypeCodeList>(list1, expectedCodes, fullList);

			list1 = APHISProcessingTypeCodeList.GetListFor(Factory, APHISProgramCodeList.Codes.APQ, APHISCategoryTypeCodeList.Codes.SeedsNotForPlanting);
			list2 = APHISProcessingTypeCodeList.GetListFor(Factory, APHISProgramCodeList.Codes.APQ, APHISCategoryTypeCodeList.Codes.SeedsNotForPlanting);

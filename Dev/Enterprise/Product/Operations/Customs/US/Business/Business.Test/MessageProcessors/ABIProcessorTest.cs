		internal void AssertEntrySummaryQueryMessageSent(CusEntryHeader entry, int expectedMessagesCount, ZDateTime heldUntilDate, string explanation)
		{
			entry.Messages.Load();
			var msgType = entry.IsACE ? ACEApplicationIdentifierCodeList.Codes.EntrySummaryQuery : ApplicationIdentifierCodeList.Codes.QueryEntrySummary;
			var ensqMessages = entry.Messages.Find(x => x.EM_MessageType == msgType);
			AssertEquals(explanation, expectedMessagesCount, ensqMessages.Count());
			if (ensqMessages.Any())
			{
				AssertEquals("Held until date", heldUntilDate.Date, ensqMessages.ToList()[0].EM_HeldUntilDate.Date);
			}
		}

		void AssertEmailBranchLogoChangesDoNotCauseException()
		{
			if (EmailsExpectedAtCompletionOfEndToEndTest > 0)
			{
				AssertEquals("Emails expected to be generated by this processor", EmailsExpectedAtCompletionOfEndToEndTest, Env.OutgoingCustomsMailManager.EmailsCreated.Count);

				EmailDef notificationEmail = Env.OutgoingCustomsMailManager.EmailsCreated[EmailsExpectedAtCompletionOfEndToEndTest - 1];
				Assert("At least 1 recipient is expected", notificationEmail.Recipients.Count > 0);
			}
		}

		protected virtual ZInt EmailsExpectedAtCompletionOfEndToEndTest
		{
			get { return 0; }
		}

		protected abstract void EndToEndCore();

		/// <summary>
		/// Call this method to actually process the message - it will check the attributes are attached to make the message identifiable
		/// </summary>
		/// <param name="generator"></param>
		protected void ProcessMessage(ABIOutputBlockControlGenerator generator)
		{
			ProcessMessage(Factory, generator);
		}

		protected virtual bool ClearEmails
		{
			get { return true; }
		}

		protected void ProcessMessage(BusinessObjectFactory factory, ABIOutputBlockControlGenerator generator, GlbBranch branch = null)
		{
			var ediMessage = factory.New<MQEDIMessage>();
			ediMessage.EM_ReceiveTransmit = "RCV";
			ediMessage.EM_MessageText = generator.Serialise();
			ediMessage.EM_MessageNum = generator.B.UserData;
			ediMessage.EM_MessageType = generator.B.ApplicationIdentifier;
			ediMessage.EM_SystemCreateTimeUtc = ZDateTime.Now;
			ediMessage.EM_GB = branch == null ? GlbBranch.CurrentBranch.PK : branch.PK;
			if (ClearEmails)
			{
				Env.OutgoingCustomsMailManager.EmailsCreated.Clear();
			}
			AssertNoExceptionThrown(delegate
			{ CreateNewMessageProcessorFactory(new LoggingInformation()).ProcessMessage(ediMessage); });
		}

		protected virtual MessageProcessorFactory CreateNewMessageProcessorFactory(LoggingInformation logger)
		{
			return new ABIMessageProcessorFactory(logger);
		}

		protected void AssertNotClearedWhenMessageWasSendWithoutError(EDIMessage originalMessage, EDIMessage responseMessage, params ZString[] extraMessages)
		{
			string lastExpectedKey = ResponseMessageAbnormalityReporter.NotClearedWhenMessageWasSendWithoutErrorKey;
			AssertLastMessageReported(lastExpectedKey, originalMessage, responseMessage, extraMessages);
		}

		protected void AssertClearedWhenMessageWasSendWithError(EDIMessage originalMessage, EDIMessage responseMessage, params ZString[] extraMessages)
		{
			string lastExpectedKey = ResponseMessageAbnormalityReporter.ClearedWhenMessageWasSendWithErrorKey;
			AssertLastMessageReported(lastExpectedKey, originalMessage, responseMessage, extraMessages);
		}

		protected void AssertLastMessageReported(string lastExpectedKey, EDIMessage originalMessage, EDIMessage responseMessage, params ZString[] extraMessages)
		{
			if (responseMessage != null)
			{
				lastExpectedKey += string.Format(" for Message Type '{0}' and Application Code '{1}'", responseMessage.EM_MessageType, responseMessage.EM_ApplicationCode);
				AssertContains("LastMessageReported contains response message", responseMessage.EM_FormattedMessageText, ErrorReporter.LastMessageReported);
			}

			AssertEquals("LastKeyReported", lastExpectedKey, ErrorReporter.LastKeyReported);
			if (originalMessage != null)
			{
				AssertContains("LastMessageReported contains original message", originalMessage.EM_FormattedMessageText, ErrorReporter.LastMessageReported);
			}

			foreach (ZString extraMessage in extraMessages)
			{
				AssertContains("LastMessageReported contains extra message errors", extraMessage, ErrorReporter.LastMessageReported);
			}
			ErrorReporter.Clear();
		}

		protected void AssertQuotaStoreInCusDisposition(CusEntryLine cusEntryLine, BaseEDIMessage message, Dictionary<ZString, ZString[]> expectedValued)
		{
			cusEntryLine.QuotaDispositions.Cast<CusDisposition>().ForEach(disposition =>
			{
				var lineToCheck = expectedValued.GetValueSafe(disposition.CDI_Status);
				AssertEquals("CDI_ParentID", cusEntryLine.PK, disposition.CDI_ParentID);
				AssertEquals("CDI_ParentTableCode", "CL", disposition.CDI_ParentTableCode);
				AssertEquals("CDI_Sequence", new ZShort(lineToCheck[0]), disposition.CDI_Sequence);
				AssertEquals("CDI_Status", lineToCheck[1], disposition.CDI_Status);
				AssertEquals("CDI_StatusDate", message.EM_MessageDateTime, disposition.CDI_StatusDate);
				AssertEquals("CDI_StatusKey", lineToCheck[2], disposition.CDI_StatusKey);
				Assert("CDI_SystemCreateTimeUtc", Env.Time.GetLocalTimeFromUtc(DateTime.Now) > message.EM_MessageDateTime);
				AssertEquals("CDI_Type", CusDispositionTypeCodeList.Codes.USQuotaLineStatus, disposition.CDI_Type);
				AssertEquals("CDI_Notes", lineToCheck[3], disposition.CDI_Notes);
			});
		}

		protected void AddMessageBlocksToProcessor(ABIProcessor<ControlMessageBlockA, ControlMessageBlockB, ControlMessageBlockY> processor, string applicationReference, params string[] messageBlocks)
		{
			BlockControlGenerator block = OutputBlockControlGeneratorTestHelper.GetBlockControlGenerator(applicationReference, messageBlocks);
			foreach (MessageBlock messageBlock in block.MessageBlocks)
			{
				processor.AddMessageBlock(messageBlock);
			}
		}

		protected MQEDIMessage CreateInterchangeAndMessageResponse(string applicationReference, string interchangeHeaderText, string messageText, string interchangeFooterText, string messageNum)
		{
			var interchange = Factory.New<CBPEDIInterchange>();
			interchange.EI_ApplicationCode = EDIMessage.ApplicationCodes.USCustomsImport;
			interchange.EI_From = "USC";
			interchange.EI_To = "SV9";
			interchange.EI_ReceiveTransmit = CBPEDIInterchange.Direction.Receive;
			interchange.EI_HeaderText = interchangeHeaderText;
			interchange.EI_BodyText = messageText;
			interchange.EI_FooterText = interchangeHeaderText;
			MQEDIMessage message = (MQEDIMessage)interchange.ContainedMessages.AddNew(typeof(MQEDIMessage));
			message.EM_ApplicationCode = EDIMessage.ApplicationCodes.USCustomsImport;
			message.EM_ReceiveTransmit = EDIMessage.Direction.Receive;
			message.EM_MessageType = applicationReference;
			message.EM_MessageText = messageText;
			message.EM_Status = EDIMessage.Status.Queued;
			message.EM_MessageNum = messageNum;
			Factory.Save();
			return message;
		}

		protected ZString HtmlEncode(ZString data)
		{
			return WebUtility.HtmlEncode(data).Replace("\r\n", "<br>").Replace("\n", "<br>");
		}


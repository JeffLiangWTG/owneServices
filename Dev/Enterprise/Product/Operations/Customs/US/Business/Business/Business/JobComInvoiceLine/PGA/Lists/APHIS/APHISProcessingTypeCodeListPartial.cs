		public static ICodeDescriptionPairList GetListFor(BusinessObjectFactory factory, ZString programType, ZString categoryType)
		{
			var localFactory = factory;
			return localFactory.GetCachedValue<ICodeDescriptionPairList>(string.Format("APHISProcessingTypeCodeList_{0}_{1}", programType, categoryType), () =>
			{
				var result = new CodeDescriptionPairList();
				result.AddPair(Codes.ACA, Descriptions.ACA);
				result.AddPair(Codes.ATR, Descriptions.ATR);
				switch (programType)
				{
					case APHISProgramCodeList.Codes.APQ:
						AddAPQCodes(result, localFactory, categoryType);
						break;
					case APHISProgramCodeList.Codes.AVS:
						AddAVSCodes(result, localFactory, categoryType);
						break;
				}

				result.SortByDescription();
				return result;
			});
		}

		static void AddAPQCodes(CodeDescriptionPairList result, BusinessObjectFactory factory, ZString categoryType)
		{
			switch (categoryType)
			{
				case APHISCategoryTypeCodeList.Codes.PropagativeMaterial:
					result.AddRange(GetListForT200(factory));
					break;
				case APHISCategoryTypeCodeList.Codes.CutFlowersAndGreenery:
				case APHISCategoryTypeCodeList.Codes.SeedsNotForPlanting:
					result.AddRange(GetListForT200(factory));
					result.AddRange(GetListForT300(factory));
					break;
				case APHISCategoryTypeCodeList.Codes.FruitsAndVegetables:
					result.AddRange(GetListForT100(factory));
					result.AddRange(GetListForT200(factory));
					result.AddRange(GetListForT500(factory));
					break;
				case APHISCategoryTypeCodeList.Codes.MiscellaneousAndProcessedProducts:
					result.AddRange(GetListForT300(factory));
					result.AddRange(GetListForT400(factory));
					result.AddRange(GetListForT500(factory));
					break;
			}
		}

		static void AddAVSCodes(CodeDescriptionPairList result, BusinessObjectFactory factory, ZString categoryType)
		{
			switch (categoryType)
			{
				case APHISCategoryTypeCodeList.Codes.LiveAnimals:
					result.AddPair(Codes.AVDIP, Descriptions.AVDIP);
					result.AddPair(Codes.AVRAB, Descriptions.AVRAB);
					break;
				case APHISCategoryTypeCodeList.Codes.AnimalProductsAndAnimalByProducts:
					result.AddPair(Codes.AVHTD, Descriptions.AVHTD);
					break;
			}
		}


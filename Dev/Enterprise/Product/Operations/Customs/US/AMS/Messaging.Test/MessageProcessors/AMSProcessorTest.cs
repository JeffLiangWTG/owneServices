		void AssertEmailBranchLogoChangesDoNotCauseException()
		{
			if (EmailsExpectedAtCompletionOfEndToEndTest > 0)
			{
				AssertEquals("Emails expected to be generated by this processor", EmailsExpectedAtCompletionOfEndToEndTest, Env.OutgoingCustomsMailManager.EmailsCreated.Count);
				var notificationEmail = Env.OutgoingCustomsMailManager.EmailsCreated[EmailsExpectedAtCompletionOfEndToEndTest - 1];
				Assert("At least 1 recipient is expected", notificationEmail.Recipients.Count > 0);
			}
		}


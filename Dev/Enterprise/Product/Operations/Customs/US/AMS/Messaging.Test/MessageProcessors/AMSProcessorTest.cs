		/// Call this method to actually process the message - it will check the attributes are attached to make the message identifiable
		/// </summary>
		/// <param name = "generator"></param>
		protected void ProcessMessage(AMSOutputBlockControlGenerator generator)
		{
			ProcessMessage(Factory, generator);
		}

		protected void ProcessMessage(BusinessObjectFactory factory, AMSOutputBlockControlGenerator generator)
		{
			var ediMessage = factory.New<AMSEDIMessage>();
			ediMessage.EM_ReceiveTransmit = AMSEDIMessage.Direction.Receive;
			ediMessage.EM_MessageText = generator.Serialise();
			Env.OutgoingCustomsMailManager.EmailsCreated.Clear();
			AssertNoExceptionThrown(delegate
			{
				new AMSMessageProcessorFactory(new LoggingInformation()).ProcessMessage(ediMessage);
			});
		}

		protected void AssertNotClearedWhenMessageWasSendWithoutError(EDIMessage originalMessage, EDIMessage responseMessage, params ZString[] extraMessages)
		{
			var lastExpectedKey = ResponseMessageAbnormalityReporter.NotClearedWhenMessageWasSendWithoutErrorKey;
			AssertLastMessageReported(lastExpectedKey, originalMessage, responseMessage, extraMessages);
		}

		protected void AssertClearedWhenMessageWasSendWithError(EDIMessage originalMessage, EDIMessage responseMessage, params ZString[] extraMessages)
		{
			var lastExpectedKey = ResponseMessageAbnormalityReporter.ClearedWhenMessageWasSendWithErrorKey;
			AssertLastMessageReported(lastExpectedKey, originalMessage, responseMessage, extraMessages);
		}

		protected void AssertLastMessageReported(string lastExpectedKey, EDIMessage originalMessage, EDIMessage responseMessage, params ZString[] extraMessages)
		{
			if (responseMessage != null)
			{
				lastExpectedKey += string.Format(" for Message Type '{0}' and Application Code '{1}'", responseMessage.EM_MessageType, responseMessage.EM_ApplicationCode);
				AssertContains("LastMessageReported contains response message", responseMessage.EM_FormattedMessageText, ErrorReporter.LastMessageReported);
			}

			AssertEquals("LastKeyReported", lastExpectedKey, ErrorReporter.LastKeyReported);
			if (originalMessage != null)
			{
				AssertContains("LastMessageReported contains original message", originalMessage.EM_FormattedMessageText, ErrorReporter.LastMessageReported);
			}

			foreach (var extraMessage in extraMessages)
			{
				AssertContains("LastMessageReported contains extra message errors", extraMessage, ErrorReporter.LastMessageReported);
			}

			ErrorReporter.Clear();
		}

		protected AMSEDIMessage CreateInterchangeAndMessageResponse(string applicationReference, string interchangeHeaderText, string messageText, string interchangeFooterText, string messageNum)
		{
			var interchange = Factory.New<CBPEDIInterchange>();
			interchange.EI_ApplicationCode = CBPEDIInterchange.ApplicationCodes.AMS;
			interchange.EI_From = "USC";
			interchange.EI_To = "SV9";
			interchange.EI_ReceiveTransmit = EDIInterchange.Direction.Receive;
			interchange.EI_HeaderText = interchangeHeaderText;
			interchange.EI_BodyText = messageText;
			interchange.EI_FooterText = interchangeFooterText;
			var message = (AMSEDIMessage)interchange.ContainedMessages.AddNew(typeof(AMSEDIMessage));
			message.EM_ApplicationCode = EDIMessage.ApplicationCodes.AMS;
			message.EM_ReceiveTransmit = EDIMessage.Direction.Receive;
			message.EM_MessageType = applicationReference;
			message.EM_MessageText = interchange.EI_InterchangeText;
			message.EM_Status = EDIMessage.Status.Queued;
			message.EM_MessageNum = messageNum;
			Factory.Save();
			return message;
		}


		[TestDate(2021, 2, 4)]
		public void TestMatchingIncomingEventByDataContextKey()
		{
			var trip = GetNewBusinessObjectForTesting();
			trip.BH_JobReference = "Test Reference";
			Factory.SaveForTesting();
			var universalEvent = new UniversalXml.Event();
			universalEvent.DataContext = DataContextFactory.New();
			universalEvent.DataContext.AddDataTarget(DataContextType.USeManifestTrip, "Test Reference 2");
			universalEvent.EventType = Events.CustomisableEvent00Code;
			universalEvent.EventTime = ZDateTimeOffset.Today;
			var serviceTaskLog = new ServiceTaskLogForTesting();
			var manager = new UniversalMessageProcessingManager(serviceTaskLog);
			var message = GetQueuedUniversalEventMessage(universalEvent);
			manager.Process(message);
			AssertEquals(EDIMessageStatusList.Codes.Discarded, message.EM_Status);
			universalEvent.DataContext.DataTargetCollection.Single().Key = "Test Reference";
			serviceTaskLog = new ServiceTaskLogForTesting();
			manager = new UniversalMessageProcessingManager(serviceTaskLog);
			message = GetQueuedUniversalEventMessage(universalEvent);
			manager.Process(message);
			Factory.SaveForTesting();
			CombineAssertions(() =>
			{
				AssertEquals(EDIMessageStatusList.Codes.ProcessedOK, message.EM_Status);
				AssertMultilineASCIIEquals("Service Task Log", @"
Linked Event to Trip: Test Reference.
".Trim(), serviceTaskLog.ToString());
				var logNoteText = message.GetLogNoteText();
				AssertMultilineASCIIEquals("Message Log", @"
Linked Event to Trip: Test Reference.
".Trim(), logNoteText);
				var tripInNewFactory = new BusinessObjectFactory().Load<Trip>(trip.PK);
				var importedEvent = tripInNewFactory.Logs.Find(x => x.SL_SE_NKEvent == Events.CustomisableEvent00Code).Single();
				AssertEquals(ZDateTime.Today, importedEvent.SL_EventTime);
			});
		}

		[TestDate(2021, 2, 4)]
		public void TestOutgoingUniversalEvent()
		{
			using (eAdaptorRegistry.Instance.OutboundAdapterServiceUrl.SetTemporaryValue(Guid.Empty, Guid.Empty, Guid.Empty, "http://abc.def"))
			{
				var trip = GetNewBusinessObjectForTesting();
				trip.BH_JobReference = "Test Reference";
				var trigger = MasterFilesTestHelper.CreateTrigger(trip, Events.CustomisableEvent00Code);
				var action = MasterFilesTestHelper.CreateTriggerAction(trigger, WorkflowTriggerActionTypeConstants.Codes.SendUniversalEventXML, MessageRecipientPartyTypeList.Codes.OrgProxy);
				action.PQ_MessagePurpose = "EVT";
				Factory.SaveForTesting();
				var orgProxy = GlbCompany.CurrentCompany.OrgProxy;
				var mode = orgProxy.EDICommunicationsModes.AddNew();
				mode.EK_Module = ((IWorkflowProvider)trip).WorkflowType;
				mode.EK_FileFormat = EDICommunicationsModeFileFormatList.Codes.XmlUniversalEvent;
				mode.EK_CommunicationsTransport = EDICommunicationsModeCommunicationsTransportList.Codes.EAdaptorInterface;
				mode.EK_Destination = "To the void";
				mode.Factory.Save();
				trip.Logs.AddNew(Events.CustomisableEvent00, "Test Reference", ZDateTimeOffset.Now, false);
				Factory.SaveForTesting();
				MasterFilesTestHelper.RunLogWalker();
				var messages = Factory.Load<EDIMessage>(new ZQuery());
				AssertEquals("1 Message should have been generated by the trigger", 1, messages.Length);
				var message = messages.Single();
				var interchange = message.Interchange;
				AssertEquals("Message Type", EDIMessageTypeList.Codes.XDC, message.EM_MessageType);
				AssertEquals("Message Status", EDIMessageStatusList.Codes.Sent, message.EM_Status);
				AssertIsXml(message.EM_MessageText)
					.HavingExactlyOneChildNode("Event/DataContext/ActionPurpose/Code",
						node => node.WithValue(action.PQ_MessagePurpose)
					).HavingExactlyOneChildNode("Event/DataContext/EventType/Code",
						node => node.WithValue("Z00")
					).HavingExactlyOneChildNode("Event/EventReference",
						node => node.WithValue(trip.BH_JobReference)
					);
			}
		}

		public void TestGetShipmentDataObjectReader()
		{
			var trip = Factory.New<Trip>();
			var eventManager = trip.GetUniversalDataContextManager() as IShipmentDataContextManagerInternal;
			var reader = eventManager.GetShipmentDataObjectReader(new UniversalXml.Shipment(), new DummyLogger(), Factory);
			AssertNull(reader);
			var shipment = new UniversalXml.Shipment(DefaultDataObjectWriterStrategy.TestInstance);
			shipment.DataContext = DataContextFactory.New();
			shipment.DataContext.AddDataSource(DataContextType.ForwardingConsol, "test consol");
			shipment.DataContext.AddDataSource(DataContextType.ForwardingShipment, "test shipment");
			var subShipment = new UniversalXml.Shipment(DefaultDataObjectWriterStrategy.TestInstance);
			shipment.SetSubShipmentCollection(() => new DataObjectList<UniversalXml.Shipment>());
			shipment.SubShipmentCollection.Add(subShipment);
			subShipment.ShipmentType = new UniversalXml.CodeDescriptionPair()
			{
				Code = Core.Constants.ShipmentTypes.HighVolumeLowValue
			};
			subShipment.DataContext = DataContextFactory.New();
			subShipment.DataContext.AddDataSource(DataContextType.ForwardingShipment, "test shipment");
			subShipment.SetSubShipmentCollection(() => new DataObjectList<UniversalXml.Shipment>());
			var consignmentSubShipment = new UniversalXml.Shipment(DefaultDataObjectWriterStrategy.TestInstance);
			subShipment.SubShipmentCollection.Add(consignmentSubShipment);
			consignmentSubShipment.DataContext = DataContextFactory.New();
			consignmentSubShipment.DataContext.AddDataSource(DataContextType.HVLVConsignment, "test consignment");
			reader = eventManager.GetShipmentDataObjectReader(shipment, new DummyLogger(), Factory);
			AssertType<HVLVTripDataObjectReader>(reader);
		}


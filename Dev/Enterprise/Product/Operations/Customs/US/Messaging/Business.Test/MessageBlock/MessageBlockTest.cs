		public void TestNonABICharactersAreReplaceWithASpace()
		{
			MessageBlockDummy dummy = new MessageBlockDummy();
			dummy.Dummy = "HELLO\r\nbob";
			AssertEquals("F109 HELLO**BOB0000000000".PadRight(80), dummy.Serialise());

			dummy.Dummy = "YoÓweÜndy";
			AssertEquals("F109 YO*WE*NDY 0000000000".PadRight(80), dummy.Serialise());

			string[] validStrings = new string[] {
					@"!@#$%^&*()",
					@"-_=+[{]}\|",
					@";:'"",<.>/?",
					@"`~  ABCDEF",
					@"GHIJKLMNOP",
					@"QRSTUVWXYZ",
					@"0123456789",
					@"abcdefghij",
					@"klmnopqrst",
					@"uvwxyz    "
			};

			foreach (string validString in validStrings)
			{
				dummy.Dummy = validString;
				AssertEquals(("F109 " + validString.ToUpper() + "0000000000").PadRight(80), dummy.Serialise());
			}
		}

		[ExpectNoExceptions]
		public void TestMessageBlockIntAttributeLengthIsNotGreaterThan9Numerics()
		{
			StringBuilder failures = new StringBuilder();
			SubClassRetriever retriever = new SubClassRetriever(GetType().Assembly, typeof(MessageBlock));
			retriever.IncludeAutoGeneratedCode = false;
			retriever.IncludeAbstractClasses = false;
			Type messageBlockIntAttributeType = typeof(MessageBlockIntAttribute);

			foreach (Type type in retriever.Retrieve())
			{
				MessageBlock block = (MessageBlock)Activator.CreateInstance(type);
				List<MessageBlock.AttributeFieldInfo> fieldInfos = new List<MessageBlock.AttributeFieldInfo>(block.GetAttributeFieldInfos());
				foreach (MessageBlock.AttributeFieldInfo fieldInfo in fieldInfos)
				{
					if (fieldInfo.Attribute.GetType() == messageBlockIntAttributeType && fieldInfo.Attribute.Length > 9)
					{
						failures.AppendLine(string.Format("{0}.{1}'s MessageBlockIntAttribute.Length is greater than 9 numeric characters", type.FullName, fieldInfo.FieldInfo.Name));
					}
				}
			}

			if (failures.Length > 0)
			{
				Fail(failures.ToString());
			}
		}


		public void TestEndDateAdjustment()
		{
			MessageBlockDummy dummy = new MessageBlockDummy();
			var beginDate = new ZDate(2016, 2, 2);
			var endDate = new ZDate(1939, 12, 31);

			var cultureInfo = (CultureInfo)System.Threading.Thread.CurrentThread.CurrentCulture.Clone();
			try
			{
				System.Threading.Thread.CurrentThread.CurrentCulture.DateTimeFormat.Calendar.TwoDigitYearMax = 2029;
				endDate = dummy.AdjustedEndDateForTest(beginDate, endDate);
				AssertEquals(new ZDate(2039, 12, 31), endDate);
				endDate = new ZDate(1959, 12, 31);
				endDate = dummy.AdjustedEndDateForTest(beginDate, endDate);
				AssertEquals(new ZDate(2059, 12, 31), endDate);
			}
			finally
			{
				System.Threading.Thread.CurrentThread.CurrentCulture = cultureInfo;
			}
		}


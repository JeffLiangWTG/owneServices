		public void TestIsEmpty()
		{
			MessageBlockDummy dummy = new MessageBlockDummy();
			AssertEquals("IsEmpty", false, dummy.IsEmpty);

			dummy.Dummy = "";
			AssertEquals("IsEmpty", true, dummy.IsEmpty);


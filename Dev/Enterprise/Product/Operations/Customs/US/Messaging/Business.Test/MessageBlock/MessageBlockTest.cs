		[ExpectNoExceptions]
		public void TestMandatoryCharacters()
		{
			StringBuilder failures = new StringBuilder();
			SubClassRetriever retriever = new SubClassRetriever(GetType().Assembly, typeof(MessageBlock));
			retriever.IncludeAbstractClasses = false;
			foreach (Type type in retriever.Retrieve())
			{
				MessageBlock block = (MessageBlock)Activator.CreateInstance(type);
				List<MessageBlock.AttributeFieldInfo> fieldInfos = new List<MessageBlock.AttributeFieldInfo>(block.GetAttributeFieldInfos());
				fieldInfos.Sort((MessageBlock.AttributeFieldInfo x, MessageBlock.AttributeFieldInfo y) => x.Attribute.Offset.CompareTo(y.Attribute.Offset));

				int startPos = block.MandatoryCharacters.Length;
				if (fieldInfos.Count > 0 && fieldInfos[0].Attribute.Offset < block.MandatoryCharacters.Length)
				{
					failures.AppendLine(type.FullName + " - Mandatory characters overlap with writable data");
				}
			}
			if (failures.Length > 0)
			{
				Fail(failures.ToString());
			}
		}

		public void TestSerialise()
		{
			MessageBlockDummy messageBlock = new MessageBlockDummy();
			string result = messageBlock.Serialise();

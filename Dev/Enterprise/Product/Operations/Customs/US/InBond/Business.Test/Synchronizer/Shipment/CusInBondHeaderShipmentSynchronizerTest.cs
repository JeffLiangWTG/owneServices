		public void TestDeletingMoveHeadersIfNeeded()
		{
			var declaration = Factory.New<JobDeclaration>();
			declaration.JE_JS = shipment.PK;
			declaration.US_SchDEntry = "8659";
			var header = Factory.New<CusInBondHeader>();

		public void Test5GT()
		{
			Env.OutgoingCustomsMailManager.EmailsCreated.Clear();
			var entry = CreateEntryWithOutgoingMessageForImport();
			var incomingMessage = CreateMessageForTest("GOVCBR5GT_0.xml");
			SampleCodeType();
			Factory.Save();

			Assert("PreCondition: No entry is linked", incomingMessage.EM_LinkUniqueID.IsEmpty);

			new KRCIncomingMessageProcessor(new BatchProcessor.LoggingInformation()).ExecuteBatch();
			entry.Reload();
			incomingMessage.Reload();

			AssertEquals("entry is located", entry.PK, incomingMessage.EM_LinkUniqueID);

			AssertContains("수입신고서", incomingMessage.EM_MessageInterpretation);
			AssertContains("12345-20-000045M", incomingMessage.EM_MessageInterpretation);
			AssertContains("2014-05-06", incomingMessage.EM_MessageInterpretation);
			AssertContains("042-8082-8195", incomingMessage.EM_MessageInterpretation);
			AssertContains("[01020] 서울세관 내륙기지통관과", incomingMessage.EM_MessageInterpretation);
			AssertContains("김남순", incomingMessage.EM_MessageInterpretation);
			AssertContains("051-10-정정-13-00001", incomingMessage.EM_MessageInterpretation);
			AssertContains("042-8082-8195", incomingMessage.EM_MessageInterpretation);

			AssertEquals(1, Env.OutgoingCustomsMailManager.EmailsCreated.Count);
			var email = Env.OutgoingCustomsMailManager.EmailsCreated[0];
			var recipient = email.Recipients[0];
			AssertEquals("OriginalSender@wisetechglobal.com", recipient.Email);
			AssertContains("수입신고서", email.Body);
			AssertContains("12345-20-000045M", email.Body);
			AssertContains("2014-05-06", email.Body);
			AssertContains("042-8082-8195", email.Body);
			AssertContains("[01020] 서울세관 내륙기지통관과", email.Body);
			AssertContains("김남순", email.Body);
			AssertContains("051-10-정정-13-00001", email.Body);
			AssertContains("042-8082-8195", email.Body);
		}

		public void TestWrongStructure()
		{
			Env.OutgoingCustomsMailManager.EmailsCreated.Clear();
			var entry = CreateEntryWithOutgoingMessageForImport();
			var incomingMessage = CreateMessageForTest("GOVCBR5GT_WrongDeclarationOfficeID.xml");
			SampleCodeType();
			Factory.Save();

			Assert("PreCondition: No entry is linked", incomingMessage.EM_LinkUniqueID.IsEmpty);
			Assert("PreCondition: Entry Status is Empty", entry.CH_EntryStatus.IsEmpty);

			AssertNoExceptionThrown(() => new KRCIncomingMessageProcessor(new BatchProcessor.LoggingInformation()).ExecuteBatch());
			entry.Reload();
			incomingMessage.Reload();

			AssertEquals("entry is located", entry.PK, incomingMessage.EM_LinkUniqueID);

			AssertContains("수입신고서", incomingMessage.EM_MessageInterpretation);
			AssertNotContains("[010] 서울세관", incomingMessage.EM_MessageInterpretation);
			AssertNotContains("[20] 내륙기지통관과", incomingMessage.EM_MessageInterpretation);

			AssertEquals(1, Env.OutgoingCustomsMailManager.EmailsCreated.Count);
			var email = Env.OutgoingCustomsMailManager.EmailsCreated[0];

			AssertNotContains("[010] 서울세관", email.Body);
			AssertNotContains("[20] 내륙기지통관과", email.Body);
		}


	public void TestValidateAll_NZ50023() => CombineAssertions(() =>
	{
		const string jobReference1 = "1234567";
		const string jobReference2 = "7654321";
		const string jobReference3 = "3333333";
		const string existingMRN1 = "23IT123456789012J1";
		const string existingMRN2 = "23IT123456789112J9";

		CreateMovementReferenceNumber(null, jobReference1, existingMRN1);
		CreateMovementReferenceNumber(null, jobReference2, existingMRN2);
		Factory.Save();

		var mrn = CreateMovementReferenceNumber(NctsHeader, jobReference3, existingMRN1);
		ArrivalMovementHeader.Validation.ValidateAll();
		AssertHasRowErrorContaining(mrn, jobReference1);

		mrn.CSI_ReferenceNumber = existingMRN2;
		ArrivalMovementHeader.Validation.ValidateAll();
		AssertHasRowErrorContaining(mrn, jobReference2);

		mrn.CSI_ReferenceNumber = "23CH063456789012N8";
		ArrivalMovementHeader.Validation.ValidateAll();
		AssertNoRowErrorContaining(mrn, jobReference1);

		Factory.Save();
		ArrivalMovementHeader.Validation.ValidateAll();
		AssertNoRowErrorContaining(mrn, jobReference3);

		MovementReferenceNumberSupportingInfo CreateMovementReferenceNumber(NctsHeader header, string referenceNumber, string mrnNumber)
		{
			var arrival = (header == null ? CreateNctsHeader() : NctsHeader).ArrivalMovementHeader;
			arrival.Header.BH_JobReference = referenceNumber;
			var newMRN = arrival.MovementReferenceNumbers.AddNew();
			newMRN.CSI_ReferenceNumber = mrnNumber;
			return newMRN;
		}
	});

	public void TestCheckBM_PaperlessInbondNum() => CombineAssertions(() =>
	{
		const string errorMessage = "Destination Trader must have a Business Partner ID (BID) in order to generate the Customer Reference.";

		var destinationTraderOrg = Factory.New<OrgHeader>();
		NctsHeader.DestinationTrader.OrganisationPK = destinationTraderOrg.PK;

		using (EU.Registry.EUCustomsDataRegistry.Instance.NctsIsManualArrivalCustomerReferenceEnabled.SetTemporaryValue(GlbCompany.CurrentCompany.PK.ToGuid(), Guid.Empty, Guid.Empty, true))
		{
			ArrivalMovementHeader.Validation.ValidateBM_PaperlessInbondNum();
			AssertNoMessageError("Arrival Customer Reference is not auto generated", ArrivalMovementHeader.BM_PaperlessInbondNumInfo, errorMessage);
		}

		using (EU.Registry.EUCustomsDataRegistry.Instance.NctsIsManualArrivalCustomerReferenceEnabled.SetTemporaryValue(GlbCompany.CurrentCompany.PK.ToGuid(), Guid.Empty, Guid.Empty, false))
		{
			ArrivalMovementHeader.Validation.ValidateBM_PaperlessInbondNum();
			AssertHasMessageError("Destination Trader does not have a Business Partner ID (BID)", ArrivalMovementHeader.BM_PaperlessInbondNumInfo, errorMessage);

			ArrivalMovementHeader.BM_PaperlessInbondNum = "123";
			AssertNoMessageError("Arrival Customer Reference has been generated", ArrivalMovementHeader.BM_PaperlessInbondNumInfo, errorMessage);

			ArrivalMovementHeader.BM_PaperlessInbondNum = ZString.Empty;
			destinationTraderOrg.CustomsCodes.AddNew(OrgCusCode.SwissCodeTypes.BID, "BID123");
			ArrivalMovementHeader.Validation.ValidateBM_PaperlessInbondNum();
			AssertNoMessageError("Destination Trader has a Business Partner ID (BID)", ArrivalMovementHeader.BM_PaperlessInbondNumInfo, errorMessage);
		}
	});

	public void TestCheckBM_PaperlessInbondNum_AutoGeneratedCustomerReference()
	{
		var messageError = "No entry is found in the Registry for Customer Reference customization. Please check ‘NCTS Arrival Customer Reference Customization’ Registry Item.";
		var secondNctsHeader = Factory.New<NctsHeader>();
		secondNctsHeader.SetMovementType(NctsMovementType.Codes.Arrival);
		var destinationTraderOrg = Factory.New<OrgHeader>();
		destinationTraderOrg.OH_Code = "1234";
		GlbCompany.GetCurrentCompany(Factory).GC_OH_OrgProxy = destinationTraderOrg.PK;
		destinationTraderOrg.CustomsCodes.UpdateOrAddCustomsCodesIfNoneExists(OrgCusCode.SwissCodeTypes.BID, "2233445566", "CH");
		NctsHeader.DestinationTrader.OrganisationPK = destinationTraderOrg.PK;
		secondNctsHeader.DestinationTrader.OrganisationPK = destinationTraderOrg.PK;

		CusAuthorisationHeaderTestHelper.CreateAuthorisationHeader(Factory, CH.Business.CusAuthorizationHeaderTypeList.Codes.AuthorizedLocationCodeForPassar, destinationTraderOrg.PK, "001");
		CusAuthorisationHeaderTestHelper.CreateAuthorisationHeader(Factory, CH.Business.CusAuthorizationHeaderTypeList.Codes.AuthorizedLocationCodeForPassar, destinationTraderOrg.PK, "002");

		var fallbackLevel = new FallbackLevel(GlbCompany.CurrentCompany, null, null);
		var referenceFormat = new ArrivalCustomerReferenceFormat();
		var customFormat = new CustomArrivalCustomerReferenceFormat(fallbackLevel, Factory);
		customFormat.AuthorizationLocationCode = "002";
		customFormat.Prefix = "AB";
		customFormat.Suffix = "CD";
		customFormat.YearOption = CustomArrivalCustomerReferenceFormatYearOptionList.Codes.Prefix4;
		customFormat.SequenceNumberLength = 8;
		customFormat.IsRemoveLeadingZeros = true;
		referenceFormat.CustomFormats.Add(customFormat);
		referenceFormat.UseSystemDefinedFormat = false;

		CombineAssertions(() =>
		{
			using (EU.Registry.EUCustomsDataRegistry.Instance.NctsIsManualArrivalCustomerReferenceEnabled.SetTemporaryValue(GlbCompany.CurrentCompany.PK.ToGuid(), Guid.Empty, Guid.Empty, false))
			{
				using (CHCustomsDataRegistry.Instance.ArrivalCustomerReferenceFormat.SetTemporaryValue(GlbCompany.CurrentCompany.PK.ToGuid(), Guid.Empty, Guid.Empty, referenceFormat))
				{
					ArrivalMovementHeader.GoodsLocation.Address.AuthorisationNumber = "001";
					secondNctsHeader.ArrivalMovementHeader.GoodsLocation.Address.AuthorisationNumber = "002";
					Factory.Save();

					AssertHasMessageError("The selected Authorization No. has no entry on the Arrival Customer Format Registry. The message error should appear.", NctsHeader.ArrivalMovementHeader.BM_PaperlessInbondNumInfo, messageError);
					AssertNoMessageError("The selected Authorization No. has an entry on the Arrival Customer Format Registry. No message error should appear.", secondNctsHeader.ArrivalMovementHeader.BM_PaperlessInbondNumInfo, messageError);
				}
			}
		});
	}


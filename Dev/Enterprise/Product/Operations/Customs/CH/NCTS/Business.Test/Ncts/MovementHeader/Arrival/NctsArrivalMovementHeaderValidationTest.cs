	public void TestCheckBM_UnloadingDateFutureDate() => CombineAssertions(() =>
	{
		var messageError = "[NP70025] The unloading date can’t be in the future.";

		ArrivalMovementHeader.BM_UnloadingDate = ZDateTimeOffset.Empty;
		AssertNoMessageErrorContaining("BM_UnloadingDate is empty", ArrivalMovementHeader.BM_UnloadingDateInfo, messageError);

		ArrivalMovementHeader.BM_UnloadingDate = ZDateTimeOffset.Today.AddDays(-1);
		AssertNoMessageErrorContaining("BM_UnloadingDate lies behind the current date", ArrivalMovementHeader.BM_UnloadingDateInfo, messageError);

		ArrivalMovementHeader.BM_UnloadingDate = ZDateTimeOffset.Today;
		AssertNoMessageErrorContaining("BM_UnloadingDate is equal to the current date", ArrivalMovementHeader.BM_UnloadingDateInfo, messageError);

		ArrivalMovementHeader.BM_UnloadingDate = ZDateTimeOffset.Today.AddDays(1);
		AssertHasMessageErrorContaining("BM_UnloadingDate lies in the future compared to the current date", ArrivalMovementHeader.BM_UnloadingDateInfo, messageError);
	});


			if (sourceAddress?.LocalAddress is TWJobDocAddress localAddress)
			{
				destinationAddress.LocalAddress?.CopyPersistentValuesFrom(localAddress, cloneArgs);
				destinationAddress.IDCode = sourceAddress.IDCode;
			}
		}


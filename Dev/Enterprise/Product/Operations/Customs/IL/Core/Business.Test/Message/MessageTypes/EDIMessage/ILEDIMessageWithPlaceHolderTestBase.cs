using CargoWise.EntityFramework;
using CargoWise.IO;
using CargoWise.Types;
using Enterprise.Freight.Forwarding.Business;
using Enterprise.MasterFiles.Business;
using Enterprise.Messaging.Integration;

namespace Enterprise.Customs.IL.Business.Testing
{
	abstract class ILEDIMessageWithPlaceHolderTestBase<T> : ILEDIRequestMessageTestBase<T>
		where T : ILEDIRequestMessage
	{
		public void TestFillInPlaceHolders()
		{
			var factory = Factory;
			var currentCompanyPk = GlbCompany.CurrentCompany.PK;

			var shipmentWithoutReference = GetNewEmptyElectronicMessageProvider();
			shipmentWithoutReference.MessageReferenceNumber = ZString.Empty;
			var emptyShipmentMessage = CreateAndSaveILMessage(factory, (ForwardingShipment)shipmentWithoutReference.BusinessObject, GetExampleRequestMessage());

			var newFactory = new BusinessObjectFactory();
			emptyShipmentMessage = newFactory.Load<T>(emptyShipmentMessage.PK);
			CombineAssertions("shipment with empty reference", () =>
			{
				AssertContains("reference Generated by NumberFountains", "10000000", shipmentWithoutReference.MessageReferenceNumber);
				AssertContains("Message Text Contains the new reference", $"<{GetReferenceTag()}>10000000</{GetReferenceTag()}>", emptyShipmentMessage.EM_MessageText);
			});

			using (GlbCompany.TemporaryLoginInNewCompanyForCountry(Core.Constants.CountryCodes.Israel))
			{
				var shipmentInNewCompany = GetNewEmptyElectronicMessageProvider();
				shipmentInNewCompany.MessageReferenceNumber = ZString.Empty;
				var anotherCompanyMessage = CreateAndSaveILMessage(factory, (ForwardingShipment)shipmentInNewCompany.BusinessObject, GetExampleRequestMessage());

				newFactory = new BusinessObjectFactory();
				anotherCompanyMessage = newFactory.Load<T>(anotherCompanyMessage.PK);
				CombineAssertions("shipment with empty reference In new company", () =>
				{
					AssertNotEquals("Pre-Condition", currentCompanyPk, GlbCompany.CurrentCompany.PK);
					AssertContains("reference Generated by NumberFountains", "10000001", shipmentInNewCompany.MessageReferenceNumber);
					AssertContains("Message Text Contains the new reference", $"<{GetReferenceTag()}>10000001</{GetReferenceTag()}>", anotherCompanyMessage.EM_MessageText);
				});
			}

			var shipmentWithGMN = GetNewEmptyElectronicMessageProvider();
			shipmentWithGMN.MessageReferenceNumber = "10000123";
			factory.Save();

			var messageWithGMN = CreateAndSaveILMessage(factory, (ForwardingShipment)shipmentWithGMN.BusinessObject, GetExampleRequestMessage());

			emptyShipmentMessage = newFactory.Load<T>(messageWithGMN.PK);
			CombineAssertions("shipment reference not empty", () =>
			{
				AssertContains("reference not changed", "10000123", shipmentWithGMN.MessageReferenceNumber);
				AssertContains("Message Text Contains the old reference", $"<{GetReferenceTag()}>10000123</{GetReferenceTag()}>", emptyShipmentMessage.EM_MessageText);
			});
		}

		T CreateAndSaveILMessage(BusinessObjectFactory factory, ForwardingShipment shipment, string resourcePath)
		{
			var message = shipment.Factory.New<T>();
			message.EM_MessageSubType = GetRequestMessageSubType();
			message.EM_Status = EDIMessageStatusList.Codes.Queued;
			message.EM_ReceiveTransmit = ILEDIInterchange.Direction.Transmit;
			message.EM_LinkedObject = shipment;
			message.EM_MessageText = new EmbeddedResourceRetriever().GetString(ILBusinessTestHelper.GetEmbeddedResourcePath(resourcePath));
			factory.Save();
			return message;
		}

		abstract protected string GetExampleRequestMessage();

		abstract protected string GetReferenceTag();

		abstract protected IILElectronicMessageProvider GetNewEmptyElectronicMessageProvider();

		abstract protected string GetRequestMessageSubType();
	}
}

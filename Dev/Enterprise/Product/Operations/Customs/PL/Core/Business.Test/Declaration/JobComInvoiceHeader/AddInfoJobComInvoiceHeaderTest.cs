using System.Reflection;
using CargoWise.EntityFramework;
using CargoWise.EntityFramework.Testing;
using CargoWise.Types;
using Enterprise.Customs.Business;
using Enterprise.Customs.EU.Business;
using Enterprise.Customs.EU.Business.Testing;
using NUnit.Framework;
using Resources;

namespace Enterprise.Customs.PL.Business.Declaration.Testing;

[TestedType(typeof(AddInfoJobComInvoiceHeader))]
sealed class AddInfoJobComInvoiceHeaderTest : NonPersistentBusinessObjectTestCase
{
	public void TestAddInfo_IsConnectedToAutoClass()
	{
		AssertEquals(true, typeof(JobComInvoiceHeader).IsSubclassOf(typeof(AutoJobComInvoiceHeader)));
	}

	public void TestAddInfo_IsAutoGenerated()
	{
		AssertNotNull(typeof(AutoJobComInvoiceHeader).GetCustomAttribute<AutoGeneratedSourceCodeAttribute>());
	}

	public void TestAddInfo_HasUseAddInfoPropertyDescriptorsTrue()
	{
		AssertNotNull(typeof(AutoJobComInvoiceHeader).GetCustomAttribute<PropertyDescriptorCollectionAttribute>());
	}

	public void TestAddInfoType()
	{
		AssertEquals(typeof(AddInfoJobComInvoiceHeader), JobComInvoiceHeader.AddInfoType);
	}

	public void TestZG_TransportChargesMethodOfPayment_MaxLength()
	{
		AssertEquals(1, Factory.New<JobComInvoiceHeader>().AddInfo.ZG_TransportChargesMethodOfPaymentInfo.MaxLength);
	}

	public void TestGetNewValidation()
	{
		var declaration = Factory.New<JobDeclaration>();
		var header = declaration.Invoices.AddNew();
		CombineAssertions(() =>
		{
			declaration.JE_MessageType = JobMessageTypeList.Codes.Import;
			AssertType<ImportAddInfoJobComInvoiceHeaderValidation>("IMP", header.AddInfo.Validation);

			declaration.JE_MessageType = JobMessageTypeList.Codes.Export;
			AssertType<ExportAddInfoJobComInvoiceHeaderValidation>("EXP", header.AddInfo.Validation);

			declaration.JE_MessageType = JobMessageTypeList.Codes.MiscellaneousCustoms;
			AssertType<AddInfoJobComInvoiceHeaderValidation>("Other", header.AddInfo.Validation);
		});
	}

	public void TestShouldClearJZ_IncoTermPlace_Import()
	{
		CombineAssertions(() =>
		{
			var declaration = Factory.New<JobDeclaration>();
			declaration.JE_MessageType = JobMessageTypeList.Codes.Import;
			var invoice = declaration.Invoices.AddNew();
			invoice.JZ_IncoTermPlace = "abc";
			invoice.ZG_AgreedPlaceCode = Core.Constants.CountryCodes.Belgium;
			AssertEquals("AgreedPlaceCode is country", "abc", invoice.JZ_IncoTermPlace);

			invoice.ZG_AgreedPlaceCode = "BEAAA";
			AssertEquals("Invalid Unloco Code", "abc", invoice.JZ_IncoTermPlace);

			using (ConfigurationTestHelper.TemporarilyClearDeclarationConfigurationAndThenSetInvoiceHeaderConfiguration(declaration, true))
			{
				invoice.JZ_IncoTermPlace = "abc";
				invoice.ZG_AgreedPlaceCode = "BEBRU";
				AssertEquals("AgreedPlaceCode enabled - Valid Unloco Code", "abc", invoice.JZ_IncoTermPlace);
			}

			using (ConfigurationTestHelper.TemporarilyClearDeclarationConfigurationAndThenSetInvoiceHeaderConfiguration(declaration, false))
			{
				invoice.JZ_IncoTermPlace = "abc";
				invoice.ZG_AgreedPlaceCode = "BEBRU";
				AssertEquals("AgreedPlaceCode disabled - Valid Unloco Code", "abc", invoice.JZ_IncoTermPlace);
			}
		});
	}

	public void TestShouldClearJZ_IncoTermPlace_Export()
	{
		CombineAssertions(() =>
		{
			var declaration = Factory.New<JobDeclaration>();
			declaration.JE_MessageType = JobMessageTypeList.Codes.Export;
			var invoice = declaration.Invoices.AddNew();
			invoice.JZ_IncoTermPlace = "abc";
			invoice.ZG_AgreedPlaceCode = Core.Constants.CountryCodes.Belgium;
			AssertEquals("AgreedPlaceCode is country", "abc", invoice.JZ_IncoTermPlace);

			invoice.ZG_AgreedPlaceCode = "BEAAA";
			AssertEquals("Invalid Unloco Code", "abc", invoice.JZ_IncoTermPlace);

			using (ConfigurationTestHelper.TemporarilyClearDeclarationConfigurationAndThenSetInvoiceHeaderConfiguration(declaration, true))
			{
				invoice.JZ_IncoTermPlace = "abc";
				invoice.ZG_AgreedPlaceCode = "BEBRU";
				AssertEquals("Import AgreedPlaceCode enabled - Valid Unloco Code", ZString.Empty, invoice.JZ_IncoTermPlace);
			}

			using (ConfigurationTestHelper.TemporarilyClearDeclarationConfigurationAndThenSetInvoiceHeaderConfiguration(declaration, false))
			{
				invoice.JZ_IncoTermPlace = "abc";
				invoice.ZG_AgreedPlaceCode = "BEBRU";
				AssertEquals("AgreedPlaceCode disabled - Valid Unloco Code", "abc", invoice.JZ_IncoTermPlace);
			}
		});
	}

	protected override BusinessObject GetNewBusinessObject()
	{
		var declaration = Factory.New<JobDeclaration>();
		declaration.JE_MessageType = MessageTypeList.Codes.Import;
		var invoiceHeader = declaration.Invoices.AddNew();
		return new AddInfoJobComInvoiceHeader(invoiceHeader.JZ_AddInfoInfo);
	}
}

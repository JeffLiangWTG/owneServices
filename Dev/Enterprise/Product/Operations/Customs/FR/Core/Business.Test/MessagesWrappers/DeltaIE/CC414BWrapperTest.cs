using System.Linq;
using CargoWise.Types;
using Enterprise.Customs.FR.Business.Declaration;
using Enterprise.Customs.FR.Business.MessageSending;
using Enterprise.MasterFiles.Business;
using NUnit.Framework;

namespace Enterprise.Customs.FR.Business.MessagesWrappers.DeltaIE.Testing
{
	sealed class CC414BWrapperTest : Customs.Business.Testing.DataProviderTestCase<CC414BWrapper>
	{
		public void TestDeclarant()
		{
			var declarant = Provider.Declarant;
			CombineAssertions("CC414BWrapper.Declarant", () =>
			{
				AssertType<DeclarantWrapper>("Declarant should be of type DeclarantWrapper.", declarant);
				AssertEquals("Declarant.IdentificationNumber should be captured from the EORI of declarant.", "FR20230510", declarant.IdentificationNumber);
				AssertNull("Declarant.Name should be null when EORI is set for declarant..", declarant.Name);
				AssertNull("Declarant.Address shoudle be null when EORI is set for declarant.", declarant.Address);
				AssertEquals("Name", declarant.ContactPerson.Name);
				AssertEquals("emailAddress", declarant.ContactPerson.EMailAddress);
				AssertEquals("staffPhone", declarant.ContactPerson.PhoneNumber);
			});
		}

		public void TestDeclarant_ShouldContainAddress_WhenNoEORI()
		{
			var alternativeProvider = GetAlternativeProvider_ThatDeclarantHasNoEORI();
			var declarant = alternativeProvider.Declarant;
			CombineAssertions("CC414BWrapper.Declarant without EORI", () =>
			{
				AssertEquals("Declarant.IdentificationNumber should be empty when no EORI exists for declarant.", string.Empty, declarant.IdentificationNumber);
				AssertEquals("Declarant.Name should be captured from the full name of declarant.", "Declarant Full Name", declarant.Name);
				OrganisationAddressWrapperTest.AssertOrganisationAddressWrapper(declarant.Address, Core.Constants.CountryCodes.France, "NanJing City", "JiangDong Middle Road, T6 Building", "23456");
			});

			CC414BWrapper GetAlternativeProvider_ThatDeclarantHasNoEORI()
			{
				var declaration = Factory.NewWithValidTestData<JobDeclaration>();
				var invoice = declaration.Invoices.AddNew();
				var invoiceLine = invoice.InvoiceLines.AddNew();

				var declarantOrg = CreateDeclarant();
				declarantOrg.CustomsCodes.RemoveAndDeleteAll();
				declaration.JE_OA_DeclarantAddress = declarantOrg.MainAddress.PK;

				var merger = new LineMerger(declaration);
				merger.DoMerge();
				var entryHeader = declaration.CustomsEntryHeaders[0];

				var messageObject = new DeltaIEJobDeclarationMessageSendingObject(entryHeader);

				return CC414BWrapper.New(messageObject);
			}
		}

		[TestDate(2023, 5, 13, 16, 13, 2)]
		public void TestImportOperation()
		{
			var importOperation = Provider.ImportOperation.First();
			CombineAssertions("CC414BWrapper.ImportOperation", () =>
			{
				AssertEquals("ImportOperation.LRN should be captured from entry header's CorrelationID.", "LRN #", importOperation.LRN);
				AssertEquals("ImportOperation.MRN should be captured from entry header's MovementReferenceNumber.", "MRN #", importOperation.MRN);
				AssertEquals("ImportOperation.Customs Registration Number should be captured from entry header's DeclarationReference.", "CRN #", importOperation.CustomsRegistrationNumber);
				AssertEquals("ImportOperation.InvalidationMotivation should be captured from ChangeAcknowledgementIndicator of message object.", "XXX", importOperation.InvalidationMotivation);
				AssertEquals("ImportOperation.InvalidationReason should be captured from VOCReason of message object.", "VOR Reason", importOperation.InvalidationReason);
				AssertEquals("ImportOperation.InvalidationReason should be generated by ZDateTime.Now.", "2023-05-13T16:13:02", importOperation.InvalidationRequestDateAndTime);
				var documents = importOperation.SupportingDocument.ToList();
				AssertEquals("Supporting Document Count", 3, documents.Count);
				SupportingDocumentWrapperTest.AssertSupportingDocumentWrapper(documents[0], type: "AAA", referenceNumber: "1111");
				SupportingDocumentWrapperTest.AssertSupportingDocumentWrapper(documents[1], type: "BBB", referenceNumber: "2222");
				SupportingDocumentWrapperTest.AssertSupportingDocumentWrapper(documents[2], type: "CCC", referenceNumber: "3333");
			});
		}

		public void TestRepresentative()
		{
			var representative = Provider.Representative;
			CombineAssertions("CC414BWrapper.Representative", () =>
			{
				AssertType<RepresentativeWrapper>("Representative should be of type RepresentativeWrapper.", representative);
				AssertEquals("Representative.Status should be captured from RepresentationTypeNo of the declaration.", "3", representative.Status);
				AssertEquals("IdentificationNumber should equal representative EORI number.", "FR98765432", representative.IdentificationNumber);
				AssertEquals("Name", representative.ContactPerson.Name);
				AssertEquals("staffPhone", representative.ContactPerson.PhoneNumber);
				AssertEquals("emailAddress", representative.ContactPerson.EMailAddress);
			});
		}

		[TestDate(2024, 03, 18, 12, 30, 00)]
		public void TestRequest()
		{
			var request = Provider.Request;
			var importOperation = Provider.ImportOperation.First();
			AssertEquals("OperatorRequestReference should be equal to LRN - YYYYMMDDHHMMSS", importOperation.LRN + "-" + ZDateTime.UtcNow.ToString("yyyyMMddhhmmss"), request.OperatorRequestReference);
			AssertEquals("AmendmentRequestDateAndTime should be equal to sendingObject Date.", new ZDateTime(2024, 03, 18, 12, 30, 00).ToString("yyyy-MM-ddTHH:mm:ss"), Provider.Request.AmendmentRequestDateAndTime);
			AssertEquals("AmendmentReason should be equal to sendingObject VOCReason.", "VOR Reason", Provider.Request.AmendmentReason);
		}

		public void TestDeclarant_ForOperational()
		{
			var provider = GetWrapper(true);
			SetupGlobalBranch();
			var declarant = provider.Declarant;
			CombineAssertions("CC414BCurrentUserWrapper.Declarant", () =>
			{
				AssertType<DeclarantWrapper>("Declarant should be of type DeclarantWrapper.", declarant);
				AssertEquals("Declarant.IdentificationNumber should be captured from the EORI of declarant.", "FRABC", declarant.IdentificationNumber);
				AssertNull("Declarant.Name should be null when EORI is set for declarant..", declarant.Name);
				AssertNull("Declarant.Address shoudle be null when EORI is set for declarant.", declarant.Address);
				AssertNull("Declarant.ContactPerson has not been mapped yet.", declarant.ContactPerson); // TODO
			});
		}

		public void TestDeclarant_ShouldContainAddress_WhenNoEORI_ForOperational()
		{
			var provider = GetWrapper(true);
			SetupGlobalBranch();
			GlbBranch.CurrentBranch.OrgProxy.CustomsCodes.RemoveAndDeleteAll();
			var declarant = provider.Declarant;
			CombineAssertions("CC414BCurrentUserWrapper.Declarant without EORI", () =>
			{
				AssertEquals("Declarant.IdentificationNumber should be empty when no EORI exists for declarant.", string.Empty, declarant.IdentificationNumber);
				AssertEquals("Declarant.Name should be captured from the full name of declarant.", "Declarant Global Branch Name", declarant.Name);
				OrganisationAddressWrapperTest.AssertOrganisationAddressWrapper(declarant.Address, Core.Constants.CountryCodes.France, "Global City", "Global Road, Global Building", "56789");
			});
		}

		protected override CC414BWrapper GetProvider()
		{
			return GetWrapper(false);
		}

		CC414BWrapper GetWrapper(bool isForOperational)
		{
			var declaration = Factory.NewWithValidTestData<JobDeclaration>();
			declaration.JE_DeclarantType = RepresentationTypeList.Codes.IND;
			declaration.JE_ApplicationCode = DeclarationApplicationCodeList.Codes.DeltaIE;
			var decSupportingDoc1 = declaration.SupportingDocuments.AddNew();
			decSupportingDoc1.CSI_Code = "AAA";
			decSupportingDoc1.CSI_ReferenceNumber = "1111";
			var invoice = declaration.Invoices.AddNew();
			var invoiceSupportingDoc = invoice.SupportingDocuments.AddNew();
			invoiceSupportingDoc.CSI_Code = "BBB";
			invoiceSupportingDoc.CSI_ReferenceNumber = "2222";
			var invoiceLine = invoice.InvoiceLines.AddNew();
			var lineSupportingDoc = invoiceLine.SupportingDocuments.AddNew();
			lineSupportingDoc.CSI_Code = "CCC";
			lineSupportingDoc.CSI_ReferenceNumber = "3333";

			var representative = Factory.NewWithValidTestData<OrgHeader>();
			representative.CustomsCodes.RemoveAndDeleteAll();
			representative.CustomsCodes.AddNew(OrgCusCode.EuropeanUnionSharedCodeTypes.Eori, "98765432", Core.Constants.CountryCodes.France);
			declaration.JE_OA_Representative = representative.MainAddress.PK;

			var declarant = CreateDeclarant();
			declaration.JE_OA_DeclarantAddress = declarant.MainAddress.PK;

			var merger = new LineMerger(declaration);
			merger.DoMerge();
			var entryHeader = declaration.CustomsEntryHeaders[0];
			entryHeader.CorrelationID = "LRN #";
			entryHeader.MRN = "MRN #";
			entryHeader.CRN = "CRN #";
			entryHeader.CH_EntrySubmittedDate = new ZDateTime(2020, 01, 01, 12, 30, 00);

			var staff = Factory.New<GlbStaff>();
			staff.GS_Code = "CUS";
			staff.GS_FullName = "Name";
			staff.GS_WorkPhone = "staffPhone";
			var email = staff.EmailAddresses.AddNew();
			email.GSE_EmailAddress = "emailAddress";
			email.GSE_Type = Core.Constants.EmailFromAddressTypes.Codes.Main;

			Factory.Save();

			declaration.JE_GS_NKCusAgent = "CUS";

			var messageObject = new DeltaIEJobDeclarationMessageSendingObject(entryHeader);
			messageObject.ChangeAcknowledgementIndicator = "XXX";
			messageObject.VOCReason = "VOR Reason";
			return CC414BWrapper.New(messageObject, isForOperational);
		}

		OrgHeader CreateDeclarant()
		{
			var declarant = Factory.NewWithValidTestData<OrgHeader>();
			declarant.OH_FullName = "Declarant Full Name";
			declarant.CustomsCodes.RemoveAndDeleteAll();
			declarant.CustomsCodes.AddNew(OrgCusCode.EuropeanUnionSharedCodeTypes.Eori, "20230510", Core.Constants.CountryCodes.France);
			declarant.MainAddress.OA_Address1 = "JiangDong Middle Road";
			declarant.MainAddress.OA_Address2 = "T6 Building";
			declarant.MainAddress.OA_PostCode = "23456";
			declarant.MainAddress.OA_City = "NanJing City";
			declarant.MainAddress.OA_RN_NKCountryCode = Core.Constants.CountryCodes.France;

			return declarant;
		}

		void SetupGlobalBranch()
		{
			GlbBranch.CurrentBranch.OrgProxy.OH_FullName = "Declarant Global Branch Name";
			GlbBranch.CurrentBranch.OrgProxy.CustomsCodes.UpdateOrAddCustomsCodesIfNoneExists(OrgCusCode.EuropeanUnionSharedCodeTypes.Eori, "ABC", Core.Constants.CountryCodes.France);
			GlbBranch.CurrentBranch.OrgProxy.MainAddress.OA_Address1 = "Global Road";
			GlbBranch.CurrentBranch.OrgProxy.MainAddress.OA_Address2 = "Global Building";
			GlbBranch.CurrentBranch.OrgProxy.MainAddress.OA_PostCode = "56789";
			GlbBranch.CurrentBranch.OrgProxy.MainAddress.OA_City = "Global City";
			GlbBranch.CurrentBranch.OrgProxy.MainAddress.OA_RN_NKCountryCode = Core.Constants.CountryCodes.France;
		}
	}

		new NCTSFREDIMessage GetNCTSFREDIMessage(NctsHeader nctsHeader)
		{
			var interchange = Factory.NewWithValidTestData<EDIInterchange>();
			interchange.EI_BodyText = resourceRetriever.Value.GetString("Enterprise.Customs.FR.Business.Testing.EDIMessage.TestFiles.NCTS_CC043CResponseMessageWithGoodsItem.xml");

			var message = Factory.New<NCTSFREDIMessage>();
			message.EM_EI = interchange.PK;
			message.EM_MessageSubType = GetMessageSubType();
			message.EM_ApplicationCode = EDIMessage.ApplicationCodes.FRCustomsMessage;
			message.EM_Status = EDIMessage.Status.Queued;
			message.EM_ReceiveTransmit = ReceiveTransmitList.Codes.Receive;
			message.EM_MessageText = interchange.EI_BodyText;
			message.EM_LinkedObject = nctsHeader;
			return message;
		}

		public void TestMappingFromXML()
		{
			var header = Factory.New<NctsHeader>();
			header.BH_ApplicationCode = CusInBondApplicationCodeList.Codes.NCTS5;
			header.SetMovementType(EU.NCTS.Business.NctsMovementType.Codes.Arrival);

			var message = GetNCTSFREDIMessage(header);
			var processor = GetNCTSBaseProcessor();
			processor.ProcessMessage(message);
			var movementHeader = header.ArrivalMovementHeader;
			AssertEquals("Number of transport means", 1, movementHeader.ArrivalTransportInfos.Count);
			AssertEquals("Identification number of the transport means", "AK123AK", movementHeader.ArrivalTransportInfos.First().TPM_IdentificationNumber);

			AssertEquals("Number of HouseConsigment", 2, header.Bills.Count);
			AssertEquals("Number of GoodsItem of the first House of Consignement", true, header.Bills.Any(x => x.ArrivalGoodsItems.Count == 3));
			AssertEquals("Number of GoodsItem of the second House of Consignement", true, header.Bills.Any(x => x.ArrivalGoodsItems.Count == 1));
		}


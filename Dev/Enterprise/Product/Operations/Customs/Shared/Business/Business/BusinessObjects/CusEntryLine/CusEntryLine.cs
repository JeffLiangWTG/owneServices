		public ZString GetInvoiceLinesReference()
		{
			StringBuilder resultBuilder = new StringBuilder();

			Hashtable invoicesInvoiceLines = new Hashtable();
			foreach (BaseJobComInvoiceLine invoiceLine in InvoiceLines)
			{
				if (!invoicesInvoiceLines.ContainsKey(invoiceLine.InvoiceHeader.JZ_InvoiceNumber))
				{
					invoicesInvoiceLines[invoiceLine.InvoiceHeader.JZ_InvoiceNumber] = new ArrayList();
				}
				((ArrayList)invoicesInvoiceLines[invoiceLine.InvoiceHeader.JZ_InvoiceNumber]).Add(invoiceLine.JI_LineNo);
			}
			ICollection keys = invoicesInvoiceLines.Keys;
			ArrayList keysArrayList = new ArrayList(keys);
			keysArrayList.Sort();
			foreach (ZString invoiceNumber in keysArrayList)
			{
				StringBuilder invoiceLines = new StringBuilder();
				((ArrayList)(invoicesInvoiceLines[invoiceNumber])).Sort();
				foreach (ZShort lineNum in (ArrayList)(invoicesInvoiceLines[invoiceNumber]))
				{
					invoiceLines.Append(lineNum + ", ");
				}
				if (invoiceLines.Length > 2)
				{
					invoiceLines.Remove(invoiceLines.Length - 2, 2);
				}

				resultBuilder.Append(Res.GetString("1964f3c6-8389-4ef6-83b4-fd4b3af16115", "invoice {0}(line {1}),", invoiceNumber, invoiceLines.ToString()) + " ");
			}
			if (resultBuilder.Length > 2)
			{
				resultBuilder.Remove(resultBuilder.Length - 2, 2);
			}

			return resultBuilder.ToString();
		}


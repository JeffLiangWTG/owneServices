		public void MergeInvoiceLine(BaseJobComInvoiceLine baseInvoiceLine)
		{
			CL_CustomsValue += GetInvoiceLineCustomsValueToAggregate(baseInvoiceLine);
			ClearCachedCustomsQuantities();
			DoMergeInvoiceLine(baseInvoiceLine);
		}


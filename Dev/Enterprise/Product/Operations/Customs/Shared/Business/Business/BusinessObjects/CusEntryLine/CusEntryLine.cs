		public override void Delete()
		{
			if (!IsDeleted)
			{
				FetchForLoadChildEditableObjectsIfNeeded();
				this.DeleteAllCusAddInfoCodeDataAndSupportingInfoChildrenIfSupported();
			}
			AdditionalInvoiceLineLinks.DeleteAll();
			foreach (BaseJobComInvoiceLine invoiceLine in InvoiceLines)
			{
				if (invoiceLine.JI_CL == PK)
				{
					invoiceLine.JI_CL = ZGuid.Empty;
				}
			}

			Fees.RemoveAndDeleteAll();
			ConfirmedFees.RemoveAndDeleteAll();
			base.Delete();
		}

		protected override void DeleteForDataRefresh()
		{
			AdditionalInvoiceLineLinks.DeleteAll();

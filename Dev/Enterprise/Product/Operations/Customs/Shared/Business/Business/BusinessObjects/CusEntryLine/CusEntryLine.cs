		{
			public Loader(BusinessObjectFactory factory)
				: base(factory)
			{
			}

			protected override Type GetTypeOfBusinessObjectToLoad()
			{
				return typeof(CusEntryLine);
			}

			/// <summary>
			/// Finds an entry line with match entry number and line number in the current company
			/// </summary>
			public CusEntryLine FindByDeclarationAndLineNumbers(ZString importDeclarationNumber, ZString importDeclarationType, ZInt importDeclarationLine, ZQuery query)
			{
				return FindByDeclarationAndLineNumbersCore(importDeclarationNumber, importDeclarationType, importDeclarationLine, query);
			}

			protected virtual CusEntryLine FindByDeclarationAndLineNumbersCore(ZString importDeclarationNumber, ZString importDeclarationType, ZInt importDeclarationLine, ZQuery query)
			{
				if (importDeclarationLine > short.MaxValue)
				{
					return null;
				}

				query.AddToFilter(CusEntryLineSchema.CL_CustomsPostedStatus, SQLComparisonOperator.Equal, Customs.Business.EntryLineStatusList.Codes.Active);
				query.AddToFilter(CusEntryLineSchema.CL_LineNumber, SQLComparisonOperator.Equal, (short)importDeclarationLine);
				ZDBOnlyQuery entryLineQuery = new ZDBOnlyQuery(typeof(CusEntryLine));
				ZDBOnlySubQuery entryHeaderQuery = new ZDBOnlySubQuery(typeof(CusEntryHeader), CusEntryLineSchema.CL_CH);
				ZDBOnlySubQuery cusEntryNumQuery = new ZDBOnlySubQuery(typeof(CusEntryNumber), CusEntryNumSchema.CE_ParentID);
				cusEntryNumQuery.AddToFilter(CusEntryNumSchema.CE_EntryNum, SQLComparisonOperator.Equal, importDeclarationNumber);
				cusEntryNumQuery.AddToFilter(JoinCondition.And, CusEntryNumSchema.CE_RN_NKCountryCode, SQLComparisonOperator.Equal, GlbCompany.CurrentCompany.GC_RN_NKCountryCode);
				if (!importDeclarationType.IsEmpty)
				{
					cusEntryNumQuery.AddToFilter(CusEntryNumSchema.CE_EntryType, importDeclarationType);
				}
				entryHeaderQuery.AddSubQuery(cusEntryNumQuery, JoinCondition.And);
				entryLineQuery.AddSubQuery(entryHeaderQuery, JoinCondition.And);
				query.AddToFilter(entryLineQuery);
				return Factory.LoadTop1<CusEntryLine>(query);
			}

			public CusEntryLine FindByDeclarationAndLineNumbers(ZString importDeclarationNumber, ZInt importDeclarationLine)
			{
				return FindByDeclarationAndLineNumbers(importDeclarationNumber, ZString.Empty, importDeclarationLine);
			}

			public CusEntryLine FindByDeclarationAndLineNumbers(ZString importDeclarationNumber, ZString importDeclarationType, ZInt importDeclarationLine)
			{
				return FindByDeclarationAndLineNumbers(importDeclarationNumber, importDeclarationType, importDeclarationLine, new ZQuery());
			}
		}

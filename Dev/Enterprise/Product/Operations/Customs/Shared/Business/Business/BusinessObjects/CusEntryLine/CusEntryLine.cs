		public void MarkDeletionPendingOrDelete(bool lineNumberBeingLessThanCH_HighestLineNumberMeansTheEntryLineIsLodged)
		{
			if (!IsDeleted)
			{
				if (lineNumberBeingLessThanCH_HighestLineNumberMeansTheEntryLineIsLodged &&
					CL_LineNumber > 0 && CL_LineNumber <= Header.CH_HighestLineNumber)//line number checks for being lodged
				{
					CL_CustomsPostedStatus = EntryLineStatusList.Codes.DeletePending;

					AdditionalInvoiceLineLinks.DeleteAll();
				}
				else if (AdditionalInvoiceLineLinks.Count == 0)
				{
					Delete();
				}
			}
		}


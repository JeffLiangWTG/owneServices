using System.Collections.Generic;
using System.Linq;
using CargoWise.EntityFramework;
using CargoWise.Types;
using Enterprise.Customs.DataTransfer.Universal;
using Enterprise.MasterFiles.Business;
using Enterprise.UniversalDataBuss.DataObjects.Core;
using Enterprise.UniversalDataBuss.DataObjects.Universal;
using Enterprise.UniversalDataBuss.Integration;
using Enterprise.ZArchitecture.Schema;

namespace Enterprise.Customs.AU.Declaration.Business
{
	class CusOutturnHeaderDataObjectReader : DataTransfer.Universal.Outturn.CusOutturnHeaderDataObjectReader<CusOutturnHeader, DepotCusOutturn>, IAUCusOutturnHeaderDataObjectReader
	{
		public CusOutturnHeaderDataObjectReader(Shipment dataObject, IXmlImportLogger logger, UniversalObjectFactory factory)
			: base(dataObject, logger, factory)
		{
		}

		protected override ZString GetReasonForNotAbleToUpdateFromDataSourceOrTargetBO(CusOutturnHeader outturnHeader)
		{
			var reason = new ZStringBuilder();
			reason.Append(base.GetReasonForNotAbleToUpdateFromDataSourceOrTargetBO(outturnHeader));

			if (!LloydsIMO.HasValue || LloydsIMO.Value.IsEmpty || !PremiseID.HasValue || PremiseID.Value.IsEmpty || !dataObject.VoyageFlightNo.HasValue || dataObject.VoyageFlightNo.Value.IsEmpty)
			{
				reason.Append(Res.GetString("37A3E443-0FC4-4F6C-8170-70D6740AD27E", "Vessel Lloyds and Voyage Number and Premise ID must not be empty."));
			}

			return reason.ToStringWithDelimiterBetweenAppends(" ");
		}

		#region Country Speical BO population
		protected override DepotCusOutturn FillSubShipmentCore(Shipment shipment, IXmlImportLogger logger, UniversalObjectFactory factory, CusOutturnHeader outturnHeader)
		{
			var reader = new DepotCusOutturnDataObjectReader(shipment, logger, factory, outturnHeader);
			return reader.ReadIntoBusinessObject();
		}

		protected override void FillVessel(IColumnIndexer headerRow, CusOutturnHeader outturnHeader)
		{
			//Should set C6_VesselName before C6_LloydsIMO to use defaulting value generated by C6_LloydsIMO setter when vessel in XML is empty
			using (outturnHeader.SetterSuspender.ResumeSetting(nameof(outturnHeader.C6_VesselName)))
			{
				SetValue(headerRow, CusOutturnHeaderSchema.C6_VesselName, dataObject.VesselName);
			}
			using (outturnHeader.SetterSuspender.ResumeSetting(nameof(outturnHeader.C6_LloydsIMO)))
			{
				SetValue(headerRow, CusOutturnHeaderSchema.C6_LloydsIMO, LloydsIMO);
			}
		}

		protected override void FillPremiseAddress(IColumnIndexer headerRow, CusOutturnHeader outturnHeader)
		{
			//Should set C6_OA_OutturningPremise before C6_OutturningPremiseID to use defaulting value generated by C6_OutturningPremiseID setter when Premise Address in XML is empty or unMatched
			using (outturnHeader.SetterSuspender.ResumeSetting(nameof(outturnHeader.C6_OA_OutturningPremise)))
			{
				SetValue(headerRow, CusOutturnHeaderSchema.C6_OA_OutturningPremise, MatchedPremiseAddressPK);
			}
			using (outturnHeader.SetterSuspender.ResumeSetting(nameof(outturnHeader.C6_OutturningPremiseID)))
			{
				SetValue(headerRow, CusOutturnHeaderSchema.C6_OutturningPremiseID, PremiseID);
			}
		}
		#endregion

		#region SuspendSetters
		protected override IEnumerable<ZString> GetOutturnHeaderPropertiesToSuspendSetting()
		{
			if (LloydsIMO.HasValue)
			{
				yield return CusOutturnHeader.Schema.C6_LloydsIMO;
			}
			if (dataObject.VesselName.HasValue)
			{
				yield return CusOutturnHeader.Schema.C6_VesselName;
			}
			if (PremiseID.HasValue)
			{
				yield return CusOutturnHeader.Schema.C6_OutturningPremiseID;
			}
			if (MatchedPremiseAddressPK.HasValue)
			{
				yield return CusOutturnHeader.Schema.C6_OA_OutturningPremise;
			}
		}
		#endregion

		#region Calculated value

		protected override ZString? CalculateLloydsCore()
		{
			var result = base.CalculateLloydsCore();
			if (!result.HasValue)
			{
				var vesselName = dataObject.VesselName.GetValueOrDefault();
				if (!vesselName.IsEmpty)
				{
					var loadedVessels = RefVessel.LookupVesselByName(vesselName, factory.BOFactory);
					if (loadedVessels != null && loadedVessels.Length > 0)
					{
						result = loadedVessels.OrderBy(x => x.RV_LloydsNumber).FirstOrDefault().RV_LloydsNumber;
					}
				}
			}
			return result;
		}

		protected override ZString? CalculatePremiseIDCore()
		{
			var result = base.CalculatePremiseIDCore();
			if (!result.HasValue && MatchedPremiseAddressPK.HasValue)
			{
				var outturningPremise = factory.Load<OrgAddress>(MatchedPremiseAddressPK.Value);
				result = outturningPremise?.LocalControlledPremisesID;
			}
			return result;
		}

		#endregion
	}
}

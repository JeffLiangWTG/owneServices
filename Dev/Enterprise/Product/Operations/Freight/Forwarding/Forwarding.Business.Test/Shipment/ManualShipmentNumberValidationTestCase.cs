using Enterprise.Environment;
using Enterprise.Freight.Business.Testing;

namespace Enterprise.Freight.Forwarding.Business.Testing
{
	sealed class ManualShipmentNumberValidationTestCase : BaseFreightTest
	{
		public void TestDontValidateUnchangedValues_Shipment()
		{
			Env.Registry.AllowManualShipmentEntry = true;

			ForwardingShipment shipment = Factory.New<ForwardingShipment>();
			shipment.JS_UniqueConsignRef = "S99999999";
			AssertHasError(shipment.JS_UniqueConsignRefInfo, "Numbers of the form A00000000 (a letter followed by 8 digits) are reserved for Auto-Generated numbers.");

			Factory.Save();
			shipment.Validation.ValidateJS_UniqueConsignRef();
			AssertNoNotifications(shipment.JS_UniqueConsignRefInfo);

			shipment.JS_UniqueConsignRef = "S99999990";
			AssertHasError(shipment.JS_UniqueConsignRefInfo, "Numbers of the form A00000000 (a letter followed by 8 digits) are reserved for Auto-Generated numbers.");

			shipment.JS_UniqueConsignRef = "S99999999";
			AssertNoNotifications(shipment.JS_UniqueConsignRefInfo);
		}

		public void TestDontValidateUnchangedValues_ShipmentNumberEntry()
		{
			Env.Registry.AllowManualShipmentEntry = true;

			ForwardingShipment shipment = Factory.New<ForwardingShipment>();
			shipment.JS_UniqueConsignRef = "S99999999";
			ShipmentNumberEntry entry = new ShipmentNumberEntry(shipment);

			entry.ValidateShipmentNumber();
			AssertHasError(entry.ShipmentNumberInfo, "Numbers of the form A00000000 (a letter followed by 8 digits) are reserved for Auto-Generated numbers.");

			Factory.Save();
			entry.ValidateShipmentNumber();
			AssertNoNotifications(entry.ShipmentNumberInfo);

			entry.ShipmentNumber = "S99999990";
			AssertHasError(entry.ShipmentNumberInfo, "Numbers of the form A00000000 (a letter followed by 8 digits) are reserved for Auto-Generated numbers.");

			entry.ShipmentNumber = "S99999999";
			AssertNoNotifications(entry.ShipmentNumberInfo);
		}

		public void TestLikeAutoGenerated()
		{
			Env.Registry.AllowManualShipmentEntry = true;

			ForwardingShipment shipment = Factory.New<ForwardingShipment>();
			shipment.JS_UniqueConsignRef = "43211-11004";
			AssertNoNotifications(shipment.JS_UniqueConsignRefInfo);

			shipment.JS_UniqueConsignRef = "S00001000";
			AssertHasError(shipment.JS_UniqueConsignRefInfo, "Numbers of the form A00000000 (a letter followed by 8 digits) are reserved for Auto-Generated numbers.");

			shipment.JS_UniqueConsignRef = "B00001000";
			AssertHasError(shipment.JS_UniqueConsignRefInfo, "Numbers of the form A00000000 (a letter followed by 8 digits) are reserved for Auto-Generated numbers.");

			shipment.JS_UniqueConsignRef = "Blah00000000";
			AssertNoNotifications(shipment.JS_UniqueConsignRefInfo);

			shipment.JS_UniqueConsignRef = "43211/11004";
			AssertHasError(shipment.JS_UniqueConsignRefInfo, @"A forward slash (""/"") is not valid in a shipment number.");
		}
	}
}

using Enterprise.Freight.Business.Testing;

namespace Enterprise.Freight.Forwarding.Business.Testing
{
	sealed class ShipmentNumberEntryTest : BaseFreightTest
	{
		#region TestAutoAcceptNextForTesting

		public void TestAutoAcceptNextForTesting()
		{
			ForwardingShipment shipment = Factory.New<ForwardingShipment>();
			ShipmentNumberEntry.AutoAcceptNextForTesting = true;
			ShipmentNumberEntry entry = new ShipmentNumberEntry(shipment);
			AssertEquals(true, entry.Accepted);
			AssertEquals(false, ShipmentNumberEntry.AutoAcceptNextForTesting);
		}

		#endregion

		#region TestAccept

		public void TestAccept()
		{
			ForwardingShipment shipment = Factory.New<ForwardingShipment>();

			shipment.JS_UniqueConsignRef = "Dodgy Arse";

			ShipmentNumberEntry entry = new ShipmentNumberEntry(shipment);

			AssertEquals("Not accepted yet", false, entry.Accepted);
			AssertEquals("shipment number should default from the shipment", "Dodgy Arse", entry.ShipmentNumber);

			entry.ShipmentNumber = "Blah";
			AssertEquals("Not accepted yet", false, entry.Accepted);
			AssertEquals("shipment number was set to blah", "Blah", entry.ShipmentNumber);
			AssertEquals("the shipment should remain unchanged", "Dodgy Arse", shipment.JS_UniqueConsignRef);

			entry.Accept();

			AssertEquals("Has now been accepted", true, entry.Accepted);
			AssertEquals("shipment number was set to blah", "Blah", entry.ShipmentNumber);
			AssertEquals("the shipment number should have been copyed to the shipment", "Blah", shipment.JS_UniqueConsignRef);
		}

		#endregion

		#region TestValidation

		public void TestValidation()
		{
			ForwardingShipment shipment = Factory.New<ForwardingShipment>();
			ShipmentNumberEntry entry = new ShipmentNumberEntry(shipment);

			entry.ShipmentNumber = "";
			AssertHasErrors("Empty string is not a valid shipment number", entry.ShipmentNumberInfo);

			entry.ShipmentNumber = "Blah";
			AssertNoNotifications(entry.ShipmentNumberInfo);

			entry.ShipmentNumber = "S00001000";
			AssertHasErrors("Setting to a value that looks like an autogenerated number", entry.ShipmentNumberInfo);

			entry.ShipmentNumber = "S0000100";
			AssertNoNotifications("Looks nothing like an autogenerated shipment number.", entry.ShipmentNumberInfo);

			entry.ShipmentNumber = "S000010000";
			AssertNoNotifications("Looks nothing like an autogenerated shipment number.", entry.ShipmentNumberInfo);

			entry.AllowBlankShipmentNumber();
			entry.ShipmentNumber = "";
			AssertNoErrors("Accept blank, Empty string", entry.ShipmentNumberInfo);
			AssertHasWarnings("Empty string -  treat as warning", entry.ShipmentNumberInfo);
		}

		#endregion
	}
}

using System.Text.RegularExpressions;
using CargoWise.ComponentModel;
using CargoWise.EntityFramework;
using CargoWise.Types;
using Enterprise.ZArchitecture.Schema;

namespace Enterprise.Freight.Forwarding.Business
{
	public class ManualShipmentNumberValidation
	{
		public void ValidateManualShipmentNumber(ForwardingShipment shipment, bool allowBlank)
		{
			ValidateManualShipmentNumber(shipment.JS_UniqueConsignRefInfo, PreviousShipmentNumber(shipment), allowBlank);

			ZString value = shipment.JS_UniqueConsignRef;

			if (!shipment.JS_UniqueConsignRefInfo.HasErrors() && !value.IsEmpty)
			{
				if (shipment.CurrentRootConsol != null)
				{
					foreach (ForwardingShipment otherShipment in shipment.CurrentRootConsol.Shipments)
					{
						if (otherShipment.PK != shipment.PK && otherShipment.JS_UniqueConsignRef == value)
						{
							shipment.JS_UniqueConsignRefInfo.AddError(Res.GetString("c3847af9-23c6-4e50-9f37-acae123f38cc", "Another Shipment with this number already exists on this consol. Please change the number."));
							break;
						}
					}
				}

				if (!shipment.JS_UniqueConsignRefInfo.HasErrors() && !IsUniqueShipmentNumber(value, shipment))
				{
					shipment.JS_UniqueConsignRefInfo.AddError(Res.GetString("db9c0bf7-fb56-4d8e-8e30-674f14857fe4", "Another Shipment with this number already exists. Please change the number."));
				}
			}
		}

		public void ValidateManualShipmentNumber(ShipmentNumberEntry shipmentEntry, bool allowBlank)
		{
			shipmentEntry.ShipmentNumberInfo.ClearAllNotifications();
			ValidateManualShipmentNumber(shipmentEntry.ShipmentNumberInfo, PreviousShipmentNumber(shipmentEntry.Shipment), allowBlank);

			ZString value = (ZString)shipmentEntry.ShipmentNumberInfo.Value;

			if (!shipmentEntry.ShipmentNumberInfo.HasErrors() && !value.IsEmpty)
			{
				if (((IBusinessObjectInternals)shipmentEntry).ParentCollections.Length > 0)
				{
					foreach (ShipmentNumberEntry otherEntry in ((IBusinessObjectInternals)shipmentEntry).ParentCollections[0])
					{
						if (otherEntry.PK != shipmentEntry.PK && otherEntry.ShipmentNumber == value)
						{
							shipmentEntry.ShipmentNumberInfo.AddError(Res.GetString("1d8d7e33-eb8f-47b9-b548-c96b7497b542", "Another Shipment with this number already exists on this consol. Please change the number."));
							break;
						}
					}
				}

				if (!shipmentEntry.ShipmentNumberInfo.HasErrors() && !IsUniqueShipmentNumber(value, shipmentEntry.Shipment))
				{
					shipmentEntry.ShipmentNumberInfo.AddError(Res.GetString("1e3582f7-6820-4fcc-8517-571d738b9212", "Another Shipment with this number already exists. Please change the number."));
				}
			}
		}

		ZString PreviousShipmentNumber(ForwardingShipment shipment)
		{
			return shipment.IsInDatabase ? (ZString)shipment.JS_UniqueConsignRefInfo.OriginalValue : ZString.Empty;
		}

		void ValidateManualShipmentNumber(ZPropertyInfo info, ZString previousValue, bool allowBlank)
		{
			ZString value = (ZString)info.Value;

			if (previousValue.IsEmpty || previousValue != value)
			{
				if (value.IsEmpty)
				{
					if (allowBlank)
					{
						info.AddWarning(Res.GetString("5eece369-1df8-44c4-9077-a022f7e5a5e1", "Blank Shipment Number - Will be Auto Generated if left blank"));
					}
					else
					{
						info.AddError(Res.GetString("dcf5eb58-c6c2-48c6-a0af-f464bed23b8b", "Please Enter a Shipment Number"));
					}
				}
				else
				{
					Match match = AutoGeneratedNumber.Match(value);
					if (match.Success)
					{
						info.AddError(Res.GetString("182dc320-f114-4923-9e28-f3bdf17c4d2e", "Numbers of the form A00000000 (a letter followed by 8 digits) are reserved for Auto-Generated numbers."));
					}

					if (value.Contains('/'))
					{
						info.AddError(Res.GetString("90939fa7-4b56-4869-b977-abc4af93404f", @"A forward slash (""/"") is not valid in a shipment number."));
					}
				}
			}
		}

		bool IsUniqueShipmentNumber(ZString number, ForwardingShipment shipment)
		{
			ZQuery filter = new ZQuery(JobShipmentSchema.JS_UniqueConsignRef, number);
			filter.AddToFilter(JobShipmentSchema.PK, SQLComparisonOperator.NotEqual, shipment.PK);
			filter.IgnoreActiveFilter = true;

			BusinessObjectFactory factory = shipment.Factory;
			return !factory.ExistsInDatabase(JobShipmentSchema.Constants.TableName, filter);
		}

		#region AutoGeneratedNumber

		Regex AutoGeneratedNumber
		{
			get
			{
				if (fAutoGeneratedNumber == null)
				{
					fAutoGeneratedNumber = new Regex("^[A-Z][0-9]{8}$", RegexOptions.Compiled | RegexOptions.IgnoreCase);
				}
				return fAutoGeneratedNumber;
			}
		}

		Regex fAutoGeneratedNumber;

		#endregion
	}
}

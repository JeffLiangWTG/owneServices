using System;
using System.Collections;
using System.Collections.Generic;
using System.Diagnostics.CodeAnalysis;
using System.IO;
using System.Linq;
using System.Reflection;
using CargoWise.Application;
using CargoWise.BuildTools;
using CargoWiseOne.ResourceStrings;
using Enterprise.MasterFiles.Business;
using Enterprise.ZArchitecture.Core;
using Microsoft.Build.Locator;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Workflow.CodeGeneration
{
	[SuppressMessage("CargoWiseOne", "CW1161:ResSGetStringAnalyzer", Justification = "Non-customer facing strings.")]
	static class WorkflowDescriptorGenerator
	{
		public static void Generate(string baseSourcePath = "..")
		{
			SetUpMsBuild();
			GenerateWorkflowDescriptorsList(baseSourcePath, "FullWorkflowDescriptorListAuto", w => true);
			GenerateWorkflowDescriptorsList(baseSourcePath, "WorkflowDescriptorListAuto", w => w.SupportsWorkflowTypeFilters);
			GenerateWorkflowDescriptorsList(baseSourcePath, "TemplateWorkflowDescriptorListAuto", w => w.SupportsWorkflowTypeFilters && (w.SupportsWorkflowTemplates || w.SupportsUniversalTemplates));
			GenerateWorkflowDescriptorsList(baseSourcePath, "BMSWorkflowDescriptorListAuto", w => w.SupportsWorkflowTypeFilters && w.SupportsBufferManagement);
			GenerateWorkflowDescriptorsList(baseSourcePath, "EventPublisherWorkflowDescriptorListAuto", w => ((object)w).GetType().GetInterface("IEventPublisher") != null);
		}

		static void GenerateWorkflowDescriptorsList(string baseSourcePath, string className, Func<WorkflowDescriptor, bool> filter)
		{
			var items = ScrapeWorkflowDescriptors(filter)
				.OrderBy(tuple => tuple.code)
				.Where(tuple => tuple.description is IResString)
			.Select(tuple =>
			{
				var code = tuple.code;
				var description = (IResString)tuple.description;
				var str = FormattableString.Invariant($"AddPair(\"{code}\", ResString._GetMultilingualString({tuple.asmid},\"{description.ResourceKey}\", \"{description.EnglishText}\"));");
				return SyntaxFactory.ParseStatement(str);
			}).ToArray();

			var constructor = SyntaxFactory.ConstructorDeclaration(className)
				.AddModifiers(SyntaxFactory.Token(SyntaxKind.PublicKeyword))
				.AddBodyStatements(items);

			var suppressCW1161 = SyntaxFactory.ParseStatement("[System.Diagnostics.CodeAnalysis.SuppressMessage(\"CargoWiseOne\", \"CW1161:Res.GetString Analyzer\", Justification = \"It's drunk\")]");
			var suppressCW1173 = SyntaxFactory.ParseStatement("[System.Diagnostics.CodeAnalysis.SuppressMessage(\"CargoWiseOne\", \"CW1173:Do Not Invoke Res Underscore GetString\", Justification = \"It exists somewhere else.\")]");
			var classDef = SyntaxFactory.ClassDeclaration(className)
				.AddAttributeLists(suppressCW1161.AttributeLists.Single())
				.AddAttributeLists(suppressCW1173.AttributeLists.Single())
				.AddModifiers(SyntaxFactory.Token(SyntaxKind.PublicKeyword))
				.AddBaseListTypes(SyntaxFactory.SimpleBaseType(SyntaxFactory.ParseTypeName("CodeDescriptionPairList")))
				.AddMembers(constructor);

			var nameSpace = SyntaxFactory.NamespaceDeclaration(SyntaxFactory.ParseName("Enterprise.Workflow.Business"))
				.AddMembers(classDef);

			UsingDirectiveSyntax Using(string str) => SyntaxFactory.UsingDirective(SyntaxFactory.IdentifierName(str));
			var unit = SyntaxFactory.CompilationUnit()
					.AddUsings(Using("Enterprise.ZArchitecture.Core"))
					.AddMembers(nameSpace);

			var path = FormattableString.Invariant(@$"{baseSourcePath}\Enterprise\Product\Operations\Workflow\Workflow.Business\WorkflowDescriptors\{className}.cs");
			using (var writer = File.CreateText(path))
			{
				var comment = @"// AUTO 🚗 GENERATED 🚗 FILE
//
// Hey! This file is automatically generated.
// Generate it by running Workflow.CodeGeneration.exe in the bin directory.
// Do not manually modify it please.
//
// AUTO 🚗 GENERATED 🚗 FILE";
				writer.WriteLine(comment);
				unit.NormalizeWhitespace(indentation: "\t").WriteTo(writer);
				writer.WriteLine();
			}
		}

		static void SetUpMsBuild()
		{
			if (MSBuildLocator.CanRegister)
			{
				var instance = DevMSBuildLocator.GetMSBuildInstance();
				MSBuildLocator.RegisterInstance(instance);
			}
		}

		static IEnumerable<(ushort asmid, string code, IMultilingualString description)> ScrapeWorkflowDescriptors(Func<WorkflowDescriptor, bool> filter)
		{
			EnterpriseApplicationConfiguration.ConfigureObjectFactory();
			var objectHandleHashtable = (Hashtable)ObjectFactory.Get("WorkflowDescriptors");
			foreach (DictionaryEntry entry in objectHandleHashtable)
			{
				var value = (WorkflowDescriptor)((ObjectHandle)entry.Value).GetObject();
				object obj = value;
				if (filter(value))
				{
					yield return (GetAsmid(obj.GetType().Assembly), value.Code, value.Description);
				}
			}
		}

		public static ushort GetAsmid(Assembly assembly)
		{
			var assemblyIdAttribute = (ResourceStringAssemblyIdAttribute)assembly.GetCustomAttributes(typeof(ResourceStringAssemblyIdAttribute)).FirstOrDefault();
			return assemblyIdAttribute.Id;
		}
	}
}

using CargoWise.EntityFramework.Testing;
using NUnit.Framework;

namespace Enterprise.Workflow.Business.Test
{
	[TestedType(typeof(UniversalValidationRuleCollection))]
	class UniversalValidationRuleCollectionTest : ActiveBusinessObjectCollectionTestCase<UniversalValidationRuleCollection>
	{
		protected override UniversalValidationRuleCollection GetCollectionToTest()
		{
			var parent = Factory.New<UniversalValidationRuleSet>();
			return new UniversalValidationRuleCollection(parent);
		}

		public void TestSequenceIsAutoGenerated()
		{
			var parent = Factory.New<UniversalValidationRuleSet>();
			var rules = new UniversalValidationRuleCollection(parent);
			var rule1 = rules.AddNew();
			var rule2 = rules.AddNew();
			var rule3 = rules.AddNew();

			AssertEquals(1, (int)rule1.VR_Sequence);
			AssertEquals(2, (int)rule2.VR_Sequence);
			AssertEquals(3, (int)rule3.VR_Sequence);
		}
	}
}

		#region TestGetNewBusinessEntityInLocalFactory

		public void TestGetNewBusinessEntityInLocalFactory()
		{
			var controller = new BarcodeParsingController();
			using (var form = (ZForm)controller.ShowNewForm())
			{
				var ruleSet = (BarcodeRuleSet)form.BusinessEntity;
				AssertNotNull(ruleSet);
				AssertEquals(0, ruleSet.Rules.Count);
			}

			using (BarcodeParsingTestCase.EnableDummyBarcodeParsingConsumer(Factory))
			{
				var rule = Helper.CreateRule();
				Factory.Save(); // Edit form only works with Entities in DB

				using (var form = (ZForm)controller.ShowEditForm(rule))
				{
					var ruleSet = (BarcodeRuleSet)form.BusinessEntity;
					AssertNotNull(ruleSet);
					AssertContainsExactElementsInAnyOrder(new[] { rule.PK }, ruleSet.Rules.Select(r => r.PK));

					var grid = (ZGrid)form.Controls["MainPanel"].Controls["MainTabControl"].Controls["MainTabPage"]
						.Controls["RulesPanel"].Controls["RulesTabControl"].Controls["ParsingRulesTabPage"].Controls["ParsingRulesGroupBox"].Controls["ParsingRulesGrid"];
					AssertContainsExactElementsInAnyOrder("If Rule was double clicked from Module, it should be selected when form shown.", new[] { rule.PK }, grid.SelectedElements.Select(r => r.PK));
				}
			}
		}

		#endregion

		#region TestGetNewBusinessEntityInLocalFactoryFromSystemRuleSet

		public void TestGetNewBusinessEntityInLocalFactoryFromSystemRuleSet()
		{
			var controller = new BarcodeParsingController(copyFromSystemTemplate: true);
			using (var form = (ZForm)controller.ShowNewForm())
			{
				var ruleSet = (BarcodeRuleSet)form.BusinessEntity;
				Assert("New RuleSet should have Rules.", ruleSet.Rules.Count > 0);
				Assert("All autogenerated rules must be GS1.", ruleSet.Rules.All(x => x.IsGS1));
				Assert("All autogenerated rules must be partial.", ruleSet.Rules.All(x => x.IsPartialRule));

				// components for part attributes should be added
				var consumer = Factory.GetBarcodeParsingConsumerFromModuleCode(BarcodeModuleTypes.Codes.Warehouse);
				foreach (var gs1TargetField in consumer.GS1TargetFieldsToDefault)
				{
					Assert("Should have component for " + consumer.TargetFields.GetDescriptionFromCode(gs1TargetField),
						ruleSet.Rules.Any(x => x.Components.Any(y => y.BRC_TargetField == gs1TargetField)));
				}
			}
		}


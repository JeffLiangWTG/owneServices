		#region TestDeleteSingleRule

		public void TestDeleteSingleRule()
		{
			using (BarcodeParsingTestCase.EnableDummyBarcodeParsingConsumer(Factory))
			{
				var ruleSet1 = Helper.CreateRuleSet();
				var rule1 = Helper.CreateRule(ruleSet1, "r1");
				var rule2 = Helper.CreateRule(ruleSet1, "r2");
				Helper.CreateRuleComponent(rule1);
				Helper.CreateRuleComponent(rule2);
				Factory.Save();

				var controller = new BarcodeParsingControllerForTest();
				UnitTestUserNotification.Instance.AddAnswer(DialogResult.No);
				controller.ShowDeleteFormForTest(rule1);
				AssertEquals("Rule1 deleting should show message", "Are you sure you wish to delete the selected Rule?", UnitTestUserNotification.Instance.LastMessage.Text);
				AssertEquals("Rule1 should *not* be deleted if the user selects *No*", false, rule1.IsDeleted);
				AssertEquals("RuleSet1 should *not* be deleted", false, ruleSet1.IsDeleted);

				UnitTestUserNotification.Instance.AddAnswer(DialogResult.Yes);
				controller.ShowDeleteFormForTest(rule1);
				AssertEquals("Rule1 deleting should show message", "Are you sure you wish to delete the selected Rule?", UnitTestUserNotification.Instance.LastMessage.Text);
				AssertEquals("Rule1 should be deleted if the user selects *Yes*", true, rule1.IsDeleted);
				AssertEquals("RuleSet1 should *not* be deleted", false, ruleSet1.IsDeleted);

				UnitTestUserNotification.Instance.AddAnswer(DialogResult.Yes);
				controller.ShowDeleteFormForTest(rule2);
				AssertEquals("Rule2 deleting should show message", "Are you sure you wish to delete the selected Rule?", UnitTestUserNotification.Instance.LastMessage.Text);
				AssertEquals("Rule2 should be deleted if the user selects *Yes*", true, rule2.IsDeleted);
				AssertEquals("RuleSet1 should be deleted if there is only one rule left", true, ruleSet1.IsDeleted);
			}
		}


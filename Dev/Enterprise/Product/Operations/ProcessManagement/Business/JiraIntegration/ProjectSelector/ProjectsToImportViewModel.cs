	{
		public ProjectsToImportViewModel(BusinessObjectFactory factory)
			: base(factory)
		{
		}

		#region NonPersistentBusinessObject Overrides

		protected override void SetDefaultValues()
		{
			base.SetDefaultValues();

			ShouldImportInProgressIssues = ZBool.True;
			ShouldImportUnStartedIssues = ZBool.True;

			if (JiraUrls.Count == 1)
			{
				JiraSystemCode = JiraUrls[0].Code;
			}
		}

		public override ProjectsToImportViewModelValidation GetNewValidation() => new ProjectsToImportViewModelValidation(this);

		#endregion

		#region ShouldImportAllProjects

		[ResourceStringData("ProjectsToImportViewModel.ShouldImportAllProjects", Caption = "Import all projects", FullDescription = "When ticked, all Jira projects will be imported.")]
		public ZBool ShouldImportAllProjects
		{
			get => shouldImportAllProjects;
			set
			{
				SetNonPersistentPropertyValue(ShouldImportAllProjectsInfo, ref shouldImportAllProjects, value);

				if (!IsValidationSuspended)
				{
					foreach (ProjectKeyViewModel projectKey in SpecificProjectsToImport)
					{
						projectKey.Validation.ValidateProjectKey();
					}
				}

				SpecificProjectsToImport.SetReadOnlyIncludingChildren(value);
			}
		}

		ZBool shouldImportAllProjects;

		public ZPropertyInfo ShouldImportAllProjectsInfo => GetZPropertyInfo(nameof(ShouldImportAllProjects));

		#endregion

		#region SelectedUri

		public Uri SelectedUri => string.IsNullOrEmpty(JiraSystemCode) ? null : new Uri(JiraUrls.GetDescriptionFromCode(JiraSystemCode));

		[List(nameof(JiraUrls))]
		[ResourceStringData("ProjectsToImportViewModel.JiraUrl", Caption = "Jira URL")]
		public ZString JiraSystemCode
		{
			get => jiraSystemCode;
			set
			{
				SetNonPersistentPropertyValue(JiraSystemCodeInfo, ref jiraSystemCode, value);

				if (!IsValidationSuspended)
				{
					Validation.ValidateJiraSystemCode();
				}
			}
		}

		ZString jiraSystemCode;

		public ZPropertyInfo JiraSystemCodeInfo => GetZPropertyInfo(nameof(JiraSystemCode));

		public ReadOnlyCodeDescriptionPairList JiraUrls => jiraUrls ?? (jiraUrls = ProcessManagementRegistry.Instance.JiraSiteUrls.Value);
		ReadOnlyCodeDescriptionPairList jiraUrls;


		public string FormattedIssueStatusQuery => ManyIssuesJiraQuery.GetIssueStatusesQueryString(IssueStatusModifier);

		public IssueStatusModifiers IssueStatusModifier
		{
			get
			{
				var result = default(IssueStatusModifiers);

				if (ShouldImportCompletedIssues)
				{
					result |= IssueStatusModifiers.Completed;
				}

				if (ShouldImportUnStartedIssues)
				{
					result |= IssueStatusModifiers.Unstarted;
				}

				if (ShouldImportInProgressIssues)
				{
					result |= IssueStatusModifiers.WorkInProgress;
				}

				return result;
			}
		}


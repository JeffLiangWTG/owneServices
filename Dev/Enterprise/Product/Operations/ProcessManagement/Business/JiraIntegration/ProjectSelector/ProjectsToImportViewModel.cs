		#region Import

		public ProjectImportReport ImportJiraContentAndReportResult(IJiraImporterProgressTracker progressTracker)
		{
			return ImportJiraContentAndReportResultCore(progressTracker);
		}

		protected virtual ProjectImportReport ImportJiraContentAndReportResultCore(IJiraImporterProgressTracker progressTracker)
		{
			var credentials = new JiraCredentials(JiraUserName, JiraAuthToken);
			var reportImportResult = new ProjectImportReport(true, ProjectImportReport.UnspecifiedFailure);
			JiraResult importResult;

			try
			{
				if (!CheckJiraApiVersion(new JiraWebHelper()))
				{
					reportImportResult.ShouldCloseImportForm = false;
					reportImportResult.ProjectReportMessage = ProjectImportReport.IncorrectJiraUrl;
					return reportImportResult;
				}
			}
			catch (Exception ex) when (!ex.IsCriticalException())
			{
				reportImportResult.ShouldCloseImportForm = false;
				reportImportResult.ProjectReportMessage = string.Join(System.Environment.NewLine, ex.FlattenInnerExceptions()
					.Skip(ex is AggregateException ? 1 : 0)
					.Select(e => e.Message));
				return reportImportResult;
			}

			try
			{
				importResult = GetImporter(progressTracker).Import(credentials);
			}
			finally
			{
				reportImportResult.ShouldCloseImportForm = true;
			}

			if (importResult != null)
			{
				var savedDataString = importResult.WasDataSaved ? "\r\n\r\n" + ProjectImportReport.PartiallySavedImport : string.Empty;

				switch (importResult.Status)
				{
					case JiraResponseStatus.Success:
						reportImportResult.ShouldCloseImportForm = true;
						reportImportResult.ProjectReportMessage = ProjectImportReport.Success(JiraApiVersion);
						break;
					case JiraResponseStatus.InvalidRequest:
						reportImportResult.ShouldCloseImportForm = false;
						reportImportResult.ProjectReportMessage = ProjectImportReport.InvalidRequest + savedDataString;
						break;
					case JiraResponseStatus.InvalidRequestWithCustomQuery:
						reportImportResult.ShouldCloseImportForm = false;
						reportImportResult.ProjectReportMessage = ProjectImportReport.InvalidRequestWithCustomQuery + savedDataString;
						break;
					case JiraResponseStatus.BadCredentials:
						reportImportResult.ShouldCloseImportForm = false;
						reportImportResult.ProjectReportMessage = ProjectImportReport.BadCredentials + savedDataString;
						break;
					case JiraResponseStatus.InsufficientPermissions:
						reportImportResult.ShouldCloseImportForm = false;
						reportImportResult.ProjectReportMessage = ProjectImportReport.InsufficientPermissions + savedDataString;
						break;
					case JiraResponseStatus.FailedServerCall:
						reportImportResult.ShouldCloseImportForm = false;
						reportImportResult.ProjectReportMessage = ProjectImportReport.FailedServerCall(SelectedUri) + savedDataString;
						break;
					case JiraResponseStatus.NoProjectClient:
						reportImportResult.ShouldCloseImportForm = true;
						reportImportResult.ProjectReportMessage = importResult.Response;
						break;
					default:
						reportImportResult.ShouldCloseImportForm = true;
						reportImportResult.ProjectReportMessage = importResult.Response.IsNullOrEmpty() ?
																ProjectImportReport.UnspecifiedFailure + savedDataString : importResult.Response;
						break;
				}
			}

			return reportImportResult;
		}

		protected virtual JiraEntityImporter GetImporter(IJiraImporterProgressTracker progressTracker)
		{
			return new JiraEntityImporter(this, progressTracker);
		}


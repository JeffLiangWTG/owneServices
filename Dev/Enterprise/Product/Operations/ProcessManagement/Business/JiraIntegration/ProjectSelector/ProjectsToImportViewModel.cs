		public string JiraApiVersion { get; set; }

		public virtual bool CheckJiraApiVersion(JiraWebHelper jiraWebHelper)
		{
			JiraApiVersion = jiraWebHelper.GetJiraApiVersion(SelectedUri);
			if (JiraApiVersion.IsNullOrEmpty())
			{
				return false;
			}
			return true;
		}

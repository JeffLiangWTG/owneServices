		#region SpecificProjectsToImport

		public ProjectKeyViewModelCollection SpecificProjectsToImport
		{
			get
			{
				if (specificProjectsToImport == null)
				{
					specificProjectsToImport = new ProjectKeyViewModelCollection(this);
					RegisterEditableChildObject(specificProjectsToImport);
				}

				return specificProjectsToImport;
			}
		}

		ProjectKeyViewModelCollection specificProjectsToImport;

		#endregion


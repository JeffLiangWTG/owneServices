		[TestDate(2021, 03, 03)]
		public void TestStandAloneShipmentsSendEmailForClientRatesGoingToExpireSoon_UsesMainFactoryForWorkflowAutoRater()
		{
			using (RatingDataRegistry.Instance.ClientRateGoingToExpireNotification.SetTemporaryValue(GlbCompany.CurrentCompany.PK.ToGuid(), Guid.Empty, Guid.Empty, true))
			{
				var today = ZDate.Today;
				var consignee = Helper.NewOrgHeader(0);
				var consignor = Helper.NewOrgHeader(1);
				var shipment = CreateForwardingShipment(TransportModes.Air, consignor.PK, consignee.PK, "ITNAP", "AUSYD", 50m, 0.5m);

				var salesRep = Factory.New<GlbStaff>();
				salesRep.GS_Code = "SAL";
				salesRep.GS_EmailAddress = "sales@somecompany.com";

				var clientRate = Helper.NewClientRate(consignee);
				clientRate.Header.StaffAssignments.OverallSalesRep = salesRep.GS_Code;

				var rateEntry = clientRate.AddRateEntry("AIR", "LSE", "ITNAP", "AUSYD");
				rateEntry.TI_RateStartDate = today.AddMonths(-4);
				rateEntry.TI_RateEndDate = today.AddDays(1);
				rateEntry.RateLines.RemoveAndDeleteAll();
				rateEntry.AddRateLine("WAR", FlatCalculator.Code, "", CurrencyCodes.Australia).GetCalculator<FlatCalculator>().BaseRate = 250m;

				Factory.Save();

				var query = new ZQuery(MailDBItemsSchema.MI_Subject, "Client Rate Test Client #1 Expiring Soon");
				var email = Factory.LoadTop1<MailItem>(query);
				AssertNull("Pre-condition", email);

				new AutoRatingStarter(shipment, new LoggerDecorator()).SearchForRates(AutoRateOptions.AutorateCostsRevenue);
				email = Factory.LoadTop1<MailItem>(query);
				AssertNull("Search For rates should not generate emails", email);

				var jobParent = shipment;
				var localClient = consignee;
				var expected = new[] { new AssertionCharge { ChargeCode = "WAR", JR_OSSellAmt = 250m } };

				UnitTestUserNotification.Instance.ClearMessages();

				using (var job = new JobHeader.Loader(jobParent).TryLoadOrCreate() as Job)
				{
					job.Charges.RemoveAndDeleteAll();
					job.ExchangeRates.RemoveAndDeleteAll();
					job.JH_OA_LocalChargesAddr = localClient.MainAddress.PK;

					var notifications = new NotificationBuffer();
					IProcessor rater = new WorkflowAutoRater(jobParent, autoRateRevenue: true, autoRateCosts: true, excludeConsolLevelCharges: false);
					rater.Process(notifications);

					var autoRatingSummary = GetAutoRatingSummary("", jobParent, null, null);

					AssertCharges(autoRatingSummary, expected, job);
				}

				var expectedEmailBody = @$"Shipment EBM22Q33TU475BXH3P60 was autorated by {ProductSupportName} using Client Rate(s) that will expire soon:
	• Client Rate Test Client #1 expires on 4/03/2021

Job Details:
Origin:	ITNAP
Destination:	AUSYD
Consignee:	Test Client #1
Consignor:	Test Client #2
Mode:	LSE
Weight:	50 KG
Volume:	0.5 M3

This message was automatically generated by {ProductName}. To configure this email, please go to the registry item at Autorating --> Notifications --> Client Rate Going To Expire Email.";

				query.FetchOnlyFromLocalCache = true;
				email = Factory.LoadTop1<MailItem>(query);
				AssertNotNull("Expiring rate email should have been generated in the job factory", email);
				AssertEquals("email should be not have been saved", false, email.IsInDatabase);
				AssertMultilineASCIIEquals("Email body should match", expectedEmailBody, email.BodyTextDecoded);
			}
		}


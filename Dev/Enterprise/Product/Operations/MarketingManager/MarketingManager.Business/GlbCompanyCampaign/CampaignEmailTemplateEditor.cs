		byte[] GetHtmlBlobWithCharsetDefinition(string html)
		{
			Encoding writeToDocumentBlobEncoding = Encoding.UTF8;

			HtmlDocument doc = new HtmlDocument();
			doc.LoadHtml(html);

			#region SuppressResourceStringsCheckRegion

			var headNode = doc.DocumentNode.SelectSingleNode("//head");
			if (headNode != null)
			{
				HtmlNode metaNode = null;
				if ((metaNode = doc.DocumentNode.SelectSingleNode("//meta[@http-equiv]")) != null)
				{
					metaNode.SetAttributeValue("content", "text/html; charset=" + writeToDocumentBlobEncoding.WebName);
				}
				else if ((metaNode = doc.DocumentNode.SelectSingleNode("//meta[@charset]")) != null)
				{
					metaNode.SetAttributeValue("charset", writeToDocumentBlobEncoding.WebName);
				}
				else
				{
					// Ude.CharsetDetector does a great job at detecting UTF-8 encoded bytes
					// However, add meta tag if it doesn't exist just in case
					metaNode = doc.CreateElement("meta");
					metaNode.SetAttributeValue("charset", writeToDocumentBlobEncoding.WebName);
					if (headNode.ChildNodes.Count > 0)
					{
						headNode.ChildNodes.Insert(0, metaNode);
					}
					else
					{
						headNode.AppendChild(metaNode);
					}
				}
			}

			#endregion

			string htmlText = doc.DocumentNode.WriteTo();
			return writeToDocumentBlobEncoding.GetBytes(htmlText);
		}


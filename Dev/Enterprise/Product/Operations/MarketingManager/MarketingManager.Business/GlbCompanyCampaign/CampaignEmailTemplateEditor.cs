		Dictionary<GlbCompanyCampaignLink, List<UrlInfo>> MatchUrlsWithPreviousTrackedLinks(List<UrlInfo> urls)
		{
			var linkToInfo = new Dictionary<GlbCompanyCampaignLink, List<UrlInfo>>();

			foreach (var url in urls)
			{
				if (!urls.Any(u => u != url && u.DestinationUrl == url.DestinationUrl && u.Context == url.Context))
				{
					int matchRank;
					var link = FindLink(url.DestinationUrl, url.Context, url.HasTrackingMacro, out matchRank);
					url.MatchingLink = link;
					url.MatchRank = matchRank;

					if (link != null)
					{
						List<UrlInfo> otherInfos;
						if (linkToInfo.TryGetValue(link, out otherInfos))
						{
							if (otherInfos != null)
							{
								if (otherInfos[0].DestinationUrl == url.DestinationUrl && otherInfos[0].Context == url.Context)
								{
									// add identical links
									otherInfos.Add(url);
								}
								else
								{
									// non-identical links all match - abandon all
									url.MatchingLink = null;
									foreach (var other in otherInfos)
									{
										other.MatchingLink = null;
									}
									linkToInfo[link] = null;
								}
							}
						}
						else
						{
							otherInfos = new List<UrlInfo>();
							otherInfos.Add(url);
							linkToInfo.Add(link, otherInfos);
						}
					}
				}
			}

			return linkToInfo;
		}

		[SuppressMessage("CargoWiseOne", "CW1161:ResGetStringAnalyzer", Justification = "Constant for http protocol, Constant")]
		List<UrlInfo> ExtractUrls(HtmlDocument doc)
		{
			var urls = new List<UrlInfo>();
			urlStreamPosToTagOrder = new Dictionary<int, int>();

			var invalidContextChars = @",""'".ToArray();
			int urlCount = 0;

			foreach (var node in doc.DocumentNode.Descendants())
			{
				UrlInfo url = null;

				if (node.Name == "a")
				{
					urlCount++;
					url = CreateURLInforForHyperlink(node);
				}

				if (url != null)
				{
					try
					{
						var val = url.Attrib.Value;
						var destinationUrl = LinkMacroRemover.Parse(LinkMacroDoc, val);
						var elementTrackIDTag = url.Attrib.OwnerNode.Attributes[HtmlNodeTrackIDAttribute];
						bool hasTrackingMacro = destinationUrl != val || elementTrackIDTag != null;

						Uri uriResult;
						if (Uri.TryCreate(destinationUrl, UriKind.Absolute, out uriResult) && uriResult.Scheme == Uri.UriSchemeFile) //isLocalImage
						{
							continue;
						}

						// ignore schemes like mailto:
						if (hasTrackingMacro ||
							(destinationUrl.IndexOf(':') < 0 || destinationUrl.StartsWith("http", StringComparison.OrdinalIgnoreCase)))
						{
							url.HasTrackingMacro = hasTrackingMacro;
							url.DestinationUrl = destinationUrl.Trim();

							if (hasTrackingMacro)
							{
								url.Context = LinkMacroDoc.LastContext;
								if (elementTrackIDTag != null)
								{
									url.Context = elementTrackIDTag.Value;
								}
							}
							else if (url.IsImage && string.IsNullOrEmpty(url.Context))
							{
								url.Context = GetImageFileName(destinationUrl);
							}

							if (url.Context.Length > GlbCompanyCampaignLink.Schema.GCL_ContextMaxLength)
							{
								url.Context = url.Context.Substring(0, GlbCompanyCampaignLink.Schema.GCL_ContextMaxLength);
							}

							if (url.Context.IndexOfAny(invalidContextChars) >= 0)
							{
								StringBuilder s = new StringBuilder(url.Context.Length);
								foreach (char c in url.Context)
								{
									if (!invalidContextChars.Contains(c))
									{
										s.Append(c);
									}
								}
								url.Context = s.ToString();
							}

							url.Context = url.Context.Trim();

							urls.Add(url);
							urlStreamPosToTagOrder[url.Attrib.StreamPosition] = urlCount;
						}
					}
					catch (Exception ex) when (!ex.IsCriticalException())
					{
					}
				}
			}

			return urls;
		}

		UrlInfo CreateURLInforForHyperlink(HtmlNode node)
		{
			var urlAttribute = node.Attributes["href"];
			if (urlAttribute != null &&
				IsUrlTrackable(urlAttribute.Value) &&
				(!string.IsNullOrWhiteSpace(node.InnerText) || !string.IsNullOrWhiteSpace(node.InnerHtml)))
			{
				string context = node.InnerText.Trim('\r', '\n', '\t');
				context = context.Replace("\r\n", "");

				var imageChildren = node.SelectNodes(@".//img");

				if (string.IsNullOrWhiteSpace(context) && imageChildren != null && imageChildren.Count > 0)
				{
					var imgUrl = imageChildren[0].Attributes["src"];
					if (imgUrl != null)
					{
						if (imgUrl.Value.StartsWith("data:image", StringComparison.OrdinalIgnoreCase))
						{
							context = Res.GetString("66c5d5bf-c86b-438e-90fe-d84a75dda9c7", "Embedded Image");
						}
						else
						{
							context = GetImageFileName(LinkMacroRemover.Parse(LinkMacroDoc, imgUrl.Value)) + " " + Res.GetString("7c616c40-9474-43b9-8984-5bc162468ffc", "[Image Link]");
						}
					}
				}

				return new UrlInfo() { Attrib = urlAttribute, Context = context };
			}
			return null;
		}

		bool IsUrlTrackable(string url)
		{
			Uri uriResult;
			bool result = Uri.TryCreate(url, UriKind.Absolute, out uriResult);
			try
			{
				var destinationUrl = LinkMacroRemover.Parse(LinkMacroDoc, url);
				result = destinationUrl.IsEmpty || Uri.TryCreate(destinationUrl, UriKind.Absolute, out uriResult);
			}
			catch (Exception ex)
			{
				if (ex.IsCriticalException())
				{
					throw;
				}
			}

			return result;
		}

		static string GetImageFileName(string url)
		{
			string path = null;
			if (Uri.IsWellFormedUriString(url, UriKind.Absolute))
			{
				path = new Uri(url, UriKind.Absolute).AbsolutePath;
			}
			else
			{
				int queryStringIndex = url.IndexOf('?');
				int endPathIndex = queryStringIndex > 0 ? queryStringIndex - 1 : url.Length - 1;
				int lastComponentIndex = Math.Max(0, url.LastIndexOfAny(new char[] { '/', ':' }, endPathIndex, endPathIndex + 1));
				path = url.Substring(lastComponentIndex, endPathIndex - lastComponentIndex + 1);
			}

			return (path.IndexOfAny(Path.GetInvalidPathChars()) < 0)
				? Path.GetFileName(path)
				: null;
		}

		GlbCompanyCampaignLink FindLink(string url, string context, bool hasTrackingMacro, out int matchRank)
		{
			GlbCompanyCampaignLink bestMatch = null;
			int bestRank = 0;
			int countAtRank = 0;
			const int ContextRank = 2;
			const int UrlRank = 1;
			foreach (GlbCompanyCampaignLink link in TrackedLinks)
			{
				if (link.HasTrackingMacro == hasTrackingMacro)
				{
					int rank = 0;
					if (link.GCL_URL == url)
					{
						rank += UrlRank;
					}
					if (link.GCL_Context == context)
					{
						rank += ContextRank;
					}
					if (link.GCL_IsTracked && rank != (UrlRank + ContextRank))
					{
						rank = 0;
					}

					if (bestRank < rank)
					{
						bestRank = rank;
						countAtRank = 1;
						bestMatch = link;
					}
					else if (rank > 0 && bestRank == rank)
					{
						++countAtRank;
					}
				}
			}

			if (countAtRank > 1)
			{
				// ambiguous match
				bestMatch = null;
				bestRank = 0;
			}

			matchRank = bestRank;
			return bestMatch;
		}


		static string RestoreTrackingMacro(string html)
		{
			if (string.IsNullOrEmpty(html))
			{
				return html;
			}

			var templateHtmlDocument = new HtmlDocument();
			templateHtmlDocument.LoadHtml(html);

			var nodes = templateHtmlDocument.DocumentNode.SelectNodes(@"//a") ?? new HtmlNodeCollection(null);
			foreach (var node in nodes)
			{
				var attr = node.Attributes["href"];
				if (attr != null && HasAttributeWithTrackID(node, HtmlNodeTrackIDAttribute) && !attr.Value.Contains(LinkTrackingIdentifier))
				{
					attr.Value = LinkTrackingIdentifier + ReadAttributeValue(node, HtmlNodeTrackIDAttribute) + "," + attr.Value + ")*)";
				}
				node.Attributes.Remove(HtmlNodeTrackIDAttribute);
			}

			nodes = templateHtmlDocument.DocumentNode.SelectNodes(@"//img") ?? new HtmlNodeCollection(null);
			foreach (var node in nodes)
			{
				var attr = node.Attributes["src"];
				if (HasAttributeWithTrackID(node, HtmlNodeTrackIDAttribute) && !attr.Value.Contains(LinkTrackingIdentifier))
				{
					attr.Value = LinkTrackingIdentifier + ReadAttributeValue(node, HtmlNodeTrackIDAttribute) + "," + attr.Value + ")*)";
					node.Attributes.Remove(HtmlNodeTrackIDAttribute);
				}
				node.Attributes.Remove(HtmlImgEmbeddedIdentifier);
			}

			return templateHtmlDocument.DocumentNode.WriteTo();
		}


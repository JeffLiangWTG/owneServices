		void HasTrackingMacroValueChanged(object sender, EventArgs e)
		{
			if (inSyncHtmlAndLinks)
			{
				return;
			}

			using (BeginSyncHtmlAndLinks())
			{
				OnPreLinkValueChanged();

				var link = (GlbCompanyCampaignLink)sender;

				if (link.HasTrackingMacro)
				{
					var nameUsed = new Dictionary<string, bool>(StringComparer.InvariantCultureIgnoreCase);
					foreach (GlbCompanyCampaignLink other in TrackedLinks)
					{
						if (other.PK != link.PK)
						{
							if (other.HasTrackingMacro)
							{
								nameUsed[other.GCL_Context] = true;
							}
							else if (!nameUsed.ContainsKey(other.GCL_Context))
							{
								nameUsed[other.GCL_Context] = false;
							}
						}
					}

					var uniqueContext = GenerateUniqueContext(nameUsed, link.GCL_Context);
					if (link.GCL_Context != uniqueContext)
					{
						link.GCL_Context = uniqueContext;
					}
				}

				UpdateLinkAttribute(link);
				NeedHighlightCurrentLink = true;
				using (ResizeTablesForDesignSuspender.GetSuspender())
				{
					SyncHtmlAndLinks(false);
				}

				OnRefreshHostHandler();
			}
		}

		void LinkValueChanged(object sender, EventArgs e)
		{
			if (inSyncHtmlAndLinks)
			{
				return;
			}

			using (BeginSyncHtmlAndLinks())
			{
				OnPreLinkValueChanged();

				var link = (GlbCompanyCampaignLink)sender;
				UpdateLinkAttribute(link);
				NeedHighlightCurrentLink = true;
				using (ResizeTablesForDesignSuspender.GetSuspender())
				{
					SyncHtmlAndLinks(false);
				}
				SyncHtmlAndLinksFromCampaignTrackedLinks(new UrlInfo()
				{
					DestinationUrl = link.GCL_URL,
					Context = link.GCL_Context,
					HasTrackingMacro = link.HasTrackingMacro,
					IsImage = link.GCL_IsImage
				}, link);
			}
		}

		void UpdateLinkAttribute(GlbCompanyCampaignLink link)
		{
			foreach (var pair in urlAttributeToLink.Where(pair => pair.Value.PK == link.PK))
			{
				UpdateModelOnLinkTrackingSelected(link, pair.Key);
				AddTrackIDToTrackingImage(link, pair.Key, link.GCL_Context);
			}
		}


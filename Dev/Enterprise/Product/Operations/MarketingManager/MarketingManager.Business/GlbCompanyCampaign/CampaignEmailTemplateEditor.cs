		[SuppressMessage("CargoWiseOne", "CW1161:ResGetStringAnalyzer", Justification = "html code generated by editor")]
		public void SetTemplateHtmlText(ZString value, HtmlTextSource source)
		{
			if (value != templateHtmlText)
			{
				if (!templateHtmlText.IsEmpty)
				{
					const string htmlEditorBodyConstant = " scroll=\"auto\"";
					ZString newBodyValue = value.Substring(value.IndexOf("<body", StringComparison.OrdinalIgnoreCase)).Replace(htmlEditorBodyConstant, "");
					ZString oldBodyValue = templateHtmlText.Substring(templateHtmlText.IndexOf("<body", StringComparison.OrdinalIgnoreCase)).Replace(htmlEditorBodyConstant, "");
					if (!newBodyValue.EqualsIgnoringCase(oldBodyValue) && !hasChangesOnlyOnSync)
					{
						Campaign.HasChanges = true;
					}
				}

				SetNonPersistentPropertyValue(TemplateHtmlTextInfo, ref templateHtmlText, value);

				if (!inSyncHtmlAndLinks)
				{
					using (BeginSyncHtmlAndLinks())
					{
						SyncHtmlAndLinks(true);
					}
				}

				if (Regex.IsMatch(templateHtmlText, HEAD_PARSE_PRE_EXPRESSION, RegexOptions.IgnoreCase | RegexOptions.Multiline | RegexOptions.Singleline))
				{
					var expression = new Regex(HEAD_PARSE_EXPRESSION, RegexOptions.IgnoreCase | RegexOptions.Multiline | RegexOptions.Singleline | RegexOptions.Compiled | RegexOptions.ExplicitCapture);
					var match = expression.Match(value);
					if (match.Success)
					{
						if (source == HtmlTextSource.TextEditor)
						{
							templateHtmlHeadText = match.Result(HEAD_INNER_PARSE_MATCH).Replace(System.Environment.NewLine, string.Empty).Trim();
						}
						else
						{
							templateHtmlText = Regex.Replace(templateHtmlText, HEAD_PARSE_EXPRESSION, $"<head>{templateHtmlHeadText}</head>");
						}
					}
				}
			}
		}

		[SuppressMessage("CargoWiseOne", "CW1161:ResGetStringAnalyzer", Justification = "Constant HtmlAttribute value is not translatable")]

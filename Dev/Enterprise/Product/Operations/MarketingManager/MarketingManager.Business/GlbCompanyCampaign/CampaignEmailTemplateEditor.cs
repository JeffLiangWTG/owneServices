		static string TryDecodeViaPreamble(byte[] data)
		{
			string result = null;
			Encoding[] unicodeEncodings = { Encoding.BigEndianUnicode, Encoding.Unicode, Encoding.UTF8 };
			foreach (var encoding in unicodeEncodings)
			{
				var preamble = encoding.GetPreamble();
				if (ByteMatch(data, encoding.GetPreamble()))
				{
					result = encoding.GetString(data, preamble.Length, data.Length - preamble.Length);
					break;
				}
			}

			return result;
		}

		static string TryDecodeUnicode(byte[] data)
		{
			if ((data.Length & 1) == 1)
			{
				// unicode must have even length
				return null;
			}

			int countToExamine = Math.Min(32, data.Length);
			bool areOddBytesZero = true;
			bool areEvenBytesZero = true;
			for (int i = 0; i < countToExamine; ++i)
			{
				if (data[i] != 0)
				{
					if ((i & 1) == 1)
					{
						areOddBytesZero = false;
					}
					else
					{
						areEvenBytesZero = false;
					}
				}
			}

			string result = null;
			if (areOddBytesZero && !areEvenBytesZero)
			{
				result = Encoding.Unicode.GetString(data);
			}
			else if (areEvenBytesZero && !areOddBytesZero)
			{
				result = Encoding.BigEndianUnicode.GetString(data);
			}

			return result;
		}

		static Encoding GetEncodingFromDocumentBlob(byte[] data)
		{
			Encoding encoding = null;
			string charset = GetHtmlCharset(data);
			if (!string.IsNullOrEmpty(charset))
			{
				encoding = SafeGetEncoding(charset);
			}

			if (encoding == null)
			{
				Ude.CharsetDetector detector = new Ude.CharsetDetector();
				detector.Feed(data, 0, data.Length);
				detector.DataEnd();
				if (detector.Charset != null)
				{
					encoding = SafeGetEncoding(detector.Charset);
				}
			}

			if (encoding == null)
			{
				encoding = Encoding.UTF8;
			}
			return encoding;
		}

		static Encoding SafeGetEncoding(string name)
		{
			try
			{
				return Encoding.GetEncoding(name);
			}
			catch (ArgumentException)
			{
				return null;
			}
		}

		/// <summary>
		/// Search HTML header for charset definiton
		/// </summary>
		[SuppressMessage("CargoWiseOne", "CW1161:ResGetStringAnalyzer", Justification = "HTML tag is not translatable, HTML element is not translatable")]
		static string GetHtmlCharset(byte[] data)
		{
			// Pattern
			// <head>.... charset=xxx"</head>

			// HTML
			// <meta http-equiv="Content-Type" content="text/html; charset=utf-8">
			//
			// HTML5
			// <meta charset="utf-8">

			string result = null;

			const string startHtmlTag = "<head>";
			const string endHtmlTag = "</head>";
			const string charsetAttribute = " charset";

			byte[] headStartBytes = Encoding.ASCII.GetBytes(startHtmlTag);
			int headStartIndex = ByteSearch(data, headStartBytes);
			if (headStartIndex >= 0)
			{
				int headContentIndex = headStartIndex + headStartBytes.Length;
				int headEndIndex = ByteSearch(data, Encoding.ASCII.GetBytes(endHtmlTag), headContentIndex);
				if (headEndIndex > headStartIndex)
				{
					// Note, charset should be early in the header
					byte[] charsetBytes = Encoding.ASCII.GetBytes(charsetAttribute);
					int charsetIndex = ByteSearch(data, charsetBytes, headContentIndex, headEndIndex - headContentIndex);
					if (charsetIndex > 0)
					{
						int charsetContentIndex = charsetIndex + charsetBytes.Length;
						// skip equals, starting quotes and white space
						for (; charsetContentIndex < headEndIndex; ++charsetContentIndex)
						{
							byte b = data[charsetContentIndex];
							if (b != ' ' && b != '"' && b != '\'' && b != '=' && b != '\t' && b != '\r' && b != '\n')
							{
								break;
							}
						}

						// find end quote
						int endIndex = -1;
						for (int i = charsetContentIndex; i < headEndIndex; ++i)
						{
							byte b = data[i];
							if (b == '"' || b == '\'')
							{
								endIndex = i;
								break;
							}
						}
						if (endIndex > 0)
						{
							result = Encoding.ASCII.GetString(data, charsetContentIndex, endIndex - charsetContentIndex).Trim();
						}
					}
				}
			}

			return result;
		}

		static bool ByteMatch(byte[] data, byte[] key, int dataStartIndex = 0, int keyStartIndex = 0)
		{
			int matchCount = key.Length - keyStartIndex;
			if (data.Length - dataStartIndex >= matchCount)
			{
				for (int i = 0; i < matchCount; ++i)
				{
					if (data[dataStartIndex + i] != key[keyStartIndex + i])
					{
						return false;
					}
				}

				return true;
			}

			return false;
		}

		static int ByteSearch(byte[] data, byte[] key, int startIndex = 0, int length = -1)
		{
			if (length == -1)
			{
				length = data.Length - startIndex;
			}

			int found = -1;
			if (length > 0 && length >= key.Length)
			{
				int endIndex = startIndex + length - key.Length;
				for (int i = startIndex; i <= endIndex; i++)
				{
					if (data[i] == key[0] && ByteMatch(data, key, i + 1, 1))
					{
						found = i;
						break;
					}
				}
			}
			return found;
		}


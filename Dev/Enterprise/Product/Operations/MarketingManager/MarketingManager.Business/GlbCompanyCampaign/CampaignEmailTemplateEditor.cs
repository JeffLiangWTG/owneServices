		void SyncHtmlAndLinks(bool fromHtml)
		{
			if (!fromHtml && templateHtmlDocument == null)
			{
				return;
			}

			if (!fromHtml)
			{
				var htmlText = templateHtmlDocument.DocumentNode.WriteTo();
				if (htmlText != TemplateHtmlText)
				{
					TemplateHtmlText = htmlText;
					OnForceHtmlUpdate();
				}
			}

			templateHtmlDocument.LoadHtml(TemplateHtmlText);
			var urls = ExtractUrls(templateHtmlDocument);
			var oldLinks = TrackedLinks.Cast<GlbCompanyCampaignLink>().ToArray();
			var linkToInfo = MatchUrlsWithPreviousTrackedLinks(urls);

			using (TrackedLinks.SuspendListChanged())
			{
				// Remove unmatched links
				foreach (var link in oldLinks)
				{
					List<UrlInfo> otherInfos;
					if (!linkToInfo.TryGetValue(link, out otherInfos) || otherInfos == null)
					{
						UnhookEventHandlers(link);
						TrackedLinks.Remove(link);
					}
				}

				urlAttributeToLink.Clear();
				LinkHighlightAttrIdMap.Clear();
				foreach (var url in urls)
				{
					var link = url.MatchingLink;
					string context = url.Context;
					if (link != null && !fromHtml)
					{
						context = link.GCL_Context;
					}

					if (link == null)
					{
						link = SyncHtmlAndLinksFromCampaignTrackedLinks(url, link);
					}

					if (link == null)
					{
						link = TrackedLinks.AddNew();
						link.GCL_IsImage = url.IsImage;
						link.HasTrackingMacro = url.HasTrackingMacro;
						SetupEventHandlers(link);
					}

					link.GCL_Context = context;
					link.GCL_URL = url.DestinationUrl;
					link.Order = url.Attrib.StreamPosition;
					urlAttributeToLink.Add(url.Attrib, link);
					AddTrackIDToTrackingImage(link, url.Attrib);

					if (!LinkHighlightAttrIdMap.ContainsKey(link))
					{
						LinkHighlightAttrIdMap.Add(link, url.HighlightId);
					}
				}
			}
		}

		GlbCompanyCampaignLink SyncHtmlAndLinksFromCampaignTrackedLinks(UrlInfo url, GlbCompanyCampaignLink link)
		{
			foreach (var campaignLink in campaign.TrackedLinks)
			{
				if ((url.Context == campaignLink.GCL_Context && url.DestinationUrl == campaignLink.GCL_URL) && TrackedLinks.FindByPK(campaignLink.PK) == null)
				{
					link = campaignLink;
					link.HasTrackingMacro = true;
					SetupEventHandlers(link);
					TrackedLinks.Add(link);
					UpdateModelOnLinkTrackingSelected(link, url.Attrib, true);
					break;
				}
			}

			return link;
		}

		/// <summary>
		/// Generate a unique context by appending a number in brackets, or increasing the number if already present.
		///	  Dupe
		///	  Dupe (2)
		///	  Dupe (3)
		///	  ....
		/// </summary>
		static string GenerateUniqueContext(Dictionary<string, bool> nameUsed, string context)
		{
			bool isUsed;
			if (nameUsed.TryGetValue(context, out isUsed) && isUsed)
			{
				var match = Regex.Match(context, @".+(\([0-9]+\)).*");
				int index;
				string prefix;
				string separator;
				string suffix;
				var group = match.Success ? match.Groups[1] : null;
				var val = group != null ? group.Value : null;
				if (val != null && int.TryParse(val.Substring(1, val.Length - 2), out index))
				{
					prefix = context.Substring(0, group.Index);
					separator = "(";
					suffix = context.Substring(group.Index + val.Length);
				}
				else
				{
					index = 1;
					prefix = context;
					separator = " (";
					suffix = "";
				}

				do
				{
					index = (index != Int32.MaxValue) ? index + 1 : 1;
					context = prefix + separator + index + ')' + suffix;
					int countToRemove = context.Length - GlbCompanyCampaignLink.Schema.GCL_ContextMaxLength;
					if (countToRemove > 0)
					{
						int removeFromSuffix = Math.Min(countToRemove, suffix.Length);
						string newSuffix = suffix.Substring(0, suffix.Length - removeFromSuffix);
						countToRemove -= removeFromSuffix;
						string newPrefix = prefix;
						if (countToRemove > 0)
						{
							newPrefix = newPrefix.Substring(0, newPrefix.Length - countToRemove);
						}
						context = newPrefix + separator + index + ')' + newSuffix;
					}
				} while (nameUsed.ContainsKey(context));
			}

			return context;
		}


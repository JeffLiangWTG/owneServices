		static string SetImageWidthAndHeightFromCSSStyleProperties(string html)
		{
			var document = new HtmlDocument();
			document.LoadHtml(html);

			var nodes = document.DocumentNode.SelectNodes($@"//{TagNameImage}");
			if (nodes == null || nodes.Count == 0)
			{
				return html;
			}

			foreach (var node in nodes)
			{
				var style = node.Attributes[AttributeStyle]?.Value;
				if (string.IsNullOrEmpty(style))
				{
					continue;
				}

				var match = Regex.Match(style, RegexPatternWidthStyle, RegexOptions.IgnoreCase);
				if (match.Success)
				{
					node.Attributes[AttributeWidth]?.Remove();
					node.Attributes.Add(AttributeWidth, match.Groups[2].Value);
				}

				match = Regex.Match(style, RegexPatternHeightStyle, RegexOptions.IgnoreCase);
				if (match.Success)
				{
					node.Attributes[AttributeHeight]?.Remove();
					node.Attributes.Add(AttributeHeight, match.Groups[2].Value);
				}
			}

			return document.DocumentNode.WriteTo();
		}


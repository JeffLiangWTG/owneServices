		static bool HasAttributeWithTrackID(HtmlNode node, string trackID)
		{
			return node.HasAttributes &&
					 node.Attributes.Any(a => string.Equals(a.Name, trackID, StringComparison.OrdinalIgnoreCase));
		}

		static string ReadAttributeValue(HtmlNode node, string trackID)
		{
			return HasAttributeWithTrackID(node, trackID)
				? node.Attributes.First(a => string.Equals(a.Name, trackID, StringComparison.InvariantCultureIgnoreCase))
					.Value
				: null;
		}


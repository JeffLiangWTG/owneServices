		public static string RemoveEmbeddedImage(ZString html, ref bool isChanged)
		{
			var doc = new HtmlDocument();
			doc.LoadHtml(html);

			var nodes = doc.DocumentNode.SelectNodes(@"//img");
			if (nodes != null)
			{
				foreach (var node in nodes)
				{
					if (node.Attributes["src"] != null)
					{
						if (IsValidImageUrl(node.Attributes["src"].Value))
						{
							continue;
						}

						node.Attributes.Remove(HtmlImgEmbeddedIdentifier);
						node.Attributes["src"].Value = "";
						isChanged = true;
					}
				}

				return doc.DocumentNode.WriteTo();
			}

			return html;
		}


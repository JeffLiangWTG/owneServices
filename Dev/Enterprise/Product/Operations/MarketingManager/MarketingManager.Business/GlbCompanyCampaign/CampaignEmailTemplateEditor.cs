		void AddTrackIDToTrackingImage(GlbCompanyCampaignLink link, HtmlAttribute attrib, string newTrackID = "")
		{
			if (link.HasTrackingMacro && attrib.OwnerNode.Attributes[HtmlNodeTrackIDAttribute] == null)
			{
				attrib.OwnerNode.Attributes.Add(HtmlNodeTrackIDAttribute, link.GCL_Context);
			}
			else if (!attrib.Value.Contains(LinkTrackingIdentifier) && !string.IsNullOrEmpty(newTrackID))
			{
				attrib.OwnerNode.Attributes.Remove(HtmlNodeTrackIDAttribute);
			}
			else if (attrib.OwnerNode.Attributes[HtmlNodeTrackIDAttribute] != null && !string.IsNullOrEmpty(newTrackID) && attrib.OwnerNode.Attributes[HtmlNodeTrackIDAttribute].Value != newTrackID)
			{
				attrib.OwnerNode.Attributes[HtmlNodeTrackIDAttribute].Value = newTrackID;
			}
		}

		void UpdateModelOnLinkTrackingSelected(GlbCompanyCampaignLink link, HtmlAttribute attrib, bool syncWithExistingLink = false)
		{
			if (attrib != null)
			{
				templateHtmlDocument.LoadHtml(TemplateHtmlText);
				foreach (var node in templateHtmlDocument.DocumentNode.SelectNodes(@"//" + attrib.OwnerNode.Name)
					.Where(node => node.XPath == attrib.OwnerNode.XPath))
				{
					if (link.HasTrackingMacro)
					{
						if (!HasAttributeWithTrackID(node, HtmlNodeTrackIDAttribute))
						{
							node.Attributes.Add(HtmlNodeTrackIDAttribute, link.GCL_Context);
						}
						node.Attributes[HtmlNodeTrackIDAttribute].Value = link.GCL_Context;
						node.Attributes[attrib.Name].Value = link.GCL_URL;
					}
					else
					{
						node.Attributes.Remove(HtmlNodeTrackIDAttribute);
						node.Attributes[attrib.Name].Value = (string)link.GCL_URL;
					}
				}

				if (syncWithExistingLink)
				{
					TemplateHtmlText = templateHtmlDocument.DocumentNode.WriteTo();
				}
			}
		}

		public void SyncImageTrackIDAttributeAndTrackingMacro()
		{
			using (SkipHasChangesOnEditorViewChange())
			{
				templateHtmlDocument.LoadHtml(TemplateHtmlText);

				var nodes = templateHtmlDocument.DocumentNode.SelectNodes(@"//img");
				if (nodes != null)
				{
					foreach (var node in nodes)
					{
						var attr = node.Attributes["src"];
						if (attr == null || (HasAttributeWithTrackID(node, HtmlNodeTrackIDAttribute) && !attr.Value.Contains(LinkTrackingIdentifier)))
						{
							continue;
						}

						if (attr.Value.Contains(LinkTrackingIdentifier))
						{
							if (!HasAttributeWithTrackID(node, HtmlNodeTrackIDAttribute))
							{
								string[] contextSection = attr.Value.Split(new char[] { ',' });
								if (contextSection.Length > 0)
								{
									string context = contextSection[0].Remove(0, LinkTrackingIdentifier.Length);
									attr.OwnerNode.Attributes.Add(HtmlNodeTrackIDAttribute, context);
								}
							}

							attr.Value = LinkMacroRemover.Parse(LinkMacroDoc, attr.Value);
						}
					}
				}

				TemplateHtmlText = templateHtmlDocument.DocumentNode.WriteTo();
			}
		}

		public static string EmbedImagesInHtmlFromLocalDirectory(string baseDirectory, ZString html, IMappedClientPath mappedClientPath = null)
		{
			var doc = new HtmlDocument();
			doc.LoadHtml(html);

			var nodes = doc.DocumentNode.SelectNodes(@"//img");
			if (nodes != null)
			{
				foreach (var node in nodes)
				{
					var sourceAttr = node.Attributes["src"];
					if(sourceAttr == null)
					{
						continue;
					}
					if (UrlValidation.IsValidAbsoluteHttpOrHttpsUrl(sourceAttr.Value))
					{
						continue;
					}

					if (sourceAttr.Value.StartsWith("data:image"))
					{
						continue;
					}

					var extension = Path.GetExtension(sourceAttr.Value).Trim('.');
					if (!IsSupportedExtension(extension))
					{
						continue;
					}

					var fullFilePath = Path.Combine(baseDirectory, WebUtility.UrlDecode(sourceAttr.Value));
					if (mappedClientPath != null)
					{
						fullFilePath = mappedClientPath.GetMappedPath(fullFilePath);
					}

					if (string.IsNullOrEmpty(fullFilePath))
					{
						continue;
					}

					if (!File.Exists(fullFilePath))
					{
						continue;
					}

					var imageBytes = File.ReadAllBytes(fullFilePath);
					var base64String = Convert.ToBase64String(imageBytes);
					var imageContent = $"data:image/{extension};base64,{base64String}";
					sourceAttr.Value = imageContent;
				}
			}

			return doc.DocumentNode.WriteTo();
		}


namespace CargoWise.EntityFramework
{
	#region interface IValidationInternals

	public interface IValidationInternals
	{
		void Validate(ZPropertyInfo info, RunValidationInvoker runValidationInvoker);
		void Add(ZValidation validation);
		void Remove(ZValidation validation);
	}

	#endregion

	public delegate void RunValidationInvoker();

	public abstract class ZValidation : IValidationInternals
	{
		protected ZValidation(BusinessObject parent)
		{
			if (Object.ReferenceEquals(parent, null))
			{
				throw new ArgumentNullException(nameof(parent));
			}

			this.Parent = parent;
			this.ParentListInternals = parent;
			this.ZValidationInternals = this;
			this.glowValidation = new ZGlowValidation(parent.GetType());
		}

		public abstract void ValidateAll();

		public abstract Type AutoValidationType
		{
			get;
		}

		public bool ContainsPiggybackedValidation(Type zValidationType)
		{
			foreach (ZValidation validation in PiggybackedValidations.Values)
			{
				if (validation.GetType() == zValidationType)
				{
					return true;
				}
			}

			return false;
		}

		public bool ContainsDomainValidation(Type zValidationType)
		{
			if (Parent.Factory != null && Parent.Factory.Validation != null && Parent.Factory.HasDomainValidation)
			{
				Type businessObjectType = Parent.GetType();
				foreach (DomainValidationGroup validationGroup in Parent.Factory.Validation.AllValidationGroups)
				{
					if (validationGroup.ContainsDomainValidation(businessObjectType, zValidationType))
					{
						return true;
					}
				}
			}

			return false;
		}

		#region Running Validation

		void ValidateAutoGeneratedProperty(ZPropertyInfo info, RunValidationInvoker runValidationInvoker)
		{
			if (info.BizObj.IsPropertySupported(info) && info.BizObj.IsValidationEnabled(info))
			{
				ValidateProperty(info, delegate()
				{
					var propertyType = info.PropertyType;
					if (((propertyType == typeof(ZString) && info.Name.Contains("_NK")) || propertyType == typeof(ZGuid)) && ShouldValidateFKToCancelledRecord(info))
					{
						ListValidation.ErrorIfCancelledAndEditable(info);
					}
					runValidationInvoker();
					glowValidation.Validate(info);

					return new ValidationMethodsRunner(this, info, true);
				});
			}
		}

		protected virtual bool ShouldValidateFKToCancelledRecord(ZPropertyInfo info)
		{
			return true;
		}

		protected void ValidateCalculatedProperty(ZPropertyInfo info)
		{
			if (info == null)
			{
				throw new ArgumentNullException(nameof(info), "Info cannot be null when passing to ValidateCalculatedProperty.");
			}
			if (info.BizObj.IsPropertySupported(info) && info.BizObj.IsValidationEnabled(info))
			{
				ValidateProperty(info, delegate()
				{
					ZValidation validationObject = (info.BizObj == this.Parent) ? this : info.BizObj.ValidationInternal; // This is for wrapped properties.
					ValidationMethodsRunner validationMethodRunner = new ValidationMethodsRunner(validationObject, info, false);
					validationMethodRunner.RunValidationMethod();
					return validationMethodRunner;
				});
			}
		}

		delegate ValidationMethodsRunner RunValidationMethodsDelegate();

		bool IsLargeAndNotLoaded(ZPropertyInfo info)
		{
			if (Parent.Table != null && !string.IsNullOrEmpty(Parent.Table.TableName))
			{
				SchemaColumn column = ObjectFactory.Get<IApplicationSchemaResolver>().GetSchemaColumnSafe(info.Name, Parent.Table.TableName);
				var row = info.BizObj.Row;
				if (column != null && row != null && column.IsLargeBinaryOrText && LazyLoading.LoadRequired(row[info.Name]))
				{
					return true;
				}
			}
			return false;
		}

		/// <summary>
		/// Before calling this method check if required by calling Info.BizObj.IsFieldUsed(Info.Name))
		/// </summary>
		/// <param name="info"></param>
		/// <param name="runValidationMethods"></param>
		void ValidateProperty(ZPropertyInfo info, RunValidationMethodsDelegate runValidationMethods)
		{
			if (!Parent.IsValidationSuspended && !info.HasValidationBeenRun && !Parent.IsNull)
			{
				if (IsLargeAndNotLoaded(info))
				{
					return;
				}

				var factory = info.BizObj.Factory;
				factory?.BeginValidation(info);
				info.SetValidationHasBeenRun();

#if DEBUG
				bool validationSuspendCountBefore = Parent.IsValidationSuspended;
				Parent.AddInfoForValidation(info);
#endif

				try
				{
					var previousNotifications = NotificationCollection.Empty;

					try
					{
						ValidateProperty(info, runValidationMethods, factory, ref previousNotifications);
					}
					finally
					{
						factory?.EndValidation(info);
						var notificationsHaveChanged = !info.Notifications.HasSameNotificationsIgnoringOrder(previousNotifications);
						if (!Parent.IsListChangeSuspended && (notificationsHaveChanged || NotificationsChangedDeferred))
						{
							Parent.OnNotificationsChanged(true);
							NotificationsChangedDeferred = false;
						}
						else if (Parent.IsListChangeSuspended && notificationsHaveChanged)
						{
							NotificationsChangedDeferred = true;
						}
					}
				}
				catch (NullReferenceException ex)
				{
					throw new NullReferenceException($@"{ex.Message}
Parent is null: {Parent == null}
Info cannot be null at this point.
Info.Notifications is null: {info.Notifications == null}
Info.BizObj is null: {info.BizObj == null}
factory is null: {factory == null}
factory.Validation is null: {factory?.Validation == null}
ParentListInternals is null: {ParentListInternals == null}
runValidationMethods is null: {runValidationMethods == null}
Info.Value: {info.Value?.ToString() ?? ""}
Info.Name: {info.Name ?? ""}
Info.BizObj.Type: {info.BizObj?.GetType().FullName ?? ""}", ex);
				}
				finally
				{
#if DEBUG
					Parent?.RemoveInfoForValidation(info);
#endif
				}
			}
		}

		void ValidateProperty(ZPropertyInfo info, RunValidationMethodsDelegate runValidationMethods, BusinessObjectFactory factory, ref IEnumerable<INotification> previousNotifications)
		{
			using (ParentListInternals.SuspendListChanged())
			{
				if (info.HasNotifications())
				{
					previousNotifications = new NotificationCollection(info.Notifications);
					ClearAllNotifications(info);
				}

				if (factory == null || !factory.HasDomainValidation || factory.Validation.NotifyValidationRequested(info))
				{
					ValidationMethodsRunner runner = runValidationMethods() ?? throw new InvalidOperationException("Null ValidationMethodsRunner object returned by runValidationMethods().");
					info.RunAdditionalValidation();
					RunCharacterSetValidation(info);
					RunAdditionalValidationOnValidationObject(info);
					runner.RunValidationMethodsOnAdditionalValidationObjects();
				}
			}
		}

		void ClearAllNotifications(ZPropertyInfo info)
		{
#if DEBUG
			Parent.PropertyInfoCurrentlyClearing = info;
			try
			{
#endif
				info.ClearAllNotifications();
#if DEBUG
			}
			finally
			{
				Parent.PropertyInfoCurrentlyClearing = null;
			}
#endif
		}

		void RunCharacterSetValidation(ZPropertyInfo info)
		{
			if (info.BizObj is ICharacterSetValidationSupport && info.PropertyType == typeof(ZString))
			{
				((ICharacterSetValidationSupport)info.BizObj).ValidateCharacterSet(info);
			}
		}

		protected virtual void RunAdditionalValidationOnValidationObject(ZPropertyInfo propertyInfo)
		{
		}

		bool NotificationsChangedDeferred;

		#endregion

		#region IValidationInternals Members

		void IValidationInternals.Validate(ZPropertyInfo info, RunValidationInvoker runValidationInvoker)
		{
			using (PerformanceStatisticsCollector.StartMonitoring("ValidateProperty", info.Name))
			{
				ValidateAutoGeneratedProperty(info, runValidationInvoker);
			}
		}

		void IValidationInternals.Add(ZValidation validation)
		{
			Type validationType = validation.GetType();

			if (!PiggybackedValidations.Contains(validationType))
			{
				if (Parent != validation.Parent)
				{
					throw new ArgumentException("Validation object being passed in has a different parent to the current validation object");
				}
				PiggybackedValidations.Add(validationType, validation);
			}
		}

		void IValidationInternals.Remove(ZValidation validation)
		{
			Type validationType = validation.GetType();

			if (PiggybackedValidations.Contains(validationType))
			{
				PiggybackedValidations.Remove(validationType);
			}
		}

		HybridDictionary PiggybackedValidations
		{
			get
			{
				if (fPiggybackedValidations == null)
				{
					fPiggybackedValidations = new HybridDictionary();
				}
				return fPiggybackedValidations;
			}
		}

		internal ReadOnlyCollection<ZValidation> DomainValidations
		{
			get
			{
				if (fDomainValidations == null)
				{
					fDomainValidations = CreateDomainValidations();
				}
				return fDomainValidations;
			}
		}

		internal ReadOnlyCollection<ZValidation> CreateDomainValidations()
		{
			List<ZValidation> result = new List<ZValidation>();

			if (Parent.Factory != null && Parent.Factory.HasDomainValidation)
			{
				foreach (DomainValidationGroup validationGroup in Parent.Factory.Validation.AllValidationGroups)
				{
					foreach (ZValidation domainValidation in validationGroup.CreateDomainValidation(Parent))
					{
						Type domainValidationType = domainValidation.GetType();
						if (!result.Exists(delegate(ZValidation match)
						{ return match.GetType() == domainValidationType; }))
						{
							result.Add(domainValidation);
						}
					}
				}
			}

			return result.AsReadOnly();
		}

		HybridDictionary fPiggybackedValidations;
		ReadOnlyCollection<ZValidation> fDomainValidations;

		#endregion

		#region Implementation

		protected BusinessObject ParentFilter
		{
			get { return Parent; }
		}
		readonly BusinessObject Parent;
		readonly ISingleElementListInternal ParentListInternals;
		readonly IValidationInternals ZValidationInternals;
		readonly ZGlowValidation glowValidation;
#if DEBUG
		internal IValidationInternals GetIValidationInternals()
		{
			return ZValidationInternals;
		}
#endif

		#endregion

		#region class ValidationMethodsRunner

		class ValidationMethodsRunner
		{
			public ValidationMethodsRunner(ZValidation zValidation, ZPropertyInfo info, bool useBaseTypeOnValidationObject)
			{
				this.ZValidation = zValidation;
				this.Info = info;
				this.UseBaseTypeOnValidationObject = useBaseTypeOnValidationObject;
			}

			public void RunValidationMethodsOnAdditionalValidationObjects()
			{
				if (ZValidation.Parent.Factory != null && ZValidation.Parent.Factory.HasDomainValidation)
				{
					foreach (ZValidation domainValidation in ZValidation.DomainValidations)
					{
						InvokeValidationMethod(domainValidation);
						RunValidationMethodOnPiggybackedValidationObjects(domainValidation);
					}
				}
				RunValidationMethodOnPiggybackedValidationObjects(ZValidation);
			}

			public void RunValidationMethod()
			{
				InvokeValidationMethod(ZValidation);
			}

			void RunValidationMethodOnPiggybackedValidationObjects(ZValidation zValidation)
			{
				foreach (ZValidation piggybackedValidation in zValidation.PiggybackedValidations.Values)
				{
					InvokeValidationMethod(piggybackedValidation);
					RunValidationMethodOnPiggybackedValidationObjects(piggybackedValidation);
				}
			}

			void InvokeValidationMethod(ZValidation zValidation)
			{
				MethodInfo validationMethod = GetValidationMethod(zValidation);
				if (validationMethod != null)
				{
					validationMethod.Invoke(zValidation, null);
				}
			}

			MethodInfo GetValidationMethod(ZValidation validation)
			{
				KPropertyDescriptor property = (KPropertyDescriptor)Info.PropertyDescriptor;
				Type validationType = UseBaseTypeOnValidationObject ? validation.AutoValidationType : validation.GetType();

				string methodName = (NoResString)"Check" + Info.Name;
				string key = validationType.FullName + "." + methodName;
				MethodInfo result = property.UserData[key] as MethodInfo;

				if (result == null)
				{
					result = validationType.GetMethod(methodName, BindingFlags.NonPublic | BindingFlags.Instance);
					property.UserData[key] = result;
				}
				return result;
			}

			readonly ZValidation ZValidation;
			readonly ZPropertyInfo Info;
			readonly bool UseBaseTypeOnValidationObject;
		}

		#endregion
	}
}

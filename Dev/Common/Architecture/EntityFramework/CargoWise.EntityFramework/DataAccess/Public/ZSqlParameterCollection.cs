using System;
using System.Collections;
using System.Collections.Generic;
using CargoWise.Schema;

namespace CargoWise.EntityFramework
{
	[Serializable]
	public class DuplicateParameterArgumentException : ArgumentException
	{
		public DuplicateParameterArgumentException(string message) : base(message) { }
		public DuplicateParameterArgumentException(string message, Exception innerException) : base(message, innerException) { }

#if NETFRAMEWORK
		protected DuplicateParameterArgumentException(System.Runtime.Serialization.SerializationInfo info, System.Runtime.Serialization.StreamingContext context)
			: base(info, context)
		{ }
#endif
	}

	public class ZSqlParameterCollection : IEnumerable
	{
		public ZSqlParameterCollection()
		{
		}

		public ZSqlParameterCollection(params ZSqlParameter[] parameters)
		{
			AddRange(parameters);
		}

		public ZSqlParameterCollection(ZSqlParameterCollection parameters)
		{
			AddRange(parameters);
		}

		public ZSqlParameter this[string fieldName]
		{
			get { return List[GetIndexFromFieldName(fieldName)]; }
		}

		public ZSqlParameter this[int index]
		{
			get { return List[index]; }
		}

		#region Add Items

		public void Add(ZSqlParameter parameter)
		{
			bool containsKey = AlreadyAddedParamsHashByName.ContainsKey(parameter.ParameterName);

			if ((parameter.IsAutoGeneratedParameter || containsKey) && List.Contains(parameter))
			{
				return;
			}

			if (!parameter.IsAutoGeneratedParameter)
			{
				if (containsKey)
				{
					throw new DuplicateParameterArgumentException("The collection already contains a parameter with the name of " + parameter.ParameterName + ".");
				}
				else
				{
					AlreadyAddedParamsHashByName[parameter.ParameterName] = parameter;
				}
			}

			List.Add(parameter);
		}

		Dictionary<string, ZSqlParameter> AlreadyAddedParamsHashByName
		{
			get
			{
				if (alreadyAddedParamsHashByName == null)
				{
					alreadyAddedParamsHashByName = new Dictionary<string, ZSqlParameter>();
				}
				return alreadyAddedParamsHashByName;
			}
		}
		Dictionary<string, ZSqlParameter> alreadyAddedParamsHashByName;

		public ZSqlParameter Add(string parameterName, object value, SchemaColumn schemaColumn)
		{
			var parameter = ZSqlParameter.New(parameterName, value, schemaColumn);
			Add(parameter);
			return parameter;
		}

		public void AddRange(params ZSqlParameter[] parameters)
		{
			if (parameters != null)
			{
				for (int i = 0; i < parameters.Length; i++)
				{
					Add(parameters[i]);
				}
			}
		}

		public void AddRange(ZSqlParameterCollection parameterCollection)
		{
			for (int i = 0; i < parameterCollection.Count; i++)
			{
				Add(parameterCollection.List[i]);
			}
		}

		#endregion

		public bool Contains(ZSqlParameter parameter)
		{
			return List.Contains(parameter);
		}

		public bool ContainsKey(string key)
		{
			return AlreadyAddedParamsHashByName.ContainsKey(key);
		}

		public void Clear()
		{
			List.Clear();
			AlreadyAddedParamsHashByName.Clear();
		}

		public void CopyTo(ZSqlParameter[] array, int index)
		{
			this.List.CopyTo(array, index);
		}

		public ZSqlParameter[] ToArray()
		{
			ZSqlParameter[] array = new ZSqlParameter[Count];
			CopyTo(array, 0);

			return array;
		}

		public void Remove(ZSqlParameter value)
		{
			if (value.ParameterName.Length > 0)
			{
				AlreadyAddedParamsHashByName[value.ParameterName] = null;
			}
			List.Remove(value);
		}

		public void Remove(string fieldName)
		{
			AlreadyAddedParamsHashByName[fieldName] = null;
			List.RemoveAt(GetIndexFromFieldName(fieldName));
		}

		public int Count
		{
			get { return (list == null) ? 0 : list.Count; }
		}

		IEnumerator IEnumerable.GetEnumerator()
		{
			return List.GetEnumerator();
		}

		int GetIndexFromFieldName(string fieldName)
		{
			for (int i = 0; i < List.Count; i++)
			{
				if (List[i].ParameterName == fieldName)
				{
					return i;
				}
			}
			throw new ArgumentException("There is no parameter for field: " + fieldName, nameof(fieldName));
		}

		List<ZSqlParameter> List
		{
			get
			{
				if (list == null)
				{
					list = new List<ZSqlParameter>();
				}
				return list;
			}
		}
		List<ZSqlParameter> list;
	}
}

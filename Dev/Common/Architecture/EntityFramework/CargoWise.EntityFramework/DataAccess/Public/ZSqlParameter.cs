		public string LiteralTextADO
		{
			get
			{
				if (fLiteralTextADO == null || SchemaColumn.IsNonPersistent)
				{
					var builder = new SqlBuilder();
					GetAndCacheLiteralText(builder);
					fLiteralTextADO = builder.ToString();
				}
				return fLiteralTextADO;
			}
		}
		string fLiteralTextADO;

		void GetAndCacheLiteralText(SqlBuilder sqlBuilder)
		{
			if (suspendedCount > 0)
			{
				return;
			}
			else if (fLiteralTextADO == null || SchemaColumn.IsNonPersistent)
			{
				string comparisonText = ComparisonOperator.ComparisonText(fRawValue);

				if (comparisonText.Length > 0)
				{
					AddNameForNonPersistentColumn(sqlBuilder, SchemaColumn, false);
					sqlBuilder.Append(" ").Append(comparisonText).Append(" ");
					AddParameterValueTextADO(sqlBuilder);
					// We could grab the last peice of text added here to set fLiteralTextADO with, but profiling shows that this is not worth it.
				}
				else
				{
					fLiteralTextADO = string.Empty;
				}
			}
			else
			{
				sqlBuilder.Append(fLiteralTextADO);
			}
		}

		void IFilterPart.AddLiteralTextADO(SqlBuilder sqlBuilder)
		{
			GetAndCacheLiteralText(sqlBuilder);
		}


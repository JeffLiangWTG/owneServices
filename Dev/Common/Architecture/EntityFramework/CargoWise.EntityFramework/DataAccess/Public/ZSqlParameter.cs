		public string ParameterValueTextSql
		{
			get
			{
				var builder = new SqlBuilder();
				if (IsTableValued)
				{
					AddParameterList(builder, true);
				}
				else if (SchemaColumn is SchemaBoolColumn boolColumn && boolColumn.IsBitField)
				{
					builder.Append(Value.ToString());
				}
				else if (Value is ZBool || Value is bool)
				{
					builder.Append((bool)Value ? (NoResString)"'Y'" : (NoResString)"'N'");
				}
				else if (SchemaColumn is SchemaBinaryColumn && (Value is ZBlob || Value is byte[]))
				{
					AsHexString(builder, new ZBlob(Value));
				}
				else
				{
					AddParameterValueText(builder, Value, DateDelimiterForSql, ComparisonOperator.EscapedSqlValue, true);
				}
				return builder.ToString();
			}
		}

		void AddParameterList(SqlBuilder sqlBuilder, bool forSql)
		{
			var collection = (IEnumerable)Value;
			collection.Cast<object>().ForEachWithBetween(val => AddParameterValueText(sqlBuilder, val, DateDelimiterForSql, ComparisonOperator.EscapedSqlValue, forSql), () => sqlBuilder.Append(", "));
		}

		void AsHexString(SqlBuilder sqlBuilder, byte[] bytes)
		{
			sqlBuilder.Append((NoResString)"0x");
			foreach (var b in bytes)
			{
				sqlBuilder.Append(b.ToString("X2", CultureInfo.InvariantCulture));
			}
		}


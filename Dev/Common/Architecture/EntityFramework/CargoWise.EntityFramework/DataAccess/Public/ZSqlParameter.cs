		void AddParameterValueText(SqlBuilder sqlBuilder, object value, char dateDelimiter, Func<object, object> comparisonOperatorValueForDelegate, bool forSql)
		{
			if (SQLComparisonOperator.ValueIsNull(fRawValue))
			{
				sqlBuilder.Append("null");
			}
			else if (value is Decimal)
			{
				sqlBuilder.Append(((decimal)value).ToString(System.Globalization.CultureInfo.InvariantCulture));
			}
			else if (value is int)
			{
				sqlBuilder.Append(((int)value).ToString(System.Globalization.CultureInfo.InvariantCulture));
			}
			else if (value is short)
			{
				sqlBuilder.Append(((short)value).ToString(System.Globalization.CultureInfo.InvariantCulture));
			}
			else if (value is bool)
			{
				sqlBuilder.Append((bool)value ? "1" : "0");
			}
			else if (value is Guid)
			{
				EncloseInGuid(sqlBuilder, (Guid)comparisonOperatorValueForDelegate(value), forSql);
			}
			else if (value is ZGuid zguid && zguid.IsValid)
			{
				EncloseInGuid(sqlBuilder, (Guid)comparisonOperatorValueForDelegate(zguid.ToGuid()), forSql);
			}
			else if (value is ZBlob || value is byte[])
			{
				AsHexString(sqlBuilder, new ZBlob(value));
			}
			else
			{
				EncloseInQuotes(sqlBuilder, dateDelimiter, comparisonOperatorValueForDelegate(value), forSql);
			}
		}

		[SuppressMessage("Microsoft.Performance", "CA1800:DoNotCastUnnecessarily")]
		public object ValueForSql
		{
			get
			{
				if (SQLComparisonOperator.ValueIsNull(fRawValue))
				{
					return DBNull.Value;
				}

				object result = Value;
				SchemaDecimalColumn decimalColumn = SchemaColumn as SchemaDecimalColumn;
				if (decimalColumn != null && decimalColumn.Scale == 0)
				{
					// HACK: Fix .NET bug in SqlParameter that does not respect Scale = 0. Tested in BizO factory.
					result = Decimal.Truncate((Decimal)result);
				}
				if (result is bool)
				{
					result = (bool)result ? "Y" : "N";
				}
				if (result is SqlGeography geo)
				{
					return geo.AsTextZM().ToSqlString().ToString();
				}
				return ComparisonOperator.EscapedSqlValue(result);
			}
		}

		public string GetSqlParameterSuffix(DateTime factoryCreateTime)
		{
			IComparable value;
			if (IsTableValued && ValueForSql is IEnumerable enumerable)
			{
				var elementCount = enumerable.Cast<object>().Count();
				var tvpRule = ObjectFactory.Get<IEntityFrameworkSettings>().TVPRule;
				if (tvpRule.ShouldUseTVP(elementCount))
				{
					return (NoResString)"Bucket:" + tvpRule.BucketNumber(elementCount);
				}
			}
			return (IsNotSupportedForSuffixing() || (value = ValueForSql as IComparable) == null)
				? ""
				: ParameterSuffixer.Instance.GetParameterSuffix(factoryCreateTime, SchemaColumn, value);
		}

		bool IsNotSupportedForSuffixing()
		{
			return
				IsTableValued
				|| SchemaColumn.SqlDbType == SqlDbType.VarBinary && SchemaColumn.IsLargeBinaryOrText; // varbinary(max)
		}


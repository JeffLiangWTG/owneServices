		void AddNameForNonPersistentColumn(SqlBuilder sqlBuilder, SchemaColumn schemaColumn, bool forSql)
		{
			if (schemaColumn.IsNonPersistent)
			{
				BusinessObject mainElement;
				if (MainElement == null || !MainElement.TryGetTarget(out mainElement))
				{
					throw new InvalidOperationException("Cannot use non-persistent column " + schemaColumn.Name + " without specifying main element to filter against.");
				}

				var dateDelimiter = forSql ? DateDelimiterForSql : DateDelimiterForAdo;
				var comparisonOperatorValueForDelegate = forSql ? ComparisonOperator.EscapedSqlValue : (Func<object, object>)ComparisonOperator.ValueForLiteralADO;
				var mainElementValue = GetTruncatedBasicValueForDatabase(mainElement[schemaColumn.Name], schemaColumn);

				AddParameterValueText(sqlBuilder, mainElementValue, dateDelimiter, comparisonOperatorValueForDelegate, forSql);
			}
			else if (schemaColumn.ColumnType == SchemaColumnType.DateTimeOffset && !forSql)
			{
				//From https://social.msdn.microsoft.com/Forums/en-US/2f1a8b79-57e4-4c29-94dd-7d3a0dd18fc8/rowfilter-string-for-a-datetimeoffset-value?forum=adodotnetdataset
				//ADO does not support DateTimeOffset. DateTimeOffset->String->DateTime treats it as UTC, then converts it to system time zone.
				//But if we do this to both sides, then we are effectively comparing UTCs.
				sqlBuilder.Append("CONVERT(CONVERT(").Append(schemaColumn.Name).Append((NoResString)", System.String), System.DateTime)");
			}
			else if (schemaColumn.ColumnType == SchemaColumnType.Time && !forSql)
			{
				//ADO does not properly support TimeSpan. TimeSpan->String->DateTime on both sides.
				// CONVERT(<timespan>, System.String) puts the result in XML time format like this:
				// PT1H2M, which doesn't have lexographic ordering.
				// Other things you can't do that would render this abomination unnecessary:
				// Compare TimeSpans with other TimeSpans.
				// Add TimeSpans to DateTimes.
				// Convert TimeSpan's string output to DateTime.
				// Extract components out of a TimeSpan in a sensible way.
				// Convert to an integer (i.e. total seconds/minutes).
				var strExpr = $"CONVERT({schemaColumn.Name}, System.String)";
				var hourShort = $"SUBSTRING({strExpr}, 3, 1)";
				var hourLong = $"SUBSTRING({strExpr}, 3, 2)";
				var minuteShortEarly = $"SUBSTRING({strExpr}, 5, 1)";
				var minuteLongEarly = $"SUBSTRING({strExpr}, 5, 2)";
				var minuteShortLate = $"SUBSTRING({strExpr}, 6, 1)";
				var minuteLongLate = $"SUBSTRING({strExpr}, 6, 2)";
				var dateShortEarly = $"CONVERT({hourShort}+':'+{minuteShortEarly}, System.DateTime)";
				var dateLongEarly = $"CONVERT({hourShort}+':'+{minuteLongEarly}, System.DateTime)";
				var dateShortLate = $"CONVERT({hourLong}+':'+{minuteShortLate}, System.DateTime)";
				var dateLongLate = $"CONVERT({hourLong}+':'+{minuteLongLate}, System.DateTime)";
				var trueExpr = $"IIF(SUBSTRING({strExpr}, 6, 1) = 'M', {dateShortEarly}, {dateLongEarly})";
				var falseExpr = $"IIF(SUBSTRING({strExpr}, 7, 1) = 'M', {dateShortLate}, {dateLongLate})";
				sqlBuilder.Append($"IIF(SUBSTRING({strExpr}, 4, 1) = 'H', {trueExpr}, {falseExpr})");
			}
			else if (schemaColumn.ColumnType == SchemaColumnType.Geography && !SQLComparisonOperator.ValueIsNull(fRawValue))
			{
				if (!forSql)
				{
					//ADO doesn't support Z0_Geography.STAsText() or Z0_Geography.AsText().
					sqlBuilder.Append("CONVERT(").Append(schemaColumn.Name).Append((NoResString)", System.String)");
				}
				else
				{
					//geography and string cannot be compared directly.
					sqlBuilder.Append(schemaColumn.Name).Append(".STAsText()");
				}
			}
			else
			{
				sqlBuilder.Append(schemaColumn.Name);
			}
		}

		WeakReference<BusinessObject> MainElement { get; set; }


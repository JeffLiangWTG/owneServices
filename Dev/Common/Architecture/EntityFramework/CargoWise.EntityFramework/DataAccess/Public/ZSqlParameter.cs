		public void AddParameterisedSql(SqlBuilder sqlBuilder)
		{
			if (IsAutoGeneratedParameter && !SQLComparisonOperator.ValueIsNull(fRawValue) && sqlBuilder.NameFactory != null)
			{
				var newParameterName = GetParameterName(sqlBuilder.NameFactory);
				CheckValidParameterName(newParameterName);
				parameterName = newParameterName;
			}

			MaybeWrapWithNotEmptyCheck(sqlBuilder, () =>
			{
				if (!IsLiteralOnly && ComparisonOperator == SQLComparisonOperator.StartsWith && SchemaColumn.SqlDbType.In(SqlDbType.Char, SqlDbType.VarChar) && !string.IsNullOrEmpty(Value.ToString()))
				{
					sqlBuilder.Append("(");
					AddParameterisedText(sqlBuilder);
					var greaterThan = ZSqlParameter.New(sqlBuilder.NameFactory, Value, SchemaColumn, SQLComparisonOperator.GreaterThanOrEqualTo, ComparisonOptions.Default);
					sqlBuilder.Append(" AND ");
					greaterThan.AddParameterisedText(sqlBuilder);

					var topBound = DataUtils.GetBetweenEndExpressionForQueryUsingLikeWithFilteredIndex(Value.ToString(), (SchemaStringColumn)SchemaColumn);
					var lessThan = ZSqlParameter.New(sqlBuilder.NameFactory, topBound, SchemaColumn, SQLComparisonOperator.LessThanOrEqualTo, ComparisonOptions.Default);
					sqlBuilder.Append(" AND ");
					lessThan.AddParameterisedText(sqlBuilder);
					sqlBuilder.Append(")");
				}
				else
				{
					AddParameterisedText(sqlBuilder);
				}
			});

#if DEBUG
			OnParameterisedSqlAdded?.Invoke();
#endif
		}

		void MaybeWrapWithNotEmptyCheck(SqlBuilder sqlBuilder, Action buildSql)
		{
			if (NeedNotEmptyCheck)
			{
				sqlBuilder.Append("(");
				buildSql();
				sqlBuilder.Append(" AND ").Append(SchemaColumn.Name).Append(" <> '')");
			}
			else
			{
				buildSql();
			}
		}


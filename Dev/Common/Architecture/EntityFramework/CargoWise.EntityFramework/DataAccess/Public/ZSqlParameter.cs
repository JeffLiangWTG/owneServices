		ZSqlParameter(string parameterName, object value, SchemaColumn schemaColumn, SQLComparisonOperator comparisonOperator, ComparisonOptions options, bool isTableValued)
		{
			Argument.NotNull(schemaColumn, nameof(schemaColumn));

			if (schemaColumn.IsSparse && !(value is IZType))
			{
				var zEmptyValue = ZDataType.ZTypeToEmptyValue(schemaColumn.GetEquivalentZType());
				if (zEmptyValue.Equals(value))
				{
					value = zEmptyValue;
				}
			}

			if (value is ZDateTime zDateTime && !zDateTime.IsEmpty && !zDateTime.IsValidSqlDateTime)
			{
				throw new ArgumentException(ZString.Format("See WI00114690 for details. ParameterName='{0}', SchemaColumn='{1}', Value='{2:O} ({3})'", parameterName, schemaColumn.Name, value, zDateTime.Kind));
			}

			if (value is IZTypeInternals zValueInternal)
			{
				var internalValue = zValueInternal.GetValueForLogicalDataLayer(schemaColumn.IsNullable);
				CheckArguments(parameterName, schemaColumn, comparisonOperator, internalValue);
			}
			else
			{
				CheckArguments(parameterName, schemaColumn, comparisonOperator, value);
			}

			this.IsTableValued = isTableValued;

			IsAutoGeneratedParameter = parameterName.Length == 0;
			this.parameterName = parameterName;
			SchemaColumn = schemaColumn;
			fRawValue = schemaColumn.IsSparse && value is IZType
				? ((IZTypeInternals)value).GetValueForLogicalDataLayer(true)
				: value;
			Value = GetTruncatedBasicValueForDatabase(value, schemaColumn, isTableValued);
			ComparisonOperator = comparisonOperator;
			ComparisonOptions = options;
			if (comparisonOperator.In(SQLComparisonOperator.StartsWith, SQLComparisonOperator.EndsWith, SQLComparisonOperator.Contains) && (fRawValue is string || fRawValue is ZString))
			{
				var rawLength = fRawValue.ToString().Length;
				if (rawLength == schemaColumn.MaxLength)
				{
					ComparisonOperator = SQLComparisonOperator.Equal;
				}
				else if (rawLength > schemaColumn.MaxLength && schemaColumn.MaxLength > 0)
				{
					ErrorReporter.ReportOnce("FieldMaxLengthExceeded_" + schemaColumn.Name, "Field maximum length exceeded on " + schemaColumn.Name + ", Value = '" + fRawValue.ToString() + "'");
				}
			}
		}


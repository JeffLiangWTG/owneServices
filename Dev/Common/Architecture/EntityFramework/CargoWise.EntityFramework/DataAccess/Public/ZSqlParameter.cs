		void AddColumnNameModifiedForSpecialCases(SqlBuilder sqlBuilder, SchemaColumn schemaColumn, object paramValue)
		{
			bool IsParamValueNull() => paramValue is DBNull || paramValue is null;

			if (schemaColumn.ColumnType == SchemaColumnType.Xml && !(schemaColumn.IsSparse && IsParamValueNull()))
			{
				sqlBuilder.Append("cast(").Append(schemaColumn.Name).Append((NoResString)" as nvarchar(max))");
			}
			else if (schemaColumn.ColumnType == SchemaColumnType.Binary && !(schemaColumn.IsSparse && IsParamValueNull()) && (paramValue is string || paramValue is ZString))
			{
				sqlBuilder.Append("dbo.CLRUncompressAsString(").Append(schemaColumn.Name).Append(")");
			}
			else
			{
				AddNameForNonPersistentColumn(sqlBuilder, schemaColumn, true);
			}
		}


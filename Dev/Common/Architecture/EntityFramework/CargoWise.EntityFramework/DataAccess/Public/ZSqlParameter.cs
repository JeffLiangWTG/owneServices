		bool Equals(object obj, bool ignoreParameterName)
		{
			switch (obj)
			{
				case ZSqlParameter param:
					return
						(ignoreParameterName || param.ParameterName == ParameterName)
						&& param.SchemaColumn.Equals(SchemaColumn)
						&& param.Value.Equals(Value);
				case SqlParameter param:
					return
						(ignoreParameterName || param.ParameterName == ParameterName)
						&& param.SqlDbType.Equals(SchemaColumn.SqlDbType)
						&& param.Value.Equals(Value);
			}

			return base.Equals(obj);
		}


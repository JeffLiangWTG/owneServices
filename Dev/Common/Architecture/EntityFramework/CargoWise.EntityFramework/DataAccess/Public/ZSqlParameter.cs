	public static class DbCommandExtensions
	{
		public static void AddParameter(this DbCommand command, ZSqlParameter parameter)
		{
			if (parameter.IsTableValued)
			{
				command.AddTableValuedParameter(parameter.ParameterName, parameter.SchemaColumn, (IEnumerable)parameter.ValueAdjustedForComparison);
			}
			else
			{
				command.AddParameterBasedOnDbColumn(parameter.ParameterName, parameter.ValueAdjustedForComparison, parameter.SchemaColumn);
			}
		}

		public static void AddParameters(this DbCommand command, ZSqlParameter[] parameters)
		{
			foreach (var param in parameters)
			{
				AddParameter(command, param);
			}
		}

		public static void AddParameters(this DbCommand command, ZSqlParameterCollection parameters)
		{
			foreach (ZSqlParameter param in parameters)
			{
				AddParameter(command, param);
			}
		}
	}

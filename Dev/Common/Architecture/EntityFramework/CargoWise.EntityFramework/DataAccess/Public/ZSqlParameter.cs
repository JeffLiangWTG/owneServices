		void EncloseInGuid(SqlBuilder sqlBuilder, Guid valueToQuote, bool forSql)
		{
			if (forSql)
			{
				sqlBuilder.Append(valueToQuote.ToSqlGuid());
			}
			else
			{
				sqlBuilder.Append("CONVERT('").Append(valueToQuote.ToString()).Append("', '").Append(GuidName).Append("')");
			}
		}
		readonly static string GuidName = typeof(Guid).FullName; // Because reflection is expensive.

		[SuppressMessage("Microsoft.Performance", "CA1800:DoNotCastUnnecessarily")]
		void EncloseInQuotes(SqlBuilder result, char dateDelimiter, object valueToQuote, bool forSql)
		{
			string stringisedData;
			char quoteCharacter;
			if (valueToQuote is ZDateTime)
			{
				quoteCharacter = dateDelimiter;
				stringisedData = ((ZDateTime)valueToQuote).SqlFormat;
			}
			else if (valueToQuote is DateTime || valueToQuote is ZDate)
			{
				quoteCharacter = dateDelimiter;
				stringisedData = new ZDateTime(valueToQuote).SqlFormat;
			}
			else if (valueToQuote is ZTime timeToQuote)
			{
				quoteCharacter = dateDelimiter;
				stringisedData = timeToQuote.SqlFormat;
			}
			else if (valueToQuote is TimeSpan timeSpanToQuote)
			{
				quoteCharacter = dateDelimiter;
				stringisedData = new ZTime(timeSpanToQuote).SqlFormat;
			}
			else if (valueToQuote is ZDateTimeOffset)
			{
				quoteCharacter = dateDelimiter;
				stringisedData = ((ZDateTimeOffset)valueToQuote).SqlFormat;
			}
			else if (valueToQuote is DateTimeOffset)
			{
				quoteCharacter = dateDelimiter;
				stringisedData = new ZDateTimeOffset(valueToQuote).SqlFormat;
			}
			else if (valueToQuote is SqlGeography geo)
			{
				quoteCharacter = '\'';
				stringisedData = geo.AsTextZM().ToSqlString().ToString();
			}
			else if (valueToQuote is ZGeography zgeo)
			{
				quoteCharacter = '\'';
				stringisedData = zgeo.AsText();
			}
			else
			{
				quoteCharacter = '\'';
				stringisedData = CargoWise.Data.DataUtils.EscapeSingleQuotes(valueToQuote.ToString());
			}

			if ((ComparisonOptions.HasFlag(ComparisonOptions.NationalLanguage) || SchemaColumn.IsUnicode) && forSql)
			{
				result.Append('N');
			}
			result.Append(quoteCharacter);
			result.Append(stringisedData);
			result.Append(quoteCharacter);
		}

		internal object ValueForPredicate
		{
			get
			{
				var value = Value;
				var boolColumn = SchemaColumn as SchemaBoolColumn;
				if (boolColumn != null && boolColumn.IsBitField && value is int)
				{
					value = (int)value == 1;
				}
				return value;
			}
		}

		public Func<object, bool> GetPredicate()
		{
			var value = ValueForPredicate;
			var valueType = value.GetType();
			var predicate = ComparisonOperator.GetPredicate(value);
			var converter = TypeDescriptor.GetConverter(valueType);
			return o => predicate(converter.ConvertFrom(o));
		}


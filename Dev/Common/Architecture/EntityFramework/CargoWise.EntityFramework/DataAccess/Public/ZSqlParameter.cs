		}

		internal void AddParameterisedText(SqlBuilder sqlBuilder)
		{
			AddColumnNameModifiedForSpecialCases(sqlBuilder, SchemaColumn, fRawValue);
			sqlBuilder.Append(" " + ComparisonOperator.ComparisonText(fRawValue) + " ");

			if (SQLComparisonOperator.ValueIsNull(fRawValue))
			{
				sqlBuilder.Append("NULL");
			}
			else
			{
				sqlBuilder.AppendParameter(this);

				if (ValueForSql != Value)
				{
					var escapeCharacter = ComparisonOperator.SqlEscapeCharacter;
					if (escapeCharacter.Length > 0 && ValueForSql.ToString().IndexOf(escapeCharacter, StringComparison.OrdinalIgnoreCase) > -1)
					{
						sqlBuilder.Append(" " + ComparisonOperator.SqlEscapeClause);
					}
				}
			}
		}

		public bool NeedNotEmptyCheck
		{
			get
			{
				return !IsLiteralOnly
					&& (SchemaColumn is SchemaStringColumn stringSchemaColumn) && stringSchemaColumn.IsNonBlankFilteredIndexParticipant
					&& ComparisonOperator.In
					(
						SQLComparisonOperator.Equal,
						SQLComparisonOperator.GreaterThan,
						SQLComparisonOperator.GreaterThanOrEqualTo,
						SQLComparisonOperator.Contains,
						SQLComparisonOperator.Like,
						SQLComparisonOperator.StartsWith,
						SQLComparisonOperator.EndsWith
					)
					&& !string.IsNullOrEmpty(fRawValue.ToString());
			}
		}


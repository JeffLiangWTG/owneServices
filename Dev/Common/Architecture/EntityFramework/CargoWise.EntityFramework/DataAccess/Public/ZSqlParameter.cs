		// check whether two parameters are duplicated
		[Immutable]
		public class DuplicateComparer : IEqualityComparer<ZSqlParameter>
		{
			public static DuplicateComparer Instance { get; } = new DuplicateComparer();

			public static bool Equals(ZSqlParameter x, ZSqlParameter y)
			{
				return x.SchemaColumn.Equals(y.SchemaColumn)
					&& x.ValueAdjustedForComparison.Equals(y.ValueAdjustedForComparison)
					&& x.ComparisonOperator == y.ComparisonOperator;
			}

			public static int GetHashCode(ZSqlParameter obj)
			{
				return obj.SchemaColumn.GetHashCode() ^
					obj.ValueAdjustedForComparison.GetHashCode() ^
					obj.ComparisonOperator.GetHashCode();
			}

			bool IEqualityComparer<ZSqlParameter>.Equals(ZSqlParameter x, ZSqlParameter y) => Equals(x, y);

			int IEqualityComparer<ZSqlParameter>.GetHashCode(ZSqlParameter obj) => GetHashCode(obj);
		}

		static void CheckArguments(string parameterName, SchemaColumn schemaColumn, SQLComparisonOperator comparisonOperator, object parameterValue)
		{
			CheckValidParameterName(parameterName);

			if (schemaColumn == null)
			{
				throw new ArgumentNullException(nameof(schemaColumn), "CheckArguments() - SchemaColumn cannot be null.");
			}

			comparisonOperator.CheckArgumentIsValid(parameterName, parameterValue);

			schemaColumn.CheckCanAcceptValue(parameterValue);
		}

		public static void CheckValidParameterName(string parameterName)
		{
			if (parameterName.Length > 0 && !parameterName.StartsWith("@"))
			{
				throw new ArgumentException("Please use the @ symbol to prefix your parameter name, otherwise SQL server will get confused.");
			}

			if (parameterName.StartsWith("@@"))
			{
				throw new ArgumentException("Please do not use 2 or more @ symbols to prefix your parameter name");
			}
		}


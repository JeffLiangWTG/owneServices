		public IFilterPart DeepClone()
		{
			return ShallowClone();  // Immutable objects can be shallow or deep cloned with same effect
		}

		public ZSqlParameter ShallowClone()
		{
			string newParameterName = IsAutoGeneratedParameter ? "" : ParameterName;
			var cloned = new ZSqlParameter(newParameterName, fRawValue, SchemaColumn, ComparisonOperator, ComparisonOptions, IsTableValued);

#if DEBUG
			cloned.OnParameterisedSqlAdded = OnParameterisedSqlAdded;
#endif

			return cloned;
		}


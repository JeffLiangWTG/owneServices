		[SuppressMessage("CargoWiseOne", "CW1161:ResGetStringAnalyzer", Justification = "Exception message")]
		const string outOfSmallDateTimeErrorString = "Out of range smalldatetime, TableName: {0}, ColumnName: {1}, New value: {2}, smalldatetime range 01-Jan-1900 - 06-Jun-2079";

		[SuppressMessage("Microsoft.Performance", "CA1800:DoNotCastUnnecessarily")]
		public static object GetTruncatedBasicValueForDatabase(object value, SchemaColumn schemaColumn, bool isTableValued = false)
		{
			if (isTableValued && value is ICollection collection)
			{
				var newValues = new List<object>(collection.Count);
				foreach (var item in collection)
				{
					newValues.Add(GetTruncatedBasicValueForDatabase(item, schemaColumn, false));
				}

				return newValues;
			}
			else if (value is IZType)
			{
				if (schemaColumn.IsNullable && SQLComparisonOperator.ValueIsNull(value))
				{
					value = DBNull.Value;
				}
				else
				{
					value = ((IZTypeInternals)value).GetValueForLogicalDataLayer(schemaColumn.IsSparse);
				}
			}

			if (value is ZString zStringValue)
			{
				value = zStringValue.ToString();
			}

			var result = DataUtils.GetBasicValueForDatabase(value, schemaColumn);
			return TruncateIfNecessary(result, schemaColumn);
		}

		[SuppressMessage("Microsoft.Globalization", "CA1305:SpecifyIFormatProvider")]
		internal static object TruncateIfNecessary(object value, SchemaColumn schemaColumn)
		{
			if (value is ZDecimal)
			{
				value = (decimal)value;
			}

			if (value is DateTime full && schemaColumn.SqlDbType == SqlDbType.SmallDateTime)
			{
				if (full < ZDateTime.MinSmallDateTimeValue || full > ZDateTime.MaxSmallDateTimeValue)
				{
					throw new ArgumentOutOfRangeException(message: string.Format(DefaultCulture.Instance, outOfSmallDateTimeErrorString, schemaColumn.TableName, schemaColumn.Name, ((ZDateTime)full).DebuggerDisplay), innerException: null);
				}
			}

			return DataUtils.TruncateIfNecessary(value, schemaColumn);
		}

		public void TestCallingAutoGeneratedValidationMethodWithMultipleLevelPiggybackedValidation()
		{
			Dummy.Factory.Validation.MainGroup.RegisterValidationType<DummyWithValidation, DummyDomainWithMultiLevelPiggybackedValidation>();
			Dummy.ValidationType = typeof(DummyZValidationWithMultiLevelPiggyBacking);

			((INeedRow)Dummy).Row[DummyBizoSchema.Constants.Z0_Decimal] = -12345678901234567890.0M;
			Assert("Precondition", !Dummy.CheckZ0_DecimalFired);
			Assert("Precondition", !Dummy.CheckZ0_DecimalIsValidZDecimalFired);

			Assert("Precondition", !Dummy.CheckZ0_DecimalPiggyBackedFired);
			Assert("Precondition", !Dummy.CheckZ0_DecimalIsValidZDecimalPiggyBackedFired);
			Assert("Precondition", !Dummy.CheckZ0_DecimalMultiLevelPiggyBackedFired);
			Assert("Precondition", !Dummy.CheckZ0_DecimalIsValidZDecimalMultiLevelPiggyBackedFired);

			Assert("Precondition", !Dummy.CheckZ0_DecimalDomainFired);
			Assert("Precondition", !Dummy.CheckZ0_DecimalIsValidZDecimalDomainFired);
			Assert("Precondition", !Dummy.CheckZ0_DecimalDomainWithPiggybackedFired);
			Assert("Precondition", !Dummy.CheckZ0_DecimalIsValidZDecimalDomainWithPiggybackedFired);
			Assert("Precondition", !Dummy.CheckZ0_DecimalDomainWithMultiLevelPiggybackedFired);
			Assert("Precondition", !Dummy.CheckZ0_DecimalIsValidZDecimalDomainWithMultiLevelPiggybackedFired);

			Dummy.Validation.ValidateZ0_Decimal();

			Assert("Should have been called", Dummy.CheckZ0_DecimalMultiLevelPiggyBackedFired);
			Assert("Should have been called", Dummy.CheckZ0_DecimalIsValidZDecimalMultiLevelPiggyBackedFired);

			Assert("Should have been called", Dummy.CheckZ0_DecimalPiggyBackedFired);
			Assert("Should not have been called (already called in the base validation)", !Dummy.CheckZ0_DecimalIsValidZDecimalPiggyBackedFired);

			Assert("Should have been called", Dummy.CheckZ0_DecimalDomainFired);
			Assert("Should not have been called (already called in the base validation)", !Dummy.CheckZ0_DecimalIsValidZDecimalDomainFired);
			Assert("Should have been called", Dummy.CheckZ0_DecimalDomainWithPiggybackedFired);
			Assert("Should not have been called (already called in the base validation)", !Dummy.CheckZ0_DecimalIsValidZDecimalDomainWithPiggybackedFired);
			Assert("Should have been called", Dummy.CheckZ0_DecimalDomainWithMultiLevelPiggybackedFired);
			Assert("Should not have been called (already called in the base validation)", !Dummy.CheckZ0_DecimalIsValidZDecimalDomainWithMultiLevelPiggybackedFired);

			Assert("Should not have been called, ValidationType is DummyZValidationWithMultiLevelPiggyBacking", !Dummy.CheckZ0_DecimalFired);
			Assert("Should not have been called, ValidationType is DummyZValidationWithMultiLevelPiggyBacking", !Dummy.CheckZ0_DecimalIsValidZDecimalFired);

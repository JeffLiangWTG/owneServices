		public void TestCallingAutoGeneratedValidationMethodWithPiggyBackedValidation()
		{
			Dummy.ValidationType = typeof(DummyZValidationWithPiggyBacking);

			((INeedRow)Dummy).Row[DummyBizoSchema.Constants.Z0_Decimal] = -12345678901234567890.0M;
			Assert("Precondition", !Dummy.CheckZ0_DecimalFired);
			Assert("Precondition", !Dummy.CheckZ0_DecimalIsValidZDecimalFired);
			Assert("Precondition", !Dummy.CheckZ0_DecimalPiggyBackedFired);
			Assert("Precondition", !Dummy.CheckZ0_DecimalIsValidZDecimalPiggyBackedFired);
			Assert("Precondition", !Dummy.CheckZ0_DecimalDomainFired);
			Assert("Precondition", !Dummy.CheckZ0_DecimalIsValidZDecimalDomainFired);
			AssertEquals("Precondition", 0, Dummy.Z0_DecimalInfo.GetErrors().Count());

			Dummy.Validation.ValidateZ0_Decimal();
			Assert("CheckZ0_Decimal() should have been called.", Dummy.CheckZ0_DecimalFired);
			Assert("CheckZ0_DecimalIsValidZDecimal() should have been called.", Dummy.CheckZ0_DecimalIsValidZDecimalFired);
			Assert("Piggy-backed CheckZ0_Decimal() should have been called.", Dummy.CheckZ0_DecimalPiggyBackedFired);
			Assert("Piggy-backed CheckZ0_DecimalIsValidZDecimal() should *not* have been called (already called in the base validation).", !Dummy.CheckZ0_DecimalIsValidZDecimalPiggyBackedFired);
			Assert("Do domain validation registered, should not have been called", !Dummy.CheckZ0_DecimalDomainFired);
			Assert("Do domain validation registered, should not have been called", !Dummy.CheckZ0_DecimalIsValidZDecimalDomainFired);

			AssertEquals("Validation should have been run and 2 errors set.", 2, Dummy.Z0_DecimalInfo.GetErrors().Count());
		}


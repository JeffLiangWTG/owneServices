using System;
using System.Diagnostics.CodeAnalysis;

namespace CargoWise.BuildTools
{
	public sealed class DbVersion
	{
		DbVersion()
		{
		}

		public static void EnsureLatest()
		{
			bool isSchemaVersionLatest =
				SourceControl.EnterpriseDatabase.IsFileCheckedOutByMe(SchemaFileWindowsPath)
				|| !SourceControl.EnterpriseDatabase.IsDifferent(SchemaFileWindowsPath);

			bool isScriptVersionLatest =
				SourceControl.EnterpriseDatabase.IsFileCheckedOutByMe(ScriptFileWindowsPath)
				|| !SourceControl.EnterpriseDatabase.IsDifferent(ScriptFileWindowsPath);

			if (!isSchemaVersionLatest || !isScriptVersionLatest)
			{
				throw new DbVersionIsNotTheLatestException();
			}
		}

		public static string SchemaFileSourceControlPath
		{
			get
			{
				return BuildConstants.GetServerPath("Database/Odyssey/Resource/Version/AutoGenerated/SchemaVersion.cs");
			}
		}

		public static string SchemaFileWindowsPath
		{
			get
			{
				return BuildConstants.GetLocalPath(@"Database\Odyssey\Resource\Version\AutoGenerated\SchemaVersion.cs");
			}
		}

		internal static string ScriptFileWindowsPath
		{
			get
			{
				return BuildConstants.GetLocalPath(@"Database\Odyssey\Resource\Version\AutoGenerated\ScriptVersion.cs");
			}
		}
	}

	[Serializable]
	[SuppressMessage("CargoWiseOne", "CW1161:Res.GetString Analyzer", Justification = "Developer only tool")]
	public sealed class DbVersionIsNotTheLatestException : Exception
	{
		public DbVersionIsNotTheLatestException()
			: base(DefaultMessage)
		{
		}

#if NETFRAMEWORK
		public DbVersionIsNotTheLatestException(System.Runtime.Serialization.SerializationInfo info, System.Runtime.Serialization.StreamingContext context)
			: base(info, context)
		{
			Common.Argument.NotNull(info, nameof(info));
		}
#endif

		const string DefaultMessage =
			"You must have the latest DB schema+script version to setup/generate DB Schema dependent resources.\n" +
			"Please get latest, MAKE SURE YOU UPGRADE YOUR DATABASE, and try again.";
	}
}

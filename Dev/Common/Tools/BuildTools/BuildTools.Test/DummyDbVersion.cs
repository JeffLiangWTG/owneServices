using System.IO;

namespace CargoWise.BuildTools.Testing
{
	public sealed class DummyDbVersion
	{
		public static string SchemaFileWindowsPath
		{
			get
			{
				if (InTest)
				{
					return Path.Combine(MockSourceControl.MockWorkspacePath, @"Database\Odyssey\Resource\Version\AutoGenerated\SchemaVersion.cs");
				}
				return DbVersion.SchemaFileWindowsPath;
			}
		}

		static bool InTest
		{
			get { return NUnit.Framework.TestingState.IsRunningTests; }
		}
	}
}

		void AssertInternalServiceManagerAssembliesShouldNotReferenceExternalCWAssemblies(IEnumerable<string> allAssemblies, Func<string, bool> internalServiceManagerAssemblyChecker, Func<string, string, Assembly[], bool> cW1AssembliesChecker)
		{
			// Arrange
			var violatingAssemblies = new Dictionary<string, IList<string>>();
			var loadedAssemblies = AssemblyRetriever.LoadAsssembliesFromSimpleNames(allAssemblies.ToArray());

			var assembliesToCheck = loadedAssemblies
				.Where(a => internalServiceManagerAssemblyChecker(a.GetName().Name))
				.OrderBy(a => a.GetName().Name);

			// Act
			foreach (var assembly in assembliesToCheck)
			{
				var assemblyName = assembly.GetName().Name;
				if (IsTestAssembly(assemblyName))
				{
					continue;
				}

				var cW1References = assembly.GetReferencedAssemblies()
					.Where(reference => cW1AssembliesChecker(assemblyName, reference.Name, loadedAssemblies))
					.Select(reference => reference.Name)
					.OrderBy(referenceName => referenceName)
					.ToList();

				if (cW1References.Count > 0)
				{
					violatingAssemblies[assemblyName] = cW1References;
				}
			}

			// Assert
			var failures = violatingAssemblies
				.Select(v => $"{v.Key}|[{string.Join(",", v.Value)}]")
				.ToArray();

			AssertContainsExactElementsInAnyOrder("The following list of internal ServiceManager assemblies are not allowed to reference external CW assemblies.", Array.Empty<string>(), failures);
		}

		public void TestExternalCW1AssembliesExclusionsList()
		{
			// Arrange
			var violatingAssemblies = new Dictionary<string, IList<string>>();
			var assemblies = AssemblyRetriever.LoadAsssembliesFromSimpleNames(ServiceManagerExcludedAssembliesReferencingCW.Keys.ToArray())
				.ToDictionary(o => o.GetName().Name, o => o);

			// Act
			foreach (var assemblyReference in ServiceManagerExcludedAssembliesReferencingCW)
			{
				if (!assemblies.ContainsKey(assemblyReference.Key))
				{
					violatingAssemblies[assemblyReference.Key] = assemblyReference.Value;
					continue;
				}

				var actualReferences = assemblies[assemblyReference.Key]
					.GetReferencedAssemblies()
					.Select(r => r.Name);

				var obsoleteReferences = assemblyReference.Value
					.Where(r => !actualReferences.Contains(r))
					.ToArray();

				if (obsoleteReferences.Any())
				{
					violatingAssemblies[assemblyReference.Key] = obsoleteReferences;
				}
			}

			// Assert
			var failures = violatingAssemblies
				.OrderBy(v => v.Key)
				.Select(v => $"{v.Key}|[{string.Join(",", v.Value)}]")
				.ToArray();

			AssertContainsExactElementsInAnyOrder($"The following excluded assemblies are NOT referencing the listed CW assemblies any more, please remove them from the Dictionary '{nameof(ServiceManagerExcludedAssembliesReferencingCW)}'.", Array.Empty<string>(), failures);
		}

		public void TestNoLegacyUnitTests()
		{
			// Arrange
			var assembliesToCheck = ReflectionAssemblies
				.Where(ShouldCheckAssemblyForLegacyTests)
				.ToArray();

			// Act, Assert
			AssertDoesNotContainLegacyUnitTests(assembliesToCheck, ServiceManagerLegacyUnitTests.Value);

			bool ShouldCheckAssemblyForLegacyTests(string assemblyName)
			{
				string[] cw1TestAssemblies = new[]
				{
					"Enterprise.ServiceManager.Business.Test",
					"Enterprise.ServiceManager.GUI.Test",
					"Enterprise.ServiceManager.Module.Test",
					"Enterprise.ServiceManager.HostsController.Test",
				};


		void AssertReflectionShouldNotReferenceRestrictedAssemblies(IEnumerable<string> assembliesToCheck, Func<string, bool> restrictedAssembliesChecker)
		{
			// Arrange
			var violatingAssemblies = new Dictionary<string, IList<string>>();

			var assemblies = AssemblyRetriever.LoadAsssembliesFromSimpleNames(assembliesToCheck.ToArray());

			// Act
			foreach (var assembly in assemblies)
			{
				var assemblyName = assembly.GetName().Name;
				if (IsTestAssembly(assemblyName)
					|| IsServiceManagerAssembly(assemblyName))
				{
					continue;
				}

				var internalReferences = assembly.GetReferencedAssemblies()
					.Select(reference => reference.Name)
					.Where(referenceName =>
					{
						var isRestricted = restrictedAssembliesChecker(referenceName);
						var isExcluded = false;

						if (ServiceManagerExcludedAssembliesReferencedByCW1.ContainsKey(referenceName) && ServiceManagerExcludedAssembliesReferencedByCW1[referenceName].Contains(assembly.GetName().Name))
						{
							isExcluded = true;
						}

						return isRestricted && !isExcluded;
					})
					.OrderBy(referenceName => referenceName)
					.ToList();

				if (!internalReferences.IsNullOrEmpty())
				{
					violatingAssemblies[assemblyName] = internalReferences;
				}
			}

			// Assert
			var failures = violatingAssemblies
				.Select(violatingAssemblies => $"{violatingAssemblies.Key}|[{string.Join(",", violatingAssemblies.Value)}]")
				.ToArray();

			AssertContainsExactElementsInAnyOrder("The following list of assemblies are not allowed to reference the ServiceManager internal assemblies.", Array.Empty<string>(), failures);
		}


						&& !cw1TestAssemblies.Contains(assemblyName)
						&& !assemblyName.EndsWith(".CW1.Test")
						&& !assemblyName.EndsWith(".CW.Test");
			}
		}

		static void AssertDoesNotContainLegacyUnitTests(string[] assemblyNames, IDictionary<string, HashSet<string>> existingLegacyUnitTests)
		{
			// Arrange
			var assembliesWithLegacyTests = AssemblyRetriever
				.LoadAsssembliesFromSimpleNames(assemblyNames)
				.Where(o => o
					.GetReferencedAssemblies()
					.Any(x => x.Name.Equals("NUnitCore", StringComparison.OrdinalIgnoreCase)))
				.ToDictionary(
					o => o.GetName().Name,
					o => TestSuite.AssemblyClasses(o)
						.Select(x => x.Name)
						.ToArray());

			// Act
			var failures = assembliesWithLegacyTests
				.Where(o => o.Value.Any())
				.Select(o =>
				{
					var legacyUnitTests = existingLegacyUnitTests.TryGetValue(o.Key, out var value)
						? o.Value.Except(value).ToArray()
						: o.Value;

					return (AssemblyName: o.Key, LegacyUnitTests: legacyUnitTests);
				})
				.Where(o => o.LegacyUnitTests.Any())
				.Select(o => $"{o.AssemblyName}|[{string.Join(",", o.LegacyUnitTests)}]");

			// Assert
			AssertContainsExactElementsInAnyOrder($"The following assemblies have unit tests based on based on NUnitCore. Please update the unit tests to use NUnit.Framework.", Array.Empty<string>(), failures);
		}


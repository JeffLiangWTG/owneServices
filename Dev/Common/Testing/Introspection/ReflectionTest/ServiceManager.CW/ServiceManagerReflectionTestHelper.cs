		public void AssertUsageOfServiceTaskScheduleBO(IEnumerable<string> allowedNamespaces)
		{
			// Arrange
			var errors = new List<string>();
			var retriever = new SubClassRetriever(ReflectionAssemblies, Type.GetType("Enterprise.ServiceManager.Business.ServiceTaskSchedule, Enterprise.ServiceManager.Business"));
			retriever.IncludeAbstractClasses = false;
			retriever.IncludeAutoGeneratedCode = false;

			var referencingTypes = retriever.Retrieve();
			var notAllowedList = new List<Type>();

			// Act
			foreach (var reference in referencingTypes)
			{
				if (!allowedNamespaces.Any(allowed => reference.Namespace == allowed))
				{
					notAllowedList = notAllowedList.Where(x => !x.IsSubclassOf(reference)).ToList();
					if (notAllowedList.All(x => !reference.IsSubclassOf(x)))
					{
						notAllowedList.Add(reference);
					}
				}
			}

			// Assert
			foreach (var notAllowedType in notAllowedList)
			{
				errors.Add(notAllowedType.FullName);
			}

			AssertContainsExactElementsInAnyOrder("The following list of classed are not allowed to use the ServiceTaskSchedule BO since they are external to ServiceManager.", Array.Empty<string>(), errors);
		}


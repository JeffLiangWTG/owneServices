		static void AssertAllLegacyUnitTestsExist(IDictionary<string, HashSet<string>> existingLegacyUnitTests)
		{
			// Arrange
			var assemblyNames = existingLegacyUnitTests.Keys.ToArray();

			var assembliesWithLegacyTests = AssemblyRetriever
				.LoadAsssembliesFromSimpleNames(assemblyNames)
				.ToDictionary(
					o => o.GetName().Name,
					o => TestSuite.AssemblyClasses(o)
						.Select(x => x.Name)
						.ToArray());

			// Act
			var failures = existingLegacyUnitTests
				.Select(o =>
				{
					var missingUnitTests = assembliesWithLegacyTests.TryGetValue(o.Key, out var value)
						? o.Value.Except(value)

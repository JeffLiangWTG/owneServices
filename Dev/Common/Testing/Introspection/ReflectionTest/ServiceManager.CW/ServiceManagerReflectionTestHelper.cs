					return (AssemblyName: o.Key, MissingUnitTests: missingUnitTests);
				})
				.Where(o => o.MissingUnitTests.Any() || !assembliesWithLegacyTests.ContainsKey(o.AssemblyName))
				.Select(o => $"{o.AssemblyName}|[{string.Join(",", o.MissingUnitTests)}]");

			// Assert
			AssertContainsExactElementsInAnyOrder($"The following unit tests can be removed from {nameof(ServiceManagerLegacyUnitTests)}.json", Array.Empty<string>(), failures);
		}


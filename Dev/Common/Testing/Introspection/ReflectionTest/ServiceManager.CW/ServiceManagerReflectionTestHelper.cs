		static bool IsServiceManagerAssembly(string assemblyName)
		{
			return assemblyName.Contains("ServiceManager")
					&& !assemblyName.Contains("Enterprise.ServiceManager.Tasks.");
		}

		bool IsServiceManagerInternalAssembly(string assemblyName)
		{
			return IsServiceManagerAssembly(assemblyName)
					&& !ServiceManagerExternalAssemblies.Contains(assemblyName);
		}
		static bool IsRestrictedServiceManagerAssembly(string assemblyName)
		{
			var cw1Assemblies = new[]
			{
				"Enterprise.ServiceManager.Business",
				"Enterprise.ServiceManager.GUI",
				"Enterprise.ServiceManager.Module",
				"CargoWiseOne.ServiceManager.ReflectionTest",
			};

			return IsServiceManagerAssembly(assemblyName)
					&& !assemblyName.Contains(".CW1")
					&& !assemblyName.Contains(".CW")
					&& !cw1Assemblies.Contains(assemblyName);
		}

		bool IsCWExternalAssembly(string assemblyName, string referencedAssemblyName, Assembly[] assembliesMetaData)
		{
			if (IsRestrictedServiceManagerAssembly(referencedAssemblyName))
			{
				return false;
			}

			if (ServiceManagerExcludedAssembliesReferencingCW.ContainsKey(assemblyName) && ServiceManagerExcludedAssembliesReferencingCW[assemblyName].Contains(referencedAssemblyName))
			{
				return false;
			}

			return assembliesMetaData.Any(assembly =>
				assembly.GetName().Name.Equals(referencedAssemblyName) &&
				assembly.GetCustomAttributes<AssemblyProductAttribute>()
					.Single()
					.Product.Equals(
						Assembly.GetExecutingAssembly()
							.GetCustomAttributes<AssemblyProductAttribute>()
							.Single()
							.Product
					)
			);
		}

		static bool IsTestAssembly(string assemblyName)
		{
			return assemblyName.EndsWith(".Test")
					|| assemblyName.EndsWith(".Testing")
					|| assemblyName.EndsWith(".Test.Winzor")
					|| assemblyName.EndsWith(".Testing.Winzor")
					|| assemblyName.EndsWith(".Tests")
					|| assemblyName.EndsWith(".IntegrationTests")
					|| assemblyName.EndsWith(".ConcreteUnitTesting")
					|| assemblyName.EndsWith(".ReportTesting")
				;
		}


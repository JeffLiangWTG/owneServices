using Dat.Integration.SpecialFileHandling;
using Dat.Integration.VersionControl;

namespace Enterprise.Dat.SpecialFileHandling
{
	public class DataVersionChangeRequest : ApplicationVersionLabelChangeRequest
	{
		public DataVersionChangeRequest(SpecialFileHandlerContext context)
			: base(context)
		{
		}

		const string DataVersionFilePath = @"Database/Odyssey/Resource/Version/AutoGenerated/DataVersion.cs";
		const string StmEventFilePath = @"Database/Odyssey/Data/Public/StmEvent/StmEvent.xml";

		protected override bool TriggersVersionChange(string serverPath)
		{
			return serverPath.Contains(DataVersionFilePath) || new DocumentXmlVersionChangeRequest(Context).TriggersVersionChange(serverPath) || serverPath.Contains(StmEventFilePath);
		}

		protected override string GetVersionFileServerPath(string serverPath)
		{
			if (serverPath.Contains(DataVersionFilePath))
			{
				return serverPath;
			}
			else
			{
				return Context.RepositoryKey.GetServerPath(DataVersionFilePath);
			}
		}

		public override string[] UpdateForMerge(IWorkspaceAccess workspace, string sourceBranch, string targetBranch, IPendingChange originalChange)
		{
			if (originalChange.ServerItem.Contains(DataVersionFilePath))
			{
				string item = originalChange.ServerItem.Replace(sourceBranch, targetBranch);
				workspace.PendEdit(item);
				return new[] { item };
			}
			return null;
		}
	}
}

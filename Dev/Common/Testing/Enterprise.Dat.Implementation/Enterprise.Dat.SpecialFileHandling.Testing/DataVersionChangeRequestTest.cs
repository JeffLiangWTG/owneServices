using System;
using System.IO;
using Dat.Integration;
using Dat.Integration.SpecialFileHandling;
using Dat.Integration.VersionControl;
using Enterprise.ZArchitecture.Core;
using Moq;
using NUnit.Framework;
using WTG.DevTools.Definitions;

namespace Enterprise.Dat.SpecialFileHandling.Testing
{
	class DataVersionChangeRequestTest : TestCase
	{
		public void TestVersionFileChangedGit()
		{
			TestVersionFileChanged(
				RepositoryKey.ForGit("http://tfs.wtg.zone:8080/tfs/CargoWise/CW/_git/Dev", "master", "/").ForDat(),
				@"/Database/Odyssey/Resource/Version/AutoGenerated/DataVersion.cs",
				"/Enterprise/Product/Documents/ExcelTemplates/Documents/Customs/ZA/RoadManifestWithBarcode.xls");

			TestVersionFileChanged(
				RepositoryKey.ForGit("http://tfs.wtg.zone:8080/tfs/CargoWise/CW/_git/Dev", "master", "/").ForDat(),
				@"/Database/Odyssey/Resource/Version/AutoGenerated/DataVersion.cs",
				"/Enterprise/Database/Odyssey/Data/Public/StmEvent/StmEvent.xml");
		}

		void TestVersionFileChanged(IRepositoryKey repositoryKey, string versionFileServerPath, string changedFile)
		{
			using (var versionFile = TempFile.New())
			{
				File.WriteAllText(versionFile.Filename, @"
	public static class DataVersion
	{{
		public static readonly VersionLabel Application = new VersionLabel(1, 0);
	}}
");
				var workspace = new Mock<IWorkspaceAccess>(MockBehavior.Strict);
				workspace.Setup(m => m.GetLocalItemForServerItem(versionFileServerPath)).Returns(versionFile.Filename);
				workspace.Setup(m => m.PendEdit(versionFileServerPath)).Returns(1);
				workspace.Setup(m => m.GetPendingChanges(versionFileServerPath, TfsRecursionType.None)).Returns(Array.Empty<IPendingChange>());
				workspace.Setup(m => m.GetLatest(new[] { versionFileServerPath }, TfsRecursionType.None, TfsGetOptions.None)).Returns((IGetStatus)null);

				var pendingChange = new MockPendingChange(TfsChangeType.Edit, changedFile);
				var request = new DataVersionChangeRequest(new SpecialFileHandlerContext(repositoryKey));

				var unshelved = request.ShouldUnshelveForDATCheckin(pendingChange);

				AssertEquals("Data file should be unshelved.", true, unshelved);

				var modifiedFiles = request.UpdateForDATCheckin(workspace.Object, pendingChange);
				try
				{
					AssertArrayEqualsByElements(new[] { versionFileServerPath }, modifiedFiles);
				}
				catch (NullReferenceException)
				{
					Fail($"versionFileServerPath: {versionFileServerPath}, modifiedFiles: {modifiedFiles}");
				}
				AssertContains("Version file should have been updated.", "new VersionLabel(2, 0)", File.ReadAllText(versionFile.Filename));
			}
		}
	}
}

using System.Drawing;
using WinzorFramework;

namespace System.Windows.Forms;

public class ToolStripDropDownItem : ToolStripItem, IWinzorMenuItem
{
	protected override ControlCollection CreateControlsInstance() => new ControlCollection(this);

	public ToolStripItemCollection DropDownItems => DropDown.Items;

	public virtual bool HasDropDownItems => DropDownItems.Count > 0;

	public ToolStripDropDown DropDown
	{
		get => dropDown ??= new ToolStripDropDown(this, true);
		set
		{
			if (dropDown != value)
			{
				dropDown = value;
			}
		}
	}
	ToolStripDropDown? dropDown;

	public bool HasDropDown => dropDown is not null;

	public ToolStripDropDownDirection DropDownDirection { get; set; }

	internal virtual void AutoHide(ToolStripItem otherItemBeingSelected) => HideDropDown();

	public void ShowDropDown()
	{
		ShowDropDownInternal();
	}

	void ShowDropDownInternal()
	{
		if (dropDown is null || (!dropDown.Visible))
		{
			// We want to show if there's no dropdown
			// or if the dropdown is not visible.
			OnDropDownShow(EventArgs.Empty);
		}
		// the act of setting the drop down visible the first time sets the parent
		// it seems that Visible returns true if your parent is null.
		if (dropDown is not null && !dropDown.Visible)
		{
			if (dropDown.IsAutoGenerated && DropDownItems.Count <= 0)
			{
				return;  // this is a no-op for autogenerated drop downs.
			}

			var position = new Point(0, Bounds.Height);
			if (dropDown.DefaultDropDownDirection is ToolStripDropDownDirection.AboveLeft or ToolStripDropDownDirection.AboveRight)
			{
				position.Y = 0;
			}

			dropDown.OwnerItem = this;
			dropDown.Parent = this;
			dropDown.Show(this, position);
		}
	}

	public void HideDropDown()
	{
		dropDown?.Hide(this);
	}

	protected virtual void OnDropDownShow(EventArgs e)
	{
		DropDownOpening?.Invoke(this, e);
	}

	public event EventHandler? DropDownOpening;

	public event EventHandler? DropDownClosed;

	public event ToolStripItemClickedEventHandler? DropDownItemClicked;

	protected override void OnClick(EventArgs e)
	{
		ToolStripManager.CloseActiveDropDown();
		base.OnClick(e);
	}

	IWinzorMenuItem[] IWinzorMenuItem.MenuItems => dropDown?.Items.Cast<IWinzorMenuItem>().ToArray() ?? Array.Empty<IWinzorMenuItem>();

	public virtual void OnSelect() => ShowDropDown();

	bool IWinzorMenuItem.Loadable => DropDownOpening is not null || (dropDown?.HasOpeningEvent ?? false) || (dropDown?.Items.Count > 0);
}

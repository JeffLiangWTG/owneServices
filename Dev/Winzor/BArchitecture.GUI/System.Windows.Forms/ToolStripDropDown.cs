using System.ComponentModel;
using System.Drawing;
using System.Windows.Forms.Layout;
using CargoWise.Blazor.Client.Integration.Menus;
using WinzorFramework;

namespace System.Windows.Forms;

public partial class ToolStripDropDown : ToolStrip
{
	ToolStripDropDownCloseReason closeReason = ToolStripDropDownCloseReason.AppFocusChange;

	public ToolStripDropDown()
	{
		SetState(States.Visible, false);
		AutoSize = true;
	}

	internal ToolStripDropDown(ToolStripItem ownerItem) : this()
	{
		this.ownerItem = ownerItem;
	}

	internal ToolStripDropDown(ToolStripItem ownerItem, bool isAutoGenerated) : this(ownerItem)
	{
		this.isAutoGenerated = isAutoGenerated;
	}

	public ToolStripItem? OwnerItem
	{
		get => ownerItem;
		set
		{
			ownerItem = value;
		}
	}
	ToolStripItem? ownerItem;

	internal ToolStripDropDownItem? OwnerDropDownItem
	{
		get { return OwnerItem as ToolStripDropDownItem; }
	}

	internal Control? SourceControlInternal;

	public void Show(Control control, Point position)
	{
		SourceControlInternal = control.OrThrowIfNull();

		Visible = true;
		menuInterop = new MenuInterop(control, MenuType.ContextMenu, WinzorControlGuid);
		menuInterop.Closed += OnMenuClosed;
		control.InvokeRenderDispatcher(() =>
			menuInterop.ShowAsync(Items.Cast<IWinzorMenuItem>().ToArray(), control.PointToScreen(position), dropDownDirection: DefaultDropDownDirection));
	}

	MenuInterop? menuInterop;

	public void Show(Control control, Point position, ToolStripDropDownDirection direction) => Show(control, position);

	public void Show(Control control, int x, int y) => Show(control, new Point(x, y));

	public void Show(Point screenLocation)
	{
	}

	public void Hide(Control control)
	{
		SourceControlInternal = control.OrThrowIfNull();

		menuInterop = menuInterop ?? new MenuInterop(control, MenuType.ContextMenu, WinzorControlGuid);
		control.InvokeRenderDispatcher(() => menuInterop.CloseAsync());
		Close();
	}

	public void Close()
	{
		SetCloseReason(ToolStripDropDownCloseReason.CloseCalled);
		Visible = false;
	}

	internal void SetCloseReason(ToolStripDropDownCloseReason reason)
	{
		closeReason = reason;
	}

	void ResetCloseReason()
	{
		closeReason = ToolStripDropDownCloseReason.AppFocusChange;
	}

	void OnMenuClosed(object? sender, EventArgs e)
	{
		if (menuInterop is not null && Visible)
		{
			Visible = false;
			menuInterop.Closed -= OnMenuClosed;
		}
	}

	internal void OnOpening() => OnOpening(new CancelEventArgs());

	internal void OnOpening(CancelEventArgs e) => Opening?.Invoke(this, e);

	internal void OnOpened(EventArgs e) => Opened?.Invoke(this, e);

	internal void OnClosing(ToolStripDropDownClosingEventArgs e) => Closing?.Invoke(this, e);

	internal void OnClosed(ToolStripDropDownClosedEventArgs e) => Closed?.Invoke(this, e);

	internal bool HasOpeningEvent => Opening != null;

	public event EventHandler? Opened;

	public event CancelEventHandler? Opening;

	public event ToolStripDropDownClosingEventHandler? Closing;

	public event ToolStripDropDownClosedEventHandler? Closed;

	public bool IsAutoGenerated => isAutoGenerated;
	readonly bool isAutoGenerated;

	internal ToolStrip? OwnerToolStrip
	{
		get
		{
			if (ownerItem is not null)
			{
				ToolStrip? owner = ownerItem.ParentInternal;
				if (owner is not null)
				{
					return owner;
				}

				// might not actually be placed on the overflow, just check for sure.
				if (ownerItem.Placement == ToolStripItemPlacement.Overflow && ownerItem.Owner is not null)
				{
					return ownerItem.Owner.OverflowButton.DropDown;
				}

				if (owner is null)
				{
					return ownerItem.Owner;
				}
			}

			return null;
		}
	}

	protected override void SetVisibleCore(bool visible)
	{
		if (visible)
		{
			if (LayoutRequired)
			{
				LayoutTransaction.DoLayout(this, this, PropertyNames.Visible);
			}

			CancelEventArgs openEventArgs = new CancelEventArgs(cancel: DisplayedItems.Count == 0);
			OnOpening(openEventArgs);

			if (!openEventArgs.Cancel)
			{
				base.SetVisibleCore(visible);
			}

			OnOpened(EventArgs.Empty);
		}
		else
		{
			if (Visible)
			{
				var reason = closeReason;
				ResetCloseReason();
				var e = new ToolStripDropDownClosingEventArgs(reason);
				OnClosing(e);

				base.SetVisibleCore(visible);

				var closedEventArgs = new ToolStripDropDownClosedEventArgs(reason);
				OnClosed(closedEventArgs);
			}
			else
			{
				base.SetVisibleCore(visible);
			}
			SourceControlInternal = null;
		}
	}

	protected override void Dispose(bool disposing)
	{
		if (disposing)
		{
			SourceControlInternal = null;
		}

		base.Dispose(disposing);
	}

	protected override bool DefaultShowItemToolTips => false;
	ToolStripDropDownDirection toolStripDropDownDirection = ToolStripDropDownDirection.Default;

	public override ToolStripDropDownDirection DefaultDropDownDirection
	{
		get
		{
			var direction = toolStripDropDownDirection;
			if (direction != ToolStripDropDownDirection.Default)
			{
				return direction;
			}

			var dock = OwnerToolStrip?.Dock;
			var actualDock = Parent?.Dock ?? DockStyle.Left;

			if (Orientation == Orientation.Vertical)
			{
				if (IsInToolStripPanel)
				{
					direction = (actualDock == DockStyle.Right) ? ToolStripDropDownDirection.Left : ToolStripDropDownDirection.Right;
					if (DesignMode && actualDock == DockStyle.Left)
					{
						direction = ToolStripDropDownDirection.Right;
					}
				}
				else
				{
					direction = ((Dock == DockStyle.Right) && (RightToLeft == RightToLeft.No)) ? ToolStripDropDownDirection.Left : ToolStripDropDownDirection.Right;
					if (DesignMode && Dock == DockStyle.Left)
					{
						direction = ToolStripDropDownDirection.Right;
					}
				}
			}
			else
			{
				if (IsInToolStripPanel && Parent is not null)
				{
					dock = Parent.Dock;
				}

				if (dock == DockStyle.Bottom)
				{
					direction = (RightToLeft == RightToLeft.Yes) ? ToolStripDropDownDirection.AboveLeft : ToolStripDropDownDirection.AboveRight;
				}
				else
				{
					direction = (RightToLeft == RightToLeft.Yes) ? ToolStripDropDownDirection.BelowLeft : ToolStripDropDownDirection.BelowRight;
				}
			}

			return direction;
		}
		set
		{
			if (Enum.IsDefined(value))
			{
				toolStripDropDownDirection = value;
			}
			else
			{
				throw new InvalidEnumArgumentException(nameof(value), (int)value, typeof(ToolStripDropDownDirection));
			}
		}
	}

	/// <summary>
	/// Returns the ToolStrip from which all the dropdowns started from.  This can be null.
	/// </summary>
	internal override ToolStrip? GetToplevelOwnerToolStrip()
	{
		var topmost = GetFirstDropDown();
		return (topmost.OwnerItem == null) ? null : topmost.OwnerToolStrip;
	}

	internal ToolStripDropDown GetFirstDropDown()
	{
		var topmost = this;
		var ownerDropDown = topmost.OwnerToolStrip as ToolStripDropDown;
		while (ownerDropDown != null)
		{
			topmost = ownerDropDown;
			ownerDropDown = topmost.OwnerToolStrip as ToolStripDropDown;
		}
		return topmost;
	}

	protected override void OnLayout(LayoutEventArgs e)
	{
		// It's important to size the dropdown first, then layout so that
		// the layout engine and SetDisplayedItems know how big the container is.
		AdjustSize();
		base.OnLayout(e);
	}

	internal void AdjustSize()
	{
		var size = GetSuggestedSize();
		if (size != Size)
		{
			Size = size;
		}
	}

	internal Size GetSuggestedSize() => AutoSize ? GetPreferredSize(Size.Empty) : Size;
}

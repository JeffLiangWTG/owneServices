		const string SchemaMainResourceName = "Enterprise.DbUpgrader.Resource.AutoGenerated.Schema_Main.sql";

		public static void CreateTemplateDatabase(AdminConnection connection)
		{
			try
			{
				if (!Globals.IsTest)
				{
					BiLogger.StartSubtask(string.Format(CultureInfo.InvariantCulture, "Creating template database [{0}]", TemplateDatabaseName));
					CreateEmptyDatabase(connection, TemplateDatabaseName);
				}

				using (((ICurrentDbControl)connection).UseDatabase(TemplateDatabaseName))
				using (var transactionManager = connection.BeginTransactionWithManager())
				{
					if (!Globals.IsTest)
					{
						var assembly = typeof(Enterprise.DbUpgrader.Resource.ScriptManager).Assembly;
						using var stream = assembly.GetManifestResourceStream(SchemaMainResourceName);
						var schemaMainContent = new StreamReader(stream).ReadToEnd();

						var createCommands = schemaMainContent.Split(new string[] { ";" }, StringSplitOptions.RemoveEmptyEntries);

						CreateDatabaseSchema(connection);

						foreach (string createCommand in createCommands)
						{
							connection.ExecuteNonQuery(createCommand);
						}
					}
					else
					{
						DropClientTables(connection);
					}

					foreach (var script in TableCreationScripts)
					{
						connection.ExecuteNonQuery(script.CreateScript);
					}

					transactionManager.CommitTransaction();
				}
			}
			catch (Exception ex) when (!ex.IsCriticalException())
			{
				var message = string.Format(CultureInfo.InvariantCulture, "Failed to create template database [{0}]. Check Schema_Main.sql embedded resource in Shared/CargoWise.DbUpgrader and other related scripts.\r\n{1}", TemplateDatabaseName, ex.Message);
				throw new BiDatabaseSyncException(message, ex);
			}
		}

		static void DropClientTables(AdminConnection connection)
		{
			var sqlText = @"DECLARE @sql nvarchar(max) = ''

SELECT @sql = @sql + 'DROP TABLE [' + SCHEMA_NAME(schema_id) + '].[' + name + '];'
FROM sys.tables
WHERE name like 'Client%'

EXEC (@sql)";
			connection.ExecuteNonQuery(sqlText);
		}

		public static void CreateEdwDatabase(AdminConnection connection)
		{
			if (!Globals.IsTest || UseTestDatabaseName)
			{
				string source = null;
				try
				{
					BiLogger.StartSubtask(string.Format(CultureInfo.InvariantCulture, "Creating database [{0}]", EdwDatabaseName));
					CreateEdwDatabaseSafe(connection);
				}
				catch (SqlException e) when (new DbErrorMatch(e).ExceptionType == DbErrorType.CannotCreateFileBecauseItAlreadyExists)
				{
					var fileFullName = GetFileFullNameOnCannotCreateFileError(e.Message);
					DeletePreviousDbFilesIfExist(connection, fileFullName);

					CreateEdwDatabaseSafe(connection);
				}
				catch (Exception ex) when (!ex.IsCriticalException())
				{
					var message = string.Format(CultureInfo.InvariantCulture, "Failed to create EDW database. Check {0}.\r\n{1}", source, ex.Message);
					throw new BiDatabaseSyncException(message, ex);
				}
			}
		}

		static string GetFileFullNameOnCannotCreateFileError(string message)
		{
			string result = "";

			string pattern = "(?<=^Cannot create file ')([^']*)(?=' because it already exists)";    // Exception Message
			Regex fileRegex = new Regex(pattern, RegexOptions.IgnoreCase);
			Match fileMatch = fileRegex.Match(message);

			if (fileMatch.Success)
			{
				result = fileMatch.Value;
			}

			return result;
		}

		static void DeletePreviousDbFilesIfExist(DbConnection conn, string conflictingFilePath)
		{
			if (!string.IsNullOrEmpty(conflictingFilePath))
			{
				var sqlText = String.Format(CultureInfo.InvariantCulture,
					"EXEC [{0}]..[CLRDeleteFile] '{1}', '1';",
					Db.DatabaseName,
					conflictingFilePath);
				conn.ExecuteNonQuery(sqlText);
			}
		}

		static void CreateEdwDatabaseSafe(AdminConnection connection)
		{
			CreateEmptyDatabase(connection, EdwDatabaseName);

			using (((ICurrentDbControl)connection).UseDatabase(EdwDatabaseName))
			{
				connection.ExecuteNonQuery("SP_CONFIGURE 'clr enabled', 1"); // This is a stored procedure, not a column name
				DataUtils.SetTrustworthyOn(connection, EdwDatabaseName);
				DataUtils.AlterDbAuthorisation(connection, EdwDatabaseName, OdysseyAdminCredentials.AdminUserName);

				using (var transactionManager = connection.BeginTransactionWithManager())
				{
					RunAssembliesUpgrader(connection);
					CreateEdwViews(connection);
					CreateEdwStoredProcedures(connection);

					try
					{
						Db.InitializeDatabaseDetails(ServerName, TemplateDatabaseName);
					}
					catch (Exception ex) when (!ex.IsCriticalException()) { }

					((IDbLoginRepair)connection).EnableApplicationDbLogins();
					((IDbLoginRepair)connection).EnsureDbLoginsHaveRightsToCurrentDatabase();

					transactionManager.CommitTransaction();
				}
			}
		}


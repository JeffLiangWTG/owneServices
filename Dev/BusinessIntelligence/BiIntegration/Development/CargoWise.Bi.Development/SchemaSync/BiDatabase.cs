		public static void DropDatabase(AdminConnection connection, string dbName)
		{
			if (!Globals.IsTest || UseTestDatabaseName)
			{
				try
				{
					if (connection.DatabaseExists(dbName))
					{
						BiLogger.StartSubtask(string.Format(CultureInfo.InvariantCulture, "Dropping database [{0}]", dbName));
						TurnOffAutoUpdateStatistics(connection, dbName);
						SwitchToSingleUserMode(connection, dbName);
						DropDatabase_Core(connection, dbName);
					}
				}
				catch (Exception ex) when (!ex.IsCriticalException())
				{
					BiLogger.Fail(string.Format(CultureInfo.InvariantCulture, "Cannot drop database [{0}]", dbName));
					throw new BiDatabaseSyncException(ex.Message);
				}
			}
		}

		static void TurnOffAutoUpdateStatistics(AdminConnection connection, string dbName)
		{
			var query = string.Format(CultureInfo.InvariantCulture, @"
IF EXISTS(SELECT NULL FROM sys.databases WHERE name = '{0}' AND is_auto_update_stats_async_on = 1)
BEGIN
	ALTER DATABASE [{0}] SET AUTO_UPDATE_STATISTICS_ASYNC OFF

	DECLARE @killCmd nvarchar(max) = ''
	SELECT @killCmd = @killCmd + 'KILL STATS JOB ' + STR(job_id) + '; '
		FROM sys.dm_exec_background_job_queue j
		INNER JOIN sys.databases d
		ON j.database_id = d.database_id
		WHERE d.name = '{0}'
	EXEC sp_executesql @killCmd
END
", dbName); // database query
			connection.ExecuteNonQuery(query);
		}

		static void SwitchToSingleUserMode(AdminConnection connection, string dbName)
		{
			var query = string.Format(CultureInfo.InvariantCulture, @"ALTER DATABASE [{0}] SET  SINGLE_USER WITH ROLLBACK IMMEDIATE", dbName); // database query
			connection.ExecuteNonQuery(query);
		}

		static void DropDatabase_Core(AdminConnection connection, string dbName)
		{
			var query = string.Format(CultureInfo.InvariantCulture, @"DROP DATABASE [{0}]", dbName); // database query
			connection.ExecuteNonQuery(query);
		}

		static void CreateEdwStoredProcedures(AdminConnection connection)
		{
			string source = null;
			try
			{
				foreach (var modelView in BiAutomationConfigLoaderForDevelopment.Instance.ConfigData.EdwModelViewTableConfig)
				{
					source = string.Format(CultureInfo.InvariantCulture, "[{0}].[{1}]", modelView.Schema, modelView.Name);
					var sqlText = BiAutomationConfigLoaderForDevelopment.Instance.ConfigData.GetCreateModelViewQuery(modelView);
					connection.ExecuteNonQuery(sqlText);
				}

				foreach (var denormTable in BiAutomationConfigLoaderForDevelopment.Instance.ConfigData.EdwDenormalizedTableConfig)
				{
					source = string.Format(CultureInfo.InvariantCulture, "[{0}].[{1}] (Create View)", denormTable.Schema, denormTable.Name);
					var sqlText = BiAutomationConfigLoaderForDevelopment.Instance.ConfigData.GetCreateDenormalizedTableViewQuery(denormTable);
					connection.ExecuteNonQuery(sqlText);

					source = string.Format(CultureInfo.InvariantCulture, "[{0}].[{1}] (Initial Load)", denormTable.Schema, denormTable.Name);
					sqlText = BiAutomationConfigLoaderForDevelopment.Instance.ConfigData.GetInitialLoadQueryForDenormalizedTable(denormTable);
					connection.ExecuteNonQuery(sqlText);
				}
			}
			catch (Exception ex) when (!ex.IsCriticalException())
			{
				var message = string.Format(CultureInfo.InvariantCulture, "Failed to create EDW database. Check {0}.\r\n{1}", source, ex.Message);
				throw new BiDatabaseSyncException(message, ex);

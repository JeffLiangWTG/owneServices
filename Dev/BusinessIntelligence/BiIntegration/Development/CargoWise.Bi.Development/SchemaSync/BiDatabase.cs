		public static void LoadSchemaFromSQL(SchemaDataSet schema, bool useBinaries)
		{
			schema.Clear();
			schema.EnforceConstraints = false;

			BiLogger.StartSubtask("Parsing database schema");
			if (useBinaries)
			{
				var assembly = typeof(Enterprise.DbUpgrader.Resource.ScriptManager).Assembly;
				BiLogger.StartSubtask(string.Format(CultureInfo.InvariantCulture, "Loading database schema from {0}", assembly.FullName));

				using (var stream = assembly.GetManifestResourceStream(SchemaMainResourceName))
				{
					var reader = new StreamReader(stream);

					var scripts = new TextReader[TableCreationScripts.Length + 1];
					scripts[0] = reader;

					for (var i = 1; i <= TableCreationScripts.Length; i++)
					{
						scripts[i] = new StringReader(TableCreationScripts[i - 1].CreateScript);
					}

					var schemaExtractor = new SchemaExtractor(scripts);
					schemaExtractor.ExtractSchema(schema);
				}
			}
			else
			{
				var schemaMainPath = Path.Combine(BiFiles.CWSharedPath, "CargoWise.DbUpgrader", "src", "Resource", "Resource", "AutoGenerated", "Schema_Main");
				BiLogger.StartSubtask(string.Format(CultureInfo.InvariantCulture, "Loading database schema from {0}", schemaMainPath));

				var files = new FileEnumerator(schemaMainPath, "*.sql");
				var scripts = files.Concat(TableCreationScripts.Select(script => new StringReader(script.CreateScript)));

				var schemaExtractor = new SchemaExtractor(scripts);

				schemaExtractor.ExtractSchema(schema);
			}
		}

		[System.Diagnostics.CodeAnalysis.SuppressMessage("CargoWiseOne", "CW1107:UseBusinessObjectFactory", Justification = "Baseline")]
		public static void LoadSchemaFromDatabase(DbConnection connection, SchemaDataSet schema)
		{
			try
			{
				schema.Clear();
				schema.EnforceConstraints = false;

				BiLogger.StartSubtask(string.Format(CultureInfo.InvariantCulture, "Loading database schema from {0}", BiFiles.MainDbSchemaQueryFilePath));
				var query = BiFiles.MainDbSchemaQueryContent;

				using (((ICurrentDbControl)connection).UseDatabase(TemplateDatabaseName))
				using (var cmd = connection.Command(query))
				using (var reader = cmd.ExecuteReader())
				{
					schema.Load(reader, System.Data.LoadOption.OverwriteChanges, schema.Definition);
				}

				BiLogger.StartSubtask("Loading database schema completed");
			}
			catch (Exception ex) when (!ex.IsCriticalException())
			{
				BiLogger.Fail("Loading database schema failed");
				throw new BiDatabaseSyncException(ex.Message);
			}
		}


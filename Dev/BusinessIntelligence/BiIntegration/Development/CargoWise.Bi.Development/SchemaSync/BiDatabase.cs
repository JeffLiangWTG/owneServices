		[System.Diagnostics.CodeAnalysis.SuppressMessage("CargoWiseOne", "CW1107:UseBusinessObjectFactory", Justification = "Baseline")]
		static void CreateEdwViews(AdminConnection connection)
		{
			string source = "Schema_EDW.sql";
			try
			{
				string edwCreateTableScript = File.ReadAllText(BiFiles.GeneratedEDWTableSchemaPath);

				using (var command = connection.Command(edwCreateTableScript))
				{
					command.ExecuteNonQuery();
				}

				SynchroniseTableValuedTypes(connection);

				bool Filter(string name)
					=> !name.StartsWith(BiConstants.EdwModelViewPrefix, StringComparison.OrdinalIgnoreCase)
					&& !name.StartsWith(BiConstants.EdwAggregateViewPrefix + BiConstants.EdwAggregateTablePrefix, StringComparison.OrdinalIgnoreCase)
					&& !name.StartsWith(BiConstants.EdwAggregateInitialLoadProcPrefix + BiConstants.EdwAggregateTablePrefix, StringComparison.OrdinalIgnoreCase)
					&& !name.StartsWith(BiConstants.EdwAggregateIncrementalLoadProcPrefix + BiConstants.EdwAggregateTablePrefix, StringComparison.OrdinalIgnoreCase);

				foreach (var script in CoreEdwScriptIndex.GetScripts().Concat(CoreEdwScriptIndex.GetModelScripts()))
				{
					if (Filter(script.Name))
					{
						source = script.Name;

						using (var command = connection.Command(script.Text))
						{
							command.ExecuteNonQuery();
						}
					}
				}
			}
			catch (Exception ex) when (!ex.IsCriticalException())
			{
				var message = string.Format(CultureInfo.InvariantCulture, "Failed to create EDW database. Check {0}.\r\n{1}", source, ex.Message);
				throw new BiDatabaseSyncException(message, ex);
			}
		}

		static void SynchroniseTableValuedTypes(AdminConnection connection)

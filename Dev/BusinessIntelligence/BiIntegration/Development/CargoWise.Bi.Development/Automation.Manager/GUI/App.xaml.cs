using System;
using System.Globalization;
using System.Windows;
using System.Windows.Markup;

namespace CargoWise.Bi.Automation.Manager
{
	/// <summary>
	/// Interaction logic for App.xaml
	/// </summary>
	public partial class App : Application
	{
		static App()
		{
			AppDomain currentDomain = AppDomain.CurrentDomain;
			currentDomain.UnhandledException += new UnhandledExceptionEventHandler(MyHandler);

			FrameworkElement.LanguageProperty.OverrideMetadata(
				typeof(FrameworkElement),
				new FrameworkPropertyMetadata(
					XmlLanguage.GetLanguage(CultureInfo.CurrentCulture.IetfLanguageTag)));
		}

		[System.Diagnostics.CodeAnalysis.SuppressMessage("CargoWiseOne", "CW1161:ResGetStringAnalyzer", Justification = "Not using ZorKArchitecture")]
		static void MyHandler(object sender, UnhandledExceptionEventArgs args)
		{
			Exception ex = (Exception)args.ExceptionObject;
			MessageBox.Show("UnhandledException caught : " + ex.Message + "\nRuntime terminating: " + args.IsTerminating);
		}

		/// <summary>
		/// SDK project call wpf build tasks v6 - if targeting .net6 it generates Main()
		/// classic project call wpf build tasks v4 - can target only full framework versions and also generates Main()
		/// after port to SDK project we still target full framework
		/// seems that in that case wpf build tasks v6 generates everything it need to generate except Main() - manually added here
		/// baml resources and code generated by wpf build task v6 work on .net48
		/// </summary>
		[STAThread()]
		public static void Main()
		{
			App app = new App();

			app.InitializeComponent();
			app.Run();
		}
	}
}

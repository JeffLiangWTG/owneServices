using CargoWise.Data;
using CargoWise.DbUpgrader.Foundation;
using Enterprise.DbUpgrader.Shared;

namespace Enterprise.DbUpgrader.ReferenceDatabases.AU
{
	class AUTariffReferenceDbUpgrader : ReferenceDbUpgrader
	{
		#region Factory Class

		public class AUTrfRefDbUpgraderFactory : IRefDbUpgraderFactory
		{
			public ReferenceDbUpgrader New(IUpgradeContext upgradeContext, DbConnection upgradeConnection, IUpgradeTaskWorkflowLogger logger)
			{
				return new AUTariffReferenceDbUpgrader(upgradeContext, upgradeConnection, logger);
			}
		}

		#endregion

		public AUTariffReferenceDbUpgrader(IUpgradeContext upgradeContext, DbConnection upgradeConnection, IUpgradeTaskWorkflowLogger logger)
			: base(upgradeContext, upgradeConnection, logger)
		{
		}

		public override string ReferenceName
		{
			get { return "AU Tariff"; }
		}

		public override RefDbTypeEnum DatabaseType
		{
			get { return RefDbTypeEnum.Tariff; }
		}

		public override string CountryCode
		{
			get { return "AU"; }
		}

		//------------------------------------------------------------------------------
		// Please Read. Any questions, please talk to Joo or Brendon or Dong
		//------------------------------------------------------------------------------
		//	Reference File upgrade occurs only when there is a schema version number change in the main Enterprise database.
		//	When this number increases, please make sure there is a schema version number bumped up too. For alpha, it should be a major number. For releases, it should be a minor version number.
		//	Schema version number is located in $/Dev/Database/Odyssey/Resource/Version/AutoGenerated/SchemaVersion.cs
		//	All changes in reference files should be patched to releases even if WIs are enhancements that are meant to be checked into alpha because there might be subsequent upgrades that need to be patched to releases.
		public override int LatestVersion
		{
			get { return 10; }
		}

		protected override void DoDataUpgrade(DbConnection conn, int currentVersion)
		{
			if (currentVersion < 1)
			{
				CreateInitialObjects(conn);
			}

			if (currentVersion < 3)
			{
				UpgradeBlobToVarMaxDataType(conn);
			}
		}

		void CreateInitialObjects(DbConnection conn)
		{
			CreateInitialTables(conn);
			CreateInitialIndexes(conn);
		}

		void CreateInitialTables(DbConnection conn)
		{
			if (!DbObjectCreator.TableExists(conn, "AUCSection"))
			{
				conn.ExecuteNonQuery(AUCSectionTableSql);
			}

			if (!DbObjectCreator.TableExists(conn, "AUCAHECC"))
			{
				conn.ExecuteNonQuery(AUCAHECCTableSql);
			}

			if (!DbObjectCreator.TableExists(conn, "AUCChapter"))
			{
				conn.ExecuteNonQuery(AUCChapterTableSql);
			}

			if (!DbObjectCreator.TableExists(conn, "AUCClass"))
			{
				conn.ExecuteNonQuery(AUCClassTableSql);
			}
		}

		void CreateInitialIndexes(DbConnection conn)
		{
			if (!DbObjectCreator.IndexExists(conn, "AUCSection", "UG_Section"))
			{
				conn.ExecuteNonQuery(AUCSectionIndexUG_SectionSql);
			}

			if (!DbObjectCreator.IndexExists(conn, "AUCAHECC", "NR_RX__UA_AHECC"))
			{
				conn.ExecuteNonQuery(AUCAHECCIndexNR_RX__UA_AHECCSql);
			}

			if (!DbObjectCreator.IndexExists(conn, "AUCAHECC", "AUCAHECC"))
			{
				conn.ExecuteNonQuery(AUCAHECCIndexAUCAHECCSql);
			}

			if (!DbObjectCreator.IndexExists(conn, "AUCChapter", "UH_Chapter"))
			{
				conn.ExecuteNonQuery(AUCChapterIndexUH_ChapterSql);
			}

			if (!DbObjectCreator.IndexExists(conn, "AUCChapter", "AUCSection"))
			{
				conn.ExecuteNonQuery(AUCChapterIndexAUCSectionSql);
			}

			if (!DbObjectCreator.IndexExists(conn, "AUCClass", "AUCClass"))
			{
				conn.ExecuteNonQuery(AUCClassIndexAUCClassSql);
			}

			if (!DbObjectCreator.IndexExists(conn, "AUCClass", "UJ_HDG"))
			{
				conn.ExecuteNonQuery(AUCClassIndexUJ_HDGSql);
			}
		}

		#region Table Creation Script

		const string AUCSectionTableSql = @"
			CREATE TABLE AUCSection
			(
				UG_PK uniqueidentifier ROWGUIDCOL NOT NULL DEFAULT (newid()),
				UG_Description varchar(max) NOT NULL DEFAULT (''),
				UG_Section tinyint NOT NULL DEFAULT (0),
				UG_Notes varchar(max) NOT NULL DEFAULT (''),
				CONSTRAINT PK_AUCSection PRIMARY KEY NONCLUSTERED (UG_PK)
			)";

		const string AUCAHECCTableSql = @"
			CREATE TABLE AUCAHECC
			(
				UA_PK uniqueidentifier ROWGUIDCOL NOT NULL DEFAULT (newid()),
				UA_UA uniqueidentifier NULL,
				UA_Index int NOT NULL DEFAULT (0),
				UA_AHECC varchar(10) NOT NULL DEFAULT (''),
				UA_UQ char(2) NOT NULL DEFAULT (''),
				UA_ShortDescription varchar(1024) NOT NULL DEFAULT (''),
				UA_LongDescription varchar(1024) NOT NULL DEFAULT (''),
				UA_DateStart datetime NULL,
				UA_DateFinish datetime NULL,
				CONSTRAINT [PK_AUCAHECC] PRIMARY KEY NONCLUSTERED (UA_PK)
			)";

		const string AUCChapterTableSql = @"
			CREATE TABLE AUCChapter
			(
				UH_PK uniqueidentifier ROWGUIDCOL NOT NULL DEFAULT (newid()),
				UH_Description varchar(max) NOT NULL DEFAULT (''),
				UH_Chapter char(2) NOT NULL DEFAULT (''),
				UH_Notes varchar(max) NOT NULL DEFAULT (''),
				UH_UG uniqueidentifier NOT NULL,
				CONSTRAINT PK_AUCChapter PRIMARY KEY NONCLUSTERED (UH_PK)
			)";

		const string AUCClassTableSql = @"
			CREATE TABLE AUCClass
			(
				UJ_PK uniqueidentifier ROWGUIDCOL NOT NULL DEFAULT (newid()),
				UJ_UJ uniqueidentifier NULL,
				UJ_Code varchar(14) NOT NULL DEFAULT (''),
				UJ_Txt varchar(2048) NOT NULL DEFAULT (''),
				UJ_UQ1 char(3) NOT NULL DEFAULT (''),
				UJ_UQ2 char(3) NOT NULL DEFAULT (''),
				UJ_FTN varchar(20) NOT NULL DEFAULT (''),
				UJ_Rates varchar(1024) NOT NULL DEFAULT (''),
				UJ_OPR varchar(20) NOT NULL DEFAULT (''),
				UJ_OPS varchar(20) NOT NULL DEFAULT (''),
				UJ_STDesc varchar(1024) NOT NULL DEFAULT (''),
				CONSTRAINT PK_AUCClass PRIMARY KEY NONCLUSTERED (UJ_PK)
			)";

		const string AUCSectionIndexUG_SectionSql = "CREATE UNIQUE NONCLUSTERED INDEX UG_Section ON AUCSection (UG_Section)";
		const string AUCAHECCIndexNR_RX__UA_AHECCSql = "CREATE NONCLUSTERED INDEX NR_RX__UA_AHECC ON AUCAHECC (UA_AHECC)";
		const string AUCAHECCIndexAUCAHECCSql = "CREATE NONCLUSTERED INDEX AUCAHECC ON AUCAHECC (UA_UA)";
		const string AUCChapterIndexUH_ChapterSql = "CREATE UNIQUE NONCLUSTERED INDEX UH_Chapter ON AUCChapter (UH_Chapter)";
		const string AUCChapterIndexAUCSectionSql = "CREATE NONCLUSTERED INDEX AUCSection ON AUCChapter (UH_UG)";
		const string AUCClassIndexAUCClassSql = "CREATE NONCLUSTERED INDEX AUCClass ON AUCClass (UJ_UJ)";
		const string AUCClassIndexUJ_HDGSql = "CREATE NONCLUSTERED INDEX UJ_HDG ON AUCClass (UJ_Code)";

		#endregion
	}
}

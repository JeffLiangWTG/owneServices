		public static void DropTableIfExists(DbConnection conn, string tableName)
		{
			if (DbObjectCreator.TableExists(conn, tableName))
			{
				string sQLCommand = @"DROP TABLE " + tableName;
				conn.ExecuteNonQuery(sQLCommand);
			}
		}

		#region Version 1

		void DoVersion1Upgrade(DbConnection conn, int currentVersion)
		{
			if (currentVersion < 1)
			{
				CreateBaseDbObjectsIfNotExist(conn);
				CMRSeaImpendingArrivalsTableIfNotExist(conn);
				CreateCMRSACThesaurusTableIfNotExists(conn);
				CreateCMRAqisPostCodesTableIfNotExists(conn);
			}
		}


		protected override void DoDataUpgrade(DbConnection conn, int currentVersion)
		{
			DoVersion1Upgrade(conn, currentVersion);
			DoVersion4Upgrade(conn, currentVersion);
			DoVersion14Upgrade(conn, currentVersion);
			DoVersion15Upgrade(conn, currentVersion);
			DoVersion16Upgrade(conn, currentVersion);
		}


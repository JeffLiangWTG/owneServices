		protected override void CopyDataFromVersionBeforeUpgradeCore(int versionBeforeUpgrade, string previousRefDbName, string currentRefDbName)
		{
			AcquireUpdateLockForSharedDatabaseAndCopyData(currentRefDbName, nameof(ReferenceLockType.ScheduleB), () => CopyTableData(currentRefDbName, previousRefDbName, "USCScheduleB", "UB_PK", "UB_Code"));
			AcquireUpdateLockForSharedDatabaseAndCopyData(currentRefDbName, nameof(ReferenceLockType.FDAProductNumber), () => CopyTableData(currentRefDbName, previousRefDbName, "USCFDAProductNumber", "UP_PK", "UP_Code"));
			AcquireUpdateLockForSharedDatabaseAndCopyData(currentRefDbName, nameof(ReferenceLockType.Tariff), () => CopyTariffDetails(currentRefDbName, previousRefDbName));
		}

		[System.Diagnostics.CodeAnalysis.SuppressMessage("Microsoft.Maintainability", "CA1502:AvoidExcessiveComplexity")]
		void CopyTariffDetails(string currentRefDbName, string previousRefDbName)
		{
			var allUSCTariffColumnNames = GetColumnNames(currentRefDbName, previousRefDbName, upgradeConnection, "USCTariff");

			if (!allUSCTariffColumnNames.Contains("UE_Tariff") || !allUSCTariffColumnNames.Contains("UE_DateFrom") || !allUSCTariffColumnNames.Contains("UE_DateTo") || !allUSCTariffColumnNames.Contains("UE_PK"))
			{
				logger.ShowInfoMessage("Could not copy USCTariff data as table doesn't exists or table doesn't have these columns: UE_Tariff, UE_DateFrom, UE_DateTo, UE_PK.");
			}
			else
			{
				allUSCTariffColumnNames.Remove("UE_PK");
				var tariffcolumnNames = string.Join(", ", allUSCTariffColumnNames);
				var sqlText = new SqlQueryBuilder(string.Format(CultureInfo.InvariantCulture, @"
DECLARE @USCTariffCount INT, @sql NVARCHAR(MAX)
SET @USCTariffCount = 0
SET @sql = 
'
DECLARE @tblAlpha AS TABLE
(
	PreviousPK uniqueidentifier,
	NewPK uniqueidentifier
)

INSERT INTO @tblAlpha
SELECT UE_PK, NEWID()
FROM [{0}].dbo.USCTariff tblPre
WHERE NOT EXISTS (
	SELECT 1 FROM [{1}].dbo.USCTariff tblCur
	WHERE tblPre.UE_Tariff = tblCur.UE_Tariff
)

INSERT INTO [{1}].dbo.USCTariff (UE_PK, {2})
SELECT tblA.NewPK, {2}
FROM [{0}].dbo.USCTariff preTbl
INNER JOIN @tblAlpha tblA ON tblA.PreviousPK = preTbl.UE_PK

SET @USCTariffCount = @@ROWCOUNT;
"
	, previousRefDbName // {0}
	, currentRefDbName // {1}
	, tariffcolumnNames // {2}
));
				var useUSCTariffDateRestriction = GetTariffRelatedData(sqlText, currentRefDbName, previousRefDbName, "USCTariffDateRestriction", "UF_PK", "UF_UE");
				var useUSCTariffDutyRate = GetTariffRelatedData(sqlText, currentRefDbName, previousRefDbName, "USCTariffDutyRate", "UD_PK", "UD_UE");
				var useUSCTariffQuantity = GetTariffRelatedData(sqlText, currentRefDbName, previousRefDbName, "USCTariffQuantity", "UQ_PK", "UQ_UE");
				var useUSCTariffValue = GetTariffRelatedData(sqlText, currentRefDbName, previousRefDbName, "USCTariffValue", "UA_PK", "UA_UE");

				sqlText.Append(string.Format(CultureInfo.InvariantCulture, @"
'
{12}{13}{14}{15}
exec sp_executesql @sql,
N'
	@USCTariffCount int output{0}{1}{2}{3}
', @USCTariffCount = @USCTariffCount output{4}{5}{6}{7}

SELECT @USCTariffCount AS TariffCount{8}{9}{10}{11}
"
	, useUSCTariffDateRestriction ? @"
	, @USCTariffDateRestrictionCount int output" : "" // {0}
	, useUSCTariffDutyRate ? @"
	, @USCTariffDutyRateCount int output" : "" // {1}
	, useUSCTariffQuantity ? @"
	, @USCTariffQuantityCount int output" : "" // {2}
	, useUSCTariffValue ? @"
	, @USCTariffValueCount int output" : "" // {3}
	, useUSCTariffDateRestriction ? @"
	, @USCTariffDateRestrictionCount = @USCTariffDateRestrictionCount output" : "" // {4}
	, useUSCTariffDutyRate ? @"
	, @USCTariffDutyRateCount = @USCTariffDutyRateCount output" : "" // {5}
	, useUSCTariffQuantity ? @"
	, @USCTariffQuantityCount = @USCTariffQuantityCount output" : "" // {6}
	, useUSCTariffValue ? @"
	, @USCTariffValueCount = @USCTariffValueCount output" : "" // {7}
	, useUSCTariffDateRestriction ? @", @USCTariffDateRestrictionCount AS TariffDateRestrictionCount" : "" // {8}
	, useUSCTariffDutyRate ? @", @USCTariffDutyRateCount AS TariffDutyRateCount" : "" // {9}
	, useUSCTariffQuantity ? @", @USCTariffQuantityCount AS TariffQuantityCount" : "" // {10}
	, useUSCTariffValue ? @", @USCTariffValueCount AS TariffValueCount" : "" // {11}
	, useUSCTariffDateRestriction ? @"
DECLARE @USCTariffDateRestrictionCount INT" : "" // {12}
	, useUSCTariffDutyRate ? @"
DECLARE @USCTariffDutyRateCount INT" : "" // {13}
	, useUSCTariffQuantity ? @"
DECLARE @USCTariffQuantityCount INT" : "" // {14}
	, useUSCTariffValue ? @"
DECLARE @USCTariffValueCount INT" : "" // {15}
	));

				using (var reader = upgradeConnection.Command(sqlText.ToStringWithNewLineBetweenAppends()).ExecuteReader())
				{
					if (reader.Read())
					{
						var tariffCopies = (int)reader["TariffCount"];
						if (tariffCopies > 0)
						{
							logger.ShowInfoMessage(string.Format(CultureInfo.InvariantCulture, "{0} row(s) inserted into USCTariff.", tariffCopies));
						}
						if (useUSCTariffDateRestriction)
						{
							var tariffDateRestrictionCopies = (int)reader["TariffDateRestrictionCount"];
							if (tariffDateRestrictionCopies > 0)
							{
								logger.ShowInfoMessage(string.Format(CultureInfo.InvariantCulture, "{0} row(s) inserted into USCTariffDateRestriction.", tariffDateRestrictionCopies));
							}
						}
						if (useUSCTariffDutyRate)
						{
							var tariffDutyRateCopies = (int)reader["TariffDutyRateCount"];
							if (tariffDutyRateCopies > 0)
							{
								logger.ShowInfoMessage(string.Format(CultureInfo.InvariantCulture, "{0} row(s) inserted into USCTariffDutyRate.", tariffDutyRateCopies));
							}
						}
						if (useUSCTariffQuantity)
						{
							var tariffQuantityCopies = (int)reader["TariffQuantityCount"];
							if (tariffQuantityCopies > 0)
							{
								logger.ShowInfoMessage(string.Format(CultureInfo.InvariantCulture, "{0} row(s) inserted into USCTariffQuantity.", tariffQuantityCopies));
							}
						}
						if (useUSCTariffValue)
						{
							var tariffValueCopies = (int)reader["TariffValueCount"];
							if (tariffValueCopies > 0)
							{
								logger.ShowInfoMessage(string.Format(CultureInfo.InvariantCulture, "{0} row(s) inserted into USCTariffValue.", tariffValueCopies));
							}
						}
					}
				}
			}
		}

		bool GetTariffRelatedData(SqlQueryBuilder sqlText, string currentRefDbName, string previousRefDbName, string tableName, string primaryKey, string foreignKey)
		{
			var result = GetColumnNames(currentRefDbName, previousRefDbName, upgradeConnection, tableName);
			if (!result.Contains(primaryKey) || !result.Contains(foreignKey))
			{
				logger.ShowInfoMessage(string.Format(CultureInfo.InvariantCulture, "Could not copy {0} data as table doesn't exists or table doesn't have {1} or {2}.", tableName, primaryKey, foreignKey));
				result = null;
			}
			else
			{
				result.Remove(primaryKey);
				result.Remove(foreignKey);
				var columnNames = string.Join(", ", result);
				sqlText.Append(string.Format(CultureInfo.InvariantCulture, @"SET @{3}Count = 0

INSERT INTO [{0}].dbo.{3} ({4}, {5}, {2})
SELECT NEWID(), tblA.NewPK, {2}
FROM [{1}].dbo.{3}
INNER JOIN @tblAlpha tblA ON tblA.PreviousPK = {5}

SET @{3}Count = @@ROWCOUNT;
"
	, currentRefDbName // ({0}
	, previousRefDbName // {1}
	, columnNames // {2}
	, tableName // {3}
	, primaryKey // {4}
	, foreignKey // {5}
));
			}
			return result != null;
		}

		void CopyTableData(string currentRefDbName, string previousRefDbName, string tableName, string primaryPK, string naturalKey)
		{
			var allColumnNames = GetColumnNames(currentRefDbName, previousRefDbName, upgradeConnection, tableName);
			if (!allColumnNames.Contains(primaryPK) || !allColumnNames.Contains(naturalKey))
			{
				logger.ShowInfoMessage(string.Format(CultureInfo.InvariantCulture, "Could not copy {0} data as table doesn't exists or table doesn't have {1} or {2}.", tableName, primaryPK, naturalKey));
			}
			else
			{
				allColumnNames.Remove(primaryPK);
				var columnNames = string.Join(", ", allColumnNames);
				var sqlText = string.Format(CultureInfo.InvariantCulture, @"INSERT INTO [{0}].dbo.[{3}] ({4}, {1})
				SELECT NEWID(), {1} FROM [{2}].dbo.[{3}]
				WHERE RTrim(LTRim({5})) <> '' AND {5} NOT IN (
					SELECT {5} FROM [{0}].dbo.[{3}]
				)
				SELECT @@ROWCOUNT;
				"
	, currentRefDbName // ({0}
	, columnNames // {1}
	, previousRefDbName // {2}
	, tableName // {3}
	, primaryPK // {4}
	, naturalKey // {5}
);
				var rowCopies = (int)upgradeConnection.ExecuteScalar(sqlText);
				if (rowCopies > 0)
				{
					logger.ShowInfoMessage(string.Format(CultureInfo.InvariantCulture, "{0} row(s) inserted into {1}.", rowCopies, tableName));
				}
			}
		}

		protected override void DoDataUpgrade(DbConnection conn, int currentVersion)
		{
			if (currentVersion == 0)
			{
				InitialiseDatabase(conn);
			}

			if (ShouldUpgradeScheduleBData(conn))
			{
				new USRefDbScriptRunner(conn, this).ReplaceScheduleBData();
			}

			UpdateData(conn, currentVersion);

			CreateIndexesIfNotExist(conn);
		}

		bool ShouldUpgradeScheduleBData(DbConnection conn)
		{
			return (int)conn.ExecuteScalar(USCDataVersionExists) == 0 ||
				(int)conn.ExecuteScalar(string.Format(USCScheduleBDataVersionCheck, ScheduleBDataVersionYear)) == 0 ||
				(int)conn.ExecuteScalar(USCScheduleBRecordCountCheck) == 0;
		}

		const string USCDataVersionExists = "SELECT CASE WHEN OBJECT_ID('USCDataVersion') IS NOT NULL THEN 1 ELSE 0 END";
		const string USCScheduleBDataVersionCheck = "SELECT CASE WHEN COUNT(UZ_PK) > 0 THEN 1 ELSE 0 END FROM USCDataVersion WHERE UZ_Name = 'ScheduleBDataVersion' AND UZ_Version = '{0}'";
		const string USCScheduleBRecordCountCheck = "SELECT COUNT(*) FROM USCScheduleB";

		void InitialiseDatabase(DbConnection conn)
		{
			DbSchemaChange.DropAllTables(conn);
			RecreateObjects(conn);
		}

		void RecreateObjects(DbConnection conn)
		{
			CreateTables(conn, Tables.ToArray());
		}


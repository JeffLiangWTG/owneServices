		protected static void UpgradeConcessionTable(DbConnection conn)
		{
			string sqlText = @"
				IF not exists(SELECT null FROM sys.columns WHERE name = 'U2_DateActiveTo')
					ALTER TABLE NZCConcession ADD U2_DateActiveTo datetime NULL;";

			using (var command = conn.Command(sqlText))
			{
				command.ExecuteNonQuery();
			}
		}

		protected static void IncreaseDutyRatePercentPrecisionAndScale(DbConnection conn)
		{
			string sqlText = @"
				IF EXISTS (SELECT NULL FROM sys.columns WHERE name = 'U1_DutyRatePercent')
					ALTER TABLE NZCClassificationDutyRate
						ALTER COLUMN U1_DutyRatePercent decimal(12,6) NOT NULL;";

			using (var command = conn.Command(sqlText))
			{
				command.ExecuteNonQuery();
			}
		}

		protected static void DropFlightsAndVesselsTable(DbConnection conn)
		{
			if (DbObjectCreator.TableExists(conn, FlightsAndVesselsTableName))
			{
				using (var command = conn.Command("DROP TABLE " + FlightsAndVesselsTableName))
				{
					command.ExecuteNonQuery();
				}
			}
		}

		public NZTariffReferenceDbUpgrader(IUpgradeContext upgradeContext, DbConnection upgradeConnection, IUpgradeTaskWorkflowLogger logger)
			: base(upgradeContext, upgradeConnection, logger)
		{
		}

		public override string ReferenceName
		{
			get { return "NZ Tariff"; }
		}

		public override RefDbTypeEnum DatabaseType
		{
			get { return RefDbTypeEnum.Tariff; }
		}

		public override string CountryCode
		{
			get { return "NZ"; }
		}

		protected override void DoDataUpgrade(DbConnection conn, int currentVersion)
		{
			if (currentVersion < 2)
			{
				CreateInitialTables(conn);
			}

			if (currentVersion < 4)
			{
				UpgradeBlobToVarMaxDataType(conn);
			}

			RunUpgradeStep(currentVersion, 7, () => UpgradeConcessionTable(conn));
			RunUpgradeStep(currentVersion, 9, () => IncreaseDutyRatePercentPrecisionAndScale(conn));
			RunUpgradeStep(currentVersion, 15, () => DropFlightsAndVesselsTable(conn));
		}

		//------------------------------------------------------------------------------
		// Please Read. Any questions, please talk to Joo or Brendon or Dong
		//------------------------------------------------------------------------------
		//	Reference File upgrade occurs only when there is a schema version number change in the main Enterprise database.
		//	When this number increases, please make sure there is a schema version number bumped up too. For alpha, it should be a major number. For releases, it should be a minor version number.
		//	Schema version number is located in $/Dev/Database/Odyssey/Resource/Version/AutoGenerated/SchemaVersion.cs
		//	All changes in reference files should be patched to releases even if WIs are enhancements that are meant to be checked into alpha because there might be subsequent upgrades that need to be patched to releases.
		public override int LatestVersion
		{
			get { return 15; }
		}


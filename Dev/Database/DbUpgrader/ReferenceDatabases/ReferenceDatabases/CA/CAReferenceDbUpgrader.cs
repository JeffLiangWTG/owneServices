		protected override void DoDataUpgrade(DbConnection conn, int currentVersion)
		{
			var upgraded = false;

			DropViewsIfExists(conn);
			foreach (var upgrade in Upgrades)
			{
				if (currentVersion < upgrade.Version)
				{
					upgrade.DoUpgrade(conn);
					if (!upgraded)
					{
						upgraded = true;
					}
				}
			}
			CreateViews(conn);
			CreateIndexesIfNotExist(conn);

			if (upgraded)
			{
				SetRefreshRequired(conn);
			}
		}

		protected override string CsvFileStoragePath
		{
			get { return base.CsvFileStoragePath + "CA.Data."; }
		}

		#region RefreshRequired

		internal const string RefreshRequiredPropertyName = "RefreshRequired";

		public static void SetRefreshRequired(DbConnection conn)
		{
			var newValue = "Y";
			var oldValue = DataUtils.LoadDbExtendedProperty(conn, RefreshRequiredPropertyName);
			if (oldValue == null)
			{
				DataUtils.AddDbExtendedProperty(conn, RefreshRequiredPropertyName, newValue);
			}
			else if (oldValue != newValue)
			{
				DataUtils.SaveDbExtendedProperty(conn, RefreshRequiredPropertyName, newValue);
			}
		}


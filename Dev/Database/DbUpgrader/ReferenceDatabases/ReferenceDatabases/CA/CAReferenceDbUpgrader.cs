		class Upgrade
		{
			public Upgrade(int version, DoUpgradeDelegate doUpgrade)
			{
				Version = version;
				DoUpgrade = doUpgrade;
			}

			public int Version { get; private set; }
			public DoUpgradeDelegate DoUpgrade { get; private set; }
		}

		delegate void DoUpgradeDelegate(DbConnection conn);

		void DropTableIfExists(DbConnection conn, string tableName)
		{
			if (DbObjectCreator.TableExists(conn, tableName))
			{
				string sQLCommand = @"DROP TABLE " + tableName;
				conn.ExecuteNonQuery(sQLCommand);
			}
		}

		void DropViewsIfExists(DbConnection connection)
		{
			DropViewIfExists(connection, "CACDocumentTypesCombinedView");
		}

		void CreateViews(DbConnection connection)
		{
			CreateViewFromSqlFile(connection, "CACDocumentTypesCombinedView.sql");
		}

		void DropViewIfExists(DbConnection conn, string viewName)
		{
			if (DbObjectCreator.ViewExists(conn, viewName))
			{
				var sQLCommand = @"DROP VIEW " + viewName;
				conn.ExecuteNonQuery(sQLCommand);
			}
		}

		void CreateViewFromSqlFile(DbConnection conn, string embeddedResourceFileName)
		{
			using (var stream = GetType().Assembly.GetManifestResourceStream("Enterprise.DbUpgrader.ReferenceDatabases.CA.View." + embeddedResourceFileName))
			{
				if (stream != null)
				{
					var sqlScript = new StreamReader(stream).ReadToEnd();
					conn.ExecuteNonQuery(sqlScript);
				}
			}
		}


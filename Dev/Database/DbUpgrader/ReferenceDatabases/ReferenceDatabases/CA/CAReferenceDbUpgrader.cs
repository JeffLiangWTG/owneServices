		void DoVersion171Upgrade_PGAHSCode(DbConnection connection)
		{
			var tableScriptCACPGAHSCode = new CACPGAHSCode();
			DropTableIfExists(connection, tableScriptCACPGAHSCode.TableName);
			CreateTables(connection, new ITableScript[] { tableScriptCACPGAHSCode });
			ClearAndRePopulateTables(connection, new IPopulateData[] { tableScriptCACPGAHSCode }, (string line) =>
			{
				string[] columns = line.Split(',');
				string hcFromHS = columns[1];
				string hcToHS = columns[2];

				if (int.TryParse(hcFromHS, out int hcFromHSInt))
				{
					columns[1] = hcFromHS.PadRight(10, '0');
				}

				if (int.TryParse(hcToHS, out int hcToHSInt))
				{
					// WITHIN RANGE
					columns[2] = hcToHS.PadRight(10, '0');
				}
				else if (string.IsNullOrEmpty(hcToHS))
				{
					if (hcFromHS.Length == 10)
					{
						// EQUAL TO
						columns[2] = hcFromHS;
					}
					else
					{
						// STARTS WITH
						columns[2] = hcFromHS.PadRight(10, '9');
					}
				}
				return string.Join(",", columns);
			});
			PopulateTableFromCsvFile(connection, ',', "CACPGAHSCode_GAC.csv", tableScriptCACPGAHSCode.TableName, tableScriptCACPGAHSCode.ColumnSqlList, tableScriptCACPGAHSCode.ColumnTypes, false);
		}


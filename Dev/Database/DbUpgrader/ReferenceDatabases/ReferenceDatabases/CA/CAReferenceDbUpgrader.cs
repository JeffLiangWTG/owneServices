		#region Version 146 Upgrade
		void DoVersion146Upgrade(DbConnection connection)
		{
			var script = $@"
UPDATE Main
SET Main.ZA_ExpiryDate = DATEADD(DAY, -1, Temp.NewExpiryDate)
FROM CACClassHeader Main
INNER JOIN
(
SELECT TempTable.* FROM 
(SELECT ZA_PK, ZA_ExpiryDate,
LAG(ZA_EffectiveDate) OVER (PARTITION BY ZA_ClassificationNumber ORDER BY ZA_EffectiveDate DESC) AS NewExpiryDate
FROM CACClassHeader
)TempTable
WHERE TempTable.NewExpiryDate IS NOT NULL AND ZA_ExpiryDate >= NewExpiryDate
)
Temp ON Temp.ZA_PK = Main.ZA_PK
";
			connection.ExecuteNonQuery(script);
		}


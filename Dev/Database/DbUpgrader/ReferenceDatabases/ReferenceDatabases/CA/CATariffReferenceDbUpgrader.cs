using CargoWise.Data;
using CargoWise.DbUpgrader.Foundation;
using Enterprise.DbUpgrader.Shared;

namespace Enterprise.DbUpgrader.ReferenceDatabases.CA
{
	class CATariffReferenceDbUpgrader : ReferenceDbUpgrader
	{
		#region Factory Class

		public class CATrfRefDbUpgraderFactory : IRefDbUpgraderFactory
		{
			public ReferenceDbUpgrader New(IUpgradeContext upgradeContext, DbConnection upgradeConnection, IUpgradeTaskWorkflowLogger logger)
			{
				return new CATariffReferenceDbUpgrader(upgradeContext, upgradeConnection, logger);
			}
		}

		#endregion

		public CATariffReferenceDbUpgrader(IUpgradeContext upgradeContext, DbConnection upgradeConnection, IUpgradeTaskWorkflowLogger logger)
			: base(upgradeContext, upgradeConnection, logger)
		{
		}

		public override string ReferenceName
		{
			get { return "CA EdiTariff"; }
		}

		public override RefDbTypeEnum DatabaseType
		{
			get { return RefDbTypeEnum.Tariff; }
		}

		public override string CountryCode
		{
			get { return "CA"; }
		}

		//------------------------------------------------------------------------------
		// Please Read. Any questions, please talk to Joo or Brendon or Dong
		//------------------------------------------------------------------------------
		//	Reference File upgrade occurs only when there is a schema version number change in the main Enterprise database.
		//	When this number increases, please make sure there is a schema version number bumped up too. For alpha, it should be a major number. For releases, it should be a minor version number.
		//	Schema version number is located in $/Dev/Database/Odyssey/Resource/Version/AutoGenerated/SchemaVersion.cs
		//	All changes in reference files should be patched to releases even if WIs are enhancements that are meant to be checked into alpha because there might be subsequent upgrades that need to be patched to releases.
		public override int LatestVersion
		{
			get { return 10; }
		}

		protected override void DoDataUpgrade(DbConnection conn, int currentVersion)
		{
			if (currentVersion < 1)
			{
				DoVersion1Upgrade(conn);
			}
		}

		#region Version 1 Upgrade

		void DoVersion1Upgrade(DbConnection conn)
		{
			DbObjectCreator.CreateTableIfNotExists(conn, "CACClass", CACClassCreationScript);
			CreateIndexIfNotExists(conn, "CACClass", "NR_UX__CT_Tariff", CACClassIndexCreationScript);
		}

		const string CACClassCreationScript = @"
CREATE TABLE CACClass
(
	CT_PK uniqueidentifier NOT NULL DEFAULT (newid()),
	CT_Tariff nvarchar(10) NOT NULL,
	CT_DateFrom datetime NULL,
	CT_DateTo datetime NULL,
	CT_LongDescription nvarchar(1024) NOT NULL,
	CT_UQ nvarchar(4) NOT NULL,
	CT_IsConveyanceIDRequired CHAR(1) NOT NULL DEFAULT ('N'),
	CT_RateMFN nvarchar(80) NOT NULL,
	CT_RateGT nvarchar(80) NOT NULL,
	CT_RateAUT nvarchar(80) NOT NULL,
	CT_RateNZT nvarchar(80) NOT NULL,
	CT_RateCCCT nvarchar(80) NOT NULL,
	CT_RateLDCT nvarchar(80) NOT NULL,
	CT_RateGPT nvarchar(80) NOT NULL,
	CT_RateUST nvarchar(80) NOT NULL,
	CT_RateMT nvarchar(80) NOT NULL,
	CT_RateMUST nvarchar(80) NOT NULL,
	CT_RateCIAT nvarchar(80) NOT NULL,
	CT_RateCT nvarchar(80) NOT NULL,
	CT_RateCRT nvarchar(80) NOT NULL,

	CONSTRAINT PK_CACClass PRIMARY KEY NONCLUSTERED 
	(
		CT_PK ASC
	)
)";

		const string CACClassIndexCreationScript = @"
CREATE UNIQUE NONCLUSTERED INDEX NR_UX__CT_Tariff ON CACClass 
(
	CT_Tariff ASC
)";

		#endregion
	}
}

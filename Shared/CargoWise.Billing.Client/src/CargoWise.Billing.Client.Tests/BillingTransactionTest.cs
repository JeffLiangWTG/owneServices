using System.Linq;
using System.Reflection;
using CargoWise.Billing.API;
using AutoGeneratedBillingTransaction = CargoWise.Billing.Client.BillingServiceReference.BillingTransaction;

namespace CargoWise.Billing.Client.Tests
{
    [TestFixture]
    public class BillingTransactionTest
    {
        [Test]
        public void TestHasSamePropertiesAsAutoGeneratedTransaction()
        {
            Assert.That(
                typeof(BillingTransaction).GetProperties().Select(p => new { p.Name, p.PropertyType }),
                Is.EquivalentTo(typeof(AutoGeneratedBillingTransaction).GetProperties(BindingFlags.Instance | BindingFlags.NonPublic).Select(p => new { p.Name, p.PropertyType })));
        }
    }
}

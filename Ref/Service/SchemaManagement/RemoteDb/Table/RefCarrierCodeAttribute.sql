	CONSTRAINT CK_RefCarrierCodeAttribute_ZZG_Name CHECK (ZZG_Name <>''),
	CONSTRAINT CK_RefCarrierCodeAttribute_ZZG_Value CHECK (ZZG_Value <>'')
)
GO

	ZZG_Name VARCHAR(32) NOT NULL,
	ZZG_Value NVARCHAR(100) NOT NULL,
	CONSTRAINT PK_RefCarrierCodeAttribute PRIMARY KEY CLUSTERED( ZZG_PK ASC ),

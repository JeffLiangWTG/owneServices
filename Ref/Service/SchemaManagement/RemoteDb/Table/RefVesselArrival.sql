CREATE TABLE RefVesselArrival
(
ZYA_PK UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_RefVesselArrival_ZYA_PK DEFAULT (NEWID()),
ZYA_ZZO_Vessel UNIQUEIDENTIFIER NOT NULL,
ZYA_VoyageNumber VARCHAR(10) NOT NULL,
ZYA_ArrivalDate SMALLDATETIME NOT NULL,
ZYA_ArrivalPort VARCHAR(5) NOT NULL CONSTRAINT DF_RefVesselArrival_ZYA_ArrivalPort DEFAULT (''),
CONSTRAINT PK_RefVesselArrival PRIMARY KEY CLUSTERED (ZYA_PK ASC),
CONSTRAINT FK_RefVesselArrival_RefVesselZZ FOREIGN KEY(ZYA_ZZO_Vessel) REFERENCES RefVesselZZ (ZZO_PK),
CONSTRAINT CK_RefVesselArrival_ZYA_VoyageNumber CHECK (ZYA_VoyageNumber <> ''),
)
GO
CREATE UNIQUE NONCLUSTERED INDEX IX_RefVesselArrival_ZYA_ZZO_Vessel_ZYA_VoyageNumber_ZYA_ArrivalDate ON RefVesselArrival (ZYA_ZZO_Vessel ASC, ZYA_VoyageNumber ASC, ZYA_ArrivalDate ASC)
GO

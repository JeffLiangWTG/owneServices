CREATE TABLE RefCusMapType 
(
ZZP_PK UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_RefCusMapType_ZZP_PK DEFAULT (NEWID()),
ZZP_MapType VARCHAR(5) NOT NULL,
ZZP_Direction VARCHAR(3) NOT NULL CONSTRAINT DF_RefCusMapType_ZZP_Direction DEFAULT ('BTH'),
ZZP_Description NVARCHAR(500) NOT NULL,
ZZP_IsReadonly BIT NOT NULL CONSTRAINT DF_RefCusMapType_ZZP_IsReadonly DEFAULT (0),
CONSTRAINT PK_RefCusMapType PRIMARY KEY CLUSTERED (ZZP_PK ASC),
CONSTRAINT CK_RefCusMapType_ZZP_MapType CHECK (ZZP_MapType <> ''),
CONSTRAINT CK_RefCusMapType_ZZP_Direction CHECK ([ZZP_Direction]='ANY' OR [ZZP_Direction]='OUT' OR [ZZP_Direction]='INW' OR [ZZP_Direction]='BTH'),
CONSTRAINT CK_RefCusMapType_ZZP_Description CHECK (ZZP_Description <> ''),
)
GO
CREATE UNIQUE NONCLUSTERED INDEX IX_RefCusMapType_ZZP_MapType ON RefCusMapType(ZZP_MapType ASC)
GO

CREATE VIEW RefCusCodeListTransportModeView_V1
WITH SCHEMABINDING 
AS
SELECT ZZU_ZZD_CodeList,
	SUM(CASE WHEN ZZU_TransportMode = 'AIR' THEN 1 ELSE 0 END) AS ZZD_IsAir,
	SUM(CASE WHEN ZZU_TransportMode = 'SEA' THEN 1 ELSE 0 END) AS ZZD_IsSea,
	SUM(CASE WHEN ZZU_TransportMode = 'FIX' THEN 1 ELSE 0 END) AS ZZD_IsFix,
	SUM(CASE WHEN ZZU_TransportMode = 'RAI' THEN 1 ELSE 0 END) AS ZZD_IsRai,
	SUM(CASE WHEN ZZU_TransportMode = 'ROA' THEN 1 ELSE 0 END) AS ZZD_IsRoa,
	SUM(CASE WHEN ZZU_TransportMode = 'MAI' THEN 1 ELSE 0 END) AS ZZD_IsMai,
	SUM(CASE WHEN ZZU_TransportMode = 'INW' THEN 1 ELSE 0 END) AS ZZD_IsInw,
	COUNT_BIG(*) CNT
FROM dbo.RefCusCodeOrAttributeTransportMode
WHERE ZZU_ZZD_CodeList IS NOT NULL
GROUP BY ZZU_ZZD_CodeList

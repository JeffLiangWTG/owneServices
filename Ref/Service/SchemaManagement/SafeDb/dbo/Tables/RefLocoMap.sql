CREATE TABLE RefLocoMap(
	[RY_PK] UNIQUEIDENTIFIER NOT NULL,
	[RY_LocalPortCode] VARCHAR(10) NOT NULL CONSTRAINT [DF_RY_LocalPortCode] DEFAULT (''),
	[RY_RL_NKLocoPort] VARCHAR(5) NOT NULL CONSTRAINT [DF_RY_RL_NKLocoPort] DEFAULT (''),
	[RY_SystemUsage] VARCHAR(3) NOT NULL CONSTRAINT [DF_RY_SystemUsage] DEFAULT (''),
	[RY_RN_NKCountryCode] CHAR(2) NULL,
	[RY_SysStartTime] DATETIME2 GENERATED ALWAYS AS ROW START NOT NULL CONSTRAINT [DF_RY_SysStartTime] DEFAULT CONVERT(DATETIME2, '1900-01-01 0:0:0.0000000'),
	[RY_SysEndTime] DATETIME2 GENERATED ALWAYS AS ROW END NOT NULL CONSTRAINT [DF_RY_SysEndTime] DEFAULT CONVERT(DATETIME2, '9999-12-31 23:59:59.9999999'),
	PERIOD FOR SYSTEM_TIME ([RY_SysStartTime], [RY_SysEndTime]),
	CONSTRAINT [PK_RefLocoMap] PRIMARY KEY CLUSTERED ([RY_PK] ASC),
	CONSTRAINT [RefLocoMap_RefCountry] FOREIGN KEY([RY_RN_NKCountryCode]) REFERENCES RefCountry([RN_Code]),
	CONSTRAINT [FK_RefLocoMap_RefUNLOCO] FOREIGN KEY([RY_RL_NKLocoPort]) REFERENCES RefUNLOCO ([RL_Code])
)
WITH (SYSTEM_VERSIONING = ON (HISTORY_TABLE = dbo.RefLocoMapHistory))
GO
CREATE UNIQUE NONCLUSTERED INDEX [NR_UX_RY__RL_NKLocoPort_RY_LocalPortCode_RY_SystemUsage_RY_RN_NKCountryCode] ON [RefLocoMap] ([RY_RL_NKLocoPort] ASC, [RY_LocalPortCode] ASC,[RY_SystemUsage] ASC,[RY_RN_NKCountryCode] ASC)
GO
ALTER TABLE RefLocoMap SET (LOCK_ESCALATION = DISABLE);

CREATE TABLE RefTimeZoneSet(
	[R3_PK] UNIQUEIDENTIFIER NOT NULL CONSTRAINT [DF_RefTimeZoneSet_R3_PK] DEFAULT (NEWID()),
	[R3_TimeZoneSetName] VARCHAR(35) NOT NULL CONSTRAINT [DF_RefTimeZoneSet_R3_TimeZoneSetName] DEFAULT (''),
	[R3_IsActive] BIT NOT NULL CONSTRAINT [DF_RefTimeZoneSet_R3_IsActive] DEFAULT(1),
	[R3_SysStartTime] DATETIME2 GENERATED ALWAYS AS ROW START NOT NULL CONSTRAINT [DF_R3_SysStartTime] DEFAULT CONVERT(DATETIME2, '1900-01-01 0:0:0.0000000'),
	[R3_SysEndTime] DATETIME2 GENERATED ALWAYS AS ROW END NOT NULL CONSTRAINT [DF_R3_SysEndTime] DEFAULT CONVERT(DATETIME2, '9999-12-31 23:59:59.9999999'),
	PERIOD FOR SYSTEM_TIME ([R3_SysStartTime], [R3_SysEndTime]),
	CONSTRAINT [PK_RefTimeZoneSet_R3_PK] PRIMARY KEY CLUSTERED ([R3_PK] ASC),
)
WITH (SYSTEM_VERSIONING = ON (HISTORY_TABLE = dbo.RefTimeZoneSetHistory))
GO
CREATE UNIQUE NONCLUSTERED INDEX IX_RefTimeZoneSet_R3_TimeZoneSetName ON RefTimeZoneSet (R3_TimeZoneSetName)
GO
ALTER TABLE RefTimeZoneSet SET (LOCK_ESCALATION = DISABLE);

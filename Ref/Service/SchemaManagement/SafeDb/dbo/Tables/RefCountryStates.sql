CREATE TABLE RefCountryStates(
	[RW_PK] UNIQUEIDENTIFIER NOT NULL,
	[RW_Description] NVARCHAR(35) NOT NULL,
	[RW_RegionName] NVARCHAR(35) NOT NULL,
	[RW_IsActive] BIT NOT NULL,
	[RW_Code] VARCHAR(3) NOT NULL,
	[RW_RN_NKCountryCode] CHAR(2) NOT NULL,
	[RW_SysStartTime] DATETIME2 GENERATED ALWAYS AS ROW START NOT NULL CONSTRAINT [DF_RW_SysStartTime] DEFAULT CONVERT(DATETIME2, '1900-01-01 0:0:0.0000000'),
	[RW_SysEndTime] DATETIME2 GENERATED ALWAYS AS ROW END NOT NULL CONSTRAINT [DF_RW_SysEndTime] DEFAULT CONVERT(DATETIME2, '9999-12-31 23:59:59.9999999'),
	PERIOD FOR SYSTEM_TIME ([RW_SysStartTime], [RW_SysEndTime]),
	CONSTRAINT [PK_UX__RW_PK] PRIMARY KEY NONCLUSTERED ([RW_PK] ASC)
)
WITH (SYSTEM_VERSIONING = ON (HISTORY_TABLE = dbo.RefCountryStatesHistory))
GO
CREATE UNIQUE NONCLUSTERED INDEX [NR_UX__RW_RN_NKCountryCode_RW_Code] ON [dbo].[RefCountryStates]
(
	[RW_RN_NKCountryCode] ASC,
	[RW_Code] ASC
)
GO
ALTER TABLE RefCountryStates SET (LOCK_ESCALATION = DISABLE);

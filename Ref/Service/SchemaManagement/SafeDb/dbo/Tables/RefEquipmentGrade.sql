CREATE TABLE RefEquipmentGrade
(
	[REG_PK] UNIQUEIDENTIFIER NOT NULL CONSTRAINT [DF_RefEquipmentGrade_REG_PK] DEFAULT NEWID(),
	[REG_IsActive] BIT NOT NULL CONSTRAINT [DF_RefEquipmentGrade_REG_IsActive] DEFAULT 1,
	[REG_Code] VARCHAR(3) NOT NULL CONSTRAINT [DF_RefEquipmentGrade_REG_Code] DEFAULT '',
	[REG_Description] VARCHAR(50) NOT NULL CONSTRAINT [DF_RefEquipmentGrade_REG_Desciption] DEFAULT '',
	[REG_SysStartTime] DATETIME2 GENERATED ALWAYS AS ROW START NOT NULL CONSTRAINT [DF_REG_SysStartTime] DEFAULT CONVERT(DATETIME2, SYSUTCDATETIME()),
	[REG_SysEndTime] DATETIME2 GENERATED ALWAYS AS ROW END NOT NULL CONSTRAINT [DF_REG_SysEndTime] DEFAULT CONVERT(DATETIME2, '9999-12-31 23:59:59.9999999'),
	PERIOD FOR SYSTEM_TIME ([REG_SysStartTime], [REG_SysEndTime]),
	CONSTRAINT [PK_RefEquipmentGrade] PRIMARY KEY CLUSTERED ([REG_PK] ASC),
	CONSTRAINT [CK_RefEquipmentGrade_REG_Code] CHECK  ([REG_Code] <> ''),
	CONSTRAINT [CK_RefEquipmentGrade_REG_Description] CHECK  ([REG_Description] <> '')
)
WITH (SYSTEM_VERSIONING = ON (HISTORY_TABLE = dbo.RefEquipmentGradeHistory))
GO
CREATE UNIQUE NONCLUSTERED INDEX IX_RefEquipmentGrade_REG_Code ON RefEquipmentGrade(REG_Code)
GO
ALTER TABLE RefEquipmentGrade SET (LOCK_ESCALATION = DISABLE);
GO

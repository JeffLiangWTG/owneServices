CREATE TABLE [dbo].[RefAccessorial]
(
	[ASI_PK] UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_RefAccessorial_ASI_PK DEFAULT (NEWID()),
	[ASI_Code] CHAR(3) NOT NULL CONSTRAINT DF_RefAccessorial_ASI_Code DEFAULT (''), 
	[ASI_Description] VARCHAR(50) NOT NULL CONSTRAINT DF_RefAccessorial_ASI_Description DEFAULT (''),
	[ASI_SysStartTime] DATETIME2 GENERATED ALWAYS AS ROW START NOT NULL CONSTRAINT [DF_RefAccessorial_ASI_SysStartTime] DEFAULT SYSUTCDATETIME(),
	[ASI_SysEndTime] DATETIME2 GENERATED ALWAYS AS ROW END NOT NULL CONSTRAINT [DF_RefAccessorial_ASI_SysEndTime] DEFAULT CONVERT(DATETIME2, '9999-12-31 23:59:59.9999999'),
	PERIOD FOR SYSTEM_TIME ([ASI_SysStartTime], [ASI_SysEndTime]),
	CONSTRAINT [PK_RefAccessorial] PRIMARY KEY CLUSTERED ([ASI_PK]), 
	CONSTRAINT [CK_RefAccessorial_ASI_Code] CHECK (LEN([ASI_Code])=(3)), 
	CONSTRAINT [CK_RefAccessorial_ASI_Description] CHECK ([ASI_Description]<>''))
WITH (SYSTEM_VERSIONING = ON (HISTORY_TABLE = dbo.RefAccessorialHistory))
GO
CREATE UNIQUE NONCLUSTERED INDEX [IX_RefAccessorial_ASI_Code] ON [dbo].[RefAccessorial] ([ASI_Code])
GO
ALTER TABLE RefAccessorial SET (LOCK_ESCALATION = DISABLE);
GO

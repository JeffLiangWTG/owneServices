CREATE TABLE RefCurrency (
	[RX_PK] UNIQUEIDENTIFIER NOT NULL,
	[RX_Code] CHAR(3) NOT NULL CONSTRAINT [DF_RX_Code] DEFAULT (''),
	[RX_IsActive] BIT NOT NULL CONSTRAINT [DF_RX_IsActive] DEFAULT (1),
	[RX_Symbol] NVARCHAR(3) NOT NULL CONSTRAINT [DF_RX_Symbol] DEFAULT (''),
	[RX_Desc] NVARCHAR(35) NOT NULL CONSTRAINT [DF_RX_Desc] DEFAULT (''),
	[RX_UnitName] VARCHAR(20) NOT NULL CONSTRAINT [DF_RX_UnitName] DEFAULT (''),
	[RX_SubUnitName] VARCHAR(20) NOT NULL CONSTRAINT [DF_RX_SubUnitName] DEFAULT (''),
	[RX_SubUnitRatio] INT NOT NULL CONSTRAINT [DF_RX_SubUnitRatio] DEFAULT ((100)),
	[RX_ISOSubUnitRatio] INT NOT NULL CONSTRAINT DF_RX_ISOSubUnitRatio DEFAULT 0,
	[RX_SysStartTime] DATETIME2 GENERATED ALWAYS AS ROW START NOT NULL CONSTRAINT [DF_RX_SysStartTime] DEFAULT CONVERT(DATETIME2, '1900-01-01 0:0:0.0000000'),
	[RX_SysEndTime] DATETIME2 GENERATED ALWAYS AS ROW END NOT NULL CONSTRAINT [DF_RX_SysEndTime] DEFAULT CONVERT(DATETIME2, '9999-12-31 23:59:59.9999999'),
	PERIOD FOR SYSTEM_TIME ([RX_SysStartTime], [RX_SysEndTime]),
 CONSTRAINT PK_UX__RX_PK PRIMARY KEY CLUSTERED (RX_PK ASC),
 CONSTRAINT [Constraint_RX_ISOSubUnitRatio] CHECK (RX_ISOSubUnitRatio >= 1)
)
WITH (SYSTEM_VERSIONING = ON (HISTORY_TABLE = dbo.RefCurrencyHistory))
GO
CREATE UNIQUE NONCLUSTERED INDEX [NR_UX_RX_Code] ON [RefCurrency] ([RX_Code] ASC)
GO
ALTER TABLE RefCurrency SET (LOCK_ESCALATION = DISABLE);

CREATE TABLE RefCusProfileQuestionLanguage
(
	XQL_PK UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_RefCusProfileQuestionLanguage_XQL_PK DEFAULT (NEWID()),

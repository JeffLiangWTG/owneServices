CREATE TABLE UNDGAttribute(
	[DA_PK] UNIQUEIDENTIFIER NOT NULL,
	[DA_Language] VARCHAR(3) NOT NULL CONSTRAINT [DF_UNDGAttribute_DA_Language] DEFAULT '',
	[DA_Type] VARCHAR(3) NOT NULL CONSTRAINT [DF_UNDGAttribute_DA_Type] DEFAULT '',
	[DA_Index] VARCHAR(6) NOT NULL CONSTRAINT [DF_UNDGAttribute_DA_Index] DEFAULT '',
	[DA_Descriptor] NVARCHAR(MAX) NOT NULL CONSTRAINT [DF_UNDGAttribute_DA_Descriptor] DEFAULT '',
	[DA_DG] UNIQUEIDENTIFIER NOT NULL,
	[DA_SysStartTime] DATETIME2 GENERATED ALWAYS AS ROW START NOT NULL CONSTRAINT [DF_DA_SysStartTime] DEFAULT CONVERT(DATETIME2, '1900-01-01 0:0:0.0000000'),
	[DA_SysEndTime] DATETIME2 GENERATED ALWAYS AS ROW END NOT NULL CONSTRAINT [DF_DA_SysEndTime] DEFAULT CONVERT(DATETIME2, '9999-12-31 23:59:59.9999999'),
	PERIOD FOR SYSTEM_TIME ([DA_SysStartTime], [DA_SysEndTime]),
	CONSTRAINT [PK_UNDGAttribute] PRIMARY KEY NONCLUSTERED  ([DA_PK] ASC),
	CONSTRAINT [FK_UNDGAttribute_UNDGSubstance] FOREIGN KEY([DA_DG]) REFERENCES [UNDGSubstance] ([DG_PK]),
)
WITH (SYSTEM_VERSIONING = ON (HISTORY_TABLE = dbo.UNDGAttributeHistory))
GO
CREATE UNIQUE NONCLUSTERED INDEX [IX_UNDGAttribute_DA_Language_DA_Type_DA_Index] ON [UNDGAttribute] ([DA_DG] ASC,[DA_Language] ASC,[DA_Type] ASC,[DA_Index] ASC)
GO
ALTER TABLE UNDGAttribute SET (LOCK_ESCALATION = DISABLE);

CREATE TABLE UNDGCommonData(
	[DC_PK] UNIQUEIDENTIFIER NOT NULL,
	[DC_Language] VARCHAR(3) NOT NULL CONSTRAINT [DF_UNDGCommonData_DC_Language] DEFAULT '',
	[DC_Type] VARCHAR(3) NOT NULL CONSTRAINT [DF_UNDGCommonData_DC_Type] DEFAULT '',
	[DC_Index] VARCHAR(6) NOT NULL CONSTRAINT [DF_UNDGCommonData_DC_Index] DEFAULT '',
	[DC_Descriptor] NVARCHAR(MAX) NOT NULL CONSTRAINT [DF_UNDGCommonData_DC_Descriptor] DEFAULT '',
	[DC_SysStartTime]  DATETIME2 GENERATED ALWAYS AS ROW START NOT NULL CONSTRAINT [DF_DC_SysStartTime] DEFAULT CONVERT(DATETIME2, '1900-01-01 0:0:0.0000000'),
	[DC_SysEndTime] DATETIME2 GENERATED ALWAYS AS ROW END NOT NULL CONSTRAINT [DF_DC_SysEndTime] DEFAULT CONVERT(DATETIME2, '9999-12-31 23:59:59.9999999'),
	PERIOD FOR SYSTEM_TIME ([DC_SysStartTime], [DC_SysEndTime]),
	CONSTRAINT [PK_UNDGCommonData] PRIMARY KEY NONCLUSTERED ([DC_PK] ASC)
)
WITH (SYSTEM_VERSIONING = ON (HISTORY_TABLE = dbo.UNDGCommonDataHistory))
GO
CREATE UNIQUE NONCLUSTERED INDEX [IX_UNDGCommonData_Language_DC_Type_DC_Index] ON [UNDGCommonData] ([DC_Language] ASC,[DC_Type] ASC,[DC_Index] ASC)
GO
ALTER TABLE UNDGCommonData SET (LOCK_ESCALATION = DISABLE);

CREATE TABLE UNDGReference(
	[DR_PK] UNIQUEIDENTIFIER NOT NULL,
	[DR_DG] UNIQUEIDENTIFIER NOT NULL,
	[DR_Type] VARCHAR(5) NOT NULL CONSTRAINT [DF_UNDGReference_DR_Type] DEFAULT '',
	[DR_RN_NKCountry] VARCHAR(2) NOT NULL CONSTRAINT [DF_UNDGReference_DR_RN_NKCountry] DEFAULT '',
	[DR_Code] VARCHAR(6) NOT NULL CONSTRAINT [DF_UNDGReference_DR_Code] DEFAULT '',
	[DR_Description] VARCHAR(100) NOT NULL CONSTRAINT [DF_UNDGReference_DR_Description] DEFAULT '',
	[DR_HasFlashPointLower] BIT NOT NULL CONSTRAINT [DF_UNDGReference_DR_HasFlashPointLower] DEFAULT 0,
	[DR_FlashPointLower] DECIMAL(8,1) NOT NULL CONSTRAINT [DF_UNDGReference_DR_FlashPointLower] DEFAULT 0,
	[DR_HasFlashPointUpper] BIT NOT NULL CONSTRAINT [DF_UNDGReference_DR_HasFlashPointUpper] DEFAULT 0,
	[DR_FlashPointUpper] DECIMAL(8,1) NOT NULL CONSTRAINT [DF_UNDGReference_DR_FlashPointUpper] DEFAULT 0,
	[DR_SysStartTime]  DATETIME2 GENERATED ALWAYS AS ROW START NOT NULL CONSTRAINT [DF_DR_SysStartTime] DEFAULT CONVERT(DATETIME2, '1900-01-01 0:0:0.0000000'),
	[DR_SysEndTime] DATETIME2 GENERATED ALWAYS AS ROW END NOT NULL CONSTRAINT [DF_DR_SysEndTime] DEFAULT CONVERT(DATETIME2, '9999-12-31 23:59:59.9999999'),
	PERIOD FOR SYSTEM_TIME ([DR_SysStartTime], [DR_SysEndTime]),
	CONSTRAINT [PK_UNDGReference] PRIMARY KEY NONCLUSTERED  ([DR_PK] ASC),
	CONSTRAINT [FK_UNDGReference_UNDGSubstance] FOREIGN KEY([DR_DG]) REFERENCES [UNDGSubstance] ([DG_PK]),
	CONSTRAINT [CK_DR_FlashPointLower] CHECK ([DR_FlashPointLower] >= -273.15),
	CONSTRAINT [CK_DR_Code] CHECK ([DR_Code] <> ''),
	CONSTRAINT [CK_DR_Type] CHECK ([DR_Type] <> '')
)
WITH (SYSTEM_VERSIONING = ON (HISTORY_TABLE = dbo.UNDGReferenceHistory))
GO
CREATE UNIQUE CLUSTERED INDEX [IX_UNDGReference_DR_DG_DR_RN_NKCountry_DR_Type_DR_Code_DR_HasFlashPointLower_DR_FlashPointLower] ON [UNDGReference] ([DR_DG] ASC,[DR_RN_NKCountry] ASC,[DR_Type] ASC,[DR_Code] ASC,[DR_HasFlashPointLower] ASC,[DR_FlashPointLower] ASC)
GO
ALTER TABLE UNDGReference SET (LOCK_ESCALATION = DISABLE);

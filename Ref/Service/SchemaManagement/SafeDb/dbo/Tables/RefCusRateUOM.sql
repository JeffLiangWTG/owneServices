CREATE TABLE RefCusRateUOM(
	[ZXG_PK] UNIQUEIDENTIFIER NOT NULL CONSTRAINT [DF_RefCusRateUOM_ZXG_PK]  DEFAULT (NEWID()),
	[ZXG_ZZ2_Rate] UNIQUEIDENTIFIER NOT NULL,
	[ZXG_UOM] VARCHAR(10) NOT NULL CONSTRAINT [DF_RefCusRateUOM_ZXG_UOM]  DEFAULT (''),
	[ZXG_DataSetPK] UNIQUEIDENTIFIER,
	[ZXG_DataSetCode] VARCHAR(3),
	[ZXG_SysStartTime] DATETIME2 GENERATED ALWAYS AS ROW START NOT NULL CONSTRAINT [DF_ZXG_SysStartTime] DEFAULT CONVERT(DATETIME2, '1900-01-01 0:0:0.0000000'),
	[ZXG_SysEndTime] DATETIME2 GENERATED ALWAYS AS ROW END NOT NULL CONSTRAINT [DF_ZXG_SysEndTime] DEFAULT CONVERT(DATETIME2, '9999-12-31 23:59:59.9999999'),
	PERIOD FOR SYSTEM_TIME ([ZXG_SysStartTime], [ZXG_SysEndTime]), 
	CONSTRAINT [PK_RefCusRateUOM] PRIMARY KEY CLUSTERED ([ZXG_PK] ASC),
	CONSTRAINT [FK_RefCusRateUOM_RefCusRate] FOREIGN KEY([ZXG_ZZ2_Rate])REFERENCES [RefCusRate] ([ZZ2_PK]),
	CONSTRAINT [CK_RefCusRateUOM_ZXG_UOM] CHECK (([ZXG_UOM]<>''))
)
WITH (SYSTEM_VERSIONING = ON (HISTORY_TABLE = dbo.RefCusRateUOMHistory))
GO

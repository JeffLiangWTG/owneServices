CREATE TABLE RefCusTariffAttribute(
	[ZZ3_PK] UNIQUEIDENTIFIER NOT NULL CONSTRAINT [DF_RefCusTariffAttribute_ZZ3_PK] DEFAULT (NEWID()),
	[ZZ3_ZZ1_Tariff] UNIQUEIDENTIFIER NULL,
	[ZZ3_ZZW_TariffNationalCode] UNIQUEIDENTIFIER NULL,
	[ZZ3_Name] VARCHAR(50) NOT NULL,
	[ZZ3_Value] NVARCHAR(MAX) NOT NULL,
	[ZZ3_DataSetPK] UNIQUEIDENTIFIER, 
	[ZZ3_DataSetCode] VARCHAR(3), 
	[ZZ3_SysStartTime]  DATETIME2 GENERATED ALWAYS AS ROW START NOT NULL CONSTRAINT [DF_ZZ3_SysStartTime] DEFAULT CONVERT(DATETIME2, '1900-01-01 0:0:0.0000000'),
	[ZZ3_SysEndTime] DATETIME2 GENERATED ALWAYS AS ROW END NOT NULL CONSTRAINT [DF_ZZ3_SysEndTime] DEFAULT CONVERT(DATETIME2, '9999-12-31 23:59:59.9999999'),
	PERIOD FOR SYSTEM_TIME ([ZZ3_SysStartTime], [ZZ3_SysEndTime]),
	CONSTRAINT [PK_RefCusTariffAttribute] PRIMARY KEY CLUSTERED( [ZZ3_PK] ASC ),
	CONSTRAINT [FK_RefCusTariffAttribute_RefCusTariff] FOREIGN KEY([ZZ3_ZZ1_Tariff]) REFERENCES RefCusTariff ([ZZ1_PK]),
	CONSTRAINT [FK_RefCusTariffAttribute_RefCusTariffNationalCode] FOREIGN KEY ([ZZ3_ZZW_TariffNationalCode]) REFERENCES RefCusTariffNationalCode ([ZZW_PK]),
	CONSTRAINT [CK_RefCusTariffAttribute_ZZ3_Name] CHECK ([ZZ3_Name] <>''),
	CONSTRAINT [CK_RefCusTariffAttribute_ZZ3_Value] CHECK ([ZZ3_Value] <>''),
	CONSTRAINT [CK_RefCusTariffAttribute_ZZ3_ZZ1_Tariff_ZZ3_ZZW_TariffNationalCode] CHECK (([ZZ3_ZZ1_Tariff] IS NOT NULL AND [ZZ3_ZZW_TariffNationalCode] IS NULL) OR ([ZZ3_ZZ1_Tariff] IS NULL AND [ZZ3_ZZW_TariffNationalCode] IS NOT NULL)),
)
WITH (SYSTEM_VERSIONING = ON (HISTORY_TABLE = dbo.RefCusTariffAttributeHistory))
GO

CREATE TABLE UNDGVersion
(
	[DV_PK] UNIQUEIDENTIFIER NOT NULL CONSTRAINT [DF_UNDGVersion_DV_PK] DEFAULT NEWID(),
	[DV_Name] VARCHAR(20) NOT NULL CONSTRAINT [DF_UNDGVersion_DV_Name] DEFAULT '',
	[DV_Standard] VARCHAR(3) NOT NULL CONSTRAINT [DF_UNDGVersion_DV_Standard] DEFAULT '',
	[DV_IsActive] BIT NOT NULL CONSTRAINT [DF_UNDGVersion_DV_IsActive] DEFAULT 1,
	[DV_SysStartTime]  DATETIME2 GENERATED ALWAYS AS ROW START NOT NULL CONSTRAINT [DF_DV_SysStartTime] DEFAULT CONVERT(DATETIME2, SYSUTCDATETIME()),
	[DV_SysEndTime] DATETIME2 GENERATED ALWAYS AS ROW END NOT NULL CONSTRAINT [DF_DV_SysEndTime] DEFAULT CONVERT(DATETIME2, '9999-12-31 23:59:59.9999999'),
	PERIOD FOR SYSTEM_TIME ([DV_SysStartTime], [DV_SysEndTime]),
	CONSTRAINT [PK_UNDGVersion] PRIMARY KEY ([DV_PK]),
	CONSTRAINT [CK_UNDGVersion_DV_Standard] CHECK ([DV_Standard] = 'ADN' OR [DV_Standard] = 'ADR' OR [DV_Standard] = 'CFR' OR [DV_Standard] = 'JTT' OR [DV_Standard] = 'RID')
)
WITH (SYSTEM_VERSIONING = ON (HISTORY_TABLE = dbo.UNDGVersionHistory))
GO
CREATE UNIQUE NONCLUSTERED INDEX [IX_UNDGVersion_DV_Name] ON UNDGVersion ([DV_Name] ASC)
GO
ALTER TABLE UNDGVersion SET (LOCK_ESCALATION = DISABLE);

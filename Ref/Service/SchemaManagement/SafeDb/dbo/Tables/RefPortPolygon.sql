CREATE TABLE [dbo].[RefPortPolygon]
(
	[RPP_PK] UNIQUEIDENTIFIER NOT NULL CONSTRAINT [DF_RefPortPolygon_RPP_PK] DEFAULT (NEWID()),
	[RPP_PortId] INT NOT NULL,
	[RPP_SerializedPolygon] geography NULL CONSTRAINT [DF_RefPortPolygon_RPP_SerializedPolygon] DEFAULT geography::STPointFromText('POINT EMPTY', 4326),
	[RPP_SysStartTime] DATETIME2 GENERATED ALWAYS AS ROW START NOT NULL CONSTRAINT [DF_RPP_SysStartTime] DEFAULT CONVERT(DATETIME2, '1900-01-01 0:0:0.0000000'),
	[RPP_SysEndTime] DATETIME2 GENERATED ALWAYS AS ROW END NOT NULL CONSTRAINT [DF_RPP_SysEndTime] DEFAULT CONVERT(DATETIME2, '9999-12-31 23:59:59.9999999'),
	PERIOD FOR SYSTEM_TIME ([RPP_SysStartTime], [RPP_SysEndTime]),

	CONSTRAINT [PK_UX_RPP_PK] PRIMARY KEY NONCLUSTERED ([RPP_PK] ASC),
)
WITH (SYSTEM_VERSIONING = ON (HISTORY_TABLE = dbo.RefPortPolygonHistory))
GO
CREATE UNIQUE NONCLUSTERED INDEX [NR_UX_RefPortPolygon_RPP_PortId] ON [RefPortPolygon] ([RPP_PortId] ASC)
GO
ALTER TABLE RefPortPolygon SET (LOCK_ESCALATION = DISABLE);

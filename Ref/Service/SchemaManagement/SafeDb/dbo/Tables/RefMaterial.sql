CREATE TABLE [RefMaterial](
	[RMC_PK] UNIQUEIDENTIFIER NOT NULL,
	[RMC_IsActive] BIT NOT NULL CONSTRAINT [DF_RefMaterial_RMC_IsActive]  DEFAULT (1),
	[RMC_Code] VARCHAR(10) NOT NULL CONSTRAINT [DF_RefMaterial_RMC_Code]  DEFAULT (''),
	[RMC_Description] VARCHAR(240) NOT NULL CONSTRAINT [DF_RefMaterial_RMC_Description]  DEFAULT (''),
	[RMC_Group] VARCHAR(25) NOT NULL CONSTRAINT [DF_RefMaterial_RMC_Group]  DEFAULT (''),
	[RMC_SysStartTime] DATETIME2 GENERATED ALWAYS AS ROW START NOT NULL CONSTRAINT [DF_RMC_SysStartTime] DEFAULT CONVERT(DATETIME2, '1900-01-01 0:0:0.0000000'),
	[RMC_SysEndTime] DATETIME2 GENERATED ALWAYS AS ROW END NOT NULL CONSTRAINT [DF_RMC_SysEndTime] DEFAULT CONVERT(DATETIME2, '9999-12-31 23:59:59.9999999'),
	PERIOD FOR SYSTEM_TIME ([RMC_SysStartTime], [RMC_SysEndTime]),
	CONSTRAINT [PK_RefMaterial] PRIMARY KEY CLUSTERED ([RMC_PK] ASC),
	CONSTRAINT [CK_RefMaterial_RMC_Code] CHECK  ([RMC_Code] <> ''),
	CONSTRAINT [CK_RefMaterial_RMC_Description] CHECK  ([RMC_Description] <> ''),
	CONSTRAINT [CK_RefMaterial_RMC_Group] CHECK  ([RMC_Group] = 'CEDEX' OR [RMC_Group] = 'MERC')

)
WITH (SYSTEM_VERSIONING = ON (HISTORY_TABLE = dbo.RefMaterialHistory))
GO
CREATE UNIQUE NONCLUSTERED INDEX [IX_RefMaterial_RMC_Code_RMC_Group] ON [RefMaterial] ([RMC_Code] ASC, [RMC_Group] ASC)
GO
ALTER TABLE [RefMaterial] SET (LOCK_ESCALATION = DISABLE);

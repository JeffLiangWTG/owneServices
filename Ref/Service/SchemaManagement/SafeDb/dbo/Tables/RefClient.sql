CREATE TABLE [dbo].[RefClient]
(
	[RCT_PK] UNIQUEIDENTIFIER NOT NULL CONSTRAINT [DF_RefClient_RCT_PK] DEFAULT NEWID(),
	[RCT_ClientID] VARCHAR(255) NOT NULL,
	[RCT_Certificate] VARBINARY(MAX) NOT NULL,
	[RCT_LegacyCertificate] VARBINARY(MAX),
	[RCT_Signature] VARBINARY(MAX) NOT NULL,
	[RCT_SysStartTime] DATETIME2 GENERATED ALWAYS AS ROW START NOT NULL CONSTRAINT [DF_RefClient_RCT_SysStartTime] DEFAULT CONVERT(DATETIME2, SYSUTCDATETIME()),
	[RCT_SysEndTime] DATETIME2 GENERATED ALWAYS AS ROW END NOT NULL CONSTRAINT [DF_RefClient_RCT_SysEndTime] DEFAULT CONVERT(DATETIME2, SYSUTCDATETIME()),
	PERIOD FOR SYSTEM_TIME ([RCT_SysStartTime], [RCT_SysEndTime]),
	CONSTRAINT [PK_RefClient] PRIMARY KEY CLUSTERED ([RCT_PK] ASC),
)
WITH (SYSTEM_VERSIONING = ON (HISTORY_TABLE = dbo.RefClientHistory))
GO 
CREATE UNIQUE NONCLUSTERED INDEX IX_RCT_RefCLient_RCT_ClientID ON RefClient ( RCT_ClientID )
GO
ALTER TABLE RefClient SET (LOCK_ESCALATION = DISABLE);

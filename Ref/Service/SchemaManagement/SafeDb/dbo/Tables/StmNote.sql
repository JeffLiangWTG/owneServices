CREATE TABLE [StmNote] (
    [ST_PK] UNIQUEIDENTIFIER NOT NULL CONSTRAINT [DF_StmNote_ST_PK] DEFAULT NEWID(),
    [ST_ParentId] UNIQUEIDENTIFIER NULL,
    [ST_ParentTableCode] VARCHAR(4) NOT NULL,
    [ST_Description] NVARCHAR(50) NOT NULL CONSTRAINT [DF_StmNote_ST_Description] DEFAULT 'Terms and Conditions',
    [ST_ForceRead] BIT NOT NULL CONSTRAINT [DF_StmNote_ST_ForceRead] DEFAULT 1,
    [ST_NoteText] NVARCHAR(MAX) NOT NULL CONSTRAINT [DF_StmNote_ST_NoteText] DEFAULT '',
    [ST_NoteType] CHAR(3) NOT NULL CONSTRAINT [DF_StmNote_ST_NoteType] DEFAULT 'INT',
    [ST_NoteContext] VARCHAR(3) NOT NULL CONSTRAINT [DF_StmNote_ST_NoteContext] DEFAULT 'ALL',
	[ST_SysStartTime] DATETIME2 GENERATED ALWAYS AS ROW START NOT NULL CONSTRAINT [DF_ST_SysStartTime] DEFAULT CONVERT(DATETIME2, '1900-01-01 0:0:0.0000000'),
	[ST_SysEndTime] DATETIME2 GENERATED ALWAYS AS ROW END NOT NULL CONSTRAINT [DF_ST_SysEndTime] DEFAULT CONVERT(DATETIME2, '9999-12-31 23:59:59.9999999'),
	PERIOD FOR SYSTEM_TIME ([ST_SysStartTime], [ST_SysEndTime]),
	CONSTRAINT [PK_StmNote] PRIMARY KEY CLUSTERED ([ST_PK] ASC),
	CONSTRAINT [CK_StmNote_ST_Description] CHECK ([ST_Description] = 'Terms and Conditions')
)
WITH (SYSTEM_VERSIONING = ON (HISTORY_TABLE = dbo.StmNoteHistory))
GO
CREATE NONCLUSTERED INDEX [IX_StmNote_ST_ParentId_ST_Table] ON [StmNote] ([ST_ParentId] ASC, [ST_ParentTableCode] ASC)
GO
ALTER TABLE [StmNote] SET (LOCK_ESCALATION = DISABLE);

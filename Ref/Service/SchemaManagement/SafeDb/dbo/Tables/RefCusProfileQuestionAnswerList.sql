CREATE TABLE RefCusProfileQuestionAnswerList
(
	XQ4_PK UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_RefCusProfileQuestionAnswerList_XQ4_PK  DEFAULT (NEWID()),
	XQ4_XQ2_Question UNIQUEIDENTIFIER NOT NULL,
	XQ4_Value NVARCHAR(100) NOT NULL,
	XQ4_Description NVARCHAR(500) NOT NULL,
	XQ4_SysStartTime DATETIME2 GENERATED ALWAYS AS ROW START NOT NULL CONSTRAINT DF_XQ4_SysStartTime DEFAULT SYSUTCDATETIME(),
	XQ4_SysEndTime DATETIME2 GENERATED ALWAYS AS ROW END NOT NULL CONSTRAINT DF_XQ4_SysEndTime DEFAULT CONVERT(DATETIME2, '9999-12-31 23:59:59.9999999'),
	PERIOD FOR SYSTEM_TIME (XQ4_SysStartTime, XQ4_SysEndTime),

	CONSTRAINT PK_RefCusProfileQuestionAnswerList PRIMARY KEY CLUSTERED (XQ4_PK ASC),
	CONSTRAINT FK_RefCusProfileQuestionAnswerList_RefCusProfileQuestion FOREIGN KEY(XQ4_XQ2_Question) REFERENCES RefCusProfileQuestion (XQ2_PK),
	CONSTRAINT CK_RefCusProfileQuestionAnswerList_XQ4_Value CHECK (XQ4_Value <> ''),
	CONSTRAINT CK_RefCusProfileQuestionAnswerList_XQ4_Description CHECK (XQ4_Description <> '')
)
WITH (SYSTEM_VERSIONING = ON (HISTORY_TABLE = dbo.RefCusProfileQuestionAnswerListHistory))
GO
CREATE UNIQUE INDEX IX_RefCusProfileQuestionAnswerList_XQ4_XQ2_Question_XQ4_Value ON RefCusProfileQuestionAnswerList (XQ4_XQ2_Question ASC, XQ4_Value ASC)
GO
ALTER TABLE RefCusProfileQuestionAnswerList SET (LOCK_ESCALATION = DISABLE);

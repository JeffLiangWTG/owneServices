using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using CargoWise.RefDbRepo.Common.Argument;
using CargoWise.RefDbRepo.Service.Schema_0_9_New;
using CargoWise.RefDbRepo.Tools.Common;

namespace CargoWise.RefDbRepo.DataSetServiceGenerator
{
	public class DataSetServiceGenerator
	{
		public DataSetServiceGenerator(IEnumerable<string[]> dataSetsList, IDataSetHelper dataSetHelper)
		{
			Argument.NotNull(dataSetsList, nameof(dataSetsList));
			Argument.NotNull(dataSetHelper, nameof(dataSetHelper));

			dataSetsDictionary = dataSetsList.ToDictionary(k => k[0], v => v);
			serviceGeneratorHelper = new ServiceGeneratorHelper(dataSetHelper);
		}

		public void CreateDataSetServices(string servicePath)
		{
			Argument.NotNullOrEmpty(servicePath, nameof(servicePath));
			if (!Directory.Exists(servicePath))
			{
				Directory.CreateDirectory(servicePath);
			}

			foreach (var dataSetName in dataSetsDictionary.Keys)
			{
				var dataSetList = dataSetsDictionary[dataSetName];
				if (ExcludedDataSets.Contains(dataSetName))
				{
					Console.ForegroundColor = ConsoleColor.Yellow;
					Console.WriteLine($"Please create {dataSetName} service manually.");
					Console.ResetColor();
					continue;
				}
#pragma warning disable CA1031 // Do not catch general exception types
				try
				{
					CreateDataSetService(dataSetList, servicePath);
				}
				catch (Exception ex)
				{
					Console.Error.WriteLine($"Failed to generate {dataSetName} service. " + ex.ToString());
				}
#pragma warning restore CA1031 // Do not catch general exception types
			}
		}

		void CreateDataSetService(string[] dataSets, string servicePath)
		{
			Argument.NotNull(dataSets, nameof(dataSets));
			Argument.NotNullOrEmpty(servicePath, nameof(servicePath));

			var dataSetName = dataSets[0];
			var content = serviceGeneratorHelper.CreateServiceForDateSets(dataSets);
			if (!string.IsNullOrEmpty(content))
			{
				Console.WriteLine($"Create {dataSetName} successfully.");
				content = AutoGeneratedInfo + content;
				var serviceFilePath = Path.Combine(servicePath, $"{dataSetName}Service.cs");
				File.WriteAllText(serviceFilePath, content);
			}
			else
			{
				Console.WriteLine($"Create {dataSetName} failed.");
			}
		}

		readonly ServiceGeneratorHelper serviceGeneratorHelper;
		readonly Dictionary<string, string[]> dataSetsDictionary;
		public static string[] ExcludedDataSets => new[]
		{
			nameof(RefCusTariff),
			nameof(RefCusPreference),
			nameof(RefCusNomenclatureGroup),
			nameof(RefTimeZoneSet),
			nameof(RefUNLOCO),
			nameof(RefCusCodeList),
			nameof(RefCusProfileType),
            nameof(RefCusProfile),
            nameof(RefCusProfileQuestion),
			nameof(RefCusProfileQuestionPathway)
		};

		const string AutoGeneratedInfo = @"////////////////////////////////////////////////////////////////////////////////
// <auto-generated>
//     This code was generated from DataSetServiceGenerator.
//
//     Manual changes to this file may cause unexpected behavior in your application.
//     Manual changes to this file will be overwritten if the code is regenerated.
// </auto-generated>
////////////////////////////////////////////////////////////////////////////////
";
	}
}

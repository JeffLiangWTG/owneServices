using System.IO;
using CargoWise.RefDbRepo.Common.Infrastructure.Test;
using CargoWise.RefDbRepo.Common.Utils;
using CargoWise.RefDbRepo.Tools.Common;
using Microsoft.Data.SqlClient;
using NUnit.Framework;

namespace CargoWise.RefDbRepo.DataSetServiceGenerator.Test;

[TestFixture]
public class DataSetServiceGeneratorFixture
{
	[Test]
	[TransactionedTestCase]
	[Property("DAT:CapabilityRequirements", "SQL2019+")]
	public void AllAutoGeneratedServicesAreUpToDate()
	{
		var dbName = TransactionedTestCaseAttribute.GetDbName(DbSchema.RefDbRepoSafe);
		using var connection = new SqlConnection(TestConnectionString.GetAdmin(dbName));
		connection.Open();
		var tempPath = Path.Combine(Path.GetTempPath(), "{667AA7594426402481B65FF77E396320}");
		var dataSetsList = DataSetStructureProvider.StructuredDataSets;
		var dataSetHelper = new DataSetHelper(connection);
		var serviceGenerator = new DataSetServiceGenerator(dataSetsList, dataSetHelper);
		Assert.DoesNotThrow(() => serviceGenerator.CreateDataSetServices(tempPath));
		foreach (var excludedDataSet in DataSetServiceGenerator.ExcludedDataSets)
		{
			var filePath = Path.Combine(tempPath, $"{excludedDataSet}Service.cs");
			Assert.False(File.Exists(filePath));
		}

		var serviceFiles = Directory.GetFiles(tempPath);
		Assert.True(serviceFiles != null && serviceFiles.Length > 0);

		var rootPath = TestSourcePathHelper.DATTestSupplementaryContentPath;
		var servicesPath = Path.Combine(rootPath, "Service\\NewService\\Services");
		foreach (var serviceFile in serviceFiles)
		{
			var fileName = Path.GetFileName(serviceFile);
			var expectedContents = File.ReadAllText(serviceFile);
			var contents = File.ReadAllText(Path.Combine(servicesPath, fileName));
			Assert.AreEqual(expectedContents, contents);
		}

		Directory.Delete(tempPath, true);
	}
}

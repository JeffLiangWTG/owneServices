using System.Text.Json;
using CargoWise.RefDbRepo.Common.Utils;

namespace CargoWise.RefDbRepo.MetaDataGenerator;

class MetaDataFileWriter(
	string outputFolder,
	IFileFinder fileFinder,
	IColumnMetaDataProvider metaDataProvider) : IFileWriter
{
	public void Write()
	{
		var objectNames = fileFinder.GetFiles().Select(f => Path.GetFileNameWithoutExtension(f)!);
		foreach (var objectName in objectNames)
		{
			WriteMetaDataFileIfMissing(objectName);
		}
	}

	void WriteMetaDataFileIfMissing(string objectName)
	{
		var metaDataJsonFile = Path.Combine(outputFolder, $"{objectName}.metadata.json");
		if (File.Exists(metaDataJsonFile))
		{
			Console.WriteLine($"Skipped (exists): {metaDataJsonFile}");
			return;
		}

		WriteToJsonFile(objectName, metaDataJsonFile);
		Console.WriteLine($"Generated: {metaDataJsonFile}");
	}

	void WriteToJsonFile(string objectName, string metaDataJsonFile)
	{
		var columnMetaData = metaDataProvider.GetMetaData(objectName);
		var content = JsonSerializer.Serialize(columnMetaData, WriteOption);
		File.WriteAllText(metaDataJsonFile, FileHeaderComment + content);
	}

	static readonly JsonSerializerOptions WriteOption = new() { WriteIndented = true };

	const string FileHeaderComment = """
									//------------------------------------------------------------------------------
									// <auto-generated>
									//     This file is auto-generated by CargoWise.RefDbRepo.MetaDataGenerator
									//
									//     Do not change this file without consulting reference data team.
									//     Manual change will cause unexpected backward compatibility issue.
									// </auto-generated>
									//------------------------------------------------------------------------------

									""";
}

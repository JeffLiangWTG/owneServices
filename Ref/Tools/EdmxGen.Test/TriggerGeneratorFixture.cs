namespace CargoWise.RefDbRepo.EdmxGen.Test;

[TestFixture]
public class TriggerGeneratorFixture
{
	[Test]
	public void NoErrorOutPutWhenCreateTriggers()
	{
		dataSetHelperMock.Setup(x => x.GetAllTableAndColumns()).Returns(DataSetHelperFixture.CreateTableAndColumns());
		dataSetHelperMock.Setup(x => x.GetAllTableAndFKs()).Returns(DataSetHelperFixture.CreateTableAndFKs());
		TextWriter oldOut = Console.Out;
		try
		{
			using var stringWriter = new StringWriter();
			Console.SetOut(stringWriter);
			var safeDbTriggersPath = Path.Combine(Path.GetTempPath(), "TestTriggers");
			if (Directory.Exists(safeDbTriggersPath))
			{
				Directory.Delete(safeDbTriggersPath, true);
			}
			triggerGenerator.CreateTriggers(safeDbTriggersPath);
			Directory.Delete(safeDbTriggersPath, true);

			Assert.False(stringWriter.ToString().Contains("Please create triggers manually"));
		}
		finally
		{
			Console.SetOut(oldOut);
		}
	}

	[Test]
	public void CreateTriggers()
	{
		dataSetHelperMock.Setup(x => x.GetAllTableAndColumns()).Returns(DataSetHelperFixture.CreateTableAndColumns());
		dataSetHelperMock.Setup(x => x.GetAllTableAndFKs()).Returns(DataSetHelperFixture.CreateTableAndFKs());
		var safeDbTriggersPath = Path.Combine(Path.GetTempPath(), "TestTriggers");
		if (Directory.Exists(safeDbTriggersPath))
		{
			Directory.Delete(safeDbTriggersPath, true);
		}
		triggerGenerator.CreateTriggers(safeDbTriggersPath);
		var files = Directory.GetFiles(safeDbTriggersPath);
		Assert.AreEqual(22, files.Length);

		var expectedFiles = Directory.GetFiles(testFilePath, "*Trigger.sql");
		foreach (var expectedFile in expectedFiles)
		{
			var fileName = Path.GetFileName(expectedFile);
			var generatedFile = Path.Combine(safeDbTriggersPath, fileName);
			Assert.True(File.Exists(generatedFile));
			Assert.AreEqual(File.ReadAllText(expectedFile), File.ReadAllText(generatedFile));
		}

		Directory.Delete(safeDbTriggersPath, true);
	}

	[Test]
	[TransactionedTestCase]
	[Property("DAT:CapabilityRequirements", "SQL2019+")]
	public void AllAutoGeneratedTriggersAreUpToDate()
	{
		var dbName = TransactionedTestCaseAttribute.GetDbName(DbSchema.RefDbRepoSafe);
		using var connection = new SqlConnection(TestConnectionString.GetAdmin(dbName));
		connection.Open();
		var tempPath = Path.Combine(Path.GetTempPath(), Guid.NewGuid().ToString());
		var dataSetsList = DataSetStructureProvider.StructuredDataSets;
		var dataSetHelper = new DataSetHelper(connection);
		triggerGenerator = new TriggerGenerator(dataSetsList, dataSetHelper);
		triggerGenerator.CreateTriggers(tempPath);

		var triggerFiles = Directory.GetFiles(tempPath);
		Assert.True(triggerFiles != null && triggerFiles.Any());
		foreach (var triggerFile in triggerFiles)
		{
			var fileName = Path.GetFileNameWithoutExtension(triggerFile);
			var expectedScripts = File.ReadAllText(triggerFile);
			var scripts = SqlScriptHelper.GetSqlScriptFromZippedFile(ZippedSafeDbSqlFiles, "Triggers", fileName);
			Assert.AreEqual(expectedScripts, scripts);
		}
	}

	[SetUp]
	public void SetUp()
	{
		testFilePath = Path.Combine(AppDomain.CurrentDomain.BaseDirectory, "testfiles");
		dataSetHelperMock = new Mock<IDataSetHelper>();
		triggerGenerator = new TriggerGenerator(DataSetHelperFixture.DataSetsList, dataSetHelperMock.Object);
	}

	string testFilePath;
	const string ZippedSafeDbSqlFiles = @"..\..\Server\SafeDbSqlFiles.zip";
	Mock<IDataSetHelper> dataSetHelperMock;
	TriggerGenerator triggerGenerator;
}

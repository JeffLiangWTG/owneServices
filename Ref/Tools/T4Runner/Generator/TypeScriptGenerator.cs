using System;
using System.Globalization;
using System.Linq;
using System.Reflection;
using System.Text;

namespace CargoWise.RefDbRepo.T4Runner.Generator
{
	public class TypeScriptGenerator : BaseSafeModelGeneratorTemplate
	{
		public static string[] EntitiesForTypeScript
		{
			get 
			{ 
				return new [] 
				{ 
					"RefCusCodeType",
					"RefAccTaxRateUserView",
					"RefCusCodeListUserView",
					"RefCusProcedureUserView",
					"RefShippingLineUserView",
					"RefStlScriptUserView",
					"RefCusCodeListAttributeUserView",
					"RefCusProcedureAttributeUserView"
				}; 
			}
		}
		
		protected TypeScriptGenerator(string targetPath, string[] entities) : base(targetPath, entities)
		{
		}
		
		public static TypeScriptGenerator CreateFor(string targetPath)
		{
			return new TypeScriptGenerator(targetPath, EntitiesForTypeScript);
		}
		
		protected override string GetFileName(string entity)
		{
			return $"{entity}.ts";
		}
		
		protected override string GetContent(Type type)
		{
			StringBuilder stringBuilder = new StringBuilder();
			stringBuilder.Append(@"//------------------------------------------------------------------------------
// <auto-generated>
//     This code was generated from a template.
//
//     Manual changes to this file may cause unexpected behavior in your application.
//     Manual changes to this file will be overwritten if the code is regenerated.
// </auto-generated>
//------------------------------------------------------------------------------
");
			stringBuilder.AppendLine(@"import { IEntity } from ""./IEntity"";");
			stringBuilder.AppendLine();
			stringBuilder.AppendLine(CultureInfo.InvariantCulture, $"export class {type.Name} implements IEntity {{");
			var properties = type.GetProperties()
				.Select(x => new TypeScriptPropertyInfoMapper(x))
				.Where(x => !x.IsSystemProperty())
				.ToArray();
			foreach (var propertyInfoMapper in properties)
			{
				if (propertyInfoMapper.IsSimpleType())
				{
					stringBuilder.AppendLine(CultureInfo.InvariantCulture, $"\t{propertyInfoMapper.PropertyName()}: {propertyInfoMapper.TypeNameForTypeScript()};");
					if (propertyInfoMapper.IsString() && propertyInfoMapper.HasMaximumLength())
					{
						stringBuilder.AppendLine(CultureInfo.InvariantCulture, $"\tstatic readonly {propertyInfoMapper.PropertyName()}_MaxLength: number = {propertyInfoMapper.MaximumLength()};");
					}
				}
			}
			stringBuilder.AppendLine("}");
			return stringBuilder.ToString();
		}
		class TypeScriptPropertyInfoMapper : BasePropertyInfoMapper
		{
			public TypeScriptPropertyInfoMapper(PropertyInfo propertyInfo) : base(propertyInfo)
			{
			}
			
			public string TypeNameForTypeScript()
			{
				switch(PropertyTypeFullName())
				{
					case "System.Guid":
					case "Nullable<System.Guid>":
						return "string";
					case "System.DateTime":
						return "string";
					case "Nullable<System.DateTime>":
						return "string | null";
					case "System.String":
						return "string";
					case "System.Boolean":
					case "Nullable<System.Boolean>":
						return "boolean";
					case "System.Int32":
					case "System.Byte":
						return "number";
					case "System.Byte[]":
						return "Uint8Array";
					default:
						return PropertyTypeFullName();
				}
			}
		}
	}
}

using System;
using System.ComponentModel.DataAnnotations.Schema;
using System.Globalization;
using System.Linq;
using System.Reflection;
using System.Text;
using CargoWise.RefDbRepo.Common.Utils;

namespace CargoWise.RefDbRepo.T4Runner.Generator
{
	public class UniversalXMLModelGenerator : BaseStagingModelGeneratorTemplate
	{
		protected UniversalXMLModelGenerator(string targetPath, string[] entities) : base(targetPath, entities)
		{
		}

		public static UniversalXMLModelGenerator CreateFor(string targetPath)
		{
			var entities = DataSetStructureProvider.StructuredDataSets.SelectMany(dataSet => dataSet).ToArray();
			return new UniversalXMLModelGenerator(targetPath, entities);
		}

		protected override string GetContent(Type type)
		{
			StringBuilder stringBuilder = new StringBuilder();
			stringBuilder.Append(@"//------------------------------------------------------------------------------
// <auto-generated>
//     This code was generated from a template.
//
//     Manual changes to this file may cause unexpected behavior in your application.
//     Manual changes to this file will be overwritten if the code is regenerated.
// </auto-generated>
//------------------------------------------------------------------------------

");
			stringBuilder.AppendLine(@"namespace CargoWise.RefDbRepo.Common.UniversalXmlWriter.EntityType");
			stringBuilder.AppendLine("{");
			stringBuilder.AppendLine("\tusing System;");
			stringBuilder.AppendLine("\tusing System.Collections.Generic;");
			stringBuilder.AppendLine("");
			stringBuilder.AppendLine(CultureInfo.InvariantCulture, $"\tpublic partial class {type.Name} : RefDataRepoModelEntityType");
			stringBuilder.AppendLine("\t{");
			var properties = type.GetProperties()
			.Select(x => new UXMLWriterPropertyInfoMapper(x))
			.Where(x => !x.IsSystemProperty())
			.ToArray();
			var simpleProperties = properties
				.Where(x => x.IsSimpleType() && (!x.IsGuid() || x.IsGuidOfOtherSystem()) && !x.IsNotMapped())
				.ToArray();
			if (simpleProperties.Any())
			{
				foreach (var property in simpleProperties)
				{
					stringBuilder.AppendLine(BuildPropertySchema(property));
					stringBuilder.AppendLine(CultureInfo.InvariantCulture, $"\t\tpublic {property.TypeNameForUXMLWriter()} {property.Name()} {{ get; set; }}");
				}
			}
			var navigationProperties = properties
				.Where(x => x.IsNavigationProperty() && !x.IsNotMapped())
				.ToArray();
			if (navigationProperties.Any() && !type.Name.Equals("RefSysConfigType", StringComparison.OrdinalIgnoreCase))
			{
				stringBuilder.AppendLine("");
				foreach (var property in navigationProperties)
				{
					if (Entities.Contains(property.GetNavigationPropertyTypeName()))
					{
						stringBuilder.AppendLine(
							@"		[System.Diagnostics.CodeAnalysis.SuppressMessage(""Microsoft.Usage"", ""CA2227:CollectionPropertiesShouldBeReadOnly"")]");
						stringBuilder.AppendLine(CultureInfo.InvariantCulture,
							$"\t\tpublic {property.GetNavigationPropertyTypeName() + "[]"} {property.Name()} {{ get; set; }}");
					}
				}
			}
			stringBuilder.AppendLine("\t}");
			stringBuilder.AppendLine("}");
			return stringBuilder.ToString();
		}

		static string BuildPropertySchema(UXMLWriterPropertyInfoMapper property)
		{
			StringBuilder sb = new StringBuilder();
			sb.Append(@"		[PropertySchema(""&lt;");
			sb.Append(CultureInfo.InvariantCulture, $@"Property Name=&quot;{property.Name()}&quot; ");
			sb.Append(CultureInfo.InvariantCulture, $@"Type=&quot;{property.GetSchemaType()}&quot; ");
			if (property.MaximumLength() > 0
				&& !(property.GetSchemaType().StartsWith("nvarchar", StringComparison.OrdinalIgnoreCase) && property.MaximumLength() == 4000))
			{
				sb.Append(CultureInfo.InvariantCulture, $@"MaxLength=&quot;{property.MaximumLength()}&quot; ");
			}
			if (property.IsDecimal())
			{
				var precisionAndScale = property.GetPrecisionAndScale();
				if (precisionAndScale.precision != 18)
				{
					sb.Append(CultureInfo.InvariantCulture, $@"Precision=&quot;{precisionAndScale.precision}&quot; ");
				}
				sb.Append(CultureInfo.InvariantCulture, $@"Scale=&quot;{precisionAndScale.scale}&quot; ");
			}
			sb.Append(@"/&gt;"")]");
			return sb.ToString();
		}

		class UXMLWriterPropertyInfoMapper : BasePropertyInfoMapper
		{
			public UXMLWriterPropertyInfoMapper(PropertyInfo propertyInfo) : base(propertyInfo)
			{
			}

			public string TypeNameForUXMLWriter()
			{
				switch (PropertyTypeFullName())
				{
					case "System.String":
						return "string";
					case "System.Boolean":
						return "bool";
					case "Nullable<System.Boolean>":
						return PropertyInfo().Name == "ZY2_IsMandatory" ? "Nullable<bool>" : "bool";
					case "System.Int16":
						return "short";
					case "Nullable<System.Int16>":
						return "Nullable<short>";
					case "System.Decimal":
						return "decimal";
					case "System.Int32":
						return "int";
					case "Nullable<System.Int32>":
						return "Nullable<int>";
					case "System.Byte[]":
						return "byte[]";
					case "System.Byte":
						return "byte";
					case "NetTopologySuite.Geometries.Geometry":
						return "RefGeography";
					case "System.Guid":
						return "Guid";
					default:
						return PropertyTypeFullName();
				}
			}

			public bool IsDecimal()
			{
				ColumnAttribute columnAttribute = PropertyInfo().GetCustomAttribute<ColumnAttribute>();
				if (columnAttribute != null)
				{
					string typeName = columnAttribute.TypeName;
					return typeName != null && typeName.StartsWith("decimal", StringComparison.OrdinalIgnoreCase);
				}

				return false;
			}

			public (int precision, int scale) GetPrecisionAndScale()
			{
				ColumnAttribute columnAttribute = PropertyInfo().GetCustomAttribute<ColumnAttribute>();
				var typeName = columnAttribute.TypeName;
				string insideParentheses = typeName.Substring(typeName.IndexOf('(') + 1,
					typeName.IndexOf(')') - typeName.IndexOf('(') - 1);
				string[] parts = insideParentheses.Split(',');
				int precision = int.Parse(parts[0].Trim(), CultureInfo.InvariantCulture);
				int scale = int.Parse(parts[1].Trim(), CultureInfo.InvariantCulture);
				return (precision, scale);
			}

			public string GetSchemaType()
			{
				ColumnAttribute columnAttribute = PropertyInfo().GetCustomAttribute<ColumnAttribute>();
				switch (PropertyTypeFullName())
				{
					case "System.String":
						if (MaximumLength() > 0 && columnAttribute?.TypeName?.IndexOf('(') > 0)
						{
							return columnAttribute.TypeName.Substring(0, columnAttribute.TypeName.IndexOf('('));
						}
						return columnAttribute != null ? columnAttribute.TypeName : PropertyTypeFullName();
					case "System.Decimal":
						return "decimal";
					default:
						return columnAttribute != null ? columnAttribute.TypeName : PropertyTypeFullName();
				}
			}
		}

	}
}

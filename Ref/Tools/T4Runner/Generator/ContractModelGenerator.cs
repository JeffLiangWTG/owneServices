using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Reflection;
using System.Text;
using CargoWise.RefDbRepo.Common.Utils;
using LiteDB;

namespace CargoWise.RefDbRepo.T4Runner.Generator
{
	public class ContractModelGenerator : BaseSafeModelGeneratorTemplate
	{
		IEnumerable<string[]> DataSets { get; }

		protected ContractModelGenerator(string targetPath, IEnumerable<string[]> dataSets, string[] entities) : base(targetPath, entities)
		{
			DataSets = dataSets;
		}

		public static ContractModelGenerator CreateFor(string targetPath)
		{
			var dataSets = DataSetStructureProvider.StructuredDataSets;
			var entities = dataSets.SelectMany(dataSet => dataSet).ToArray();
			return new ContractModelGenerator(targetPath, dataSets, entities);
		}

		protected override string GetContent(Type type)
		{
			StringBuilder stringBuilder = new StringBuilder();
			stringBuilder.Append(@"//------------------------------------------------------------------------------
// <auto-generated>
//     This code was generated from a template.
//
//     Manual changes to this file may cause unexpected behavior in your application.
//     Manual changes to this file will be overwritten if the code is regenerated.
// </auto-generated>
//------------------------------------------------------------------------------

");

			stringBuilder.AppendLine(@"namespace CargoWise.RefDbRepo.Common.Contract_0_9");
			stringBuilder.AppendLine("{");
			stringBuilder.AppendLine("\tusing System;");
			stringBuilder.AppendLine("\tusing System.Collections.Generic;");
			stringBuilder.AppendLine();
			stringBuilder.AppendLine(IsMainTable(type)
				? $"\tpublic partial class {type.Name} : CargoWise.RefDbRepo.Common.Models.RefDataSet"
				: $"\tpublic partial class {type.Name}");
			stringBuilder.AppendLine("\t{");
			var properties = type.GetProperties()
			.Select(x => new ContractPropertyInfoMapper(x))
			.Where(x => !x.IsSystemProperty())
			.ToArray();
			var simpleProperties = properties
				.Where(x => x.IsSimpleType() && (!x.IsGuid() || x.IsGuidOfOtherSystem()) && !x.IsNotMapped())
				.ToArray();
			if (simpleProperties.Any())
			{
				foreach (var property in simpleProperties)
				{
					stringBuilder.AppendLine(CultureInfo.InvariantCulture, $"\t\tpublic {property.TypeNameForContract()} {property.Name()} {{ get; set; }}");
				}
			}
			var navigationProperties = properties
				.Where(x => x.IsNavigationProperty() && !x.IsNotMapped())
				.ToArray();
			if (navigationProperties.Any())
			{
				stringBuilder.AppendLine();
				foreach (var property in navigationProperties)
				{
					if (Entities.Contains(property.GetNavigationPropertyTypeName()))
					{
						stringBuilder.AppendLine(
							@"		[System.Diagnostics.CodeAnalysis.SuppressMessage(""Microsoft.Usage"", ""CA2227:CollectionPropertiesShouldBeReadOnly"")]");
						stringBuilder.AppendLine(CultureInfo.InvariantCulture,
							$"\t\tpublic {property.GetNavigationPropertyTypeName() + "[]"} {property.Name()} {{ get; set; }}");
					}
				}
			}
			stringBuilder.AppendLine("\t}");
			stringBuilder.AppendLine("}");
			return stringBuilder.ToString();
		}

		bool IsMainTable(Type entity)
		{
			return DataSets.Any(x => x.Length > 0 && x[0] == entity.Name);
		}

		class ContractPropertyInfoMapper : BasePropertyInfoMapper
		{

			public ContractPropertyInfoMapper(PropertyInfo propertyInfo) : base(propertyInfo)
			{
			}

			public string TypeNameForContract()
			{
				switch (PropertyTypeFullName())
				{
					case "System.String":
						return "string";
					case "System.Boolean":
						return "bool";
					case "Nullable<System.Boolean>":
						return PropertyInfo().Name == "ZY2_IsMandatory" ? "Nullable<bool>" : "bool";
					case "System.Int16":
						return "short";
					case "Nullable<System.Int16>":
						return "Nullable<short>";
					case "System.Decimal":
						return "decimal";
					case "System.Int32":
						return "int";
					case "Nullable<System.Int32>":
						return "Nullable<int>";
					case "System.Byte[]":
						return "byte[]";
					case "System.Byte":
						return "byte";
					case "NetTopologySuite.Geometries.Geometry":
						return "string";
					case "System.Guid":
						return "Guid";
					default:
						return PropertyTypeFullName();
				}
			}

		}
	}
}

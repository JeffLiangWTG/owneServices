	public class TestUniversalXMLModelGenerator : UniversalXMLModelGenerator
	{
		public TestUniversalXMLModelGenerator(string targetPath, string[] entities) : base(targetPath, entities)
		{
		}
		
		protected override Type GetEntityType(string entity)
		{
			return typeof(TestUXMLModel);
		}
	}
	
	public class TestUXMLModel
	{
		[Column(TypeName = "uniqueidentifier")]

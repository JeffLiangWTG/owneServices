	[TestFixture]
	public class ContractModelGeneratorTest
	{
		[Test]
		public void TestGenerateContractModel()
		{
			string currentDirectory = Path.GetDirectoryName(Assembly.GetExecutingAssembly().Location);
			new TestContractModelGenerator(".", new[] { new[] { "TestContractModel" } }, new[] {"TestContractModel"}).Generate();
			var content = File.ReadAllText($@"{currentDirectory}\TestContractModel.cs");
			Assert.That(content, Is.EqualTo(@"//------------------------------------------------------------------------------

using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection;
using NUnit.Framework;

namespace CargoWise.RefDbRepo.T4Runner.Generator.Test
{
	[TestFixture]
	public class TypeScriptGeneratorTest
	{
		[Test]
		public void TestGenerateTypeScript()
		{
			string currentDirectory = Path.GetDirectoryName(Assembly.GetExecutingAssembly().Location);
			new TestTypeScriptGenerator(".", new[] { "TestTypeScriptModel" }).Generate();
			var content = File.ReadAllText($@"{currentDirectory}\TestTypeScriptModel.ts");
			Assert.That(content, Is.EqualTo(@"//------------------------------------------------------------------------------
// <auto-generated>
//     This code was generated from a template.
//
//     Manual changes to this file may cause unexpected behavior in your application.
//     Manual changes to this file will be overwritten if the code is regenerated.
// </auto-generated>
//------------------------------------------------------------------------------
import { IEntity } from ""./IEntity"";

export class TestTypeScriptModel implements IEntity {
	TestGuid: string;
	TestString: string;
	TestDate: string;
	TestBool: boolean;
	TestInt: number;
	TestByte: number;
	ZGF_QuickStartPK: string;
}
"));
		}

		[Test]
		public void EntitiesForTypeScriptHasIsEditableProperty()
		{
			var entities = TypeScriptGenerator.EntitiesForTypeScript;
			var safeAssembly = Assembly.Load("CargoWise.RefDbRepo.Service.Schema_0_9_New");
			foreach (var entity in entities.Where(x => x.EndsWith("UserView")))
			{
				var entityType = safeAssembly.GetType($"CargoWise.RefDbRepo.Service.Schema_0_9_New.{entity}");
				var isEditableProperty = entityType.GetProperties().FirstOrDefault(x => x.Name.EndsWith("_IsEditable"));
				Assert.That(isEditableProperty, Is.Not.Null, $"{entityType.Name} Type should have '_IsEditable' Property.");
			}
		}
	}

	public class TestTypeScriptGenerator : TypeScriptGenerator
	{
		public TestTypeScriptGenerator(string targetPath, string[] entities) : base(targetPath, entities)
		{
		}

		protected override Type GetEntityType(string entity)
		{
			return typeof(TestTypeScriptModel);
		}
	}

	public class TestTypeScriptModel
	{
		public Guid TestGuid { get; set; }

		public string TestString { get; set; }

		public DateTime TestDate { get; set; }

		public bool? TestBool { get; set; }

		public int TestInt { get; set; }

		public Byte TestByte { get; set; }

		public Guid ZGF_QuickStartPK { get; set; }


		public virtual ICollection<TestTypeScriptModel> TestSubObjects { get; set; }
	}
}

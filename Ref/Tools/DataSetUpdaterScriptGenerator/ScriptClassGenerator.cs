using System;
using System.IO;
using System.Linq;
using CargoWise.RefDbRepo.Client.Common;
using CargoWise.RefDbRepo.Client.SqlServer;

namespace CargoWise.RefDbRepo.DataSetUpdaterScriptGenerator
{
	public class ScriptClassGenerator
	{
		public ScriptClassGenerator(IScriptGenerator generator, ISchemaInfo schemaInfo, ISQLBuilder sQLBuilder, ICustomScriptProvider provider)
		{
			this.generator = generator;
			this.schemaInfo = schemaInfo;
			this.sQLBuilder = sQLBuilder;
			this.provider = provider;
		}
		IScriptGenerator generator;
		ISchemaInfo schemaInfo;
		ISQLBuilder sQLBuilder;
		ICustomScriptProvider provider;

		public string GenerateScriptContent(IDataSetUpdaterInfo info, int version)
		{
			var script = string.IsNullOrEmpty(info.GetOverriddenPrepareTemporaryTablesScripts()) ? string.Join(",\r\n", generator.GeneratePrepareTemporaryTablesScripts(info).Select(x => "{ \"" + x.Item1 + "\", @\"" + x.Item2 + "\" }"))
				: info.GetOverriddenPrepareTemporaryTablesScripts();
			var prerequisites = generator.GetPrerequisites(info)
				.Select(x => "\"" + x.Substring(1) + "\"").ToArray();
			var prerequisitesText = prerequisites.Length == 0 ? "new string[0]" :
				"new [] { " + string.Join(", ", prerequisites) + " }";

			var customScript = provider.Get(info);
			var mergeScript = string.IsNullOrEmpty(customScript)
				? generator.GenerateMergeScript(info)
				: $"{customScript}\r\n{generator.GenerateMergeScript(info)}";

			return $@"//------------------------------------------------------------------------------
// <auto-generated>
//     This code was generated from DataSetUpdaterScriptGenerator.
//
//     Manual changes to this file may cause unexpected behavior in your application.
//     Manual changes to this file will be overwritten if the code is regenerated.
// </auto-generated>
//------------------------------------------------------------------------------
using System.Collections.Generic;

namespace {GeneratedNameSpace}
{{
	public partial class {info.GetStorageType().Name.Substring(1)}UpdaterInfo_{version} : IUpdaterScriptInfo
	{{
		public string DataSetName => ""{info.GetStorageType().Name.Substring(1)}"";

		public Dictionary<string, string> PrepareTemporaryTablesScripts => new Dictionary<string, string>
		{{
{script}
		}};

		public string MergeScript => @""
{mergeScript}
"";

		public string[] Prerequisites => {prerequisitesText};
		public int UpdaterVersion => {version};
	}}
}}
";
		}

		public static void WriteTo(IDataSetUpdaterInfo info, int version, string contents, string path)
		{
			var fileName = $"{info.GetStorageType().Name.Substring(1)}UpdaterInfo_{version}.cs";
			var filePath = Path.Combine(path, fileName);
			File.WriteAllText(filePath, contents);
			Console.WriteLine($"{fileName} generated successfully.");
		}

		const string GeneratedNameSpace = "CargoWise.RefDbRepo.RemoteDbManager";
	}
}

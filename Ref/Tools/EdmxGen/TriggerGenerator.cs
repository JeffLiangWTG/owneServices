		public TriggerGenerator(IEnumerable<string[]> dataSetsList, IDataSetHelper dataSetHelper)
		{
			Argument.NotNull(dataSetsList, nameof(dataSetsList));
			Argument.NotNull(dataSetHelper, nameof(dataSetHelper));
			this.dataSetHelper = dataSetHelper;
			dataSetsDictionary = dataSetsList.ToDictionary(k => k[0], v => v);
			tableAndColumnsDictionary = new Lazy<Dictionary<string, List<string>>>(() => dataSetHelper.GetAllTableAndColumns());
			tableAndFKsDictionary = new Lazy<Dictionary<string, List<FKRelationship>>>(() => GetFilteredTableAndFKs());
		}

		Dictionary<string, List<FKRelationship>> GetFilteredTableAndFKs()
		{
			var fkRelationshipProvider = new FKRelationshipProvider(dataSetsDictionary);
			var tableAndFKsDic = dataSetHelper.GetAllTableAndFKs();
			return fkRelationshipProvider.GetFilteredTableAndFKs(tableAndFKsDic);
		}

		static Tuple<string, string> GetPKAndTableCode(List<string> columnList)
		{
			return DataSetHelper.GetPKAndTableCode(columnList);
		}

		bool IsDataSet(string tableName)
		{
			return dataSetsDictionary.ContainsKey(tableName);
		}

		static bool IsFKColumnUniqueidentifier(FKRelationship fkRelation)
		{
			Argument.NotNull(fkRelation, nameof(fkRelation));
			return fkRelation.DataType.ToLower(CultureInfo.CurrentCulture) == "uniqueidentifier";
		}

		static bool ContainDataSetPKAndCodeColumns(List<string> columnList, out Tuple<string, string> dataSetColumns)
		{
			return DataSetHelper.ContainDataSetPKAndCodeColumns(columnList, out dataSetColumns);
		}

		public void CreateTriggers(string safeDbTriggersPath)
		{
			Argument.NotNullOrEmpty(safeDbTriggersPath, nameof(safeDbTriggersPath));
			if (!Directory.Exists(safeDbTriggersPath))
			{
				Directory.CreateDirectory(safeDbTriggersPath);
			}

			foreach (var dataSets in dataSetsDictionary.Keys)
			{
				var dataSetList = dataSetsDictionary[dataSets];
				CreateTrigger(dataSetList, safeDbTriggersPath);
			}
		}

		void CreateTrigger(string[] dataSets, string safeDbTriggersPath)
		{
			Argument.NotNull(dataSets, nameof(dataSets));
			var dataSetName = dataSets[0];
			foreach (var tableName in dataSets)
			{
				try
				{
					string scripts;
					if (tableName == dataSetName)
					{
						scripts = CreateTriggerForDataSet(tableName);
					}
					else
					{
						scripts = CreateTriggerForChildTable(tableName, dataSetName);
					}

					Argument.NotNullOrEmpty(scripts, nameof(scripts));
					var triggerFileName = Path.Combine(safeDbTriggersPath, $"{tableName}Trigger.sql");
					scripts = AutoGeneratedInfo + scripts;
					File.WriteAllText(triggerFileName, scripts);
					Console.WriteLine($"Generated {tableName}Trigger.sql successfully.");
				}
				catch
				{
					Console.WriteLine($"Generated {tableName}Trigger.sql failed.");
					throw;
				}
			}
		}

		string CreateTriggerForDataSet(string dataSetName)
		{
			var pkAndTableCode = GetPKAndTableCode(tableAndColumnsDictionary.Value[dataSetName]);
			var pkColumn = pkAndTableCode.Item1;
			var tableCode = pkAndTableCode.Item2;
			var scripts = $@"CREATE TRIGGER {dataSetName}_Version_Create
	ON {dataSetName}
	FOR INSERT
	AS
	INSERT RefDbVersionControl (RVC_ParentPK, RVC_ParentCode)
	SELECT {pkColumn}, '{tableCode}'
	FROM inserted
GO
CREATE TRIGGER {dataSetName}_Version_Update
	ON {dataSetName}
	FOR Update
	AS
	UPDATE version SET RVC_IsPublished = 0, RVC_LastEditedUser = dbo.GetUserId()
	FROM RefDbVersionControl version
	JOIN inserted ON {pkColumn} = RVC_ParentPK
	WHERE RVC_IsPublished = 1
GO
CREATE TRIGGER {dataSetName}_DataChangeHistory
	ON {dataSetName}
	FOR INSERT, UPDATE, DELETE
	AS
	DECLARE @sourcePK SourcePKList;
	INSERT @sourcePK
	SELECT {pkColumn}, '{tableCode}' FROM inserted
	UNION
	SELECT {pkColumn}, '{tableCode}' FROM deleted

	EXEC dbo.RecordDataSetChangeHistory @sourcePK
GO
CREATE TRIGGER {dataSetName}_DataProcessingResult_Delete
	ON {dataSetName}
	FOR DELETE
	AS
	BEGIN
		DELETE dpr
		FROM dbo.RefStagingDatabase_DataProcessingResult dpr
		JOIN deleted d ON dpr.DPR_ParentPK = d.{pkColumn}
	END
GO
";
			return scripts;
		}

		string CreateTriggerForChildTable(string tableName, string dataSetName)
		{
			var scripts = new StringBuilder($@"CREATE TRIGGER {tableName}_Combined
	ON {tableName}
	FOR INSERT, UPDATE, DELETE
	AS");
			var allColumns = tableAndColumnsDictionary.Value[tableName];
			var fkRelations = new List<FKRelationship>();
			if (tableAndFKsDictionary.Value.ContainsKey(tableName))
			{
				fkRelations = tableAndFKsDictionary.Value[tableName];
			}

			var pkColumn = GetPKAndTableCode(allColumns).Item1;

			Tuple<string, string> dataSetColumns;
			if (!ContainDataSetPKAndCodeColumns(allColumns, out dataSetColumns))
			{
				scripts.Append($@"
	DECLARE @sourcePK SourcePKList;
	INSERT @sourcePK");
				scripts.Append(CreateSelectStatements(tableName, dataSetName, allColumns, fkRelations));
			}
			else
			{
				var dataSetPKColumn = dataSetColumns.Item1;
				var dataSetCodeColumn = dataSetColumns.Item2;
				scripts.Append(CreateUpdateStatements(tableName, dataSetName, allColumns, fkRelations));
				scripts.AppendLine(CultureInfo.InvariantCulture, $@"
	DECLARE @sourcePK SourcePKList;
	INSERT @sourcePK
	SELECT t.{dataSetPKColumn}, t.{dataSetCodeColumn}
	FROM {tableName} t
	JOIN inserted ON t.{pkColumn} = inserted.{pkColumn}
	UNION
	SELECT {dataSetPKColumn}, {dataSetCodeColumn}
	FROM deleted");
			}

			scripts.AppendLine($@"
	UPDATE version SET RVC_IsPublished = 0, RVC_LastEditedUser = dbo.GetUserId()
	FROM RefDbVersionControl version
	JOIN @sourcePK ON RVC_ParentPK = PK AND RVC_ParentCode = TablePrefix
	WHERE RVC_IsPublished = 1

	EXEC dbo.RecordDataSetChangeHistory @sourcePK
GO");
			scripts.Append(CultureInfo.InvariantCulture, $@"
CREATE TRIGGER {tableName}_DataProcessingResult_Delete
	ON {tableName}
	FOR DELETE
	AS
	BEGIN
		DELETE dpr
		FROM dbo.RefStagingDatabase_DataProcessingResult dpr
		JOIN deleted d ON dpr.DPR_ParentPK = d.{pkColumn}
	END
GO
");
			return scripts.ToString();
		}

		string CreateSelectStatements(string tableName, string dataSetName, List<string> allColumns, IEnumerable<FKRelationship> fkRelationships)
		{
			Argument.NotNull(fkRelationships, nameof(fkRelationships));
			var strBuilder = new StringBuilder();
			var dataSetPKAndTableCode = GetPKAndTableCode(tableAndColumnsDictionary.Value[dataSetName]);
			var columnName = dataSetPKAndTableCode.Item1;
			var dataSetTableCode = $"'{dataSetPKAndTableCode.Item2}'";
			var joinStatements = string.Empty;
			var fkRelationToDataset = fkRelationships.FirstOrDefault(x => x.ReferencedTable == dataSetName);

			if (DataSetHelper.ContainParentPKAndCodeColumns(allColumns, out var parentPKAndCodeColumns))
			{
				//edge case e.g. StmNote, UNDGAttributeZZ
				columnName = parentPKAndCodeColumns.Item1;
				dataSetTableCode = parentPKAndCodeColumns.Item2;
			}
			else if (fkRelationToDataset != null)
			{
				var fkColumn = fkRelationToDataset.Column;
				if (IsFKColumnUniqueidentifier(fkRelationToDataset))
				{
					columnName = fkColumn;
				}
				else
				{
					//edge case e.g.RefCusTaxOrFee
					joinStatements = $@"
	JOIN {dataSetName} ON {fkRelationToDataset.ReferencedColumn} = {fkColumn}";
				}
			}
			else
			{
				Console.ForegroundColor = ConsoleColor.Red;
				Console.WriteLine($"Failed to generate triggers for table {tableName}. Please create triggers manually.");
				Console.ResetColor();
			}

			strBuilder.AppendLine(CultureInfo.InvariantCulture, $@"
	SELECT {columnName}, {dataSetTableCode} FROM inserted{joinStatements}
	UNION
	SELECT {columnName}, {dataSetTableCode} FROM deleted{joinStatements}");
			return strBuilder.ToString();
		}

		string CreateUpdateStatements(string tableName, string dataSetName, List<string> allColumns, IEnumerable<FKRelationship> fkRelationships)
		{
			Argument.NotNull(fkRelationships, nameof(fkRelationships));
			var fkRelations = fkRelationships.OrderBy(x => x.ReferencedTable).ToList();
			var fkRelationToDataset = fkRelations.FirstOrDefault(x => x.ReferencedTable == dataSetName);
			var strBuilder = new StringBuilder();
			var dataSetPKStatements = string.Empty;
			var dataSetCodeStatements = string.Empty;
			var joinStatements = string.Empty;

			if (fkRelationToDataset != null)
			{
				fkRelations.Remove(fkRelationToDataset);
				fkRelations.Insert(0, fkRelationToDataset);
			}
			for (var i = 0; i < fkRelations.Count; i++)
			{
				var fkRelation = fkRelations[i];
				var referencedTableColumns = tableAndColumnsDictionary.Value[$"{fkRelation.ReferencedTable}"];
				string pk;
				string dataSetCode;
				if (IsDataSet(fkRelation.ReferencedTable))
				{
					pk = $"inserted.{fkRelation.Column}";
					dataSetCode = $"'{GetPKAndTableCode(referencedTableColumns).Item2}'";
				}
				else if (ContainDataSetPKAndCodeColumns(referencedTableColumns, out var dataSetColumns))
				{
					pk = dataSetColumns.Item1;
					dataSetCode = dataSetColumns.Item2;
					joinStatements += $@"
		LEFT JOIN {fkRelation.ReferencedTable} ON inserted.{fkRelation.Column} = {fkRelation.ReferencedColumn}";
				}
				else
				{
					var referencedTableFK = tableAndFKsDictionary.Value[fkRelation.ReferencedTable]?.First(x => IsDataSet(x.ReferencedTable));
					if (referencedTableFK == null)
					{
						Console.ForegroundColor = ConsoleColor.Red;
						Console.WriteLine($"Failed to generate triggers for table {tableName}. Please create triggers manually.");
						Console.ResetColor();
						continue;
					}
					else
					{
						//e.g. RefCusTaxOrFeeType->RefCusTaxOrFee->RefCusTaxOrFeeLanguage
						if (!IsFKColumnUniqueidentifier(referencedTableFK))
						{
							var parentOfReferencedTable = tableAndFKsDictionary.Value[referencedTableFK.Table]?.First(x => IsDataSet(x.ReferencedTable));
							var parentPkAndTableCode = GetPKAndTableCode(tableAndColumnsDictionary.Value[parentOfReferencedTable.ReferencedTable]);
							pk = parentPkAndTableCode.Item1;
							dataSetCode = $"'{parentPkAndTableCode.Item2}'";
							joinStatements += $@"
		LEFT JOIN {fkRelation.ReferencedTable} ON inserted.{fkRelation.Column} = {fkRelation.ReferencedColumn}
		LEFT JOIN {parentOfReferencedTable.ReferencedTable} ON {parentOfReferencedTable.Column} = {parentOfReferencedTable.ReferencedColumn}";
						}
						else
						{
							pk = referencedTableFK.Column;
							dataSetCode = $"'{GetPKAndTableCode(tableAndColumnsDictionary.Value[referencedTableFK.ReferencedTable]).Item2}'";
							joinStatements += $@"
		LEFT JOIN {fkRelation.ReferencedTable} ON inserted.{fkRelation.Column} = {fkRelation.ReferencedColumn}";
						}
					}
				}

				if (fkRelations.Count == 1)
				{
					//e.g. RefCusConditionLanguage
					dataSetPKStatements = $"{pk},";
					dataSetCodeStatements = dataSetCode;
				}
				else
				{
					if (i == 0)
					{
						dataSetPKStatements = $"COALESCE({pk}";
						dataSetCodeStatements = $"CASE WHEN {pk} IS NOT NULL THEN {dataSetCode} ";
					}
					else
					{
						dataSetPKStatements += $", {pk}";
						dataSetCodeStatements += $"ELSE CASE WHEN {pk} IS NOT NULL THEN {dataSetCode} ";
					}
					if (i == fkRelations.Count - 1)
					{
						dataSetPKStatements += "),";
						dataSetCodeStatements += string.Concat(Enumerable.Repeat("END ", fkRelations.Count));
					}
				}
			}

			var tablePKColumn = GetPKAndTableCode(allColumns).Item1;
			ContainDataSetPKAndCodeColumns(allColumns, out var tableDataSetPKAndCodeColumns);
			strBuilder.AppendLine(CultureInfo.InvariantCulture, $@"
	IF (SELECT CASE WHEN EXISTS(SELECT 1 FROM INSERTED) AND NOT EXISTS(SELECT 1 FROM DELETED) THEN 1 ELSE 0 end) = 1
	BEGIN
		UPDATE t SET
		{tableDataSetPKAndCodeColumns.Item1} = {dataSetPKStatements}
		{tableDataSetPKAndCodeColumns.Item2} = {dataSetCodeStatements}
		FROM {tableName} t
		JOIN inserted ON t.{tablePKColumn} = inserted.{tablePKColumn}{joinStatements}
	END");
			return strBuilder.ToString();
		}


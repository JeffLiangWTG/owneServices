using System;
using System.Diagnostics;
using System.IO;
using System.Linq;
using System.Reflection;
using WTG.ErrorReporting;

namespace CargoWise.RefDbRepo.Common.ErrorReporting
{
	public class ErrorReportBuilder : IErrorReportBuilder
	{
		public string AutoGeneratedSubjectPrefix => "AUTO-GENERATED by RefDbRepo";

#if DEBUG
		public
#endif
		IOpaqueErrorReport BuildErrorReport(Exception exception, string keyBase, string description, bool autoGenerated, string machineName, bool forceReport = false)
		{
			Argument.Argument.NotNull(exception, nameof(exception));
			if (!forceReport && AvoidReport(exception, machineName))
			{
				return null;
			}

			var assembly = Assembly.GetExecutingAssembly();
			var fvi = FileVersionInfo.GetVersionInfo(assembly.Location);
			var fi = new FileInfo(assembly.Location);
			var key = (string.IsNullOrEmpty(keyBase) ? "" : keyBase) + (exception.StackTrace ?? exception.Message);
			var desValue = string.IsNullOrEmpty(description) ? exception.Message : description;

			var builder = new EnterpriseErrorReportBuilder();
			builder.SetRandomErrorReportID();
			builder.SetKey(key);
			builder.SetExceptionDescription(desValue);
			builder.SetSubject(autoGenerated ? AutoGeneratedSubjectPrefix : string.Empty);
			builder.SetSourcePrefix("REF");
			builder.SetExeCreationTime(fi.LastWriteTimeUtc);
			builder.SetVersion(new Version(fvi.FileVersion));
			builder.SetTimeOfException(DateTime.UtcNow);
			builder.SetRootException(exception);

			return builder;
		}

		public IOpaqueErrorReport BuildErrorReport(Exception exception, string keyBase, string description, bool autoGenerated)
		{
			Argument.Argument.NotNull(exception, nameof(exception));
			return BuildErrorReport(exception, keyBase, description, autoGenerated, Environment.MachineName);
		}

		static bool AvoidReport(Exception exception, string machineName)
		{
#if DEBUG
			return true;
#else
			if (!MachineNameHelper.ShouldErrorBeLogged(machineName))
			{
				return true;
			}

			var currentException = exception;
			while (currentException != null)
			{
				var exceptionMessage = currentException.Message;
				if (!string.IsNullOrEmpty(exceptionMessage))
				{
					if (exceptionMessage.Contains(ErrorReportingKnownExceptionsMapping.ErrorReportingTestMessage))
					{
						return true;
					}

					if (ErrorReportingKnownExceptionsMapping.SQLConnectionExceptionMessages.Any(avoidMessage => exceptionMessage.Contains(avoidMessage)))
					{
						return true;
					}
				}
				currentException = currentException.InnerException;
			}
			return false;
#endif
		}
	}
}

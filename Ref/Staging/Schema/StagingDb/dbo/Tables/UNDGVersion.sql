CREATE TABLE UNDGVersion
(
	[DV_PK] UNIQUEIDENTIFIER NOT NULL CONSTRAINT [DF_UNDGVersion_DV_PK] DEFAULT NEWID(),
	[DV_Name] VARCHAR(20) NOT NULL CONSTRAINT [DF_UNDGVersion_DV_Name] DEFAULT '',
	[DV_Standard] VARCHAR(3) NOT NULL CONSTRAINT [DF_UNDGVersion_DV_Standard] DEFAULT '',
	[DV_IsActive] BIT NOT NULL CONSTRAINT [DF_UNDGVersion_DV_IsActive] DEFAULT 1,
	CONSTRAINT [PK_UNDGVersion] PRIMARY KEY ([DV_PK]),
	CONSTRAINT [CK_UNDGVersion_DV_Standard] CHECK ([DV_Standard] = 'ADN' OR [DV_Standard] = 'ADR' OR [DV_Standard] = 'CFR' OR [DV_Standard] = 'JTT' OR [DV_Standard] = 'RID')
)

CREATE TABLE RefApplicationAttributeType(
	RAT_PK UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_RefApplicationAttributeType_RAT_PK DEFAULT (NEWID()),
	RAT_Type VARCHAR(10) NOT NULL CONSTRAINT DF_RefApplicationAttributeType_RAT_Type DEFAULT(''),
	RAT_Description NVARCHAR(200) NOT NULL CONSTRAINT DF_RefApplicationAttributeType_RAT_Description DEFAULT(''),
	RAT_SysStartTime DATETIME2 GENERATED ALWAYS AS ROW START NOT NULL CONSTRAINT DF_RAT_SysStartTime DEFAULT CONVERT(DATETIME2, '1900-01-01 0:0:0.0000000'),
	RAT_SysEndTime DATETIME2 GENERATED ALWAYS AS ROW END NOT NULL CONSTRAINT DF_RAT_SysEndTime DEFAULT CONVERT(DATETIME2, '9999-12-31 23:59:59.9999999'),
	PERIOD FOR SYSTEM_TIME (RAT_SysStartTime, RAT_SysEndTime),
	CONSTRAINT PK_RefApplicationAttributeType PRIMARY KEY CLUSTERED (RAT_PK ASC),
)
WITH (SYSTEM_VERSIONING = ON (HISTORY_TABLE = dbo.RefApplicationAttributeTypeHistory))
GO
CREATE UNIQUE NONCLUSTERED INDEX IX_RefApplicationAttributeType_RAT_Type ON RefApplicationAttributeType (RAT_Type)
GO

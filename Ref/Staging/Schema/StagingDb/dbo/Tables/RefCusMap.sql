CREATE TABLE RefCusMap (
	ZZM_PK UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_RefCusMap DEFAULT (NEWID()),
	ZZM_ZZP_NKMapType VARCHAR(5) NOT NULL,
	ZZM_CW1orCommercialValue NVARCHAR(35) NOT NULL,
	ZZM_CustomsValue NVARCHAR(35) NOT NULL,
	ZZM_StartDate SMALLDATETIME NOT NULL,
	ZZM_EndDate SMALLDATETIME NOT NULL,
	ZZM_ZZZ_NKDataGrouping VARCHAR(3) NOT NULL,
	CONSTRAINT PK_RefCusMap PRIMARY KEY CLUSTERED (ZZM_PK ASC),
	CONSTRAINT CK_RefCusMap_ZZM_StartDate_ZZM_EndDate CHECK (ZZM_StartDate<=ZZM_EndDate),
)

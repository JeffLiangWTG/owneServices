CREATE TABLE [dbo].[RefErrorReport](
	[RER_PK] [UNIQUEIDENTIFIER] NOT NULL CONSTRAINT DF_RefErrorReport_RER_PK DEFAULT NEWID(),
	[RER_Exception] [VARCHAR](MAX) NOT NULL,
	[RER_Status] [CHAR](3) NOT NULL CONSTRAINT DF_RefErrorReport_RER_Status DEFAULT 'QUE',
	[RER_JobName] [VARCHAR](50) NOT NULL CONSTRAINT DF_RefErrorReport_RER_JobName DEFAULT '',
	[RER_Source] [VARCHAR](50) NOT NULL,
	[RER_SDA] [UNIQUEIDENTIFIER] NULL,
	[RER_ExceptionTimeUtc] [datetime] NOT NULL,
CONSTRAINT PK_RER_RefErrorReport PRIMARY KEY NONCLUSTERED (RER_PK),
CONSTRAINT FK_RER_RefErrorReport_SourceData FOREIGN KEY([RER_SDA]) REFERENCES [dbo].[SourceData] ([SDA_PK]),
CONSTRAINT CK_RER_Status CHECK ([RER_Status] = 'QUE' OR [RER_Status] = 'SNT' OR [RER_Status] = 'ERR'))

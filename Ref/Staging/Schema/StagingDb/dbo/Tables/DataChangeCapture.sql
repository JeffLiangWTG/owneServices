CREATE TABLE [dbo].[DataChangeCapture]
(
	DCC_PK uniqueidentifier NOT NULL CONSTRAINT DF_DataChangeCapture_DCC_PK DEFAULT (newid()),
	DCC_Column VARCHAR(25) NOT NULL,
	DCC_ParentPK UNIQUEIDENTIFIER NOT NULL,
	DCC_ParentCode VARCHAR(3) NOT NULL,
	DCC_OldValue VARCHAR(MAX) NULL,
	DCC_NewValue VARCHAR(MAX) NOT NULL,
	DCC_EventTimeUTC DATETIME2 NOT NULL CONSTRAINT DF_DataChangeCapture_DCC_EventTimeUTC DEFAULT SYSUTCDATETIME(),
	CONSTRAINT PK_DataChangeCapture_DCC_PK PRIMARY KEY CLUSTERED (DCC_PK)
)

CREATE TABLE RefApplicationAttribute(
	RAA_PK UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_RefApplicationAttribute_RAA_PK DEFAULT (NEWID()),
	RAA_ConfigFilePath VARCHAR(200) NOT NULL CONSTRAINT DF_RefApplicationAttribute_RAA_ConfigFilePath DEFAULT(''),
	RAA_AttributeName NVARCHAR(100) NOT NULL CONSTRAINT DF_RefApplicationAttribute_RAA_AttributeName DEFAULT(''),
	RAA_Value NVARCHAR(200) NOT NULL CONSTRAINT DF_RefApplicationAttribute_RAA_Value DEFAULT(''),
	RAA_RAT_NKType VARCHAR(10) NOT NULL,
	RAA_Content VARBINARY(MAX) NULL,
	RAA_JobGroup NVARCHAR(150) NOT NULL CONSTRAINT DF_RefApplicationAttribute_RAA_JobGroup DEFAULT(''),
	RAA_SysStartTime DATETIME2 GENERATED ALWAYS AS ROW START NOT NULL CONSTRAINT DF_RAA_SysStartTime DEFAULT CONVERT(DATETIME2, '1900-01-01 0:0:0.0000000'),
	RAA_SysEndTime DATETIME2 GENERATED ALWAYS AS ROW END NOT NULL CONSTRAINT DF_RAA_SysEndTime DEFAULT CONVERT(DATETIME2, '9999-12-31 23:59:59.9999999'),
	PERIOD FOR SYSTEM_TIME (RAA_SysStartTime, RAA_SysEndTime),
	CONSTRAINT PK_RefApplicationAttribute PRIMARY KEY CLUSTERED (RAA_PK ASC),
	CONSTRAINT FK_RefApplicationAttribute_ApplicationAttributeType FOREIGN KEY (RAA_RAT_NKType) REFERENCES RefApplicationAttributeType (RAT_Type),
)
WITH (SYSTEM_VERSIONING = ON (HISTORY_TABLE = dbo.RefApplicationAttributeHistory))
GO
CREATE UNIQUE NONCLUSTERED INDEX IX_RefApplicationAttribute_RAA_ConfigFilePath_RAA_AttributeName ON RefApplicationAttribute (RAA_ConfigFilePath ASC, RAA_AttributeName ASC)
GO

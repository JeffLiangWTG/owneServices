CREATE TABLE [dbo].[RefFacility](
	[RFT_PK] UNIQUEIDENTIFIER NOT NULL CONSTRAINT [DF_RefFacility_RFT_PK] DEFAULT(NEWID()),
	[RFT_IsActive] BIT NOT NULL CONSTRAINT [DF_RefFacility_RFT_IsActive] DEFAULT 1,
	[RFT_Code] CHAR(11) NOT NULL CONSTRAINT [DF_RefFacility_RFT_Code] DEFAULT '',
	[RFT_Name] NVARCHAR(128) NOT NULL CONSTRAINT [DF_RefFacility_RFT_Name] DEFAULT '',
	[RFT_FacilityType] CHAR(3) NOT NULL CONSTRAINT [DF_RefFacility_RFT_FacilityType] DEFAULT '',
	[RFT_Address1] NVARCHAR(50) NOT NULL CONSTRAINT [DF_RefFacility_RFT_Address1] DEFAULT '',
	[RFT_Address2] NVARCHAR(50) NOT NULL CONSTRAINT [DF_RefFacility_RFT_Address2] DEFAULT '',
	[RFT_City] NVARCHAR(50) NOT NULL CONSTRAINT [DF_RefFacility_RFT_City] DEFAULT '',
	[RFT_State] NVARCHAR(25) NOT NULL CONSTRAINT [DF_RefFacility_RFT_State] DEFAULT '',
	[RFT_PostCode] NVARCHAR(10) NOT NULL CONSTRAINT [DF_RefFacility_RFT_PostCode] DEFAULT '',
	[RFT_RL_NKLocationCode] VARCHAR(5) NOT NULL CONSTRAINT [DF_RefFacility_RFT_RL_NKLocationCode] DEFAULT '',
	[RFT_RN_NKCountryCode] CHAR(2) NOT NULL CONSTRAINT [DF_RefFacility_RFT_RN_NKCountryCode] DEFAULT '',
	[RFT_SMDGCode] VARCHAR(12) NOT NULL CONSTRAINT [DF_RefFacility_RFT_SMDGCode] DEFAULT '',
	[RFT_BICCode] VARCHAR(9) NOT NULL CONSTRAINT [DF_RefFacility_RFT_BICCode] DEFAULT '',
	[RFT_IHSGlobalPortId] VARCHAR(22) NOT NULL CONSTRAINT [DF_RefFacility_RFT_IHSGlobalPortId] DEFAULT '',
	[RFT_IATACode] VARCHAR(3) NOT NULL CONSTRAINT [DF_RefFacility_RFT_IATACode] DEFAULT '',
	[RFT_IsSea] BIT NOT NULL CONSTRAINT [DF_RefFacility_RFT_IsSea] DEFAULT 0,
	[RFT_IsAir] BIT NOT NULL CONSTRAINT [DF_RefFacility_RFT_IsAir] DEFAULT 0,
	[RFT_IsRail] BIT NOT NULL CONSTRAINT [DF_RefFacility_RFT_IsRail] DEFAULT 0,
	[RFT_IsRoad] BIT NOT NULL CONSTRAINT [DF_RefFacility_RFT_IsRoad] DEFAULT 0,
	[RFT_IsInlandWaterway] BIT NOT NULL CONSTRAINT [DF_RefFacility_RFT_IsInlandWaterway] DEFAULT 0,
	[RFT_ContainerAutomationAvailable] BIT NOT NULL CONSTRAINT [DF_RefFacility_RFT_ContainerAutomationAvailable] DEFAULT 0,
	[RFT_RequiresCredentials] BIT NOT NULL CONSTRAINT [DF_RefFacility_RFT_RequiresCredentials] DEFAULT 0,
	[RFT_GeoLocation] GEOGRAPHY NULL CONSTRAINT [DF_RefFacility_RFT_GeoLocation] DEFAULT geography::STPointFromText('POINT EMPTY', 4326),
	CONSTRAINT [PK_RefFacility] PRIMARY KEY NONCLUSTERED (RFT_PK ASC),
	CONSTRAINT [CK_RefFacility_RFT_Code] CHECK (LEN(RFT_Code) = 11),
	CONSTRAINT [CK_RefFacility_RFT_FacilityType] CHECK (RFT_FacilityType = 'CTO' OR RFT_FacilityType = 'CYD' OR RFT_FacilityType = 'CFS'),
	CONSTRAINT [CK_RefFacility_RFT_GeoLocation] CHECK (RFT_GeoLocation.STIsValid() = 1 AND RFT_GeoLocation.STGeometryType() = 'Point'),
	CONSTRAINT [CK_RefFacility_RFT_IATACode] CHECK (LEN(RFT_IATACode) = 0 OR LEN(RFT_IATACode) = 3),
	CONSTRAINT [CK_RefFacility_RFT_IHSGlobalPortId] CHECK (LEN(RFT_IHSGlobalPortId) = 0 OR LEN(RFT_IHSGlobalPortId) = 22),
	CONSTRAINT [CK_RefFacility_RFT_Name] CHECK (DATALENGTH(RFT_Name) > 0),
	CONSTRAINT [CK_RefFacility_RFT_RL_NKLocationCode] CHECK (LEN(RFT_RL_NKLocationCode) = 0 OR (LEN(RFT_RL_NKLocationCode) = 5 AND SUBSTRING(RFT_RL_NKLocationCode, 1, 2) = RFT_RN_NKCountryCode)),
	CONSTRAINT [CK_RefFacility_RFT_RN_NKCountryCode] CHECK (LEN(RFT_RN_NKCountryCode) = 2)
)
GO

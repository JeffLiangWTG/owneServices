CREATE TABLE [RefMaterial](
	[RMC_PK] UNIQUEIDENTIFIER NOT NULL,
	[RMC_IsActive] BIT NOT NULL CONSTRAINT [DF_RefMaterial_RMC_IsActive]  DEFAULT (1),
	[RMC_Code] VARCHAR(10) NOT NULL CONSTRAINT [DF_RefMaterial_RMC_Code]  DEFAULT (''),
	[RMC_Description] VARCHAR(240) NOT NULL CONSTRAINT [DF_RefMaterial_RMC_Description]  DEFAULT (''),
	[RMC_Group] VARCHAR(25) NOT NULL CONSTRAINT [DF_RefMaterial_RMC_Group]  DEFAULT (''),
	CONSTRAINT [PK_RefMaterial] PRIMARY KEY CLUSTERED ([RMC_PK] ASC),
	CONSTRAINT [CK_RefMaterial_RMC_Group] CHECK  ([RMC_Group] = 'CEDEX' OR [RMC_Group] = 'MERC')
)
GO

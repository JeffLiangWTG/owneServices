	@Test
	public void testDecryptMessageStream_Success() throws FileNotFoundException, Exception {
		String content = "Hello World";
		TestCIGDecodeEncodeHelper helper = getCIGDecodeEncodeHelper();
		byte[] encryptedMessageInput = helper.encryptAndWrapIntoMimeMessage(content);
		StringBuilder expected = new StringBuilder();
		expected.append(helper.getPreviousAutoGeneratedForTestOnlyMimeHeaders()).append("\r\n");
		expected.append("<CIGDecode Part Boundry>\r\n");
		expected.append("Received-content-MIC: eyqjqVfwAvcHEhpwTa+6kRBUNPY=\r\n");
		expected.append("<CIGDecode Part Boundry>\r\n");
		expected.append(content);

		CIGDecode cigdecode = new CIGDecode(getSenderPrivateKey(), PASSWORD, LOGGER);

		ByteArrayOutputStream outputStream = new ByteArrayOutputStream();
		cigdecode.decryptMessage(new ByteArrayInputStream(encryptedMessageInput), outputStream);
		assertEquals(expected.toString(), outputStream.toString("UTF-8"));
	}


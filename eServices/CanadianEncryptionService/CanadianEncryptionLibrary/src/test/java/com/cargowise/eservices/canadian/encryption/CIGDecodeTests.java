	@Test
	public void testValidateCertificates_CertificationException_ReturnFalse()
			throws UserBadPasswordException, UserFatalException, CertificateException, IOException, UserNotLoggedInException {
		CIGEncode cigencode = new CIGEncode(getRecipientPublicKey(), getSenderPrivateKey(), PASSWORD, LOGGER);
		CIGDecode cigdecode = new CIGDecode(getSenderPrivateKey(), PASSWORD, LOGGER);
		boolean isValid = cigdecode.validateCertificates(cigencode.signerCertificates);
		assertTrue(isValid);
		isValid = cigdecode.validateCertificates(new X509Certificate[]{cigencode.recipientCertificate});
		assertFalse(isValid);
	}

package com.cargowise.eservices.canadian.encryption;

import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.FileNotFoundException;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.Charset;

import org.apache.commons.io.IOUtils;
import org.apache.log4j.Logger;

public class TestCIGDecodeEncodeHelper {
	private final CIGEncode cigencode;
	private final CIGDecode cigdecode;

	public TestCIGDecodeEncodeHelper(final InputStream senderPublicKey, final InputStream senderPrivateKey,
			final String password, final Logger logger) throws Exception {
		byte[] senderPrivateKeyBytes = IOUtils.toByteArray(senderPrivateKey);
		cigencode = new CIGEncode(senderPublicKey, new ByteArrayInputStream(senderPrivateKeyBytes), password, logger);
		cigdecode = new CIGDecode(new ByteArrayInputStream(senderPrivateKeyBytes), password, logger);
	}

	public final byte[] encryptAndWrapIntoMimeMessage(final String content) throws FileNotFoundException, Exception {
		ByteArrayInputStream inputStream = new ByteArrayInputStream(content.getBytes(Charset.forName("UTF-8")));
		ByteArrayOutputStream outputStream = new ByteArrayOutputStream();
		cigencode.createSignedAndEncryptedMessage(inputStream, outputStream);
		byte[] encryptedContent = outputStream.toByteArray();
		return combineByteArray(getMimeHeaders(encryptedContent.length), encryptedContent);
	}

	public final String getDecryptedContent(final byte[] content) throws Exception {
		byte[] encryptedMimeMessage = combineByteArray(getMimeHeaders(content.length), content);
		return cigdecode.decryptMessage(encryptedMimeMessage)
				.replaceFirst("Received-content-MIC: .*", "Received-content-MIC: pr0qhRoqtrxPxF4rCVlBeGgbWV4=")
				.replaceFirst("Content-Length: .*", "Content-Length: 6343");
	}

	public final String getDecryptedContentAndRemoveHeader(final byte[] content) throws Exception {
		String result = getDecryptedContent(content);
		String lastHeaderElement = "<CIGDecode Part Boundry>";
		int lastIndexOfHeader = result.lastIndexOf(lastHeaderElement) + lastHeaderElement.length();
		return result.substring(lastIndexOfHeader).trim();
	}

	public static byte[] combineByteArray(final byte[] bytes1, final byte[] bytes2) throws IOException {
		ByteArrayOutputStream outputStream = new ByteArrayOutputStream();
		outputStream.write(bytes1);
		outputStream.write(bytes2);
		return outputStream.toByteArray();
	}

	public final byte[] getMimeHeaders(final int messageLength) {
		StringBuilder mimeHeaders = new StringBuilder();
		mimeHeaders.append("MIME-Version: 1.0\r\n");
		mimeHeaders.append("From: ver7enterprise@cargowise.com\r\n");
		mimeHeaders.append("Message-ID: <15830.3046945.433.1487113607876.JavaMail.ctladm3@EC07ZT5615>\r\n");
		mimeHeaders.append("Date: Fri, 17 Feb 2017 23:06:47 GMT\r\n");
		mimeHeaders.append("Accept: application/pkcs7-mime; text/plain\r\n");
		mimeHeaders.append("Connection: keep-alive\r\n");
		mimeHeaders.append("Host: www.test.com\r\n");
		mimeHeaders.append("Content-Transfer-Encoding: binary\r\n");
		mimeHeaders.append("User-Agent: Canadian Customs InboundServiceTask 1.0\r\n");
		mimeHeaders.append("Content-Type: Application/pkcs7-mime\r\n");
		mimeHeaders.append(String.format("Content-Length: %1$d\r%n\r%n", messageLength));
		previousMimeHeaders = mimeHeaders.toString();
		return previousMimeHeaders.getBytes(Charset.forName("UTF-8"));
	}

	private String previousMimeHeaders = "";

	public final String getPreviousAutoGeneratedForTestOnlyMimeHeaders() {
		return previousMimeHeaders.trim();
	}
}

using System;
using System.Configuration;
using System.IO;
using System.IO.Compression;
using System.Text;
using System.Web.Services.Protocols;
using BAMManagement;

/// <summary>
/// Web page to view eHub message data stored in BAM
/// </summary>
public partial class _Default : System.Web.UI.Page 
{
    private const string INVALID_QUERY_STRING_MSG = "Insufficient information to perform query";
    private const string BAM_SOAP_EXCEPTION_MSG = "Cannot retrieve message data.  Please review the server EventLog for more information";
    private const string DOWNLOAD_COMPLETE_MSG = "Message data delivery complete";
    private const string NO_MSG_FOUND_MSG = "No message data available";

    /// <summary>
    /// Validate the query string and call the render/download logic if all is good
    /// </summary>
    /// <param name="sender"></param>
    /// <param name="e"></param>
    protected void Page_Load(object sender, EventArgs e)
    {
        // Unpack the query string
        string viewName = Request.QueryString["viewName"];
        string activityName = Request.QueryString["activityName"];
        string activityInstanceId = Request.QueryString["activityInstanceId"];
        string referenceType = Request.QueryString["referenceType"];

        // Validate all content was passed
        if (!String.IsNullOrEmpty(viewName) &&
            !String.IsNullOrEmpty(activityName) &&
            !String.IsNullOrEmpty(activityInstanceId) &&
            !String.IsNullOrEmpty(referenceType))
        {
            bool decompress = false;
            bool.TryParse(Request.QueryString["compressed"], out decompress);
            RenderMessage(viewName, activityName, activityInstanceId, referenceType, decompress);
        }
        else
        {
            Response.Write(INVALID_QUERY_STRING_MSG);
        }
    }

    /// <summary>
    /// Calls the BAM management webservice to retrieve the logged BAM message body as long reference
    /// data. The query string content is passed in to retrieve the right BAM view and activity ID.
    /// Then, decides whether to decompress and/or render in the browser or force a file download
    /// depending on the FileDownloadThresholdBytes application setting
    /// </summary>
    /// <remarks>Any soap exceptions generated by the BAM management webservice will be logged
    /// in the event log of the BAM webservice host machine</remarks>
    /// <param name="viewName"></param>
    /// <param name="activityName"></param>
    /// <param name="activityInstanceId"></param>
    /// <param name="referenceType"></param>
    /// <param name="decompress"></param>
    private void RenderMessage(string viewName, string activityName, string activityInstanceId, string referenceType, bool decompress)
    {
        // TODO: Refactor this method
        Reference[] references = null;

        try
        {
            // Call the management webservice
            using (BamManagementService bam = new BamManagementService())
            {
                bam.UseDefaultCredentials = true;
                references = bam.GetReferences(viewName, activityName, activityInstanceId, referenceType);
            }
        }
        catch (SoapException)
        {
            Response.Write(BAM_SOAP_EXCEPTION_MSG);
            return;
        }

        // Write the long reference data to the browser as XML or plain text
        // or force a download depending on the message's content and size
        if (references.Length > 0 && references[0].LongReferenceData.Length > 0)
        {
            string messageText = string.Empty;
            int downloadThreshold = Convert.ToInt32(ConfigurationManager.AppSettings["FileDownloadThresholdBytes"]);
            if (references[0].LongReferenceData.Length <= downloadThreshold)
            {
                // Render the message through the browser
                // Does it need to be decompressed
                if (decompress)
                {
                    using (MemoryStream ms = Decompress(references[0].LongReferenceData))
                    {
                        Encoding encoding = Encoding.UTF8;

                        byte[] first4Bytes = new byte[4];
                        ms.Read(first4Bytes, 0, 4);
                        ms.Seek(0, SeekOrigin.Begin);

                        if (first4Bytes[0] == 0xEF && first4Bytes[1] == 0xBB && first4Bytes[2] == 0xBF)
                            encoding = Encoding.UTF8;
                        else if (first4Bytes[0] == 0xFE && first4Bytes[1] == 0xFF)
                            encoding = Encoding.BigEndianUnicode;
                        else if (first4Bytes[0] == 0xFF && first4Bytes[1] == 0xFE)
                            encoding = Encoding.Unicode;
                        else if (first4Bytes[0] == 0xFF && first4Bytes[1] == 0xFE && first4Bytes[2] == 0x00 && first4Bytes[3] == 0x00)
                            encoding = Encoding.UTF32;
                        else if (first4Bytes[0] == 0x2B && first4Bytes[1] == 0x2F && first4Bytes[2] == 0x76 && (first4Bytes[3] == 0x38 || first4Bytes[3] == 0x39 || first4Bytes[3] == 0x2B || first4Bytes[3] == 0x2F))
                            encoding = Encoding.UTF7;

                        messageText = encoding.GetString(ms.ToArray());
                    }
                }
                else
                {
                    messageText = references[0].LongReferenceData;
                }

                // Is it XML or text
                if (messageText.StartsWith("<"))
                {
                    Response.ContentType = "text/xml";
                }
                else
                {
                    Response.ContentType = "text/html";
                }
                Response.Write(messageText);
                messageText = null;
            }
            else
            {
                // Stream it to the client via a file download avoiding the 4MB download limit of IIS
                Response.Buffer = false;
                Response.ContentType = "application/octet-stream";
                Response.AddHeader("content-disposition", "attachment;filename=" + activityInstanceId + ".txt");

                // Start streaming the data back to the client
                int bytesRead = 0;
                int bufferSize = Convert.ToInt32(ConfigurationManager.AppSettings["StreamingBufferSize"]);
                if (bufferSize == 0) throw new ConfigurationErrorsException("StreamingBufferSize configuration value is zero.  Check the .config file has the appSetting key value pair.");
                byte[] bytes = new byte[bufferSize];

                if (decompress)
                {
                    // Decompress the data while streaming each chunk back to the client
                    using (MemoryStream zippedData = new MemoryStream(Convert.FromBase64String(references[0].LongReferenceData)))
                    {
                        references[0].LongReferenceData = null;
                        using (GZipStream zipStream = new GZipStream(zippedData, CompressionMode.Decompress, true))
                        {
                            do
                            {
                                bytesRead = zipStream.Read(bytes, 0, bufferSize);
                                if (Response.IsClientConnected)
                                {
                                    Response.OutputStream.Write(bytes, 0, bytesRead);
                                }
                                else
                                {
                                    break;
                                }
                            } while (bytesRead > 0);
                            Response.Flush();
                            Response.End();
                        }
                    }
                }
                else
                {
                    // Stream data back to the client in chunks
                    using (MemoryStream ms = new MemoryStream(Encoding.UTF8.GetBytes(references[0].LongReferenceData)))
                    {
                        references[0].LongReferenceData = null;
                        do
                        {
                            bytesRead = ms.Read(bytes, 0, bufferSize);
                            if (Response.IsClientConnected)
                            {
                                Response.OutputStream.Write(bytes, 0, bytesRead);
                            }
                            else
                            {
                                break;
                            }
                        } while (bytesRead > 0);
                        Response.Flush();
                        Response.End();
                    }
                }
                Response.Write(DOWNLOAD_COMPLETE_MSG);
            }
        }
        else
        {
            Response.Write(NO_MSG_FOUND_MSG);
        }
    }

    /// <summary>
    /// Decompress a string using the GZip algorithm
    /// </summary>
    /// <param name="target">String to be unzipped</param>
    private static MemoryStream Decompress(string target)
    {
        using (MemoryStream zippedData = new MemoryStream(Convert.FromBase64String(target)))
        {
            MemoryStream unzippedData = new MemoryStream();

            // Use the newly created memory stream for the decompressed data
            using (GZipStream zipStream = new GZipStream(zippedData, CompressionMode.Decompress, true))
            {
                int bufferSize = Convert.ToInt32(ConfigurationManager.AppSettings["StreamingBufferSize"]);
                if (bufferSize == 0) throw new ConfigurationErrorsException("StreamingBufferSize configuration value is zero.  Check the .config file has the appSetting key value pair.");
                byte[] bytes = new byte[bufferSize];
                int lastBytesRead = 0;
                do
                {
                    lastBytesRead = zipStream.Read(bytes, 0, bufferSize);
                    unzippedData.Write(bytes, 0, lastBytesRead);
                } while (lastBytesRead > 0);
            }

            unzippedData.Flush();
            unzippedData.Position = 0;
            return unzippedData;
        }
    }
}

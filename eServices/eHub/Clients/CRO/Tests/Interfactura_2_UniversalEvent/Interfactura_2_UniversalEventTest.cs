			MapTester mapTester = new MapTester(Assembly.GetExecutingAssembly(), comparer);

			string sourceFile = "Interfactura_2_UniversalEvent.TestFiles.Input1.xml";
			string expectedFile = "Interfactura_2_UniversalEvent.TestFiles.Output1.xml";
			mapTester.Execute<Interfactura_2_UniversalEvent>(sourceFile, expectedFile);

		{
			InitialiseCodeMapsTestingContext();
			
			List<string> exclusionXpaths = new List<string>();
			exclusionXpaths.Add("//*[local-name()='EstimatedArrival']");
			exclusionXpaths.Add("//*[local-name()='EstimatedDeparture']");
			exclusionXpaths.Add("//*[local-name()='DateCollection']/*[local-name()='Date']/*[local-name()='Value']");
			
			ICompare comparer = new ExcludingComparer( exclusionXpaths );
			
			MapTester mapTester = new MapTester( Assembly.GetExecutingAssembly(), comparer );
			
			string sourceFile   = "LegacyXML_2_UniShip.TestFiles.01_Courier_Input.xml";
			string expectedFile = "LegacyXML_2_UniShip.TestFiles.01_Courier_Output.xml";
			mapTester.ExecuteCompiled<LegacyXML_2_UniShip>( sourceFile, expectedFile );
			
			sourceFile          = "LegacyXML_2_UniShip.TestFiles.02_Packages_Input.xml";
			expectedFile        = "LegacyXML_2_UniShip.TestFiles.02_Packages_Output.xml";
			mapTester.ExecuteCompiled<LegacyXML_2_UniShip>( sourceFile, expectedFile );
		}
		
		
